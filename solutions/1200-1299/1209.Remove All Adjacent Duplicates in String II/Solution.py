# 题目：1209. 删除字符串中的所有相邻重复项 II（Remove All Adjacent Duplicates in String II）
# 思路：用栈把「当前字符 + 连续出现次数」压在一起，计数凑满 k 就立刻出栈，让左右两边重新相邻，从而一次扫描完成消除。
# 时间复杂度：O(n)，每个字符进出栈各一次，最后拼接还需 O(n)；空间复杂度：O(n)，栈最坏压入 n 个分段。
class Solution:  # LeetCode 约定的题解类
    def removeDuplicates(self, s: str, k: int) -> str:  # s：输入字符串；k：连续重复多少个就删除；返回消除后的字符串
        stk = []  # 栈元素为 [字符, 该字符连续出现次数]，栈中相邻两项的字符必然不同
        for c in s:  # 从左到右逐个字符扫描
            if stk and stk[-1][0] == c:  # 栈非空且栈顶字符与当前字符相同，可以并入同一连续段
                stk[-1][1] = (stk[-1][1] + 1) % k  # 计数加一并取模 k：凑满 k 个就归零，等价于把这 k 个字符就地删掉
                if stk[-1][1] == 0:  # 计数归零说明这一段已凑满 k 个被消除
                    stk.pop()  # 弹出该段，使它左右两侧的字符重新相邻，后续可继续合并
            else:  # 栈为空或栈顶字符不同，无法合并
                stk.append([c, 1])  # 新开一个连续段，初始计数为 1
        ans = [c * v for c, v in stk]  # 把栈中每个剩余段按「字符 × 次数」展开成片段
        return "".join(ans)  # 把所有片段连接起来即为消除后的字符串
