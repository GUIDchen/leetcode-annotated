// 题目：1262. 可被三整除的最大和（Greatest Sum Divisible by Three）
// 思路：动态规划——f[i][j] 表示从前 i 个数中选若干、其和模 3 余 j 的最大和；每个数只需决策「不选」或「选」，取较大值转移。
// 时间复杂度：O(n)，每个数只更新 3 个余数状态；空间复杂度：O(n)，使用 (n+1)×3 的 DP 表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxSumDivThree(vector<int>& nums) {  // nums 是正整数数组，返回能被 3 整除的最大元素和（可以不选任何元素，此时和为 0）
        int n = nums.size();  // n 为数组长度
        const int inf = 1 << 30;  // 「不可达」标记：负得足够多，加上任何元素后仍远小于 0，取 max 时不会污染结果
        int f[n + 1][3];  // f[i][j]：只考虑前 i 个数、选出子集和模 3 余 j 时的最大和（VLA 大小由 n 决定）
        f[0][0] = 0;  // 一个数都不选时和为 0，0 % 3 == 0
        f[0][1] = f[0][2] = -inf;  // 余 1、余 2 的状态在 0 个数时无法达到，置为负无穷
        for (int i = 1; i <= n; ++i) {  // 枚举前 i 个数（i 从 1 到 n）
            int x = nums[i - 1];  // 第 i 个数对应下标 i-1，取出来备用
            for (int j = 0; j < 3; ++j) {  // 枚举目标余数 j（0、1、2）
                f[i][j] = max(f[i - 1][j], f[i - 1][(j - x % 3 + 3) % 3] + x);  // 取「不选 x」（沿用 f[i-1][j]）与「选 x」（由余数 j-x%3 转移而来，+3 保证下标非负）的较大值
            }  // 结束余数枚举
        }  // 结束元素枚举
        return f[n][0];  // f[n][0] 就是和处理全集、模 3 余 0 的最大和
    }  // 结束 maxSumDivThree
};  // 结束题解类