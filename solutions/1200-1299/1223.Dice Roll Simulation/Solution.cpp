// 题目：1223. 掷骰子模拟（Dice Roll Simulation）
// 思路：记忆化搜索，状态为「已掷次数 i、上一次点数 j、j 已连续出现次数 x」，逐层枚举下一个点数，超过 rollMax 限制的分支剪掉，最后把各分支方案数累加取模。
// 时间复杂度：O(n × 6 × 15)，状态数约 90n、每个状态枚举 6 个点数；空间复杂度：O(n × 6 × 15)，即记忆化数组 f。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    int dieSimulator(int n, vector<int>& rollMax) {  // n：要掷的总次数；rollMax[i]：点数 i+1 最多能连续出现的次数
        int f[n][7][16];  // 记忆化数组 f[i][j][x]：已掷 i 次、上次点数为 j、j 已连续出现 x 次的方案数；j=0 表示还没掷过
        memset(f, 0, sizeof f);  // 全部清零，0 同时充当「这个状态还没算过」的标记
        const int mod = 1e9 + 7;  // 取模常量，防止方案数在中间求和时溢出
        function<int(int, int, int)> dfs = [&](int i, int j, int x) -> int {  // 记忆化深搜：i 已掷次数、j 上一次点数、x 该点数已连续出现的次数，返回掷完剩余次数的方法数
            if (i >= n) {  // 递归出口：n 次已经全部掷完
                return 1;  // 这条完整序列合法，计 1 种方案
            }  // 结束递归出口分支
            if (f[i][j][x]) {  // 该状态之前算过（值非 0），可以直接复用
                return f[i][j][x];  // 返回记忆化结果，避免重复搜索同一状态
            }  // 结束记忆化命中分支
            long ans = 0;  // 累计当前状态的方案数；用 long 防止 6 路求和的中间值溢出 int
            for (int k = 1; k <= 6; ++k) {  // 枚举下一次可能掷出的点数 1..6
                if (k != j) {  // 点数换了：连续段结束，所以这一段不再受 rollMax 约束
                    ans += dfs(i + 1, k, 1);  // 换点数后连续次数重置为 1，递归到下一层
                } else if (x < rollMax[j - 1]) {  // 点数没变，检查是否还在该点数的连续次数上限内
                    ans += dfs(i + 1, j, x + 1);  // 还在上限内，可以继续接着掷同一个点数，连续次数 +1
                }  // 结束「同点数」分支
            }  // 结束 6 个点数的枚举
            ans %= mod;  // 对累加结果取模
            return f[i][j][x] = ans;  // 把结果写回记忆化数组并返回
        };  // lambda 定义结束
        return dfs(0, 0, 0);  // 从「第 0 次、没有上一次点数、连续 0 次」开始搜索，得到的方案数就是答案
    }  // 方法结束
};  // 类定义结束
