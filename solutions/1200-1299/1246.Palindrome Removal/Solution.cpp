// 题目：1246. 删除回文子数组（Palindrome Removal）
// 思路：区间 DP —— f[i][j] 表示删空区间 [i,j] 的最少次数，两端相等时可并入内部区间，否则枚举分割点拆分。
// 时间复杂度：O(n^3)，状态 O(n^2) 且每个状态枚举 O(n) 个分割点；空间复杂度：O(n^2)，即 f 表。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的解法入口
    int minimumMoves(vector<int>& arr) {  // 返回删除整个数组所需的最少回文删除次数
        int n = arr.size();  // 数组长度
        int f[n][n];  // f[i][j]：删空区间 [i,j] 的最少次数
        memset(f, 0, sizeof f);  // 先把整张表清零
        for (int i = 0; i < n; ++i) {  // 长度为 1 的区间
            f[i][i] = 1;  // 单个元素本身就是回文，删一次即可
        }
        for (int i = n - 2; i >= 0; --i) {  // 从右往左枚举左端点，保证长度更短的子区间已经算好
            for (int j = i + 1; j < n; ++j) {  // 右端点从 i+1 开始往右扩展
                if (i + 1 == j) {  // 区间长度为 2
                    f[i][j] = arr[i] == arr[j] ? 1 : 2;  // 两数相等可以一次删完，否则需要删两次
                } else {  // 长度不小于 3，需要考虑更复杂的情况
                    int t = arr[i] == arr[j] ? f[i + 1][j - 1] : 1 << 30;  // 两端相等时可以先删内部再带上两端，否则先记为极大值
                    for (int k = i; k < j; ++k) {  // 枚举分割点，把区间拆成左右两段分别删除
                        t = min(t, f[i][k] + f[k + 1][j]);  // 取「两端合并」与「拆分」中的较小值
                    }
                    f[i][j] = t;  // 写入该区间的答案
                }
            }
        }
        return f[0][n - 1];  // 整个数组的答案
    }
};  // 类定义结束