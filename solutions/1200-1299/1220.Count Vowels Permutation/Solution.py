# 题目：1220. 统计元音字母序列的数目（Count Vowels Permutation）
# 思路：按题目给定的元音相邻规则做 DP，f[c] 表示以元音 c 结尾、当前长度的序列数，逐层滚动更新并取模。
# 时间复杂度：O(n)，每层只有常数次加法；空间复杂度：O(1)，只用两个长度为 5 的列表。
class Solution:  # LeetCode 约定的题解类
    def countVowelPermutation(self, n: int) -> int:  # n：序列长度，1 <= n <= 2*10^4
        f = [1] * 5  # 长度 1 时每种元音结尾各 1 种；下标 0..4 依次对应 a,e,i,o,u
        mod = 10**9 + 7  # 题目要求的取模值
        for _ in range(n - 1):  # 从长度 1 逐层递推到长度 n
            g = [0] * 5  # 存放长度 i+1 的状态，避免原地更新时互相污染
            g[0] = (f[1] + f[2] + f[4]) % mod  # 只有 e/i/u 后面能接 a，所以这些结尾的序列数相加
            g[1] = (f[0] + f[2]) % mod  # 只有 a/i 后面能接 e
            g[2] = (f[1] + f[3]) % mod  # 只有 e/o 后面能接 i
            g[3] = f[2]  # 只有 i 后面能接 o，所以只继承 f[2]
            g[4] = (f[2] + f[3]) % mod  # 只有 i/o 后面能接 u
            f = g  # 滚动：把新一层状态换给 f
        return sum(f) % mod  # 所有元音结尾的序列数求和后再取模
