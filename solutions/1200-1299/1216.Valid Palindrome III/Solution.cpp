// 题目：1216. 验证回文串 III（Valid Palindrome III）
// 思路：区间 DP 求 s[i..j] 的最长回文子序列长度 f[i][j]，只要某区间满足 f[i][j]+k>=n，就说明删除不超过 k 个字符能变回文。
// 时间复杂度：O(n^2)，枚举所有区间；空间复杂度：O(n^2)，二维 DP 表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isValidPalindrome(string s, int k) {  // s：待判断的字符串；k：最多允许删除的字符数
        int n = s.length();  // 字符串长度，后面 DP 的边界都要用到
        int f[n][n];  // DP 表：f[i][j] 表示子串 s[i..j] 的最长回文子序列长度
        memset(f, 0, sizeof f);  // 整体清零，未显式赋值的区间都按 0 处理
        for (int i = 0; i < n; ++i) {  // 初始化长度为 1 的区间：单个字符本身就是回文
            f[i][i] = 1;  // 单字符区间的最长回文子序列长度是 1
        }  // 长度 1 的初始化结束
        for (int i = n - 2; i >= 0; --i) {  // 左端点倒序枚举，保证用到 f[i+1][...] 时它已经算好
            for (int j = i + 1; j < n; ++j) {  // 右端点正序枚举，只处理长度至少为 2 的区间
                if (s[i] == s[j]) {  // 两端字符相同，可以同时收进回文子序列的两头
                    f[i][j] = f[i + 1][j - 1] + 2;  // 内部区间答案加上两端的这两个字符
                } else {  // 两端字符不同，只能放弃其中一端
                    f[i][j] = max(f[i + 1][j], f[i][j - 1]);  // 取放弃左端或放弃右端后的较大值
                }  // 分支结束
                if (f[i][j] + k >= n) {  // 回文子序列长度 + 可删除数覆盖整个长度，等价于需要删除的字符数不超过 k
                    return true;  // 条件满足，提前返回 true
                }  // 提前返回分支结束
            }  // 内层循环结束
        }  // 外层循环结束
        return false;  // 所有区间都无法在 k 次删除内变成回文
    }  // 方法结束
};  // 类定义结束