// 题目：1215. 步进数（Stepping Numbers）
// 思路：以 1~9 为种子做 BFS，每次在末位数字上拼接 x-1 或 x+1 生成相邻的步进数，按数值递增顺序扩展到 high 为止。
// 时间复杂度：O(high 以内的步进数个数)，每个数只入队出队一次；空间复杂度：O(同上的队列与答案规模)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> countSteppingNumbers(int low, int high) {  // low/high：闭区间边界，返回区间内所有步进数（升序）
        vector<int> ans;  // ans：收集答案，BFS 天然按数值递增出队，所以无需再排序
        if (low == 0) {  // 0 按题面约定也算步进数，但它无法由 1~9 的种子扩展得到，需要单独处理
            ans.push_back(0);  // 区间包含 0 时先把 0 放进答案
        }  // 结束 0 的特殊分支
        queue<long long> q;  // BFS 队列；用 long long 存放，避免 v*10+x 超出 int 范围
        for (int i = 1; i < 10; ++i) {  // 把 1~9 全部作为一位数的种子入队
            q.push(i);  // 一位数天然是步进数，直接入队
        }  // 种子初始化结束
        while (!q.empty()) {  // 队列按数值从小到大取出，相当于逐位扩展的层序遍历
            long long v = q.front();  // 取出当前待扩展的步进数
            q.pop();  // 出队，保证每个数只被处理一次
            if (v > high) {  // 队列有序，一旦 v 超过上界，后面扩展出的数只会更大
                break;  // 直接结束整个 BFS，不再生成更大的数
            }  // 结束上界判断
            if (v >= low) {  // 只有落在 [low, high] 区间内才需要收集
                ans.push_back(v);  // 把合法步进数加入答案
            }  // 结束区间判断
            int x = v % 10;  // 取末位数字 x，它决定下一步可以拼接哪两个数字
            if (x > 0) {  // 末位大于 0 才能拼接 x-1（相邻数字差为 1）
                q.push(v * 10 + x - 1);  // 生成 v 后面接一位更小数字的新步进数
            }  // 结束拼 x-1 的分支
            if (x < 9) {  // 末位小于 9 才能拼接 x+1（相邻数字差为 1）
                q.push(v * 10 + x + 1);  // 生成 v 后面接一位更大数字的新步进数
            }  // 结束拼 x+1 的分支
        }  // 队列为空说明所有不超过 int 范围的步进数都已扩展完毕
        return ans;  // 返回按升序排列的答案
    }  // 方法结束
};  // 类定义结束