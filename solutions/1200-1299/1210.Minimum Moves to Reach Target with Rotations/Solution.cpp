// 题目：1210. 穿过迷宫的最少移动次数（Minimum Moves to Reach Target with Rotations）
// 思路：把「蛇身两格的位置 + 朝向」作为状态做 BFS，每个状态尝试右移、下移以及合法时旋转 90°，首次到达终点即为最少移动次数。
// 时间复杂度：O(n²)，状态数为 n² 个格子 × 2 种朝向；空间复杂度：O(n²)，访问数组与队列最多存这么多状态。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumMoves(vector<vector<int>>& grid) {  // grid：n×n 迷宫，0 表示空格、1 表示障碍；返回最少移动次数
        int n = grid.size();  // 迷宫边长，坐标压缩与越界判断都要用
        auto target = make_pair(n * n - 2, n * n - 1);  // 终点状态：蛇横放在最后一行最后两格，压缩后就是这两个编号
        queue<pair<int, int>> q;  // BFS 队列，元素是蛇身两格压缩后的一维编号 (a, b)
        q.emplace(0, 1);  // 初始状态：蛇横放在 (0,0) 与 (0,1)
        bool vis[n * n][2];  // 访问标记：vis[前格编号][status]，status 为 0 表示横放、1 表示竖放
        memset(vis, 0, sizeof vis);  // 把标记数组整体清零，表示所有状态都未访问
        vis[0][0] = true;  // 起点（前格编号 0、横放）标记为已访问

        auto move = [&](int i1, int j1, int i2, int j2) {  // 局部函数：尝试把蛇整体挪到 (i1,j1)-(i2,j2)，合法且未访问才入队
            if (i1 >= 0 && i1 < n && j1 >= 0 && j1 < n && i2 >= 0 && i2 < n && j2 >= 0 && j2 < n) {  // 先检查两格都落在迷宫范围内，越界直接放弃这次移动
                int a = i1 * n + j1, b = i2 * n + j2;  // 把二维坐标压缩成一维编号，便于存储状态与查重
                int status = i1 == i2 ? 0 : 1;  // 前格与后格同行说明横放(0)，同列说明竖放(1)
                if (!vis[a][status] && grid[i1][j1] == 0 && grid[i2][j2] == 0) {  // 该「前格 + 朝向」状态没访问过，且两格都不是障碍
                    q.emplace(a, b);  // 新状态入队，等待下一层扩展
                    vis[a][status] = true;  // 标记已访问，避免同一状态重复入队
                }  // 访问判断分支结束
            }  // 边界判断分支结束
        };  // move 函数定义结束

        int ans = 0;  // BFS 的层数，也就是蛇已经移动的步数
        while (!q.empty()) {  // 队列非空说明还有状态可以扩展
            for (int k = q.size(); k; --k) {  // 固定本层结点数逐一出队，保证 ans 与层数严格对应
                auto p = q.front();  // 取出一个待扩展状态
                q.pop();  // 队头出队
                if (p == target) {  // 当前状态正是终点（蛇尾横放在右下角两格）
                    return ans;  // BFS 首次到达即最少步数，直接返回
                }  // 终点判断结束
                auto [a, b] = p;  // 结构化绑定拆出蛇身两格的压缩编号
                int i1 = a / n, j1 = a % n;  // 由一维编号还原前格的二维坐标
                int i2 = b / n, j2 = b % n;  // 由一维编号还原后格的二维坐标
                // 尝试向右平移（保持身体水平/垂直状态）
                move(i1, j1 + 1, i2, j2 + 1);  // 整体向右平移一格，朝向保持不变
                // 尝试向下平移（保持身体水平/垂直状态）
                move(i1 + 1, j1, i2 + 1, j2);  // 整体向下平移一格，朝向保持不变
                // 当前处于水平状态，且 grid[i1 + 1][j2] 无障碍，尝试顺时针旋转90°
                if (i1 == i2 && i1 + 1 < n && grid[i1 + 1][j2] == 0) {  // 横放且下方两格都为空时，可以绕左上格顺时针旋转 90°
                    move(i1, j1, i1 + 1, j1);  // 旋转后变为竖放：前格 (i1,j1)、后格 (i1+1,j1)
                }  // 水平旋转分支结束
                // 当前处于垂直状态，且 grid[i2][j1 + 1] 无障碍，尝试逆时针旋转90°
                if (j1 == j2 && j1 + 1 < n && grid[i2][j1 + 1] == 0) {  // 竖放且右侧两格都为空时，可以绕上格逆时针旋转 90°
                    move(i1, j1, i1, j1 + 1);  // 旋转后变为横放：前格 (i1,j1)、后格 (i1,j1+1)
                }  // 垂直旋转分支结束
            }  // 本层状态遍历结束
            ++ans;  // 本层全部处理完仍未到终点，步数加一并进入下一层
        }  // BFS 循环结束
        return -1;  // 队列耗尽仍不可达，说明无法到达终点
    }  // minimumMoves 方法结束
};  // 题解类定义结束