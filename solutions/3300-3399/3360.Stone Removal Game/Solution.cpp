// 题目：3360. 移除石头游戏（Stone Removal Game）
// 思路：第 t 轮必须恰好取 11-t 块，两人能否继续只取决于剩余石头数；能完整打完的回合数 k 是固定的，Alice 先手，k 为奇数则 Alice 取走最后一堆获胜。
// 时间复杂度：O(1)，最多约 5 轮；空间复杂度：O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露题解方法
    bool canAliceWin(int n) {  // n：初始石头总数
        int x = 10, k = 0;  // x：本轮必须取的块数，从 10 开始每轮减一；k：已完成的完整回合数
        while (n >= x) {  // 只要剩余石头够本轮取，就继续这一回合
            n -= x;  // 取走本轮的 x 块
            --x;  // 下一轮要求少取一块
            ++k;  // 完整回合数加一
        }
        return k % 2;  // k 为奇数说明最后一步属于先手 Alice，返回 true；偶数回合则 Bob 赢
    }  // 题解类结束
};
