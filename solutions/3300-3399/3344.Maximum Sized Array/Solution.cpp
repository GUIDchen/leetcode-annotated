// 题目：3344. 最大尺寸数组（Maximum Sized Array）
// 思路：预处理长度对应的最小总代价基数 f[i]，再对数组长度二分，用 f[m-1]*(m-1)*m/2 判断该长度能否放进预算 s。
// 时间复杂度：O(MX^2) 预处理 + O(log MX) 单调查找；空间复杂度：O(MX) 的预处理表。
const int MX = 1330;  // 预处理上界：s 最大到 1e18 时答案长度也在这一量级以内
long long f[MX];  // f[i]：规模 i 对应的代价基数，数值较大，用 long long
auto init = [] {  // 静态初始化 lambda：程序启动时先把表算好
    f[0] = 0;  // 边界：规模 0 的代价基数为 0
    for (int i = 1; i < MX; ++i) {  // 逐个规模从小到大递推
        f[i] = f[i - 1] + i;  // 先累加新加入下标自身带来的贡献 i
        for (int j = 0; j < i; ++j) {  // 枚举所有比 i 小的下标
            f[i] += 2 * (i | j);  // 新下标与每个旧下标配对产生按位或贡献，对称地出现两次，故乘 2
        }  // 结束内层枚举
    }  // 结束外层循环
    return 0;  // lambda 必须有返回值，返回 0 占位
}();  // 立即执行，完成预处理

class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxSizedArray(long long s) {  // s：允许的最大总代价
        int l = 1, r = MX;  // 二分区间：答案至少为 1，右界取预处理范围
        while (l < r) {  // 二分找满足条件的最大长度
            int m = (l + r + 1) >> 1;  // 上取整的中点，避免 l 与 r 只差 1 时死循环
            if (f[m - 1] * (m - 1) * m / 2 <= s) {  // 长度 m 所需的最小代价不超过 s，说明 m 可行
                l = m;  // 可行就把左界抬到 m，继续向右试探
            } else {  // 代价超过了预算
                r = m - 1;  // 长度只能缩小到 m-1
            }  // 结束可行性分支
        }  // 结束二分
        return l;  // l == r，即最大可行长度
    }  // 结束方法
};  // 结束类
