// 题目：3363. 最多可收集的水果数目（Find the Maximum Number of Fruits Collected）
// 思路：第一个孩子只能沿主对角线走到终点，路径固定；另两个孩子分别只在上三角（列 > 行）与下三角（行 > 列）活动，互不重叠，各自做一次网格 DP 求最大收集量，最后加上主对角线的水果。
// 时间复杂度：O(n^2)，两次 DP 各遍历半个网格；空间复杂度：O(n^2)，状态表 f。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露题解方法
    int maxCollectedFruits(vector<vector<int>>& fruits) {  // fruits：n×n 的水果数目矩阵
        int n = fruits.size();  // 网格边长
        const int inf = 1 << 29;  // 足够大的常数，配合 -inf 表示「不可达」，累加后仍是极小数而不会溢出
        vector<vector<int>> f(n, vector<int>(n, -inf));  // f[i][j]：某个孩子走到 (i, j) 时的最大收集数，-inf 表示无法到达

        f[0][n - 1] = fruits[0][n - 1];  // 右上角孩子的起点，先收集该格水果
        for (int i = 1; i < n; i++) {  // 逐行向下推进
            for (int j = i + 1; j < n; j++) {  // 只在上三角（j > i）活动，避免与主对角线和另一个孩子的路径重叠
                f[i][j] = max(f[i - 1][j], f[i - 1][j - 1]) + fruits[i][j];  // 从上方的同列或左上格转移过来，再收集当前格
                if (j + 1 < n) {  // 右上方格子仍在界内时才能从那里转移
                    f[i][j] = max(f[i][j], f[i - 1][j + 1] + fruits[i][j]);  // 尝试从右上方转移，与已有值取更优者
                }  // 右侧转移分支结束
            }  // 列循环结束
        }  // 行循环结束

        f[n - 1][0] = fruits[n - 1][0];  // 左下角孩子的起点，先收集该格水果
        for (int j = 1; j < n; j++) {  // 逐列向右推进
            for (int i = j + 1; i < n; i++) {  // 只在下三角（i > j）活动，与另一个孩子的区域不重叠
                f[i][j] = max(f[i][j - 1], f[i - 1][j - 1]) + fruits[i][j];  // 从左方的同行或左上格转移过来，再收集当前格
                if (i + 1 < n) {  // 左下方格子仍在界内时才能从那里转移
                    f[i][j] = max(f[i][j], f[i + 1][j - 1] + fruits[i][j]);  // 尝试从左下方转移，与已有值取更优者
                }  // 下方转移分支结束
            }  // 行循环结束
        }  // 列循环结束

        int ans = f[n - 2][n - 1] + f[n - 1][n - 2];  // 两个孩子在终点前一格的最优值相加（终点 (n-1,n-1) 那格由主对角线一项计入）
        for (int i = 0; i < n; i++) {  // 累加第一个孩子固定走过的对角线水果
            ans += fruits[i][i];  // 主对角线上的每一格都会被第一个孩子经过
        }  // 累加循环结束

        return ans;  // 返回三个孩子收集的水果总数
    }  // 题解方法结束
};  // 题解类结束
