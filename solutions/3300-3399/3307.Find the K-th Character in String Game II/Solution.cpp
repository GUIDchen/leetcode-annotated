// 题目：3307. 找出第 K 个字符 II（Find the K-th Character in String Game II）
// 思路：字符串长度只取决于操作次数，先翻倍求出覆盖下标 k 所需的最少步数，再逆着从最终长度回溯：k 落在后半段就说明它由前半段复制（可能整体 +1）而来，据此累加字符偏移。
// 复杂度：时间 O(log k)，翻倍与回溯各 O(log k) 次；空间 O(1)，只用了若干整型变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    char kthCharacter(long long k, vector<int>& operations) {  // k：1 起始的目标下标；operations[i]：第 i 次操作的规则，0 表示只复制，1 表示复制后整体加一
        long long n = 1;  // n：模拟串的当前长度，初始串只有一个字符
        int i = 0;  // i：已经执行过的操作次数，也等于当前长度是 2 的几次幂
        while (n < k) {  // 不断翻倍，直到长度覆盖第 k 个字符
            n *= 2;  // 每执行一次操作，长度翻倍
            ++i;  // 操作次数同步加一
        }  // while 结束，此时 n = 2^i 且 n >= k
        int d = 0;  // d：目标字符相对 'a' 的累计偏移量
        while (n > 1) {  // 从最终长度逐层回溯到长度 1
            if (k > n / 2) {  // k 落在后半段，说明它是前半段字符复制（可能再整体 +1）得到的
                k -= n / 2;  // 换算回它在上一轮前半段中的位置
                d += operations[i - 1];  // 该次操作若为「复制并加一」，偏移量累加 1
            }  // if 结束
            n /= 2;  // 长度回退到上一轮的一半
            --i;  // 操作下标同步回退，指向更早的那次操作
        }  // while 结束，已回溯到初始的单字符串
        return 'a' + (d % 26);  // 偏移量对 26 取模（字母循环），加上 'a' 得到最终字符
    }  // 方法结束
};  // 类定义结束
