// 题目：3325. 字符至少出现 K 次的子字符串 I（Count Substrings With K-Frequency Characters I）
// 思路：滑动窗口。维护窗口 [l, r] 使其内部没有字符出现 ≥ k 次；收缩到临界后，以 r 结尾的合法子串恰好有 l 个。
// 时间复杂度：O(n)，每个字符最多进出窗口各一次；空间复杂度：O(1)，只要 26 个小写字母的计数。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberOfSubstrings(string s, int k) {  // s 为只含小写字母的字符串，k 是要求的最低出现次数
        int n = s.size();  // 字符串长度，窗口边界都以它为范围
        int ans = 0, l = 0;  // ans 累计合法子串数；l 是窗口左边界（窗口为 [l, r]）
        int cnt[26]{};  // 26 个字母在窗口内的出现次数，空花括号保证初始化为 0
        for (char& c : s) {  // 右端点 r 逐位右扩，c 是当前入窗字符
            ++cnt[c - 'a'];  // 当前字符入窗，计数加一
            while (cnt[c - 'a'] >= k) {  // c 在窗口里仍达到 k 次，窗口不合法，需要收缩左端
                --cnt[s[l++] - 'a'];  // 左端字符出窗，l 后移；先取 s[l] 再自增
            }  // 收缩结束：c 的计数已小于 k，窗口回到「无字符超标」的状态
            ans += l;  // 起点在 [0, l-1] 的子串都包含刚被移出的那个字符至少 k 次，正好 l 个
        }  // 右端点继续后移
        return ans;  // 返回合法子串总数
    }  // 方法结束
};  // 类定义结束
