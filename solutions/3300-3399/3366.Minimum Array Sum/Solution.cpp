// 题目：3366. 最小数组和（Minimum Array Sum）
// 思路：三维 DP，f[i][j][k] 表示处理前 i 个数、已用 j 次除 2 与 k 次减 d 时的最小和，逐个数枚举不用操作、单用一种操作、两种操作同用的三种搭配。
// 时间复杂度：O(n * op1 * op2)，每个状态常数次转移；空间复杂度：O(n * op1 * op2)，需要保存整张 DP 表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minArraySum(vector<int>& nums, int d, int op1, int op2) {  // nums：原数组；d：减法操作的减数；op1、op2：两种操作各自可用的次数
        int n = nums.size();  // 元素个数
        int f[n + 1][op1 + 1][op2 + 1];  // DP 表：f[i][j][k] 表示考虑前 i 个元素、用掉 j 次操作一与 k 次操作二后的最小和
        memset(f, 0x3f, sizeof f);  // 先用 0x3f 按字节填成「近似无穷大」，再叠加值也不会溢出 int
        f[0][0][0] = 0;  // 边界：还没处理元素、也没用任何操作时，和为 0
        for (int i = 1; i <= n; ++i) {  // 逐个元素推进，i 从 1 开始，对应 nums[i - 1]
            int x = nums[i - 1];  // 当前正在处理的元素值
            for (int j = 0; j <= op1; ++j) {  // 枚举已经用掉的操作一次数 j
                for (int k = 0; k <= op2; ++k) {  // 枚举已经用掉的操作二次数 k
                    f[i][j][k] = f[i - 1][j][k] + x;  // 情况一：当前元素两种操作都不用，直接累加原值
                    if (j > 0) {  // 情况二：只对当前元素用一次操作一（除以 2 上取整）
                        f[i][j][k] = min(f[i][j][k], f[i - 1][j - 1][k] + (x + 1) / 2);  // 取「不用」与「用操作一」的较小值，(x + 1) / 2 就是上取整的 x / 2
                    }  // 结束操作一分支
                    if (k > 0 && x >= d) {  // 情况三：只对当前元素用一次操作二（减去 d），要求减完不为负
                        f[i][j][k] = min(f[i][j][k], f[i - 1][j][k - 1] + (x - d));  // x >= d 才允许减，减完与原有方案取最小
                    }  // 结束操作二分支
                    if (j > 0 && k > 0) {  // 情况四：两种操作都作用在同一个元素上，先后顺序不同结果不同，需要分别尝试
                        int y = (x + 1) / 2;  // 先算出「除以 2 上取整」的结果 y
                        if (y >= d) {  // 顺序一：先除 2 再减 d，要求除完后仍不小于 d
                            f[i][j][k] = min(f[i][j][k], f[i - 1][j - 1][k - 1] + (y - d));  // 用 y - d 做转移，与当前最优值取小
                        }  // 结束顺序一分支
                        if (x >= d) {  // 顺序二：先减 d 再除 2，要求原值不小于 d
                            f[i][j][k] = min(f[i][j][k], f[i - 1][j - 1][k - 1] + (x - d + 1) / 2);  // (x - d + 1) / 2 就是对 x - d 上取整除以 2
                        }  // 结束顺序二分支
                    }  // 结束双操作分支
                }  // 结束 k 循环
            }  // 结束 j 循环
        }  // 结束 i 循环
        int ans = INT_MAX;  // 最终可能没把操作次数用完，答案为所有结束状态中的最小值
        for (int j = 0; j <= op1; ++j) {  // 枚举最终用掉的操作一次数
            for (int k = 0; k <= op2; ++k) {  // 枚举最终用掉的操作二次数
                ans = min(ans, f[n][j][k]);  // 在所有合法结束状态中取最小
            }  // 结束 k 循环
        }  // 结束 j 循环
        return ans;  // 返回最小数组和
    }  // 方法结束
};  // 类定义结束
