// 题目：3345. 最小可整除数位乘积 I（Smallest Divisible Digit Product I）
// 思路：从 n 开始逐个向上枚举，计算每个数的数位乘积，第一个能被 t 整除的数就是答案。
// 时间复杂度：O(答案 - n) 次枚举，每次 O(log n) 取位；空间复杂度：O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int smallestNumber(int n, int t) {  // n：枚举起点；t：数位乘积必须能被它整除
        for (int i = n;; ++i) {  // 无条件递增枚举，找到即可返回（题目保证有解）
            int p = 1;  // 数位乘积的累积变量，乘法单位元取 1
            for (int x = i; x > 0; x /= 10) {  // 用副本 x 逐位剥离，保住原数 i 不被破坏
                p *= (x % 10);  // 当前最低位乘进乘积
            }  // 结束取位循环
            if (p % t == 0) {  // 数位乘积能被 t 整除
                return i;  // 由于是从小到大枚举，第一个满足条件的就是最小答案
            }  // 结束判断
        }  // 不满足则继续枚举下一个数
    }  // 结束方法
};  // 结束类
