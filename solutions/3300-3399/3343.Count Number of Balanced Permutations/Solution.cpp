// 题目：3343. 统计平衡排列的数目（Count Number of Balanced Permutations）
// 思路：统计每个数字的出现次数与总和；总和为偶数时，用组合数选位置、用记忆化搜索逐个数字分配到两半，使两半数字和相等。
// 时间复杂度：O(10 * (s/2) * (n/2)^2 * 可选个数)，即状态数乘枚举量；空间复杂度：O(10 * (s/2) * (n/2)^2) 的记忆化数组。
using ll = long long;  // 起别名：排列计数会远超 int 范围，中间量统一用 long long
const int MX = 80;  // 题目字符串最长为 80 位，组合数表开到这个上界
const int MOD = 1e9 + 7;  // 题目要求的取模常数
ll c[MX][MX];  // 组合数表 c[n][k]：分配数字时按位选位置会用到

auto init = [] {  // 静态初始化用的 lambda：在 Solution 被调用之前把表算好
    c[0][0] = 1;  // 边界条件：从 0 个里选 0 个只有 1 种方案
    for (int i = 1; i < MX; ++i) {  // 逐行递推杨辉三角
        c[i][0] = 1;  // 每行第一项 C(i, 0) = 1
        for (int j = 1; j <= i; ++j) {  // 行内逐列计算到主对角线
            c[i][j] = (c[i - 1][j] + c[i - 1][j - 1]) % MOD;  // 帕斯卡公式 C(i,j) = C(i-1,j) + C(i-1,j-1)，边算边取模防止溢出
        }  // 结束列循环
    }  // 结束行循环
    return 0;  // lambda 必须有返回值，这里返回 0 仅作占位
}();  // 立即调用该 lambda，让静态表在任何用例前就绪

class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countBalancedPermutations(string num) {  // num：由数字字符组成的字符串，允许重排
        int cnt[10]{};  // 每种数字的出现次数，值初始化为 0
        int s = 0;  // 所有数字之和，用来判断能否均分成相等的两半
        for (char& c : num) {  // 遍历字符串中的每个字符
            ++cnt[c - '0'];  // 字符减去 '0' 得到数字，对应计数加一
            s += c - '0';  // 累加所有数字之和
        }  // 结束统计循环
        if (s % 2) {  // 总和为奇数时，两半数字和不可能相等
            return 0;  // 方案数为 0
        }  // 结束奇偶性判断
        int n = num.size();  // n 是排列的总位数
        int m = n / 2 + 1;  // 记忆化表第 3 维上界：最多 n/2 个位置，多留 1 位余量
        int f[10][s / 2 + 1][m][m + 1];  // f[数字][剩余数字和][第一半剩余位置][第二半剩余位置]，四维记忆化表
        memset(f, -1, sizeof(f));  // 全部置 -1，表示这些状态都还没有被计算过
        auto dfs = [&](this auto&& dfs, int i, int j, int a, int b) -> int {  // dfs：把数字 i..9 分配完后，能凑出目标的方案数
            if (i > 9) {  // 数字 0~9 已经全部处理完
                return ((j | a | b) == 0 ? 1 : 0);  // 三个剩余量全为 0 才算恰好填满，否则不是合法方案
            }  // 结束终止条件
            if (a == 0 && j) {  // 第一半的位置用完了但数字和还没凑够，后面无法再补
                return 0;  // 该分支无解
            }  // 结束剪枝
            if (f[i][j][a][b] != -1) {  // 该状态之前算过
                return f[i][j][a][b];  // 直接返回缓存的结果，避免重复搜索
            }  // 结束缓存查询
            int ans = 0;  // 累计当前状态的方案数
            for (int l = 0; l <= min(cnt[i], a); ++l) {  // 枚举数字 i 放进第一半的个数 l，不超过该数字总数与剩余位置数
                int r = cnt[i] - l;  // 其余的个数 r 全部放进第二半
                if (r >= 0 && r <= b && l * i <= j) {  // 第二半放得下，且数字和不超过剩余目标
                    int t = c[a][l] * c[b][r] % MOD * dfs(i + 1, j - l * i, a - l, b - r) % MOD;  // 先分别从剩余位置中选 l、r 个，再递归分配下一个数字；每步取模防溢出
                    ans = (ans + t) % MOD;  // 累加到答案并取模
                }  // 结束可行性判断
            }  // 结束个数枚举
            return f[i][j][a][b] = ans;  // 写入记忆化表后再返回
        };  // lambda 定义结束
        return dfs(0, s / 2, n / 2, (n + 1) / 2);  // 从数字 0 开始；目标和为总和的一半；两半位置数分别为 n/2 与 n 为奇数时多一个的 (n+1)/2
    }  // 结束方法
};  // 结束类
