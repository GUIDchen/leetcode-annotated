// 题目：3340. 检查平衡字符串（Check Balanced String）
// 思路：按下标奇偶分成两组，分别累加各位数字，最后比较两组和是否相等。
// 时间复杂度：O(n)，只遍历一次；空间复杂度：O(1)，只用两个计数器。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isBalanced(string num) {  // num 是只含数字字符的字符串
        int f[2]{};  // f[0]/f[1] 分别累加偶数下标与奇数下标的数字和，{} 将其初始化为 0
        for (int i = 0; i < num.size(); ++i) {  // 遍历每个字符的下标
            f[i & 1] += num[i] - '0';  // i & 1 区分奇偶下标；字符减 '0' 得到对应数字
        }
        return f[0] == f[1];  // 两组数字和相等即为平衡字符串
    }  // 方法结束
};  // 类定义结束
