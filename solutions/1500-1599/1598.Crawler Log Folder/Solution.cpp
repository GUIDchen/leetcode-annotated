// 题目：1598. 文件夹操作日志搜集器（Crawler Log Folder）
// 思路：维护当前目录深度，"../" 让深度减一（不低于 0），"./" 不变，其余目录名让深度加一。
// 时间复杂度：O(n)，只需扫一遍日志；空间复杂度：O(1)，只用一个深度变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minOperations(vector<string>& logs) {  // logs 为按时间顺序记录的日志
        int ans = 0;  // 当前目录深度，也正是回到主目录所需的最少操作数
        for (auto& v : logs) {  // 逐条处理日志，用引用避免字符串拷贝
            if (v == "../") {  // 返回父目录
                ans = max(0, ans - 1);  // 深度减一，但最低只到主目录 0
            } else if (v[0] != '.') {  // 首字符不是句点，说明是普通子文件夹
                ++ans;  // 进入子文件夹，深度加一
            }  // 分支判断结束（"./" 表示停留在当前目录，深度不变）
        }  // 遍历结束
        return ans;  // 返回最终深度，即最少需要的操作次数
    }  // 方法结束
};  // 类结束