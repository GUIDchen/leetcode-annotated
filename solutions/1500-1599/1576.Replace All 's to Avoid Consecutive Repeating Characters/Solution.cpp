// 题目：1576. 替换所有的问号（Replace All 's to Avoid Consecutive Repeating Characters）
// 思路：从左到右遇到问号时，只在 {a, b, c} 中挑一个与左右邻居都不同的字符填入；三个候选一定够用，因为每个位置最多只有两个邻居。
// 时间复杂度：O(n)，每个位置最多试 3 个字符；空间复杂度：O(1)，只在原串上原地修改。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string modifyString(string s) {  // s：只含小写字母与问号的字符串，直接在副本上修改并返回
        int n = s.size();  // 字符串长度，作为扫描边界
        for (int i = 0; i < n; ++i) {  // 从左到右扫描每个位置
            if (s[i] == '?') {  // 只有问号位置才需要替换
                for (char c : "abc") {  // 候选字符只需 a、b、c 三个，足以避开左右两个邻居
                    if ((i && s[i - 1] == c) || (i + 1 < n && s[i + 1] == c)) {  // 若与左邻居或右邻居相同，这个字符不能用
                        continue;  // 跳过当前候选，换下一个
                    }  // 候选判断结束
                    s[i] = c;  // 该字符与左右邻居都不相同，直接填入
                    break;  // 填好即跳出候选循环，处理下一个位置
                }  // 候选循环结束
            }  // 问号判断结束
        }  // 扫描循环结束
        return s;  // 返回替换完成后的字符串
    }  // 方法结束
};  // 题解类结束