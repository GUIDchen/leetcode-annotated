// 题目：1567. 乘积为正数的最长子数组长度（Maximum Length of Subarray With Positive Product）
// 思路：动态规划，f[i] 记以 i 结尾乘积为正的最长子数组长度，g[i] 记乘积为负的最长长度，按 nums[i] 的正负转移。
// 时间复杂度：O(n)，一次线性扫描；空间复杂度：O(n)，两个长度 n 的 DP 数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int getMaxLen(vector<int>& nums) {  // nums：输入整数数组
        int n = nums.size();  // 数组长度
        vector<int> f(n, 0), g(n, 0);  // f：以 i 结尾乘积为正的最长长度；g：乘积为负的最长长度
        f[0] = nums[0] > 0 ? 1 : 0;  // 只有一个元素时，正数才使乘积为正
        g[0] = nums[0] < 0 ? 1 : 0;  // 只有一个元素时，负数才使乘积为负
        int ans = f[0];  // 答案至少是第一个元素贡献的正乘积长度

        for (int i = 1; i < n; ++i) {  // 从第二个元素开始递推
            if (nums[i] > 0) {  // 当前是正数：不改变乘积符号，长度各加一
                f[i] = f[i - 1] + 1;  // 正乘积只能在原有正乘积后面继续延长
                g[i] = g[i - 1] > 0 ? g[i - 1] + 1 : 0;  // 只有原负乘积存在时才能延长，否则仍不存在
            } else if (nums[i] < 0) {  // 当前是负数：正负乘积互换
                f[i] = g[i - 1] > 0 ? g[i - 1] + 1 : 0;  // 负乘积乘上负数变正
                g[i] = f[i - 1] + 1;  // 正乘积乘上负数变负
            }  // nums[i] == 0 时 f[i]、g[i] 保持初始值 0，表示含 0 的子数组不计入
            ans = max(ans, f[i]);  // 用当前的正乘积长度更新答案
        }
        return ans;  // 返回乘积为正的最长子数组长度
    }
};
