// 题目：1535. 找出数组游戏的赢家（Find the Winner of an Array Game）
// 思路：用 mx 维护当前擂主（也是已扫描元素的最大值），cnt 记录它连续赢的场次，连胜达到 k 即结束；若始终不到 k，最大值一定最终获胜。
// 时间复杂度：O(n)，最多扫描一遍数组；空间复杂度：O(1)，只需常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int getWinner(vector<int>& arr, int k) {  // arr：参赛数组；k：夺冠所需的连续获胜次数
        int mx = arr[0];  // 当前擂主初始化为第一个元素
        for (int i = 1, cnt = 0; i < arr.size(); ++i) {  // i 从 1 开始逐个挑战，cnt 记录擂主打下的连续胜场
            if (mx < arr[i]) {  // 挑战者比擂主大，擂主易主
                mx = arr[i];  // 更新擂主为更大的那个元素
                cnt = 1;  // 新擂主刚赢下这一场，连胜数重置为 1
            } else {  // 否则擂主更大，它继续赢
                ++cnt;  // 擂主的连胜次数加一
            }  // 分支结束
            if (cnt == k) {  // 连胜已满 k 场，赢家此时就已经确定
                break;  // 提前跳出循环，不必再看后面元素
            }  // 判断结束
        }  // 遍历结束
        return mx;  // 返回赢家；若没到 k 场，最大值必然在后续无敌手
    }  // 方法结束
};  // 题解类结束