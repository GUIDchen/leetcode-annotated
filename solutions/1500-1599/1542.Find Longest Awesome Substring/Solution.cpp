// 题目：1542. 找出最长的超赞子字符串（Find Longest Awesome Substring）
// 思路：用 10 位掩码记录每个数字出现次数的奇偶性，两个前缀掩码相同（或只差一位）时中间那段就能重排成回文，记下每个掩码最早出现的下标即可求最长。
// 时间复杂度：O(n * 10)，每步多检查 10 种「差一位」的情况；空间复杂度：O(2^10)，掩码状态表大小固定。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int longestAwesome(string s) {  // s：只含数字字符的字符串
        vector<int> d(1024, -1);  // d[mask] 记录掩码 mask 第一次出现的位置，-1 表示还没出现过（共 2^10 种掩码）
        d[0] = 0;  // 空前缀的掩码是 0，位置记作 0
        int st = 0, ans = 1;  // st 是当前前缀的奇偶掩码；ans 至少为 1，因为单字符一定是回文
        for (int i = 1; i <= s.size(); ++i) {  // i 表示前缀长度，从 1 开始便于直接做下标差
            int v = s[i - 1] - '0';  // 取第 i 个字符对应的数字 0..9
            st ^= 1 << v;  // 翻转这一位的奇偶性
            if (~d[st]) {  // ~d[st] 非 0 等价于 d[st] != -1，即该掩码此前出现过
                ans = max(ans, i - d[st]);  // 两个同等奇偶性的前缀之差全是偶数次，可以重排成回文，更新答案
            } else {  // 该掩码第一次出现
                d[st] = i;  // 记下它的位置，供后面算长度
            }
            for (v = 0; v < 10; ++v) {  // 再枚举「恰好一个数字出现奇数次」的合法情况
                if (~d[st ^ (1 << v)]) {  // 只差第 v 位的前缀出现过，说明区间内只有一个数字是奇数次，同样能重排成回文
                    ans = max(ans, i - d[st ^ (1 << v)]);  // 更新最长回文子串长度
                }
            }
        }
        return ans;  // 返回最长的超赞子串长度
    }
};