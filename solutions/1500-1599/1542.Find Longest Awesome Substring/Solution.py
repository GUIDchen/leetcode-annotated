# 题目：1542. 找出最长的超赞子字符串（Find Longest Awesome Substring）
# 思路：用 10 位掩码记录每个数字出现次数的奇偶性，两个前缀掩码相同（或只差一位）时中间那段就能重排成回文，记下每个掩码最早出现的下标即可求最长。
# 时间复杂度：O(n * 10)，每步多检查 10 种「差一位」的情况；空间复杂度：O(2^10)，掩码状态表大小固定。
class Solution:
    def longestAwesome(self, s: str) -> int:  # s：只含数字字符的字符串
        st = 0  # st 是当前前缀的奇偶掩码，空前缀时为 0
        d = {0: -1}  # 字典记录每个掩码第一次出现的下标，空前缀掩码 0 的位置记作 -1
        ans = 1  # 答案至少为 1，因为单个字符本身就是回文
        for i, c in enumerate(s):  # 逐个字符扩展前缀
            v = int(c)  # 当前数字的值 0..9
            st ^= 1 << v  # 翻转该数字对应的奇偶位
            if st in d:  # 掩码出现过，说明两段之间每个数字都出现偶数次
                ans = max(ans, i - d[st])  # 用当前下标减去首次出现下标来更新最长长度
            else:  # 该掩码第一次出现
                d[st] = i  # 记下它的下标，供后面算长度
            for v in range(10):  # 再枚举「恰好一个数字出现奇数次」的合法情况
                if st ^ (1 << v) in d:  # 只差第 v 位的前缀出现过，说明区间内只有一个数字是奇数次，同样能重排成回文
                    ans = max(ans, i - d[st ^ (1 << v)])  # 更新最长回文子串长度
        return ans  # 返回最长的超赞子串长度
