// 题目：1556. 千位分隔数（Thousand Separator）
// 思路：不断对 10 取余取出最低位、拼到答案串尾部，每凑满 3 位就补一个点，最后整体反转得到从高位到低位的字符串。
// 时间复杂度：O(log n)（位数级别次循环 + 一次反转）；空间复杂度：O(log n)（答案串长度与位数同阶）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string thousandSeparator(int n) {  // n：待格式化的非负整数
        int cnt = 0;  // cnt：当前已经拼接了多少个数字位（用来判断是否该插入点）
        string ans;  // ans：从低位到高位依次拼接的字符结果（最后会反转）
        while (1) {  // 至少处理一位数字，用 break 控制退出
            int v = n % 10;  // 取出当前的最低位数字
            n /= 10;  // 去掉已经处理过的最低位
            ans += to_string(v);  // 把这一位字符追加到答案尾部
            if (n == 0) break;  // 所有位都取完了，结束循环（最高位前面不能再加点）
            if (++cnt == 3) {  // 位数计数先自增，刚好满 3 位时插入分隔点
                ans += '.';  // 追加千位分隔符
                cnt = 0;  // 位计数清零，开始统计下一组三位
            }
        }
        reverse(ans.begin(), ans.end());  // 反转前是从低位到高位，反转后得到正常的从高位到低位顺序
        return ans;  // 返回带千位分隔符的数字字符串
    }
};