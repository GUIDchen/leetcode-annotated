// 题目：1541. 平衡括号字符串的最少插入次数（Minimum Insertions to Balance a Parentheses String）
// 思路：从左到右扫描，用 x 记录待匹配的左括号个数；每遇到一个右括号先尽量凑成 "))"，缺的右括号或左括号都靠插入补足。
// 时间复杂度：O(n)，每个字符只扫描一次；空间复杂度：O(1)，只用了两个计数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minInsertions(string s) {  // s：只含 '(' 与 ')' 的括号串
        int ans = 0, x = 0;  // ans 记录最少插入次数，x 记录当前等待匹配的左括号个数
        int n = s.size();  // 预先取出串长，避免循环里反复调用 size()
        for (int i = 0; i < n; ++i) {  // 从左到右逐字符扫描
            if (s[i] == '(') {  // 遇到左括号：先记下来，等后面的右括号来匹配
                ++x;  // 待匹配的左括号加 1
            } else {  // 遇到右括号：每个左括号需要两个右括号
                if (i < n - 1 && s[i + 1] == ')') {  // 后面紧跟着一个右括号，可以凑成一对 "))"
                    ++i;  // 跳过下一个字符，i 额外加 1
                } else {  // 否则只有一个右括号，需要再插入一个右括号
                    ++ans;  // 插入次数加 1
                }
                if (x == 0) {  // 没有可匹配的左括号，说明左边还缺一个左括号
                    ++ans;  // 插入一个左括号
                } else {  // 有左括号可以匹配
                    --x;  // 消耗掉一个待匹配的左括号
                }
            }  // 结束右括号分支
        }  // 结束扫描
        ans += x << 1;  // 扫描结束后仍有 x 个左括号没配对，每个都要补两个右括号
        return ans;  // 返回最少插入次数
    }  // 方法结束
};  // 类定义结束