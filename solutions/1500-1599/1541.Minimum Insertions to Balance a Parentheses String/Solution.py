# 题目：1541. 平衡括号字符串的最少插入次数（Minimum Insertions to Balance a Parentheses String）
# 思路：从左到右扫描，用 x 记录待匹配的左括号个数；每遇到一个右括号先尽量凑成 "))"，缺的右括号或左括号都靠插入补足。
# 时间复杂度：O(n)，每个字符只扫描一次；空间复杂度：O(1)，只用了两个计数变量。
class Solution:  # LeetCode 约定的题解类
    def minInsertions(self, s: str) -> int:  # s：只含 '(' 与 ')' 的括号串
        ans = x = 0  # ans 记录最少插入次数，x 记录当前等待匹配的左括号个数
        i, n = 0, len(s)  # i 是扫描指针，n 是串长
        while i < n:  # 从左到右逐个字符处理
            if s[i] == '(':
                # 待匹配的左括号加 1
                x += 1
            else:  # 遇到右括号：每个左括号需要两个右括号配对
                if i < n - 1 and s[i + 1] == ')':  # 后面紧跟着一个右括号，可以凑成一对 "))"
                    # 有连续两个右括号，i 往后移动
                    i += 1
                else:  # 否则只有一个右括号，需要再插入一个右括号
                    # 只有一个右括号，插入一个
                    ans += 1
                if x == 0:  # 检查是否还有可用的左括号
                    # 无待匹配的左括号，插入一个
                    ans += 1
                else:  # 有左括号可配对，消耗掉一个
                    # 待匹配的左括号减 1
                    x -= 1
            i += 1  # 指针后移，继续扫描下一个字符
        # 遍历结束，仍有待匹配的左括号，说明右括号不足，插入 x << 1 个
        ans += x << 1
        return ans  # 返回最少插入次数
