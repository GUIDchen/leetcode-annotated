// 题目：1529. 最少的后缀翻转次数（Minimum Suffix Flips）
// 思路：从左往右扫描，ans 同时记录翻转次数与当前位的实际奇偶；一旦实际值与 target 不同，就必须对当前后缀翻一次。
// 时间复杂度：O(n)，只扫描一遍字符串；空间复杂度：O(1)，只用了一个整型计数器。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minFlips(string target) {  // target：由 '0' 和 '1' 组成的目标二进制串
        int ans = 0;  // ans 一身二职：既是已翻转次数，也是当前前缀被翻转的奇偶性
        for (char c : target) {  // 从左到右逐位处理每一位
            int v = c - '0';  // 把字符 '0'/'1' 转成数值 0/1，方便异或运算
            if ((ans & 1) ^ v) {  // 当前位的实际值是初始 0 被翻 ans 次的结果；(ans&1)^v 为 1 表示实际值与目标值不同
                ++ans;  // 既然这一位不对，就必须翻转一次从该位开始的后缀
            }  // 分支结束
        }  // 循环结束，此时每一位都已被贪心地修正
        return ans;  // 返回最少翻转次数
    }  // 方法结束
};  // 题解类结束