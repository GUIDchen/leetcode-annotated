// 题目：1573. 分割字符串的方案数（Number of Ways to Split a String）
// 思路：设字符串中 '1' 的总数为 cnt。cnt 不能被 3 整除则无解；cnt 为 0 时是选两个切点的组合数 C(n-1, 2)；
//       否则每段必须含 cnt/3 个 '1'，答案 = 第一刀可选的空档数 × 第二刀可选的空档数。
// 时间复杂度：O(n)，线性扫描统计与定位；空间复杂度：O(1)，只用常数个额外变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numWays(string s) {  // s：只含 '0' 与 '1' 的字符串
        int cnt = 0;  // 统计字符串中 '1' 的总个数
        for (char& c : s) {  // 遍历字符串的每个字符
            cnt += c == '1';  // 用比较结果的 0/1 累加，等价于遇到 '1' 就加一
        }
        int m = cnt % 3;  // 三段必须含有相同数量的 '1'
        if (m) {  // 若 '1' 的个数不能被 3 整除
            return 0;  // 无法均分，方案数为 0
        }
        const int mod = 1e9 + 7;  // 结果需要对 1e9+7 取模
        int n = s.size();  // 字符串长度
        if (cnt == 0) {  // 特例：整个字符串没有 '1'
            return (n - 1LL) * (n - 2) / 2 % mod;  // 从 n-1 个空隙里选两个切点，即 C(n-1, 2)
        }
        cnt /= 3;  // 每一段应包含的 '1' 的个数
        auto find = [&](int x) {  // 找到第 x 个 '1' 所在的下标
            int t = 0;  // 已遇到的 '1' 的个数
            for (int i = 0;; ++i) {  // 从前往后线性查找，循环上界可以省略
                t += s[i] == '1';  // 遇到 '1' 就累加计数
                if (t == x) {  // 正好数到第 x 个 '1'
                    return i;  // 返回它的下标
                }
            }
        };
        int i1 = find(cnt), i2 = find(cnt + 1);  // 第一段末尾 '1' 与第二段开头 '1' 的位置，决定第一刀的可选空档
        int j1 = find(cnt * 2), j2 = find(cnt * 2 + 1);  // 第二段末尾 '1' 与第三段开头 '1' 的位置，决定第二刀的可选空档
        return (1LL * (i2 - i1) * (j2 - j1)) % mod;  // 两刀的选择数相乘，用 1LL 提升为长整型防溢出
    }
};