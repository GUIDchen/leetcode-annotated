// 题目：1536. 排布二进制网格的最少交换次数（Minimum Swaps to Arrange a Binary Grid）
// 思路：先记下每行最右边的 1 在哪一列；再从上到下为第 i 行找第一行满足 pos<=i 的行，把它上移 i 位（即 j-i 次相邻交换）。
// 时间复杂度：O(n²)，每行找候选并冒泡上移；空间复杂度：O(n)，记录每行最右 1 的列号。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minSwaps(vector<vector<int>>& grid) {  // grid：n×n 的 01 网格
        int n = grid.size();  // 网格边长 n
        vector<int> pos(n, -1);  // pos[i] 记录第 i 行最右边那个 1 的列号，-1 表示该行全为 0
        for (int i = 0; i < n; ++i) {  // 逐行统计最右的 1
            for (int j = n - 1; j >= 0; --j) {  // 从最右一列往左找，第一个遇到的 1 就是最右的 1
                if (grid[i][j] == 1) {  // 找到值为 1 的元素
                    pos[i] = j;  // 记下它所在的列号
                    break;  // 已经是最右的 1，不必再看左边的列
                }  // if 分支结束
            }  // 内层列扫描结束
        }  // 外层行扫描结束
        int ans = 0;  // 最少交换次数从 0 开始累计
        for (int i = 0; i < n; ++i) {  // 从上到下依次确定第 i 行
            int k = -1;  // k 记录被选中、需要搬到第 i 行的那一行行号
            for (int j = i; j < n; ++j) {  // 只能从第 i 行及其下方挑行，上方已排好不能再动
                if (pos[j] <= i) {  // 该行最右的 1 已落在第 i 列（含）左边，搬到第 i 行后右上三角必为 0
                    ans += j - i;  // 把它上移 j-i 行，恰好需要 j-i 次相邻交换
                    k = j;  // 记下被选中的行号
                    break;  // 贪心选最近的一行，交换次数最少
                }  // if 分支结束
            }  // 候选行扫描结束
            if (k == -1) {  // 下面没有任何一行满足条件，说明无论怎么换都排不出来
                return -1;  // 返回 -1 表示无解
            }  // if 分支结束
            for (; k > i; --k) {  // 把选中的行一路向上冒泡到第 i 行
                swap(pos[k], pos[k - 1]);  // 一次相邻交换；只交换记录的位置，不必真的搬动整行数据
            }  // 冒泡循环结束
        }  // 行的外层循环结束
        return ans;  // 返回最少交换次数
    }  // 方法结束
};  // 题解类结束