// 题目：3223. 操作后字符串的最短长度（Minimum Length of String After Operations）
// 思路：一次操作会删掉某个字符左右各一个同字符，所以每个字符的个数只按奇偶性收缩：奇数次最终留 1 个，偶数次最终留 2 个。
// 时间复杂度：O(n)，n 为字符串长度；空间复杂度：O(1)，只用 26 个计数器。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外公开
    int minimumLength(string s) {  // 返回操作后字符串可能的最短长度
        int cnt[26]{};  // 统计每个小写字母的出现次数，{} 把 26 个计数器初始化为 0
        for (char& c : s) {  // 遍历字符串中的每个字符（按引用避免拷贝）
            ++cnt[c - 'a'];  // 用 c - 'a' 把字母映射到 0..25 的下标并累加计数
        }  // 字符遍历结束，每个字母的频次统计完成
        int ans = 0;  // 累积最短长度
        for (int x : cnt) {  // 逐个字母检查它的出现次数
            if (x) {  // 只处理出现过的字母
                ans += x % 2 ? 1 : 2;  // 出现奇数次最终只能留 1 个，偶数次最少留 2 个
            }  // 字母枚举结束
        }  // 各字母能留下的个数之和就是答案
        return ans;  // 返回最短长度
    }  // 方法结束
};