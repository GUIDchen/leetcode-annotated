// 3284. 连续子数组的和（Sum of Consecutive Subarrays）
// 核心思路：连续子数组只能逐项 +1 递增或逐项 -1 递减。分别维护以当前元素结尾、公差为 +1 和 -1 的最长连续段长度，用「段长 × 末项」递推该段内所有合法子数组之和，再单独计入长度为 1 的子数组。
// 复杂度：时间 O(n)，空间 O(1)

class Solution {  // 定义题解类
public:  // 公开接口
    int getSum(vector<int>& nums) {  // 返回所有连续子数组之和的总和（对 1e9+7 取模）
        const int mod = 1e9 + 7;  // 取模常数
        long long s = nums[0], t = nums[0], ans = nums[0];  // s、t 分别是以当前元素结尾、公差为 +1 / -1 的所有连续子数组之和；ans 为总答案
        int f = 1, g = 1;  // f、g 分别是以当前元素结尾、公差为 +1 / -1 的最长连续段长度
        for (int i = 1; i < nums.size(); ++i) {  // 从第二个元素开始遍历，每次考察相邻的一对元素
            int x = nums[i - 1], y = nums[i];  // x 为前一个元素，y 为当前元素
            if (y - x == 1) {  // 相邻两数相差 1，可以延续递增段
                ++f;  // 递增段长度加一
                s += 1LL * f * y;  // 该段所有后缀之和增加「段长 × 当前末项」
                ans = (ans + s) % mod;  // 把以 y 结尾的递增连续子数组之和累加进答案
            } else {  // 递增段在此断开
                f = 1;  // 长度重置为 1
                s = y;  // 和重置为只剩当前元素自身
            }  // 结束递增段处理
            if (y - x == -1) {  // 相邻两数相差 -1，可以延续递减段
                ++g;  // 递减段长度加一
                t += 1LL * g * y;  // 该段所有后缀之和增加「段长 × 当前末项」
                ans = (ans + t) % mod;  // 把以 y 结尾的递减连续子数组之和累加进答案
            } else {  // 递减段在此断开
                g = 1;  // 长度重置为 1
                t = y;  // 和重置为只剩当前元素自身
            }  // 结束递减段处理
            if (abs(y - x) != 1) {  // 差值不为 ±1 时，单元素子数组 (y) 不会被上面两段统计到
                ans = (ans + y) % mod;  // 把单元素子数组的和累加进答案
            }  // 结束单元素判定
        }  // 结束遍历
        return ans;  // 返回取模后的总答案
    }  // 方法结束
};  // 类定义结束
