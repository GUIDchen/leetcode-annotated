// 题目：3240. 最少翻转次数使二进制矩阵回文 II（Minimum Number of Flips to Make Binary Grid Palindromic II）
// 思路：行回文与列回文同时成立，把每一组四个对称格子凑成相同的值；再单独处理中间行/列，并保证 1 的总个数是 4 的倍数。
// 时间复杂度：O(m × n)；空间复杂度：O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minFlips(vector<vector<int>>& grid) {  // grid：0/1 矩阵，返回最少翻转次数
        int m = grid.size(), n = grid[0].size();  // m 行数，n 列数
        int ans = 0;  // ans 累计需要翻转的次数
        for (int i = 0; i < m / 2; ++i) {  // 枚举左上四分之一区域
            for (int j = 0; j < n / 2; ++j) {  // 每个格子 (i, j) 代表一组 4 个互相约束的对称位置
                int x = m - i - 1, y = n - j - 1;  // 求出这一组中右下对称格子的坐标 (x, y)
                int cnt1 = grid[i][j] + grid[x][j] + grid[i][y] + grid[x][y];  // 四个对称位置上 1 的个数
                ans += min(cnt1, 4 - cnt1);  // 四个都变 0 要翻 cnt1 次，都变 1 要翻 4-cnt1 次，取较小
            }  // 内层 for 结束
        }  // 外层 for 结束
        // 中间行与中间列这两条线上的格子不属于任何四元组，需要单独配对处理
        if (m % 2 == 1 && n % 2 == 1) {  // 行列都是奇数时，正中间那一格自成一且唯一的组
            ans += grid[m / 2][n / 2];  // 孤立的一格必须变成 0，否则 1 的总数除不尽 4
        }  // if 结束

        int diff = 0, cnt1 = 0;  // diff：中间行/列里两数不同、必须翻一次的组数；cnt1：其中已是 11 的组贡献的 1 的个数
        if (m % 2 == 1) {  // 行数为奇数时处理中间行
            for (int j = 0; j < n / 2; ++j) {  // 中间行的左半部分与右半部分配对
                if (grid[m / 2][j] == grid[m / 2][n - j - 1]) {  // 配对的两个数相同，可以一起变 0 或一起变 1
                    cnt1 += grid[m / 2][j] * 2;  // 都是 1 时这一对贡献 2 个 1，先记下来
                } else {  // 两个数不同：只翻转其中一个是必须的，翻完只剩奇数个 1
                    diff += 1;  // 记一个「必翻一次」的组
                }  // if 结束
            }  // for 结束
        }  // if 结束
        if (n % 2 == 1) {  // 列数为奇数时处理中间列，逻辑与中间行相同
            for (int i = 0; i < m / 2; ++i) {  // 中间列的上半部分与下半部分配对
                if (grid[i][n / 2] == grid[m - i - 1][n / 2]) {  // 配对的两个数相同
                    cnt1 += grid[i][n / 2] * 2;  // 都是 1 时贡献 2 个 1
                } else {  // 两个数不同，必须翻一个
                    diff += 1;  // 记一个「必翻一次」的组
                }  // if 结束
            }  // for 结束
        }  // if 结束
        // 若已有的 1 个数已是 4 的倍数，或存在 diff 组可调节，就只加 diff；
        // 否则只能额外翻 2 次把某一对 11 拆成 00
        ans += cnt1 % 4 == 0 || diff > 0 ? diff : 2;  // 收尾：每个 diff 组翻一次会改变 1 的个数的奇偶，可用来把总数调成 4 的倍数
        return ans;  // 返回最少翻转次数
    }  // 方法结束
};  // 类结束
