# 题目：3247. 奇数和子序列的数量（Number of Subsequences with Odd Sum）
# 思路：动态规划，f[0]/f[1] 分别记录偶数和的子序列数与奇数和的子序列数，按当前元素的奇偶性转移。
# 时间复杂度：O(n)，只需遍历一次数组；空间复杂度：O(1)，只用了常数个状态。
class Solution:  # # LeetCode 约定的题解类
    def subsequenceCount(self, nums: List[int]) -> int:  # # nums 为输入数组，返回和是奇数的非空子序列个数（对 1e9+7 取模）
        mod = 10**9 + 7  # # 取模常数，防止答案过大
        f = [0] * 2  # # f[0] 是偶数和的子序列数，f[1] 是奇数和的子序列数；空序列不计入，故初值都是 0
        for x in nums:  # # 逐个把元素加入考虑范围
            if x % 2:  # # 分情况讨论 x 的奇偶性：非 0 即奇数
                f[0], f[1] = (f[0] + f[1]) % mod, (f[0] + f[1] + 1) % mod  # # 元组赋值先算右边旧值：新偶 = f[0]+f[1]，新奇 = f[0]+f[1]+只选 x 的 1
            else:  # # x 是偶数时
                f[0], f[1] = (f[0] + f[0] + 1) % mod, (f[1] + f[1]) % mod  # # 新偶 = f[0]+f[0]+只选 x 的 1，新奇 = f[1]+f[1]
        return f[1]  # # 返回奇数和的子序列总数
