// 题目：3247. 奇数和子序列的数量（Number of Subsequences with Odd Sum）
// 思路：动态规划，f[0]/f[1] 分别记录偶数和的子序列数与奇数和的子序列数，按当前元素的奇偶性转移。
// 时间复杂度：O(n)，只需遍历一次数组；空间复杂度：O(1)，只用了常数个状态。
class Solution {  // // LeetCode 约定的题解类
public:  // // 题解方法对外可见
    int subsequenceCount(vector<int>& nums) {  // // nums 为输入数组，返回和是奇数的非空子序列个数（对 1e9+7 取模）
        const int mod = 1e9 + 7;  // // 取模常数，防止答案过大溢出
        vector<int> f(2);  // // f[0] 是偶数和的子序列数，f[1] 是奇数和的子序列数；空序列不计入，故初值都是 0
        for (int x : nums) {  // // 逐个把元素加入考虑范围
            vector<int> g(2);  // // g 保存加入 x 之后的新状态，先开一个临时数组
            if (x % 2 == 1) {  // // 分情况讨论 x 的奇偶性
                g[0] = (f[0] + f[1]) % mod;  // // x 是奇数：不选 x 仍为偶，选 x 则奇偶翻转，所以新偶数 = f[0] + f[1]
                g[1] = (f[0] + f[1] + 1) % mod;  // // 新奇数 = f[0] + f[1]，再加只选 x 本身这一个子序列的 +1
            } else {  // // x 是偶数时
                g[0] = (f[0] + f[0] + 1) % mod;  // // 不选与选 x 都还是偶，再加只选 x 本身：新偶数 = f[0] + f[0] + 1
                g[1] = (f[1] + f[1]) % mod;  // // 选或不选 x 都仍是奇：新奇数 = f[1] + f[1]
            }  // // 奇偶分支结束
            f = g;  // // 用新状态覆盖旧状态，进入下一轮
        }  // // 数组遍历结束
        return f[1];  // // 返回奇数和的子序列总数
    }  // // 方法结束
};  // // 类结束
