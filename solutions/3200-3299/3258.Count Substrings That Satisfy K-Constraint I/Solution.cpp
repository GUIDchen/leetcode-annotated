// 题目：3258. 统计满足 K 约束的子字符串数量 I（Count Substrings That Satisfy K-Constraint I）
// 思路：滑动窗口。窗口 [l, r] 内 '0' 与 '1' 的个数都不超过 k 时才合法；右端每扩张一格，若两种字符同时超过 k 就让左端收缩，此时以 r 结尾的合法子串恰有 r-l+1 个，累加即为答案。
// 时间复杂度：O(n)，l 与 r 各自只向右移动；空间复杂度：O(1)，只用一个长度为 2 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外公开
    int countKConstraintSubstrings(string s, int k) {  // s 只含 '0' 和 '1'，k 为每种字符个数上限；返回满足 K 约束的子串数量
        int cnt[2]{};  // cnt[0]、cnt[1] 分别统计窗口内 '0' 与 '1' 的个数，默认初始化为 0
        int ans = 0, l = 0;  // ans 累计答案，l 是滑动窗口的左端点
        for (int r = 0; r < s.length(); ++r) {  // 右端点 r 从左到右逐个扩张窗口
            cnt[s[r] - '0']++;  // 把当前字符计入对应计数（'0' - '0' = 0，'1' - '0' = 1）
            while (cnt[0] > k && cnt[1] > k) {  // 两种字符同时超过 k 时窗口不合法，需要收缩左端点
                cnt[s[l++] - '0']--;  // 左端字符移出窗口，并把 l 右移一位
            }  // 收缩到窗口重新合法为止
            ans += r - l + 1;  // 以 r 结尾且起点落在 [l, r] 的子串都合法，共 r-l+1 个
        }  // 右端点遍历结束
        return ans;  // 返回满足 K 约束的子字符串总数
    }  // 方法结束
};  // 类定义结束
