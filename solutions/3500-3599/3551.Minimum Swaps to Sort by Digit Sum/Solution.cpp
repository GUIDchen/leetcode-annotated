// 题目：3551. 数位和排序需要的最小交换次数（Minimum Swaps to Sort by Digit Sum）
// 思路：把每个元素换成键 (数位和, 数值) 并排序，得到目标排列；记录每个数值的目标下标，把“原下标 → 目标下标”的映射拆成若干置换环，长度 L 的环需要 L-1 次交换，故答案为 n 减去环的个数。
// 时间复杂度：O(n log n)，排序主导，环的遍历是 O(n)；空间复杂度：O(n)，存放键数组、位置表和访问标记。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int f(int x) {  // f：计算整数 x 的十进制数位和
        int s = 0;  // s：累计数位和
        while (x) {  // 逐位拆分，直到 x 为 0
            s += x % 10;  // 累加最低位上的数字
            x /= 10;  // 去掉最低位，继续处理更高位
        }  // 循环结束，s 即数位和
        return s;  // 返回数位和
    }  // 辅助函数与主方法之间的空行

    int minSwaps(vector<int>& nums) {  // 返回把数组按（数位和，数值）升序排好所需的最小交换次数
        int n = nums.size();  // n：数组长度
        vector<pair<int, int>> arr(n);  // arr：每个元素的目标二元组（数位和，数值）
        for (int i = 0; i < n; ++i) arr[i] = {f(nums[i]), nums[i]};  // 按题目比较规则生成排序键，排序后的顺序就是目标顺序
        sort(arr.begin(), arr.end());  // pair 默认先比数位和再比数值，正是题目要求的排序规则
        unordered_map<int, int> d;  // d：数值 -> 它在目标顺序中的下标位置
        for (int i = 0; i < n; ++i) d[arr[i].second] = i;  // 记录每个数值的目标下标（数值互不相同，可直接作键）
        vector<char> vis(n, 0);  // vis：目标位置是否已在某个置换环中被访问过
        int ans = n;  // ans 初值取 n，每识别出一个置换环就减 1，最终等于 n 减去环的个数
        for (int i = 0; i < n; ++i) {  // 枚举每个起点位置
            if (!vis[i]) {  // 尚未访问，说明进入了一个新的置换环
                --ans;  // 长度为 L 的环只需 L-1 次交换，这里先统一扣掉一份
                int j = i;  // j：环内的游标位置
                while (!vis[j]) {  // 沿“当前元素应去的位置”一路走，直到回到已访问点
                    vis[j] = 1;  // 标记该位置已访问
                    j = d[nums[j]];  // nums[j] 的目标下标就是置换关系中的下一个节点
                }  // 环内遍历结束
            }  // 新环处理完毕
        }  // 所有位置处理完毕
        return ans;  // 交换次数 = Σ(环长-1) = n - 环的个数
    }  // 方法结束
};  // 类定义结束
