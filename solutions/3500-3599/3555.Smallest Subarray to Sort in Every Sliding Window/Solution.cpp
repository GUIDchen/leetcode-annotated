// 题目：3555. 排序每个滑动窗口中最小的子数组（Smallest Subarray to Sort in Every Sliding Window）
// 思路：对每个长度为 k 的窗口，用一次循环同时从左、从右向中间扫描：左起扫描记录最右的“比前面最大值小”的位置（右端点 r），右起扫描记录最左的“比后面最小值大”的位置（左端点 l），区间 [l, r] 就是需要排序的最短子数组；若整段有序则答案为 0。
// 时间复杂度：O(n·k)，每个窗口线性扫描一次；空间复杂度：O(k)，只存每个窗口的答案（不计输出则为 O(1)）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> minSubarraySort(vector<int>& nums, int k) {  // nums：给定数组；k：窗口长度；返回每个窗口的最短排序子数组长度
        const int inf = 1 << 30;  // inf：足够大的哨兵值，用作最小/最大值的初值
        int n = nums.size();  // n：数组长度
        auto f = [&](int i, int j) -> int {  // f：求闭区间 [i, j] 内需要排序的最短子数组长度
            int mi = inf, mx = -inf;  // mi、mx：右起/左起扫描时分别见过的最小值、最大值
            int l = -1, r = -1;  // l、r：需要排序区间的左、右端点，先置为 -1 表示尚未出现乱序
            for (int k = i; k <= j; ++k) {  // 一次循环同时从左、从右向中间扫描
                if (nums[k] < mx) {  // 左起扫描：当前值比历史最大值小，说明它必须参与排序
                    r = k;  // 记录最靠右的乱序位置
                } else {  // 当前值不小于历史最大值，说明它已处在正确位置
                    mx = nums[k];  // 更新历史最大值
                }  // 左起判断结束
                int p = j - k + i;  // p：与 k 关于区间中点对称的、从右往左的下标
                if (nums[p] > mi) {  // 右起扫描：当前值比历史最小值大，说明它必须参与排序
                    l = p;  // 记录最靠左的乱序位置
                } else {  // 当前值不大于历史最小值，说明它已处在正确位置
                    mi = nums[p];  // 更新历史最小值
                }  // 右起判断结束
            }  // 扫描结束
            return r == -1 ? 0 : r - l + 1;  // 没有乱序则整段已有序返回 0，否则区间长度 r-l+1 即答案
        };  // lambda 定义结束
        vector<int> ans;  // ans：每个窗口的答案
        for (int i = 0; i < n - k + 1; ++i) {  // 枚举所有长度为 k 的窗口起点
            ans.push_back(f(i, i + k - 1));  // 计算并收集该窗口的最短排序子数组长度
        }  // 窗口枚举结束
        return ans;  // 返回全部窗口的结果
    }  // 方法结束
};  // 类定义结束