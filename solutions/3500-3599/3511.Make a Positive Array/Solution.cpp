// 题目：3511. 构造正数组（Make a Positive Array）
// 思路：一次扫描做贪心。s 是当前窗口的和，preMx 是窗口内更短子数组和的最大值；窗口长度达到 3 后若 s <= preMx，说明窗口里已出现和不为正的子数组，必须修改一次，于是答案加一，并以当前位置为新窗口起点重新累计。窗口长度不足 3 时只更新 preMx。
// 时间复杂度：O(n)，只扫描一遍数组；空间复杂度：O(1)，只用了几个常数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int makeArrayPositive(vector<int>& nums) {  // nums：可修改的数组；返回需要的最少修改次数
        int ans = 0;  // 记录需要做的修改次数
        long long preMx = 0, s = 0;  // s：当前窗口和；preMx：窗口内更短子数组和的最大值（用 long long 防溢出）
        for (int l = -1, r = 0; r < nums.size(); r++) {  // l 是窗口左边界的前一个下标（-1 表示从数组开头算起），r 向右扫描
            int x = nums[r];  // 当前元素
            s += x;  // 累加到窗口和
            if (r - l > 2 && s <= preMx) {  // 窗口长度至少 3，且存在和更小或相等的子数组，说明已出现非正和的子数组
                ans++;  // 必须做一次修改
                l = r;  // 以当前位置为新窗口起点，之前的元素不再参与
                preMx = s = 0;  // 重置窗口和与子数组和的最大值
            } else if (r - l >= 2) {  // 否则窗口长度至少 2 时，更新更短子数组和的最大值
                preMx = max(preMx, s - x - nums[r - 1]);  // s - x - nums[r-1] 就是窗口内以 r-2 结尾的那个子数组的和
            }  // 判定结束
        }  // 扫描结束
        return ans;  // 返回最少修改次数
    }  // 方法结束
};  // 类定义结束