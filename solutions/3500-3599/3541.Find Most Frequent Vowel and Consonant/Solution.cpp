// 题目：3541. 找到频率最高的元音和辅音（Find Most Frequent Vowel and Consonant）
// 思路：统计每个字母的出现次数，再分别取元音字母与辅音字母中的最大次数，两者相加即为答案。
// 时间复杂度：O(n + 26)，n 为字符串长度，只需扫一遍字符串和 26 个字母；空间复杂度：O(26)，即 O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxFreqSum(string s) {  // s：只含小写字母的输入字符串
        int cnt[26]{};  // 计数数组：cnt[i] 表示字母 'a' + i 的出现次数，花括号把数组初始化为 0
        for (char c : s) {  // 遍历字符串中的每个字符
            ++cnt[c - 'a'];  // 把字符映射到 0~25 的下标并累加计数
        }
        int a = 0, b = 0;  // a 记录最高元音频率，b 记录最高辅音频率
        for (int i = 0; i < 26; ++i) {  // 枚举全部 26 个小写字母
            char c = 'a' + i;  // 还原出下标 i 对应的字母
            if (c == 'a' || c == 'e' || c == 'i' || c == 'o' || c == 'u') {  // 判断当前字母是否为五个元音之一
                a = max(a, cnt[i]);  // 是元音，用它去更新最高元音频率
            } else {  // 否则当作辅音处理（未出现的字母次数为 0，不影响结果）
                b = max(b, cnt[i]);  // 用它去更新最高辅音频率
            }
        }
        return a + b;  // 题目要求返回最高元音频率与最高辅音频率之和
    }
};