# 题目：3581. 计算数字中的奇数字母数量 / Count Odd Letters from Number（简单）
# 核心思路：把 n 的每一位数字写成英文单词（0 到 9 的固定表），用一个 26 位整数 mask 记录每个字母出现次数的奇偶性：出现一次就异或对应二进制位，最后 mask 中 1 的个数就是出现奇数次的字母种数。
# 复杂度：时间复杂度 O(log n)，空间复杂度 O(1)。
d = {  # 数字到英文单词的固定映射表
    0: "zero",  # 数字 0 的拼写
    1: "one",  # 数字 1 的拼写
    2: "two",  # 数字 2 的拼写
    3: "three",  # 数字 3 的拼写
    4: "four",  # 数字 4 的拼写
    5: "five",  # 数字 5 的拼写
    6: "six",  # 数字 6 的拼写
    7: "seven",  # 数字 7 的拼写
    8: "eight",  # 数字 8 的拼写
    9: "nine",  # 数字 9 的拼写
}  # 映射表定义结束


class Solution:  # 定义题解类
    def countOddLetters(self, n: int) -> int:  # 返回英文拼写中出现奇数次的字母种数
        mask = 0  # 第 k 位为 1 表示第 k 个字母出现奇数次
        while n:  # 逐位处理 n 的十进制数字
            x = n % 10  # 取出最低位数字
            n //= 10  # 去掉最低位
            for c in d[x]:  # 遍历该数字英文单词的每个字母
                mask ^= 1 << (ord(c) - ord("a"))  # 该字母的奇偶性翻转
        return mask.bit_count()  # 统计二进制中 1 的个数，即出现奇数次的字母种数
