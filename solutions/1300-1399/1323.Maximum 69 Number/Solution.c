// 题目：1323. 6 和 9 组成的最大数字（Maximum 69 Number）
// 思路：把数字转成字符串，把最左边的一个 6 改成 9（位权最高，收益最大），再转回整数。
// 时间复杂度：O(log num)，即十进制位数；空间复杂度：O(log num)，字符缓冲区。
int maximum69Number(int num) {  // 求把 num 中最多一位的 6 翻成 9 后得到的最大数字（判题片段，无需 main）
    char buf[12];  // 12 字节足够容纳 int 的十进制写法及结束符
    sprintf(buf, "%d", num);  // 把整数格式化成字符串，方便逐位查找与替换
    for (int i = 0; buf[i] != '\0'; i++) {  // 从左到右扫描，直到遇到字符串结束符
        if (buf[i] == '6') {  // 找到第一个字符 6
            buf[i] = '9';  // 把它改成 9，靠左的位权更高，这样得到的数最大
            break;  // 只允许翻一位，立即跳出循环
        }  // 字符替换分支结束
    }  // 扫描循环结束
    int ans;  // 用于接收转换结果
    sscanf(buf, "%d", &ans);  // 把修改后的数字串转回整数
    return ans;  // 返回最大值
}  // 函数结束
