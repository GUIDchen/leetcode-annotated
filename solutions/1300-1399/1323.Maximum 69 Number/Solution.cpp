// 题目：1323. 6 和 9 组成的最大数字（Maximum 69 Number）
// 思路：把数字转成字符串，把最左边的一个 6 改成 9（位权最高，收益最大），再转回整数。
// 时间复杂度：O(log num)，即十进制位数；空间复杂度：O(log num)，字符串长度。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maximum69Number(int num) {  // 求把 num 中最多一位的 6 翻成 9 后得到的最大数字
        string s = to_string(num);  // 转成字符串，方便逐位查找与替换
        for (char& ch : s) {  // 用引用遍历，才能原地改写字符
            if (ch == '6') {  // 找到第一个字符 6
                ch = '9';  // 改成 9：越靠左的位权越高，翻转最左边的 6 收益最大
                break;  // 只能翻一位，立即跳出循环
            }  // 字符替换分支结束
        }  // 遍历结束
        return stoi(s);  // 把修改后的字符串转回整数返回
    }  // 方法结束
};  // 类定义结束