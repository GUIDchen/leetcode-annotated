// 题目：1390. 四因数（Four Divisors）
// 思路：辅助函数 f 试除到 sqrt(x)，成对累加因数个数与因数之和；只有恰好 4 个因数时返回和，否则返回 0，外层全部累加。
// 时间复杂度：O(n * sqrt(max(nums)))，每个数枚举到平方根；空间复杂度：O(1)，只使用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int sumFourDivisors(vector<int>& nums) {  // nums：待统计的数组
        int ans = 0;  // 所有「恰好 4 个因数」的数之和
        for (int x : nums) {  // 逐个处理数组中的每个数
            ans += f(x);  // f(x) 返回 x 的四因数之和，x 不满足条件时返回 0
        }  // 循环结束：答案累加完毕
        return ans;  // 返回总和
    }

    int f(int x) {  // 计算 x 的因数之和，仅当因数个数恰为 4 时才有效
        int cnt = 2, s = x + 1;  // 1 和 x 本身已是两个因数，先把个数记为 2、和记为 x + 1
        for (int i = 2; i <= x / i; ++i) {  // 从小到大试除到 sqrt(x)；用 i <= x / i 代替 i * i <= x，避免乘法溢出
            if (x % i == 0) {  // i 能整除 x，说明 i 是一个因数
                ++cnt;  // 因数个数加一
                s += i;  // 把较小的因数 i 累加进和
                if (i * i != x) {  // 配对的另一个因数 x / i 与 i 不同，即 x 不是完全平方数
                    ++cnt;  // 另一半因数个数也要加一
                    s += x / i;  // 把较大的因数 x / i 累加进和
                }  // 内层 if 结束：这一对因数处理完毕
            }  // if 结束：i 不是因数或已处理
        }  // 循环结束：所有小于 sqrt(x) 的因数都枚举过了
        return cnt == 4 ? s : 0;  // 因数个数恰好为 4 才返回和，否则这个数不合格返回 0
    }
};