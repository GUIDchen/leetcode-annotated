// 题目：1351. 统计有序矩阵中的负数（Count Negative Numbers in a Sorted Matrix）
// 思路：矩阵的行、列都非递增，因此从右上角换成左下角出发做阶梯扫描：当前元素非负就右移，为负就说明这一列从当前行往上全是负数，一次累加 n-j 个后上移一行。
// 时间复杂度：O(m + n)，每一步要么右移一列要么上移一行；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countNegatives(vector<vector<int>>& grid) {  // grid：每行非递增、每列也非递增的二维矩阵
        int m = grid.size();  // m：行数
        int n = grid[0].size();  // n：列数
        int i = m - 1;  // i 从最后一行开始向上移动（阶梯扫描的起点是左下角）
        int j = 0;  // j 从第 0 列开始向右移动
        int ans = 0;  // ans 累计负数的个数
        while (i >= 0 && j < n) {  // 只要还在矩阵范围内就继续走阶梯
            if (grid[i][j] >= 0) {  // 当前元素非负，说明本行它左边的元素也都非负，这一格帮不上忙
                j++;  // 右移一列，去寻找本行更靠右（更小）的元素
            } else {  // 否则当前元素已经是负数
                ans += n - j;  // 列单调性保证 grid[i][j..n-1] 全为负，一次性把这 n-j 个负数计入
                i--;  // 这一行剩下的位置都统计完了，上移一行
            }  // else 块结束
        }  // while 循环结束，说明已经走出矩阵边界
        return ans;  // 返回负数总个数
    }  // 方法结束
};  // 类定义结束
