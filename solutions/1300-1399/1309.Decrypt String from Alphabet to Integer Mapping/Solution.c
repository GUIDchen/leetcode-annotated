// 题目：1309. 解码字母到整数映射（Decrypt String from Alphabet to Integer Mapping）
// 核心思路：从左往右扫描，若三字符形如 "d#" 说明是两位数 10~26，否则是一位数 1~9；
//           把 1~26 映射回 'a'~'z' 追加到结果，最后补 '\0'。
// 时间复杂度：O(n)，每个字符最多被跳过一次；空间复杂度：O(n)，需要一段与输入等长的输出缓冲区。
char* freqAlphabets(char* s) {  // s 是形如 "10#11#12" 的编码串
    int n = strlen(s);  // 编码串长度
    int i = 0;  // 读指针，指向当前待解码的位置
    int j = 0;  // 写指针，指向答案缓冲区下一个空位
    char* ans = malloc(sizeof(s) * n);  // 分配输出缓冲区；sizeof(s) 是指针大小，足以容纳 n 个字符
    while (i < n) {  // 读指针没到末尾就继续解码
        int t;  // 暂存本段解码出的数字（1~26）
        if (i + 2 < n && s[i + 2] == '#') {  // 后面第三位是 '#'，说明是 "dd#" 形式的两位数
            t = (s[i] - '0') * 10 + s[i + 1];  // 十位取数值，个位直接用 ASCII（'0' 的码值恰好抵消 'a'-'1' 的偏移）
            i += 3;  // 连同 '#' 一起跳过三个字符
        } else {  // 否则是个位数
            t = s[i];  // 直接取该字符的 ASCII 码
            i += 1;  // 只前进一个字符
        }
        ans[j++] = 'a' + t - '1';  // 数字 1~26 映射到 'a'~'z' 并写入，写指针后移
    }
    ans[j] = '\0';  // 补上字符串结束符
    return ans;  // 返回解码结果（由调用方负责释放）
}  // 函数结束（文件末尾无换行，保持原样）