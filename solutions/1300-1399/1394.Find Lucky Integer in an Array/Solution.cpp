// 题目：1394. 找出数组中的幸运数（Find Lucky Integer in an Array）
// 思路：用计数数组统计每个数值出现的次数，再从大到小扫描，第一个「数值等于出现次数」的数就是最大的幸运数。
// 时间复杂度：O(n + max(arr))，统计一遍加扫描一遍；空间复杂度：O(max(arr))，计数数组长度为 501。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int findLucky(vector<int>& arr) {  // arr：输入数组，元素取值范围 1 ~ 500
        int cnt[501]{};  // 计数数组，cnt[x] 表示数值 x 出现的次数；{} 保证全部初始化为 0
        for (int x : arr) {  // 遍历数组，统计每个数值的频次
            ++cnt[x];  // 数值 x 的出现次数加一
        }  // 统计循环结束
        for (int x = 500; x; --x) {  // 从大到小枚举可能的数值，x 为 0 时条件为假、循环结束
            if (x == cnt[x]) {  // 数值等于它的出现次数，说明 x 是幸运数
                return x;  // 从大往小找，第一个满足条件的就是最大的幸运数
            }  // if 结束
        }  // 扫描循环结束
        return -1;  // 不存在幸运数，按题目要求返回 -1
    }
};