// 题目：1332. 删除回文子序列（Remove Palindromic Subsequences）
// 思路：字符串只含 'a'、'b'。整串是回文就一次删完；否则先删掉所有 'a'、再删掉所有 'b'，两次必然清空，所以答案只会是 1 或 2。
// 时间复杂度：O(n)，双指针判断回文；空间复杂度：O(1)，只用两个下标。
class Solution {  // 题解类
public:  // 对外暴露题解接口
    int removePalindromeSub(string s) {  // s：仅由 'a'、'b' 组成的字符串，返回最少删除次数
        for (int i = 0, j = s.size() - 1; i < j; ++i, --j) {  // 双指针 i、j 从两端向中间比较，判断整串是否为回文
            if (s[i] != s[j]) {  // 出现不对称，说明整串不是回文
                return 2;  // 不是回文时两次就够了：先删所有 'a'，再删所有 'b'
            }  // 判断结束
        }  // 回文检查结束
        return 1;  // 整串是回文，一次删掉全部字符
    }  // 方法结束
};  // 类定义结束