// 题目：1345. 跳跃游戏 IV（Jump Game IV）
// 思路：把每个下标看成图上的点，相邻下标与「值相同」的下标之间连边，用 BFS 逐层扩展求 0 到 n-1 的最短步数；同值点集访问过一次后立刻清空以避免重复枚举。
// 时间复杂度：O(n)，每个下标入队一次、每条「同值边」只被展开一次；空间复杂度：O(n)，存同值下标表、访问数组与队列。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minJumps(vector<int>& arr) {  // arr：输入数组，每次可以从 i 跳到 i-1、i+1 或任意 arr[j] == arr[i] 的位置
        unordered_map<int, vector<int>> g;  // 哈希表：值 → 该值出现的所有下标，相当于图里的「同值跳转边」
        int n = arr.size();  // n 为数组长度，也是目标下标 n-1
        for (int i = 0; i < n; ++i) {  // 一次线性扫描，把每个下标按值分组
            g[arr[i]].push_back(i);  // 把下标 i 挂到它对应的值下面
        }  // 分组完成
        vector<bool> vis(n);  // vis[i] 表示下标 i 是否已经入队，避免重复访问
        queue<int> q{{0}};  // 队列初始只有起点 0
        vis[0] = true;  // 起点标记为已访问
        for (int ans = 0;; ++ans) {  // ans 是当前 BFS 层数，也就是已经跳过的步数；终点一定可达所以上界省略
            for (int k = q.size(); k; --k) {  // 一次处理一整层，先把队列长度固定下来，避免把新入队节点算进本层
                int i = q.front();  // 取出队首下标
                q.pop();  // 弹出队首
                if (i == n - 1) {  // 走到终点就立刻返回当前步数，BFS 保证这是最短的
                    return ans;  // 返回答案
                }  // if 结束
                for (int j : g[arr[i]]) {  // 枚举所有与 arr[i] 同值的下标（同值跳转边）
                    if (!vis[j]) {  // 还没访问过才展开
                        vis[j] = true;  // 标记已访问并入队
                        q.push(j);  // 入队操作
                    }  // 判断结束
                }  // 同值下标循环结束
                g[arr[i]].clear();  // 清空该值的下标表：同值边是双向的，处理完当前值后无需再枚举，这是保证线性复杂度的关键
                for (int j : {i - 1, i + 1}) {  // 再尝试左右相邻下标 i-1 与 i+1
                    if (0 <= j && j < n && !vis[j]) {  // 检查下标合法且未访问
                        vis[j] = true;  // 标记已访问并入队
                        q.push(j);  // 入队操作
                    }  // 判断结束
                }  // 相邻下标循环结束
            }  // 本层处理完毕
        }  // ans 自增进入下一层（循环体外的 ++ans）
    }  // 方法结束
};  // 类定义结束（源文件末尾无换行，逐字节保持不变）
