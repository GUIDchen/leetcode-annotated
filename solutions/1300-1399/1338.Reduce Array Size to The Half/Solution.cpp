// 题目：1338. 数组大小减半（Reduce Array Size to The Half）
// 思路：贪心 + 计数排序。统计每个值出现的次数，把「出现次数」数组按降序排好，从出现最多的值开始删，累计删掉的元素数一旦达到数组长度的一半就停止，此时删掉的数值种类数最少。
// 时间复杂度：O(n + V log V)，V 为最大值域（也可视为 O(n log n)）；空间复杂度：O(V)，计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minSetSize(vector<int>& arr) {  // arr 是待减半的数组，返回最少要删除多少个不同的值
        int mx = ranges::max(arr);  // 数组中的最大值，用来确定计数数组的大小
        int cnt[mx + 1];  // 计数数组：cnt[v] 表示值 v 在数组中出现的次数
        memset(cnt, 0, sizeof(cnt));  // 计数全部清零
        for (int& x : arr) {  // 遍历数组做计数
            ++cnt[x];  // 引用递增，避免拷贝
        }  // 计数结束
        sort(cnt, cnt + mx + 1, greater<int>());  // 只按出现次数降序排序（下标即原来的值，这里不再需要）
        int ans = 0;  // 已删除的「不同值」个数，也就是集合大小
        int m = 0;  // 已删除的元素总个数
        for (int& x : cnt) {  // 从出现次数最多的位置开始贪心选取
            if (x) {  // 跳过没有出现过的值
                m += x;  // 删掉该值全部出现，累计已删元素数
                ++ans;  // 集合大小加一
                if (m * 2 >= arr.size()) {  // 已删元素达到总数的一半（乘 2 避免浮点）
                    break;  // 已经满足要求，提前退出
                }  // 达标判断结束
            }  // 一趟贪心结束
        }  // 遍历结束
        return ans;  // 返回最少删除的不同值个数
    }  // 方法结束
};  // 类定义结束
