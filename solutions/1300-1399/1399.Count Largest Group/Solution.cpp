// 题目：1399. 统计最大组的数目（Count Largest Group）
// 思路：按「十进制数位和」分组计数；边遍历边维护当前最大组的大小，并统计有多少个组达到了这个大小。
// 时间复杂度：O(n * log10 n)，每个数都要拆一遍数位；空间复杂度：O(log10 n)，计数数组只需容纳最大数位和 36。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countLargestGroup(int n) {  // n：统计范围 1 ~ n
        int cnt[40]{};  // cnt[s] 表示数位和为 s 的数字个数；最大数位和不超过 36，所以 40 足够
        int ans = 0, mx = 0;  // ans：达到当前最大组大小的组数；mx：当前最大的组大小
        for (int i = 1; i <= n; ++i) {  // 依次处理 1 ~ n 中的每个数
            int s = 0;  // 当前数字的数位和
            for (int x = i; x; x /= 10) {  // 用临时变量 x 逐位拆解，避免破坏外层循环变量 i
                s += x % 10;  // 取出最低位并累加到数位和
            }  // 内层拆位循环结束
            ++cnt[s];  // 数位和为 s 的这一组计数加一
            if (mx < cnt[s]) {  // 出现了比当前最大组更大的组
                mx = cnt[s];  // 更新最大组大小
                ans = 1;  // 目前只有这一个组达到最大，重置计数为 1
            } else if (mx == cnt[s]) {  // 该组追平了当前的最大组
                ++ans;  // 达到最大组大小的组数加一
            }  // if-else 结束
        }  // 外层遍历结束
        return ans;  // 返回达到最大大小的组数
    }
};