// 题目：1328. 破坏回文串（Break a Palindrome）
// 思路：贪心。在前半段找第一个不是 'a' 的字符改成 'a'，这样字典序最小；若前半段全是 'a'，就把最后一个字符改成 'b'，这是唯一不破坏字典序优势的改法。
// 时间复杂度：O(n)，只扫描前半段；空间复杂度：O(1)，原地修改（入参按值传递）。
class Solution {  // 题解类
public:  // 对外暴露题解接口
    string breakPalindrome(string palindrome) {  // palindrome：给定的回文串，返回破坏回文后的最小字典序串
        int n = palindrome.size();  // 字符串长度
        if (n == 1) {  // 长度为 1 时无论怎么改都不可能是非回文
            return "";  // 按题意返回空串
        }  // 长度判断结束
        int i = 0;  // i 为从左开始的扫描下标
        while (i < n / 2 && palindrome[i] == 'a') {  // 只看前半段，找第一个不是 'a' 的位置（'a' 已是最小字符，改成 'a' 没有意义）
            ++i;  // 跳过 'a' 继续往后找
        }  // 查找结束
        if (i == n / 2) {  // 前半段全是 'a'，改前面任何位置都会得到更小的回文，只能动尾部
            palindrome[n - 1] = 'b';  // 把最后一个字符改成 'b'：既破坏回文，又让字典序尽量小
        } else {  // 否则后半段分支
            palindrome[i] = 'a';  // 把第一个非 'a' 的字符改成 'a'，字典序最小
        }  // 分支结束
        return palindrome;  // 返回破坏后的字符串
    }  // 方法结束
};  // 类定义结束