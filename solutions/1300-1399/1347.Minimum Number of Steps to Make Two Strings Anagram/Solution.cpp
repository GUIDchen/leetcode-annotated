// 题目：1347. 制造字母异位词的最小步骤数（Minimum Number of Steps to Make Two Strings Anagram）
// 思路：先统计 s 的字符频次，再用 t 的字符逐个抵消；某字符被扣成负数说明 s 中数量不够，必须把 s 里的一个字符替换成它，替换一次即一步。
// 时间复杂度：O(n + |Σ|)，两趟线性扫描，字母表大小 26 视作常数；空间复杂度：O(|Σ|) = O(1)，只需一个长度 26 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minSteps(string s, string t) {  // s、t：长度相同的两个字符串，每次操作可把 s 中一个字符改成任意字符
        int cnt[26]{};  // cnt[26] 统计 s 中每个小写字母出现的次数，{} 保证全部初始化为 0
        for (char c : s) {  // 遍历 s 的每个字符
            ++cnt[c - 'a'];  // 把字符 c 映射到 0~25 的下标并计数
        }  // s 的频次统计完成
        int ans = 0;  // ans 记录需要替换的步数
        for (char c : t) {  // 遍历 t 的每个字符，用 s 的频次逐个抵消
            if (--cnt[c - 'a'] < 0) {  // 先减 1 再判断：若减完小于 0，说明 s 中该字符不够用
                ++ans;  // 不够用就意味着 s 里要有一个别的字符被改成它，步数加一
            }  // if 语句结束
        }  // t 的遍历结束
        return ans;  // 返回最小替换步数
    }  // 方法结束
};  // 类定义结束
