// 题目：3446. 按对角线进行矩阵排序（Sort Matrix by Diagonals）
// 思路：题目要求左下三角（i >= j）的同一条对角线从左上到右下递减、右上三角（i < j）从左上到右下递增。①把每条对角线元素取出升序排序，再从左下端点倒着回填，就得到递减；②把元素升序排序后从右上端点正着回填，就得到递增。两种回填共用「先排序、再按方向填回」的套路，靠 i/j 的 ++ 与 -- 控制方向。
// 时间复杂度：O(n² log n)，共 2n-1 条对角线、每条排序 O(n log n)；空间复杂度：O(n)，每条对角线最多暂存 n 个元素。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<vector<int>> sortMatrix(vector<vector<int>>& grid) {  // grid：n×n 方阵，原地排序后返回
        int n = grid.size();  // n 是方阵边长
        for (int k = n - 2; k >= 0; --k) {  // 第一轮：处理左下半区（i >= j）的对角线，k 是它落在左边界上的行号
            int i = k, j = 0;  // 从这条对角线的左下端点 (k, 0) 出发
            vector<int> t;  // t 暂存这条对角线上的所有元素
            while (i < n && j < n) {  // 沿右上方向走，直到出界为止
                t.push_back(grid[i++][j++]);  // 取当前元素，然后同时下移一行、右移一列
            }
            ranges::sort(t);  // 升序排序，稍后倒着回填才能变成递减
            for (int x : t) {  // 按升序依次回填
                grid[--i][--j] = x;  // 此时 (i, j) 已出界，先退回一格再写：从右上往左下填入升序值，使对角线沿右上方向递减
            }
        }
        for (int k = n - 2; k > 0; --k) {  // 第二轮：处理右上半区（i < j）的对角线，k 是它落在右边界上的行号
            int i = k, j = n - 1;  // 从这条对角线的右上端点 (k, n - 1) 出发
            vector<int> t;  // t 暂存这条对角线上的所有元素
            while (i >= 0 && j >= 0) {  // 沿左下方向走，直到出界为止
                t.push_back(grid[i--][j--]);  // 取当前元素，然后同时上移一行、左移一列
            }
            ranges::sort(t);  // 升序排序，正着回填即可得到递增
            for (int x : t) {  // 按升序依次回填
                grid[++i][++j] = x;  // 此时 (i, j) 已出界，先退回一格再写：从左上往右下填入升序值，使对角线沿右下方向递增
            }
        }
        return grid;  // 返回原地排序后的矩阵
    }  // 方法结束
};  // 类定义结束
