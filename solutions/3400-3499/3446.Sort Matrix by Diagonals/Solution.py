# 题目：3446. 按对角线进行矩阵排序（Sort Matrix by Diagonals）
# 思路：题目要求左下三角（i >= j）的同一条对角线从左上到右下递减、右上三角（i < j）从左上到右下递增。①把每条对角线元素取出升序排序，再从左下端点用 pop() 取最大值回填，就得到递减；②把元素升序排序后从右上端点同样取最大值回填，就得到递增。两种回填共用「先排序、再按方向填回」的套路，靠 i/j 的 += 与 -= 控制方向。
# 时间复杂度：O(n² log n)，共 2n-1 条对角线、每条排序 O(n log n)；空间复杂度：O(n)，每条对角线最多暂存 n 个元素。
class Solution:  # LeetCode 约定的题解类
    def sortMatrix(self, grid: List[List[int]]) -> List[List[int]]:  # grid：n×n 方阵，原地排序后返回
        n = len(grid)  # n 是方阵边长
        for k in range(n - 2, -1, -1):  # 第一轮：处理左下半区（i >= j）的对角线，k 是它落在左边界上的行号
            i, j = k, 0  # 从这条对角线的左下端点 (k, 0) 出发
            t = []  # t 暂存这条对角线上的所有元素
            while i < n and j < n:  # 沿右上方向走，直到出界为止
                t.append(grid[i][j])  # 收集当前元素
                i += 1  # 行号加一，向下一行
                j += 1  # 列号加一，向右一列
            t.sort()  # 升序排序
            i, j = k, 0  # 重新回到这条对角线的起点，准备回填
            while i < n and j < n:  # 再沿右上方向走一遍
                grid[i][j] = t.pop()  # pop() 取当前最大值先填在左下起点，使对角线沿右上方向递减
                i += 1  # 行号加一，向下一行
                j += 1  # 列号加一，向右一列
        for k in range(n - 2, 0, -1):  # 第二轮：处理右上半区（i < j）的对角线，k 是它落在右边界上的行号
            i, j = k, n - 1  # 从这条对角线的右上端点 (k, n - 1) 出发
            t = []  # t 暂存这条对角线上的所有元素
            while i >= 0 and j >= 0:  # 沿左下方向走，直到出界为止
                t.append(grid[i][j])  # 收集当前元素
                i -= 1  # 行号减一，向上一行
                j -= 1  # 列号减一，向左一列
            t.sort()  # 升序排序
            i, j = k, n - 1  # 重新回到这条对角线的起点，准备回填
            while i >= 0 and j >= 0:  # 再沿左下方向走一遍
                grid[i][j] = t.pop()  # pop() 取当前最大值先填在右上起点，使对角线沿左下方向递减（也就是沿右上方向递增）
                i -= 1  # 行号减一，向上一行
                j -= 1  # 列号减一，向左一列
        return grid  # 返回原地排序后的矩阵
