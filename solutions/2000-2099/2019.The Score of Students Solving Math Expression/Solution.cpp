// 题目：2019. 解出数学表达式的学生分数（The Score of Students Solving Math Expression）
// 思路：先用 cal 按标准优先级算出正确答案（答对得 5 分）；再用区间 DP，f[i][j] 保存第 i 到第 j 个数字所有可能的结果，凡落在 f[0][m-1] 中且不等于正确答案的答案得 2 分。
// 时间复杂度：O(m^3 * V^2)，m 为数字个数、V 为区间可能取值数（结果剪枝到 1000 以内）；空间复杂度：O(m^2 * V)，二维集合表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int scoreOfStudents(string s, vector<int>& answers) {  // s：表达式字符串；answers：学生作答的答案列表
        int n = s.size();  // 表达式长度（数字与运算符交替出现）
        int x = cal(s);  // 按标准优先级算出的正确答案
        int m = (n + 1) >> 1;  // 数字个数：长度为 2m - 1
        unordered_set<int> f[m][m];  // 区间 DP 表：f[i][j] 是第 i 到第 j 个数字所有可能的运算结果
        for (int i = 0; i < m; ++i) {  // 初始化长度为 1 的区间
            f[i][i] = {s[i * 2] - '0'};  // 单个数字只有它本身一种结果（数字位于下标 2i）
        }  // 单数字区间初始化结束
        for (int i = m - 1; ~i; --i) {  // 左端点从右往左枚举（~i 等价于 i >= 0），保证依赖的子区间已算好
            for (int j = i; j < m; ++j) {  // 枚举右端点
                for (int k = i; k < j; ++k) {  // 枚举最后一次运算，把区间切成 [i, k] 与 [k+1, j]
                    for (int l : f[i][k]) {  // 遍历左半区间的所有可能值
                        for (int r : f[k + 1][j]) {  // 遍历右半区间的所有可能值
                            char op = s[k << 1 | 1];  // 取两数字之间的运算符，位置是 2k + 1
                            if (op == '+' && l + r <= 1000) {  // 加法结果超过 1000 时学生答案不可能命中，剪枝
                                f[i][j].insert(l + r);  // 记录加法得到的结果
                            } else if (op == '*' && l * r <= 1000) {  // 乘法同样只保留 1000 以内的结果
                                f[i][j].insert(l * r);  // 记录乘法得到的结果
                            }  // 运算符分支结束
                        }  // 右半区间取值遍历结束
                    }  // 左半区间取值遍历结束
                }  // 切分点枚举结束
            }  // 右端点枚举结束
        }  // 左端点枚举结束
        int cnt[1001]{};  // 统计每个答案的人数：答案范围是 0 到 1000，超出范围的答案不得分
        for (int t : answers) {  // 遍历学生答案
            ++cnt[t];  // 对应答案的人数加一
        }  // 答案统计结束
        int ans = 5 * cnt[x];  // 答对的学生每人 5 分
        for (int i = 0; i <= 1000; ++i) {  // 枚举所有可能的答案取值
            if (i != x && f[0][m - 1].count(i)) {  // 不是正确答案，但确实是某种合法运算顺序能得到的结果
                ans += cnt[i] << 1;  // 这类学生每人 2 分（左移一位等于乘 2）
            }  // 计分分支结束
        }  // 取值枚举结束
        return ans;  // 返回全班总得分
    }  // scoreOfStudents 方法结束

    int cal(string& s) {  // 辅助函数：按乘除优先于加减的标准规则计算表达式
        int res = 0;  // res 累计已经确定可以结算的部分
        int pre = s[0] - '0';  // pre 保存当前待定项的数值
        for (int i = 1; i < s.size(); i += 2) {  // 每一步跳过一个运算符和一个数字
            int cur = s[i + 1] - '0';  // 取运算符右边紧跟的数字
            if (s[i] == '*') {  // 遇到乘号：立即并入待定项，体现先乘后加
                pre *= cur;  // 先把乘法算完，保证优先级
            } else {  // 遇到加号：说明前面的项可以结算了
                res += pre;  // 把待定项 pre 计入总和
                pre = cur;  // 新的待定项从 cur 开始
            }  // 运算符分支结束
        }  // 表达式遍历结束
        res += pre;  // 加上最后剩下的那一项
        return res;  // 返回标准优先级下的正确答案
    }  // cal 函数结束
};  // Solution 类定义结束