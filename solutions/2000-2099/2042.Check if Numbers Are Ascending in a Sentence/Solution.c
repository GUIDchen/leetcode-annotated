// 题目：2042. 检查句子中的数字是否递增（Check if Numbers Are Ascending in a Sentence）
// 思路：一次扫描，用 cur 累积当前数字，遇到非数字字符时与上一个数字 pre 比较；扫描结束后再补一次末尾数字的比较。
// 时间复杂度：O(n)，每个字符只访问一次；空间复杂度：O(1)，只用两个整型变量。
bool areNumbersAscending(char* s) {  // s：只含小写字母、空格和数字的句子；返回数字序列是否严格递增
    int pre = -1;  // pre：上一个读到的数字，初始为 -1 保证第一个数字一定更大
    int cur = 0;  // cur：正在读取的数字，0 表示当前不在数字中
    for (int i = 0; s[i]; i++) {  // 逐字符扫描，遇到字符串结束符时停止
        if (isdigit(s[i])) {  // 当前字符是数字
            cur = cur * 10 + s[i] - '0';  // 把这一位并进 cur：旧值乘 10 再加上该位的数值
        } else {  // 遇到非数字字符，说明一个数字可能刚刚读完
            if (cur != 0) {  // cur 不为 0 说明前面确实读到了数字
                if (cur <= pre) {  // 当前数字不大于上一个数字，说明不是严格递增
                    return 0;  // 返回 false（C 里用 0 表示）
                }
                pre = cur;  // 把这个数字记为新的比较基准
                cur = 0;  // 清零，准备读取下一个数字
            }
        }
    }
    if (cur != 0 && cur <= pre) {  // 扫描结束时末尾还可能残留一个尚未比较的数字
        return 0;  // 末尾数字不大于前一个数字，返回 false（0）
    }
    return 1;  // 全部数字严格递增，返回 true（1）
}