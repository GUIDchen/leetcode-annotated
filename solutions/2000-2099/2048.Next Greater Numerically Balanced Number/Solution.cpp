// 题目：2048. 下一个更大的数值平衡数（Next Greater Numerically Balanced Number）
// 思路：从 n+1 开始逐个枚举，先统计每个数字出现次数，再验证每个出现的数字 d 恰好出现 d 次，第一个满足的数就是答案。
// 时间复杂度：O(k · log n)，k 为要跳过的候选个数，每个数按位数检查；空间复杂度：O(1)，只用了长度为 10 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int nextBeautifulNumber(int n) {  // n：给定的下界；返回严格大于 n 的最小数值平衡数
        for (int x = n + 1;; ++x) {  // 从小到大枚举候选数，条件省略上界，找到答案就 return
            int cnt[10]{};  // cnt[d] 记录数字 d 在 x 的十进制表示中出现的次数，花括号零初始化
            for (int y = x; y > 0; y /= 10) {  // 逐位拆解 x
                ++cnt[y % 10];  // 最低位数字的计数加一
            }  // 结束拆位循环
            bool ok = true;  // 先假设 x 是数值平衡数
            for (int y = x; y > 0; y /= 10) {  // 再逐位验证：每一位上的数字 d 必须恰好出现 d 次
                if (y % 10 != cnt[y % 10]) {  // 该位的数字与它出现的次数不相等
                    ok = false;  // 标记不满足条件
                    break;  // 无需再检查其他位
                }  // 结束相等性判断
            }  // 结束验证循环
            if (ok) {  // 所有位都满足要求
                return x;  // x 就是最小的答案，直接返回
            }  // 结束判断
        }  // 继续枚举下一个数
    }  // 方法结束
};  // 题解类结束