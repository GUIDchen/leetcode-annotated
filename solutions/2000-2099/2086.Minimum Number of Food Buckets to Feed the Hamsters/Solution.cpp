// 题目：2086. 喂食仓鼠的最小食物桶数（Minimum Number of Food Buckets to Feed the Hamsters）
// 思路：贪心。一个桶最多喂左右两只仓鼠，所以扫描时遇到仓鼠优先在它右侧放桶（可顺带喂到下一只），右侧不行再看左侧是否已有桶可放，两边都不行说明无解。
// 时间复杂度：O(n)，n 为街道长度，只从左到右扫一遍；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumBuckets(string street) {  // street：只含 'H'（仓鼠）与 '.'（空地）的街道字符串；返回最少桶数，无解返回 -1
        int n = street.size();  // 街道长度，后面判断右边是否越界要用
        int ans = 0;  // 累计需要的食物桶数
        for (int i = 0; i < n; ++i) {  // 从左到右逐个位置扫描；i 会在放桶后主动跳跃
            if (street[i] == 'H') {  // 只有仓鼠这一格才需要被喂食
                if (i + 1 < n && street[i + 1] == '.') {  // 优先把桶放在仓鼠右边：同一个桶还能喂到右邻格的那只仓鼠
                    ++ans;  // 桶数加一
                    i += 2;  // 右边这一格放桶并喂饱当前仓鼠，跳过它继续往后扫，避免重复计数
                } else if (i && street[i - 1] == '.') {  // 右边不能放桶时，退而看左边是否已放桶或为空地
                    ++ans;  // 在左侧放一个桶，这个桶只能喂当前这一只仓鼠
                } else {  // 左右两侧都无法放桶
                    return -1;  // 当前仓鼠永远喂不到，题目无解
                }  // 结束「左右放桶」分支
            }  // 结束「当前是仓鼠」判断
        }  // 结束整条街道的扫描
        return ans;  // 返回最少桶数
    }  // 结束 minimumBuckets 方法
};  // 结束 Solution 类