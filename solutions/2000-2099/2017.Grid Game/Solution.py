# 题目：2017. 网格游戏（Grid Game）
# 思路：枚举机器人一在第一行第 j 列向下拐弯，之后机器人二只能选第一行 j 右侧的后缀和或第二行 j 左侧的前缀和中的较大者；对所有 j 取这个最大值的最小值。
# 时间复杂度：O(n)，只扫一遍数组；空间复杂度：O(1)，仅常数个变量。
class Solution:  # LeetCode 约定的题解类
    def gridGame(self, grid: List[List[int]]) -> int:  # grid：2 行 n 列的网格，返回机器人二在双方最优策略下的最大得分
        ans = inf  # 用正无穷作初值，保证第一次比较一定会被更新
        s1, s2 = sum(grid[0]), 0  # s1 是第一行剩余后缀和，初始为第一行总和；s2 是第二行已走过部分的前缀和
        for j, v in enumerate(grid[0]):  # 枚举机器人一向下拐弯的列 j，同时拿到该列上第一行的值 v
            s1 -= v  # 机器人一取走 (0, j)，s1 变为第一行 j 之后的后缀和
            ans = min(ans, max(s1, s2))  # 机器人二走剩余和更大的一侧，取最大后再与 ans 取最小
            s2 += grid[1][j]  # (1, j) 已被机器人一拿走，将其更新进第二行前缀和
        return ans  # 返回机器人二能确保拿到的最大分数
