# 题目：2027. 转换字符串的最少操作次数（Minimum Moves to Convert String）
# 思路：贪心从左往右扫，遇到 'X' 就必须操作一次，且把操作起点定在这个 'X' 上最不浪费，一次操作可覆盖它和后面两位。
# 时间复杂度：O(n)，下标只前进不后退；空间复杂度：O(1)，只用常数个变量。
class Solution:  # LeetCode 约定的题解类
    def minimumMoves(self, s: str) -> int:  # s 是只含 'O'/'X' 的字符串，返回把所有 'X' 变成 'O' 的最少操作次数
        ans = i = 0  # ans 记录操作次数，i 是当前扫描到的下标
        while i < len(s):  # 从左到右逐位扫描，直到串尾
            if s[i] == "X":  # 遇到 'X' 必须处理，且越靠左处理覆盖范围越不会浪费
                ans += 1  # 执行一次「连续三位取反」的操作
                i += 3  # 这次操作影响 i、i+1、i+2 三位，直接跳过三个字符
            else:  # 否则当前位是 'O'，无需操作
                i += 1  # 只前进一位继续检查
        return ans  # 返回最少操作次数
