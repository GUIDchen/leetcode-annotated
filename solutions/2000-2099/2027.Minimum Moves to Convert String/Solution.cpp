// 题目：2027. 转换字符串的最少操作次数（Minimum Moves to Convert String）
// 思路：贪心从左往右扫，遇到 'X' 就必须操作一次，且把操作起点定在这个 'X' 上最不浪费，一次操作可覆盖它和后面两位。
// 时间复杂度：O(n)，下标只前进不后退；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumMoves(string s) {  // s：只含 'O'/'X' 的字符串；返回把所有 'X' 变成 'O' 的最少操作次数
        int ans = 0;  // ans 记录已执行的操作次数
        for (int i = 0; i < s.size(); ++i) {  // 从左到右扫描字符串
            if (s[i] == 'X') {  // 遇到 'X' 必须处理，且越靠左处理，覆盖范围越不会浪费
                ++ans;  // 执行一次「连续三位取反」的操作
                i += 2;  // 本次操作覆盖 i、i+1、i+2，再配合循环的 ++i 正好跳过三个字符
            }  // 当前位是 'O'，这一位不需要操作
        }  // 循环体结束，交由循环条件推进或终止
        return ans;  // 返回最少操作次数
    }  // 方法结束
};  // 类定义结束