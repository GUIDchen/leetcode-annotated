// 题目：2027. 转换字符串的最少操作次数（Minimum Moves to Convert String）
// 思路：贪心从左往右扫，遇到 'X' 就必须操作一次，且把操作起点定在这个 'X' 上最不浪费，一次操作能覆盖它和后面两位。
// 时间复杂度：O(n)，下标只前进不后退；空间复杂度：O(1)，只用常数个变量。
int minimumMoves(char* s) {  // s：只含 'O'/'X' 的字符串；返回把字符串里所有 'X' 都变成 'O' 的最少操作次数
    int n = strlen(s);  // 串长，作为循环上界
    int ans = 0;  // ans 记录已经执行的操作次数
    int i = 0;  // i 是当前扫描到的下标
    while (i < n) {  // 从左到右逐位扫描，直到串尾
        if (s[i] == 'X') {  // 遇到 'X' 时必须处理：越靠左处理，覆盖范围越不会浪费
            ans++;  // 执行一次「连续三位取反」的操作
            i += 3;  // 这次操作影响 i、i+1、i+2 三位，直接跳过三个字符
        } else {  // 否则当前位是 'O'，无需任何操作
            i++;  // 只需前进一位继续检查
        }  // 分支结束
    }  // 扫描到字符串末尾
    return ans;  // 返回最少操作次数
}  // 函数定义结束