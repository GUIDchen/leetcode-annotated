// 题目：2002. 两个回文子序列长度的最大乘积（Maximum Product of the Length of Two Palindromic Subsequences）
// 思路：n ≤ 12，用二进制掩码枚举每个子集，先预处理哪些子集是回文，再对每个回文子集枚举其补集的全部子集，取两个不相交回文子集长度的最大乘积。
// 时间复杂度：O(3^n)，枚举补集的所有子集；空间复杂度：O(2^n)，存每个子集的回文标记。
class Solution {  // LeetCode 约定的题解类
public:
    int maxProduct(string s) {  // s 为只含小写字母的字符串；返回两个不相交回文子序列长度的最大乘积
        int n = s.size();  // n 是字符串长度，子集掩码共 1 << n 个
        vector<bool> p(1 << n, true);  // p[mask] 表示只取 mask 中为 1 的那些位置拼成的子序列是否为回文
        for (int k = 1; k < 1 << n; ++k) {  // 从 1 开始枚举所有非空子集（空子集对乘积没有贡献）
            for (int i = 0, j = n - 1; i < j; ++i, --j) {  // 双指针从两端向中间检查该子集的回文性
                while (i < j && !(k >> i & 1)) {  // 左指针跳过所有没有被选中的位置：(k >> i) & 1 为 1 才表示选中
                    ++i;  // 左指针右移一位
                }  // 左指针停在第一个被选中的位置
                while (i < j && !(k >> j & 1)) {  // 右指针同样跳过没有被选中的位置
                    --j;  // 右指针左移一位
                }  // 右指针停在最后一个被选中的位置
                if (i < j && s[i] != s[j]) {  // 两端字符不相同，说明该子集不是回文
                    p[k] = false;  // 打上「非回文」标记，后续不再考虑它
                    break;  // 已经确定不是回文，无需继续比较中点
                }  // if 判断结束
            }  // 内层双指针扫描结束
        }  // 所有子集的回文性预处理完毕
        int ans = 0;  // ans 记录两个回文子序列长度的最大乘积
        for (int i = 1; i < 1 << n; ++i) {  // 枚举第一个回文子集 i
            if (p[i]) {  // 只有回文子集才能作为候选
                int a = __builtin_popcount(i);  // a 是子集 i 的元素个数，也就是对应回文子序列的长度
                int mx = ((1 << n) - 1) ^ i;  // mx 是 i 的补集：在 mx 中取子集就一定与 i 不相交
                for (int j = mx; j; j = (j - 1) & mx) {  // 经典技巧：从全 1 掩码 mx 开始不断 (j - 1) & mx，不重不漏地枚举 mx 的所有子集
                    if (p[j]) {  // 第二个子集也必须回文
                        int b = __builtin_popcount(j);  // b 是子集 j 的元素个数
                        ans = max(ans, a * b);  // 两个子序列不相交，用长度乘积更新答案
                    }  // if 判断结束
                }  // mx 的子集枚举结束
            }  // if (p[i]) 结束
        }  // 第一个子集枚举结束
        return ans;  // 返回最大乘积
    }  // maxProduct 方法结束
};  // Solution 类结束