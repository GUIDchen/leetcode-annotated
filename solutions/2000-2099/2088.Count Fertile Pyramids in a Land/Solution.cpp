// 题目：2088. 统计农场中肥沃金字塔的数目（Count Fertile Pyramids in a Land）
// 思路：f[i][j] 表示以 (i,j) 为塔尖能形成的最大高度。正金字塔（塔尖朝上）自底向上递推，倒金字塔自顶向下递推，高度 h 的塔尖贡献 h 个金字塔。
// 时间复杂度：O(mn)，两轮二维遍历；空间复杂度：O(mn)，额外的 f 表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countPyramids(vector<vector<int>>& grid) {  // grid：m 行 n 列的 0/1 矩阵，1 表示肥沃格子，返回金字塔总数
        int m = grid.size(), n = grid[0].size();  // 行数 m 与列数 n
        int f[m][n];  // dp 表：f[i][j] 为以 (i,j) 为塔尖的最大高度；-1 表示该格是空地不可用
        int ans = 0;  // 累计金字塔个数
        for (int i = m - 1; ~i; --i) {  // 第一轮自底向上：正金字塔的高度依赖下一行的三个相邻格
            for (int j = 0; j < n; ++j) {  // 从左到右遍历每一列
                if (grid[i][j] == 0) {  // 该格是空地，不能作为塔尖
                    f[i][j] = -1;  // 用 -1 标记不可用，这样相邻格取 min 时会自动得到 0
                } else if (i == m - 1 || j == 0 || j == n - 1) {  // 贴边界（最后一行或左右边界）时无法再向下扩展，高度只能是 0
                    f[i][j] = 0;  // 高度 0 表示单格，不构成金字塔，所以不累加
                } else {  // else 分支：非边界格，可以继续向下扩展
                    f[i][j] = min({f[i + 1][j - 1], f[i + 1][j], f[i + 1][j + 1]}) + 1;  // 高度取正下方三个相邻格中最小高度再加 1
                    ans += f[i][j];  // 高度为 h 的塔尖能形成高度 1..h 共 h 个正金字塔，全部累加
                }  // if/else 分支结束
            }  // 内层列循环结束
        }  // 外层行循环结束
        for (int i = 0; i < m; ++i) {  // 第二轮自顶向下：统计倒金字塔（塔尖朝下，依赖上一行）
            for (int j = 0; j < n; ++j) {  // 从左到右遍历每一列
                if (grid[i][j] == 0) {  // 该格是空地，不能作为塔尖
                    f[i][j] = -1;  // 同样用 -1 标记不可用格
                } else if (i == 0 || j == 0 || j == n - 1) {  // 贴边界（第一行或左右边界）时无法再向上扩展，高度只能是 0
                    f[i][j] = 0;  // 高度 0 不构成金字塔，不累加
                } else {  // else 分支：非边界格，可以继续向上扩展
                    f[i][j] = min({f[i - 1][j - 1], f[i - 1][j], f[i - 1][j + 1]}) + 1;  // 高度取正上方三个相邻格中最小高度再加 1
                    ans += f[i][j];  // 高度为 h 的塔尖能形成高度 1..h 共 h 个倒金字塔，全部累加
                }  // if/else 分支结束
            }  // 内层列循环结束
        }  // 外层行循环结束
        return ans;  // 正金字塔与倒金字塔总数
    }  // 结束 countPyramids 方法
};  // 结束 Solution 类