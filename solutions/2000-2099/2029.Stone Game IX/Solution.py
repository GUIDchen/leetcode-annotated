# 题目：2029. 石子游戏 IX（Stone Game IX）
# 思路：胜负只与石子价值模 3 的余数有关；先手第一手只能取余 1 或余 2，之后按 1,1,2,1,2,... 交替消耗，余 0 的石子可穿插在任意回合。用闭式公式算出可走的总回合数 r，r 为奇数且两种非零余数未耗尽成平局时先手胜，两种开局各判一次。
# 时间复杂度：O(n)，只需统计一遍余数；空间复杂度：O(1)，只用长度 3 的计数列表。
class Solution:  # LeetCode 约定的题解类
    def stoneGameIX(self, stones: List[int]) -> bool:  # stones 是每颗石子的价值，返回先手 Alice 是否必胜
        def check(cnt: List[int]) -> bool:  # 内部函数 check：判断在给定余数分布下先手是否必胜（会就地修改传入的计数列表）
            if cnt[1] == 0:  # 没有余 1 的石子，先手这种开局不成立
                return False  # 无法开局，该开局先手必败
            cnt[1] -= 1  # 先手第一步吃掉一颗余 1 的石子
            r = 1 + min(cnt[1], cnt[2]) * 2 + cnt[0]  # r：按最优交替可走完的总回合数 = 开局 1 步 + 余 1/余 2 成对交替 + 余 0 任意穿插的步数
            if cnt[1] > cnt[2]:  # 先手这一侧余 1 更多，可以在末尾多走一步
                cnt[1] -= 1  # 多消耗一颗余 1 的石子
                r += 1  # 总回合数加一
            return r % 2 == 1 and cnt[1] != cnt[2]  # 回合数为奇数且两种非零余数没有互相对消完时，先手获胜

        c1 = [0] * 3  # c1 统计价值模 3 余 0、1、2 的石子各有多少颗
        for x in stones:  # 遍历全部石子
            c1[x % 3] += 1  # 按价值对 3 的余数归类计数
        c2 = [c1[0], c1[2], c1[1]]  # c2 对调余 1 与余 2 的计数，相当于换一种开局：先手第一手取余 2
        return check(c1) or check(c2)  # 两种开局只要有一种能赢，就返回 True
