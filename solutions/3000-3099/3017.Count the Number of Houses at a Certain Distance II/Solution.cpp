// 题目：3017. 按距离统计房屋对数目 II（Count the Number of Houses at a Certain Distance II）
// 思路：整张图是一条 0-1-...-(n-1) 的链再补一条边 (x, y)。返回数组下标 k 对应距离 k+1、且 (a, b) 与 (b, a) 都计数。枚举每个房屋 i，用差分数组把它「到其余所有房屋的距离分布」以 4 段连续区间的形式整段加进去（左端、右端各截断一次，环上两端汇合处各修正一次），最后做前缀和还原出每个距离的房屋对数。
// 时间复杂度：O(n)，每个房屋只做 7 次常数级差分修改；空间复杂度：O(n)，需要一个长度为 n 的差分数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<long long> countOfPairs(int n, int x, int y) {  // n 是房屋数，x、y 是额外街道连接的两栋房屋，返回按距离统计的房屋对数目
        --x, --y;  // 把 1~n 的编号统一减 1，换成 0~n-1 的下标，方便做下标运算
        if (x > y) {  // 保证 x <= y，下面的公式都以左端 x、右端 y 为准
            swap(x, y);  // 顺序反了就交换过来
        }  // if 结束
        vector<long long> diff(n);  // diff 是差分数组：前缀和之后 diff[k] 就是距离 k+1 的房屋对数
        for (int i = 0; i < n; ++i) {  // 枚举每个房屋 i，把它到其余所有房屋的距离分布整段累加进差分数组
            diff[0] += 1 + 1;  // 房屋 i 的距离分布由左右两段连续区间叠加而成，两段都从距离 1 开始，所以在起点各开一次 +1
            ++diff[min(abs(i - x), abs(i - y) + 1)];  // 往 x 一侧走：入口距离取 min(|i-x|, |i-y|+1)，即直达 x 或先到 y 再跨一条额外边，从这一距离起整段 +1
            ++diff[min(abs(i - y), abs(i - x) + 1)];  // 往 y 一侧走：同理，入口距离取 min(|i-y|, |i-x|+1)
            --diff[min(abs(i - 0), abs(i - y) + 1 + abs(x - 0))];  // 左边界截断：越过最左房屋 0 之后不再有房屋，于是在 min(|i-0|, |i-y|+1+|x-0|) 处结束其中一段的计数
            --diff[min(abs(i - (n - 1)), abs(i - x) + 1 + abs(y - (n - 1)))];  // 右边界截断：越过最右房屋 n-1 之后不再有房屋，在 min(|i-(n-1)|, |i-x|+1+|y-(n-1)|) 处结束另一段的计数
            --diff[max(x - i, 0) + max(i - y, 0) + ((y - x) + 0) / 2];  // 减去绕环产生的重复部分：从两端同时绕环会在环中点汇合，环长为偶数时修正点取 max(x-i,0)+max(i-y,0)+(y-x)/2
            --diff[max(x - i, 0) + max(i - y, 0) + ((y - x) + 1) / 2];  // 环长为奇数时中点有两格，再用 (y-x+1)/2 修正另一半，保证每个距离只数一次
        }  // for 结束，此时每个距离的「变化量」都已登记完
        for (int i = 0; i + 1 < n; ++i) {  // 从左到右做前缀和，把差分数组还原成真正的计数
            diff[i + 1] += diff[i];  // diff[i+1] 累加 diff[i] 即前缀和
        }  // for 结束
        return diff;  // 返回答案：下标 k 表示距离 k+1 的房屋对数
    }  // 方法结束
};  // 题解类结束
