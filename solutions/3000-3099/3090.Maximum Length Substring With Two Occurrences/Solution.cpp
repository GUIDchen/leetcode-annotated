// 题目：3090. 每个字符最多出现两次的最长子字符串（Maximum Length Substring With Two Occurrences）
// 思路：滑动窗口；右指针逐字符扩张并计数，某字符超过 2 次时左指针收缩，窗口内始终合法，过程中记录最大长度。
// 时间复杂度：O(n)，每个字符至多被左右指针各访问一次；空间复杂度：O(1)，只需 26 个字母的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maximumLengthSubstring(string s) {  // s 为输入字符串，返回满足「每个字符至多出现两次」的最长子串长度
        int ans = 0;  // 记录答案（最长合法子串长度）
        int cnt[26]{};  // 窗口内每个小写字母的出现次数，{} 初始化为 0
        for (int l = 0, r = 0; r < s.size(); ++r) {  // l 为窗口左端、r 为右端；右端不断右移扩大窗口
            int idx = s[r] - 'a';  // 把当前字符映射成 0..25 的下标
            ++cnt[idx];  // 新字符进入窗口，计数加一
            while (cnt[idx] > 2) {  // 若该字符出现超过 2 次，窗口不再合法
                --cnt[s[l++] - 'a'];  // 左端字符移出窗口：先计数减一，再把左指针右移一位
            }
            ans = max(ans, r - l + 1);  // 当前窗口合法，用其长度更新答案
        }
        return ans;  // 返回最长合法子串长度
    }
};  // 类定义结束