// 题目：3005. 最大频率元素计数（Count Elements With Maximum Frequency）
// 核心思路：用频次数组统计每个元素出现次数，再扫描一遍频次数组，把频次等于最大频次的元素出现次数全部累加。
// 时间复杂度：O(n + 100)，n 为数组长度；空间复杂度：O(100)，一个定长计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxFrequencyElements(vector<int>& nums) {  // nums：输入数组，元素取值在 1..100 之间
        int cnt[101]{};  // 频次数组，下标是元素值，值是出现次数，{} 保证全部初始化为 0
        for (int x : nums) {  // 遍历输入数组，做词频统计
            ++cnt[x];  // 当前元素出现次数加一
        }  // 统计循环结束
        int ans = 0, mx = -1;  // ans 累加所有最大频次元素的总出现次数；mx 记录目前见过的最大频次
        for (int x : cnt) {  // 注意这里是遍历整个 cnt 数组，下标顺序从小到大
            if (mx < x) {  // 出现了比当前最大值更大的频次
                mx = x;  // 更新最大频次
                ans = x;  // 之前的累加作废，答案重置为这个新频次
            } else if (mx == x) {  // 频次恰好等于当前最大频次
                ans += x;  // 这种频次的元素也计入答案
            }  // if / else if 分支结束
        }  // 频次数组遍历结束
        return ans;  // 返回所有出现次数等于最大频次的元素的出现次数之和
    }  // 方法结束
};  // 类定义结束