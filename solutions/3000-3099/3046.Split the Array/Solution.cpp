// 题目：3046. 分割数组（Split the Array）
// 核心思路：要分成两个等长且各自元素互不相同的数组，等价于原数组中没有任何数字出现 3 次及以上；出现 2 次就两侧各放一个。
// 时间复杂度：O(n)，只需一次遍历计数；空间复杂度：O(V)，V 为取值上界 100，用定长数组统计频次。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外公开
    bool isPossibleToSplit(vector<int>& nums) {  // nums：待分割的数组，返回能否分成两个等长且各自元素互不相同的数组
        int cnt[101]{};  // cnt：值域 1..100 的频次数组，花括号初始化为全 0
        for (int x : nums) {  // 逐个统计每个数字出现的次数
            if (++cnt[x] >= 3) {  // 先自增再判断：某个数字出现到第 3 次时，两个数组必然有一个要放重复元素
                return false;  // 出现次数达到 3，无法完成分割，立即返回 false
            }
        }
        return true;  // 所有数字出现次数都不超过 2，一定可以均分到两个数组
    }  // 方法结束
};  // 题解类结束