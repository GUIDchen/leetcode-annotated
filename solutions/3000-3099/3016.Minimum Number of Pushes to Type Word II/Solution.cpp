// 题目：3016. 输入单词需要的最少按键次数 II（Minimum Number of Pushes to Type Word II）
// 思路：先统计 26 个字母各自的出现次数，再按频次降序分配键位：前 8 个高频字母只需按 1 次，接下来 8 个按 2 次，以此类推，第 i 名（0 起）需按 i/8+1 次，乘上频次即该字母的总按键数。
// 时间复杂度：O(n + 26log26)，n 为单词长度，排序开销常数级；空间复杂度：O(1)，只用长度 26 的计数数组和几个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumPushes(string word) {  // word 是待输入的单词，返回打完它所需的最少按键总次数
        vector<int> cnt(26);  // cnt[k] 表示字母 'a'+k 的出现次数，26 个桶全部初始化为 0
        for (char& c : word) {  // 遍历单词中的每个字符
            ++cnt[c - 'a'];  // 用 c - 'a' 把字符映射成 0~25 的下标，再累加该字母的计数
        }  // for 结束
        sort(cnt.rbegin(), cnt.rend());  // 降序排序：让出现次数越多的字母越靠前，优先占按键次数最少的键位
        int ans = 0;  // ans 累计按键总次数
        for (int i = 0; i < 26; ++i) {  // 按频次从高到低依次给 26 个字母排位（电话键盘只有 2~9 共 8 个可用键位）
            ans += (i / 8 + 1) * cnt[i];  // 第 i 名落在第 i/8+1 轮键位上，单次输入要按 i/8+1 下，乘上频次即它的总按键数
        }  // for 结束
        return ans;  // 返回最少按键总次数
    }  // 方法结束
};  // 题解类结束