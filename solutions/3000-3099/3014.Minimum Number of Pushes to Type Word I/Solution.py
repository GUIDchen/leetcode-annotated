# 题目：3014. 输入单词需要的最少按键次数 I（Minimum Number of Pushes to Type Word I）
# 思路：键盘只有 8 个按键，某个按键上的第 t 个字符需要按 t 次。本题单词字母互不相同，于是把字符尽量摊到各按键的第 1 位：前 8 个字符各按 1 次，接着 8 个各按 2 次，依层递推，最后不足 8 个的部分按当前层数计。
# 时间复杂度：O(n)，n 为单词长度（求长度与按层累加）；空间复杂度：O(1)，只用常数个变量。
class Solution:  # LeetCode 约定的题解类
    def minimumPushes(self, word: str) -> int:  # word 是要输入的单词；返回最少的按键次数
        n = len(word)  # n 是单词长度；本题字母互不相同，所以只需关心一共要打多少个字符
        ans, k = 0, 1  # ans 累计按键次数；k 是当前层每个字符需要按的次数，第 1 层为 1 次
        for _ in range(n // 8):  # 每 8 个字符占满一层：8 个按键各放一个字符，按键次数都是 k
            ans += k * 8  # 这一层的 8 个字符每个按 k 次
            k += 1  # 进入下一层，单个字符的按键次数加 1
        ans += k * (n % 8)  # 最后不足 8 个字符的部分按当前层数 k 计算
        return ans  # 返回最少按键次数
