// 题目：3097. 或值至少为 K 的最短子数组 II（Shortest Subarray With OR at Least K II）
// 思路：滑动窗口 + 按位计数，用 cnt[32] 记录窗口内每个二进制位各自出现多少次，从而在右端加入、左端移除元素时动态维护整个窗口的按位或值。
// 时间复杂度：O(32n)，左右指针各最多移动 n 次且每次移动都扫描 32 位；空间复杂度：O(32)，即常数级计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumSubarrayLength(vector<int>& nums, int k) {  // nums：输入数组；k：要求的按位或下界；返回满足条件的最短子数组长度
        int n = nums.size();  // 数组长度，用于初始化哨兵值以及判断答案是否存在
        int cnt[32]{};  // cnt[h] 记录第 h 个二进制位在当前窗口内出现的次数，全初始化为 0
        int ans = n + 1;  // 答案先取比任何合法长度都大的哨兵值，方便后面取 min
        for (int i = 0, j = 0, s = 0; j < n; ++j) {  // i 是窗口左端、j 是窗口右端、s 是窗口内所有元素的按位或；枚举右端扩张窗口
            s |= nums[j];  // 右端新元素并入窗口，直接按位或进 s
            for (int h = 0; h < 32; ++h) {  // 逐位统计新元素 nums[j] 对窗口的贡献
                if ((nums[j] >> h & 1) == 1) {  // 取出 nums[j] 的第 h 位，判断它是否为 1
                    ++cnt[h];  // 该位在窗口内出现次数加一
                }  // 结束“第 h 位为 1”的判断分支
            }  // 结束逐位统计循环
            for (; s >= k && i <= j; ++i) {  // 只要窗口或值已达标且窗口非空，就收缩左端以求出更短的合法窗口；头部 ++i 让左端右移
                ans = min(ans, j - i + 1);  // 当前窗口长度是合法候选答案，更新最短长度
                for (int h = 0; h < 32; ++h) {  // 从左端移除 nums[i] 之前，逐位撤销它的贡献
                    if ((nums[i] >> h & 1) == 1) {  // 只有 nums[i] 的第 h 位为 1 才需要撤销
                        if (--cnt[h] == 0) {  // 该位在窗口内出现次数减一，判断是否清零
                            s ^= 1 << h;  // 通过异或把 s 的第 h 位清 0
                        }  // 结束“该位清零”判断分支
                    }  // 结束“nums[i] 第 h 位为 1”判断分支
                }  // 结束撤销贡献的循环
            }  // 结束左端收缩循环
        }  // 结束右端扩张循环
        return ans > n ? -1 : ans;  // 哨兵未被更新说明不存在合法子数组，返回 -1；否则返回最短长度
    }  // 结束题解方法
};  // 结束题解类