// 题目：3039. 进行操作使字符串为空（Apply Operations to Make String Empty）
// 思路：每轮删掉每个出现过的字符各一次，共需 maxCnt 轮；最后一轮开始前剩下的，正是出现次数最多的那些字符各自最后一次出现的位置。
// 时间复杂度：O(n)，两次线性扫描；空间复杂度：O(|Σ|)，只有 26 个字母的计数数组与最后位置数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string lastNonEmptyString(string s) {  // s：输入字符串
        int cnt[26]{};  // 每个字母的出现次数，花括号零初始化
        int last[26]{};  // 每个字母最后一次出现的下标，零初始化
        int n = s.size();  // 字符串长度，供两轮循环复用
        int mx = 0;  // 记录出现次数的最大值，也就是需要执行的操作轮数
        for (int i = 0; i < n; ++i) {  // 第一轮扫描：同时统计词频、最后位置与最大词频
            int c = s[i] - 'a';  // 把字符映射成 0~25 的字母下标
            mx = max(mx, ++cnt[c]);  // 先自增该字母的计数，再更新最大词频
            last[c] = i;  // 覆盖式记录该字母最后一次出现的下标
        }
        string ans;  // 存放最后一轮操作之前的非空字符串
        for (int i = 0; i < n; ++i) {  // 第二轮扫描：按原串顺序收集答案，保证字符先后次序不变
            int c = s[i] - 'a';  // 再次映射成字母下标
            if (cnt[c] == mx && last[c] == i) {  // 只取出现次数最多的字母，并且只在它最后一次出现的位置上取一次
                ans.push_back(s[i]);  // 把这个字符追加到答案末尾
            }
        }
        return ans;  // 返回最后一轮开始前的非空字符串
    }
};