// 题目：3020. 子集中元素的最大数量（Find the Maximum Number of Elements in Subset）
// 思路：子集必须排成 x, x*x, x*x*x*x, ..., 最上层, ..., x*x*x*x, x*x, x 这样左右对称的平方链，长度一定是奇数，除正中间那个值外每个值都要出现偶数次。用哈希表统计频次，对每个底数沿平方链一层层往上走（每层取 2 个），再看链顶能否取 1 个；x=1 的平方链退化，单独按「尽量取奇数长度」处理。
// 时间复杂度：O(n + U·loglogM)，U 为不同元素个数、链长为 O(loglogM)，可近似看作 O(n)；空间复杂度：O(n)，哈希表最多存 n 个键值对。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maximumLength(vector<int>& nums) {  // nums 是候选集合，返回满足对称平方模式的子集的最大元素个数
        unordered_map<long long, int> cnt;  // 哈希表：键是数值，值是出现次数；键用 long long 是为了后面反复平方时不溢出
        for (int x : nums) {  // 遍历数组中的每个数
            ++cnt[x];  // 累加该数的出现次数
        }  // for 结束
        int ans = cnt[1] - (cnt[1] % 2 ^ 1);  // 先单独处理 1 的退化链：1 的平方还是 1，链长必须为奇数，所以偶数个 1 时要丢掉一个（cnt[1]%2^1 在偶数时为 1、奇数时为 0）
        cnt.erase(1);  // 把 1 从哈希表删掉，避免后面把它当成普通底数重复枚举
        for (auto [v, _] : cnt) {  // 枚举每个出现过的值作为平方链的底数（结构化绑定拆出键 v 与值 _）
            int t = 0;  // t 记录当前这条链能取到的元素个数
            long long x = v;  // x 是链的当前层的值，用 long long 防止平方溢出
            while (cnt.count(x) && cnt[x] > 1) {  // 只要 x 还有至少 2 个，就能在链的左右两侧各放一个，继续往上平方
                x = x * x;  // x 平方得到链的上一层
                t += 2;  // 同一层左右各取一个，元素个数 +2
            }  // while 结束，此时 cnt[x] 要么是 1、要么是 0
            t += cnt.count(x) ? 1 : -1;  // 链顶只能放 1 个：若该值还存在就 +1 凑成奇数长度，否则说明上一层多算了 1 个，要减回来
            ans = max(ans, t);  // 用当前链长更新答案
        }  // for 结束
        return ans;  // 返回子集的最大元素个数
    }  // 方法结束
};  // 题解类结束
