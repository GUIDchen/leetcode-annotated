// 题目：3099. 哈沙德数（Harshad Number）
// 思路：逐位取出数字求数位和，再判断数位和能否整除原数：能整除就是哈沙德数。
// 时间复杂度：O(log x)，即十进制位数；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int sumOfTheDigitsOfHarshadNumber(int x) {  // x：待判断的整数，返回其数位和或 -1
        int s = 0;  // 数位和累加器，初始为 0
        for (int y = x; y > 0; y /= 10) {  // 用临时变量 y 逐位取出数字，y /= 10 每次去掉已处理的末位
            s += y % 10;  // 取出当前末位并累加进数位和
        }  // 结束取位循环
        return x % s == 0 ? s : -1;  // 数位和能整除 x 说明是哈沙德数，返回数位和；否则返回 -1
    }  // 结束题解方法
};  // 结束题解类