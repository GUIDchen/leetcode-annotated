// 题目：3088. 使字符串反回文（Make String Anti-palindrome，会员题）
// 思路：先排序；若前后两半在中点处相接会形成回文，就把后半段开头的重复字符依次换到前半段对应位置，换不出字符时返回 -1。
// 时间复杂度：O(n log n)，瓶颈在排序；空间复杂度：O(1)，除排序外只用了常数个下标（不计排序自身开销）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string makeAntiPalindrome(string s) {  // s 为输入字符串，返回字典序最小的反回文串，无解时返回 "-1"
        sort(s.begin(), s.end());  // 升序排序，让相同字符聚在一起，方便判断能否错开
        int n = s.length();  // 字符串长度
        int m = n / 2;  // 中点下标；前 m 个字符与后 n-m 个字符两两配对不等时才是反回文
        if (s[m] == s[m - 1]) {  // 排序后 s[m-1] 与 s[m] 相同，说明后半段会与前半段末尾形成对称回文
            int i = m;  // i 指向后半段中第一个与 s[m-1] 不同的字符
            while (i < n && s[i] == s[i - 1]) {  // 跳过所有与 s[m-1] 相同的字符
                ++i;  // 继续往后找分界点
            }
            for (int j = m; j < n && s[j] == s[n - j - 1]; ++i, ++j) {  // j 从后半段起点开始；条件 s[j] == s[n-j-1] 表示该对称位置仍需修正
                if (i >= n) {  // 后半段里已经没有可换的字符
                    return "-1";  // 无法构造反回文，按题目要求返回 "-1"
                }
                swap(s[i], s[j]);  // 把后半段的 s[i] 换到 s[j]，打破对称位置上的相同字符
            }
        }
        return s;  // 返回构造好的（字典序最小的）反回文串
    }
};  // 类定义结束