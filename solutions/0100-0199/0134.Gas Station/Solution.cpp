// 题目：134. 加油站（Gas Station）
// 思路：双指针维护一个“环上的窗口”。右端顺时针不断加入加油站，油量变负时把左端逆时针补进来，窗口扩满一圈后剩下的唯一候选就是答案。
// 时间复杂度：O(n)，每个站点最多被左右指针各扫一次；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int canCompleteCircuit(vector<int>& gas, vector<int>& cost) {  // 返回能绕行一周的起点下标；无解返回 -1
        int n = gas.size();  // n 是加油站数量
        int i = n - 1, j = n - 1;  // i 是窗口左端、j 是窗口右端，都从最后一站开始向两侧扩张
        int cnt = 0, s = 0;  // cnt 记录窗口已覆盖多少站，s 记录窗口内的净油量
        while (cnt < n) {  // 窗口还没覆盖完整一圈就继续扩张
            s += gas[j] - cost[j];  // 把右端 j 站加进窗口：加油量减去到下一站的耗油量
            ++cnt;  // 窗口长度加一
            j = (j + 1) % n;  // 右端顺时针前进一格，取模实现环形
            while (s < 0 && cnt < n) {  // 净油量为负说明当前起点走不通，需要把起点继续往前（逆时针）挪
                --i;  // 左端逆时针前进一格
                s += gas[i] - cost[i];  // 把新并入的 i 站计入净油量
                ++cnt;  // 窗口长度加一
            }
        }
        return s < 0 ? -1 : i;  // 绕完一圈总油量仍为负则无解；否则左端 i 就是可行起点
    }
};