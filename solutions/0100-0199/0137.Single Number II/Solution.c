// 题目：137. 只出现一次的数字 II（Single Number II）
// 思路：按位统计。除答案外每个数都出现三次，所以某一位上 1 的总数对 3 取余，就是答案在该位上的值。
// 时间复杂度：O(32 * n) = O(n)，定长 32 位逐位扫描；空间复杂度：O(1)，只用常数个变量。
int singleNumber(int* nums, int numsSize) {  // 返回只出现一次的那个数（其余数都恰好出现三次）
    int ans = 0;  // 逐位拼出来的答案
    for (int i = 0; i < 32; i++) {  // 枚举二进制的 32 个位
        int cnt = 0;  // 统计当前这一位上 1 的出现次数
        for (int j = 0; j < numsSize; j++) {  // 遍历数组里的所有元素
            if (nums[j] >> i & 1) {  // 取出 nums[j] 的第 i 位，看它是不是 1
                cnt++;  // 是 1 就累加计数
            }
        }
        ans |= (unsigned) (cnt % 3) << i;  // 出现三次的数在这一位贡献 3 个 1、正好被 3 整除；余下的就是答案的这一位
    }
    return ans;  // 返回拼好的答案
}