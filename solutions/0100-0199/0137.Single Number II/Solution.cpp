// 题目：137. 只出现一次的数字 II（Single Number II）
// 思路：按位统计。把每个数的每一位上 1 的个数加起来对 3 取余，得到的就是答案对应位的值，注意补码下第 31 位要特殊处理。
// 时间复杂度：O(32 * n) = O(n)，逐位扫描；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int singleNumber(vector<int>& nums) {  // 返回只出现一次的那个数
        int ans = 0;  // 逐位拼出的结果
        for (int i = 0; i < 32; ++i) {  // 枚举 32 个二进制位（包含符号位）
            int cnt = 0;  // 统计当前位上 1 的个数
            for (int num : nums) {  // 遍历所有元素
                cnt += ((num >> i) & 1);  // 取出 num 的第 i 位并累加到计数里
            }
            cnt %= 3;  // 出现三次的数在这一位贡献 3 个 1、被 3 整除消掉，余数就是答案的这一位
            if (cnt) {  // 余数为 1 说明答案的该位是 1，需要置位
                if (i == 31) {  // 第 31 位是符号位，直接 1 << 31 会溢出成未定义行为
                    ans = INT_MIN + ans;  // 用 INT_MIN 补上 -2^31，等价于在补码意义下置上符号位
                } else {  // 其余位是普通位
                    ans |= cnt << i;  // 把第 i 位置成 1
                }
            }
        }
        return ans;  // 返回拼好的答案
    }
};
