// 题目：130. 被围绕的区域（Surrounded Regions）
// 思路：反向思考——先把与四条边界连通的 'O' 全部标记成 '.'，剩下的 'O' 才是被完全包围的，最后统一翻成 'X'。
// 时间复杂度：O(m * n)，每个格子最多被访问一次；空间复杂度：O(m * n)，递归栈最坏要吃下整块棋盘。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    void solve(vector<vector<char>>& board) {  // board 是字符棋盘，原地修改，所以返回类型是 void
        int m = board.size(), n = board[0].size();  // m、n 分别是棋盘的行数和列数（题面保证 board 非空）
        int dirs[5] = {-1, 0, 1, 0, -1};  // 方向数组：dirs[k] 与 dirs[k+1] 拼成一对偏移，代表上、右、下、左四个方向
        function<void(int, int)> dfs = [&](int i, int j) {  // 定义递归的深度优先搜索：从 (i, j) 出发，把与边界连通的 'O' 全部打上 '.' 标记
            if (i < 0 || i >= m || j < 0 || j >= n || board[i][j] != 'O') {  // 越界，或者当前格子不是 'O'（是 'X' 或已经标记过的 '.'）就停止
                return;  // 直接返回，不继续往下搜
            }
            board[i][j] = '.';  // 标记成 '.'：既表示“与边界连通、不能被翻转”，又顺带当访问标记防止重复搜索
            for (int k = 0; k < 4; ++k) {  // 枚举上下左右四个方向
                dfs(i + dirs[k], j + dirs[k + 1]);  // 递归处理相邻格子，i + dirs[k] 是行偏移，j + dirs[k + 1] 是列偏移
            }  // 四个方向处理完毕
        };  // 递归 lambda 的定义结束
        for (int i = 0; i < m; ++i) {  // 从左右两列边界出发，把边界上的 'O' 及其连通块全部标记掉
            dfs(i, 0);  // 左边界第 0 列
            dfs(i, n - 1);  // 右边界第 n-1 列
        }
        for (int j = 1; j < n - 1; ++j) {  // 再从上下两行边界出发；两个角已经在上一个循环里处理过，所以从 1 开始到 n-2
            dfs(0, j);  // 上边界第 0 行
            dfs(m - 1, j);  // 下边界第 m-1 行
        }
        for (auto& row : board) {  // 逐行遍历整块棋盘做收尾替换
            for (auto& c : row) {  // 逐列遍历当前行
                if (c == '.') {  // '.' 是与边界连通的 'O'，按题目要求恢复成 'O'
                    c = 'O';  // 恢复字符
                } else if (c == 'O') {  // 仍是 'O' 说明四面都被 'X' 围住了
                    c = 'X';  // 翻转成 'X'
                }
            }
        }
    }
};