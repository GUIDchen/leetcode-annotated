// 题目：191. 位1的个数（Number of 1 Bits）
// 思路：反复执行 n &= n - 1，每次消掉最低位的一个 1，执行次数即 1 的个数。
// 时间复杂度：O(1)，最多 32 次循环；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int hammingWeight(uint32_t n) {  // 输入 32 位无符号整数，返回二进制中 1 的个数
        int ans = 0;  // 计数器
        while (n) {  // n 不为 0 时继续，有几个 1 就循环几次
            n &= n - 1;  // 消掉 n 的最低位 1（n-1 会翻转最低位 1 及其右侧所有位）
            ++ans;  // 计数加一
        }
        return ans;  // 循环结束时 ans 即 1 的总数
    }
};