// 题目：191. 位1的个数（Number of 1 Bits）
// 思路：n &= n - 1 每次消掉最低位的那个 1，消几次就说明有几个 1。
// 时间复杂度：O(1)，最多循环 32 次（等于 1 的个数）；空间复杂度：O(1)，只用常数变量。
int hammingWeight(uint32_t n) {  // 输入 32 位无符号整数，返回其二进制中 1 的个数
    int ans = 0;  // 计数器，记录已经消掉的 1 的个数
    while (n) {  // n 还不为 0 就继续处理
        n &= n - 1;  // 把最低位的 1 清零：n-1 会把该位及其右边全部取反，按位与后该位消掉
        ans++;  // 消掉一个 1，计数加一
    }
    return ans;  // n 变成 0 时 ans 就是 1 的总个数
}