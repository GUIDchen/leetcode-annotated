// 题目：151. 反转字符串中的单词（Reverse Words in a String）
// 思路：原地双指针——先把每个单词逐个写到前面并单独反转（顺带压缩多余空格），再整体反转字符串。
// 时间复杂度：O(n)，每个字符被常数次搬运；空间复杂度：O(1)，除返回值外只用几个下标变量。
class Solution {  // 题目要求的题解类
public:  // 对外提供 reverseWords 方法
    string reverseWords(string s) {  // s 为输入字符串，原地整理后返回
        int i = 0;  // 读指针：扫描原始字符串
        int j = 0;  // 写指针：整理结果写入的位置
        int n = s.size();  // 原字符串长度
        while (i < n) {  // 逐个单词处理
            while (i < n && s[i] == ' ') {  // 跳过单词之间的空格
                ++i;  // 读指针前进
            }
            if (i < n) {  // 跳完空格后还有字符，说明拿到了一个单词
                if (j != 0) {  // 不是第一个单词时，需要补一个分隔空格
                    s[j++] = ' ';  // 写入空格并把写指针后移
                }
                int k = i;  // k 用来找当前单词的右边界
                while (k < n && s[k] != ' ') {  // 一直走到单词结束（遇到空格或串尾）
                    s[j++] = s[k++];  // 把字符搬到写指针处，两个指针同时后移
                }
                reverse(s.begin() + j - (k - i), s.begin() + j);  // 把刚写入的这段单词原地反转，单词内部变成倒序
                i = k;  // 读指针跳过这个单词
            }
        }  // 所有单词处理完毕
        s.erase(s.begin() + j, s.end());  // 删掉尾部残留的多余字符
        reverse(s.begin(), s.end());  // 整体反转：单词顺序颠倒，单词内部顺序又恢复正常
        return s;  // 返回整理好的字符串
    }  // reverseWords 方法结束
};  // Solution 类定义结束