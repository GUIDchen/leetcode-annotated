// 题目：198. 打家劫舍（House Robber）
// 思路：记忆化搜索。f[i] 表示从第 i 间房开始能偷到的最大金额，选偷第 i 间就跳到 i+2，不偷就看 i+1，取两者较大值。
// 时间复杂度：O(n)，每个状态只计算一次；空间复杂度：O(n)，记忆化数组（另加 O(n) 递归栈）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int rob(vector<int>& nums) {  // nums：每间房的现金金额；返回在不触动警报的前提下能偷到的最大金额
        int n = nums.size();  // 房子总数，递归时用它判断是否越界
        int f[n];  // 记忆化数组：f[i] 表示从第 i 间房开始决策能偷到的最大金额
        memset(f, -1, sizeof(f));  // 统一初始化为 -1，表示该状态还没被计算过
        auto dfs = [&](this auto&& dfs, int i) -> int {  // C++23 显式对象参数 lambda：把自身作为 dfs 传入，从而可以直接递归调用自己
            if (i >= n) {  // 越过最后一间房（i == n），已无房可偷
                return 0;  // 金额为 0
            }
            if (f[i] < 0) {  // 只有没算过的状态才需要往下递归（记忆化的关键）
                f[i] = max(nums[i] + dfs(i + 2), dfs(i + 1));  // 方案一：偷第 i 间，则第 i+1 间不能碰，跳到 i+2；方案二：不偷第 i 间，直接看 i+1；取较大者
            }
            return f[i];  // 返回该状态的结果（已写入 f[i]，后续复用）
        };
        return dfs(0);  // 从第 0 间房开始做决策
    }
};
