// 题目：136. 只出现一次的数字（Single Number）
// 思路：异或运算的性质——a ^ a = 0、a ^ 0 = a，把所有数异或起来，成对出现的数两两抵消，剩下的就是答案。
// 时间复杂度：O(n)，只遍历一次数组；空间复杂度：O(1)，只用一个累加变量。
int singleNumber(int* nums, int numsSize) {  // 返回唯一只出现一次的元素（题目保证其余元素都恰好出现两次）
    int ans = 0;  // 异或累加器，0 是异或的单位元
    for (int i = 0; i < numsSize; i++) {  // 顺序遍历数组中的每个元素
        ans ^= nums[i];  // 累积异或：相同的数互相抵消，等价于“消消乐”
    }
    return ans;  // 最后剩下的就是只出现一次的数字
}