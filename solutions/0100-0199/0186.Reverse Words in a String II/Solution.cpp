// 题目：186. 反转字符串中的单词 II（Reverse Words in a String II）
// 思路：先翻转每个单词的内部字符，再整体翻转整个字符数组，两次翻转叠加后只有单词顺序被颠倒。
// 时间复杂度：O(n)，每个字符至多被交换两次；空间复杂度：O(1)，只用常数额外变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    void reverseWords(vector<char>& s) {  // s 是字符数组，要求原地修改，不返回新数组
        auto reverse = [&](int i, int j) {  // 局部 lambda：原地翻转区间 s[i..j]（闭区间）
            for (; i < j; ++i, --j) {  // 双指针从两端向中间靠拢，相遇即结束
                swap(s[i], s[j]);  // 交换左右两个字符，逐步把区间翻过来
            }
        };
        int n = s.size();  // 字符总数，供后面判断是否到达末尾
        for (int i = 0, j = 0; j < n; ++j) {  // i 是当前单词的起点，j 顺序扫描每个字符
            if (s[j] == ' ') {  // 遇到空格，说明一个单词到此结束
                reverse(i, j - 1);  // 翻转 s[i..j-1] 这段单词（不含空格）
                i = j + 1;  // 下一个单词从空格的后一位重新开始
            } else if (j == n - 1) {  // 已经走到末尾，最后一个单词后面没有空格
                reverse(i, j);  // 单独翻转最后一个单词
            }
        }
        reverse(0, n - 1);  // 整体翻转整句话：单词内部又变回原样，而单词先后顺序被颠倒
    }
};