// 题目：190. 颠倒二进制位（Reverse Bits）
// 思路：从低位到高位逐位取出 n 的末位，放到结果 ans 的对称高位（第 31-i 位）上。
// 时间复杂度：O(1)，最多循环 32 次；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    uint32_t reverseBits(uint32_t n) {  // 输入是 32 位无符号整数，返回它按位颠倒后的结果
        uint32_t ans = 0;  // 结果累加器，初始为全 0
        for (int i = 0; i < 32 && n; ++i) {  // 最多处理 32 位；n 提前变成 0 时省掉剩余高位
            ans |= (n & 1) << (31 - i);  // 取 n 的最低位，左移到对称位置后按位或进 ans
            n >>= 1;  // n 右移一位，把下一位挪到最低位待取
        }
        return ans;  // 返回颠倒后的 32 位结果
    }
};