# 题目：1017. 负二进制转换（Convert to Base -2）
# 思路：模拟短除法：当前位取 n 的奇偶，若为 1 就把 n 减去本位权重 k，再让 n //= 2，权重 k 每轮取反，以抵消底数 -2 的影响。
# 时间复杂度：O(log n)，与结果位数同阶；空间复杂度：O(log n)，用于存放结果列表与字符串。
class Solution:  # LeetCode 约定的题解类
    def baseNeg2(self, n: int) -> str:  # n：待转换的非负整数
        k = 1  # 当前位对应的权重，处理过程中在 1 与 -1 之间交替
        ans = []  # 从低位到高位收集字符
        while n:  # 反复除以 2，直到 n 变成 0
            if n % 2:  # 当前位是 1
                ans.append('1')  # 记录本位为 1
                n -= k  # 减去本位权重，让剩余部分能被 2 整除，从而保证除尽
            else:  # 当前位是 0
                ans.append('0')  # 记录本位为 0，无需调整 n
            n //= 2  # 右移一位（整除 2），继续处理下一位
            k *= -1  # 权重取反：底数是 -2，而每轮又把 n 除以 2，等效权重正好翻转符号
        return ''.join(ans[::-1]) or '0'  # 反转为高位在前；答案为空时（原 n 为 0）兜底返回 "0"
