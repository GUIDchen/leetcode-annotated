// 题目：1017. 负二进制转换（Convert to Base -2）
// 思路：模拟短除法：当前位取 n 的奇偶，若为 1 就把 n 减去本位权重 k，再让 n /= 2，权重 k 每轮取反，从而抵消底数 -2 的影响。
// 时间复杂度：O(log n)，与结果位数同阶；空间复杂度：O(log n)，用于存放结果字符串。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string baseNeg2(int n) {  // n：待转换的非负整数
        if (n == 0) {  // 特判 0
            return "0";  // 0 的负二进制表示就是 "0"
        }
        int k = 1;  // 当前位对应的权重，处理过程中在 1 与 -1 之间交替
        string ans;  // 从低位到高位收集字符
        while (n) {  // 反复除以 2，直到 n 变成 0
            if (n % 2) {  // 当前位是 1
                ans.push_back('1');  // 记录本位为 1
                n -= k;  // 减去本位权重，让剩余部分能被 2 整除，从而保证除尽
            } else {  // 当前位是 0
                ans.push_back('0');  // 记录本位为 0，无需调整 n
            }
            k *= -1;  // 权重取反：底数是 -2，而每轮又把 n 除以 2，等效权重正好翻转符号
            n /= 2;  // 右移一位，继续处理下一位
        }
        reverse(ans.begin(), ans.end());  // 目前是低位在前，反转为从高到低的正常顺序
        return ans;  // 返回负二进制表示
    }
};