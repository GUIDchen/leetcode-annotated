# 题目：1086. 前五科的均分（High Five）
# 思路：用字典按学生编号把成绩分组，同时记录最大的学生编号；再按编号从小到大遍历，用 nlargest(5) 取出最高的 5 个成绩求平均（整除），按编号顺序写入答案。
# 时间复杂度：O(n log n)，n 为成绩条数，瓶颈在取前 5 名的堆操作；空间复杂度：O(n)，用于存放按编号分组的全部成绩。
class Solution:  # LeetCode 约定的题解类
    def highFive(self, items: List[List[int]]) -> List[List[int]]:  # items 中每个元素是 [编号, 成绩]
        d = defaultdict(list)  # 编号 -> 该学生的全部成绩，访问不存在的键时自动创建空列表
        m = 0  # 记录出现过的最大编号，用于确定遍历上界（编号从 1 开始，故初值取 0）
        for i, x in items:  # 逐条遍历成绩记录并解包出编号 i 与成绩 x
            d[i].append(x)  # 把成绩追加到对应编号的列表中
            m = max(m, i)  # 顺手更新出现过的最大编号
        ans = []  # 存放 [编号, 前五科均分] 的结果，按编号升序
        for i in range(1, m + 1):  # 按编号从小到大扫描，天然得到题目要求的排序
            if xs := d[i]:  # 海象运算符：取出该编号的成绩列表并判断非空，没有记录的学生直接跳过
                avg = sum(nlargest(5, xs)) // 5  # 取出最高的 5 个成绩求和，再整除 5 得到整数平均分
                ans.append([i, avg])  # 把编号与均分写入答案
        return ans  # 返回按编号升序排列的均分列表
