# 题目：1089. 复写零（Duplicate Zeros）
# 思路：先正向模拟算出「原数组前多少个元素最终会被保留」以及复写后的虚拟长度 k，再从后往前倒序搬运，遇到 0 就在左侧多写一个 0，做到原地修改。
# 时间复杂度：O(n)，只正反各扫描一遍；空间复杂度：O(1)，只用几个下标变量。
class Solution:  # LeetCode 约定的题解类
    def duplicateZeros(self, arr: List[int]) -> None:  # arr 原地修改，函数不需要返回任何值
        """
        Do not return anything, modify arr in-place instead.
        """  # 文档字符串结束；本题要求原地修改，不返回新数组
        n = len(arr)  # 数组长度
        i, k = -1, 0  # i 是原数组下标（先置 -1，循环里先自增）；k 是复写后的虚拟长度
        while k < n:  # 正向模拟：直到虚拟写入长度达到 n 为止
            i += 1  # 指向下一个待扫描的原元素
            k += 1 if arr[i] else 2  # 非 0 元素占 1 格，0 要复写所以占 2 格
        j = n - 1  # j 是从后往前写的目标下标，从数组末尾开始
        if k == n + 1:  # k == n + 1 说明最后一个 0 的第二次复写越界被丢掉了
            arr[j] = 0  # 先把被截断的那个 0 写到数组末尾
            i, j = i - 1, j - 1  # 该 0 只写了一次，所以原指针回退一格、目标指针左移
        while ~j:  # ~j 为真等价于 j != -1，表示还有位置要写
            if arr[i] == 0:  # 当前原元素是 0，需要复写一次
                arr[j] = arr[j - 1] = arr[i]  # 链式赋值，把 0 同时写到相邻的两个位置
                j -= 1  # 已经写了两个 0，目标指针额外多退一格
            else:  # 非 0 元素只占一格
                arr[j] = arr[i]  # 非 0 元素直接写一格
            i, j = i - 1, j - 1  # 两个指针同时左移，继续向前搬运
