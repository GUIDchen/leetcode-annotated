// 题目：1089. 复写零（Duplicate Zeros）
// 思路：先正向模拟算出复写后数组的「虚拟长度」，确定哪些元素最终会被保留以及各自的最后落点，再从后往前原地覆盖，遇到 0 就在左侧多写一个 0。
// 时间复杂度：O(n)，正反各扫描一遍；空间复杂度：O(1)，只用几个下标变量。
void duplicateZeros(int* arr, int arrSize) {  // 原地复写 arr，无返回值；arrSize 为数组长度
    int i = 0;  // i 指向原数组中当前要处理的元素
    int j = 0;  // j 记录该元素复写后落到的位置，相当于模拟出来的写入长度
    while (j < arrSize) {  // 正向模拟：直到写入位置越过数组末尾为止
        if (arr[i] == 0) {  // 当前元素是 0
            j++;  // 0 要被复写，所以写入位置额外多前进一格
        }  // 0 的处理结束
        i++;  // 原数组指针前进一格
        j++;  // 非 0 元素只占一格，写入位置再前进一格
    }  // 正向模拟结束
    i--;  // 回退到最后一个真正被写进数组的原元素
    j--;  // 回退到它在数组中的最后落点
    while (i >= 0) {  // 从后往前搬运，避免覆盖掉还没读到的元素
        if (arr[i] == 0) {  // 当前元素是 0，需要复写
            if (j < arrSize) {  // 复写出的第二个 0 若仍在数组范围内（越界的那次会被截断丢弃）
                arr[j] = arr[i];  // 先写右边那个 0
            }  // 结束边界判断
            j--;  // 位置左移，准备写左边那个 0
        }  // 结束 0 的处理
        arr[j] = arr[i];  // 把当前原元素写到它的最终位置
        i--;  // 原数组指针左移
        j--;  // 写入位置左移
    }  // 倒序搬运结束
}  // 函数结束