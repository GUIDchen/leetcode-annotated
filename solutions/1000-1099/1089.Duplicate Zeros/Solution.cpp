// 题目：1089. 复写零（Duplicate Zeros）
// 思路：先正向模拟出复写后的「虚拟长度」k，据此确定最后一个有效原元素 i 与它的落点，再从后往前原地覆盖，遇到 0 就多写一个 0。
// 时间复杂度：O(n)，正反各扫描一遍；空间复杂度：O(1)，只用几个下标变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    void duplicateZeros(vector<int>& arr) {  // arr 原地复写，函数无返回值
        int n = arr.size();  // 数组长度
        int i = -1, k = 0;  // i 为原数组下标（从 -1 开始，循环里先自增）；k 为复写后的虚拟长度
        while (k < n) {  // 正向模拟：直到虚拟写入长度达到 n
            ++i;  // 指向下一个待扫描的原元素
            k += arr[i] ? 1 : 2;  // 非 0 元素占 1 格，0 要复写所以占 2 格
        }  // 正向模拟结束
        int j = n - 1;  // j 为从后往前写的目标下标，从数组末尾开始
        if (k == n + 1) {  // k == n + 1 说明最后一个 0 的第二次复写越界被丢掉了
            arr[j--] = 0;  // 先把被截断的那个 0 写到数组末尾，并把 j 左移
            --i;  // 该 0 只写了一次，原指针也回退一格
        }  // 结束截断处理
        while (~j) {  // ~j 为真等价于 j != -1，表示还有位置要写
            arr[j] = arr[i];  // 先把原元素写到目标位置
            if (arr[i] == 0) arr[--j] = arr[i];  // 若是 0，再往左一格复写一个 0
            --i;  // 原数组指针左移
            --j;  // 目标位置指针左移
        }  // 倒序搬运结束
    }  // 结束方法体
};  // 类定义结束