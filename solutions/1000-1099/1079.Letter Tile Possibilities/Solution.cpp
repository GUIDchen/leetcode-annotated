// 题目：1079. 活字印刷（Letter Tile Possibilities）
// 思路：先统计每个字母的出现次数，再按字典序做回溯 DFS：每层任选一个仍有剩余的字母接到当前序列后面，选完立刻计数（每个非空前缀都是一条合法序列），然后递归、回溯恢复计数，靠固定字母顺序天然去重。
// 时间复杂度：O(n * n!)，n 为字母个数，最坏要枚举所有排列；空间复杂度：O(n)，递归栈深度不超过 n（另加 O(1) 的计数数组）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numTilePossibilities(string tiles) {  // tiles 是可用的字母集合（每个字符是一张字牌）
        int cnt[26]{};  // 统计每个大写字母的剩余张数，值初始化为 0
        for (char c : tiles) {  // 遍历所有字牌
            ++cnt[c - 'A'];  // 把字符映射到 0~25 的下标并累加张数
        }
        function<int(int* cnt)> dfs = [&](int* cnt) -> int {  // 递归函数：返回从当前剩余字母出发还能组成多少个不同的非空序列
            int res = 0;  // 记录本轮能产生的序列个数
            for (int i = 0; i < 26; ++i) {  // 按字母从小到大枚举，保证不同排列只被统计一次
                if (cnt[i] > 0) {  // 该字母还有剩余字牌才可以选择
                    ++res;  // 选它构成一个长度 +1 的新序列，先计数
                    --cnt[i];  // 用掉一张该字母的字牌
                    res += dfs(cnt);  // 递归统计在这个前缀之后继续接字母得到的所有序列
                    ++cnt[i];  // 回溯：恢复这张字牌，供其他分支使用
                }
            }
            return res;  // 返回本轮统计到的序列总数
        };
        return dfs(cnt);  // 从空序列开始搜索，答案即所有非空序列的个数
    }
};