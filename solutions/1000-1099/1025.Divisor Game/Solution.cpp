// 题目：1025. 除数博弈（Divisor Game）
// 思路：n 为奇数时，它的因数都是奇数，n - x 必为偶数；对手总能再走一步把偶数变回奇数，因此偶数必胜、奇数必败。
// 时间复杂度：O(1)，只做一次取模；空间复杂度：O(1)，不需要额外空间。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool divisorGame(int n) {  // n：初始数字；返回先手 Alice 是否能赢下这局博弈
        return n % 2 == 0;  // n 为偶数时先手必胜，为奇数时必败，所以直接判断奇偶性
    }
};