// 题目：1047. 删除字符串中的所有相邻重复项（Remove All Adjacent Duplicates In String）
// 思路：从左到右扫描，用栈保存结果；当前字符与栈顶相同就弹栈（相当于把这一对一起删掉），否则入栈。
// 时间复杂度：O(n)，每个字符最多入栈出栈一次；空间复杂度：O(n)，栈最多保存 n 个字符。
char* removeDuplicates(char* s) {  // s：输入字符串；返回删除所有相邻重复对之后的新串
    int n = strlen(s);  // 先量出长度，用来决定栈数组的大小
    char* stack = malloc(sizeof(char) * (n + 1));  // 手工实现字符栈：最多存 n 个字符，多开 1 字节留给 '\0'
    int i = 0;  // i 既是栈顶下标，也等于栈中已有的字符个数
    for (int j = 0; j < n; j++) {  // 从左到右逐个处理输入字符
        char c = s[j];  // 取出当前字符
        if (i && stack[i - 1] == c) {  // 栈非空且栈顶与当前字符相同，构成一对相邻重复
            i--;  // 弹出栈顶，等价于把这两个字符一起删掉
        } else {  // 否则当前字符需要入栈
            stack[i++] = c;  // 写入栈顶位置后把栈顶指针后移
        }  // 分支结束
    }  // 扫描结束
    stack[i] = '\0';  // 补上字符串结束符，让栈内容成为合法的 C 字符串
    return stack;  // 返回结果串（由判题器负责后续释放）
}  // 函数结束