// 题目：1033. 移动石子直到连续（Moving Stones Until Consecutive）
// 思路：先定位最小、中间、最大值；跨度为 2（已连续）时答案为 0，否则最小步数看是否存在长度 <3 的空隙（1 步），最大步数是空位总数。
// 时间复杂度：O(1)，只做常数次比较；空间复杂度：O(1)，仅用几个整型变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> numMovesStones(int a, int b, int c) {  // 返回 {最小移动次数, 最大移动次数}；每步只能把端点石子移到空位，且移动后仍保持有序
        int x = min({a, b, c});  // 最左边那颗石子的位置
        int z = max({a, b, c});  // 最右边那颗石子的位置
        int y = a + b + c - x - z;  // 中间那颗石子的位置：三数之和减去首尾即可得到
        int mi = 0, mx = 0;  // mi 最小移动次数，mx 最大移动次数；若三颗已经连续则两者都保持 0
        if (z - x > 2) {  // 首尾跨度大于 2 说明还没连成连续三颗，一定需要移动
            mi = y - x < 3 || z - y < 3 ? 1 : 2;  // 相邻两颗的间距不超过 2 时可一步补空；否则至少两步
            mx = z - x - 2;  // 最大步数：跨度 z-x 里有 (z-x-2) 个空位，逐个挪过去就是最大次数
        }  // 是否需要移动的判断结束
        return {mi, mx};  // 按题目要求返回 [最小移动次数, 最大移动次数]
    }  // 方法结束
};  // 类定义结束