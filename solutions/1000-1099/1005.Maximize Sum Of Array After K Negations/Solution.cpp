// 题目：1005. K 次取反后最大化的数组和（Maximize Sum Of Array After K Negations）
// 核心思路：先尽量把负数取反成正数，剩余次数用偶数次抵消或牺牲最小正数
// 复杂度：时间 O(n + 100)（值域仅 201 个桶）；空间 O(1)
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int largestSumAfterKNegations(vector<int>& nums, int k) {  // nums：整数数组；k：必须恰好执行 k 次「把某个数取反」
        unordered_map<int, int> cnt;  // 计数表：键是数值，值是它在数组中出现的次数
        for (int& x : nums) {  // 遍历原数组，把每个数的出现次数统计进表
            ++cnt[x];  // 数值 x 的出现次数加一
        }  // 统计结束
        // 负数按绝对值从大到小枚举（x 从 -100 递增到 -1）
        for (int x = -100; x < 0 && k > 0; ++x) {  // 尽量先把负数翻成正数，k 用完即停
            if (cnt[x]) {  // 该负数在数组中确实存在才处理
                int m = min(cnt[x], k);  // 最多只能取反 min(出现次数, 剩余次数) 个
                cnt[x] -= m;  // 这些负数被取反，计数减少
                cnt[-x] += m;  // 对应的相反数（正数）计数增加
                k -= m;  // 消耗掉用掉的取反次数
            }  // 当前负数处理完毕
        }  // 负数处理结束，此时 k 可能仍有剩余
        if ((k & 1) && !cnt[0]) {  // 还剩奇数次取反且数组里有 0：翻转 0 不损失，无需再动其他数
            for (int x = 1; x <= 100; ++x) {  // 没有 0 可用，只能牺牲最小的正数
                if (cnt[x]) {  // 找到最小的、确实存在的正数
                    --cnt[x];  // 该正数被取反，计数减少
                    ++cnt[-x];  // 它的相反数（负数）计数增加
                    break;  // 只需取反一次，跳出循环
                }  // 存在性判断结束
            }  // 正数循环结束
        }  // 奇偶性处理结束
        int ans = 0;  // 累加数组和的变量
        for (auto& [x, v] : cnt) {  // 结构化绑定遍历计数表：x 是数值，v 是出现次数
            ans += x * v;  // 数值乘出现次数累加进总和
        }  // 求和结束
        return ans;  // 返回取反操作后的最大数组和
    }  // 方法结束
};  // 类定义结束