# 题目：1056. 易混淆数（Confusing Number）
# 思路：从低位到高位逐位旋转 180°，映射表 {0:0, 1:1, 6:9, 8:8, 9:6} 判断合法性；旋转结果与原数不同才是易混淆数。
# 时间复杂度：O(log n)，与数位个数成正比；空间复杂度：O(1)，映射表与常数个变量。
class Solution:  # LeetCode 约定的题解类
    def confusingNumber(self, n: int) -> bool:  # 判断 n 是否为易混淆数
        x, y = n, 0  # x 保存待处理的部分，y 保存旋转后得到的新数
        d = [0, 1, -1, -1, -1, -1, 9, -1, 8, 6]  # 数字 0~9 旋转后的值，-1 表示该位旋转后非法
        while x:  # 只要还有未处理的位就继续
            x, v = divmod(x, 10)  # 同时得到商（去掉最低位）和余数（最低位数字 v）
            if d[v] < 0:  # 最低位是 2/3/4/5/7，旋转后不合法
                return False  # 不是易混淆数
            y = y * 10 + d[v]  # 把旋转后的数字追加到 y 的低位，逆序重建新数
        return y != n  # 旋转后与原数不相等才算易混淆数
