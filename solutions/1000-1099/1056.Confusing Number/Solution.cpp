// 题目：1056. 易混淆数（Confusing Number）
// 思路：从最低位开始逐位取出数字，用映射表判断旋转 180° 是否合法，并逆序重建旋转后的新数，最后比较新数与原数是否不同。
// 时间复杂度：O(log n)，与数位个数成正比；空间复杂度：O(1)，映射表与常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool confusingNumber(int n) {  // 判断 n 旋转 180° 后是否得到不同的合法数字
        vector<int> d = {0, 1, -1, -1, -1, -1, 9, -1, 8, 6};  // 数字 0~9 旋转后的值，-1 表示该位旋转后非法
        int x = n, y = 0;  // x 是待处理的剩余部分，y 是旋转拼接出的新数字
        while (x) {  // 从最低位开始逐位处理
            int v = x % 10;  // 取当前最低位数字
            if (d[v] < 0) {  // 该位旋转后不合法（2、3、4、5、7）
                return false;  // 不是易混淆数，返回假
            }  // 非法分支结束
            y = y * 10 + d[v];  // 把旋转后的数字接到 y 的末尾，实现逆序重建
            x /= 10;  // 去掉已经处理过的最低位
        }  // 所有位处理完毕
        return y != n;  // 旋转后与原数不同才是易混淆数
    }  // 方法结束
};  // 类定义结束