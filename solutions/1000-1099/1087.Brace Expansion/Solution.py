# 题目：1087. 花括号展开（Brace Expansion）
# 思路：先把表达式切分成若干组候选词（花括号内按逗号拆分，花括号外整段算一个候选），再用 DFS 做各组之间的笛卡尔积拼出全部组合，最后按字典序排序。
# 时间复杂度：O(L + T·L)，L 为字符串长度、T 为展开后的组合数（最坏 2^L）；空间复杂度：O(T·L)，用于存放 T 个结果字符串与切分好的候选组。
class Solution:  # LeetCode 约定的题解类
    def expand(self, s: str) -> List[str]:  # s 形如 "{a,b}c{d,e}"，返回全部展开结果
        def convert(s):  # 内层函数：把表达式切分成「一组组候选词」存进 items
            if not s:  # 递归出口：剩余字符串为空
                return  # 没有可切分的内容，直接返回
            if s[0] == '{':  # 当前段以左花括号开头，说明这一组是候选集合
                j = s.find('}')  # 找到配对的右花括号位置
                items.append(s[1:j].split(','))  # 取出括号内的内容按逗号拆成候选词，作为一组
                convert(s[j + 1 :])  # 递归处理右括号之后的部分
            else:  # 否则当前段以普通字符（字面量）开头
                j = s.find('{')  # 找下一个左花括号的位置
                if j != -1:  # 找到了：花括号前还有一段字面量
                    items.append(s[:j].split(','))  # 把这段字面量整体作为一个候选词放进一组
                    convert(s[j:])  # 从花括号处继续递归切分
                else:  # 没找到：剩余部分全是字面量
                    items.append(s.split(','))  # 整段剩余字面量作为最后一组

        def dfs(i, t):  # 内层 DFS：i 是当前处理的组下标，t 是已拼好的片段列表
            if i == len(items):  # 所有组都处理完，得到一个完整组合
                ans.append(''.join(t))  # 把片段拼成一个字符串并收集到答案
                return  # 回溯，返回上一层继续换下一个候选词
            for c in items[i]:  # 枚举当前这一组的每一个候选词
                t.append(c)  # 选择当前候选词
                dfs(i + 1, t)  # 递归处理下一组
                t.pop()  # 撤销选择，恢复现场以便尝试下一个候选词

        items = []  # 保存切分后的分组候选：每组是一个字符串列表
        convert(s)  # 先完成切分，把 s 拆成 items
        ans = []  # 保存全部展开出来的组合
        dfs(0, [])  # 从第 0 组、空前缀开始做笛卡尔积
        ans.sort()  # 题目要求结果按字典序升序排列
        return ans  # 返回排序后的全部组合
