// 题目：1006. 笨阶乘（Clumsy Factorial）
// 核心思路：用栈延迟加减：乘除立即作用于栈顶，加减压栈后统一求和
// 复杂度：时间 O(n)；空间 O(n)，栈最多存 n 项
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int clumsy(int n) {  // n：笨阶乘的起点，运算符按 *、/、+、-、* … 循环
        stack<int> stk;  // 栈中存放待相加的各项：先算乘除，加减留到栈里统一求和
        stk.push(n);  // 第一个操作数 n 直接入栈
        int k = 0;  // k 记录下一位该用的运算符：0 乘、1 除、2 加、3 减
        for (int x = n - 1; x; --x) {  // 从 n-1 递减到 1，依次作为右操作数
            if (k == 0) {  // 轮到乘号
                stk.top() *= x;  // 乘号优先级高，直接与栈顶那一项相乘
            } else if (k == 1) {  // 轮到除号
                stk.top() /= x;  // 除号优先级高，与栈顶相除（C++ 整除向零取整）
            } else if (k == 2) {  // 轮到加号
                stk.push(x);  // 加号优先级低，先把 x 压栈等待最后统一相加
            } else {  // 轮到减号
                stk.push(-x);  // 减 x 等价于加上 -x，压入负数即可
            }  // 本次运算符处理完毕
            k = (k + 1) % 4;  // 运算符循环：乘 → 除 → 加 → 减 → 乘 …
        }  // 所有操作数处理完毕
        int ans = 0;  // 最终结果累加器
        while (!stk.empty()) {  // 逐个弹出栈中各项累加
            ans += stk.top();  // 加上栈顶这一项
            stk.pop();  // 弹出已累加的项
        }  // 栈空表示累加完成
        return ans;  // 返回笨阶乘的计算结果
    }  // 方法结束
};  // 类定义结束