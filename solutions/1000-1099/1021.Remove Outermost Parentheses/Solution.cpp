// 题目：1021. 删除最外层的括号（Remove Outermost Parentheses）
// 思路：用深度 cnt 表示当前括号嵌套层数；只有深度 > 1 的左括号和减完后深度 > 0 的右括号才属于原语内部，加入答案。
// 时间复杂度：O(n)，只扫描一遍字符串；空间复杂度：O(n)，答案字符串最多存 n - 2 个字符。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string removeOuterParentheses(string s) {  // s：由若干合法括号串拼接而成；返回删掉每个原语最外层括号后的结果
        string ans;  // 用字符缓冲区逐步拼接答案，避免反复创建字符串
        int cnt = 0;  // 当前括号深度：遇到 '(' 加一，遇到 ')' 减一
        for (char& c : s) {  // 按引用遍历每个字符，只读不修改
            if (c == '(') {  // 遇到左括号：嵌套深度先加一
                if (++cnt > 1) {  // 先自增再比较；深度 > 1 说明它不是某个原语的最外层左括号
                    ans.push_back(c);  // 属于内部结构，保留该左括号
                }
            } else {  // 遇到右括号：嵌套深度先减一
                if (--cnt) {  // 先自减再判断；自减后仍非 0 说明它没有把某个原语闭合到最外层
                    ans.push_back(c);  // 属于内部结构，保留该右括号
                }
            }
        }
        // 遍历结束，缓冲区里就是删掉最外层括号后的所有内部字符
        return ans;  // 返回拼接好的结果串
    }
};