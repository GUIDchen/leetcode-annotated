# 题目：1021. 删除最外层的括号（Remove Outermost Parentheses）
# 思路：维护当前嵌套深度 cnt，只保留深度大于 1 的左括号和减完后深度仍大于 0 的右括号，其余都是某个原语的最外层括号。
# 时间复杂度：O(n)，只遍历一遍字符串；空间复杂度：O(n)，用于保存结果字符列表。
class Solution:  # LeetCode 约定的题解类
    def removeOuterParentheses(self, s: str) -> str:  # s：由若干合法括号原语拼接而成；返回删除每个原语最外层括号后的结果
        ans = []  # 用列表收集字符，最后统一 join，避免字符串反复拼接
        cnt = 0  # 当前括号嵌套深度：'(' 使深度加一，')' 使深度减一
        for c in s:  # 逐字符扫描
            if c == '(':  # 左括号让嵌套深度加一
                cnt += 1  # 深度增加
                if cnt > 1:  # 深度仍大于 1，说明不是原语最外层的那个左括号
                    ans.append(c)  # 属于内部结构，保留
            else:  # 右括号让嵌套深度减一
                cnt -= 1  # 深度减少
                if cnt > 0:  # 减完后深度仍大于 0，说明不是原语最外层的那个右括号
                    ans.append(c)  # 属于内部结构，保留
        # 所有原语处理完毕，把收集到的字符拼成字符串返回
        return ''.join(ans)  # 用空串连接字符列表
