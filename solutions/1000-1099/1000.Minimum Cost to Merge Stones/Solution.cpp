// 题目：1000. 合并石头的最低成本（Minimum Cost to Merge Stones）
// 思路：区间 DP，f[i][j][k] 表示把区间 [i, j] 合并成 k 堆的最小代价；枚举分界点把区间拆成「左边 1 堆 + 右边 k-1 堆」，再单独处理 k=1 时把 K 堆并成 1 堆的额外代价。
// 时间复杂度：O(n^3 · K)，空间复杂度：O(n^2 · K)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int mergeStones(vector<int>& stones, int K) {  // stones：每堆石子的数量；K：每次必须合并的堆数；返回合并成一堆的最小总代价
        int n = stones.size();  // 石子堆数
        if ((n - 1) % (K - 1)) {  // 每次合并把 K 堆变成 1 堆，总堆数减少 K-1；要从 n 堆减到 1 堆，必须能整除
            return -1;  // 不能整除说明无解，按题意返回 -1
        }
        int s[n + 1];  // 前缀和数组：s[i] 表示前 i 堆石子之和，用于 O(1) 求任意区间和
        s[0] = 0;  // 空前缀的和为 0
        for (int i = 1; i <= n; ++i) {  // 从第 1 堆开始递推前缀和
            s[i] = s[i - 1] + stones[i - 1];  // 把第 i 堆（下标 i-1）累加进前缀和
        }
        int f[n + 1][n + 1][K + 1];  // f[i][j][k]：把区间 [i, j] 合并成 k 堆所需的最小代价
        memset(f, 0x3f, sizeof(f));  // 用 0x3f 填满，相当于初始化为无穷大，表示状态暂不可达
        for (int i = 1; i <= n; ++i) {  // 先处理长度为 1 的区间
            f[i][i][1] = 0;  // 单堆区间本身已经是 1 堆，代价为 0
        }
        for (int l = 2; l <= n; ++l) {  // 按区间长度由小到大递推，保证子区间先算好
            for (int i = 1; i + l - 1 <= n; ++i) {  // 枚举区间左端点，保证右端点不越界
                int j = i + l - 1;  // 由左端点和长度算出右端点
                for (int k = 1; k <= K; ++k) {  // 枚举要把区间合并成的堆数 k
                    for (int h = i; h < j; ++h) {  // 枚举分界点 h，把 [i, j] 拆成 [i, h] 与 [h+1, j]
                        f[i][j][k] = min(f[i][j][k], f[i][h][1] + f[h + 1][j][k - 1]);  // 左半段合成 1 堆、右半段合成 k-1 堆，两边代价相加取最小
                    }
                }
                f[i][j][1] = f[i][j][K] + s[j] - s[i - 1];  // 把整个区间的 K 堆再合并成 1 堆，额外付出的代价就是这段石子的总数
            }
        }
        return f[1][n][1];  // 返回把 1..n 全部合并成 1 堆的最小总代价
    }
};