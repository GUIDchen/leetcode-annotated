// 题目：1073. 负二进制数相加（Adding Two Negabinary Numbers）
// 思路：从最低位向最高位模拟 -2 进制加法；本位和 x 只有 -1/0/1/2/3 几种可能，x>=2 时本位留 x-2 并向高位进 -1，x==-1 时本位写 1 并向高位进 +1。
// 时间复杂度：O(max(m, n))，两个数组各扫描一遍；空间复杂度：O(max(m, n))，用于存放结果数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> addNegabinary(vector<int>& arr1, vector<int>& arr2) {  // arr1、arr2 为高位在前的 -2 进制数字数组
        int i = arr1.size() - 1, j = arr2.size() - 1;  // 两个指针都指向各自数组的最低位（末尾）
        vector<int> ans;  // 按“低位到高位”的顺序收集每一位结果
        for (int c = 0; i >= 0 || j >= 0 || c; --i, --j) {  // c 是进位（可为 -1）；只要还有位或还有进位就继续
            int a = i < 0 ? 0 : arr1[i];  // 取 arr1 当前位，指针越界时补 0
            int b = j < 0 ? 0 : arr2[j];  // 取 arr2 当前位，指针越界时补 0
            int x = a + b + c;  // 三个加数在本位的和
            c = 0;  // 先清零进位，下面按规则重新计算
            if (x >= 2) {  // 本位和 >= 2，说明多了两个单位，需要向高位“进 -1”
                x -= 2;  // 本位留下 x-2，结果为 0 或 1
                c -= 1;  // 因为 (-2)^(k+1) = -2 * (-2)^k，两个本位单位等于高位的一个 -1
            } else if (x == -1) {  // 本位和为 -1，用 -1 = 1 - 2 改写成合法数字
                x = 1;  // 本位写成 1
                c += 1;  // 多减掉的 2 折算成向高位进 +1
            }
            ans.push_back(x);  // 记录本位最终数字（此时为低位在前）
        }
        while (ans.size() > 1 && ans.back() == 0) {  // 去掉高位多余的 0，但至少保留一位
            ans.pop_back();  // 弹出当前最高位的 0
        }
        reverse(ans.begin(), ans.end());  // 由低位在前翻转为题目要求的高位在前
        return ans;  // 返回 -2 进制表示的数组
    }
};