// 题目：2423. 删除字符使频率相同（Remove Letter To Equalize Frequency）
// 思路：先统计 26 个字母的出现次数，再枚举「删掉哪一个字母」，删后检查所有非零频率是否全部相同。
// 时间复杂度：O(26 × 26 + n) = O(n)，统计一遍字符串后最多做 26 次 O(26) 的检查；空间复杂度：O(1)，只用 26 大小的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool equalFrequency(string word) {  // word：输入字符串；判断能否恰好删除一个字符使剩余字符频率全相同
        int cnt[26]{};  // 计数数组，cnt[i] 表示第 i 个小写字母出现的次数，{} 保证全部初始化为 0
        for (char& c : word) {  // 遍历字符串中的每个字符
            ++cnt[c - 'a'];  // 字符减 'a' 映射到 0..25 的下标，出现次数加一
        }
        for (int i = 0; i < 26; ++i) {  // 枚举被删除的那个字符是哪一个小写字母
            if (cnt[i]) {  // 只有实际出现过的字母才可能被删除
                --cnt[i];  // 试删一个该字母，模拟删除操作
                int x = 0;  // x 记录第一个非零频率，作为后面比较的基准
                bool ok = true;  // ok 表示删掉该字母后，剩余字母的频率是否全部相同
                for (int v : cnt) {  // 遍历 26 个字母的频率
                    if (v == 0) {  // 频率为 0 说明该字母已不存在，不参与比较
                        continue;  // 跳过它
                    }
                    if (x && v != x) {  // 基准已确定且当前频率与基准不同，说明剩余频率不一致
                        ok = false;  // 标记检查失败
                        break;  // 无需继续检查，提前跳出内层循环
                    }
                    x = v;  // 首次遇到非零频率时（x 为 0），把它设为基准
                }
                if (ok) {  // 删掉该字母后所有剩余频率都相同
                    return true;  // 找到可行方案，立即返回
                }
                ++cnt[i];  // 恢复现场：把刚才试删的次数补回来，继续尝试下一个字母
            }
        }
        return false;  // 所有出现过的字母都试过仍不行，返回 false
    }
};