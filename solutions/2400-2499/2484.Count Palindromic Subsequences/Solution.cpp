// 题目：2484. 统计回文子序列数目（Count Palindromic Subsequences）
// 思路：回文子序列必为 a b c b a；枚举中心位置，用前后缀计数表相乘拼出所有形如 (j,k,c,k,j) 的方案。
// 时间复杂度：O(n * 10 * 10)，n 为串长；空间复杂度：O(n * 10 * 10)，即 pre、suf 两张计数表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    const int mod = 1e9 + 7;  // 取模常量：答案很大，按题意对 1e9+7 取模

    int countPalindromes(string s) {  // s：只含数字字符的字符串；返回长度为 5 的回文子序列个数
        int n = s.size();  // 字符串长度
        int pre[n + 2][10][10];  // pre[i][j][k]：前缀 s[0..i-1] 中形如「j 在前、k 在后」的下标对个数
        int suf[n + 2][10][10];  // suf[i][j][k]：后缀 s[i-1..n-1] 中形如「j 在前、k 在后」的下标对个数
        memset(pre, 0, sizeof pre);  // 前缀表清零：i=0 表示空前缀，没有任何下标对
        memset(suf, 0, sizeof suf);  // 后缀表清零：i=n+1 表示空后缀，没有任何下标对
        int t[n];  // 把字符预先转成数字，循环里就不用反复做减法
        for (int i = 0; i < n; ++i) t[i] = s[i] - '0';  // 把 '0'..'9' 映射为 0..9
        int c[10] = {0};  // c[d]：当前已扫描部分中数字 d 出现的次数
        for (int i = 1; i <= n; ++i) {  // 从前往后构造前缀表，i 表示把前 i 个字符纳入统计
            int v = t[i - 1];  // 本次新纳入的数字（0 基下标）
            for (int j = 0; j < 10; ++j) {  // 枚举下标对的第一个数字 j
                for (int k = 0; k < 10; ++k) {  // 枚举下标对的第二个数字 k
                    pre[i][j][k] = pre[i - 1][j][k];  // 先整体继承前一个前缀的计数
                }  // k 维复制结束
            }  // j 维复制结束
            for (int j = 0; j < 10; ++j) {  // 再用新字符 v 作为下标对的第二个元素去扩展
                pre[i][j][v] += c[j];  // v 之前 j 出现过 c[j] 次，故新增 c[j] 个 (j, v) 下标对
            }  // 扩展循环结束
            c[v]++;  // v 计入已扫描次数，供后续位置使用
        }  // 前缀表构造完毕
        memset(c, 0, sizeof c);  // 计数清空，复用同一个数组做从右往左的扫描
        for (int i = n; i > 0; --i) {  // 从后往前构造后缀表，i 表示把 s[i-1..n-1] 纳入统计
            int v = t[i - 1];  // 本次新纳入的数字
            for (int j = 0; j < 10; ++j) {  // 枚举下标对的第一个数字 j
                for (int k = 0; k < 10; ++k) {  // 枚举下标对的第二个数字 k
                    suf[i][j][k] = suf[i + 1][j][k];  // 继承右邻后缀的计数
                }  // k 维复制结束
            }  // j 维复制结束
            for (int j = 0; j < 10; ++j) {  // 再用新字符 v 作为下标对的首元素向左扩展
                suf[i][j][v] += c[j];  // v 在左、j 在右的组合新增 c[j] 个
            }  // 扩展循环结束
            c[v]++;  // v 计入已扫描次数
        }  // 后缀表构造完毕
        long ans = 0;  // 答案用 long 累加，避免中途溢出
        for (int i = 1; i <= n; ++i) {  // 枚举回文子序列的中心位置（长度为 5，中心是唯一的中位字符）
            for (int j = 0; j < 10; ++j) {  // 枚举前半部分第一个数字 j
                for (int k = 0; k < 10; ++k) {  // 枚举前半部分第二个数字 k
                    ans += 1ll * pre[i - 1][j][k] * suf[i + 1][j][k];  // 左右两侧 (j, k) 下标对数量相乘，即所有 j k c k j 方案的组合数
                    ans %= mod;  // 随时取模，防止累加过程溢出
                }  // k 循环结束
            }  // j 循环结束
        }  // 中心位置枚举结束
        return ans;  // 返回方案总数
    }  // 方法结束
};  // 类定义结束