// 题目：2417. 最近的公平整数（Closest Fair Integer）
// 思路：公平整数的奇数位与偶数位个数相等，所以位数必须是偶数；先统计 n 的位数 k 与奇偶位计数，若已公平直接返回，若 k 为奇数则答案是最小的 k+1 位数 10^k + 11...1（k/2 个 1），否则逐次 +1 向后尝试。
// 时间复杂度：O(k + d)，k 为位数、d 为向后枚举的次数（d 很小）；空间复杂度：O(1)，只用了常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int closestFair(int n) {  // 返回大于等于 n 的最小公平整数
        int a = 0, b = 0;  // a：奇数数字的个数；b：偶数数字的个数
        int t = n, k = 0;  // t：用于逐位剥离的副本；k：n 的十进制位数
        while (t) {  // 不断取末位，直到 t 变成 0
            if ((t % 10) & 1) {  // t % 10 取出最低位，& 1 判断是否为奇数
                ++a;  // 奇数位计数加一
            } else {  // 否则是偶数数字
                ++b;  // 偶数位计数加一
            }
            ++k;  // 处理掉一位，位数加一
            t /= 10;  // 右移一位，继续处理下一位
        }
        if (a == b) {  // 当前 n 的奇偶位个数已经相等
            return n;  // n 本身就是公平整数，直接返回
        }
        if (k % 2 == 1) {  // k 为奇数说明奇偶位总数是奇数，不可能平分，答案必然位数更多
            int x = pow(10, k);  // 10^k：最小的 k+1 位数（1 后面 k 个 0）
            int y = 0;  // y 用来拼出 k/2 个 1
            for (int i = 0; i < k >> 1; ++i) {  // 循环 k/2 次（>> 优先级低于 <，等价于 i < (k >> 1)）
                y = y * 10 + 1;  // 逐次在后面接一个 1，得到 1、11、111……
            }
            return x + y;  // 10^k + 11...1：奇数位与偶数位各 (k+1)/2 个，是最小的公平整数
        }
        return closestFair(n + 1);  // k 为偶数但奇偶位不等：n 不行，递归检查 n+1
    }
};