# 题目：2417. 最近的公平整数（Closest Fair Integer）
# 思路：公平整数的奇数位与偶数位个数相等，所以位数必须是偶数；先统计 n 的位数 k 与奇偶位计数，若 k 为奇数则答案是最小的 k+1 位数 10^k + 11...1（k/2 个 1），否则若已公平直接返回，不然逐次 +1 向后尝试。
# 时间复杂度：O(k + d)，k 为位数、d 为向后枚举的次数（d 很小）；空间复杂度：O(1)，只用了常数个变量（递归深度同理很小）。
class Solution:  # LeetCode 约定的题解类
    def closestFair(self, n: int) -> int:  # 返回大于等于 n 的最小公平整数
        a = b = k = 0  # a：奇数数字个数；b：偶数数字个数；k：n 的十进制位数
        t = n  # t 是 n 的副本，逐位剥离时不能破坏原值
        while t:  # 不断取末位，直到 t 变成 0
            if (t % 10) & 1:  # t % 10 取出最低位，& 1 判断是否为奇数
                a += 1  # 奇数位计数加一
            else:  # 否则是偶数数字
                b += 1  # 偶数位计数加一
            t //= 10  # 整除 10，右移一位继续处理
            k += 1  # 处理掉一位，位数加一
        if k & 1:  # k 为奇数说明奇偶位总数是奇数，不可能平分，答案必然位数更多
            x = 10**k  # 10^k：最小的 k+1 位数（1 后面 k 个 0）
            y = int('1' * (k >> 1) or '0')  # 拼出 k/2 个 1；k=1 时字符串为空，用 or '0' 兜底取 0
            return x + y  # 10^k + 11...1：奇数位与偶数位各 (k+1)/2 个，是最小的公平整数
        if a == b:  # k 为偶数，再看当前 n 的奇偶位个数是否已经相等
            return n  # n 本身就是公平整数，直接返回
        return self.closestFair(n + 1)  # 否则 n 不行，递归检查 n+1
