// 题目：2472. 不重叠回文子字符串的最大数目（Maximum Number of Non-overlapping Palindrome Substrings）
// 思路：区间 DP 预处理 g[i][j] 表示 s[i..j] 是否回文；再用 f[i] 表示后缀 s[i..] 中长度不小于 k 的不重叠回文子串最大个数，转移 f[i] = max(f[i+1], 1 + f[j+1])。
// 时间复杂度：O(n^2)，预处理与转移都是平方级；空间复杂度：O(n^2)，g 表占 n×n。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见，判题器据此调用
    int maxPalindromes(string s, int k) {  // s 是原字符串，k 是可选取回文子串的最小长度
        int n = s.size();  // n 记录串长，后续所有 DP 都依赖它
        bool g[n][n];  // g[i][j] 表示子串 s[i..j] 是否为回文，先开好二维布尔表
        memset(g, true, sizeof(g));  // 按字节全置 1，等价于把每个位置初始化为 true，便于处理长度 ≤ 1 的区间
        for (int i = n - 1; ~i; --i) {  // 逆序枚举左端点 i，保证计算 g[i][j] 时内部区间 g[i+1][j-1] 已经算好
            for (int j = i + 1; j < n; ++j) {  // 枚举右端点 j，从 i+1 开始，长度 1 的区间天然是回文无需再判
                g[i][j] = s[i] == s[j] && g[i + 1][j - 1];  // 两端字符相同且内部区间回文，则 s[i..j] 整体回文
            }  // 右端点循环结束
        }  // 左端点循环结束，回文判定表预处理完成
        int f[n + 1];  // f[i]：从下标 i 开始的后缀最多能取出多少个不重叠且长度 ≥ k 的回文子串
        memset(f, 0, sizeof(f));  // 初值全 0，表示后缀长度不足时一个也取不到
        for (int i = n - 1; ~i; --i) {  // 同样逆序枚举，保证 f[j+1] 这种更靠后的状态已经求出
            f[i] = f[i + 1];  // 不选以 i 开头的任何回文子串时，直接继承 f[i+1]
            for (int j = i + k - 1; j < n; ++j) {  // 枚举以 i 开头、长度至少为 k 的右端点 j
                if (g[i][j]) {  // 只有 s[i..j] 确实是回文才可能作为一段被选中
                    f[i] = max(f[i], 1 + f[j + 1]);  // 选中这一段得 1 个，剩余部分从 j+1 继续，两者取较大值
                }  // 分支结束
            }  // 右端点枚举结束
        }  // 左端点枚举结束，此时 f[0] 就是整体最优
        return f[0];  // 从整串起点出发的最大数目就是答案
    }  // 方法结束
};  // 类定义结束
