// 题目：2481. 分割圆的最少切割次数（Minimum Cuts to Divide a Circle）
// 思路：n == 1 不用切；n 为偶数时每条直径一刀切出两块，共 n/2 刀；n 为奇数时没有任何一刀能同时照顾两个点，必须每个点单独引一条半径，共 n 刀。
// 时间复杂度：O(1)，只做常数次判断；空间复杂度：O(1)，只用常数额外变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberOfCuts(int n) {  // n：要把圆分成的等份数；返回最少切割次数
        return n > 1 && n % 2 == 1 ? n : n >> 1;  // n>1 且为奇数时需 n 刀，否则取 n/2（n==1 时 1>>1 正好得 0）
    }  // 结束题解方法
};  // 结束题解类