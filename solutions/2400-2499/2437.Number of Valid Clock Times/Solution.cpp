// 题目：2437. 有效时间的数目（Number of Valid Clock Times）
// 思路：枚举 0..23 时与 0..59 分，格式化成 "HH:MM" 后逐位与模式串比对，'?' 视为通配符，累加所有匹配项。
// 时间复杂度：O(24 * 60 * 5)，枚举量固定，视为常数级；空间复杂度：O(1)，只用固定长度的字符缓冲。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countTime(string time) {  // time：形如 "??:??" 的模式串，'?' 可以匹配任意数字
        int ans = 0;  // 答案计数器：统计能匹配模式串的合法时间个数
        for (int h = 0; h < 24; ++h) {  // 枚举小时 0..23
            for (int m = 0; m < 60; ++m) {  // 枚举分钟 0..59
                char s[20];  // 字符缓冲，存放格式化后的时间串，长度足够容纳 "HH:MM"
                sprintf(s, "%02d:%02d", h, m);  // 把时、分格式化成两位补零的时间串
                int ok = 1;  // 标记当前时间是否与模式串匹配，先假定匹配
                for (int i = 0; i < 5; ++i) {  // 逐位比对 5 个字符（4 位数字加上中间的冒号）
                    if (s[i] != time[i] && time[i] != '?') {  // 该位不相同且模式串该位不是 '?' 通配符，说明匹配失败
                        ok = 0;  // 标记为不匹配
                        break;  // 已经确定不匹配，无需再比对后面的位
                    }  // if 分支结束
                }  // 内层 for 循环结束
                ans += ok;  // ok 为 1 时答案加一，为 0 时不变
            }  // 分钟循环结束
        }  // 小时循环结束
        return ans;  // 返回匹配模式串的合法时间总数
    }  // countTime 方法结束
};  // 类定义结束