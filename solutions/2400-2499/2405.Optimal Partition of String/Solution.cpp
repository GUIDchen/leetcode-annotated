// 题目：2405. 子字符串的最优划分（Optimal Partition of String）
// 思路：贪心加 26 位掩码：当前段只要不出现重复字母就继续延伸，一旦重复说明必须在这里切分并重开一段。
// 时间复杂度：O(n)，每个字符只处理一次；空间复杂度：O(1)，只用一个掩码和一个计数器。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int partitionString(string s) {  // s：待划分的字符串，返回最少需要划分出的子串个数
        int ans = 1, mask = 0;  // ans 至少为 1 段；mask 用二进制位记录当前段里已经出现过的字母
        for (char& c : s) {  // 依次扫描字符串中的每个字符
            int x = c - 'a';  // 把字母映射成 0~25 的编号，对应 mask 的第几位
            if (mask >> x & 1) {  // 该位为 1 说明本段已出现过这个字母，必须切分
                ++ans;  // 段数加一
                mask = 0;  // 清空掩码，开始记录新的一段
            }  // 重复分支结束
            mask |= 1 << x;  // 把当前字母标记进本段的字母集合
        }  // 扫描结束
        return ans;  // 返回最少段数
    }  // 方法结束
};  // 题解类结束
