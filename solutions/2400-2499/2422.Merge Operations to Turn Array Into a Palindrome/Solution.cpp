// 题目：2422. 使用合并操作将数组转换为回文序列（Merge Operations to Turn Array Into a Palindrome）
// 思路：双指针从两端向中间靠拢，分别维护左段累计和 a 与右段累计和 b；哪边小就把下一个元素并进来，直到两端累计和相等，合并次数即答案。
// 时间复杂度：O(n)，两指针只向中间移动，每个元素至多被并入一次；空间复杂度：O(1)，仅用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumOperations(vector<int>& nums) {  // nums：输入数组；返回把它变成回文所需的最少合并次数
        int i = 0, j = nums.size() - 1;  // 左指针指向首元素，右指针指向尾元素，二者向中间靠拢
        long a = nums[i], b = nums[j];  // a、b 分别为左段与右段的累计和；用 long 防止多次合并后溢出
        int ans = 0;  // 累计合并操作的次数
        while (i < j) {  // 两端尚未相遇，说明还有元素待处理
            if (a < b) {  // 左段累计和偏小，只能从左边再并入一个元素
                a += nums[++i];  // 左指针先右移一位，再把该元素累加到 a
                ++ans;  // 发生了一次合并，计数加一
            } else if (b < a) {  // 右段累计和偏小，对称地从右边并入
                b += nums[--j];  // 右指针先左移一位，再把该元素累加到 b
                ++ans;  // 发生了一次合并，计数加一
            } else {  // 两端累计和相等，这一对已经配对成功，两指针同时内移
                a = nums[++i];  // 左指针内移，并把左段累计和重置为新元素的起点
                b = nums[--j];  // 右指针内移，并把右段累计和重置为新元素的起点
            }
        }
        return ans;  // 返回最少的合并次数
    }
};