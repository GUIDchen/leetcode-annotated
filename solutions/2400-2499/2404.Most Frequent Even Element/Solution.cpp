// 题目：2404. 出现最频繁的偶数元素（Most Frequent Even Element）
// 思路：用哈希表统计每个偶数的出现次数，再在「次数最多」的前提下选出数值最小的偶数。
// 时间复杂度：O(n)，一次遍历统计加一次遍历哈希表；空间复杂度：O(n)，最多存 n 个不同的偶数。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int mostFrequentEven(vector<int>& nums) {  // nums：输入整数数组，返回出现次数最多且数值最小的偶数
        unordered_map<int, int> cnt;  // 哈希表：键是偶数，值是它出现的次数
        for (int x : nums) {  // 遍历数组中的每一个元素
            if (x % 2 == 0) {  // 只关心偶数，奇数直接跳过
                ++cnt[x];  // 该偶数的出现次数加一（键不存在时默认从 0 开始）
            }  // 偶数分支结束
        }  // 统计阶段结束
        int ans = -1, mx = 0;  // ans 记录答案（-1 表示还没有遇到偶数），mx 记录当前最大出现次数
        for (auto& [x, v] : cnt) {  // 结构化绑定遍历哈希表：x 是偶数，v 是它的出现次数
            if (mx < v || (mx == v && ans > x)) {  // 次数更多，或次数相同但数值更小，都要更新答案（题目要求并列时取最小值）
                ans = x;  // 把答案的偶数更新为 x
                mx = v;  // 同步更新当前最大出现次数
            }  // 更新分支结束
        }  // 遍历哈希表结束
        return ans;  // 没有偶数时 ans 仍是 -1，正好符合题目要求
    }  // 方法结束
};  // 题解类结束