// 题目：2483. 商店的最少代价（Minimum Penalty for a Shop）
// 思路：先假设 0 点关门，代价就是全部 'Y' 的个数；之后逐小时把关门时刻右移，遇到 'N' 代价加 1（营业时白等），遇到 'Y' 代价减 1（少拒一个顾客），全程取最小代价且只在严格更小时更新，保证并列时保留最早时刻。
// 时间复杂度：O(n)，两次线性扫描；空间复杂度：O(1)，只用几个整型变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int bestClosingTime(string customers) {  // customers：每小时 'Y' 有顾客 / 'N' 没顾客；返回代价最小的最早关门时刻（小时数）
        int ans = 0;  // 目前最优的关门时刻，初值为 0 点（一直营业）
        int cost = 0;  // 当前关门时刻对应的代价
        for (char c : customers) {  // 先统计整个字符串里 'Y' 的个数
            if (c == 'Y') {  // 该小时有顾客
                cost++;  // 0 点关门时所有 'Y' 都会被挡在门外，代价加一
            }  // 结束 if
        }  // 结束统计循环
        int mn = cost;  // 记录目前的最小代价（对应 0 点关门）
        for (int j = 1; j <= customers.size(); ++j) {  // j 从 1 到 n 枚举关门时刻：关门后前 j 小时营业
            cost += customers[j - 1] == 'N' ? 1 : -1;  // 把第 j 小时纳入营业：'N' 多一个空转代价(+1)，'Y' 则少一个被拒代价(-1)
            if (cost < mn) {  // 出现更小的代价；用严格小于保证并列时保留更早的时刻
                ans = j;  // 更新最优关门时刻
                mn = cost;  // 更新最小代价
            }  // 结束 if
        }  // 结束枚举
        return ans;  // 返回最优关门时刻
    }  // 结束题解方法
};  // 结束题解类
