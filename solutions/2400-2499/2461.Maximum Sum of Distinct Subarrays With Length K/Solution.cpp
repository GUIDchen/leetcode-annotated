// 题目：2461. 长度为 K 子数组中的最大和（Maximum Sum of Distinct Subarrays With Length K）
// 思路：定长滑动窗口 + 哈希表记录窗口内各值出现次数；窗口内不同值个数等于 k 时窗口和才合法，滑动时增量维护窗口和。
// 时间复杂度：O(n)，每个元素最多进出窗口一次；空间复杂度：O(k)，哈希表最多保存窗口内 k 个不同值。
class Solution {  // LeetCode 题解类，判题器会实例化它并调用下面的方法
public:  // 方法需要对外可见，所以放在 public 区
    long long maximumSubarraySum(vector<int>& nums, int k) {  // nums 是输入数组，k 是窗口长度；答案可能很大，返回值用 long long
        using ll = long long;  // 给 long long 起短别名，后面声明哈希表和累加变量时更简洁
        int n = nums.size();  // 数组长度，循环边界只求一次，避免重复调用 size()
        unordered_map<int, ll> cnt;  // 哈希表：键为元素值、值为它在当前窗口内出现的次数，用来判断窗口内是否每个数都不同
        ll s = 0;  // s 维护当前窗口的元素和，滑动时增量更新，省掉每次重新求和 O(k) 的开销
        for (int i = 0; i < k; ++i) {  // 先把前 k 个元素装进初始窗口
            ++cnt[nums[i]];  // 新元素进入窗口，出现次数加一
            s += nums[i];  // 把该元素累加进窗口和
        }  // 初始窗口构造完成
        ll ans = cnt.size() == k ? s : 0;  // 不同值个数等于 k 说明这 k 个数互不相同，此时初始和才是合法候选；否则先记 0 表示还没有合法窗口
        for (int i = k; i < n; ++i) {  // 窗口整体右移一格：右侧进一个新元素、左侧出一个旧元素
            ++cnt[nums[i]];  // 新元素 nums[i] 进入窗口，计数加一
            if (--cnt[nums[i - k]] == 0) {  // 旧元素 nums[i-k] 移出窗口；先自减再看是否为 0，为 0 说明它已完全离开窗口
                cnt.erase(nums[i - k]);  // 把计数为 0 的键从哈希表删掉，保证 cnt.size() 恰好等于窗口内不同元素的个数
            }  // 移出窗口的处理结束
            s += nums[i] - nums[i - k];  // 窗口和增量更新：加上进窗的新元素、减去出窗的旧元素
            if (cnt.size() == k) {  // 不同元素个数等于窗口长度，说明当前窗口内没有重复
                ans = max(ans, s);  // 用当前窗口和刷新历史最大值
            }  // 本次窗口的判定结束
        }  // 所有长度为 k 的窗口都枚举完毕
        return ans;  // 返回最大和；若全程不存在元素互不相同的窗口则返回 0
    }  // 方法结束
};  // 类定义结束（源文件末尾没有换行，保持原样）