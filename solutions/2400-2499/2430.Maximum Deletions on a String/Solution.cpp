// 题目：2430. 对字母串可执行的最大删除数（Maximum Deletions on a String）
// 核心思路：先预处理 g[i][j] 为从 i、j 开始的最长公共前缀长度，再用记忆化搜索 f[i] 表示后缀 s[i..] 的最大删除次数，枚举可删的前缀长度 j；整串也可一次删完。
// 时间复杂度：O(n^2)，预处理与状态转移各 O(n^2)；空间复杂度：O(n^2)，保存 g 表与 f 数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int deleteString(string s) {  // s 是输入的字母串，返回最多可执行的删除次数
        int n = s.size();  // n 是字符串长度
        vector<vector<int>> g(n + 1, vector<int>(n + 1));  // g[i][j]：从 i 与 j 开始的最长公共前缀长度；多开一行一列避免 i+1、j+1 越界
        for (int i = n - 1; ~i; --i) {  // 从后往前枚举 i，保证 g[i+1][j+1] 已经算好
            for (int j = i + 1; j < n; ++j) {  // j 只需从 i+1 开始，因为两段前缀不能重叠
                if (s[i] == s[j]) {  // 当前位置两字符相同，公共前缀长度才能继续延长
                    g[i][j] = g[i + 1][j + 1] + 1;  // 由下一对字符的结果加 1 递推得到
                }  // 对应 if 分支结束
            }  // 内层 j 循环结束
        }  // 外层 i 循环结束
        int f[n];  // f[i]：后缀 s[i..n-1] 最多还能删几次；0 表示尚未计算（记忆化标记）
        memset(f, 0, sizeof(f));  // 全部清零，作为“未访问”的初始状态
        function<int(int)> dfs = [&](int i) -> int {  // 记忆化搜索：返回从下标 i 开始最多能执行的删除次数
            if (i == n) {  // 已经删到末尾，无法再删
                return 0;  // 返回 0 次删除
            }  // if 分支结束
            if (f[i]) {  // 该状态此前算过，直接复用结果避免重复计算
                return f[i];  // 返回缓存下来的答案
            }  // if 分支结束
            f[i] = 1;  // 保底方案：一次把剩余整串删掉，所以至少是 1
            for (int j = 1; j <= (n - i) / 2; ++j) {  // 枚举要删除的前缀长度 j，剩余长度必须不小于 j
                if (g[i][i + j] >= j) {  // 前 j 个字符与紧随其后的 j 个字符完全相同，才允许这次删除
                    f[i] = max(f[i], 1 + dfs(i + j));  // 删掉这 j 个字符，再递归求剩余后缀的最优值
                }  // if 分支结束
            }  // j 枚举结束
            return f[i];  // 返回后缀 s[i..] 的最优删除次数
        };  // lambda 定义结束
        return dfs(0);  // 从整个字符串开头开始搜索
    }  // deleteString 方法结束
};  // Solution 类定义结束