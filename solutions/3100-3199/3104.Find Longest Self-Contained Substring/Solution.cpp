// 题目：3104. 查找最长的自包含子串（Find Longest Self-Contained Substring）
// 思路：先统计每个字母的首、末出现位置；以每个字母的首位置为左端点向右扩展，维护区间内最远末位置 mx，当 mx 恰好等于右端点 j 时区间自包含；长度等于 n 的整串不计，取最大值。
// 时间复杂度：O(26 * n) 即 O(n)，左端点只有 26 种取值；空间复杂度：O(26) 即 O(1)，只存首末位置数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxSubstringLength(string s) {  // s：输入字符串；返回最长自包含子串的长度，找不到返回 -1
        vector<int> first(26, -1);  // 记录每个字母首次出现的下标，-1 表示没出现过
        vector<int> last(26);  // 记录每个字母最后出现的下标
        int n = s.length();  // 字符串长度，后面多处要用
        for (int i = 0; i < n; ++i) {  // 第一遍扫描：统计每个字母的首末位置
            int j = s[i] - 'a';  // 把字符映射到 0~25 的字母下标
            if (first[j] == -1) {  // 说明这是第一次遇到该字母
                first[j] = i;  // 记录首次出现位置
            }
            last[j] = i;  // 每次遇到都刷新末次出现位置
        }
        int ans = -1;  // 答案初值 -1，表示暂时没有找到合法子串
        for (int k = 0; k < 26; ++k) {  // 枚举左端点所属字母：自包含子串的左端一定是某个字母的首次出现
            int i = first[k];  // 候选子串的左端点
            if (i == -1) {  // 该字母根本没在 s 中出现过
                continue;  // 跳过这个字母
            }
            int mx = last[k];  // 区间内「最远末次出现位置」的初值
            for (int j = i; j < n; ++j) {  // 从 i 开始逐个尝试右端点
                int a = first[s[j] - 'a'];  // 右端点字母的首次出现位置
                int b = last[s[j] - 'a'];  // 右端点字母的末次出现位置
                if (a < i) {  // 该字母在 i 左边也出现过，说明区间左侧「漏」了它
                    break;  // 再往右扩展也不可能自包含，直接中断内层循环
                }
                mx = max(mx, b);  // 把当前字母的末位置并入，得到区间内所有字母的最远末位置
                if (mx == j && j - i + 1 < n) {  // mx == j 表示 [i, j] 刚好闭合；长度 < n 用来排除整串
                    ans = max(ans, j - i + 1);  // 用当前子串长度更新答案
                }
            }
        }
        return ans;  // 返回最长自包含子串的长度
    }
};