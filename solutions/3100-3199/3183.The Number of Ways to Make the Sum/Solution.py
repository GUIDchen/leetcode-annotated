# 题目：3183. 达到总和的方法数量（The Number of Ways to Make the Sum）
# 思路：完全背包求出「只用 1、2、6 凑出 j」的方案数，再加上恰好用一枚 4（f[n-4]）与恰好用两枚 4（f[n-8]）的方案数。
# 时间复杂度：O(n)，三层面值各扫一遍 dp；空间复杂度：O(n)，dp 数组长度为 n+1。
class Solution:  # LeetCode 约定的题解类
    def numberOfWays(self, n: int) -> int:  # n 是目标和，返回凑出 n 的方案数（对 1e9+7 取模）
        mod = 10**9 + 7  # 取模常量：答案可能非常大，必须边算边取模
        coins = [1, 2, 6]  # 可以无限取用的三种硬币面值
        f = [0] * (n + 1)  # f[j] 表示只用 1、2、6 凑出 j 的方案数（完全背包）
        f[0] = 1  # 边界：凑出 0 只有「一枚都不取」这一种方案
        for x in coins:  # 逐个面值做完全背包，保证组合与硬币顺序无关
            for j in range(x, n + 1):  # 容量正序遍历：j-x 已在本轮更新过，同一面值可以重复使用
                f[j] = (f[j] + f[j - x]) % mod  # 不取这一枚 / 再取一枚 x 两种来源相加并取模
        ans = f[n]  # 一枚 4 都不用的方案数
        if n >= 4:  # 容量至少为 4 才可能用一枚 4
            ans = (ans + f[n - 4]) % mod  # 恰好用一枚 4，剩下的 n-4 仍由 1、2、6 凑出
        if n >= 8:  # 容量至少为 8 才可能用两枚 4
            ans = (ans + f[n - 8]) % mod  # 恰好用两枚 4（题目只提供两枚），剩下的 n-8 由 1、2、6 凑出
        return ans  # 三类方案互不重叠，相加即为答案
