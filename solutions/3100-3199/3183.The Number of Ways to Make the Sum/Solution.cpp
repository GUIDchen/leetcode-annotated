// 题目：3183. 达到总和的方法数量（The Number of Ways to Make the Sum）
// 思路：先用完全背包算出「只用 1、2、6 凑出 j」的方案数 f[j]，再分别加上恰好用一枚 4（f[n-4]）和恰好用两枚 4（f[n-8]）的方案数。
// 时间复杂度：O(n)，两层背包循环总工作量约 3n；空间复杂度：O(n)，dp 数组长度为 n+1。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberOfWays(int n) {  // n：目标和；返回凑出 n 的方案数（对 1e9+7 取模）
        const int mod = 1e9 + 7;  // 取模常量：答案可能非常大，必须边算边取模
        int coins[3] = {1, 2, 6};  // 可以无限使用的三种硬币面值
        int f[n + 1];  // f[j]：只用 1、2、6 三种硬币凑出 j 的方案数（完全背包）
        memset(f, 0, sizeof(f));  // 全部清零，未计算的状态都视为 0 种方案
        f[0] = 1;  // 边界：凑出 0 只有「一枚都不取」这一种方案
        for (int x : coins) {  // 逐个面值做完全背包，保证硬币顺序无关（组合数而不是排列数）
            for (int j = x; j <= n; ++j) {  // 容量正序遍历：j-x 在本轮已经更新过，所以同一面值可以重复使用
                f[j] = (f[j] + f[j - x]) % mod;  // 不取这一枚 / 再取一枚 x 两种来源相加，并立即取模
            }  // 结束当前面值的容量枚举
        }  // 三种面值都处理完，此时 f 只统计 1、2、6 的组合
        int ans = f[n];  // 一枚 4 都不用的方案数
        if (n >= 4) {  // 容量至少为 4 才可能塞进一枚 4
            ans = (ans + f[n - 4]) % mod;  // 恰好用一枚 4，剩下的 n-4 仍由 1、2、6 凑出
        }  // 结束「用一枚 4」的累加
        if (n >= 8) {  // 容量至少为 8 才可能塞进两枚 4
            ans = (ans + f[n - 8]) % mod;  // 恰好用两枚 4（题目只提供两枚），剩下的 n-8 由 1、2、6 凑出
        }  // 结束「用两枚 4」的累加
        return ans;  // 不用 4、用一枚 4、用两枚 4 三类互不重叠，直接相加即为答案
    }  // 方法结束
};