# 3197. 包含所有 1 的最小矩形面积 II（Find the Minimum Area to Cover All Ones II）
# 核心思路：三个不重叠矩形的所有切分方式归结为「三横带」「三竖带」「先一刀再在剩余区域切一刀」三类；枚举切分线，用辅助函数求子区域内 1 的包围矩形面积。
# 复杂度：时间 O(m^3·n + m·n^3)，空间 O(1)（不计输入）

class Solution:  # 定义题解类
    def minimumSum(self, grid: List[List[int]]) -> int:  # 返回用三个不重叠矩形覆盖所有 1 的最小面积和
        def f(i1: int, j1: int, i2: int, j2: int) -> int:  # 辅助函数：返回子矩形 [i1..i2]×[j1..j2] 内所有 1 的包围矩形面积
            x1 = y1 = inf  # 最小行号、最小列号先置为无穷大
            x2 = y2 = -inf  # 最大行号、最大列号先置为负无穷
            for i in range(i1, i2 + 1):  # 枚举子矩形的每一行
                for j in range(j1, j2 + 1):  # 枚举子矩形的每一列
                    if grid[i][j] == 1:  # 只统计值为 1 的格子
                        x1 = min(x1, i)  # 更新最上方的 1 所在行
                        y1 = min(y1, j)  # 更新最左方的 1 所在列
                        x2 = max(x2, i)  # 更新最下方的 1 所在行
                        y2 = max(y2, j)  # 更新最右方的 1 所在列
            return (x2 - x1 + 1) * (y2 - y1 + 1)  # 包围矩形面积 = 高 × 宽

        m, n = len(grid), len(grid[0])  # 网格行数、列数
        ans = m * n  # 答案上界：整张网格当作一个矩形
        for i1 in range(m - 1):  # 切法一：三条横带——枚举第一条水平分界线
            for i2 in range(i1 + 1, m - 1):  # 枚举第二条水平分界线
                ans = min(  # 三条横带各自的包围面积之和，取最小
                    ans,  # 当前最优答案
                    f(0, 0, i1, n - 1)  # 上方横带
                    + f(i1 + 1, 0, i2, n - 1)  # 中间横带
                    + f(i2 + 1, 0, m - 1, n - 1),  # 下方横带
                )  # 结束本次三横带切法
        for j1 in range(n - 1):  # 切法二：三条竖带——枚举第一条竖直分界线
            for j2 in range(j1 + 1, n - 1):  # 枚举第二条竖直分界线
                ans = min(  # 三条竖带各自的包围面积之和，取最小
                    ans,  # 当前最优答案
                    f(0, 0, m - 1, j1)  # 左侧竖带
                    + f(0, j1 + 1, m - 1, j2)  # 中间竖带
                    + f(0, j2 + 1, m - 1, n - 1),  # 右侧竖带
                )  # 结束本次三竖带切法
        for i in range(m - 1):  # 切法三：切一刀分出整条一侧，再把另一侧切两刀——枚举行分界线
            for j in range(n - 1):  # 枚举列分界线
                ans = min(  # 情况 A：上方左右分割，下方整条
                    ans,  # 当前最优答案
                    f(0, 0, i, j) + f(0, j + 1, i, n - 1) + f(i + 1, 0, m - 1, n - 1),  # 左上 + 右上 + 下方整条
                )  # 结束情况 A
                ans = min(  # 情况 B：上方整条，下方左右分割
                    ans,  # 当前最优答案
                    f(0, 0, i, n - 1)  # 上方整条
                    + f(i + 1, 0, m - 1, j)  # 左下角矩形
                    + f(i + 1, j + 1, m - 1, n - 1),  # 右下角矩形
                )  # 结束情况 B

                ans = min(  # 情况 C：左侧上下分割，右侧整条
                    ans,  # 当前最优答案
                    f(0, 0, i, j) + f(i + 1, 0, m - 1, j) + f(0, j + 1, m - 1, n - 1),  # 左上 + 左下 + 右侧整条
                )  # 结束情况 C
                ans = min(  # 情况 D：左侧整条，右侧上下分割
                    ans,  # 当前最优答案
                    f(0, 0, m - 1, j)  # 左侧整条
                    + f(0, j + 1, i, n - 1)  # 右上角矩形
                    + f(i + 1, j + 1, m - 1, n - 1),  # 右下角矩形
                )  # 结束情况 D
        return ans  # 返回三个矩形的最小面积和
