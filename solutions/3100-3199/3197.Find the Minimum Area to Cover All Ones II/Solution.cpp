// 3197. 包含所有 1 的最小矩形面积 II（Find the Minimum Area to Cover All Ones II）
// 核心思路：三个不重叠矩形覆盖全部 1 的切分方式只有两类——平行切（三横带/三竖带）与先切一刀再在剩余区域切一刀；枚举切分线，用辅助函数求每个子区域中 1 的包围矩形面积。
// 复杂度：时间 O(m^3·n + m·n^3)，空间 O(1)（不计输入）

class Solution {  // 定义题解类
public:  // 公开接口
    int minimumSum(vector<vector<int>>& grid) {  // 返回用三个不重叠矩形覆盖所有 1 的最小面积和
        int m = grid.size();  // 网格行数
        int n = grid[0].size();  // 网格列数
        int ans = m * n;  // 答案上界：整张网格当作一个矩形
        int inf = INT_MAX / 4;  // 足够大的值，表示该区域没有 1，同时避免相加溢出
        auto f = [&](int i1, int j1, int i2, int j2) {  // 辅助函数：返回子矩形 [i1..i2]×[j1..j2] 内所有 1 的包围矩形面积
            int x1 = inf, y1 = inf;  // 最小行号、最小列号先置为无穷大
            int x2 = -inf, y2 = -inf;  // 最大行号、最大列号先置为负无穷
            for (int i = i1; i <= i2; i++) {  // 枚举子矩形的每一行
                for (int j = j1; j <= j2; j++) {  // 枚举子矩形的每一列
                    if (grid[i][j] == 1) {  // 只统计值为 1 的格子
                        x1 = min(x1, i);  // 更新最上方的 1 所在行
                        y1 = min(y1, j);  // 更新最左方的 1 所在列
                        x2 = max(x2, i);  // 更新最下方的 1 所在行
                        y2 = max(y2, j);  // 更新最右方的 1 所在列
                    }  // 结束 1 的判断
                }  // 结束列循环
            }  // 结束行循环
            return x1 > x2 || y1 > y2 ? inf : (x2 - x1 + 1) * (y2 - y1 + 1);  // 区域内无 1 时返回 inf，否则返回包围矩形面积 = 高 × 宽
        };  // 辅助函数定义结束

        for (int i1 = 0; i1 < m - 1; i1++) {  // 切法一：三条横带——枚举第一条水平分界线
            for (int i2 = i1 + 1; i2 < m - 1; i2++) {  // 枚举第二条水平分界线
                ans = min(ans, f(0, 0, i1, n - 1) + f(i1 + 1, 0, i2, n - 1) + f(i2 + 1, 0, m - 1, n - 1));  // 上、中、下三条横带各自包围面积之和，取最小
            }  // 结束第二条分界线枚举
        }  // 结束第一条分界线枚举

        for (int j1 = 0; j1 < n - 1; j1++) {  // 切法二：三条竖带——枚举第一条竖直分界线
            for (int j2 = j1 + 1; j2 < n - 1; j2++) {  // 枚举第二条竖直分界线
                ans = min(ans, f(0, 0, m - 1, j1) + f(0, j1 + 1, m - 1, j2) + f(0, j2 + 1, m - 1, n - 1));  // 左、中、右三条竖带各自包围面积之和，取最小
            }  // 结束第二条分界线枚举
        }  // 结束第一条分界线枚举

        for (int i = 0; i < m - 1; i++) {  // 切法三：切一刀分出整条一侧，再把另一侧切两刀——枚举行分界线
            for (int j = 0; j < n - 1; j++) {  // 枚举列分界线
                ans = min(ans, f(0, 0, i, j) + f(0, j + 1, i, n - 1) + f(i + 1, 0, m - 1, n - 1));  // 情况 A：上方左右分割，下方整条
                ans = min(ans, f(0, 0, i, n - 1) + f(i + 1, 0, m - 1, j) + f(i + 1, j + 1, m - 1, n - 1));  // 情况 B：上方整条，下方左右分割
                ans = min(ans, f(0, 0, i, j) + f(i + 1, 0, m - 1, j) + f(0, j + 1, m - 1, n - 1));  // 情况 C：左侧上下分割，右侧整条
                ans = min(ans, f(0, 0, m - 1, j) + f(0, j + 1, i, n - 1) + f(i + 1, j + 1, m - 1, n - 1));  // 情况 D：左侧整条，右侧上下分割
            }  // 结束列分界线枚举
        }  // 结束行分界线枚举

        return ans;  // 返回三个矩形的最小面积和
    }  // 方法结束
};  // 类定义结束