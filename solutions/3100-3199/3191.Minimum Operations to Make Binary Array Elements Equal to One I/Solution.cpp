// 题目：3191. 使二进制数组全部等于 1 的最少操作次数 I（Minimum Operations to Make Binary Array Elements Equal to One I）
// 思路：从左到右贪心，遇到 0 就必须以它作为左端点翻转「i、i+1、i+2」三位（否则 i 位再也没机会变 1）；右侧不足三位时无解。
// 时间复杂度：O(n)，每个位置最多被处理一次；空间复杂度：O(1)，只用了常数个变量并在原数组上就地翻转。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minOperations(vector<int>& nums) {  // nums：只含 0/1 的数组，允许原地修改，返回最少操作次数或 -1
        int ans = 0;  // 记录已经执行的翻转次数
        int n = nums.size();  // 数组长度，用于判断右侧是否还剩两位
        for (int i = 0; i < n; ++i) {  // 从左向右依次处理每个位置
            if (nums[i] == 0) {  // 当前位为 0，必须修好它
                if (i + 2 >= n) {  // 右侧不足两位，凑不出长度为 3 的翻转区间
                    return -1;  // 说明无论怎么操作都修不好，返回 -1
                }
                nums[i + 1] ^= 1;  // 异或 1 即按位取反：翻转 i+1 位，0 变 1、1 变 0
                nums[i + 2] ^= 1;  // 同理翻转 i+2 位，与上一步共同完成整段三位的翻转
                ++ans;  // 这一次操作让 nums[i] 变成 1，操作次数加一
            }
        }
        return ans;  // 走完整个数组都没失败，说明已全部为 1，返回操作次数
    }
};