// 题目：3138. 同位字符串连接的最小长度（Minimum Length of Anagram Concatenation）
// 思路：从小到大枚举块长 k（必须整除 n），检查每个长 k 的块字符频次是否相同；块频次乘以块数应等于整体频次。
// 时间复杂度：O(n*d)，d 为 n 的约数个数（每个约数都要扫全串）；空间复杂度：O(1)，只用 26 字母的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minAnagramLength(string s) {  // s：待拆分的原串，返回最小的块长度
        int n = s.size();  // 记录原串长度
        int cnt[26]{};  // 整体字符频次：cnt[c-'a'] 表示字符 c 在 s 中出现的次数
        for (char c : s) {  // 先扫一遍原串统计总频次
            cnt[c - 'a']++;  // 累加当前字符的计数
        }  // 总频次统计结束
        auto check = [&](int k) {  // 闭包：判断能否把 s 切成若干长 k 且互为字母异位词的块；按引用捕获外部变量
            for (int i = 0; i < n; i += k) {  // 按长度 k 从头逐块枚举每个块
                int cnt1[26]{};  // 当前块的字符频次
                for (int j = i; j < i + k; ++j) {  // 统计当前块内的每个字符
                    cnt1[s[j] - 'a']++;  // 累加当前字符的计数
                }  // 块内统计结束
                for (int j = 0; j < 26; ++j) {  // 逐字母比较块频次与整体频次
                    if (cnt1[j] * (n / k) != cnt[j]) {  // 若所有块同构，则块频次 × 块数必须等于整体频次
                        return false;  // 只要有一个字母不满足，该 k 就不可行
                    }  // 比较结束
                }  // 26 个字母遍历结束
            }  // 所有块检查完毕
            return true;  // 每个块都同构，返回可行
        };  // 闭包定义结束
        for (int i = 1;; ++i) {  // 从小到大枚举块长度；i=n 时必然成立，因此不需要写循环上界
            if (n % i == 0 && check(i)) {  // 块长必须整除 n，且切分后每个块都同构
                return i;  // 第一个可行的长度就是最小长度
            }  // 判断结束
        }  // 枚举结束
    }  // 方法结束
};  // 类定义结束