// 题目：3170. 删除星号以后字典序最小的字符串（Lexicographically Minimum String After Removing Stars）
// 思路：每个 '*' 都必须删除它左边的一个字符；要让剩余串字典序最小，应删除左边最小的字母，同一字母则删最靠右的那个。用 26 个栈按下标保存每种字母的位置，栈顶就是该字母最靠右的出现位置，标记 rem 后按原顺序拼接未被删除的字符。
// 时间复杂度：O(n)，每个星号最多扫 26 个字母栈，26 视为常数；空间复杂度：O(n)，rem 数组与各栈合计保存 n 个下标。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string clearStars(string s) {  // s 只含小写字母和 '*'，返回删除所有星号（以及被星号删掉的字符）后字典序最小的字符串
        stack<int> g[26];  // 26 个栈，g[c] 保存字母 c 出现过的下标，栈顶就是它最靠右的出现位置
        int n = s.length();  // 字符串长度，作为下面循环的上界
        vector<bool> rem(n);  // rem[i] 为 true 表示下标 i 的字符最终要删除，默认全部保留
        for (int i = 0; i < n; ++i) {  // 第一趟：从左到右扫描，处理每一个 '*'
            if (s[i] == '*') {  // 遇到星号：星号本身要删，还要连带删掉它左边一个最小的字母
                rem[i] = true;  // 先把星号自身标记为删除
                for (int j = 0; j < 26; ++j) {  // 从 'a' 到 'z' 找第一个还有剩余下标的字母，即当前可用的最小字母
                    if (!g[j].empty()) {  // 该字母还有没被删掉的出现位置
                        rem[g[j].top()] = true;  // 删除它最靠右的出现位置（同一字母删最右边的，剩余串字典序更小）
                        g[j].pop();  // 弹出这个下标，避免后续星号重复删除它
                        break;  // 每个星号只删一个字符，删完就跳出内层循环
                    }
                }
            } else {  // 否则是普通字母，先记录下来，等后面的星号可能删掉它
                g[s[i] - 'a'].push(i);  // 把下标压入对应字母的栈，栈顶始终保持最新即最靠右
            }
        }
        string ans;  // 结果字符串，用来收集保留下来的字符
        for (int i = 0; i < n; ++i) {  // 第二趟：按原顺序重新扫描
            if (!rem[i]) {  // 只保留没有被标记删除的字符
                ans.push_back(s[i]);  // 追加到结果末尾，保持原有相对顺序
            }
        }
        return ans;  // 返回删除后字典序最小的字符串
    }
};