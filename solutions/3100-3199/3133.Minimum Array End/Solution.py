# 题目：3133. 数组最后一个元素的最小值（Minimum Array End）
# 思路：数组按位与必须等于 x，故 x 为 1 的位不能动；把 n-1 的二进制位从低到高依次填进 x 的 0 位即可得到最小末元素。
# 时间复杂度：O(1)，固定 31 次循环；空间复杂度：O(1)，只用常数个变量（Python 整数不会溢出）。
class Solution:  # LeetCode 约定的题解类
    def minEnd(self, n: int, x: int) -> int:  # n 是数组长度，x 是所有元素按位与的结果
        n -= 1  # 末元素是第 n-1 个候选（从 0 开始编号），先把 n 转成 0 基
        ans = x  # 结果必须保留 x 的所有 1 位，所以从 x 开始累加
        for i in range(31):  # 只处理低 31 位，高位留给 n 剩下的部分
            if x >> i & 1 ^ 1:  # 取出 x 的第 i 位；等于 0 才允许自由填写
                ans |= (n & 1) << i  # 把 n 的最低位填到这一位，保证按位与仍为 x
                n >>= 1  # 用掉一位后 n 右移，接着填下一位
        ans |= n << 31  # 剩余高位整体平移到 31 位以上（Python 大整数无需强制类型转换）
        return ans  # 返回最小末元素
