// 题目：3133. 数组最后一个元素的最小值（Minimum Array End）
// 思路：整个数组按位与的结果必须等于 x，故每个元素的 x 为 1 的位都不能动；把 n-1 的二进制位从低到高填进 x 的 0 位，得到的数就是最小的末元素。
// 时间复杂度：O(1)，固定 31 次循环；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long minEnd(int n, int x) {  // n 是数组长度，x 是所有元素按位与的结果
        --n;  // 末元素是第 n-1 个候选（从 0 开始编号），先把 n 转成 0 基
        long long ans = x;  // 结果必须保留 x 的所有 1 位，所以从 x 开始累加
        for (int i = 0; i < 31; ++i) {  // 只处理低 31 位，高位留给 n 剩下的部分
            if (x >> i & 1 ^ 1) {  // 取出 x 的第 i 位；等于 0 才允许自由填写
                ans |= (n & 1) << i;  // 把 n 的最低位填到这一位，保证按位与仍为 x
                n >>= 1;  // 用掉一位后 n 右移，接着填下一位
            }  // 可填位分支结束
        }  // 低 31 位扫描结束
        ans |= (1LL * n) << 31;  // 剩余高位整体平移到 31 位以上（转 long long 防止溢出）
        return ans;  // 返回最小末元素
    }  // 方法体结束
};  // 类定义结束