// 题目：3163. 压缩字符串 III（String Compression III）
// 思路：用双指针切出每一段连续相同字符，再把段长拆成若干个不超过 9 的次数，逐个「次数+字符」写出。
// 时间复杂度：O(n)，每个字符只被读一次，输出长度也不超过 2n；空间复杂度：O(1)，只用几个下标（不计结果串）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string compressedString(string word) {  // word 是待压缩的字符串
        string ans;  // 结果串：形如「次数字符次数字符」的压缩结果
        int n = word.length();  // 先缓存串长，循环里会反复用到
        for (int i = 0; i < n;) {  // i 是当前这一组相同字符的起点，循环体内手动推进
            int j = i + 1;  // j 从 i 的下一位开始，向后寻找这一组的右边界
            while (j < n && word[j] == word[i]) {  // 只要没越界且字符仍相同，就说明还在同一组内
                ++j;  // 扩大当前组的右边界
            }  // 内层 while 结束，此时 j 指向下一组的第一个字符
            int k = j - i;  // k 是当前组内相同字符的个数
            while (k > 0) {  // 次数必须拆成若干个不超过 9 的段，所以要循环输出
                int x = min(9, k);  // 本题规则：一次最多写 9 个，取剩余次数与 9 的较小者
                ans.push_back('0' + x);  // 把次数转成数字字符（'0' + x 得到 '1'~'9'）写入结果
                ans.push_back(word[i]);  // 紧接着写入这一组对应的字符
                k -= x;  // 扣掉已经写出的次数，剩余部分继续拆
            }  // 当前组的次数拆分完毕
            i = j;  // i 跳到下一组的起点
        }  // 外层循环结束，所有组都处理完
        return ans;  // 返回压缩后的字符串
    }  // 方法结束
};  // 类定义结束