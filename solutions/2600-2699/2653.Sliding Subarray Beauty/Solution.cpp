// 题目：2653. 滑动子数组的美丽值（Sliding Subarray Beauty）
// 思路：维护长度 k 的滑动窗口与值域计数桶，每次在桶中从小到大找第 x 个数；负数不足 x 个时美丽值为 0。
// 时间复杂度：O(n × 50)，50 是值域常数，每个窗口扫一遍桶；空间复杂度：O(n + 101)，答案数组与计数桶。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的解题方法
    vector<int> getSubarrayBeauty(vector<int>& nums, int k, int x) {  // nums：原数组；k：窗口长度；x：第 x 小；返回每个窗口的美丽值
        int n = nums.size();  // 数组长度
        int cnt[101]{};  // 值域桶：下标 = 数值 + 50，覆盖 -50..50 共 101 个取值，初值全 0
        for (int i = 0; i < k; ++i) {  // 先统计第一个长度为 k 的窗口
            ++cnt[nums[i] + 50];  // 数值映射成桶下标后计数加一
        }
        vector<int> ans(n - k + 1);  // 长度为 k 的窗口共 n-k+1 个，ans[j] 是第 j 个窗口的美丽值
        // 在桶里从小到大找第 x 个元素：负数的桶下标是 0..49（对应 -50..-1），
        // 累计到某个值个数达到 x 它就是第 x 小；负数凑不够 x 个时按定义返回 0
        auto f = [&](int x) {  // 求第 x 小的负数
            int s = 0;  // 目前累计比当前值小的元素个数
            for (int i = 0; i < 50; ++i) {  // 只扫负数区间，下标 0..49
                s += cnt[i];  // 把当前值的计数累加进来
                if (s >= x) {  // 累计个数达到 x，说明第 x 小就落在当前桶
                    return i - 50;  // 桶下标减去 50 还原成真实数值
                }
            }
            return 0;  // 负数不足 x 个，美丽值为 0
        };
        ans[0] = f(x);  // 第一个窗口直接算
        for (int i = k, j = 1; i < n; ++i) {  // 窗口右移：i 是新进窗口的元素下标，j 是下一个待填的答案下标
            ++cnt[nums[i] + 50];  // 新元素进窗口
            --cnt[nums[i - k] + 50];  // 窗口最左侧元素移出
            ans[j++] = f(x);  // 重新求第 x 小，写入答案后 j 自增
        }
        return ans;  // 返回所有窗口的美丽值
    }
};  // 类定义结束