// 题目：2652. 倍数求和（Sum Multiples）
// 思路：枚举 1..n，凡是能被 3、5、7 中任意一个整除的数就累加；一个数同时满足多个条件也只加一次。
// 时间复杂度：O(n)，枚举一次；空间复杂度：O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的解题方法
    int sumOfMultiples(int n) {  // n：统计范围上界（1..n）
        int ans = 0;  // 累加满足条件的数之和
        for (int x = 1; x <= n; ++x) {  // 逐个枚举 1..n
            if (x % 3 == 0 || x % 5 == 0 || x % 7 == 0) {  // 能被 3、5、7 中任意一个整除
                ans += x;  // 是倍数就累加，同时被多个数整除也只加一次
            }
        }
        return ans;  // 返回所有倍数的和
    }
};  // 类定义结束