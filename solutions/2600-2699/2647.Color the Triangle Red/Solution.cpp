// 题目：2647. 把三角形染成红色（Color the Triangle Red）🔒
// 思路：找规律——第 1 行必涂，其余各行自底向上按「整行隔一个 / 只涂第 2 列 / 从第 3 列隔一个 / 只涂第 1 列」四行一循环。
// 时间复杂度：O(n²)，最多输出 O(n²) 个格子；空间复杂度：O(1)，不计答案数组。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的解题方法
    vector<vector<int>> colorRed(int n) {  // n：三角形边长；返回最初要涂红的三角形坐标列表
        vector<vector<int>> ans;  // 答案数组：存放所有需要预先涂红的坐标
        ans.push_back({1, 1});  // 第 1 行只有一个三角形，必须预先涂红
        // 从第 n 行自底向上走到第 2 行；k 是「每四行一循环」的相位，0..3 轮转
        // 观察图形可知四种相位分别是：整行隔一个涂、只涂第 2 列、从第 3 列隔一个涂、只涂第 1 列
        for (int i = n, k = 0; i > 1; --i, k = (k + 1) % 4) {  // 主循环
            if (k == 0) {  // 相位 0：该行奇数列全部涂红
                for (int j = 1; j < i << 1; j += 2) {  // 第 i 行共 2i-1 个三角形，j 从 1 开始步长 2，条件 j < 2i 保证取到 2i-1
                    ans.push_back({i, j});  // 记录坐标 (i, j)
                }
            } else if (k == 1) {  // 相位 1：该行只涂第 2 列
                ans.push_back({i, 2});  // 记录该行唯一的红格
            } else if (k == 2) {  // 相位 2：从第 3 列起隔一个涂一个
                for (int j = 3; j < i << 1; j += 2) {  // 跳过前两列，其余奇数列涂红
                    ans.push_back({i, j});  // 记录坐标 (i, j)
                }
            } else {  // 相位 3：该行只涂第 1 列
                ans.push_back({i, 1});  // 记录该行唯一的红格
            }
        }
        return ans;  // 返回所有需要预先涂红的坐标
    }
};  // 类定义结束