# 题目：2647. 把三角形染成红色（Color the Triangle Red）🔒
# 思路：找规律——第 1 行必涂，其余各行自底向上按「整行隔一个 / 只涂第 2 列 / 从第 3 列隔一个 / 只涂第 1 列」四行一循环。
# 时间复杂度：O(n²)，最多输出 O(n²) 个格子；空间复杂度：O(1)，不计答案数组。
class Solution:  # LeetCode 约定的题解类
    def colorRed(self, n: int) -> List[List[int]]:  # n：三角形边长；返回最初要涂红的坐标列表
        ans = [[1, 1]]  # 第 1 行只有一个三角形，必须预先涂红
        k = 0  # 相位 k：每四行循环一次，从最后一行开始为 0
        # 从第 n 行自底向上走到第 2 行（range 的 stop 为 1，不含 1）
        # 四种相位依次是：整行隔一个涂、只涂第 2 列、从第 3 列隔一个涂、只涂第 1 列
        for i in range(n, 1, -1):  # 主循环
            if k == 0:  # 相位 0：奇数列全部涂红
                for j in range(1, i << 1, 2):  # 第 i 行有 2i-1 个三角形，步长 2 正好取 1,3,...,2i-1
                    ans.append([i, j])  # 记录坐标 (i, j)
            elif k == 1:  # 相位 1：只涂第 2 列
                ans.append([i, 2])  # 记录该行唯一的红格
            elif k == 2:  # 相位 2：从第 3 列起隔一个涂一个
                for j in range(3, i << 1, 2):  # 起点 3、步长 2，正好取 3,5,...,2i-1
                    ans.append([i, j])  # 记录坐标 (i, j)
            else:  # 相位 3：只涂第 1 列
                ans.append([i, 1])  # 记录该行唯一的红格
            k = (k + 1) % 4  # 相位在 0..3 之间循环
        return ans  # 返回所有需要预先涂红的坐标
