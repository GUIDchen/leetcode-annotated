// 题目：2673. 使二叉树所有路径值相等的最小代价（Make Costs of Paths Equal in a Binary Tree）
// 思路：自底向上，把每个内部结点左右子树的路径和补齐到较大的那个，差值累加即最小代价；回填后继续与父结点比较。
// 时间复杂度：O(n)，每个结点只处理一次；空间复杂度：O(1)，就地修改 cost，只用常数个额外变量。
class Solution {  // 自底向上补齐左右子树的路径和
public:  // 对外接口
    int minIncrements(int n, vector<int>& cost) {  // n 是结点个数（完全二叉树按数组编号），cost 是各结点代价，会被就地修改
        int ans = 0;  // ans 累计需要增加的总代价
        for (int i = n >> 1; i > 0; --i) {  // 从编号最大的内部结点往上遍历：n >> 1 就是最后一个非叶结点
            int l = i << 1, r = i << 1 | 1;  // 左孩子编号 2i，右孩子编号 2i+1（用位移实现）
            ans += abs(cost[l - 1] - cost[r - 1]);  // 左右路径和之差必须被补上，这笔差值就是当前结点要花的代价
            cost[i - 1] += max(cost[l - 1], cost[r - 1]);  // 补齐后该子树路径和变成较大的那个，回填给父结点参与下一层比较
        }  // for 结束：根结点到这一步已经包含全部代价，不必再回填
        return ans;  // 返回累计的最小总代价
    }  // minIncrements 结束
};  // 类定义结束