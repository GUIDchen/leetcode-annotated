// 题目：2664. 巡逻的骑士（The Knight’s Tour）
// 核心思路：从给定起点做深度优先搜索，按 8 个骑士走法逐个尝试未访问格子并编号，一旦覆盖满 m*n 格就停止并返回棋盘。
// 时间复杂度：最坏 O(8^(m*n))，实际靠「找到即停」和棋盘规模剪枝；空间复杂度：O(m*n)，棋盘与递归栈深度。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<vector<int>> tourOfKnight(int m, int n, int r, int c) {  // m、n：棋盘行列数；r、c：骑士的起始位置
        vector<vector<int>> g(m, vector<int>(n, -1));  // 棋盘初始化为 -1，表示该格尚未被访问（未编号）
        g[r][c] = 0;  // 起点标记为第 0 步
        int dirs[9] = {-2, -1, 2, 1, -2, 1, 2, -1, -2};  // 8 个骑士走法的方向增量，按 (dx, dy) 交替存放，共 9 个元素方便成对读取
        bool ok = false;  // 标记是否已经找到一条覆盖全盘的路径
        function<void(int, int)> dfs = [&](int i, int j) {  // 递归 lambda：从 (i, j) 继续走，用引用捕获棋盘与 ok 标志
            if (g[i][j] == m * n - 1) {  // 走到编号 m*n-1 说明全部格子都已覆盖，巡逻完成
                ok = true;  // 置位成功标志，让上层递归逐层提前返回
                return;  // 立刻返回，不再尝试其它走法
            }  // if 判断结束
            for (int k = 0; k < 8; ++k) {  // 依次尝试 8 个骑士走法
                int x = i + dirs[k], y = j + dirs[k + 1];  // 算出下一个落点 (x, y)，dirs 中相邻两项组成一个方向
                if (x >= 0 && x < m && y >= 0 && y < n && g[x][y] == -1) {  // 落点必须在棋盘内，且该格尚未被访问过
                    g[x][y] = g[i][j] + 1;  // 给新落点编号为「当前步数 + 1」
                    dfs(x, y);  // 从新落点继续深度优先搜索
                    if (ok) {  // 若下游已经找到完整路径
                        return;  // 直接向上返回，保留当前棋盘上的编号结果
                    }  // if 判断结束
                    g[x][y] = -1;  // 回溯：撤销编号，把格子恢复成未访问，供其它走法复用
                }  // 候选落点判断结束
            }  // 8 个方向都尝试完毕
        };  // lambda 定义结束
        dfs(r, c);  // 从起点 r、c 开始搜索，深搜会原地改写棋盘 g
        return g;  // 返回填好巡逻编号的棋盘
    }  // 方法结束
};  // 类定义结束（文件末尾无换行，按原样保留）