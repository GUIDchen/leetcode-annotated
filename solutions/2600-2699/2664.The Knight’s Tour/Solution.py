# 题目：2664. 巡逻的骑士（The Knight’s Tour）
# 核心思路：从给定起点做深度优先搜索，按 8 个骑士走法尝试未访问格子并递增编号，覆盖满 m*n 格后立即停止，棋盘即答案。
# 时间复杂度：最坏 O(8^(m*n))，实际因「找到即停」远小于上界；空间复杂度：O(m*n)，棋盘与递归栈深度。
class Solution:  # LeetCode 约定的题解类
    def tourOfKnight(self, m: int, n: int, r: int, c: int) -> List[List[int]]:  # m、n：棋盘行列数；r、c：骑士起始位置，返回填好巡逻编号的棋盘
        def dfs(i: int, j: int):  # 内部深度优先搜索函数：处理当前落点 (i, j)
            nonlocal ok  # 声明 ok 来自外层作用域，递归里需要修改它
            if g[i][j] == m * n - 1:  # 走到编号 m*n-1 说明全部格子都已覆盖，巡逻完成
                ok = True  # 置位成功标志，让上层递归逐层提前返回
                return  # 立刻返回，不再尝试其它走法
            for a, b in pairwise((-2, -1, 2, 1, -2, 1, 2, -1, -2)):  # pairwise 把 9 个增量两两配对成 8 个方向 (a, b)
                x, y = i + a, j + b  # 算出下一个落点 (x, y)
                if 0 <= x < m and 0 <= y < n and g[x][y] == -1:  # 落点必须在棋盘内，且该格尚未被访问过（值为 -1）
                    g[x][y] = g[i][j] + 1  # 给新落点编号为「当前步数 + 1」
                    dfs(x, y)  # 从新落点继续深度优先搜索
                    if ok:  # 若下游已经找到完整路径
                        return  # 直接向上返回，保留当前棋盘上的编号结果
                    g[x][y] = -1  # 回溯：撤销编号，把格子恢复成未访问，供其它走法复用

        g = [[-1] * n for _ in range(m)]  # 棋盘初始化为 -1，表示该格尚未被访问（未编号）
        g[r][c] = 0  # 起点标记为第 0 步
        ok = False  # 初始时还没有找到完整路径
        dfs(r, c)  # 从起点开始搜索，深搜会原地改写棋盘 g
        return g  # 返回填好巡逻编号的棋盘
