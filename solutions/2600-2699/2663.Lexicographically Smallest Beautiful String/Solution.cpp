// 题目：2663. 字典序最小的美丽字符串（Lexicographically Smallest Beautiful String）
// 核心思路：从右往左找第一个能增大字符的位置，把它换成最小的可行更大字母，再把右侧每一位贪心填成不与前两个字符相同的最小字母；越靠左增大，字典序越小。
// 时间复杂度：O(n*k)，外层尝试次数与内层填字符都是常数级枚举；空间复杂度：O(n)，字符串本身（原地修改）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string smallestBeautifulString(string s, int k) {  // s：原始字符串；k：可用字母表大小（前 k 个小写字母），返回字典序更大的最小美丽串
        int n = s.size();  // 字符串长度
        for (int i = n - 1; i >= 0; --i) {  // 从右往左找第一个还能增大的位置 i
            int p = s[i] - 'a' + 1;  // p 是 s[i] 对应字母的下一个候选下标（'a' 记 0，所以 +1）
            for (int j = p; j < k; ++j) {  // 在字母表范围内，尝试把 s[i] 换成更大的字母 j
                char c = (char) ('a' + j);  // 候选字符 c
                if ((i > 0 && s[i - 1] == c) || (i > 1 && s[i - 2] == c)) {  // 美丽串要求无长度 ≥2 的回文：不能与前一个、前两个字符相同
                    continue;  // 冲突就换下一个更大的字母继续尝试
                }  // if 判断结束
                s[i] = c;  // 确定位置 i 的新字符（这就是该位能取到的最小可行值）
                for (int l = i + 1; l < n; ++l) {  // 位置 i 右侧的每一位都要重新填成尽可能小的字符
                    for (int m = 0; m < k; ++m) {  // 在字母表内从小到大枚举候选字符 m
                        c = (char) ('a' + m);  // 第 l 位的候选字符
                        if ((l > 0 && s[l - 1] == c) || (l > 1 && s[l - 2] == c)) {  // 同样检查是否与前一个、前两个字符构成回文冲突
                            continue;  // 冲突则继续尝试更大的字母
                        }  // if 判断结束
                        s[l] = c;  // 找到最小的可行字符，写到第 l 位
                        break;  // 当前位已填好，跳出内层枚举进入下一位
                    }  // 内层枚举循环结束
                }  // 右侧整段填字符的循环结束：后缀已按贪心填好
                return s;  // 第一个可行位置即答案（越靠左增大字典序越小），立即返回
            }  // 当前位枚举结束
        }  // 外层回退循环结束
        return "";  // 所有位置都无法增大，说明不存在更大的美丽串，返回空串
    }  // 方法结束
};  // 类定义结束（文件末尾无换行，按原样保留）