// 题目：276. 栅栏涂色（Paint Fence）
// 思路：按「第 i 个栅栏与前一个是否同色」拆成两个状态：f[i] = (f[i-1]+g[i-1])*(k-1) 表示不同色，g[i] = f[i-1] 表示同色，两者之和即答案。
// 时间复杂度：O(n)，一次线性递推；空间复杂度：O(n)，两个长度为 n 的 DP 数组（可优化为 O(1)）。
class Solution {  // LeetCode 约定的题解类
public:  // 对外提供 numWays 方法
    int numWays(int n, int k) {  // n：栅栏数量；k：颜色数量
        vector<int> f(n);  // f[i]：第 i 个栅栏与前一个颜色不同的方案数
        vector<int> g(n);  // g[i]：第 i 个栅栏与前一个颜色相同的方案数
        f[0] = k;  // 只有 1 个栅栏时任意颜色都行，共 k 种
        for (int i = 1; i < n; ++i) {  // 从第 2 个栅栏递推到第 n 个
            f[i] = (f[i - 1] + g[i - 1]) * (k - 1);  // 前一个栅栏的任意方案 × (k-1) 种与它不同的颜色
            g[i] = f[i - 1];  // 要同色，则前一个必须已与它的前一个不同色，方案数正好是 f[i-1]
        }
        return f[n - 1] + g[n - 1];  // 最后一个栅栏两种状态相加就是总方案数
    }
};