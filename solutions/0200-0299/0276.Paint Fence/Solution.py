# 题目：276. 栅栏涂色（Paint Fence）
# 思路：按「第 i 个栅栏与前一个是否同色」拆成两个状态：f[i] = (f[i-1]+g[i-1])*(k-1) 表示不同色，g[i] = f[i-1] 表示同色，两者之和即答案。
# 时间复杂度：O(n)，一次线性递推；空间复杂度：O(n)，两个长度为 n 的 DP 数组（可优化为 O(1)）。
class Solution:  # LeetCode 约定的题解类
    def numWays(self, n: int, k: int) -> int:  # n：栅栏数量；k：颜色数量
        f = [0] * n  # f[i]：第 i 个栅栏与前一个颜色不同的方案数，先全部置 0
        g = [0] * n  # g[i]：第 i 个栅栏与前一个颜色相同的方案数
        f[0] = k  # 只有 1 个栅栏时任意颜色都行，共 k 种
        for i in range(1, n):  # 从第 2 个栅栏递推到第 n 个
            f[i] = (f[i - 1] + g[i - 1]) * (k - 1)  # 前一个栅栏的任意方案 × (k-1) 种与它不同的颜色
            g[i] = f[i - 1]  # 同色方案数 = 前一个「与它前一个不同色」的方案数
        return f[-1] + g[-1]  # 最后一个栅栏两种状态相加即答案
