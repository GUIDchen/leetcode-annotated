// 题目：227. 基本计算器 II（Basic Calculator II）
// 思路：v 累积当前数字、sign 记录上一个运算符；遇到运算符或末尾时结算：乘除立刻与栈顶运算，加减只把带符号的值入栈，最后把栈内元素求和。
// 时间复杂度：O(n)，每个字符扫一遍、栈内元素再各出栈一次；空间复杂度：O(n)，栈最多存 O(n) 个加数。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int calculate(string s) {  // s：只含非负整数、空格与 + - * / 的合法表达式，返回其整数值
        int v = 0, n = s.size();  // v 累积当前正在读的数字；n 是长度，先缓存避免重复求 size
        char sign = '+';  // sign 记录上一个运算符，第一个数字默认按加号处理
        stack<int> stk;  // 栈里按符号保存各加数（乘除已在入栈前结算）
        for (int i = 0; i < n; ++i) {  // 从左到右逐字符扫描表达式
            char c = s[i];  // 取出当前字符，下面两处判断都复用它
            if (isdigit(c)) v = v * 10 + (c - '0');  // 是数字就把它累积进 v（十进制左移一位再加新数字）
            if (i == n - 1 || c == '+' || c == '-' || c == '*' || c == '/') {  // 若已到末尾，或当前字符是运算符，说明一个数字读完，需要立刻结算
                if (sign == '+')  // 情况一：上一个运算符是加号
                    stk.push(v);  // 直接把当前数字作为正加数入栈
                else if (sign == '-')  // 情况二：上一个运算符是减号
                    stk.push(-v);  // 把当前数字取负后入栈，减法转成加法
                else if (sign == '*') {  // 情况三：上一个运算符是乘号，优先级高需立即计算
                    int t = stk.top();  // 乘法的左操作数就是上一次留在栈顶的结果
                    stk.pop();  // 弹出这个左操作数，准备用乘积替换它
                    stk.push(t * v);  // 把乘积压回栈顶，后续仍可继续参与乘除
                } else {  // 否则上一个运算符是除号，同样立即计算
                    int t = stk.top();  // 除法的左操作数也在栈顶
                    stk.pop();  // 弹出左操作数
                    stk.push(t / v);  // 整数除法向零截断，把商压回栈顶
                }
                sign = c;  // 当前运算符成为下一段数字的符号
                v = 0;  // 数字归零，开始累积下一段
            }
        }
        int ans = 0;  // 栈内都是已结算完的带符号加数，求和得到最终结果
        while (!stk.empty()) {  // 逐个弹出栈顶，累加到 ans
            ans += stk.top();  // 取出栈顶加数
            stk.pop();  // 取出后弹出，避免死循环
        }
        return ans;  // 返回表达式的整数值
    }
};