# 题目：227. 基本计算器 II（Basic Calculator II）
# 思路：v 累积当前数字、sign 记录上一个运算符；遇到运算符或末尾时结算：乘除立刻与栈顶运算，加减只把带符号的值入栈，最后对栈求和。
# 时间复杂度：O(n)，每个字符扫一遍、栈内元素再各出栈一次；空间复杂度：O(n)，栈最多存 O(n) 个加数。
class Solution:  # LeetCode 约定的题解类
    def calculate(self, s: str) -> int:  # s 是只含非负整数、空格与 + - * / 的合法表达式，返回它的整数值
        v, n = 0, len(s)  # v 累积当前正在读的数字；n 是长度，先缓存避免重复求 len
        sign = '+'  # sign 记录上一个运算符，第一个数字默认按加号处理
        stk = []  # 用列表当栈，按符号保存各加数（乘除已在入栈前结算）
        for i, c in enumerate(s):  # 同时拿到下标 i 与字符 c，从左到右扫描表达式
            if c.isdigit():  # 是数字就把它累积进 v
                v = v * 10 + int(c)  # 十进制左移一位再加上新的一位数字
            if i == n - 1 or c in '+-*/':  # 已到末尾或当前字符是运算符，说明一个数字读完，需要立刻结算
                match sign:  # 按上一个运算符 sign 分四种情况处理
                    case '+':  # 情况一：上一个运算符是加号
                        stk.append(v)  # 当前数字作为正加数入栈
                    case '-':  # 情况二：上一个运算符是减号
                        stk.append(-v)  # 取负后入栈，减法转成加法
                    case '*':  # 情况三：上一个运算符是乘号，优先级高需立即计算
                        stk.append(stk.pop() * v)  # 弹出栈顶左操作数，与 v 相乘后把结果压回
                    case '/':  # 情况四：上一个运算符是除号，同样立即计算
                        stk.append(int(stk.pop() / v))  # 弹出栈顶左操作数，int(... / ...) 向零截断，商压回栈顶
                sign = c  # 当前运算符成为下一段数字的符号
                v = 0  # 数字归零，开始累积下一段
        return sum(stk)  # 栈内都是已结算完的带符号加数，求和即最终结果
