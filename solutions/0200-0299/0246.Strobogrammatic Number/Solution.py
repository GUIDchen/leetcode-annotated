# 题目：246. 中心对称数（Strobogrammatic Number）
# 思路：映射表 d 给出每个数字旋转 180° 后的数字（-1 表示非法），用双指针从两端向中间成对校验。
# 时间复杂度：O(n)，n 为数字串长度；空间复杂度：O(1)，映射表长度固定为 10。
class Solution:  # LeetCode 约定的题解类
    def isStrobogrammatic(self, num: str) -> bool:  # num：数字字符串，判断其旋转 180° 后是否与原串相同
        d = [0, 1, -1, -1, -1, -1, 9, -1, 8, 6]  # 下标是原数字，值是旋转后的数字；-1 表示旋转后不是合法数字（2、3、4、5、7）
        i, j = 0, len(num) - 1  # 初始化左右指针：i 指向最左端，j 指向最右端
        while i <= j:  # 两端向中间靠拢；i <= j 保证只比较一半，奇数长度时中间位会与自己配对
            a, b = int(num[i]), int(num[j])  # 取出左右两端字符对应的数字值
            if d[a] != b:  # 左端数字旋转后应等于右端数字，否则不满足中心对称
                return False  # 一旦有一对不匹配，直接判定为否
            i, j = i + 1, j - 1  # 两个指针同时向中间移动一位
        return True  # 全部配对成功，说明是中心对称数
