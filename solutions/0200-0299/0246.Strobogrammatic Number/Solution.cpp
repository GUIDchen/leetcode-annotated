// 题目：246. 中心对称数（Strobogrammatic Number）
// 思路：用映射表 d 记录每个数字旋转 180° 后得到的数字（不合法记 -1），再用双指针从两端向中间逐位配对校验。
// 时间复杂度：O(n)，n 为字符串长度；空间复杂度：O(1)，映射表长度固定为 10。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isStrobogrammatic(string num) {  // num：由数字组成的字符串，判断它旋转 180° 后是否与原串相同
        vector<int> d = {0, 1, -1, -1, -1, -1, 9, -1, 8, 6};  // 下标是原数字，值是旋转后的数字；-1 表示该数字旋转后不再是合法数字（2、3、4、5、7）
        for (int i = 0, j = num.size() - 1; i <= j; ++i, --j) {  // i 从左端、j 从右端同时向中间移动；i <= j 保证只处理一半，奇数长度时中间位会与自己配对
            int a = num[i] - '0', b = num[j] - '0';  // a、b 分别是左右两端位置上的数字值（字符减 '0' 得到 0~9）
            if (d[a] != b) {  // 左端数字旋转后必须等于右端数字，否则不满足中心对称
                return false;  // 出现一对不匹配，立即判定为假
            }  // 结束 if 判断
        }  // 结束双指针循环
        return true;  // 每一对都匹配，说明整体中心对称
    }  // 结束 isStrobogrammatic 方法
};  // 结束 Solution 类