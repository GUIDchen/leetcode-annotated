// 题目：289. 生命游戏（Game of Life）—— 按规则把细胞矩阵原地更新为下一代状态（活细胞邻居数决定生死）。
// 核心思路：用状态编码省去额外数组——2 表示“活→死”，-1 表示“死→活”；统计邻居时只看值是否 > 0，从而兼容旧状态。
// 时间复杂度：O(m·n)，每格检查 3×3 邻域；空间复杂度：O(1)，全部原地完成。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    void gameOfLife(vector<vector<int>>& board) {  // board：0 表示死、1 表示活，要求原地更新为下一代
        int m = board.size(), n = board[0].size();  // 行数、列数
        for (int i = 0; i < m; ++i) {  // 枚举每一行
            for (int j = 0; j < n; ++j) {  // 枚举每一列
                int live = -board[i][j];  // 先减去自己：下面的 3×3 邻域会把自己也数进去，当前为 1 时正好抵消
                for (int x = i - 1; x <= i + 1; ++x) {  // 邻域的行范围 i-1 .. i+1
                    for (int y = j - 1; y <= j + 1; ++y) {  // 邻域的列范围 j-1 .. j+1
                        if (x >= 0 && x < m && y >= 0 && y < n && board[x][y] > 0) {  // 不越界，且上一代是活细胞（>0 包含 1 和中间态 2）
                            ++live;  // 活邻居计数加一
                        }
                    }
                }
                if (board[i][j] == 1 && (live < 2 || live > 3)) {  // 规则 1、3：活细胞邻居少于 2 或多于 3 → 下一代死亡
                    board[i][j] = 2;  // 写成 2 表示“活→死”，值仍 > 0，后面统计邻居时仍算活
                }
                if (board[i][j] == 0 && live == 3) {  // 规则 4：死细胞恰好有 3 个活邻居 → 下一代复活
                    board[i][j] = -1;  // 写成 -1 表示“死→活”，值 <= 0，后面统计邻居时仍算死
                }
            }
        }
        for (int i = 0; i < m; ++i) {  // 第二遍扫描：把中间状态还原成真正的 0/1
            for (int j = 0; j < n; ++j) {  // 枚举每一列
                if (board[i][j] == 2) {  // 处于“活→死”中间态
                    board[i][j] = 0;  // 还原成死
                } else if (board[i][j] == -1) {  // 处于“死→活”中间态
                    board[i][j] = 1;  // 还原成活
                }
            }
        }
    }
};