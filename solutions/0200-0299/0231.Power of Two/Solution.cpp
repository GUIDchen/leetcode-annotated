// 题目：231. 2 的幂（Power of Two）
// 思路：2 的幂在二进制中只有一个 1；n & (n - 1) 会消掉最低位的那个 1，结果为 0 即说明只有一个 1，同时要排除 0 和负数。
// 时间复杂度：O(1)，只做常数次位运算；空间复杂度：O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isPowerOfTwo(int n) {  // n 是待判断的整数，返回它是否为 2 的幂
        return n > 0 && (n & (n - 1)) == 0;  // n > 0 先排除 0 与负数；n & (n - 1) 消掉最低位的 1，结果为 0 说明二进制里只有一个 1
    }  // 方法结束
};  // 题解类结束