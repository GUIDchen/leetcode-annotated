// 题目：283. 移动零（Move Zeroes）
// 思路：k 指向「下一个非零元素该放置的位置」，遍历数组，遇到非零就与 nums[k] 交换并把 k 后移，等于把所有非零数压到前面、零自然被挤到末尾。
// 时间复杂度：O(n) 一次遍历；空间复杂度：O(1)，原地交换。
void moveZeroes(int* nums, int numsSize) {  // 原地把非零元素前移，零移到末尾
    int k = 0;  // k：下一个非零元素应该放到的位置，也是已就位非零元素个数
    for (int i = 0; i < numsSize; ++i) {  // 顺序遍历每个元素
        if (nums[i] != 0) {  // 只处理非零元素
            int t = nums[i];  // 暂存当前非零元素，准备交换
            nums[i] = nums[k];  // 把 k 位置上的元素（可能是 0）挪到当前的空位
            nums[k++] = t;  // 非零元素落到前缀位置，k 自增指向下一个空位
        }
    }
}
