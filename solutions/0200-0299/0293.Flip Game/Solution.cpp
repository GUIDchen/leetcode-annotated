// 题目：293. 翻转游戏（Flip Game）—— 一次把相邻的两个 "++" 翻成 "--"，列出所有翻转后可能得到的状态，不能重复。
// 核心思路：从左到右枚举每对相邻字符，遇到 "++" 就原地翻转、收集当前串、再翻回原状，保证后续枚举基于原始状态。
// 时间复杂度：O(n²)，共 O(n) 个位置、每次生成答案要 O(n) 复制；空间复杂度：O(n²)，答案最多存 O(n) 个长度为 n 的串。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<string> generatePossibleNextMoves(string s) {  // s：只包含 '+' 和 '-' 的当前状态
        vector<string> ans;  // 收集所有可能的下一状态
        for (int i = 0; i < s.size() - 1; ++i) {  // 枚举每对相邻位置的下标 i 与 i+1（size() 为 size_t，此处只是照原代码保留）
            if (s[i] == '+' && s[i + 1] == '+') {  // 只有两个都是 '+' 才能翻转
                s[i] = s[i + 1] = '-';  // 原地把这一对翻成 '-'（连续赋值，两者同时置为 '-'）
                ans.emplace_back(s);  // 把翻转后的完整字符串拷进答案
                s[i] = s[i + 1] = '+';  // 再翻回 '+'，保证后面的枚举仍基于原始状态
            }
        }
        return ans;  // 返回全部可能的下一状态
    }
};