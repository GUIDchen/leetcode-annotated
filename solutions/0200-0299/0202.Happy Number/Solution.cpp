// 题目：202. 快乐数（Happy Number）
// 思路：不断把 n 替换成各位数字的平方和，用哈希集合记录出现过的数；变成 1 则是快乐数，出现重复值则陷入环、必不快乐。
// 时间复杂度：近似 O(log n)，每次变换都让数值快速缩小；空间复杂度：O(k)，k 为记录过的不同数值个数。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isHappy(int n) {  // 判断 n 是否为快乐数
        unordered_set<int> vis;  // 记录已经出现过的数，用来发现「陷入循环」
        while (n != 1 && !vis.count(n)) {  // 变成 1 就成功；出现重复值说明进入环，永远不会到 1
            vis.insert(n);  // 把当前值加入集合，供后续判重
            int x = 0;  // 本轮各位数字平方和的累加器
            for (; n; n /= 10) {  // 逐位拆解 n：循环体处理末位，步进部分去掉末位
                x += (n % 10) * (n % 10);  // 累加末位数字的平方
            }
            n = x;  // 一轮变换结束，把 n 更新为平方和
        }
        return n == 1;  // 等于 1 说明快乐；否则是因为出现重复值才退出循环
    }
};