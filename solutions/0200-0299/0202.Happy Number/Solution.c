// 题目：202. 快乐数（Happy Number）
// 思路：把「各位数字平方和」看作一条链上的转移，用快慢指针找环；相遇点为 1 则是快乐数，否则陷入非 1 循环。
// 时间复杂度：O(log n)，每轮变换让数值迅速变小；空间复杂度：O(1)，只用两个指针。
int getNext(int n) {  // 计算 n 各位数字的平方和，即快乐数变换的一步
    int res = 0;  // 平方和累加器
    while (n) {  // 逐位处理，n 变成 0 时结束
        res += (n % 10) * (n % 10);  // 取末位数字并累加它的平方
        n /= 10;  // 去掉已经处理过的末位
    }
    return res;  // 返回这一步变换的结果
}

bool isHappy(int n) {  // 判断 n 是否为快乐数（反复变换后能否收敛到 1）
    int slow = n;  // 慢指针：每轮只走一步
    int fast = getNext(n);  // 快指针：每轮走两步，初始就比慢指针多走一步
    while (slow != fast) {  // 两者未相遇，说明还没进入环，也没到达 1
        slow = getNext(slow);  // 慢指针走一步
        fast = getNext(getNext(fast));  // 快指针走两步
    }
    return fast == 1;  // 相遇点等于 1 说明链最终到 1，是快乐数；否则说明掉进了不含 1 的环
}