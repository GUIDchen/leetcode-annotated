// 题目：256. 粉刷房子（Paint House）
// 思路：动态规划。r/g/b 表示当前房子刷成红/绿/蓝时前 i 栋的最小总花费，每步用上一轮另外两色的较小值转移。
// 时间复杂度：O(n)，n 为房子数；空间复杂度：O(1)，只用三个滚动变量。

class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minCost(vector<vector<int>>& costs) {  // costs[i] = {红, 绿, 蓝} 三种颜色各自的粉刷花费
        int r = 0, g = 0, b = 0;  // 第一栋房子之前，三种颜色的累计花费都是 0
        for (auto& cost : costs) {  // 逐栋房子做状态转移
            int _r = r, _g = g, _b = b;  // 先备份上一轮的三个状态，避免本轮更新互相污染
            r = min(_g, _b) + cost[0];  // 本栋刷红：上一栋只能是绿或蓝，取较小值再加上红色花费
            g = min(_r, _b) + cost[1];  // 本栋刷绿：上一栋只能是红或蓝
            b = min(_r, _g) + cost[2];  // 本栋刷蓝：上一栋只能是红或绿
        }
        return min(r, min(g, b));  // 取最后一栋三种刷法中的最小总花费
    }  // 结束方法
};  // 结束类