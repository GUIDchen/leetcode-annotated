// 题目：224. 基本计算器（Basic Calculator）
// 思路：一次扫描，ans 累加当前层的值、sign 记录下一个数的符号；遇左括号把外层 ans 与 sign 压栈并清零，遇右括号弹栈合成 ans = ans * 外层sign + 外层ans。
// 时间复杂度：O(n)，每个字符最多被扫一遍；空间复杂度：O(n)，栈深等于括号嵌套层数。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int calculate(string s) {  // s：只含数字、空格、+ - ( ) 的合法表达式，返回其整数值
        stack<int> stk;  // 栈里成对保存外层现场：先压外层 ans，再压外层的符号 sign
        int ans = 0, sign = 1;  // ans 当前累加结果；sign 是下一个数字要乘的符号，默认正号
        int n = s.size();  // 先缓存长度，循环里不必反复求 size
        for (int i = 0; i < n; ++i) {  // 从左到右逐字符扫描整个表达式
            if (isdigit(s[i])) {  // 遇到数字，就一次性把这一整段多位数读出来
                int x = 0;  // x 用来累积这个多位数
                int j = i;  // j 从 i 出发向右寻找连续的数字
                while (j < n && isdigit(s[j])) {  // 数字还没结束就继续读下一位
                    x = x * 10 + (s[j] - '0');  // 十进制左移一位再加上新的一位数字
                    ++j;  // 指针后移，准备读下一个字符
                }
                ans += sign * x;  // 把整个数按当前符号并入结果
                i = j - 1;  // 循环体还会 ++i，这里退一格让 i 正好停在数字的最后一位
            } else if (s[i] == '+') {  // 加号：后面的数字取正
                sign = 1;  // 正号作用于下一个数字
            } else if (s[i] == '-') {  // 减号：后面的数字取负
                sign = -1;  // 负号作用于下一个数字
            } else if (s[i] == '(') {  // 进入左括号：先把外层现场压栈保存
                stk.push(ans);  // 保存括号外已经算出的累加值
                stk.push(sign);  // 保存整个括号块前面的符号
                ans = 0;  // 括号内从头开始独立累加
                sign = 1;  // 括号内第一个数字默认取正
            } else if (s[i] == ')') {  // 右括号：括号块算完，弹栈恢复外层现场并合并
                ans *= stk.top();  // 括号整体的值先乘上它前面的符号
                stk.pop();  // 弹出刚用掉的外层符号
                ans += stk.top();  // 再加上括号外原本的累加值
                stk.pop();  // 弹出外层累加值，栈回到进入括号前的状态
            }
        }
        return ans;  // 扫描结束时 ans 就是整个表达式的值
    }
};