// 题目：205. 同构字符串（Isomorphic Strings）
// 思路：用两个数组分别记录 s→t 与 t→s 的字符映射，逐位检查同一位置上的两个字符是否都已建立且一致的映射。
// 时间复杂度：O(n)，一次线性扫描；空间复杂度：O(1)，字符集固定为 256。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isIsomorphic(string s, string t) {  // 判断 s 与 t 是否同构：s 中每个字符与 t 中同位置字符必须一一对应
        int d1[256]{};  // s 的字符映射到 t 的字符，元素为 0 表示还没建立映射
        int d2[256]{};  // 反向映射：t 的字符映射到 s 的字符，用来保证「不同字符不能映射到同一字符」
        int n = s.size();  // 两串长度相同，取 s 的长度即可
        for (int i = 0; i < n; ++i) {  // 逐位比较
            char a = s[i], b = t[i];  // 取同一位置上的两个字符
            if (d1[a] != d2[b]) {  // 若 a 早已映射到别的字符，或 b 早已被别的字符占用，说明映射关系冲突
                return false;  // 立即判定不同构
            }
            d1[a] = d2[b] = i + 1;  // 双向同时记录 a<->b；用 i+1 而不是 i，是为了和数组默认值 0（表示未映射）区分开
        }
        return true;  // 全部位置都没有冲突，说明两串同构
    }
};