// 题目：263. 丑数（Ugly Number）
// 思路：把 n 里的因子 2、3、5 全部除干净，若最后剩下 1 就是丑数，否则含有其他质因子。
// 时间复杂度：O(log n)，每除一次至少缩小一倍；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的解法接口
    bool isUgly(int n) {  // n 为待判断的整数，返回它是否为丑数
        if (n < 1) return false;  // 非正数按题目约定不是丑数，直接返回
        while (n % 2 == 0) {  // 反复除掉因子 2
            n /= 2;  // 每除一次就消掉一个因子 2
        }  // 因子 2 已经除尽
        while (n % 3 == 0) {  // 反复除掉因子 3
            n /= 3;  // 每除一次就消掉一个因子 3
        }  // 因子 3 已经除尽
        while (n % 5 == 0) {  // 反复除掉因子 5
            n /= 5;  // 每除一次就消掉一个因子 5
        }  // 因子 5 已经除尽
        return n == 1;  // 只剩 1 说明质因子只由 2、3、5 组成
    }  // isUgly 方法结束
};  // 类定义结束