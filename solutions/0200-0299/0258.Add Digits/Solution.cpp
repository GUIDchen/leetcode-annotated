// 题目：258. 各位相加（Add Digits）
// 思路：数根公式。反复各位相加的最终结果就是 n mod 9（余 0 时取 9），即 (n-1) % 9 + 1，可一步算出。
// 时间复杂度：O(1)；空间复杂度：O(1)。

class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int addDigits(int num) {  // num：非负整数输入
        return (num - 1) % 9 + 1;  // 数根公式：先减 1 再对 9 取余再加 1，可把 9 的倍数正确映射为 9 而不是 0
    }  // 结束方法
};  // 结束类