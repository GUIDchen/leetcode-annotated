// 题目：229. 多数元素 II（Majority Element II）
// 思路：Boyer-Moore 投票法扩展为两个候选人：第一轮抵消求出可能的 m1、m2，第二轮再统计实际次数，验证是否严格超过 n/3。
// 时间复杂度：O(n)，第一轮扫描加两轮计数共线性；空间复杂度：O(1)，只用常数个变量（不计返回值）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> majorityElement(vector<int>& nums) {  // nums 是整数数组，返回所有出现次数严格大于 len/3 的元素
        int n1 = 0, n2 = 0;  // n1、n2 分别是两个候选人的票数（计数）
        int m1 = 0, m2 = 1;  // m1、m2 是两个候选人；初值取不同的 0 和 1，避免一开始就被误配
        for (int m : nums) {  // 第一轮：遍历每个元素进行抵消投票
            if (m == m1)  // 与候选人 1 相同，就给它加一票
                ++n1;  // 候选人 1 票数加一
            else if (m == m2)  // 与候选人 2 相同，就给它加一票
                ++n2;  // 候选人 2 票数加一
            else if (n1 == 0) {  // 候选人 1 票数为 0，位置上没人，就把它换成当前元素
                m1 = m;  // 当前元素成为新的候选人 1
                ++n1;  // 新候选人 1 获得第一票
            } else if (n2 == 0) {  // 候选人 2 票数为 0，同理替换成当前元素
                m2 = m;  // 当前元素成为新的候选人 2
                ++n2;  // 新候选人 2 获得第一票
            } else {  // 两个候选人都有票且当前元素与它们都不同，三方抵消
                --n1;  // 候选人 1 少一票
                --n2;  // 候选人 2 少一票
            }
        }
        // 注意：投票法只会给出「可能的」多数元素，必须再验证一遍才严谨
        vector<int> ans;  // 第一轮只筛出候选，还需第二轮统计真实出现次数
        if (count(nums.begin(), nums.end(), m1) > nums.size() / 3) ans.push_back(m1);  // 统计 m1 出现次数，严格大于 n/3 才收进答案
        if (count(nums.begin(), nums.end(), m2) > nums.size() / 3) ans.push_back(m2);  // 统计 m2 出现次数，同样严格大于 n/3 才收进答案
        return ans;  // 返回所有满足条件的元素
    }
};