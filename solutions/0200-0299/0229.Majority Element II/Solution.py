# 题目：229. 多数元素 II（Majority Element II）
# 思路：Boyer-Moore 投票法扩展为两个候选人：第一轮抵消求出可能的 m1、m2，第二轮用 count 统计真实次数，验证是否严格超过 n/3。
# 时间复杂度：O(n)，第一轮扫描加两次 count 共线性；空间复杂度：O(1)，只用常数个变量（不计返回值）。
class Solution:  # LeetCode 约定的题解类
    def majorityElement(self, nums: List[int]) -> List[int]:  # nums 是整数数组，返回所有出现次数严格大于 len/3 的元素
        n1 = n2 = 0  # n1、n2 分别是两个候选人的票数（计数）
        m1, m2 = 0, 1  # m1、m2 是两个候选人；初值取不同的 0 和 1，避免一开始就被误配
        for m in nums:  # 第一轮：遍历每个元素进行抵消投票
            if m == m1:  # 与候选人 1 相同，就给它加一票
                n1 += 1  # 候选人 1 票数加一
            elif m == m2:  # 与候选人 2 相同，就给它加一票
                n2 += 1  # 候选人 2 票数加一
            elif n1 == 0:  # 候选人 1 票数为 0，位置上没人，就把它换成当前元素
                m1, n1 = m, 1  # 当前元素成为新的候选人 1，票数置为 1
            elif n2 == 0:  # 候选人 2 票数为 0，同理替换成当前元素
                m2, n2 = m, 1  # 当前元素成为新的候选人 2，票数置为 1
            else:  # 两个候选人都有票且当前元素与它们都不同，三方抵消
                n1, n2 = n1 - 1, n2 - 1  # 两个候选人的票数同时减一
        # 投票法只给出候选人，必须用 count 复核，否则可能返回不存在的多数元素
        return [m for m in [m1, m2] if nums.count(m) > len(nums) // 3]  # 第二轮验证：只保留真实出现次数严格大于 len/3 的候选
