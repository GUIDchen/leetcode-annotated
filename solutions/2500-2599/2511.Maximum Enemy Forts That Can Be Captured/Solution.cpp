// 题目：2511. 最多可以摧毁的敌人城堡数目（Maximum Enemy Forts That Can Be Captured）
// 思路：只有「我方城堡 1 与敌方城堡 -1 之间全为空城 0」的一段才能被占领；扫描所有相邻的非零位置，取中间 0 的个数的最大值。
// 时间复杂度：O(n)，i 每轮都跳到下一个非零位置，整体只前进不后退；空间复杂度：O(1)，只用了若干整型变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int captureForts(vector<int>& forts) {  // forts：每格状态，1 为我方城堡、-1 为敌方城堡、0 为空城
        int n = forts.size();  // 数组长度，先取出来避免重复调用
        int ans = 0, i = 0;  // ans：最多能摧毁的敌人城堡数；i：当前检查的位置
        while (i < n) {  // 从左到右扫描每个位置
            int j = i + 1;  // j 用来寻找 i 之后第一个非零位置
            if (forts[i] != 0) {  // 只有从城堡（非空城）出发才可能形成一段可占领的空城
                while (j < n && forts[j] == 0) {  // 跳过这一段中间的空城
                    ++j;  // 继续向右找下一个城堡
                }
                if (j < n && forts[i] + forts[j] == 0) {  // 右端存在城堡且两端分属我方(1)与敌方(-1)，相加恰为 0
                    ans = max(ans, j - i - 1);  // 中间的 j-i-1 个空城可以被占领，更新最大值
                }
            }
            i = j;  // 直接跳到下一个非零位置；若当前是空城则只前进一格，不会漏解
        }
        return ans;  // 返回最多可摧毁的敌人城堡数目
    }
};