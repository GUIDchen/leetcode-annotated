// 题目：2536. 子矩阵元素加 1（Increment Submatrices by One）
// 思路：二维差分。每个子矩阵只在四个角上做 +1/-1 标记，最后做一次二维前缀和还原真实覆盖次数。
// 时间复杂度：O(n^2 + q)，q 为查询数；空间复杂度：O(n^2)，返回矩阵本身占用。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<vector<int>> rangeAddQueries(int n, vector<vector<int>>& queries) {  // n 为矩阵边长，queries 每项是 {x1, y1, x2, y2}，返回所有操作后的矩阵
        vector<vector<int>> mat(n, vector<int>(n));  // n×n 全 0 矩阵，先当作二维差分数组使用；每行独立构造，避免共享同一份数据
        for (auto& q : queries) {  // 遍历每条子矩阵加 1 的查询
            int x1 = q[0], y1 = q[1], x2 = q[2], y2 = q[3];  // 拆出左上角与右下角坐标
            mat[x1][y1]++;  // 差分：左上角 +1，表示从这里开始每个格子都多 1
            if (x2 + 1 < n) {  // 若下边界 x2+1 没有越界
                mat[x2 + 1][y1]--;  // 下方一行的同一列 -1，抵消离开子矩阵后的那份贡献
            }  // if 结束
            if (y2 + 1 < n) {  // 若右边界 y2+1 没有越界
                mat[x1][y2 + 1]--;  // 右侧一行的同一列 -1
            }  // if 结束
            if (x2 + 1 < n && y2 + 1 < n) {  // 右下方再 +1，把被多减掉的那一块补回来（二维差分容斥）
                mat[x2 + 1][y2 + 1]++;  // if 结束
            }  // 单条查询标记完毕
        }  // 所有查询标记完毕
        for (int i = 0; i < n; ++i) {  // 逐行做二维前缀和，还原每个格子被覆盖的次数
            for (int j = 0; j < n; ++j) {  // 逐列处理
                if (i > 0) {  // 上方还有行时
                    mat[i][j] += mat[i - 1][j];  // 累加上方格子的值，把上方差分贡献向下传递
                }  // if 结束
                if (j > 0) {  // 左侧还有列时
                    mat[i][j] += mat[i][j - 1];  // 累加左方格子的值，把左侧差分贡献向右传递
                }  // if 结束
                if (i > 0 && j > 0) {  // 上方和左侧都存在时
                    mat[i][j] -= mat[i - 1][j - 1];  // 减去左上角，它被加了两次，需要容斥掉一次
                }  // if 结束
            }  // 列循环结束
        }  // 行循环结束
        return mat;  // 返回前缀和还原后的结果矩阵
    }  // 方法结束
};  // 类定义结束