// 题目：2531. 使字符串中不同字符的数目相等（Make Number of Distinct Characters Equal）
// 核心思路：统计两串各字母频次与不同字符数，枚举交换的一对字母 (i, j)，用「失去谁、得到谁」的增量公式判断交换后两串不同字符数能否相等。
// 时间复杂度：O(n + m + 26²)，字母对枚举只有常数级；空间复杂度：O(1)，两个长度 26 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isItPossible(string word1, string word2) {  // 判断能否只交换 word1、word2 之间的一对字符，使两串的不同字符数目相等
        int cnt1[26]{};  // word1 中各小写字母出现次数，花括号值初始化保证全为 0
        int cnt2[26]{};  // word2 中各小写字母出现次数，同样初始化为 0
        int x = 0, y = 0;  // x、y 分别是 word1、word2 当前的不同字符数
        for (char& c : word1) {  // 遍历 word1 的每个字符
            if (++cnt1[c - 'a'] == 1) {  // 频次加一；刚变成 1 说明这个字母是第一次出现
                ++x;  // 不同字符数加一
            }  // 频次大于 1 说明该字母早已统计过
        }  // word1 统计完毕
        for (char& c : word2) {  // 遍历 word2 的每个字符
            if (++cnt2[c - 'a'] == 1) {  // 频次加一；刚变成 1 说明是新出现的字母
                ++y;  // 不同字符数加一
            }  // 已统计过的字母不重复计数
        }  // word2 统计完毕
        for (int i = 0; i < 26; ++i) {  // 枚举从 word1 中拿去交换的字母 i
            for (int j = 0; j < 26; ++j) {  // 枚举从 word2 中拿去交换的字母 j
                if (cnt1[i] > 0 && cnt2[j] > 0) {  // 两边都必须真的含有这两个字母才能交换
                    if (i == j) {  // 交换的是同一个字母，等于什么都没换
                        if (x == y) {  // 原本不同字符数就相等，无需改变
                            return true;  // 直接判定可行
                        }  // 不相等则这一对无效
                    } else {  // 交换的是不同字母，需要重新推算两边的不同字符数
                        int a = x - (cnt1[i] == 1 ? 1 : 0) + (cnt1[j] == 0 ? 1 : 0);  // word1 失去 i（个数归零才减一）、得到 j（原本没有才加一）
                        int b = y - (cnt2[j] == 1 ? 1 : 0) + (cnt2[i] == 0 ? 1 : 0);  // word2 失去 j、得到 i，用同样的增量规则计算
                        if (a == b) {  // 交换后两边不同字符数目相等
                            return true;  // 找到一种可行交换
                        }  // 不相等继续尝试下一对
                    }  // 分支结束
                }  // 该字母对不可交换，跳过
            }  // 枚举下一个 j
        }  // 枚举下一个 i
        return false;  // 所有字母对都试过仍无解
    }  // 方法结束
};  // 类定义结束