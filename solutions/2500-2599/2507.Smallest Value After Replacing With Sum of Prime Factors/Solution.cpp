// 题目：2507. 使用质因数之和替换后可以取到的最小值（Smallest Value After Replacing With Sum of Prime Factors）
// 思路：反复把 n 替换成它的质因数之和（用试除法分解质因数），直到某轮结果与当前值相同，这个不动点就是最小值。
// 时间复杂度：每轮 O(sqrt(n)) 试除，轮数很少（对数级）；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int smallestValue(int n) {  // n：初始整数，返回反复替换后能得到的最小值
        while (1) {  // 不断迭代，直到某轮替换结果与当前值相同（到达不动点）
            int t = n, s = 0;  // t 保存本轮的原值用于比较；s 累计本轮质因数之和
            for (int i = 2; i <= n / i; ++i) {  // 只需试除到 sqrt(当前 n)；写成 i <= n / i 可避免乘法溢出
                while (n % i == 0) {  // 只要 i 还能整除 n，就说明 i 是 n 的一个质因数
                    s += i;  // 把这个质因数累加进质因数之和
                    n /= i;  // 同时从 n 中除掉这个质因数
                }
            }
            if (n > 1) s += n;  // 试除结束后若 n > 1，剩下的大于 1 的因子本身是质数，直接计入
            if (s == t) return s;  // 质因数之和等于原值，说明已到不动点，此即最小值
            n = s;  // 否则用质因数之和替换 n，进入下一轮
        }
    }
};