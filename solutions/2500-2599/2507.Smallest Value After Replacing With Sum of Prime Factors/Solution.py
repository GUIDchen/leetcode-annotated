# 题目：2507. 使用质因数之和替换后可以取到的最小值（Smallest Value After Replacing With Sum of Prime Factors）
# 思路：反复把 n 替换成它的质因数之和（试除法分解质因数），直到结果与当前值相同，这个不动点就是最小值。
# 时间复杂度：每轮 O(sqrt(n)) 试除，轮数很少（对数级）；空间复杂度：O(1)，只用常数个变量。
class Solution:  # LeetCode 约定的题解类
    def smallestValue(self, n: int) -> int:  # n 是初始整数，返回反复替换后能得到的最小值
        while 1:  # 死循环：靠内部的 return 结束，表示已经到达不动点
            t, s, i = n, 0, 2  # t 保存本轮原值用于比较；s 累计质因数之和；i 从 2 开始试除
            while i <= n // i:  # 只需试除到 sqrt(当前 n)，用整除避免浮点误差
                while n % i == 0:  # i 能整除 n 时说明 i 是质因数（更小的质因数已被提前除掉）
                    n //= i  # 从 n 中去掉这个质因数
                    s += i  # 把这个质因数累加进质因数之和
                i += 1  # 换下一个可能的质因数继续试
            if n > 1:  # 试除后剩下的大于 1 的因子必定是质数
                s += n  # 把它也计入质因数之和
            if s == t:  # 质因数之和等于原值，说明已经到达不动点
                return t  # 直接返回这个最小值
            n = s  # 否则用质因数之和替换 n，进入下一轮
