// 题目：2506. 统计相似字符串对的数目（Count Pairs Of Similar Strings）
// 思路：把每个字符串压成 26 位「字母是否出现过」的位掩码，掩码相同的两个字符串即相似；用哈希表累计同掩码的历史出现次数，逐对累加。
// 时间复杂度：O(L)，L 为所有字符串字符总数；空间复杂度：O(n)，哈希表最多保存 n 个不同的掩码。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int similarPairs(vector<string>& words) {  // words：输入的字符串数组，返回相似字符串对的数目
        int ans = 0;  // 答案计数器：累计满足「相似」的下标对个数
        unordered_map<int, int> cnt;  // 哈希表：键是字符集合的位掩码，值是该掩码此前出现的次数
        for (const auto& s : words) {  // 按顺序枚举每个字符串，只读引用避免拷贝
            int x = 0;  // 26 位掩码：第 i 位为 1 表示字母 ('a' + i) 在该串中出现过
            for (auto& c : s) {  // 遍历当前字符串的每一个字符
                x |= 1 << (c - 'a');  // 把对应字母的位置 1；同一字母重复出现不会改变掩码
            }
            ans += cnt[x]++;  // 之前每个同掩码字符串都与当前串相似，故先累加旧次数，再把计数加一
        }
        return ans;  // 返回相似字符串对的总数
    }
};
