// 题目：2571. 将整数减少到零需要的最少操作数（Minimum Operations to Reduce an Integer to 0）
// 思路：从低位到高位扫描二进制，统计连续 1 的长度；长度 1 用一次减法消掉，长度 ≥2 用一次加法进位、再整体消掉，共两次操作。
// 时间复杂度：O(log n)，只扫描 n 的二进制位数；空间复杂度：O(1)，只用了常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minOperations(int n) {  // n：输入的整数，返回把它减少到 0 的最少操作次数
        int ans = 0, cnt = 0;  // ans 累计操作次数；cnt 记录当前这段连续 1 的长度
        for (; n > 0; n >>= 1) {  // 从最低位开始逐位右移，直到 n 变成 0
            if ((n & 1) == 1) {  // 当前最低位是 1
                ++cnt;  // 连续 1 的段长加一
            } else if (cnt > 0) {  // 当前位是 0 且前面有连续 1，说明一段 1 到此处结束
                ++ans;  // 消掉这一段至少需要一次操作
                cnt = cnt == 1 ? 0 : 1;  // 段长为 1 直接减掉；段长 ≥2 视为向高位进位，留下一个 1 继续处理
            }
        }
        ans += cnt == 1 ? 1 : 0;  // 最高位还残留一段长度为 1 的连续 1，再花 1 步减掉
        ans += cnt > 1 ? 2 : 0;  // 最高位还残留一段长度 ≥2 的连续 1，先加再减，共 2 步
        return ans;  // 返回累计的最少操作次数
    }
};