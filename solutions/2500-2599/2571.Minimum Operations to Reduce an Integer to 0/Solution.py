# 题目：2571. 将整数减少到零需要的最少操作数（Minimum Operations to Reduce an Integer to 0）
# 思路：逐位右移扫描二进制，统计连续 1 的段长；段长 1 用一次减法，段长 ≥2 用一次加法进位后再整体消去，共两次操作。
# 时间复杂度：O(log n)，只扫描 n 的二进制位数；空间复杂度：O(1)，只用了常数个变量。
class Solution:  # LeetCode 约定的题解类
    def minOperations(self, n: int) -> int:  # n 是输入整数，返回把它减少到 0 的最少操作次数
        ans = cnt = 0  # ans 累计操作次数；cnt 记录当前这段连续 1 的长度
        while n:  # 只要 n 还不为 0 就继续逐位处理
            if n & 1:  # 当前最低位是 1
                cnt += 1  # 连续 1 的段长加一
            elif cnt:  # 当前位是 0 且前面有连续 1，说明一段 1 到此处结束
                ans += 1  # 消掉这一段至少需要一次操作
                cnt = 0 if cnt == 1 else 1  # 段长为 1 直接减掉；段长 ≥2 视为进位，留下一个 1 继续处理
            n >>= 1  # 右移一位，继续处理更高位
        if cnt == 1:  # 循环结束后，最高位还残留一段长度为 1 的连续 1
            ans += 1  # 再花 1 步把它减掉
        elif cnt > 1:  # 最高位残留的连续 1 长度大于 1
            ans += 2  # 先加一个 2 的幂再减掉，共 2 步
        return ans  # 返回累计的最少操作次数
