// 题目：2527. 查询数组异或美丽值（Find Xor-Beauty of Array）
// 思路：按位独立分析可证，下标三分组的组合中有偶数次重复，最终美丽值等于所有元素的异或和。
// 时间复杂度：O(n)，遍历一次数组；空间复杂度：O(1)，只用一个累加变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int xorBeauty(vector<int>& nums) {  // nums 是输入数组，返回它的异或美丽值
        int ans = 0;  // 异或累加器，初值 0 是异或运算的单位元
        for (auto& x : nums) {  // 按引用遍历数组，避免逐个元素拷贝
            ans ^= x;  // 把当前元素异或进答案（异或满足交换律与结合律）
        }  // 遍历结束
        return ans;  // 返回所有元素的异或值，即为所求美丽值
    }  // 方法结束
};  // 类定义结束