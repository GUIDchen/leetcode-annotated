// 题目：2544. 交替数字和（Alternating Digit Sum）
// 思路：从低位开始按 +、-、+、- 累加，记下符号翻转次数，最后整体乘 -sign 把最高位的符号纠正为正。
// 时间复杂度：O(log n)，即位数；空间复杂度：O(1)。
int alternateDigitSum(int n) {  // 按题目要求从最高位开始依次取正、负号
    int ans = 0;  // 累加交替数字和
    int sign = 1;  // 当前位的符号，初始给个位数用正号
    while (n) {  // 不断取最低位，直到 n 被除到 0
        ans += (n % 10) * sign;  // 取出个位数字，乘上当前符号后累加
        sign = -sign;  // 符号取反，供下一位使用
        n /= 10;  // 去掉已经处理过的个位
    }  // 结束循环
    return ans * -sign;  // 循环结束时 sign = (-1)^位数，从低位累加使最高位拿错了符号，整体乘 -sign 纠正
}  // 函数结束（源文件末尾无换行，保持原样）