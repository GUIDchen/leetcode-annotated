// 题目：2516. 每种字符至少取 K 个（Take K of Each Character From Left and Right）
// 思路：反过来求「整段留在中间、完全不去取」的最长子串，它必须让剩余每种字符的个数仍不少于 k；滑动窗口求最长合法窗口，答案即 n - 窗口长度。
// 时间复杂度：O(n)，每个下标最多被左右指针各访问一次；空间复杂度：O(1)，只用长度 3 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int takeCharacters(string s, int k) {  // s 只含 a/b/c，k 是每种字符至少要取的数量
        int cnt[3]{};  // 统计 a、b、c 各自的总出现次数
        int n = s.length();  // 字符串长度
        for (int i = 0; i < n; ++i) {  // 第一遍扫描统计总频次
            ++cnt[s[i] - 'a'];  // 把字符映射到 0/1/2 后计数
        }
        for (int x : cnt) {  // 检查每种字符的总数是否够取
            if (x < k) {  // 某种字符总数不足 k
                return -1;  // 无论如何都取不够，直接返回 -1
            }
        }
        int mx = 0, j = 0;  // mx：可以整段不取的最长子串长度；j：窗口左端点
        for (int i = 0; i < n; ++i) {  // i 为窗口右端点，向右扩展窗口
            int c = s[i] - 'a';  // 右端点字符对应的计数下标
            --cnt[c];  // 把 s[i] 划入「不取」的窗口，先从可取字符里扣除
            while (cnt[c] < k) {  // 扣除后该字符剩余不足 k，窗口不合法
                ++cnt[s[j++] - 'a'];  // 把左端点移出窗口，让这个字符重新可被取走
            }
            mx = max(mx, i - j + 1);  // 窗口合法，更新最长长度
        }
        return n - mx;  // 要取的字符数 = 总长度 - 可以整段不取的中间部分
    }
};