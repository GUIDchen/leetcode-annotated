# 题目：2595. 奇偶位数（Number of Even and Odd Bits）
# 思路：从最低位开始逐位扫描 n，用变量 i 在 0/1 之间交替，把每个 1 分别累加到偶数位或奇数位的计数上。
# 时间复杂度：O(log n)，只扫描 n 的二进制位数；空间复杂度：O(1)，只用长度固定为 2 的结果数组和常数变量。
class Solution:  # LeetCode 约定的题解类
    def evenOddBit(self, n: int) -> List[int]:  # n 是待统计的整数；返回 [偶数位 1 的个数, 奇数位 1 的个数]
        ans = [0, 0]  # 结果列表：[偶数位计数, 奇数位计数]
        i = 0  # 当前位的奇偶标记：0 表示偶数位，1 表示奇数位
        while n:  # 只要 n 还没被右移成 0，就说明还有二进制位待统计
            ans[i] += n & 1  # 取最低位，为 1 时累加到标记指向的那个计数上
            i ^= 1  # 异或 1 让标记在 0/1 间切换，使下一位归入另一类
            n >>= 1  # 丢掉已统计的最低位，继续处理更高的一位
        return ans  # 返回偶数位与奇数位的 1 的个数
