// 题目：2595. 奇偶位数（Number of Even and Odd Bits）
// 思路：从最低位开始逐位扫描 n，用下标 i 在 0/1 之间交替，把每个 1 分别累加到偶数位或奇数位的计数上。
// 时间复杂度：O(log n)，只扫描 n 的二进制位数；空间复杂度：O(1)，除长度固定为 2 的结果数组外只用常数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> evenOddBit(int n) {  // n：待统计的整数；返回 [偶数位 1 的个数, 奇数位 1 的个数]
        vector<int> ans(2);  // 结果数组：ans[0] 记偶数位、ans[1] 记奇数位，默认初始化为 0
        for (int i = 0; n > 0; n >>= 1, i ^= 1) {  // i 是当前位的奇偶标记（0=偶、1=奇）；每轮把 n 右移一位，同时用 i ^= 1 翻转标记
            ans[i] += n & 1;  // n & 1 取出最低位，若是 1 就累加到对应的奇/偶计数上
        }  // 循环结束：n 的二进制位已全部统计完
        return ans;  // 返回 [偶数位个数, 奇数位个数]
    }
};