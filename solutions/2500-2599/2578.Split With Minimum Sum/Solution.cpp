// 题目：2578. 最小和分割（Split With Minimum Sum）
// 思路：统计每个数字出现次数，把数字从小到大依次交替分给两个数，让两个数的最高位都尽量小，从而总和最小。
// 时间复杂度：O(d + 10)，d 为位数，扫描位数与数字种类都是线性的；空间复杂度：O(1)，计数数组与两个结果数都是常数大小。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int splitNum(int num) {  // num 是待拆分的十进制数，返回拆成两个数后的最小和
        int cnt[10]{};  // cnt[d] 统计数字 d 在 num 的十进制表示里出现了几次
        int n = 0;  // n 记录 num 的总位数
        for (; num; num /= 10) {  // 不断取最低位、再除以 10，直到 num 变成 0
            ++cnt[num % 10];  // 当前最低位数字的计数加一
            ++n;  // 位数加一
        }
        int ans[2]{};  // 两个结果数按位构造，初值都是 0
        for (int i = 0, j = 0; i < n; ++i) {  // 共要分配 n 个数字；j 指向当前能取到的最小数字，从 0 开始会自动跳过用不上的 0，因此不会产生前导零
            while (cnt[j] == 0) {  // 跳过计数为 0 的数字
                ++j;  // 前进到下一个候选数字
            }
            --cnt[j];  // 该数字用掉一个，计数减一
            ans[i & 1] = ans[i & 1] * 10 + j;  // 用 i & 1 在 0、1 之间交替，把较小的数字轮流接到两个数末尾，等价于让高位尽量小且分散在两个数上
        }
        return ans[0] + ans[1];  // 两个数相加就是最小和
    }
};