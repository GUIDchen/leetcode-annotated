# 题目：2578. 最小和分割（Split With Minimum Sum）
# 思路：先统计每位数字出现次数，再把数字从小到大依次交替接到两个数后面，让两个数的高位都尽量小，从而总和最小。
# 时间复杂度：O(d + 10)，d 是位数；空间复杂度：O(1)，计数器与两个结果数都是常数规模。
class Solution:  # LeetCode 约定的题解类
    def splitNum(self, num: int) -> int:  # num 是待拆分的十进制数，返回拆成两个数后的最小和
        cnt = Counter()  # Counter 统计每个数字出现次数，没出现过的键按 0 处理
        n = 0  # n 记录 num 的总位数
        while num:  # 逐位剥离 num，直到它变成 0
            cnt[num % 10] += 1  # 当前最低位数字的计数加一
            num //= 10  # 去掉已经处理过的最低位
            n += 1  # 位数加一
        ans = [0] * 2  # 两个结果数按位构造，初值都是 0
        j = 0  # j 是当前可取的最小数字；遇到计数为 0 就后移，所以不会产生前导零
        for i in range(n):  # 一共要分配 n 个数字
            while cnt[j] == 0:  # 越过所有已经用完的数字
                j += 1  # 找到下一个可用数字
            cnt[j] -= 1  # 用掉一个该数字
            ans[i & 1] = ans[i & 1] * 10 + j  # 用 i & 1 在 0、1 之间交替，把数字轮流接到两个数末尾，使高位尽量小
        return sum(ans)  # 两个数之和就是最小和
