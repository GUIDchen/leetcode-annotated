// 题目：2534. 通过门的时间（Time Taken to Cross the Door）
// 核心思路：两个方向各用一个队列 + 时间模拟。按到达时刻把人们按方向入队；两侧都有人时沿用上一次的放行方向（题面规定同一侧会连续通过直到该侧无人），只有一侧有人就放行该侧，都无人则时钟空转。
// 时间复杂度：O(n)，每人入队、出队各一次；空间复杂度：O(n)，两个队列与长度 n 的答案数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> timeTaken(vector<int>& arrival, vector<int>& state) {  // arrival[i] 是第 i 人的到达时刻，state[i] 是他的方向（0 或 1），返回每个人过门的时刻
        int n = arrival.size();  // 总人数
        queue<int> q[2];  // 两个队列：q[0]、q[1] 分别按方向存放排队者的下标
        int t = 0, i = 0, st = 1;  // t 是当前时刻，i 是下一个尚未到达的人，st 是上次放行的方向
        vector<int> ans(n);  // 记录每个人的过门时刻，长度 n 默认填 0

        while (i < n || !q[0].empty() || !q[1].empty()) {  // 还有人没到达或还有人没进门就继续模拟
            while (i < n && arrival[i] <= t) {  // 把当前时刻及之前已到达的人全部入队
                q[state[i]].push(i++);  // 按方向塞进对应队列，i 自增指向下一个人
            }  // 到达事件处理完毕

            if (!q[0].empty() && !q[1].empty()) {  // 两侧都有人排队，就沿用上一次的放行方向
                ans[q[st].front()] = t;  // 让 st 方向的队首在这个时刻过门
                q[st].pop();  // 该人离开队列
            } else if (!q[0].empty() || !q[1].empty()) {  // 只有一侧有人，只能放行这一侧
                st = q[0].empty() ? 1 : 0;  // 把「上次放行方向」更新为实际放行的那一侧
                ans[q[st].front()] = t;  // 该侧队首在这个时刻过门
                q[st].pop();  // 该人离开队列
            } else {  // 两侧都没人排队，门只能空转
                st = 1;  // 没有可放行的人，把放行方向复位，等下一批到达者决定
            }  // 本次放行处理完毕

            ++t;  // 门每单位时间最多通过一人，时刻前进一秒
        }  // 所有人都已过门

        return ans;  // 返回每个人的过门时刻数组
    }  // 方法结束
};  // 类定义结束
