// 题目：2566. 替换一个数字后的最大差值（Maximum Difference by Remapping a Digit）
// 思路：把某一位数字全部替换成 0 能得到最小值，替换成 9 能得到最大值；分别构造这两个数，再相减即得最大差值。
// 时间复杂度：O(d^2)，d 为数字位数（本题 d ≤ 10，可视为常数）；空间复杂度：O(d)，仅用两个长度 12 的字符数组。
int minMaxDifference(int num) {  // num：输入的整数，允许把其中某一种数字全部改写成另一个数字
    char s[12];  // 存放 num 的十进制字符串表示，12 字节足够容纳 int 及其结束符
    sprintf(s, "%d", num);  // 把整数格式化成字符串，后续按字符处理更方便

    int mi;  // 能得到的「最小值」
    {
        char tmp[12];  // 临时缓冲：存放替换后的字符串
        char t = s[0];  // 取首位数字作为要替换的目标（替换最高位能让数值损失最大，所以最小值最小）
        for (int i = 0; s[i]; i++) {  // 遍历字符串直到结束符
            tmp[i] = (s[i] == t) ? '0' : s[i];  // 把所有等于首位的数字换成 '0'，其余原样保留
        }
        tmp[strlen(s)] = '\0';  // 手动补上字符串结束符，保证 atoi 能正确停止
        mi = atoi(tmp);  // 把替换后的字符串转回整数，得到最小值
    }

    for (int i = 0; s[i]; i++) {  // 从左往右找第一个不是 '9' 的数字
        char c = s[i];  // 准备把所有出现的 c 都替换成 '9'
        if (c != '9') {  // 找到了可放大的数字，替换它能得到最大值
            char tmp[12];  // 临时缓冲：存放替换后的字符串
            for (int j = 0; s[j]; j++) {  // 遍历整个字符串
                tmp[j] = (s[j] == c) ? '9' : s[j];  // 把所有等于 c 的数字换成 '9'，其余原样保留
            }
            tmp[strlen(s)] = '\0';  // 手动补上字符串结束符
            return atoi(tmp) - mi;  // 最大值减去最小值，即为题目要求的最大差值
        }
    }

    return num - mi;  // 全是 9 时无法变大，最大差值就是 num 本身减去最小值
}
