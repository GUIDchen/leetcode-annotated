// 题目：2953. 统计完全子字符串（Count Complete Substrings）
// 思路：先按「相邻字符差不超过 2」把原串切成互不影响的块；块内完全子串长度必为 i*k（i 种字母各 k 次），用定长滑动窗口加频次表统计。
// 时间复杂度：O(n * 26)，每块内枚举字母种数并线性滑窗；空间复杂度：O(26)，频次表与计数表都是常数大小。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countCompleteSubstrings(string word, int k) {  // word：输入字符串；k：每种字母必须出现的次数；返回完全子串个数
        int n = word.length();  // 字符串总长度
        int ans = 0;  // 全局答案：所有块贡献之和
        auto f = [&](string s) {  // 处理单块：块内相邻字符差都不超过 2，块之间不可能构成完全子串
            int m = s.length();  // 当前块的长度
            int ans = 0;  // 块内答案，与外面的 ans 同名但作用域不同
            for (int i = 1; i <= 26 && i * k <= m; ++i) {  // 完全子串恰含 i 种字母，长度必为 i*k，所以只枚举合法的 i
                int l = i * k;  // 当前固定窗口长度
                int cnt[26]{};  // 窗口内 26 个字母各自的出现次数
                for (int j = 0; j < l; ++j) {  // 初始化第一个长度为 l 的窗口
                    ++cnt[s[j] - 'a'];  // 对应字母的出现次数加一
                }  // 初始窗口统计结束
                unordered_map<int, int> freq;  // 频次表：出现次数 -> 有多少种字母正好是这个次数
                for (int x : cnt) {  // 遍历 26 个字母的计数
                    if (x > 0) {  // 只统计出现过的字母
                        freq[x]++;  // 记录该频次多了一种字母
                    }  // if 分支结束
                }  // for 遍历结束
                if (freq[k] == i) {  // 恰好 i 种字母都出现 k 次，说明是合法完全子串
                    ++ans;  // 答案加一
                }  // if 分支结束
                for (int j = l; j < m; ++j) {  // 定长窗口从 l 开始逐位右移
                    int a = s[j] - 'a';  // 新进入窗口的字母
                    int b = s[j - l] - 'a';  // 即将离开窗口的字母
                    freq[cnt[a]]--;  // 先把字母 a 的旧频次从频次表里撤销
                    cnt[a]++;  // 字母 a 的计数加一
                    freq[cnt[a]]++;  // 再登记它的新频次

                    freq[cnt[b]]--;  // 同理处理要移出的字母 b：先撤销它的旧频次
                    cnt[b]--;  // 字母 b 的计数减一
                    freq[cnt[b]]++;  // 再登记它的新频次

                    if (freq[k] == i) {  // 每个窗口都重新判断一次是否满足条件
                        ++ans;  // 答案加一
                    }  // if 分支结束
                }  // 滑窗循环结束
            }  // 字母种数枚举结束
            return ans;  // 返回这一块的答案
        };  // lambda 定义结束
        for (int i = 0; i < n;) {  // 从头开始切分块
            int j = i + 1;  // 先假定块从 i 开始、至少含一个字符
            while (j < n && abs(word[j] - word[j - 1]) <= 2) {  // 相邻字符差不超过 2 才能留在同一块里
                ++j;  // 继续向右扩展当前块
            }  // while 扩展结束，j 是块的右开边界
            ans += f(word.substr(i, j - i));  // 把该块的贡献累加进总答案
            i = j;  // 跳到下一块的起点
        }  // 切块循环结束
        return ans;  // 返回全部完全子串的个数
    }  // 方法结束
};  // 类定义结束