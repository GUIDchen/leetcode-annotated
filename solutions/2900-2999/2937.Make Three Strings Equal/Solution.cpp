// 题目：2937. 使三个字符串相等（Make Three Strings Equal）
// 思路：三个字符串的共同前缀必须从下标 0 开始，先求出最长公共前缀长度 i，再把三个串都裁剪到长度 i。
// 时间复杂度：O(min(|s1|,|s2|,|s3|))，最多扫描最短串一遍；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int findMinimumOperations(string s1, string s2, string s3) {  // s1、s2、s3：三个待比较的字符串；返回最少删除的字符总数
        int s = s1.size() + s2.size() + s3.size();  // s：三个字符串的总长度，保留长度为 i 的公共前缀后结果为 s - 3 * i
        int n = min({s1.size(), s2.size(), s3.size()});  // n：三者中的最短长度，公共前缀不可能超过它
        for (int i = 0; i < n; ++i) {  // 从下标 0 开始逐位比较三个字符串
            if (!(s1[i] == s2[i] && s2[i] == s3[i])) {  // 一旦某一位三个字符不全相同，公共前缀就在这里断掉
                return i == 0 ? -1 : s - 3 * i;  // i == 0 说明首位就不同，无法让三个串相等，返回 -1；否则保留长度 i 的公共前缀
            }  // 字符不一致的分支结束
        }  // 逐位比较循环结束
        return s - 3 * n;  // 最短串本身就是公共前缀，把三个串都裁剪到长度 n
    }  // 方法结束
};  // 类定义结束（分号不能省）