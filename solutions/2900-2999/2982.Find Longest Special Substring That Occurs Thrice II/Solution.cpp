// 题目：2982. 找出出现至少三次的最长特殊子字符串 II（Find Longest Special Substring That Occurs Thrice II）
// 核心思路：二分答案长度 x；check(x) 统计每个字母能提供多少个「长度恰为 x 的特殊子串」，任一字母累加到 3 个即说明 x 可行。
// 时间复杂度：O(n log n)，每轮 check 线性扫一遍串；空间复杂度：O(1)，只用长度 26 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 对外可见的解法接口
    int maximumLength(string s) {  // s 是只含小写字母的输入串，返回最长「出现至少三次的特殊子串」长度，不存在则返回 -1
        int n = s.size();  // 串长，后续二分的上界与扫描的边界都要用到
        int l = 0, r = n;  // 二分区间 [l, r]：答案长度只可能落在 0..n 内，l = 0 代表「无解」
        auto check = [&](int x) {  // 判定闭包：长度 x 的特殊子串是否出现至少三次；按引用捕获 n 与 s
            int cnt[26]{};  // 长度为 26 的计数器，零初始化；下标就是字母编号
            for (int i = 0; i < n;) {  // 从位置 i 开始枚举每一段「连续相同字符」的区间
                int j = i + 1;  // j 是右端点游标，先指向 i 的后一位
                while (j < n && s[j] == s[i]) {  // 只要字符仍与 s[i] 相同就继续向右扩
                    ++j;  // 右端点右移一格
                }  // 连续段确定为 [i, j)，段长为 j - i
                int k = s[i] - 'a';  // 该段的字母编号，用作 cnt 的下标
                cnt[k] += max(0, j - i - x + 1);  // 长度 L 的连续段里长度恰为 x 的子串有 L-x+1 个；L < x 时取 0
                if (cnt[k] >= 3) {  // 该字母的合法特殊子串已经凑够 3 次
                    return true;  // 长度 x 可行，提前结束判定
                }  // 否则继续检查后面的连续段
                i = j;  // 直接跳到段尾，避免同一段被重复统计
            }  // 所有连续段扫描完毕
            return false;  // 没有任何字母能凑够 3 次，长度 x 不可行
        };  // 判定闭包定义结束
        while (l < r) {  // 二分找最大的可行长度，用上取整中点避免死循环
            int mid = (l + r + 1) >> 1;  // 上取整的中点，保证每次都能把 l 向前推进
            if (check(mid)) {  // mid 这个长度可行
                l = mid;  // 答案至少是 mid，把左边界抬上来
            } else {  // mid 这个长度不可行
                r = mid - 1;  // 答案严格小于 mid
            }  // 分支结束
        }  // 二分收敛，此时 l 就是最大的可行长度
        return l == 0 ? -1 : l;  // 长度为 0 说明根本不存在合法子串，按题意返回 -1
    }
};