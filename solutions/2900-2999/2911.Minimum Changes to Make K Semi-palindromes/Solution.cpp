// 题目：2911. 得到 K 个半回文串的最少修改次数（Minimum Changes to Make K Semi-palindromes）
// 核心思路：先预处理 g[i][j]＝把子串 s[i-1..j-1] 变成半回文串的最少修改次数（枚举长度 m 的因子 d 作为周期，按同余类配对累计字符差异），再做「前 i 个字符切成 j 段」的区间 DP。
// 时间复杂度：O(n^3 * d) 上界约 O(n^4) 但常数很小，实际为 O(n^2 * d + k*n^2)；空间复杂度：O(n^2 + n*k)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumChanges(string s, int k) {  // s 是待拆分的字符串，k 是要求的段数，返回最少修改次数
        int n = s.size();  // 字符串长度
        int g[n + 1][n + 1];  // g[i][j]：把 s[i-1..j-1] 变成半回文串所需的最少修改次数
        int f[n + 1][k + 1];  // f[i][j]：把 s 的前 i 个字符切成 j 段半回文串的最少修改次数
        memset(g, 0x3f, sizeof(g));  // 用 0x3f3f3f3f 填充表示“无穷大”
        memset(f, 0x3f, sizeof(f));  // f 同样初始化成无穷大
        f[0][0] = 0;  // 边界：前 0 个字符切 0 段，不需要任何修改
        for (int i = 1; i <= n; ++i) {  // 枚举子串左端点（1 基，方便与字符串下标对应）
            for (int j = i; j <= n; ++j) {  // 枚举子串右端点，子串为 s[i-1..j-1]
                int m = j - i + 1;  // 子串长度 m
                for (int d = 1; d < m; ++d) {  // 枚举半回文串的周期 d（d 必须整除 m）
                    if (m % d == 0) {  // 只有整除时才能按 d 个交错回文序列拆分
                        int cnt = 0;  // 统计该周期下需要修改的字符对数
                        for (int l = 0; l < m; ++l) {  // 枚举子串内位置 l，它与同余类的对称位置配对
                            int r = (m / d - 1 - l / d) * d + l % d;  // 配对位置：同余类 l%d 中从末尾数过来的对称点
                            if (l >= r) {  // 已扫过中点，配对会重复，可以停止
                                break;  // 结束配对扫描
                            }  // if 结束
                            if (s[i - 1 + l] != s[i - 1 + r]) {  // 配对字符不同就需要改一次
                                ++cnt;  // 修改次数加一
                            }  // if 结束
                        }  // 内层配对循环结束
                        g[i][j] = min(g[i][j], cnt);  // 所有周期中取修改次数最少的作为该子串的代价
                    }  // if 整除结束
                }  // 周期枚举结束
            }  // 右端点枚举结束
        }  // 左端点枚举结束
        for (int i = 1; i <= n; ++i) {  // DP：枚举前缀长度 i
            for (int j = 1; j <= k; ++j) {  // 枚举已经切出的段数 j
                for (int h = 0; h < i - 1; ++h) {  // 枚举最后一段的起点 h；半回文串长度至少为 2，所以 h 最多到 i-2
                    f[i][j] = min(f[i][j], f[h][j - 1] + g[h + 1][i]);  // 转移：前 h 个字符切 j-1 段的代价 + 最后一段 s[h..i-1] 的代价
                }  // 切分点枚举结束
            }  // 段数枚举结束
        }  // 前缀长度枚举结束
        return f[n][k];  // 答案：前 n 个字符切成 k 段的最小修改次数
    }  // 方法结束
};  // 类定义结束