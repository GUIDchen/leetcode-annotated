// 题目：2950. 可整除子串的数量（Number of Divisible Substrings）
// 思路：先按题意把 26 个字母映射成 1..9 的权值，再枚举所有子串，边扩展右端点边累加权值和，判断能否被子串长度整除。
// 时间复杂度：O(n^2)，枚举左右端点；空间复杂度：O(1)，只用 26 大小的映射数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countDivisibleSubstrings(string word) {  // word：由小写字母组成的字符串；返回数字和能被长度整除的子串个数
        string d[9] = {"ab", "cde", "fgh", "ijk", "lmn", "opq", "rst", "uvw", "xyz"};  // 字母到权值的分组表：第 i 组（i 从 1 起）里的字母权值就是 i
        int mp[26]{};  // 26 个字母的权值数组，值初始化全部为 0
        for (int i = 0; i < 9; ++i) {  // 逐组遍历分组表
            for (char& c : d[i]) {  // 遍历当前组内的每个字符
                mp[c - 'a'] = i + 1;  // 记录该字母的权值（组号 i 从 0 开始，所以加 1）
            }  // 内层字符循环结束
        }  // 外层分组循环结束
        int ans = 0;  // 答案：满足整除条件的子串数量
        int n = word.size();  // 字符串长度，提前取出避免循环里反复调用 size()
        for (int i = 0; i < n; ++i) {  // 枚举子串左端点 i
            int s = 0;  // 以 i 为起点的子串权值和，每换一个起点就清零
            for (int j = i; j < n; ++j) {  // 枚举右端点 j，逐步把子串向右扩展
                s += mp[word[j] - 'a'];  // 把新加入字符的权值累加进子串和
                ans += s % (j - i + 1) == 0 ? 1 : 0;  // 子串长度 j-i+1 能整除和 s 时记 1，否则记 0
            }  // 右端点枚举结束
        }  // 左端点枚举结束
        return ans;  // 返回可整除子串的总数
    }  // 方法结束
};  // 类定义结束