// 题目：2980. 检查按位或是否存在尾随零（Check if Bitwise OR Has Trailing Zeros）
// 思路：按位或结果的最低位只取决于各数的最低位，只要数组里至少有两个偶数，取它们相或最低位就是 0，即结果含尾随零。
// 时间复杂度：O(n)，只需扫一遍数组；空间复杂度：O(1)，仅用一个计数器。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool hasTrailingZeros(vector<int>& nums) {  // nums：候选整数数组，返回是否存在按位或结果带尾随零的选法
        int cnt = 0;  // 统计偶数（最低位为 0）的个数
        for (int x : nums) {  // 逐个检查数组元素
            cnt += (x & 1 ^ 1);  // x & 1 取最低位，再 ^1 取反：偶数得 1、奇数得 0，等价于判断 x 是否为偶数
        }  // 循环结束
        return cnt >= 2;  // 至少两个偶数时，取这两个数相或，最低位必为 0，即结果有尾随零
    }  // 方法结束
};  // 类定义结束