# 题目：2912. 在网格上移动到目的地的方法数（Number of Ways to Reach Destination in the Grid）
# 思路：终点相对起点只有四种位置关系，同一类格子方案数相同，用 4 个滚动状态按 k 步转移。
# 时间复杂度：O(k)，每步只做常数次转移；空间复杂度：O(1)，只用 4 个滚动状态。
class Solution:  # LeetCode 约定的题解类
    def numberOfWays(  # n 行 m 列，走 k 步；source/dest 是 1-based 的 [x, y] 坐标
        self, n: int, m: int, k: int, source: List[int], dest: List[int]  # 参数排成多行只是为了不超长，语义与题目签名一致
    ) -> int:  # 返回值是模 1e9+7 后的方案数
        mod = 10**9 + 7  # 取模常量
        f = [1, 0, 0, 0]  # f[0..3]：到达四类格子的方案数，同类格子方案数相同，只记单个格子的值；起点自身初始为 1
        for _ in range(k):  # 一共走 k 步，逐步滚动更新
            g = [0] * 4  # g 用来存放走完这一步的四类方案数
            g[0] = ((n - 1) * f[1] + (m - 1) * f[2]) % mod  # 回到起点自身：从同列的 n-1 个格子或同行的 m-1 个格子一步跳回
            g[1] = (f[0] + (n - 2) * f[1] + (m - 1) * f[3]) % mod  # 到同列异行的格子：来自起点、同列其余 n-2 个格子，以及目标所在行上异行异列的 m-1 个格子
            g[2] = (f[0] + (m - 2) * f[2] + (n - 1) * f[3]) % mod  # 到同行异列的格子：与上一条对称，来自起点、同行其余 m-2 个格子，以及目标所在列上异行异列的 n-1 个格子
            g[3] = (f[1] + f[2] + (n - 2) * f[3] + (m - 2) * f[3]) % mod  # 到行列都异的格子：来自同列其余 n-2 个、同行其余 m-2 个异行异列的格子，再加同行/同列各 1 个单异类格子
            f = g  # 滚动：g 成为下一轮的 f
        if source[0] == dest[0]:  # 起点与终点在同一行时
            return f[0] if source[1] == dest[1] else f[2]  # 列也相同就是起点自身，否则是同行异列的第 2 类状态
        return f[1] if source[1] == dest[1] else f[3]  # 行不同：列相同取同列异行的第 1 类状态，列也不同取第 3 类状态
