// 题目：2735. 收集巧克力（Collecting Chocolates）
// 思路：设 f[i][j] 为把数组整体右移不超过 j 次时，位置 i 上出现过的最低价格；枚举总右移次数 j，按 f[i][j] 逐个位置买下，再加上 j 次操作费 x*j 取最小。
// 时间复杂度：O(n^2)，预处理与枚举都是二重循环；空间复杂度：O(n^2)，需要 n×n 的 f 表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long minCost(vector<int>& nums, int x) {  // nums：每个位置巧克力的初始价格；x：把整个数组右移一次的操作费用
        int n = nums.size();  // 记录巧克力种类数（也就是位置数）
        int f[n][n];  // f[i][j]：允许最多右移 j 次时，位置 i 上出现过的最低价格
        for (int i = 0; i < n; ++i) {  // 对每个位置 i 单独预处理它的最低价序列
            f[i][0] = nums[i];  // 不做任何右移时，位置 i 上就是初始价格 nums[i]
            for (int j = 1; j < n; ++j) {  // 逐步增加允许的右移次数，把新出现的价格并入最小值
                f[i][j] = min(f[i][j - 1], nums[(i - j + n) % n]);  // 右移 j 次后位置 i 上出现的是原来位置 (i - j + n) % n 的巧克力，与历史最小值取小
            }  // 内层 j 循环结束
        }  // 外层 i 循环结束
        long long ans = 1LL << 60;  // 答案初值取一个足够大的数（1 左移 60 位），后面用 min 更新
        for (int j = 0; j < n; ++j) {  // 枚举总共执行的右移次数 j；右移 n 次会回到原状，所以 j 只需枚举到 n-1
            long long cost = 1LL * x * j;  // 先付出 j 次整体右移的操作总费用 x*j
            for (int i = 0; i < n; ++i) {  // 再把每个位置按各自的最低价买下来
                cost += f[i][j];  // 累加位置 i 在当前右移次数下的最低价格
            }  // 内层累加循环结束
            ans = min(ans, cost);  // 用当前方案的总花费更新最优答案
        }  // 外层枚举循环结束
        return ans;  // 返回所有方案中的最小总花费
    }  // 方法体结束
};  // 类定义结束