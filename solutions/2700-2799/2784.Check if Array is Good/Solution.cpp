// 题目：2784. 检查数组是否是好的（Check if Array is Good）
// 核心思路：计数。长度为 n+1 的“好数组”必是 1..n 各出现一次再加上一个 n，因此只需统计各值频率：n 出现 2 次且 1..n-1 各出现 1 次。
// 时间复杂度：O(n)，扫一遍数组再扫一遍值域；空间复杂度：O(V)，V = 200 的定长计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isGood(vector<int>& nums) {  // nums：待检查数组；返回它是否是一个好数组
        int n = nums.size() - 1;  // 好数组长度是 n+1（n 个数 1..n 再加一个 n），所以 n = 长度 - 1
        int cnt[201]{};  // 值域 1..n ≤ 200，用定长计数数组统计频率，{} 把全部元素清零
        for (int x : nums) {  // 遍历数组的每个元素
            ++cnt[x];  // 对应值的出现次数加一
        }  // 遍历结束
        if (cnt[n] != 2) {  // 最大值 n 必须恰好出现两次：一次算 1..n 中的那一份，一次是额外补的那个 n
            return false;  // 出现次数不是 2，直接判定不是好数组
        }  // if 分支结束
        for (int i = 1; i < n; ++i) {  // 检查 1 到 n-1 每个值
            if (cnt[i] != 1) {  // 这些值都必须恰好出现一次
                return false;  // 次数不是 1 说明缺数或重复，判定失败
            }  // if 分支结束
        }  // 循环结束
        return true;  // 条件全部满足，是好数组
    }  // 方法结束
};  // 类定义结束