// 题目：2765. 最长交替子数组（Longest Alternating Subarray）
// 思路：枚举每个起点 i，用 k 表示期望的相邻差值（1 与 -1 交替），沿数组尽量向右扩展，取长度至少为 2 的最大交替子数组长度。
// 时间复杂度：O(n^2)，最坏情况每个起点都扫到数组尾部；空间复杂度：O(1)，只用了 ans、n、k、j 等常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int alternatingSubarray(vector<int>& nums) {  // nums：输入数组；返回值是满足交替条件的最长子数组长度
        int ans = -1, n = nums.size();  // ans 初始为 -1 表示暂时还没有合法子数组；n 是数组长度
        for (int i = 0; i < n; ++i) {  // 枚举交替子数组的起点 i
            int k = 1;  // k 是期望的 nums[j+1] - nums[j] 差值，初始要求后一个比前一个大 1
            int j = i;  // j 是当前子数组的右端点，从起点 i 开始向右扩展
            for (; j + 1 < n && nums[j + 1] - nums[j] == k; ++j) {  // 只要右边还有元素且差值恰好等于 k，就把右端点继续右移
                k *= -1;  // 差值要求翻转：1 → -1 → 1，保证「大、小、大」交替
            }  // 扩展结束，此时 j 是这次能到达的最远右端点
            if (j - i + 1 > 1) {  // 长度至少为 2 才算合法的交替子数组，单个元素不算
                ans = max(ans, j - i + 1);  // 用当前长度更新历史最大值
            }  // 分支结束
        }  // 起点枚举结束
        return ans;  // 没有任何合法子数组时 ans 仍为 -1，正好符合题目要求
    }  // 方法结束
};  // 类定义结束（源文件末尾无换行，注释同样不追加换行）