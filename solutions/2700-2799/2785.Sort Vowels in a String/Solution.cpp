// 题目：2785. 将字符串中的元音字母排序（Sort Vowels in a String）
// 核心思路：两趟扫描。第一趟收集所有元音字母（保留大小写）并排序，第二趟按原顺序把排好序的元音填回元音所在位置，辅音位置不动。
// 时间复杂度：O(n log n)，瓶颈是元音排序；空间复杂度：O(n)，存放元音序列。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string sortVowels(string s) {  // s：输入字符串；返回元音字母按字典序重排后的字符串
        string vs;  // vs 收集所有元音字母（保留原始大小写）
        for (auto c : s) {  // 依次检查每个字符
            char d = tolower(c);  // 统一转成小写再比较，这样大写元音也能被识别
            if (d == 'a' || d == 'e' || d == 'i' || d == 'o' || d == 'u') {  // 是 a/e/i/o/u 之一，即为元音（y 按题意不算）
                vs.push_back(c);  // 按原样（保留大小写）收进 vs
            }  // if 分支结束
        }  // 第一趟扫描结束
        ranges::sort(vs);  // 对收集到的元音升序排序（C++20 ranges::sort），得到字典序
        for (int i = 0, j = 0; i < s.size(); ++i) {  // 第二趟：i 扫全串，j 依次消费排好序的元音
            char d = tolower(s[i]);  // 同样先转小写判断当前位是否为元音
            if (d == 'a' || d == 'e' || d == 'i' || d == 'o' || d == 'u') {  // 当前位是元音
                s[i] = vs[j++];  // 把排好序的下一个元音填回这个位置，j 自增指向下一个
            }  // if 分支结束
        }  // 第二趟扫描结束
        return s;  // 返回重排后的字符串
    }  // 方法结束
};  // 类定义结束
