// 题目：2748. 美丽下标对的数目（Number of Beautiful Pairs）
// 思路：顺序扫描，用 cnt[d] 记录已出现元素中最高位为 d 的个数；处理当前元素时枚举 d，统计 gcd(d, 当前末位) == 1 的前驱数量。
// 时间复杂度：O(n * 10)，每个元素常数次枚举；空间复杂度：O(10)，只有长度为 10 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 公有成员：判题器直接调用下面的方法
    int countBeautifulPairs(vector<int>& nums) {  // nums：输入数组；返回满足 gcd(前驱元素首位, 当前元素末位) == 1 的下标对数目
        int cnt[10]{};  // cnt[d]：已经扫描过的元素中，最高位（首位数字）为 d 的个数
        int ans = 0;  // 累加美丽下标对的数量
        for (int x : nums) {  // 依次处理每个元素，把它当作下标对中的后者 j
            for (int y = 0; y < 10; ++y) {  // 枚举前面元素可能的首位数字 y
                if (cnt[y] && gcd(x % 10, y) == 1) {  // 存在首位为 y 的元素，且它的首位与当前元素末位的 gcd 为 1 时配对合法
                    ans += cnt[y];  // 这些元素都能与当前元素组成美丽下标对，一次性计入
                }  // 结束 if 分支
            }  // 结束首位枚举循环
            while (x > 9) {  // 不断去掉最低位，直到只剩最高位（x 是值拷贝，不影响原数组）
                x /= 10;  // 去掉最低位
            }  // 结束求首位的循环
            ++cnt[x];  // 当前元素的最高位计数加一，供后面的元素配对使用
        }  // 结束外层循环
        return ans;  // 返回美丽下标对总数
    }  // 结束题解方法
// 结束题解类
};