// 题目：2734. 执行子串操作后的字典序最小字符串（Lexicographically Smallest String After Substring Operation）
// 思路：跳过开头的 'a'，把接下来第一段连续的非 'a' 子串整体减一（'a' 减会变 'z'，所以必须停在 'a' 前）；全串皆 'a' 时只能把末位改成 'z'。
// 时间复杂度：O(n)，指针 i、j 都只向右移动；空间复杂度：O(1)，原地修改字符串。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string smallestString(string s) {  // s：输入字符串（按值传入，可安全地原地修改后返回）
        int n = s.size();  // 记录字符串长度，后续多处判断边界要用
        int i = 0;  // i 用于定位开头连续 'a' 段之后的第一个字符
        while (i < n && s[i] == 'a') {  // 跳过开头连续的 'a'：这些字符一旦减一会变成 'z'，反而让字典序变大
            ++i;  // 继续向右寻找真正可以执行减一操作的位置
        }  // while 循环体结束
        if (i == n) {  // 整串都是 'a'，找不到任何非 'a' 字符可以减
            s[n - 1] = 'z';  // 按题意必须执行一次操作，只能把最后一个字符 'a' 改成 'z'
            return s;  // 返回这种特殊情况的结果
        }  // if 分支体结束
        int j = i;  // j 从 i 出发，向右扩展第一段连续非 'a' 的区间 [i, j)
        while (j < n && s[j] != 'a') {  // 区间越长减的字符越多、字典序越小，因此一直延伸到遇到 'a' 或串尾
            s[j] = s[j] - 1;  // 区间内每个字符都减一，得到这一段能取到的最小字符
            ++j;  // 移动到下一个字符继续判断
        }  // 内层 while 循环体结束
        return s;  // 区间 [i, j) 之外的部分保持原样，拼成最终答案返回
    }  // 方法体结束
};  // 类定义结束