# 题目：696. 计数二进制子串（Count Binary Substrings）
# 思路：把字符串按连续相同字符分组并记录每组长度，相邻两组长度取较小值即为这两组之间合法子串的个数，累加得到答案。
# 时间复杂度：O(n)，每个字符只被扫描一次；空间复杂度：O(1)，只用了若干整型变量。
class Solution:  # LeetCode 约定的题解类
    def countBinarySubstrings(self, s: str) -> int:  # s 只由 '0' 和 '1' 组成，返回满足条件的子串个数
        n = len(s)  # 字符串长度，作为扫描的边界
        ans = i = 0  # ans 累计合法子串数；i 是当前这一组连续相同字符的起点
        pre = 0  # 上一组的长度，初始为 0 以便处理第一组
        while i < n:  # 从头到尾遍历所有字符分组
            j = i + 1  # j 从 i 的下一位开始寻找本组的右边界
            while j < n and s[j] == s[i]:  # 只要字符与 s[i] 相同就继续向右推进
                j += 1  # 扩大本组范围
            cur = j - i  # 本组（连续相同字符）的长度
            ans += min(pre, cur)  # 相邻两组长度取小，就是以交界处为中心能形成的合法子串个数
            pre = cur  # 当前组变成下一轮循环的「上一组」
            i = j  # 从下一组的起点继续扫描
        return ans  # 返回统计得到的子串总数
