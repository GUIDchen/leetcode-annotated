// 题目：689. 三个无重叠子数组的最大和（Maximum Sum of 3 Non-Overlapping Subarrays）
// 思路：长度固定的滑动窗口 + 前缀最优。一次遍历同时维护三段的窗口和 s1/s2/s3，并保存「一段最优」「两段最优」的位置，最后与第三段组合成三段最优。
// 时间复杂度：O(n)，只扫描一遍数组；空间复杂度：O(1)，只用常数个变量。
class Solution {
public:
    vector<int> maxSumOfThreeSubarrays(vector<int>& nums, int k) {  // nums 为数组，k 为每个子数组的长度，返回三个子数组的起始下标
        vector<int> ans(3);  // 答案数组：三个无重叠子数组的起始下标，默认填 0
        int s = 0, s1 = 0, s2 = 0, s3 = 0;  // s 记录三段总和的当前最优；s1、s2、s3 分别是三段滑动窗口的和
        int mx1 = 0, mx12 = 0;  // mx1 为第一段窗口和的最大值；mx12 为前两段窗口和合计的最大值
        int idx1 = 0, idx121 = 0, idx122 = 0;  // idx1 是 mx1 对应的第一段起点；idx121、idx122 是 mx12 两段各自的起点
        for (int i = k * 2; i < nums.size(); ++i) {  // i 是第三段窗口的右端点，从 2k 开始，保证前面能放下两段
            s1 += nums[i - k * 2];  // s1 滑入 nums[i-2k]，使其成为以 i-2k 结尾、长度 k 的第一段窗口和
            s2 += nums[i - k];  // s2 滑入 nums[i-k]，使其成为以 i-k 结尾、长度 k 的第二段窗口和
            s3 += nums[i];  // s3 滑入 nums[i]，使其成为以 i 结尾、长度 k 的第三段窗口和
            if (i >= k * 3 - 1) {  // 三段窗口都凑满 k 个元素后，才允许统计（i-k 至少要能作为第三段终点）
                if (s1 > mx1) {  // 第一段窗口和刷新了历史最优
                    mx1 = s1;  // 更新第一段最优和
                    idx1 = i - k * 3 + 1;  // 第一段起点 = 当前第一段右端点 i-2k 减去 k-1，即 i-3k+1
                }
                if (mx1 + s2 > mx12) {  // 第一段最优与当前第二段拼起来，优于已知两段最优
                    mx12 = mx1 + s2;  // 更新前两段合计最优
                    idx121 = idx1;  // 第一段沿用最优位置 idx1
                    idx122 = i - k * 2 + 1;  // 第二段起点 = i-2k+1（以 i-k 结尾的长度 k 窗口的起点）
                }
                if (mx12 + s3 > s) {  // 前两段最优与当前第三段拼起来，优于已知三段最优
                    s = mx12 + s3;  // 更新三段总和最优
                    ans = {idx121, idx122, i - k + 1};  // 记录三段的起始下标，第三段起点为 i-k+1
                }
                s1 -= nums[i - k * 3 + 1];  // 第一段窗口右移：左端出窗，为下一轮腾出位置
                s2 -= nums[i - k * 2 + 1];  // 第二段窗口右移：左端出窗
                s3 -= nums[i - k + 1];  // 第三段窗口右移：左端出窗
            }
        }
        return ans;  // 返回三段总和最大时各段的起始下标（题目保证字典序最小）
    }
};