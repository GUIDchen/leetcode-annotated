# 题目：689. 三个无重叠子数组的最大和（Maximum Sum of 3 Non-Overlapping Subarrays）
# 思路：长度固定的滑动窗口 + 前缀最优。一趟遍历同时维护三段窗口和 s1/s2/s3，并记住「一段最优」与「两段最优」的位置，最后与第三段组合。
# 时间复杂度：O(n)，只扫描一遍数组；空间复杂度：O(1)，只用常数个变量。
class Solution:
    def maxSumOfThreeSubarrays(self, nums: List[int], k: int) -> List[int]:  # nums 为数组，k 为每段长度，返回三个子数组的起始下标
        s = s1 = s2 = s3 = 0  # s 是三段总和的最优值；s1、s2、s3 分别是三段的滑动窗口和
        mx1 = mx12 = 0  # mx1 是第一段窗口和的最大值；mx12 是前两段合计的最大值
        idx1, idx12 = 0, ()  # idx1 是 mx1 对应的第一段起点；idx12 是两段最优时两段各自的起点（先用空元组占位）
        ans = []  # ans 保存最终三个子数组的起始下标
        for i in range(k * 2, len(nums)):  # i 是第三段窗口的右端点，从 2k 开始以保证前面能放下两段
            s1 += nums[i - k * 2]  # s1 滑入 nums[i-2k]，成为以 i-2k 结尾、长度 k 的第一段窗口和
            s2 += nums[i - k]  # s2 滑入 nums[i-k]，成为以 i-k 结尾、长度 k 的第二段窗口和
            s3 += nums[i]  # s3 滑入 nums[i]，成为以 i 结尾、长度 k 的第三段窗口和
            if i >= k * 3 - 1:  # 三段窗口都凑满 k 个元素后才开始统计
                if s1 > mx1:  # 第一段窗口和刷新了历史最优
                    mx1 = s1  # 更新第一段最优和
                    idx1 = i - k * 3 + 1  # 第一段起点 = 右端点 i-2k 减去 k-1，即 i-3k+1
                if mx1 + s2 > mx12:  # 第一段最优加上当前第二段，若优于已知两段最优
                    mx12 = mx1 + s2  # 更新前两段合计最优
                    idx12 = (idx1, i - k * 2 + 1)  # 第一段沿用最优位置 idx1，第二段起点为 i-2k+1
                if mx12 + s3 > s:  # 前两段最优加上当前第三段，若优于已知三段最优
                    s = mx12 + s3  # 更新三段总和最优
                    ans = [*idx12, i - k + 1]  # 解包 idx12 并接上第三段起点 i-k+1，得到三个下标
                s1 -= nums[i - k * 3 + 1]  # 第一段窗口右移：左端元素出窗
                s2 -= nums[i - k * 2 + 1]  # 第二段窗口右移：左端元素出窗
                s3 -= nums[i - k + 1]  # 第三段窗口右移：左端元素出窗
        return ans  # 返回三段总和最大时各段的起始下标
