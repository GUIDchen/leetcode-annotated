// 题目：634. 寻找数组的错位排列（Find the Derangement of An Array）
// 思路：错排递推 f[i] = (i-1) * (f[i-1] + f[i-2])：数字 i 有 i-1 个非原位可放，放好后分「互换」与「不互换」两种情形。
// 时间复杂度：O(n)，一次线性递推；空间复杂度：O(n)，保存全部 f 值。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int findDerangement(int n) {  // n 是排列长度，返回 1..n 的错位排列个数（对 1e9+7 取模）
        long long f[n + 1];  // f[i] 表示长度为 i 的错排方案数，用变长数组声明，下标覆盖 0..n
        memset(f, 0, sizeof(f));  // 整体清零；边界 f[0]=1、f[1]=0 由此得到
        f[0] = 1;  // 边界：长度为 0 的空排列算 1 种错排；n=0 时直接返回它
        const int mod = 1e9 + 7;  // 取模常量
        for (int i = 2; i <= n; i++) {  // 从长度 2 开始递推（长度 1 没有错排）
            f[i] = (i - 1LL) * (f[i - 1] + f[i - 2]) % mod;  // 错排递推：i 有 i-1 个可放位置，放好后是 f[i-1]（与那个位置互换）或 f[i-2]（不互换）两种情形；1LL 保证乘法在 64 位下进行
        }  // 递推循环结束
        return f[n];  // 返回长度为 n 的错排方案数
    }  // 方法结束
};  // 类定义结束