// 题目：670. 最大交换（Maximum Swap）
// 思路：先倒序预处理出 s[i..n-1] 中最大字符所在下标 d[i]；再从左往右找第一个能被更大字符替换的位置，与 d[i] 交换一次即为最大。
// 时间复杂度：O(n)，两次线性扫描；空间复杂度：O(n)，字符数组与后缀最值下标数组。
class Solution {  // LeetCode 约定的题解类
public:  // 公有接口
    int maximumSwap(int num) {  // 最多交换一次数位，返回能得到的最大值
        string s = to_string(num);  // 转成字符串，方便按下标交换数位
        int n = s.size();  // 位数
        vector<int> d(n);  // d[i] 记录 s[i..n-1] 中最大字符所在的下标
        iota(d.begin(), d.end(), 0);  // iota 依次填入 0,1,2,…：先假设每个位置的最大值就是自己
        for (int i = n - 2; ~i; --i) {  // 从右往左预处理后缀最大值下标，i 从 n-2 递减到 0
            if (s[i] <= s[d[i + 1]]) {  // 右侧后缀的最大字符不小于当前字符
                d[i] = d[i + 1];  // 后缀最大值下标就继承给 d[i]（相等时取靠后的下标，交换后数值更大）
            }
        }  // 结束预处理
        for (int i = 0; i < n; ++i) {  // 从左往右找第一个能变大的位置
            int j = d[i];  // 该位置右侧最大字符的下标
            if (s[i] < s[j]) {  // 后面存在更大的字符，换过来能让整个数变大
                swap(s[i], s[j]);  // 只做这一次交换
                break;  // 交换后已最大，结束循环
            }
        }  // 结束查找
        return stoi(s);  // 字符串转回整数返回
    }  // 结束 maximumSwap
};