// 题目：621. 任务调度器（Task Scheduler）
// 思路：用出现最多的字母构造「桶」——(x-1)*(n+1)+s 给出桶模型的答案，任务总数更多时直接取任务总数。
// 时间复杂度：O(m + 26)，m 为任务个数；空间复杂度：O(26)，只用定长计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int leastInterval(vector<char>& tasks, int n) {  // tasks 是任务字符列表，n 是相同任务之间的冷却间隔
        vector<int> cnt(26);  // 26 个字母的出现次数，题目保证任务字母全是大写 A-Z
        int x = 0;  // 记录最大频次，也就是「出现最多的那个字母出现了几次」
        for (char c : tasks) {  // 遍历所有任务做词频统计
            c -= 'A';  // 把字符映射成 0..25 的下标（c 是循环变量的副本，改它不会影响容器）
            ++cnt[c];  // 该字母计数加一
            x = max(x, cnt[c]);  // 同步刷新最大频次
        }
        int s = 0;  // 统计有多少个字母并列达到最大频次
        for (int v : cnt) {  // 遍历 26 个字母的频次
            s += v == x;  // 比较结果为真时布尔值 1 被累加，等价于并列计数加一
        }
        return max((int) tasks.size(), (x - 1) * (n + 1) + s);  // 两种排布取较大者：能填满桶时用桶公式，任务更多时就是任务总数
    }
};