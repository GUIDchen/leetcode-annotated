// 题目：629. K 个逆序对数组（K Inverse Pairs Array）
// 思路：f[j] 表示当前长度下恰好有 j 个逆序对的排列数；插入新元素只会新增 0..i-1 个逆序对，所以转移是一段定长窗口求和，用前缀和 s 把它压成 O(1)。
// 时间复杂度：O(n * k)，两层递推；空间复杂度：O(k)，只保留一维 f 与前缀和 s。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int kInversePairs(int n, int k) {  // n 是排列长度，k 是要求的逆序对个数，返回方案数对 1e9+7 取模
        int f[k + 1];  // f[j]：当前长度下恰好 j 个逆序对的方案数，用变长数组声明，下标覆盖 0..k
        int s[k + 2];  // s[j]：f 的前缀和，s[j] = f[0] + ... + f[j-1]，多开一位避免 s[k+1] 越界
        memset(f, 0, sizeof(f));  // 先把 f 整体清零，稍后只把 f[0] 单独置 1
        f[0] = 1;  // 边界：长度 0（尚未插入任何元素）时逆序对为 0 的方案数是 1，这是递推起点
        fill(s, s + k + 2, 1);  // 前缀和初值全填 1，等价于长度 0 时 f[0]=1、其余为 0 的前缀和
        s[0] = 0;  // s[0] 必须是 0（空前缀和），所以把上一步填的 1 覆盖掉
        const int mod = 1e9 + 7;  // 取模常量，最终答案要对 1e9+7 取余
        for (int i = 1; i <= n; ++i) {  // 依次计算长度为 1 到 n 的排列
            for (int j = 1; j <= k; ++j) {  // 逐个计算恰好 j 个逆序对的方案数（j=0 的方案数恒为 1，无需更新）
                f[j] = (s[j + 1] - s[max(0, j - (i - 1))] + mod) % mod;  // 窗口和：新增元素贡献 0..i-1 个逆序对，故 f[j] = sum(f_prev[j-t]) = s[j+1] - s[j-(i-1)]；加 mod 是为防负数取模
            }  // j 维转移结束
            for (int j = 1; j <= k + 1; ++j) {  // 用刚算好的 f 重建前缀和数组，供下一轮 i 使用
                s[j] = (s[j - 1] + f[j - 1]) % mod;  // 前缀和递推：s[j] = s[j-1] + f[j-1]
            }  // 前缀和重建结束
        }  // 长度 i 的枚举结束
        return f[k];  // f[k] 即长度为 n 且恰好 k 个逆序对的方案数
    }  // 方法结束
};  // 类定义结束，分号不能省略