# 题目：639. 解码方法 II（Decode Ways II）
# 核心思路：线性 DP 只保留 dp[i-2]、dp[i-1] 两个滚动值；分别考虑「末位单独成码」和「末两位合并成码」，再按字符是否为 * 展开各自的转移。
# 时间复杂度：O(n)，字符串扫一遍；空间复杂度：O(1)，只用三个滚动变量。
class Solution:  # LeetCode 约定的题解类
    def numDecodings(self, s: str) -> int:  # s：含 * 通配符的数字串，返回解码方案数（对 1e9+7 取模）
        mod = int(1e9 + 7)  # 取模常量
        n = len(s)  # 字符串长度

        # dp[i - 2], dp[i - 1], dp[i]
        a, b, c = 0, 1, 0  # a=dp[i-2]、b=dp[i-1]、c=dp[i]；b 初值为 1 代表空串算一种方案
        for i in range(1, n + 1):  # i 表示当前处理的是长度为 i 的前缀
            # 1 digit
            if s[i - 1] == "*":  # 末位是通配符：可以当作 1~9 中任意一个数字
                c = 9 * b % mod  # 9 种单字符解码，各自接在 dp[i-1] 的方案之后
            elif s[i - 1] != "0":  # 末位是 1~9 的确定数字
                c = b  # 只有一种单字符解释，方案数与前一位相同
            else:  # 末位是 0，无法单独解码
                c = 0  # 单字符转移贡献为 0

            # 2 digits
            if i > 1:  # 至少两位才能做「最后两位一起解码」的转移
                if s[i - 2] == "*" and s[i - 1] == "*":  # 两位都是通配符
                    c = (c + 15 * a) % mod  # 11~19 与 21~26 共 15 种合法组合
                elif s[i - 2] == "*":  # 前一位通配、后一位确定
                    if s[i - 1] > "6":  # 个位大于 6，只有 1x 这一种可能
                        c = (c + a) % mod  # 1 种组合
                    else:  # 个位 ≤ 6，1x 与 2x 都合法
                        c = (c + 2 * a) % mod  # 2 种组合
                elif s[i - 1] == "*":  # 前一位确定、后一位通配
                    if s[i - 2] == "1":  # 十位是 1，个位可取 1~9
                        c = (c + 9 * a) % mod  # 9 种组合
                    elif s[i - 2] == "2":  # 十位是 2，个位只能取 1~6
                        c = (c + 6 * a) % mod  # 6 种组合
                elif (  # 两位都是确定数字，判断拼成的数是否落在 1~26
                    s[i - 2] != "0"  # 十位不能是 0
                    and (ord(s[i - 2]) - ord("0")) * 10 + ord(s[i - 1]) - ord("0") <= 26  # 用字符编码算出两位数值，判断不超过 26
                ):  # 两个条件都满足
                    c = (c + a) % mod  # 合法双字符解码，接上 dp[i-2] 的方案数

            a, b = b, c  # 滚动前进：dp[i-2] ← dp[i-1]，dp[i-1] ← dp[i]

        return c  # 返回 dp[n]，即整串的解码方案数
