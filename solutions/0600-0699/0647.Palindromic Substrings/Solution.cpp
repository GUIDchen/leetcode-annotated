// 题目：647. 回文子串（Palindromic Substrings）
// 思路：中心扩展法，把 n 个字符的所有 2n-1 个回文中心（单字符中心与两字符之间的间隙中心）依次向两侧扩展并计数。
// 时间复杂度：O(n^2)，每个中心最多扩展 O(n) 次；空间复杂度：O(1)，只用到常数个下标变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countSubstrings(string s) {  // s 是输入字符串，返回回文子串的个数（相同内容出现在不同位置分别计数）
        int ans = 0;  // 回文子串计数器
        int n = s.size();  // 字符串长度，循环边界与下标计算都要用
        for (int k = 0; k < n * 2 - 1; ++k) {  // 枚举 2n-1 个回文中心
            int i = k / 2, j = (k + 1) / 2;  // k 为偶数时 i == j（单字符中心），k 为奇数时 i 与 j 相邻（间隙中心）
            while (~i && j < n && s[i] == s[j]) {  // 左界未到 -1（~(-1) == 0）、右界未越界且两端字符相等，就继续向外扩
                ++ans;  // 当前这一层又扩展出一个回文子串
                --i;  // 左指针左移一位
                ++j;  // 右指针右移一位
            }
        }
        return ans;  // 返回所有回文子串的总数
    }
};