// 题目：76. 最小覆盖子串（Minimum Window Substring）
// 思路：滑动窗口 + 计数数组。右指针扩张窗口并维护「已凑齐的字符数」cnt，当 cnt == len(t) 时收缩左指针，边收缩边记录最短窗口。
// 时间复杂度：O(m + n)，左右指针各自最多移动 m 步、统计 t 需要 n 步；空间复杂度：O(Σ)，两个长度 128 的计数数组（字符集大小）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string minWindow(string s, string t) {  // s 是长串，t 是需要被完整覆盖的目标子串
        vector<int> need(128, 0);  // need[c] 记录字符 c 在 t 中需要出现多少次（按 ASCII 共 128 个字符建表）
        vector<int> window(128, 0);  // window[c] 记录字符 c 在当前窗口里实际出现了多少次
        for (char c : t) {  // 遍历 t，统计每个字符的需求量
            ++need[c];  // 字符 c 的需求数加一
        }

        int m = s.length(), n = t.length();  // m 是 s 的长度，n 是 t 的长度（即需要凑齐的字符总数）
        int k = -1, mi = m + 1, cnt = 0;  // k 是最短窗口起点，mi 是最短窗口长度（初值 m+1 表示还没有答案），cnt 是已满足需求的字符个数

        for (int l = 0, r = 0; r < m; ++r) {  // 滑动窗口：l 为左边界、r 为右边界，每轮把 s[r] 纳入窗口
            char c = s[r];  // 当前新纳入窗口的字符
            if (++window[c] <= need[c]) {  // 先把它计入窗口计数；若仍不超过需求量，说明这个字符是「有效贡献」
                ++cnt;  // 有效字符数加一，表示又凑齐了一个名额
            }

            while (cnt == n) {  // 窗口已经覆盖 t 的全部字符，于是尝试右移左边界寻找更短的解
                if (r - l + 1 < mi) {  // 当前窗口长度 r-l+1 比已知最短窗口更短
                    mi = r - l + 1;  // 更新最短长度
                    k = l;  // 同时记下这个最短窗口的起点
                }

                c = s[l];  // 取出即将被移出窗口的左端字符
                if (window[c] <= need[c]) {  // 移除它会让某个有效字符变少（计数不多于需求量正说明它是有效贡献）
                    --cnt;  // 有效字符数减一，窗口即将不再覆盖 t，从而退出 while
                }
                --window[c];  // 把该字符从窗口计数里减掉
                ++l;  // 左边界右移，完成一次收缩
            }
        }

        return k < 0 ? "" : s.substr(k, mi);  // k<0 说明从未找到可行窗口，返回空串；否则从 k 开始截取长度为 mi 的最短窗口
    }
};
