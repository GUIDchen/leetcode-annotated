// 题目：7. 整数反转（Reverse Integer）
// 思路：不断取末位（x % 10）拼到答案末尾；每次拼接前用 INT_MAX/10、INT_MIN/10 预判溢出，溢出立即返回 0。
// 时间复杂度：O(log|x|)，循环次数即十进制位数；空间复杂度：O(1)，只用常数个变量。
int reverse(int x) {  // x 为待反转的 32 位有符号整数
    int ans = 0;  // 保存反转过程中的结果
    for (; x != 0; x /= 10) {  // 每轮取末位拼到 ans 上，然后 x 去掉末位
        if (ans > INT_MAX / 10 || ans < INT_MIN / 10) {  // 再乘 10 就会越界，提前判断（这里用除法避免溢出）
            return 0;  // 按题意溢出时返回 0
        }
        ans = ans * 10 + x % 10;  // 把 x 的末位接到 ans 末尾；C 的 % 符号随被除数，负数也能正确拼接
    }
    return ans;  // x 已变成 0，返回反转结果
}