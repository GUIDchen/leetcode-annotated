# 题目：7. 整数反转（Reverse Integer）
# 思路：循环取末位拼到结果末尾；每轮先用上下界预判溢出，越界返回 0。为与 C/C++ 的截断除法一致，负数取余后要手动修正末位。
# 时间复杂度：O(log|x|)，循环次数即十进制位数；空间复杂度：O(1)。
class Solution:  # LeetCode 约定的题解类
    def reverse(self, x: int) -> int:  # x 为待反转的整数，可能为负
        ans = 0  # 反转结果累加器
        mi, mx = -(2**31), 2**31 - 1  # 32 位有符号整数的上下界
        while x:  # x 不为 0 时持续处理
            if ans < mi // 10 + 1 or ans > mx // 10:  # 预判再乘 10 是否越界；负数侧用 mi // 10 + 1 是因为 Python 的 // 向下取整
                return 0  # 越界按题意返回 0
            y = x % 10  # Python 的 % 结果恒非负，负数取余会得到正数
            if x < 0 and y > 0:  # 负数场景下把余数修正成负数
                y -= 10  # 减 10 得到真正的末位
            ans = ans * 10 + y  # 把末位拼到结果末尾
            x = (x - y) // 10  # 先减去末位再整除 10，保证对负数也是向 0 取整地去掉末位
        return ans  # 返回反转结果
