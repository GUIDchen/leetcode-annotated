// 题目：26. 删除有序数组中的重复项（Remove Duplicates from Sorted Array）
// 思路：双指针原地覆盖。k 是已去重区间的长度（下一个可写位置），用快指针 x 顺序扫过数组，遇到与已保留的最后一个元素不同的值就写到 k 位置。因为数组有序，重复元素必然相邻，所以只需和 nums[k-1] 比较。
// 时间复杂度：O(n)，每个元素只被访问一次；空间复杂度：O(1)，只用了常数个额外变量，答案在 nums 上原地构造。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int removeDuplicates(vector<int>& nums) {  // nums：升序数组（按引用传入，允许原地修改），返回去重后的长度
        int k = 0;  // k 既是已保留的不重复元素个数，也是下一个待写入的位置下标
        for (int x : nums) {  // 用范围 for 顺序读取每个元素 x；k 始终不大于当前下标，所以写 nums[k] 不会覆盖还没读到的值
            if (k == 0 || x != nums[k - 1]) {  // k == 0 说明是第一个元素；否则比较 x 与已保留的最后一个值，不同才是新值
                nums[k++] = x;  // 把新值写到前 k 个位置之后，并把长度 k 加一；后置 ++ 先取值再自增
            }
        }
        return k;  // 返回去重后的元素个数，前 k 个位置就是题目要求的有效部分
    }
};
