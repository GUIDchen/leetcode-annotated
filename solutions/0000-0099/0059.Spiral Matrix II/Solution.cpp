// 题目：59. 螺旋矩阵 II（Spiral Matrix II）
// 思路：模拟填数，方向向量按「右→下→左→上」循环使用；每格先写值，再试探下一格是否出界或已填过，若是则换向。
// 时间复杂度：O(n^2)，n*n 个格子各填一次；空间复杂度：O(1) 额外空间（返回值矩阵本身占 O(n^2)）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<vector<int>> generateMatrix(int n) {  // n：矩阵边长，返回 n×n 的螺旋填充矩阵
        vector<vector<int>> ans(n, vector<int>(n, 0));  // 结果矩阵全部初始化为 0，用 0 表示「这一格还空着」
        const int dirs[5] = {0, 1, 0, -1, 0};  // 方向编码：相邻两项构成一个位移对，(0,1) 右、(1,0) 下、(0,-1) 左、(-1,0) 上；末尾多存一个 0 使 k+1 不越界
        int i = 0, j = 0, k = 0;  // (i, j) 是当前填数的坐标，从左上角出发；k 是当前方向编号
        for (int v = 1; v <= n * n; ++v) {  // 依次填入 1、2……直到 n*n
            ans[i][j] = v;  // 先把当前数字写到脚下这一格
            int x = i + dirs[k], y = j + dirs[k + 1];  // 沿当前方向算出下一格的坐标，只试探不落子
            if (x < 0 || x >= n || y < 0 || y >= n || ans[x][y] != 0) {  // 下一格出界，或已被占用（值非 0）
                k = (k + 1) % 4;  // 顺时针换到下一个方向；%4 让方向在四个编号里循环
            }
            i += dirs[k];  // 按（可能刚换过的）方向移动到下一行
            j += dirs[k + 1];  // 同步移动到下一列
        }
        return ans;  // 1..n*n 全部填完，螺旋矩阵构造结束
    }
};
