// 题目：65. 有效数字（Valid Number）
// 思路：先跳过可选的正负号并排除「孤零零的小数点」，再逐字符扫描：小数点最多一次且不能在指数后，e 最多一次且两侧都要有数。
// 时间复杂度：O(n)，一次线性扫描；空间复杂度：O(1)，只用几个计数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isNumber(string s) {  // s：待判定的字符串，判断它是否是合法十进制数（可带指数）
        int n = s.size();  // 记下长度，后面判边界要用
        int i = 0;  // 扫描起点
        if (s[i] == '+' || s[i] == '-') ++i;  // 开头的正负号是合法的，跳过它（题目保证 s 非空）
        if (i == n) return false;  // 只有符号没有数字，非法
        if (s[i] == '.' && (i + 1 == n || s[i + 1] == 'e' || s[i + 1] == 'E')) return false;  // 小数点后面必须跟数字：'.' 结尾或 '.e' 这种形式都非法
        int dot = 0, e = 0;  // dot 统计小数点出现次数，e 统计指数符号出现次数
        for (int j = i; j < n; ++j) {  // 从符号之后逐字符扫描
            if (s[j] == '.') {  // 遇到小数点
                if (e || dot) return false;  // 指数部分不能再有小数点，且小数点只能出现一次
                ++dot;  // 记录这次小数点
            } else if (s[j] == 'e' || s[j] == 'E') {  // 遇到指数符号
                if (e || j == i || j == n - 1) return false;  // 指数符号只能有一个，前面必须有底数、后面必须有指数
                ++e;  // 记录这个指数符号
                if (s[j + 1] == '+' || s[j + 1] == '-') {  // 指数允许带正负号
                    if (++j == n - 1) return false;  // 把符号位一并跳过；若此时已到串尾，说明缺少指数数字
                }
            } else if (s[j] < '0' || s[j] > '9')  // 既不是小数点、指数符，也不是数字
                return false;  // 出现其它字符，立即判为非法
        }
        return true;  // 所有字符都符合规则，是有效数字
    }
};
