# 题目：12. 整数转罗马数字（Integer to Roman）
# 思路：13 个「符号/数值」按数值从大到小排列，贪心地反复减去最大可用数值并追加符号（含六个减法特例）。
# 时间复杂度：O(1)，输出长度有常数上界；空间复杂度：O(1)，只用了两张常数元组和结果列表。
class Solution:  # LeetCode 约定的题解类
    def intToRoman(self, num: int) -> str:  # num 是待转换的整数（题目范围 1..3999）
        cs = ('M', 'CM', 'D', 'CD', 'C', 'XC', 'L', 'XL', 'X', 'IX', 'V', 'IV', 'I')  # 罗马符号，已拆出六个减法组合
        vs = (1000, 900, 500, 400, 100, 90, 50, 40, 10, 9, 5, 4, 1)  # 与 cs 一一对应的数值，严格递减
        ans = []  # 用列表收集符号片段，最后一次性拼接，避免反复创建字符串
        for c, v in zip(cs, vs):  # 同时取出符号和它的数值
            while num >= v:  # 剩余数值还够减掉 v
                num -= v  # 减去 v，剩下的部分交给更小的符号
                ans.append(c)  # 把符号追加到结果中
        return ''.join(ans)  # 拼接成最终字符串返回
