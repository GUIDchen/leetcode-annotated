// 题目：12. 整数转罗马数字（Integer to Roman）
// 思路：把 13 个「数值 → 符号」按从大到小排列，贪心地反复减去当前最大数值并拼接对应符号（含 CM/CD/XC/XL/IX/IV 六个减法特例）。
// 时间复杂度：O(1)，输出长度有常数上界；空间复杂度：O(1)，结果缓冲区固定 20 字节。
static const char* cs[] = {  // 与下面 vs 一一对应的罗马符号，已把六个减法组合单列出来
    "M", "CM", "D", "CD", "C", "XC",
    "L", "XL", "X", "IX", "V", "IV", "I"};

static const int vs[] = {  // 对应符号代表的数值，严格递减
    1000, 900, 500, 400, 100, 90,
    50, 40, 10, 9, 5, 4, 1};

char* intToRoman(int num) {  // num 是待转换的整数（题目范围 1..3999）
    static char ans[20];  // static 缓冲区，函数返回后依然有效；20 字节足够放下最长的罗马数字
    ans[0] = '\0';  // 置为空串，让后面的 strcat 有一个合法的 '\0' 结尾起点
    for (int i = 0; i < 13; ++i) {  // 从最大的符号开始贪心尝试
        while (num >= vs[i]) {  // 剩余数值还够减这个符号的数值
            num -= vs[i];  // 减去该数值，相当于“用掉”这个符号
            strcat(ans, cs[i]);  // 把对应符号追加到结果串末尾
        }
    }
    return ans;  // 返回转换结果
}
