// 题目：91. 解码方法（Decode Ways）
// 思路：线性 DP，f[i] 表示前 i 个字符的解码方案数；第 i 位可单独解码，也可与前一位组合成 10~26 再解码。
// 时间复杂度：O(n)，一次线性扫描；空间复杂度：O(n)，保存长度为 n+1 的 DP 数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numDecodings(string s) {  // s 是只含数字的字符串，返回解码方案总数
        int n = s.size();  // 字符串长度，决定 DP 数组大小
        int f[n + 1];  // f[i]：前 i 个字符的解码方案数
        memset(f, 0, sizeof(f));  // 全部清零，保证未填的位置不会残留垃圾值
        f[0] = 1;  // 边界：空串视为一种解码方式，是后续转移的基础
        for (int i = 1; i <= n; ++i) {  // 从小到大递推每一位
            if (s[i - 1] != '0') {  // 当前位不是 '0'，才能单独解码成一个字母
                f[i] = f[i - 1];  // 单独解码这一位：方案数继承前 i-1 位
            }
            if (i > 1 && (s[i - 2] == '1' || s[i - 2] == '2' && s[i - 1] <= '6')) {  // 前一位是 1，或前一位是 2 且当前位不超过 6，即两位可组成 10~26
                f[i] += f[i - 2];  // 两位合起来解码：累加前 i-2 位的方案数
            }
        }
        return f[n];  // 前 n 个字符的方案数即答案
    }
};
