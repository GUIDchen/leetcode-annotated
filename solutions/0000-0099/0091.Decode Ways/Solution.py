# 题目：91. 解码方法（Decode Ways）
# 思路：线性 DP，f[i] 表示前 i 个字符的解码方案数；第 i 位可单独解码，也可与前一位组成 10~26 后一起解码。
# 时间复杂度：O(n)，只扫一遍字符串；空间复杂度：O(n)，保存长度为 n+1 的 DP 列表。
class Solution:  # LeetCode 约定的题解类
    def numDecodings(self, s: str) -> int:  # s 是数字字符串，返回解码方案总数
        n = len(s)  # 字符串长度，决定 DP 列表大小
        f = [1] + [0] * n  # f[0] = 1 是空串的边界；其余位置先置 0
        for i, c in enumerate(s, 1):  # 从 1 开始编号，i 表示当前处理到第 i 个字符
            if c != "0":  # 当前字符不是 '0' 才能单独解码成字母
                f[i] = f[i - 1]  # 单独解码当前位：方案数沿用前 i-1 位
            if i > 1 and s[i - 2] != "0" and int(s[i - 2 : i]) <= 26:  # 两位都不含前导 0 且数值不超过 26，才能合起来解码
                f[i] += f[i - 2]  # 合起来解码：再累加前 i-2 位的方案数
        return f[n]  # 前 n 个字符的方案数即答案
