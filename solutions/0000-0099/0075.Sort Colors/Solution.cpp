// 题目：75. 颜色分类（Sort Colors）
// 思路：三指针一次扫描。i 是 0 区的右边界，j 是 2 区的左边界，k 是当前扫描位；遇到 0 换到前面，遇到 2 换到后面，遇到 1 直接跳过。
// 时间复杂度：O(n)，每个元素至多被交换常数次；空间复杂度：O(1)，只用了三个指针。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    void sortColors(vector<int>& nums) {  // nums 里只有 0/1/2 三种值，要求原地排序成 0、1、2 依次排列
        int i = -1, j = nums.size(), k = 0;  // i 是 0 区右边界（-1 表示还没有 0），j 是 2 区左边界，k 是当前扫描位置
        while (k < j) {  // k 与 j 相遇时中间只剩 1，原地就绪，可以结束扫描
            if (nums[k] == 0) {  // 当前元素是 0，它应该被换到最前面的 0 区
                swap(nums[++i], nums[k++]);  // i 先右移一位作为 0 区新边界再交换；k 同步右移，因为换过来的一定是 1
            } else if (nums[k] == 2) {  // 当前元素是 2，它应该被换到最后面的 2 区
                swap(nums[--j], nums[k]);  // j 先左移一位作为 2 区新起点再交换；k 不动，因为换到 k 的元素还没检查过
            } else {  // 当前元素是 1，属于中间区，位置已经正确
                ++k;  // 直接跳过，继续检查下一个元素
            }
        }
    }
};