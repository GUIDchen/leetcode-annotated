# 题目：75. 颜色分类（Sort Colors）
# 思路：三指针一次扫描。i 是 0 区的右边界，j 是 2 区的左边界，k 是当前扫描位；遇到 0 换到前面，遇到 2 换到后面，遇到 1 直接跳过。
# 时间复杂度：O(n)，每个元素至多被交换常数次；空间复杂度：O(1)，只用了三个指针。
class Solution:  # LeetCode 约定的题解类
    def sortColors(self, nums: List[int]) -> None:  # nums 只含 0/1/2，要求原地排序，函数无返回值
        i, j, k = -1, len(nums), 0  # i 是 0 区右边界（-1 表示还没有 0），j 是 2 区左边界，k 是当前扫描位置
        while k < j:  # k 与 j 相遇时中间只剩 1，原地就绪，可以结束扫描
            if nums[k] == 0:  # 当前元素是 0，应该换到最前面的 0 区
                i += 1  # 0 区的右边界右移一位，腾出新的槽位
                nums[i], nums[k] = nums[k], nums[i]  # 把 0 换到前面（换回来的是 1，所以下面 k 可以直接前进）
                k += 1  # 当前位置已经确认是 1，扫描位右移
            elif nums[k] == 2:  # 当前元素是 2，应该换到最后面的 2 区
                j -= 1  # 2 区的左边界左移一位，腾出新的槽位
                nums[j], nums[k] = nums[k], nums[j]  # 把 2 换到后面；k 不动，因为换到 k 的元素还没检查过
            else:  # 当前元素是 1，属于中间区，位置已经正确
                k += 1  # 直接跳过，继续检查下一个元素
