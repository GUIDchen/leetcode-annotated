// 题目：62. 不同路径（Unique Paths）
// 思路：二维 DP，f[i][j] 表示走到 (i,j) 的方案数，它只能从上方或左方转移而来，起点初始化为 1。
// 时间复杂度：O(m*n)，每个格子算一次；空间复杂度：O(m*n)，DP 表格。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int uniquePaths(int m, int n) {  // m 行 n 列，返回从左上到右下的路径总数
        vector<vector<int>> f(m, vector<int>(n));  // DP 表，值初始化全为 0：f[i][j] 表示到达 (i,j) 的路径数
        f[0][0] = 1;  // 起点只有「原地不动」这一种方案，作为递推的基准值
        for (int i = 0; i < m; ++i) {  // 按行从上到下
            for (int j = 0; j < n; ++j) {  // 每行内从左到右，保证用到的上方、左方格已算好
                if (i) {  // 第一行没有上方格子，跳过
                    f[i][j] += f[i - 1][j];  // 从上方走下来，把上方的方案数累加进来
                }
                if (j) {  // 第一列没有左方格子，跳过
                    f[i][j] += f[i][j - 1];  // 从左方走过来，把左方的方案数累加进来
                }
            }
        }
        return f[m - 1][n - 1];  // 右下角的值就是所有走法总数
    }
};
