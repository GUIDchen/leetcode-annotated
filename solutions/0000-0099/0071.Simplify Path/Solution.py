# 题目：71. 简化路径（Simplify Path）
# 思路：用 '/' 切分路径，借助列表当栈：空串与 '.' 跳过，'..' 在栈非空时弹栈，其余目录名入栈，最后用 '/' 连接成规范路径。
# 时间复杂度：O(n)，每个字符只被处理常数次；空间复杂度：O(n)，栈中最多保存全部目录名。
class Solution:  # LeetCode 约定的题解类
    def simplifyPath(self, path: str) -> str:  # path：待简化的绝对路径
        stk = []  # 用列表当栈，存放已经确定的目录名
        for s in path.split('/'):  # 以 '/' 切分，逐个处理每段（连续斜杠会产生空串）
            if not s or s == '.':  # 空串（多余斜杠）和 '.'（当前目录）都不影响路径
                continue  # 跳过这一段
            if s == '..':  # '..' 表示返回上一级目录
                if stk:  # 栈非空才能回退；已在根目录时继续向上仍停在根目录
                    stk.pop()  # 弹出最后一个目录，相当于返回上一级
            else:
                stk.append(s)  # 普通目录名压栈，成为路径的一层
        return '/' + '/'.join(stk)  # 以 '/' 开头，各目录之间用 '/' 连接；栈空时结果正好是 '/'
