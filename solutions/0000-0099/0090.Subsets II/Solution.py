# 题目：90. 子集 II（Subsets II）
# 思路：先排序让相同的数相邻，再回溯枚举「选 / 不选」；不选的分支把连续的重复值一次跳过，从而去重。
# 时间复杂度：O(n·2^n)，共有 2^n 个子集、每个子集切片复制需 O(n)；空间复杂度：O(n)，递归栈与路径列表 t。
class Solution:  # LeetCode 约定的题解类
    def subsetsWithDup(self, nums: List[int]) -> List[List[int]]:  # nums 可能含重复元素，返回所有不重复子集
        def dfs(i: int):  # 内部回溯函数：从下标 i 开始决定后面的元素选或不选
            if i == len(nums):  # 所有元素都决策完，当前的 t 就是一个完整子集
                ans.append(t[:])  # 复制一份 t 放进答案，否则后面修改 t 会污染已有结果
                return  # 递归出口：返回上一层继续尝试其他分支
            t.append(nums[i])  # 分支一：把 nums[i] 选入当前子集
            dfs(i + 1)  # 选中之后继续决策下一个元素
            x = t.pop()  # 撤销选择，并记下刚弹出的值，用于判断后面还有多少重复值
            while i + 1 < len(nums) and nums[i + 1] == x:  # 分支二：不选这个值，同时跨过后面与它相同的元素
                i += 1  # 跳过重复值，避免同一层重复枚举出相同子集
            dfs(i + 1)  # 从重复段之后的第一个下标继续递归

        nums.sort()  # 排序让相同元素相邻，去重判断才成立
        ans = []  # 结果列表：收集所有不重复子集
        t = []  # 回溯路径：当前正在构造的子集
        dfs(0)  # 从下标 0 开始回溯（此处才真正调用，ans / t 已就绪）
        return ans  # 返回所有不重复子集
