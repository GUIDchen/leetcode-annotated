# 题目：58. 最后一个单词的长度（Length of Last Word）
# 思路：下标 i 从串尾跳过所有空格，下标 j 从 i 往前扫到前一个空格之前，返回值 i - j 就是最后一个单词的长度。
# 时间复杂度：O(n)，i、j 各扫描一遍字符串；空间复杂度：O(1)，只用了两个整型下标。
class Solution:  # LeetCode 约定的题解类
    def lengthOfLastWord(self, s: str) -> int:  # s：由单词与空格组成的输入串
        i = len(s) - 1  # i 先指向最后一个字符，从右往左处理
        while i >= 0 and s[i] == ' ':  # 先判断不越界（i >= 0），再看当前字符是不是空格
            i -= 1  # 尾部空格不计入长度，跳过
        j = i  # j 从最后一个单词的末字符开始，用来找它的左边界
        while j >= 0 and s[j] != ' ':  # 还在串内且没遇到空格，说明仍处在最后一个单词里
            j -= 1  # 继续左移，扩大单词的宽度
        return i - j  # i 是末字符下标，j 是其左侧空格下标，差值正好是单词长度
