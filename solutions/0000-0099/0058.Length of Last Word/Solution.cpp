// 题目：58. 最后一个单词的长度（Length of Last Word）
// 思路：从串尾出发，先用指针 i 跳过所有尾随空格，再用指针 j 从 i 往前扫到前一个空格为止，两下标之差即单词长度。
// 时间复杂度：O(n)，i 与 j 各自最多扫完整串；空间复杂度：O(1)，只用了两个下标变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int lengthOfLastWord(string s) {  // s：由单词与空格组成的输入串
        int i = s.size() - 1;  // i 先指向最后一个字符，准备从右往左处理
        while (~i && s[i] == ' ') {  // ~i 为 0 表示 i 已经变成 -1（越过左边界）；当前字符是空格就继续后退
            --i;  // 尾随空格不属于最后一个单词，直接跳过
        }
        int j = i;  // j 从最后一个单词的末字符出发，负责找它的左边界
        while (~j && s[j] != ' ') {  // 只要还在串内且没撞到空格，就一直往前走
            --j;  // 每退一步说明又吃掉一个单词字符
        }
        return i - j;  // i 停在单词末字符，j 停在其左侧空格处，差值恰好是单词长度
    }
};
