# 题目：38. 外观数列（Count and Say）
# 思路：从 '1' 出发迭代 n-1 轮，每轮把上一项按连续相同字符分组，写成「个数 + 数字」并拼接，得到下一项。
# 时间复杂度：O(n · L)，L 为最终串长度（每轮扫一遍上一项）；空间复杂度：O(L)，结果列表与字符串。
class Solution:  # LeetCode 约定的题解类
    def countAndSay(self, n: int) -> str:  # n 表示要求外观数列的第 n 项（从 1 开始计数）
        s = '1'  # 外观数列的第一项固定是 '1'
        for _ in range(n - 1):  # 需要从第 1 项推导到第 n 项，所以共迭代 n-1 轮；循环变量不用，写作 _
            i = 0  # i 是当前这一段的起点，段尾由内层 while 计算
            t = []  # 本轮结果先用列表收集，最后 join，避免字符串反复拼接
            while i < len(s):  # 只要还有字符没处理完就继续分段
                j = i  # j 从 i 出发，寻找这段连续相同字符的右边界
                while j < len(s) and s[j] == s[i]:  # 字符仍是段首字符就继续右移 j
                    j += 1  # 把 j 推进到段尾之后（此时 s[i:j] 是同一段）
                t.append(str(j - i))  # 先记录这一段的长度，即「读法」里的个数
                t.append(str(s[i]))  # 再记录这一段的字符本身
                i = j  # i 跳到下一段起点，跳过刚统计过的部分
            s = ''.join(t)  # 把本轮结果拼成一个字符串，作为下一轮的输入
        return s  # 迭代完成，s 就是第 n 项
