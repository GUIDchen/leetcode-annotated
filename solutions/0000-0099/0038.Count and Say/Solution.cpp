// 题目：38. 外观数列（Count and Say）
// 思路：从 "1" 出发迭代 n-1 轮，每一轮把上一项按「连续相同字符分组」，写成「个数 + 数字」再拼接，得到下一项。
// 时间复杂度：O(n · L)，L 为最终串长度（每轮都要扫一遍上一项）；空间复杂度：O(L)，两个字符串来回倒换。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string countAndSay(int n) {  // n 表示要求外观数列的第 n 项（n 从 1 开始计数）
        string s = "1";  // 外观数列的第一项固定是字符串 "1"
        while (--n) {  // 先自减再判断：共需要从第 1 项推导到第 n 项，也就是 n-1 轮
            string t = "";  // 本轮的结果串，初始为空，后面逐段拼接
            for (int i = 0; i < s.size();) {  // i 是当前这一段的起点；循环体内手动把 i 推到下一段，所以这里不写 ++i
                int j = i;  // j 从 i 出发，用来找这一段连续相同字符的右边界
                while (j < s.size() && s[j] == s[i]) ++j;  // 只要还没越界且字符仍与段首相同，就把 j 往后推
                t += to_string(j - i);  // 先写这一段的长度（个数）
                t += s[i];  // 再写这一段的字符本身
                i = j;  // i 直接跳到下一段起点，跳过刚刚统计过的部分
            }  // 内层 for 结束
            s = t;  // 用本轮结果覆盖上一项，进入下一轮
        }  // while 结束
        return s;  // 迭代完成后 s 就是第 n 项
    }  // 方法结束
};  // 类定义结束
