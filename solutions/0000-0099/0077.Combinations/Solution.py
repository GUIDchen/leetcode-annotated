# 题目：77. 组合（Combinations）
# 思路：回溯 + 子集枚举。对 1..n 的每个数做「选或不选」的二叉决策，路径 t 选够 k 个数就收集答案，否则继续向下决策或剪枝。
# 时间复杂度：O(C(n,k) * k)，共 C(n,k) 个答案、每个答案要拷贝 k 个元素；空间复杂度：O(k)，递归栈深度与路径长度。
class Solution:  # LeetCode 约定的题解类
    def combine(self, n: int, k: int) -> List[List[int]]:  # 从 1..n 中选出 k 个数，返回全部组合
        def dfs(i: int):  # 递归函数：i 是当前要决定「选不选」的数字
            if len(t) == k:  # 已经选够 k 个数，得到一个合法组合
                ans.append(t[:])  # 用 t[:] 拷贝一份存入答案，否则后续修改 t 会污染结果
                return  # 长度已够，不必继续往下决策，回溯
            if i > n:  # 数字已经超过 n，说明这条路径再也凑不齐 k 个数
                return  # 直接剪枝返回
            t.append(i)  # 分支一：把数字 i 选入当前组合
            dfs(i + 1)  # 递归处理下一个数字
            t.pop()  # 撤销选择、恢复现场，才能尝试「不选 i」的另一条分支
            dfs(i + 1)  # 分支二：不选数字 i，直接处理下一个数字

        ans = []  # 收集所有满足长度要求的组合
        t = []  # 当前正在构造的组合（回溯路径）
        dfs(1)  # 从数字 1 开始做「选或不选」的决策
        return ans  # 返回收集到的全部组合
