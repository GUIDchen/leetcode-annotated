// 题目：9. 回文数（Palindrome Number）
// 思路：只反转后一半数字，反转值追上剩余部分即停止，再比较两段是否相同（奇数位时去掉中间位再比）。
// 时间复杂度：O(log x)，只处理一半位数；空间复杂度：O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isPalindrome(int x) {  // 判断整数 x 是否为回文数
        if (x < 0 || (x && x % 10 == 0)) {  // 负数不是回文；末位为 0 的非零整数也不是（x 为 0 时放行）
            return false;  // 提前判负，省掉后续反转
        }
        int y = 0;  // 反转出的后半段数字
        for (; y < x; x /= 10) {  // 循环条件「后半段还没追上剩余部分」；每轮 x 去掉末位
            y = y * 10 + x % 10;  // 把 x 的末位并入 y
        }
        return x == y || x == y / 10;  // 偶数位时 x == y；奇数位时去掉中间位（y / 10）再比较
    }
};