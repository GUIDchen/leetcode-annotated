// 题目：9. 回文数（Palindrome Number）
// 思路：只反转后一半数字，当反转值 y 追上（或超过）剩余部分 x 时停止，再比较 x == y（偶数位）或 x == y / 10（奇数位）。
// 时间复杂度：O(log x)，处理一半的十进制位数；空间复杂度：O(1)。
bool isPalindrome(int x) {  // 判断整数 x 是否为回文数
    if (x < 0 || (x != 0 && x % 10 == 0)) {  // 负数一定不是回文；末位为 0 的非零正整数反过来会丢掉前导零，也不是回文
        return false;  // 直接判负
    }

    int y = 0;  // 存放反转出来的后半段数字
    while (y < x) {  // 只反转到一半：后半段还没追上剩余部分时继续
        y = y * 10 + x % 10;  // 把 x 的末位拼到 y 末尾
        x /= 10;  // x 去掉已处理的末位
    }

    return (x == y || x == y / 10);  // 偶数位时两段相等；奇数位时 y 多一位（中间位），用 y / 10 去掉中间位再比
}
