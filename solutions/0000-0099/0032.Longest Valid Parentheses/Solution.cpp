// 题目：32. 最长有效括号（Longest Valid Parentheses）
// 思路：动态规划。f[i] 表示「以第 i 个字符（1 起）结尾」的最长有效括号长度。若 s[i-1] == ')'：前一个是 '(' 则 f[i] = f[i-2] + 2；前一个也是 ')' 则先跳过 f[i-1] 段，看它前面那个字符能否与当前 ')' 配对，能则 f[i] = f[i-1] + 2 + f[j-1]，最后取所有 f 的最大值。
// 时间复杂度：O(n)，每个位置常数次判断；空间复杂度：O(n)，f 数组记录以每个位置结尾的最优值。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int longestValidParentheses(string s) {  // s：只含 '(' 和 ')' 的字符串，返回最长有效括号子串长度
        int n = s.size();  // 字符串长度
        int f[n + 1];  // f[i]：以第 i 个字符结尾（1 起编号）的最长有效括号长度；多开一位便于 1 起访问
        memset(f, 0, sizeof(f));  // 全部初始化为 0，末尾为 ')' 且无法配对的情况自然保持 0
        for (int i = 2; i <= n; ++i) {  // 从第 2 个字符开始，长度为 1 的子串不可能有效
            if (s[i - 1] == ')') {  // 只有以右括号结尾才可能形成有效串；s[i-1] 是 0 起下标写法
                if (s[i - 2] == '(') {  // 前一个字符是左括号，直接与当前右括号配对
                    f[i] = f[i - 2] + 2;  // 再拼上以 i-2 结尾的有效段（可能为 0），长度加 2
                } else {  // 前一个字符也是右括号，说明有一段已配好的括号被夹在中间
                    int j = i - f[i - 1] - 1;  // j 是跳过那段有效括号后，i 前面第一个未配对的字符位置（1 起）
                    if (j && s[j - 1] == '(') {  // j 存在且它正好是左括号，就能与当前右括号配对
                        f[i] = f[i - 1] + 2 + f[j - 1];  // 中间段 + 新配对的两个括号 + 更左边可能存在的有效段
                    }
                }
            }
        }
        return *max_element(f, f + n + 1);  // 取所有以某位置结尾的答案中的最大值；空串时返回 0
    }
};
