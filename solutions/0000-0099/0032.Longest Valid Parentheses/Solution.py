# 题目：32. 最长有效括号（Longest Valid Parentheses）
# 思路：动态规划。f[i] 表示「以第 i 个字符（1 起编号）结尾」的最长有效括号长度。遇到 ')' 时：前一个是 '(' 则 f[i] = f[i-2] + 2；前一个也是 ')' 则跳过 f[i-1] 段，看它前面那个字符能否与当前 ')' 配对，能则 f[i] = f[i-1] + 2 + f[j-1]。最终答案是 f 的最大值。
# 时间复杂度：O(n)，每个位置常数次判断；空间复杂度：O(n)，需要一个长度为 n+1 的 DP 数组。
class Solution:  # LeetCode 约定的题解类
    def longestValidParentheses(self, s: str) -> int:  # s：只含 '(' 和 ')' 的字符串，返回最长有效括号子串长度
        n = len(s)  # 字符串长度
        f = [0] * (n + 1)  # f[i] 表示以第 i 个字符结尾（1 起编号）的最长有效括号长度，多开一位方便 1 起访问
        for i, c in enumerate(s, 1):  # enumerate 从 1 开始编号，i 与 DP 下标一一对应，c 是当前字符
            if c == ")":  # 只有以右括号结尾才可能构成有效串
                if i > 1 and s[i - 2] == "(":  # 前一个字符是左括号（i > 1 防越界），可以直接配对
                    f[i] = f[i - 2] + 2  # 拼上以 i-2 结尾的有效段（可能为 0），长度加 2
                else:  # 前一个字符也是右括号，说明中间夹着一段已配好的括号
                    j = i - f[i - 1] - 1  # j 是跳过那段有效括号后，i 前面第一个待配对字符的位置（1 起）
                    if j and s[j - 1] == "(":  # j 存在且正好是左括号，就能与当前右括号配对
                        f[i] = f[i - 1] + 2 + f[j - 1]  # 中间段 + 新配对的 2 个括号 + 更左边可能存在的有效段
        return max(f)  # 取所有位置结尾方案的最长值；空串时 f 全 0，返回 0
