# 题目：43. 字符串相乘（Multiply Strings）
# 核心思路：模拟竖式乘法，用数组按位累加所有位对的乘积，再从低位到高位统一处理进位，最后跳过高位前导零输出。
# 时间复杂度：O(m·n)，两层循环遍历所有位对；空间复杂度：O(m+n)，结果数组的长度。
class Solution:  # LeetCode 约定的题解类
    def multiply(self, num1: str, num2: str) -> str:  # num1、num2 是两个非负整数的十进制字符串，返回乘积的十进制字符串
        if num1 == "0" or num2 == "0":  # 任一因数为 0，乘积必然是 0，直接返回省去后续计算
            return "0"  # 返回字符串形式的零
        m, n = len(num1), len(num2)  # 两个数的位数
        arr = [0] * (m + n)  # 乘积最多 m+n 位，先用 0 填满；arr 存每一位尚未处理进位的数值
        for i in range(m - 1, -1, -1):  # num1 从个位开始，从右往左逐位参与相乘
            a = int(num1[i])  # 字符转数字：取出当前位的数值
            for j in range(n - 1, -1, -1):  # num2 也从个位开始，从右往左逐位相乘
                b = int(num2[j])  # 字符转数字：取出当前位的数值
                arr[i + j + 1] += a * b  # 第 i 位与第 j 位的乘积累加到结果下标 i+j+1 上（个位对齐在末尾）
        for i in range(m + n - 1, 0, -1):  # 从最低位往高位处理进位；循环到下标 1 为止，下标 0 没有更低位可进
            arr[i - 1] += arr[i] // 10  # 把当前位的十位以上部分进位给高位
            arr[i] %= 10  # 当前位只保留个位数
        i = 0 if arr[0] else 1  # 最高位为 0 说明没有进位，从下标 1 开始以免输出前导零
        return "".join(str(x) for x in arr[i:])  # 把有效位逐个转成字符后拼接成结果字符串
