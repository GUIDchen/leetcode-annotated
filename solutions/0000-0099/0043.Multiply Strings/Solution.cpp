// 题目：43. 字符串相乘（Multiply Strings）
// 核心思路：模拟竖式乘法，用数组按位累加所有位对的乘积，再从低位到高位统一处理进位，最后跳过高位前导零输出。
// 时间复杂度：O(m·n)，两层循环遍历所有位对；空间复杂度：O(m+n)，结果数组的长度。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string multiply(string num1, string num2) {  // num1、num2 是两个非负整数的十进制字符串，返回乘积的十进制字符串
        if (num1 == "0" || num2 == "0") {  // 任一因数为 0，乘积必然是 0，直接返回省去后续计算
            return "0";  // 返回字符串形式的零
        }
        int m = num1.size(), n = num2.size();  // 两个数的位数
        vector<int> arr(m + n);  // 乘积最多 m+n 位，arr 里存每一位尚未处理进位的数值
        for (int i = m - 1; i >= 0; --i) {  // num1 从个位开始，从右往左逐位参与相乘
            int a = num1[i] - '0';  // 字符转数字：取出当前位的数值
            for (int j = n - 1; j >= 0; --j) {  // num2 也从个位开始，从右往左逐位相乘
                int b = num2[j] - '0';  // 字符转数字：取出当前位的数值
                arr[i + j + 1] += a * b;  // 第 i 位与第 j 位的乘积累加到结果下标 i+j+1 上（个位对齐在末尾）
            }
        }
        for (int i = arr.size() - 1; i; --i) {  // 从最低位往高位处理进位；循环条件写成 i 表示下标 0 不再进位
            arr[i - 1] += arr[i] / 10;  // 把当前位的十位以上部分进位给高位
            arr[i] %= 10;  // 当前位只保留个位数
        }
        int i = arr[0] ? 0 : 1;  // 最高位为 0 说明没有进位，从下标 1 开始以免输出前导零
        string ans;  // 存放最终的乘积字符串
        for (; i < arr.size(); ++i) {  // 从确定好的起始下标开始逐位输出
            ans += '0' + arr[i];  // 数字加 '0' 转成字符后追加到结果末尾
        }
        return ans;  // 返回乘积字符串
    }
};
