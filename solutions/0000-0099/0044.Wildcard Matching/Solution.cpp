// 题目：44. 通配符匹配（Wildcard Matching）
// 核心思路：递归 + 记忆化搜索，(i, j) 表示 s 从 i、p 从 j 起能否匹配；'?' 通配任意单字符，'*' 既可匹配空串也可多吃一个 s 的字符。
// 时间复杂度：O(m·n)，每个状态只计算一次；空间复杂度：O(m·n)，记忆化数组加递归栈。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isMatch(string s, string p) {  // s 是待匹配串，p 是含 ? 与 * 的模式串，返回能否完全匹配
        int m = s.size(), n = p.size();  // 两个串的长度
        vector<vector<int>> f(m + 1, vector<int>(n + 1, -1));  // 记忆化数组：-1 表示未计算，1 表示真，0 表示假（用 int 存三态）
        function<bool(int, int)> dfs = [&](int i, int j) {  // dfs(i, j)：s 从下标 i、p 从下标 j 开始能否匹配
            if (i >= m) {  // s 已经用完了，只需看 p 剩下的部分能否匹配空串
                return j >= n || (p[j] == '*' && dfs(i, j + 1));  // p 也读完才算成功；否则当前位是 * 可匹配空串，继续往后看
            }
            if (j >= n) {  // s 还有剩余而 p 已用尽，无论怎样都匹配不上
                return false;  // 返回不匹配
            }
            if (f[i][j] != -1) {  // 这个状态算过了，直接复用记忆化结果
                return f[i][j] == 1;  // 把 1/0 还原成布尔值返回
            }
            if (p[j] == '*') {  // 遇到 *：它可以匹配 0 个字符，也可以再多吃掉一个 s 的字符
                f[i][j] = dfs(i + 1, j) || dfs(i, j + 1) ? 1 : 0;  // 两种分支只要有一个走通就成功，结果存成 1/0
            } else {  // 否则是普通字符或 ?：必须消耗 s 的一个字符
                f[i][j] = (p[j] == '?' || s[i] == p[j]) && dfs(i + 1, j + 1) ? 1 : 0;  // ? 通配任意字符，普通字符要求相等；两种情况都要让两个串同时后移一位
            }
            return f[i][j] == 1;  // 返回本状态的结果
        };
        return dfs(0, 0);  // 从两个串的开头开始匹配
    }
};
