// 题目：31. 下一个排列（Next Permutation）
// 思路：从右往左找第一个「升序对」的下标 i（即 nums[i] < nums[i+1]），再从右往左找第一个比 nums[i] 大的 nums[j]，交换二者，最后把 i 右侧的后缀整体反转成升序，得到刚好比原排列大的下一个字典序排列。若整体降序则说明已是最大排列，直接反转成全升序。
// 时间复杂度：O(n)，三次线性扫描；空间复杂度：O(1)，全部原地操作。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    void nextPermutation(vector<int>& nums) {  // nums：当前排列，要求原地改成下一个字典序更大的排列
        int n = nums.size();  // 数组长度，后续边界计算都要用
        int i = n - 2;  // 从倒数第二个位置开始找「峰顶左侧」的元素（至少留一个右邻居比较）
        while (~i && nums[i] >= nums[i + 1]) {  // ~i 等价于 i != -1；只要右边不比左边大就继续左移，跳过降序尾部
            --i;  // 指针左移一位
        }
        if (~i) {  // 找到 i 说明不是完全降序，存在可以变大的位置
            for (int j = n - 1; j > i; --j) {  // 从最右端往左找第一个大于 nums[i] 的元素，它一定在 i 右侧
                if (nums[j] > nums[i]) {  // 找到比 nums[i] 大的最小元素（因为右边是降序，第一个满足的即最小）
                    swap(nums[i], nums[j]);  // 交换两者，让这一位变大到刚好合适的值
                    break;  // 只需要交换一次，跳出循环
                }
            }
        }
        reverse(nums.begin() + i + 1, nums.end());  // 把 i 后面的后缀反转成升序：i == -1 时 i+1 == 0，正好整体反转
    }
};
