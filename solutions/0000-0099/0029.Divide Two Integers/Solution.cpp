// 题目：29. 两数相除（Divide Two Integers）
// 思路：不允许用乘除和取模，就用「减法 + 倍增」。先把被除数和除数都转成负数，避免 INT_MIN 取相反数溢出；每一轮把除数不断翻倍（同时记录翻了几倍），找到不超过被除数的最大倍数一次减掉，再继续下一轮。
// 时间复杂度：O(log²|a|)，外层每轮至少让被除数减半，内层倍增又是 O(log|a|)；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int divide(int a, int b) {  // a：被除数；b：除数；返回向零截断的商
        if (b == 1) {  // 除数为 1 时商就是被除数本身（也顺带覆盖 a == INT_MIN 的情况，避免后续取反溢出）
            return a;  // 直接返回，省去一轮计算
        }
        if (a == INT_MIN && b == -1) {  // 唯一的溢出场景：最小值除以 -1，真实答案 2^31 超出 int 范围
            return INT_MAX;  // 按题目要求返回 2^31 - 1
        }
        bool sign = (a > 0 && b > 0) || (a < 0 && b < 0);  // 同号得正，异号得负，先记住结果的符号
        a = a > 0 ? -a : a;  // 把被除数统一转成非正数：正数取反，负数保持，这样 INT_MIN 也能安全处理
        b = b > 0 ? -b : b;  // 除数同样统一转成非正数，后续只做负数比较与加法
        int ans = 0;  // ans 累积商（绝对值）
        while (a <= b) {  // 当被除数的绝对值还不少于除数时，说明还能再减一份
            int x = b;  // x 是当前这一份的除数（负数），初始为原始除数
            int cnt = 1;  // cnt 记录 x 是除数的多少倍
            while (x >= -(1 << 30) && a <= x + x) {  // x 还没小于 -2^30（再翻倍会溢出 int），且被除数仍够减两份 x
                x += x;  // 除数翻倍：x = x * 2
                cnt <<= 1;  // 倍数同步翻倍：cnt = cnt * 2
            }
            ans += cnt;  // 这一轮确认可以减掉 cnt 个除数，商累加
            a -= x;  // 从被除数中减掉 cnt 个除数，继续处理剩下的部分
        }
        return sign ? ans : -ans;  // 同号返回正的商，异号返回相反数（向零截断）
    }
};
