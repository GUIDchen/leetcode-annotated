# 题目：29. 两数相除（Divide Two Integers）
# 思路：不允许用乘除和取模，就用「减法 + 倍增」。先把被除数和除数都转成负数，避免 -(2^31) 取相反数后溢出；每轮把除数不断翻倍并记录倍数，凑出不超过被除数的最大一份一次减掉。
# 时间复杂度：O(log²|a|)，外层每轮至少减半、内层倍增是 O(log|a|)；空间复杂度：O(1)，只用常数个变量。
class Solution:  # LeetCode 约定的题解类
    def divide(self, a: int, b: int) -> int:  # a：被除数；b：除数；返回向零截断的商
        if b == 1:  # 除数为 1 时商就是被除数本身，顺带避开最小值取反的问题
            return a  # 直接返回结果
        if a == -(2**31) and b == -1:  # 唯一的溢出场景：最小值除以 -1，真实答案 2^31 超出 32 位有符号范围
            return 2**31 - 1  # 按题目要求截断为 2^31 - 1
        sign = (a > 0 and b > 0) or (a < 0 and b < 0)  # 同号得正、异号得负，先记录结果符号
        a = -a if a > 0 else a  # 被除数统一转成非正数，-(2^31) 本身是负数所以保持原样
        b = -b if b > 0 else b  # 除数也统一转成非正数，后面只比较负数、只做加法
        ans = 0  # ans 累积商的绝对值
        while a <= b:  # 被除数绝对值仍不少于除数绝对值，说明还能再减一份
            x = b  # x 是当前这一份的除数（负数），先取原始除数
            cnt = 1  # cnt 记录 x 是除数的多少倍
            while x >= (-(2**30)) and a <= (x << 1):  # x 还没越过 -2^30，且被除数够减两份 x，才继续倍增
                x <<= 1  # x 左移一位相当于乘 2，除数翻倍
                cnt <<= 1  # 倍数同步翻倍
            a -= x  # 先减掉这一份（cnt 个除数），剩下的量留给下一轮
            ans += cnt  # 商累加这一轮的倍数
        return ans if sign else -ans  # 同号返回正的商，异号返回相反数，实现向零截断
