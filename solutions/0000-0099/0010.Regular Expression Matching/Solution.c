// 题目：10. 正则表达式匹配（Regular Expression Matching）
// 思路：记忆化深度优先搜索，(i, j) 表示 s 从 i 起、p 从 j 起能否匹配；遇到 "x*" 时在“用 0 次跳过”和“吃掉一个字符后原地继续”之间二选一。
// 时间复杂度：O(mn)，m、n 为两串长度，每个状态只计算一次；空间复杂度：O(mn)，记忆化数组。
#define MAX_LEN 1000  // 记忆化数组的最大边长，题目保证两串长度不超过 1000

char *ss, *pp;  // 把两个输入串提升为全局指针，dfs 里直接访问，省去层层传参
int m, n;  // s 与 p 的长度，供 dfs 判边界使用
int f[MAX_LEN + 1][MAX_LEN + 1];  // 记忆化表：0 表示未计算，1 表示可匹配，-1 表示不可匹配

bool dfs(int i, int j) {  // 判断 s[i:] 能否被 p[j:] 匹配
    if (j >= n) {  // 模式串已经用完
        return i == m;  // 只有原串也同时用完，才算整体匹配成功
    }
    if (f[i][j] != 0) {  // 这个状态以前算过
        return f[i][j] == 1;  // 直接取缓存，顺便把 -1 归一化成 false
    }
    int res = -1;  // 先假定不匹配（-1 代表 false）
    if (j + 1 < n && pp[j + 1] == '*') {  // 当前字符后面紧跟 '*'，说明它可重复 0 次或多次
        if (dfs(i, j + 2) || (i < m && (ss[i] == pp[j] || pp[j] == '.') && dfs(i + 1, j))) {  // 选择一：整段跳过 "x*"；选择二：先吃掉 s[i]，再留在 j 继续用同一个 x
            res = 1;  // 任一分支成功就说明可匹配
        }
    } else if (i < m && (ss[i] == pp[j] || pp[j] == '.') && dfs(i + 1, j + 1)) {  // 无 '*' 的普通单字符比较：相等或模式为 '.'，然后两个串各前进一位
        res = 1;  // 当前位置匹配成功
    }
    f[i][j] = res;  // 把本状态的结果写入缓存，避免重复递归
    return res == 1;  // 把 int 结果转成 bool 返回
}

bool isMatch(char* s, char* p) {  // 判题器入口：判断 s 是否整体匹配模式 p
    ss = s;  // 记录原串首地址，供 dfs 使用
    pp = p;  // 记录模式串首地址，供 dfs 使用
    m = strlen(s);  // 原串长度作为递归上界
    n = strlen(p);  // 模式串长度作为递归上界
    memset(f, 0, sizeof(f));  // 清空记忆化表，防止上一组测试数据残留（LeetCode 会复用全局变量）
    return dfs(0, 0);  // 从两个串的开头开始匹配
}
