// 题目：2170. 使数组变成交替数组的最少操作数（Minimum Operations to Make the Array Alternating）
// 思路：偶数下标与奇数下标各自统计出现次数最多的两个值；两侧最优值不冲突就各取最大，冲突则枚举「一取最大、另一取次大」两种搭配。
// 时间复杂度：O(n)，每个下标只被扫一遍；空间复杂度：O(n)，哈希表保存频次。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumOperations(vector<int>& nums) {  // nums：输入数组；返回把数组改成交替数组所需的最少操作数（每次可把任意一个元素改成任意值）
        auto f = [&](int i) -> vector<int> {  // 闭包 f(i)：统计从下标 i 出发、步长 2 的所有元素，返回 {最多次数的值, 次数, 次多次数的值, 次数}
            int k1 = 0, k2 = 0;  // k1、k2 分别记录出现最多、次多的值；用 0 表示「还没有」
            unordered_map<int, int> cnt;  // 哈希表：键是元素值，值是它在这些位置上的出现次数
            for (; i < nums.size(); i += 2) {  // 只遍历与 i 同奇偶的下标，因为交替数组中这些位置的最终取值必须相同
                cnt[nums[i]]++;  // 累加当前取值的出现频次
            }  // 统计完成，退出循环
            for (auto& [k, v] : cnt) {  // 遍历所有 (值, 次数)，一遍求出最大值与次大值
                if (!k1 || cnt[k1] < v) {  // 还没有最大值，或当前次数 v 严格大于已知最大次数
                    k2 = k1;  // 原来的最大值降级为次大值
                    k1 = k;  // 更新最大值
                } else if (!k2 || cnt[k2] < v) {  // 没超过最大值时，再单独判断能否成为新的次大值
                    k2 = k;  // 更新次大值
                }  // else-if 分支结束
            }  // 遍历结束
            return {k1, !k1 ? 0 : cnt[k1], k2, !k2 ? 0 : cnt[k2]};  // 返回 4 个数；!k1 表示计数表为空，此时直接取 0，避免 cnt[k1] 插入默认项
        };  // 闭包定义结束
        vector<int> a = f(0);  // 偶数下标的分析结果：a[0]=最优值, a[1]=其次数, a[2]=次优值, a[3]=其次数
        vector<int> b = f(1);  // 奇数下标的分析结果，字段含义同上
        int n = nums.size();  // 数组长度 n，最终最多只能保留 n 个元素不修改
        if (a[0] != b[0]) {  // 两侧的最优值不同，可以同时保留这两类值，互不冲突
            return n - (a[1] + b[1]);  // 保留最大的两类，其余 n-(a[1]+b[1]) 个元素都需要改
        }  // 冲突分支结束
        return n - max(a[1] + b[3], a[3] + b[1]);  // 最优值相同会冲突：只能在 (a 取最大, b 取次大) 与 (a 取次大, b 取最大) 中选保留更多的方案
    }  // 方法结束
};  // 类定义结束，源文件到此为止