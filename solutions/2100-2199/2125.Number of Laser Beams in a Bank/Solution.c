// 题目：2125. 银行中的激光束数量（Number of Laser Beams in a Bank）
// 核心思路：逐行统计 '1' 的个数，只有非空行才和上一个非空行按「行内 1 的个数相乘」累加激光束。
// 时间复杂度：O(m·n)，m 行 n 列每格只访问一次；空间复杂度：O(1)，只用常数个变量。
int numberOfBeams(char** bank, int bankSize) {  // bank 是每行一个 '0'/'1' 字符串的数组；bankSize 是行数；返回值是激光束总条数
    int ans = 0, pre = 0;  // ans 累计激光束总数；pre 存上一个非空行里 '1' 的个数（0 表示还没有这样的行）
    for (int i = 0; i < bankSize; ++i) {  // 自上而下逐行遍历，光束只可能出现在中间没有空行隔开的两个非空行之间
        int cur = 0;  // 本行 '1' 的计数器，每行都从 0 重新开始
        for (int j = 0; bank[i][j] != '\0'; ++j) {  // 按 C 字符串的结束符 '\0' 逐列扫描本行，遇到结束符就停
            if (bank[i][j] == '1') {  // 这个格子上有激光设备（'1'）才计数
                cur++;  // 本行设备数加一
            }
        }
        if (cur) {  // cur > 0 说明本行是非空行，才有资格和上一个非空行配对
            ans += pre * cur;  // 乘法原理：上一个非空行的每个 '1' 与本行每个 '1' 两两连一条光束
            pre = cur;  // 本行成为下一次配对时的「上一个非空行」
        }
    }
    return ans;  // 返回累计出的激光束总条数
}