// 题目：2165. 重排数字的最小值（Smallest Value of the Rearranged Number）
// 思路：先统计 0-9 各位的出现次数；负数把数字从大到小拼成绝对值最大的数再取负，正数把最小非零数字放首位、其余升序拼接。
// 时间复杂度：O(log num)，只遍历各位数字；空间复杂度：O(1)，固定 10 个计数桶。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long smallestNumber(long long num) {  // num：输入整数（可能为负）；返回重排后能得到的最小值
        bool neg = num < 0;  // 记录符号：原数为负时最后要给结果取负
        num = abs(num);  // 取绝对值，后面只处理各位数字，符号单独记住
        int cnt[10]{};  // cnt[d] 表示数字 d 在原数中出现的次数，花括号把 10 个桶都初始化为 0
        while (num > 0) {  // 逐位拆解，直到 num 被除尽
            ++cnt[num % 10];  // 取出最低位，把它的计数加一
            num /= 10;  // 丢掉最低位，继续处理更高位
        }  // 拆解结束，cnt 已是完整的数字频次表
        long long ans = 0;  // ans 用来累积拼接出来的数
        if (neg) {  // 负数分支：绝对值越大数值越小，所以数字要从大到小排列
            for (int i = 9; i >= 0; --i) {  // 从 9 到 0 逆序遍历，保证高位放更大的数字
                while (cnt[i] > 0) {  // 数字 i 有几个副本就拼几次
                    ans = ans * 10 + i;  // 左移一位腾出个位，再把数字 i 加到个位
                    --cnt[i];  // 该数字用掉一个
                }  // i 的副本用完
            }  // 9..0 全部拼完，ans 是绝对值最大的重排结果
            return -ans;  // 取负得到真正的负数最小值
        }  // 负数分支处理完毕
        if (cnt[0]) {  // 只有原数含 0 时才需要单独挑一个非零数字当首位，否则前导 0 会白占数位
            for (int i = 1; i < 10; ++i) {  // 从 1 到 9 找出最小的非零数字作为最高位
                if (cnt[i] > 0) {  // 找到还有剩余的最小非零数字
                    --cnt[i];  // 先把它从计数里扣掉，避免下面重复使用
                    ans = i;  // 把它作为最高位，此时 ans 里只有这一位
                    break;  // 首位确定，跳出查找
                }  // if 结束
            }  // for 结束
        }  // if 结束
        for (int i = 0; i < 10; ++i) {  // 剩余数字从小到大拼接，0 会紧跟在首位之后，数值最小
            while (cnt[i] > 0) {  // 依次把每个数字的所有副本拼到末尾
                ans = ans * 10 + i;  // 左移一位腾出个位
                --cnt[i];  // 把数字 i 放到个位
            }  // 副本减一
        }  // 该数字用完
        return ans;  // 全部数字拼完，得到正数情况下的最小值
    }  // 方法结束
};  // 类定义结束
