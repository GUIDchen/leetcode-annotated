// 题目：2103. 环和杆（Rings and Rods）
// 思路：把红/绿/蓝编码成 1/2/4 三个二进制位，按杆号把颜色位或起来，最后统计掩码等于 7（三色齐全）的杆数。
// 时间复杂度：O(n)，一次扫描字符串；空间复杂度：O(1)，固定 10 根杆的掩码数组。
int countPoints(char* rings) {  // rings 形如 "R0G1B2"，每两个字符是「颜色 + 杆号」，返回三色齐全的杆数
    int d['Z'];  // 颜色到二进制位的映射表，用字符的编码直接当下标
    memset(d, 0, sizeof(d));  // 先把整张映射表清零
    d['R'] = 1;  // 红色用第 0 位表示
    d['G'] = 2;  // 绿色用第 1 位表示
    d['B'] = 4;  // 蓝色用第 2 位表示

    int mask[10];  // 每根杆上出现过的颜色集合，下标就是杆号 0~9
    memset(mask, 0, sizeof(mask));  // 初始时每根杆都是空的（掩码为 0）

    for (int i = 0, n = strlen(rings); i < n; i += 2) {  // 每次前进两个字符，同时把字符串长度缓存到 n
        int c = rings[i];  // 当前环的颜色字符
        int j = rings[i + 1] - '0';  // 当前环所在杆号，字符减去 '0' 得到数字
        mask[j] |= d[c];  // 把这种颜色对应的位并进该杆的掩码
    }

    int ans = 0;  // 统计三种颜色都齐了的杆数
    for (int i = 0; i < 10; i++) {  // 依次检查 0~9 号杆
        if (mask[i] == 7) {  // 7 = 1|2|4，说明红绿蓝都出现过
            ans++;  // 这根杆满足条件，计数加一
        }
    }

    return ans;  // 返回满足条件的杆数
}