// 题目：2198. 单因数三元组 🔒（Number of Single Divisor Triplets）
// 思路：值域只有 1..100，先统计每个值的出现次数，再枚举三个「值」a、b、c，用频次乘积公式一次算出所有有序下标组合的个数。
// 时间复杂度：O(n + 100^3)，枚举部分是常数级；空间复杂度：O(1)，只需长度 101 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long singleDivisorTriplet(vector<int>& nums) {  // nums：输入数组；返回单因数三元组的个数
        int cnt[101]{};  // 频次数组：cnt[v] 表示值 v 出现的次数（值域 1..100），{} 把它全部初始化为 0
        for (int x : nums) {  // 一次遍历统计每个值的出现次数
            ++cnt[x];  // 当前值 x 的计数加一
        }  // 结束统计循环
        long long ans = 0;  // 答案可能很大，用 long long 累加
        for (int a = 1; a <= 100; ++a) {  // 枚举第一个数的取值 a：只枚举值而不枚举下标，把 O(n^3) 降到 O(100^3)
            for (int b = 1; b <= 100; ++b) {  // 枚举第二个数的取值 b
                for (int c = 1; c <= 100; ++c) {  // 枚举第三个数的取值 c
                    int s = a + b + c;  // 三个值之和
                    int x = cnt[a], y = cnt[b], z = cnt[c];  // x、y、z 分别是三个值在数组中出现的次数
                    int t = (s % a == 0) + (s % b == 0) + (s % c == 0);  // 布尔值相加：恰好一个值能整除 s 时 t 等于 1（0 个或 3 个都不合题意）
                    if (t == 1) {  // 只有恰好一个整除条件成立时才计入答案
                        if (a == b) {  // 情况一：前两个值相同（对应两个不同下标取到同一个值）
                            ans += 1LL * x * (x - 1) * z;  // 先有序选两个不同下标的 a（x*(x-1) 种），再选一个 c：共 x*(x-1)*z 个三元组
                        } else if (a == c) {  // 情况二：第一和第三个值相同
                            ans += 1LL * x * (x - 1) * y;  // 有序选两个不同下标的 a，再选一个 b：x*(x-1)*y
                        } else if (b == c) {  // 情况三：后两个值相同
                            ans += 1LL * x * y * (y - 1);  // 选一个 a，再有序选两个不同下标的 b：x*y*(y-1)
                        } else {  // 情况四：三个值互不相同
                            ans += 1LL * x * y * z;  // 三个值各取一个下标：x*y*z（值组合的每种排列都会在此被分别枚举到）
                        }  // 结束 if/else 链
                    }  // 结束 if (t == 1)
                }  // 结束 c 的枚举
            }  // 结束 b 的枚举
        }  // 结束 a 的枚举
        return ans;  // 返回统计到的三元组总数
    }  // 结束方法
};  // 结束 Solution 类