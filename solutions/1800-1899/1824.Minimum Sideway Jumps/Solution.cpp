// 题目：1824. 最少侧跳次数（Minimum Sideway Jumps）
// 核心思路：动态规划，f[j] 表示到达当前列第 j+1 条跑道的最少侧跳次数；每列先把被障碍占据的跑道置为 inf，再用三条跑道的最小值 +1 去更新可以站立的跑道。
// 时间复杂度：O(n)，每列只处理 3 条跑道；空间复杂度：O(1)，只用一个长度 3 的数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minSideJumps(vector<int>& obstacles) {  // obstacles[i] 表示第 i 个位置的障碍所在跑道，0 表示没有障碍
        const int inf = 1 << 30;  // inf 表示不可达，1 << 30 足够大且不会溢出
        int f[3] = {1, 0, 1};  // f[j]：到达第 j+1 条跑道的最少侧跳次数；起点在第 2 条跑道，所以是 {1, 0, 1}
        for (int i = 1; i < obstacles.size(); ++i) {  // 从第 1 个位置开始逐列向右推进（下标 0 是起点，没有障碍）
            for (int j = 0; j < 3; ++j) {  // 三条跑道逐一检查是否被障碍占据
                if (obstacles[i] == j + 1) {  // obstacles[i] == j + 1 说明第 j 条跑道在这一列被堵
                    f[j] = inf;  // 该跑道在这一列无法站立，置为不可达
                    break;  // 一列最多只有一个障碍，处理完即可跳出
                }
            }
            int x = min({f[0], f[1], f[2]}) + 1;  // 到达当前列任意跑道最多只需从三条跑道的最优值再侧跳一次
            for (int j = 0; j < 3; ++j) {  // 用这个基准值更新所有没被堵住的跑道
                if (obstacles[i] != j + 1) {  // 该跑道没有障碍才允许落脚
                    f[j] = min(f[j], x);  // 原地不动更优就保留原值，否则采用侧跳一次的方案
                }
            }
        }
        return min({f[0], f[1], f[2]});  // 三条跑道的最小值就是到达终点的最少侧跳次数
    }
};