// 题目：1864. 构成交替字符串需要的最小交换次数（Minimum Number of Swaps to Make the Binary String Alternating）
// 思路：先看 0 与 1 的个数是否相差不超过 1；交替形态只由首字符决定，统计与目标形态不同的位置数，一次交换能同时修正两个位置，故答案为错位数除以 2，两种形态取较小值。
// 时间复杂度：O(n)，常数次线性扫描；空间复杂度：O(1)，只用了若干计数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minSwaps(string s) {  // s：只含 '0' 和 '1' 的字符串
        int n0 = ranges::count(s, '0');  // '0' 的个数（ranges::count 是 C++20 的范围计数算法）
        int n1 = s.size() - n0;  // '1' 的个数 = 总长度 - '0' 的个数
        if (abs(n0 - n1) > 1) {  // 两种字符数量相差超过 1 时必然无法排成交替串
            return -1;  // 返回 -1 表示不可行
        }  // 不可行分支结束
        auto calc = [&](int c) -> int {  // 计算改成「第 i 位为 c ^ (i&1)」这种交替形态所需的最少交换次数
            int cnt = 0;  // 记录与目标形态不一致的位置数
            for (int i = 0; i < s.size(); ++i) {  // 逐位扫描原串
                int x = s[i] - '0';  // 取当前字符的数值（'0' → 0，'1' → 1）
                if ((i & 1 ^ c) != x) {  // 目标形态第 i 位是 c ^ (i&1)，与实际值 x 不同就计入错位
                    ++cnt;  // 错位计数加一
                }  // 这一位比对完毕
            }  // 整串扫描结束
            return cnt / 2;  // 一次交换可同时修正两个错位，所以交换次数是错位数的一半
        };  // lambda 定义结束
        if (n0 == n1) {  // 0 与 1 一样多时，首字符放 0 或放 1 都合法，取两种形态的较小值
            return min(calc(0), calc(1));  // 返回两者中的最小值
        }  // 数量相等的分支结束
        return calc(n0 > n1 ? 0 : 1);  // 数量不等时只有一种合法形态：个数多的字符必须占偶数下标，0 多则 c=0，1 多则 c=1
    }  // 方法结束
};  // 类定义结束
