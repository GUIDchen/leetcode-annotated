// 题目：1881. 插入后的最大值（Maximum Value after Insertion）
// 思路：正数时从高位找第一个小于 x 的数字并在它之前插入；负数时先跳过负号，再找第一个大于 x 的数字并在它之前插入（负数绝对值越大值越小）。
// 时间复杂度：O(L)，只做一次线性扫描；空间复杂度：O(L)，插入会复制字符串。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string maxValue(string n, int x) {  // n：可能带负号的大整数字符串；x：要插入的数字 0..9
        int i = 0;  // i：插入位置，初始指向字符串开头
        if (n[0] == '-') {  // 负数：高位数字越小整体越大，插入策略与正数相反
            ++i;  // 跳过负号，从第一位数字开始比较
            while (i < n.size() && n[i] - '0' <= x) {  // 负数希望 x 插在比它大的数字前面，所以先跳过所有不大于 x 的位
                ++i;  // 继续向后找第一个大于 x 的数字
            }  // 负数的插入位置确定
        } else {  // 正数：插得越靠前数值越大，所以要找第一个小于 x 的数字
            while (i < n.size() && n[i] - '0' >= x) {  // 跳过所有不小于 x 的位（插在它们后面不会更优）
                ++i;  // 指针右移，继续向后比较
            }  // 正数的插入位置确定
        }  // 分支结束，i 就是最佳插入位置
        n.insert(i, 1, x + '0');  // 在位置 i 处插入 1 个字符，即数字 x 对应的字符
        return n;  // 返回插入后的最大数值字符串
    }  // 方法结束
};  // 类定义结束
