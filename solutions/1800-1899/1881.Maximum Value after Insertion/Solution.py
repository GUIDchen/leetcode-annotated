# 题目：1881. 插入后的最大值（Maximum Value after Insertion）
# 思路：正数时从高位找第一个小于 x 的数字并在它之前插入；负数时先跳过负号，再找第一个大于 x 的数字并在它之前插入（负数绝对值越大值越小）。
# 时间复杂度：O(L)，只做一次线性扫描；空间复杂度：O(L)，切片拼接会复制字符串。
class Solution:  # LeetCode 约定的题解类
    def maxValue(self, n: str, x: int) -> str:  # n：可能带负号的大整数字符串；x：要插入的数字 0..9
        i = 0  # i：插入位置，初始指向字符串开头
        if n[0] == "-":  # 负数：高位数字越小整体越大，插入策略与正数相反
            i += 1  # 跳过负号，从第一位数字开始比较
            while i < len(n) and int(n[i]) <= x:  # 负数希望 x 插在比它大的数字前面，所以先跳过所有不大于 x 的位
                i += 1  # 继续向后找第一个大于 x 的数字
        else:  # 正数：插得越靠前数值越大，所以要找第一个小于 x 的数字
            while i < len(n) and int(n[i]) >= x:  # 跳过所有不小于 x 的位（插在它们后面不会更优）
                i += 1  # 指针右移，继续向后比较
        return n[:i] + str(x) + n[i:]  # 在位置 i 处把数字 x 拼接进去：前缀 + 新数字 + 后缀
