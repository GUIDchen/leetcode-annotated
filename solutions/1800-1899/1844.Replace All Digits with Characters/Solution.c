// 题目：1844. 将所有数字用字符替换（Replace All Digits with Characters）
// 思路：偶数下标是字母、奇数下标是数字，顺序扫描奇数位，把 s[i] 改成"前一个字母向后偏移 s[i]-'0' 位"得到的字母。
// 时间复杂度：O(n)，只扫一遍；空间复杂度：O(1)，直接在传入的字符串上原地修改。
char* replaceDigits(char* s) {  // 传入可写字符串指针，返回同一块内存的地址
    int n = strlen(s);  // 求串长，作为循环上界
    for (int i = 1; i < n; i += 2) {  // 步长为 2 只遍历奇数下标（题目保证这些位置是数字）
        s[i] = s[i - 1] + s[i] - '0';  // 前一个字母的 ASCII 码加上数字值，得到 shift 后的字母
    }
    return s;  // 原地修改完成，返回原指针
}  // 函数结束