// 题目：1888. 使二进制字符串字符交替的最少反转次数（Minimum Number of Flips to Make the Binary String Alternating）
// 思路：交替目标只有 "01" 与 "10" 两种模式；先统计原串与 "01" 的不匹配数 cnt（"10" 即 n-cnt），再滑动枚举「把首字符搬到末尾」的 n 种旋转，边移边更新 cnt，取所有情况的最小值。
// 时间复杂度：O(n)，只做一次统计加一次滑动；空间复杂度：O(1)，除常数个变量外只用了一个长度为 2 的模式串。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minFlips(string s) {  // s：只含 '0'/'1' 的二进制字符串，允许任意次把首字符移到末尾
        int n = s.size();  // 字符串长度，后续下标运算都以它为准
        string target = "01";  // 模式串 "01"，借它的循环下标表示交替串的两种可能模式
        int cnt = 0;  // cnt 记录当前串与 "01" 模式不匹配的位数
        for (int i = 0; i < n; ++i) {  // 先在未旋转的原始串上统计一次不匹配数
            if (s[i] != target[i & 1]) {  // i & 1 等价于 i % 2，取出 "01" 在该位置应有的字符
                ++cnt;  // 该位与模式不同，必须翻转，计数加一
            }  // 结束单点判断
        }  // 结束初始统计
        int ans = min(cnt, n - cnt);  // 模式 "01" 需 cnt 次翻转，模式 "10" 需 n-cnt 次，取更小者作为初值
        for (int i = 0; i < n; ++i) {  // 枚举 n 种旋转结果：每轮把 s[i] 从队首搬到队尾
            if (s[i] != target[i & 1]) {  // s[i] 此刻正处在位置 i，按 "01" 模式参与计数
                --cnt;  // 它即将离开队首，先撤销它在位置 i 上的贡献
            }  // 结束撤销
            if (s[i] != target[(i + n) & 1]) {  // 搬走后它落在位置 i + n，(i + n) & 1 就是它对应的新模式位
                ++cnt;  // 在新位置仍然不匹配，重新计入
            }  // 结束重新计入
            ans = min({ans, cnt, n - cnt});  // 两种模式各算一遍，用 initializer_list 版 min 刷新全局最优
        }  // 结束旋转枚举
        return ans;  // 所有旋转、所有模式中的最少翻转次数
    }  // 方法结束
};  // 类定义结束