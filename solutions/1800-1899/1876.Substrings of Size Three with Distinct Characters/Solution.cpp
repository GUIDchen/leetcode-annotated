// 题目：1876. 长度为三且各字符不同的子字符串（Substrings of Size Three with Distinct Characters）
// 思路：滑动窗口 + 26 位二进制掩码记录窗口内出现过的字母，保证窗口内字符互不重复；窗口长度 >= 3 时，以 r 结尾的最后 3 个字符就是一个合法子串。
// 时间复杂度：O(n)，左右指针各自只前进一次；空间复杂度：O(1)，只用常数个整型变量与一个掩码。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countGoodSubstrings(string s) {  // s：只含小写字母的字符串；返回长度恰为 3 且三字符互不相同的子串个数
        int ans = 0;  // ans：累计的合法子字符串个数
        int n = s.length();  // n：字符串长度，作为右指针的上界
        for (int l = 0, r = 0, mask = 0; r < n; ++r) {  // l：左指针；r：右指针；mask：窗口内字母集合（第 x 位为 1 表示字母 x 在窗口内）
            int x = s[r] - 'a';  // 把新进窗口的字符映射成 0..25 的整数 x
            while ((mask >> x & 1) == 1) {  // 若 x 已在窗口中说明出现重复，需要从左侧收缩窗口直到没有 x
                int y = s[l++] - 'a';  // 取出左端字符映射为 y，并把左指针右移一位
                mask ^= 1 << y;  // 把 y 从窗口集合中清除（该位必为 1，用异或即可清零）
            }  // 收缩结束：窗口内不再有与 x 重复的字符
            mask |= 1 << x;  // 把当前字符 x 正式加入窗口集合
            ans += r - l + 1 >= 3 ? 1 : 0;  // 窗口长度 >= 3 时，以 r 结尾的最后 3 个字符互不相同，恰是一个合法子串
        }  // 右指针扫完整个字符串，统计结束
        return ans;  // 返回合法子串总数
    }  // 方法结束
};  // 类定义结束
