// 题目：1806. 还原排列的最少操作步数（Minimum Number of Operations to Reinitialize a Permutation）
// 思路：元素 0 与 n-1 始终不动，只需跟踪下标 1 的轨迹，按置换规则反复迭代，回到 1 的步数即答案。
// 时间复杂度：O(n)，循环次数不超过 n；空间复杂度：O(1)，只用常数个整型变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int reinitializePermutation(int n) {  // n：排列长度，元素取自 0..n-1，其中 0 与 n-1 始终不动
        int ans = 0;  // ans 记录已经执行的操作次数
        for (int i = 1;;) {  // 只需跟踪下标 1 的位置，它所在循环节的长度就是整个排列复原所需的步数
            ++ans;  // 又完成了一次置换操作
            if (i < (n >> 1)) {  // 下标落在左半段：新位置来自上一轮的前半部分
                i <<= 1;  // 新下标变成 2 * i（左移一位即乘 2）
            } else {  // 下标落在右半段
                i = (i - (n >> 1)) << 1 | 1;  // 新下标变成 2 * (i - n/2) + 1，左移后按位或 1 相当于加 1
            }  // if / else 分支结束
            if (i == 1) {  // 数字 1 回到下标 1，说明整个排列已经复原
                return ans;  // 返回所需的最少操作步数
            }  // if 结束
        }  // for 结束（题面保证一定会在有限步内回到 1）
    }  // 方法结束
};  // 类定义结束