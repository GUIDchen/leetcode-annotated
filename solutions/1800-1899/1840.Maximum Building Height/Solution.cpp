// 题目：1840. 最高建筑高度（Maximum Building Height）
// 思路：把限制按位置排序并补上第 1 栋（高 0）与第 n 栋（高 n-1）两个哨兵，先从左往右、再从右往左各传播一次"相邻楼高差不超过 1"的约束，最后在每对相邻约束点之间取峰顶高度 (h1+h2+距离)/2。
// 时间复杂度：O(m log m)，m 为限制点个数，瓶颈在排序；空间复杂度：O(m)，直接在传入的 restrictions 上原地增删，哨兵占用额外元素。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxBuilding(int n, vector<vector<int>>& restrictions) {  // n：建筑总数；restrictions：{位置, 最大高度} 限制列表
        auto&& r = restrictions;  // 用转发引用起别名，避免拷贝整个二维数组
        r.push_back({1, 0});  // 哨兵：h1 必须为 0，因此第 1 栋的高度上限是 0
        ranges::sort(r);  // 按位置升序排序，方便从左往右做约束传播
        if (r[r.size() - 1][0] != n) {  // 排序后最后一个位置不是 n，说明第 n 栋没有限制
            r.push_back({n, n - 1});  // 补哨兵：每层最多涨 1，所以 hn 的上限是 n-1
        }
        int m = r.size();  // 补完哨兵后的约束点个数
        for (int i = 1; i < m; ++i) {  // 从左往右扫一遍
            r[i][1] = min(r[i][1], r[i - 1][1] + r[i][0] - r[i - 1][0]);  // 高差不能超过位置差，取更紧的上限
        }
        for (int i = m - 2; i > 0; --i) {  // 从右往左再扫一遍（0 号哨兵已是 0，无需处理）
            r[i][1] = min(r[i][1], r[i + 1][1] + r[i + 1][0] - r[i][0]);  // 用右侧更紧的约束回头收紧当前点
        }
        int ans = 0;  // 记录全局最高可达高度
        for (int i = 0; i < m - 1; ++i) {  // 枚举每对相邻约束点之间的空隙
            int t = (r[i][1] + r[i + 1][1] + r[i + 1][0] - r[i][0]) / 2;  // 两端各自向上爬，剩下的距离二人平分，得到这段能拱起的峰顶
            ans = max(ans, t);  // 更新最大值
        }
        return ans;  // 返回可达到的最高建筑高度
    }
};
