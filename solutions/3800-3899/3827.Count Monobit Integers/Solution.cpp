// 3827. Count Monobit Integers | 3827. 统计单比特整数
// 核心思路：单比特数是二进制各位全相同者（0 或全为 1，即 0、1、3、7、15…），逐个累加直到超过 n 并计数
// 复杂度：时间 O(log n)，空间 O(1)
class Solution {
public:
    int countMonobit(int n) {  // 统计 [0, n] 内二进制各位全相同的整数个数
        int ans = 1;  // 先把 0 计入答案（其二进制为全 0）
        for (int i = 1, x = 1; x <= n; ++i) {  // x 为当前的全 1 整数，从 1 开始枚举，直到超过 n 停止
            ++ans;  // 当前这个全 1 整数不超过 n，计入答案
            x += (1 << i);  // 下一个全 1 整数：在二进制末尾再补一个 1
        }
        return ans;  // 返回统计个数
    }
};
