// 3866. 找到第一个唯一偶数 / First Unique Even Element
// 核心思路：先用 101 大小的计数数组统计每个值出现的次数，再按原顺序第二次扫描，返回第一个“出现一次且为偶数”的元素。
// 复杂度：时间复杂度 O(n)，空间复杂度 O(V)，V = 101 为值域大小。
class Solution {  // LeetCode 题解类
public:  // 公有成员
    int firstUniqueEven(vector<int>& nums) {  // 返回数组中第一个只出现一次的偶数，不存在则返回 -1
        int cnt[101]{};  // 值域 1..100 的出现次数计数数组，初始化为 0
        for (int x : nums) {  // 第一遍：统计每个值的出现次数
            ++cnt[x];  // 值 x 的计数加一
        }  // 统计完毕
        for (int x : nums) {  // 第二遍：按原数组顺序寻找第一个满足条件的元素
            if (x % 2 == 0 && cnt[x] == 1) {  // 既是偶数，又只出现过一次
                return x;  // 立即返回该唯一偶数
            }  // 否则继续向后查找
        }  // 遍历结束仍未找到
        return -1;  // 不存在唯一偶数，返回 -1
    }  // 方法结束
};  // 类结束
