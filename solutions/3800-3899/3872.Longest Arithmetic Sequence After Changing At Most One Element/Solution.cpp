// 3872. 替换最多一个元素后的最长等差子数组（Longest Arithmetic Sequence After Changing At Most One Element）
// 核心思路：先求相邻差分 d，用 f[i]/g[i] 表示以 i 结尾、以 i 开头的等差段长度；再枚举被替换的位置 i，把左右两条等差段拼到新元素两侧，若两侧公差一致则合并成更长的段。
// 复杂度：时间复杂度 O(n)，空间复杂度 O(n)。
class Solution {  // 题解类
public:  // 公有成员
    int longestArithmetic(vector<int>& nums) {  // 返回最多修改一个元素后的最长等差子数组长度
        int n = nums.size();  // 数组长度
        vector<int> d(n);  // d[i] 表示 nums[i] - nums[i-1] 的相邻差分
        for (int i = 1; i < n; i++) {  // 从下标 1 开始遍历
            d[i] = nums[i] - nums[i - 1];  // 计算第 i 个差分
        }  // 差分数组构造完毕

        vector<int> f(n, 2), g(n, 2);  // f 向左延伸的等差段长度，g 向右延伸的等差段长度，单个元素配一个邻居初值为 2
        f[0] = 1;  // 首元素左侧没有邻居，长度只能是 1
        g[n - 1] = 1;  // 末元素右侧没有邻居，长度只能是 1

        for (int i = 2; i < n; i++) {  // 从左往右递推 f
            if (d[i] == d[i - 1]) {  // 相邻两个差分相同，说明可以继续延伸
                f[i] = f[i - 1] + 1;  // 在以 i-1 结尾的等差段末尾再加一个元素
            }  // 差分不同则保持初值，不再延伸
        }  // f 递推结束

        for (int i = n - 3; i >= 0; i--) {  // 从右往左递推 g
            if (d[i + 1] == d[i + 2]) {  // 右侧相邻两个差分相同，说明可以继续向左延伸
                g[i] = g[i + 1] + 1;  // 在以 i+1 开头的等差段前面再加一个元素
            }  // 差分不同则保持初值，不再延伸
        }  // g 递推结束

        int ans = 3;  // 答案下界为 3（长度不足 3 时题目按 3 计）
        for (int i = 0; i < n; i++) {  // 枚举被替换的位置 i
            ans = max(ans, max(f[i], g[i]));  // 情况一：不拼接，直接用以 i 结尾或开头的等差段
            if (i > 0) {  // 左侧还有元素时才能向左接
                ans = max(ans, f[i - 1] + 1);  // 情况二：新元素接在左侧等差段之后
            }  // 左接判断结束
            if (i + 1 < n) {  // 右侧还有元素时才能向右接
                ans = max(ans, g[i + 1] + 1);  // 情况三：新元素接在右侧等差段之前
            }  // 右接判断结束
            if (i > 0 && i < n - 1) {  // 左右都有邻居时才能尝试两侧合并
                int diff = nums[i + 1] - nums[i - 1];  // 两侧邻居的跨度，替换后公差应为其一半
                if (diff % 2 == 0) {  // 跨度为偶数才能整除出整数公差
                    diff /= 2;  // 求出合并后应有的公差
                    int k = 3;  // 合并段基础长度：左邻居 + 新元素 + 右邻居
                    if (i > 1 && diff == d[i - 1]) {  // 左侧更远的差分与新公差一致
                        k += f[i - 1] - 1;  // 把整条左侧等差段并入（f[i-1] 已包含 nums[i-1]）
                    }  // 左侧合并判断结束
                    if (i < n - 2 && diff == d[i + 2]) {  // 右侧更远的差分与新公差一致
                        k += g[i + 1] - 1;  // 把整条右侧等差段并入（g[i+1] 已包含 nums[i+1]）
                    }  // 右侧合并判断结束
                    ans = max(ans, k);  // 用合并后的长度更新答案
                }  // 偶数跨度判断结束
            }  // 两侧合并判断结束
        }  // 枚举结束
        return ans;  // 返回最长等差子数组长度
    }  // 方法结束
};  // 类结束
