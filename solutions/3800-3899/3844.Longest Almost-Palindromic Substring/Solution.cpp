// 3844. 最长的准回文子字符串 / Longest Almost-Palindromic Substring（中等）
// 核心思路：枚举每个回文中心向外扩展，再分别尝试跳过左端或右端的一个字符继续扩展，取更长的长度。
// 复杂度：时间 O(n^2)，空间 O(1)。
class Solution {  // 解题类：LeetCode 判题器约定的类名
public:  // 公有接口
    int almostPalindromic(string s) {  // 返回字符串 s 中最长准回文子串的长度
        int n = s.size();  // n 为字符串长度，供闭包与循环复用

        auto f = [&](int l, int r) {  // 定义闭包 f：以 (l, r) 为中心向外扩展，返回该中心可得到的最长准回文长度
            while (l >= 0 && r < n && s[l] == s[r]) {  // 第一阶段：常规回文扩展，两端字符相同就继续向外
                --l;  // 左指针左移
                ++r;  // 右指针右移
            }  // 常规回文扩展结束

            int l1 = l - 1, r1 = r;  // 方案一：跳过左边界外的那个字符，从 l-1 与 r 继续匹配
            int l2 = l, r2 = r + 1;  // 方案二：跳过右边界外的那个字符，从 l 与 r+1 继续匹配

            while (l1 >= 0 && r1 < n && s[l1] == s[r1]) {  // 用方案一继续向外扩展
                --l1;  // 左指针左移
                ++r1;  // 右指针右移
            }  // 方案一扩展结束
            while (l2 >= 0 && r2 < n && s[l2] == s[r2]) {  // 用方案二继续向外扩展
                --l2;  // 左指针左移
                ++r2;  // 右指针右移
            }  // 方案二扩展结束

            return min(n, max(r1 - l1 - 1, r2 - l2 - 1));  // 两种方案的长度取较大值，再与 n 取小防止越界
        };  // 闭包定义结束

        int ans = 0;  // ans 记录最终答案（最长准回文子串长度）
        for (int i = 0; i < n; ++i) {  // 枚举每一个扩展中心
            ans = max(ans, f(i, i));  // 奇数长度中心：以 i 为单个字符中心
            ans = max(ans, f(i, i + 1));  // 偶数长度中心：以 i 与 i+1 之间为中心
        }  // 中心枚举结束

        return ans;  // 返回最长准回文子串的长度
    }  // almostPalindromic 方法结束
};  // 解题类定义结束
