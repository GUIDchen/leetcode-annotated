# 3853. 合并靠近字符 / Merge Close Characters（中等）
# 核心思路：按题目规定的从左到右顺序扫描，用哈希表记录每个字符上一次保留下来的下标；若同一字符当前位置与上次保留位置的距离不超过 k，就把右边的并入左边（丢弃），否则保留并更新下标。
# 复杂度：时间 O(n)，空间 O(σ)，σ 为出现过的字符种类数。
class Solution:  # 设计一个算法：把距离不超过 k 的相同字符合并到左边那个
    def mergeCharacters(self, s: str, k: int) -> str:  # 返回所有可合并的字符对合并完毕后的字符串
        last = {}  # 记录每个字符上一次“保留”在结果中的下标
        ans = []  # 结果字符列表，长度实时变化，相当于题目里的“当前字符串”
        for c in s:  # 从左到右扫描原串（与题目要求的合并优先顺序一致）
            cur = len(ans)  # 当前字符将要落到结果中的下标
            if c in last and cur - last[c] <= k:  # 同字符上次保留位置距此不超过 k，说明二者“靠近”，应当合并
                continue  # 右边的字符并入左边：直接丢弃当前字符
            ans.append(c)  # 不靠近（或首次出现）：把当前字符追加到结果中
            last[c] = cur  # 记下该字符新的保留下标，供之后判断距离
        return "".join(ans)  # 把字符列表拼回字符串返回
