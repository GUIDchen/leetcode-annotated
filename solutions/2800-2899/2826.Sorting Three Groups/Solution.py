# 题目：2826. 将三个组排序（Sorting Three Groups）
# 思路：动态规划，f[g] 表示把已处理的前缀整理成非降的 1、2、3 三组、且最后一个元素落在第 g+1 组时的最少修改次数，逐元素转移。
# 时间复杂度：O(n)，每个元素只做常数次状态转移；空间复杂度：O(1)，只保留长度为 3 的 DP 列表。
class Solution:  # LeetCode 约定的题解类
    def minimumOperations(self, nums: List[int]) -> int:  # nums：只含 1/2/3 的数组；返回把它改成「若干 1、若干 2、若干 3」所需的最少修改次数
        f = [0] * 3  # f[g]：前缀整理完毕、末元素属于第 g+1 组时的最少修改次数，空前缀时三种情况都是 0
        for x in nums:  # 逐个把元素并入前缀
            g = [0] * 3  # 本轮 DP 结果，算完再整体替换，避免原地更新污染状态
            if x == 1:  # 当前值是 1，按它被归入哪一组分别讨论
                g[0] = f[0]  # 放进第 1 组：1 本来就是 1，不需要修改
                g[1] = min(f[:2]) + 1  # 放进第 2 组：f[:2] 取前两组的最小值，再把 1 改成 2，代价加 1
                g[2] = min(f) + 1  # 放进第 3 组：前一个可以来自任意组，再把 1 改成 3，代价加 1
            elif x == 2:  # 当前值是 2，同样按归入的组分别讨论
                g[0] = f[0] + 1  # 放进第 1 组：要把 2 改成 1，代价加 1
                g[1] = min(f[:2])  # 放进第 2 组：2 本来就是 2，前一个只能在第 1/2 组，取 f[:2] 的最小值
                g[2] = min(f) + 1  # 放进第 3 组：要把 2 改成 3，代价加 1，前一个可以来自任意组
            else:  # 当前值只能是 3
                g[0] = f[0] + 1  # 放进第 1 组：要把 3 改成 1，代价加 1
                g[1] = min(f[:2]) + 1  # 放进第 2 组：要把 3 改成 2，代价加 1，前一个只能在第 1/2 组
                g[2] = min(f)  # 放进第 3 组：3 本来就是 3，不需要修改，前一个可以来自任意组
            f = g  # 用本轮结果替换上一轮
        return min(f)  # 末元素可以停在任意一组，取最小值作为答案
