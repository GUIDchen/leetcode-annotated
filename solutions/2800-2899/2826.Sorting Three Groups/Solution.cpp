// 题目：2826. 将三个组排序（Sorting Three Groups）
// 思路：动态规划，f[g] 表示把已处理的前缀整理成非降的 1、2、3 三组、且最后一个元素落在第 g+1 组时的最少修改次数，逐元素转移。
// 时间复杂度：O(n)，每个元素只做常数次状态转移；空间复杂度：O(1)，只保留长度为 3 的 DP 数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumOperations(vector<int>& nums) {  // nums：只含 1/2/3 的数组；返回把它改成「若干 1、若干 2、若干 3」所需的最少修改次数
        vector<int> f(3);  // f[g]：前缀整理完毕、末元素属于第 g+1 组时的最少修改次数，空前缀时三种情况都是 0
        for (int x : nums) {  // 逐个把元素并入前缀
            vector<int> g(3);  // 本轮的 DP 结果，先算到 g 再整体替换，避免原地更新时读到被覆盖的旧值
            if (x == 1) {  // 当前值是 1，按它被归入哪一组分别讨论
                g[0] = f[0];  // 放进第 1 组：1 本来就是 1，不需要修改
                g[1] = min(f[0], f[1]) + 1;  // 放进第 2 组：前一个只能在第 1/2 组，且要把这个 1 改成 2，代价再加 1
                g[2] = min({f[0], f[1], f[2]}) + 1;  // 放进第 3 组：前一个可以来自任意组，且要把这个 1 改成 3，代价再加 1
            } else if (x == 2) {  // 当前值是 2，同样按归入的组分别讨论
                g[0] = f[0] + 1;  // 放进第 1 组：要把 2 改成 1，代价再加 1
                g[1] = min(f[0], f[1]);  // 放进第 2 组：2 本来就是 2，前一个只能在第 1/2 组
                g[2] = min(f[0], min(f[1], f[2])) + 1;  // 放进第 3 组：要把 2 改成 3，代价再加 1，前一个可以来自任意组
            } else {  // 当前值只能是 3
                g[0] = f[0] + 1;  // 放进第 1 组：要把 3 改成 1，代价再加 1
                g[1] = min(f[0], f[1]) + 1;  // 放进第 2 组：要把 3 改成 2，代价再加 1，前一个只能在第 1/2 组
                g[2] = min(f[0], min(f[1], f[2]));  // 放进第 3 组：3 本来就是 3，不需要修改，前一个可以来自任意组
            }  // 三种取值讨论结束
            f = move(g);  // 用本轮结果覆盖上一轮（move 转移 vector 的缓冲区，省去一次深拷贝）
        }  // 所有元素处理完毕
        return min({f[0], f[1], f[2]});  // 末元素可以停在第 1/2/3 任意一组，取三种情况中的最小值作为答案
    }  // 方法结束
};  // 类定义结束