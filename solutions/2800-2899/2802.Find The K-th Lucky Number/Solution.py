# 题目：2802. 找出第 K 个幸运数字（Find The K-th Lucky Number）
# 思路：幸运数字按位数分组，第 n 位有 2^n 个；先减掉更短位数的个数定出位数，再逐位按前后半区选 4 或 7。
# 时间复杂度：O(log k)，即幸运数字的位数；空间复杂度：O(log k)，用于存放答案字符列表。
class Solution:  # LeetCode 约定的题解类
    def kthLuckyNumber(self, k: int) -> str:  # k：从 1 开始计数的序号，返回第 k 个幸运数字
        n = 1  # n：当前考虑的位数，从 1 位开始
        while k > 1 << n:  # 位数为 n 的幸运数字共有 2^n 个，k 超出这一组就跳到下一组（<< 优先级高于 >）
            k -= 1 << n  # 减掉这一组的 2^n 个数字
            n += 1  # 位数加一，继续向后找
        ans = []  # ans：用列表逐位收集答案字符，最后再拼接
        while n:  # 从最高位开始逐位构造
            n -= 1  # 先自减，此时 n 表示「当前位之后还剩多少位」
            if k <= 1 << n:  # 落在前一半（共 2^n 个候选），当前位应该是 4
                ans.append("4")  # 该位放 '4'
            else:  # 落在后一半
                ans.append("7")  # 该位放 '7'
                k -= 1 << n  # 减去前一半的个数，把 k 换算成后一半中的相对序号
        return "".join(ans)  # 把字符列表拼成字符串返回
