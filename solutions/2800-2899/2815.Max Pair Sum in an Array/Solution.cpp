// 题目：2815. 数组中的最大数对和（Max Pair Sum in an Array）
// 思路：枚举所有下标对，用辅助函数求每个数的最大数位，最大数位相同才构成数对，在合法数对中取最大的元素和。
// 时间复杂度：O(n²·log V)，枚举数对 O(n²)，每次求最大数位 O(log V)；空间复杂度：O(1)，只用了常数个变量。
class Solution {  // 题解类：暴力枚举所有下标对
public:  // 题解方法对外可见
    int maxSum(vector<int>& nums) {  // nums：输入数组；返回满足条件的最大数对和，没有合法数对时返回 -1
        int ans = -1;  // 答案初值取 -1，与「不存在合法数对」的返回值一致
        int n = nums.size();  // 数组长度，避免循环里反复调用 size()
        auto f = [](int x) {  // 辅助 lambda：求十进制整数 x 的最大数位
            int y = 0;  // y 保存目前见到的最大数位，初始为 0
            for (; x; x /= 10) {  // 每轮取最低位，x 逐次除以 10 直到变成 0
                y = max(y, x % 10);  // x % 10 是当前最低位，用它更新最大值
            }
            return y;  // 返回最大数位
        };  // lambda 定义结束
        for (int i = 0; i < n; ++i) {  // 枚举第一个下标 i
            for (int j = i + 1; j < n; ++j) {  // 第二个下标只需从 i+1 开始，避免同一对重复计算
                int v = nums[i] + nums[j];  // 当前数对的元素和
                if (ans < v && f(nums[i]) == f(nums[j])) {  // 和比已知答案大，且两个数的最大数位相同时才更新答案
                    ans = v;  // 更新最大数对和
                }
            }  // 内层循环结束
        }  // 外层循环结束
        return ans;  // 返回答案；没有任何合法数对时仍是 -1
    }
};