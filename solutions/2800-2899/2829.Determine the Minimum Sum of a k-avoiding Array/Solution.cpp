// 题目：2829. k-avoiding 数组的最小总和（Determine the Minimum Sum of a k-avoiding Array）
// 思路：贪心，从 1 开始按升序尝试每个数能取就取；取走 i 之后立刻禁用它的搭档 k-i，保证之后不会再选出和为 k 的两个数。
// 时间复杂度：O(n + k)，i 单调递增且最多被禁用掉 n 个数；空间复杂度：O(n + k)，vis 标记数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumSum(int n, int k) {  // n：需要选出几个数；k：禁止出现和为 k 的两个数；返回满足条件的 n 个数的最小总和
        int s = 0, i = 1;  // s 是已经选出的数之和，i 是当前尝试的最小候选数，从 1 开始
        bool vis[n + k + 1];  // 标记数组：vis[v] 为真表示 v 已被选走或被禁用；长度按「最多选 n 个、最大禁用值小于 k」估算（变长数组是 GNU 扩展）
        memset(vis, false, sizeof(vis));  // 全部置为 false，初始时没有任何数被选走或禁用
        while (n--) {  // 还需要挑 n 个数，每轮挑一个，n-- 同时完成自减
            while (vis[i]) {  // 跳过一切被标记的数，找到当前可用的最小候选
                ++i;  // 候选数前移，直到落在一个可用位置
            }  // 已定位到可用的最小候选 i
            if (k >= i) {  // 只有 k - i >= 0 时才存在搭档，这个判断同时防止下标为负越界
                vis[k - i] = true;  // 禁用搭档 k - i，否则以后选出它就会与 i 凑成和为 k
            }  // 本轮禁用逻辑结束
            s += i++;  // 把 i 计入总和，并让候选数前移一位（i 本身已被选走，不会重复选）
        }  // n 个数已经选完
        return s;  // 返回这 n 个数的最小总和
    }  // 方法结束
};  // 类定义结束
