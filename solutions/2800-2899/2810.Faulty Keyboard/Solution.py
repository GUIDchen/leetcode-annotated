# 题目：2810. 故障键盘（Faulty Keyboard）
# 思路：用列表 t 累积已输入的字符；遇到 'i' 就把 t 切片反转，其他字符追加到末尾，最后拼接成字符串返回。
# 时间复杂度：O(n^2)，最坏情况下每个 'i' 都要反转一次当前串；空间复杂度：O(n)，结果长度不超过输入长度。
class Solution:  # LeetCode 约定的题解类
    def finalString(self, s: str) -> str:  # s：按键序列；返回最终屏幕上显示的字符串
        t = []  # 用列表累积已输入的字符，追加操作的均摊代价是 O(1)
        for c in s:  # 按顺序处理每一次按键
            if c == "i":  # 按下 'i'：触发整串反转
                t = t[::-1]  # 切片 t[::-1] 生成反转后的新列表，再赋值回去
            else:  # 其他字符直接追加
                t.append(c)  # 把字符追加到列表末尾
        return "".join(t)  # 把字符列表拼接成最终字符串返回
