// 题目：2380. 二进制字符串重新安排顺序需要的时间（Time Needed to Rearrange a Binary String）
// 思路：按题意直接模拟。每一秒把所有互不重叠的 "01" 同时替换成 "10"（一次扫描内交换后跳过一位即可保证互不重叠），直到某一秒没有任何 "01" 为止，秒数即为答案。
// 时间复杂度：O(n^2)，最坏每秒都要完整扫描一遍字符串；空间复杂度：O(1)，只在原串上原地交换。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int secondsToRemoveOccurrences(string s) {  // s 为只含 '0' 与 '1' 的字符串，返回全部 1 移到左侧所需的秒数
        bool find = true;  // 标记本轮是否发生过替换；初值 true 是为了进入第一轮循环
        int ans = 0;  // ans 记录已经过的秒数
        while (find) {  // 只要上一轮仍有 "01" 被替换，就继续模拟下一秒
            find = false;  // 先假设本轮没有任何替换，若扫描中发现 "01" 再置为 true
            for (int i = 0; i < s.size() - 1; ++i) {  // 从左到右扫描所有相邻位置（注意上界是 size() - 1，避免越界）
                if (s[i] == '0' && s[i + 1] == '1') {  // 找到一处 "01"，本秒可以把它交换成 "10"
                    swap(s[i], s[i + 1]);  // 原地交换这两个字符，权重不涉及额外空间
                    ++i;  // 跳过下一位，保证同一秒内的交换互不重叠（模拟同时替换）
                    find = true;  // 标记本轮确实发生了替换
                }  // if 语句结束
            }  // 本轮扫描结束
            if (find) {  // 只要本轮有替换，就说明又过去了一秒
                ++ans;  // 秒数加一
            }  // if 语句结束
        }  // while 循环结束（本轮无替换说明串已无法再变，全部 1 已在左侧）
        return ans;  // 返回总秒数
    }  // secondsToRemoveOccurrences 方法结束
};  // Solution 类结束