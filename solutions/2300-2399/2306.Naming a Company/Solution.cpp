// 题目：2306. 公司命名（Naming a Company）
// 思路：先统计 f[i][j] = 首字母为 i、且把首字母换成 j 后仍不与已有名字冲突的名字个数，再对每个名字用 f[j][i] 配对累加，得到所有合法组合数。
// 时间复杂度：O(26 * n * L)，n 个名字、每次换首字母查一次哈希表（L 为名字长度）；空间复杂度：O(n + 26^2)，哈希表存全部名字外加 26x26 的计数表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long distinctNames(vector<string>& ideas) {  // ideas：已有的公司名字列表，任选两个不同名字交换首字母生成新名字
        unordered_set<string> s(ideas.begin(), ideas.end());  // 把已有名字放进哈希集合，用来 O(1) 判断候选新名字是否与已有名字冲突
        int f[26][26]{};  // f[i][j]：首字母为 i 的名字中，把首字母改成 j 后仍不和已有名字冲突的个数；{} 保证全部初始化为 0
        for (auto v : ideas) {  // 第一轮：枚举每个已有名字，按它的首字母分类统计
            int i = v[0] - 'a';  // i 是该名字的原首字母编号（0 对应 a）
            for (int j = 0; j < 26; ++j) {  // 枚举所有可能替换成的首字母 j
                v[0] = j + 'a';  // 临时把首字母改成 j，得到候选新名字（v 是值拷贝，不污染原数据）
                if (!s.count(v)) {  // 若该候选名字不在已有集合里，说明这个替换是合法的
                    ++f[i][j];  // 合法替换计数加一
                }  // if 分支结束
            }  // 替换字母枚举结束
        }  // 本轮名字枚举结束
        long long ans = 0;  // ans 用 long long 累计，避免两两组合的数量超出 int
        for (auto& v : ideas) {  // 第二轮：换一个视角，枚举每个名字，统计它能与哪些名字配对
            int i = v[0] - 'a';  // i 是该名字的原首字母编号
            for (int j = 0; j < 26; ++j) {  // 枚举把该名字首字母替换成 j
                v[0] = j + 'a';  // 把首字母改成 j，判断这个替换是否合法
                if (!s.count(v)) {  // 只有当前名字换成 j 合法时，才能和“首字母为 j、换成 i 也合法”的名字组成一对
                    ans += f[j][i];  // 累加 f[j][i]：首字母为 j 且改成 i 合法的名字个数，正好是能与当前名字配对的数量（有序对）
                }  // if 分支结束
            }  // 替换字母枚举结束
        }  // 本轮名字枚举结束
        return ans;  // 返回所有合法有序对的数量
    }  // 方法结束
};  // 类定义结束