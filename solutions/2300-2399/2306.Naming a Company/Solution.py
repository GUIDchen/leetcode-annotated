# 题目：2306. 公司命名（Naming a Company）
# 思路：先统计 f[i][j] = 首字母为 i、且把首字母换成 j 后仍不与已有名字冲突的名字个数，再对每个名字用 f[j][i] 配对累加，得到所有合法组合数。
# 时间复杂度：O(26 * n * L)，n 个名字、每次换首字母查一次哈希表（L 为名字长度）；空间复杂度：O(n + 26^2)，哈希表存全部名字外加 26x26 的计数表。
class Solution:  # LeetCode 约定的题解类
    def distinctNames(self, ideas: List[str]) -> int:  # ideas：已有的公司名字列表，任选两个不同名字交换首字母生成新名字
        s = set(ideas)  # 转成集合，用来 O(1) 判断候选新名字是否与已有名字冲突
        f = [[0] * 26 for _ in range(26)]  # f[i][j]：首字母为 i 的名字中，把首字母改成 j 后仍不和已有名字冲突的个数
        for v in ideas:  # 第一轮：枚举每个已有名字，按它的首字母分类统计
            i = ord(v[0]) - ord('a')  # i 是该名字的原首字母编号（0 对应 a）
            t = list(v)  # 把字符串拆成字符列表，便于原地修改首字母
            for j in range(26):  # 枚举所有可能替换成的首字母 j
                t[0] = chr(ord('a') + j)  # 把首字母改成 chr('a' + j)，得到候选新名字
                if ''.join(t) not in s:  # 若该候选名字不在已有集合里，说明这个替换是合法的
                    f[i][j] += 1  # 合法替换计数加一
        ans = 0  # ans 累计答案
        for v in ideas:  # 第二轮：换一个视角，枚举每个名字，统计它能与哪些名字配对
            i = ord(v[0]) - ord('a')  # i 是该名字的原首字母编号
            t = list(v)  # 同样把字符串拆成字符列表以便修改首字母
            for j in range(26):  # 枚举把该名字首字母替换成 j
                t[0] = chr(ord('a') + j)  # 把首字母改成 chr('a' + j)，判断这个替换是否合法
                if ''.join(t) not in s:  # 只有当前名字换成 j 合法时，才能和“首字母为 j、换成 i 也合法”的名字组成一对
                    ans += f[j][i]  # 累加 f[j][i]：首字母为 j 且改成 i 合法的名字个数，正好是能与当前名字配对的数量（有序对）
        return ans  # 返回所有合法有序对的数量
