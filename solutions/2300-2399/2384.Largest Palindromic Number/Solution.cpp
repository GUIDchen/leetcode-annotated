// 题目：2384. 最大回文数字（Largest Palindromic Number）
// 核心思路：统计 0~9 各数字的出现次数，先用最大的奇数次数数字做中心，再把成对的数字按从大到小依次贴到两端，最后去掉前导零，得到能组成的最大回文数。
// 时间复杂度：O(n)，n 为 num 长度，计数与拼接都是线性；空间复杂度：O(1)，计数数组固定长度 10，答案串长度不超过 n。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string largestPalindromic(string num) {  // num：只含数字字符的字符串；返回能组成的最大的回文数字串
        vector<int> cnt(10);  // cnt[d] 表示数字 d（0~9）在 num 中出现的次数
        for (char c : num) ++cnt[c - '0'];  // 遍历每一位字符，用 c - '0' 把字符换算成 0~9 的下标后累加
        string mid = "";  // mid 保存回文最中间的那一位字符，最多一个，也可能为空
        for (int i = 9; ~i; --i) {  // 从 9 往 0 找第一个出现奇数次的数字，贪心让中间位尽量大
            if (cnt[i] % 2) {  // 该数字剩余次数是奇数，说明可以单独拿一个出来当中心
                mid += (i + '0');  // 把数字 i 转成字符追加到中心位
                --cnt[i];  // 用掉一个后剩余次数变成偶数，正好可以两两配对放到两边
                break;  // 中心位最多只能有一个数字，选定后立即结束查找
            }  // 结束 if 分支
        }  // 结束中心位的查找循环
        string t = "";  // t 收集回文左半部分（含可成对的数字），下面按升序写入
        for (int i = 0; i < 10; ++i) {  // 从小到大遍历数字，保证 t 本身就是升序，反转后才是降序
            if (cnt[i]) {  // 该数字还有剩余次数（此刻一定是偶数次）
                cnt[i] >>= 1;  // 右移一位等价于除以 2，得到该数字能配成的对数
                while (cnt[i]--) {  // 循环 cnt[i] 次，每次往 t 里放一对中的一个
                    t += (i + '0');  // 把数字 i 转成字符追加到左半部分
                }  // 结束 while 写字符的循环
            }  // 结束 if 分支
        }  // 结束填充 t 的循环
        while (t.size() && t.back() == '0') {  // 左半部分末尾的 '0' 会成为最终数字的前导零，必须全部去掉
            t.pop_back();  // 弹出末尾的这个 '0'
        }  // 结束去零循环
        string ans = t;  // 复制左半部分，用来生成右半部分
        reverse(ans.begin(), ans.end());  // 反转得到降序的右半部分，保证拼出的数值最大
        ans += mid + t;  // 拼接顺序：右半部分 + 中间位 + 左半部分，得到完整回文
        return ans == "" ? "0" : ans;  // 结果为空串说明只有 0，按题意返回 "0"；否则返回该回文串
    }  // 结束方法体
};  // 结束题解类