# 题目：2384. 最大回文数字（Largest Palindromic Number）
# 核心思路：用 Counter 统计各数字次数，先取最大的奇数次数字当中心，再把成对的数字从大到小依次贴到两端，最后剥掉前导零。
# 时间复杂度：O(n)，n 为 num 长度，统计与拼接均线性；空间复杂度：O(1)，计数器最多 10 个键，答案串长度不超过 n。
class Solution:  # LeetCode 约定的题解类
    def largestPalindromic(self, num: str) -> str:  # num 是只含数字字符的字符串，返回能组成的最大的回文数字串
        cnt = Counter(num)  # 统计每个数字字符出现的次数，键是 '0'~'9' 这样的单字符
        ans = ''  # ans 作为回文中心与两翼的拼接容器，先置为空串
        for i in range(9, -1, -1):  # 从 9 递减到 0，优先挑选数值大的数字当中心位
            v = str(i)  # 把整数 i 转成对应的单字符，方便当计数器键使用
            if cnt[v] % 2:  # 该数字出现奇数次，可以单独留一个当回文中心
                ans = v  # 把它放到中心，注意这里是覆盖 ans，中心位只应有一个
                cnt[v] -= 1  # 用掉一个后剩余次数变成偶数，可成对分到两边
                break  # 中心位确定，跳出查找
        for i in range(10):  # 从小到大遍历 0~9，让成对的数字按升序拼进两侧
            v = str(i)  # 同样先把整数转换成单字符键
            if cnt[v]:  # 该数字还有剩余次数（此时必为偶数）
                cnt[v] //= 2  # 整除 2 得到能配成的对数
                s = cnt[v] * v  # 用字符串乘法一次性生成这 v 的若干份，即这一对中的一半
                ans = s + ans + s  # 把 s 同时贴到 ans 左右两边，保持原有中心不变
        return ans.strip('0') or '0'  # strip('0') 去掉两端的前导/尾随零，若为空说明只能返回 '0'
