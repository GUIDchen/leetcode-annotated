// 题目：2342. 数位和相等数对的最大和（Max Sum of a Pair With Equal Sum of Digits）
// 思路：用桶 d[数位和] 记录该数位和下出现过的最大值；顺序扫描，遇到 v 时先用桶里已有的最大元素与 v 组成数对更新答案，再把 v 写回桶。
// 时间复杂度：O(n log M)，M 为元素最大值，需要逐位拆解数位；空间复杂度：O(1)，桶长 100 固定（最大数位和为 81）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maximumSum(vector<int>& nums) {  // nums：输入数组；返回数位和相等数对的最大和，不存在则返回 -1
        int d[100]{};  // 桶数组按数位和索引，记录该数位和下出现过的最大值；最大数位和 81，100 足够
        int ans = -1;  // 不存在合法数对时的返回值就是 -1
        for (int v : nums) {  // 顺序扫描每个元素
            int x = 0;  // x 累计 v 的数位和
            for (int y = v; y; y /= 10) {  // y 逐位剥离：y 为 0 时说明所有数位已取完，循环自然结束
                x += y % 10;  // 取最低位数字累加到 x
            }  // 数位拆解结束
            if (d[x]) {  // 桶非 0 说明之前有相同数位和的元素（元素都是正数，0 可安全表示“空”）
                ans = max(ans, d[x] + v);  // 用桶中最大值与当前 v 配对，尝试更新答案
            }  // 结束配对判断
            d[x] = max(d[x], v);  // 把 v 也写进桶，维护该数位和下的最大值；先查询后写入保证不会自己和自己配对
        }  // 扫描结束
        return ans;  // 返回最大和，若从未配对成功则保持 -1
    }  // 方法结束
};  // 类结束