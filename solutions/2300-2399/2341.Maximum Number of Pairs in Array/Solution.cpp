// 题目：2341. 数组能形成多少数对（Maximum Number of Pairs in Array）
// 思路：值域只有 0..100，先用计数数组统计每个值的出现次数，再对每个值取次数的一半累加得到对数，落单个数 = 总元素数 - 对数 * 2。
// 时间复杂度：O(n + 101) 即 O(n)；空间复杂度：O(101) 即 O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> numberOfPairs(vector<int>& nums) {  // nums：输入数组；返回 {数对数目, 落单数目}
        vector<int> cnt(101);  // 计数数组，长度 101 覆盖值域 0..100，默认初始化为 0
        for (int& x : nums) {  // 第一遍：按值统计出现次数
            ++cnt[x];  // 用引用遍历以免拷贝，值为 x 的次数加一
        }  // 统计结束
        int s = 0;  // s 累计能配成的数对总数
        for (int& v : cnt) {  // 第二遍：遍历整个值域
            s += v >> 1;  // v >> 1 即 v/2 向下取整，就是一个值能配出的对数
        }  // 配对统计结束
        return {s, (int) nums.size() - s * 2};  // 第一个元素是对数；第二个元素是总元素数减去已成对的 2s 个，即落单个
    }  // 方法结束
};  // 类结束