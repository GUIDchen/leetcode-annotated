// 题目：2315. 统计星号（Count Asterisks）
// 思路：一次扫描，用开关 ok 记录当前是否处在「成对竖线」之外；只有 ok 为 1 时遇到 '*' 才计数，遇到 '|' 就翻转开关。
// 时间复杂度：O(n)，字符串只扫一遍；空间复杂度：O(1)，只用两个整型变量。
int countAsterisks(char* s) {  // s：输入字符串，返回不在成对竖线之间的星号数量
    int ans = 0;  // 计数器：有效星号的个数
    int ok = 1;  // 开关：1 表示在两竖线之外（可计数），0 表示在两竖线之间（不可计数）
    for (int i = 0; s[i]; i++) {  // 以结尾的 '\0' 作为循环条件，遍历整个字符串
        if (s[i] == '*') {  // 遇到星号
            ans += ok;  // 只有在竖线对之外时才累加（ans += 0 等于不加）
        } else if (s[i] == '|') {  // 遇到竖线：竖线成对出现，进入或离开区间
            ok ^= 1;  // 在 0/1 之间翻转状态
        }
    }
    return ans;  // 返回统计结果
}