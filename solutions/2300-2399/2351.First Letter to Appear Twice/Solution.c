// 题目：2351. 第一个出现两次的字母（First Letter to Appear Twice）
// 思路：用长度 26 的计数数组记录每个字母出现次数，顺序扫描，第一个让计数变成 2 的字母就是答案。
// 时间复杂度：O(n)，只扫描一次；空间复杂度：O(1)，只用了固定的 26 个计数槽。
char repeatedCharacter(char* s) {  // s：只含小写字母的字符串，返回第一个出现两次的字母
    int vis[26] = {0};  // 每个字母的出现次数，初始全为 0
    for (int i = 0; s[i]; i++) {  // 逐字符扫描，遇到字符串结束符就停下
        if (vis[s[i] - 'a']) {  // 该字母此前已经出现过至少一次
            return s[i];  // 它就是第一个出现两次的字母
        }
        vis[s[i] - 'a']++;  // 首次出现，把它的计数加一
    }
    return ' ';  // 题目保证有答案，理论上不会走到这里，返回空格占位
}