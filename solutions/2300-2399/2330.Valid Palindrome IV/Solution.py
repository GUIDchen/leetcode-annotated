# 题目：2330. 验证回文串 IV（Valid Palindrome IV）
# 思路：双指针从两端向中间比较，统计对称位置不相等的字符对数；每对不相等最多用一次替换修好，
#       因此只要不匹配对数不超过 2 就能变成回文串；时间复杂度 O(n)，空间复杂度 O(1)。
class Solution:  # LeetCode 约定的题解类
    def makePalindrome(self, s: str) -> bool:  # s 是待判断的字符串
        i, j = 0, len(s) - 1  # 左右两个指针，分别指向字符串首尾
        cnt = 0  # 计数器：记录对称位置字符不相等的对数
        while i < j:  # 双指针向中间靠拢，i 与 j 相遇或交错即停止
            cnt += s[i] != s[j]  # 布尔值参与加法：不相等时 cnt 加 1，否则加 0
            i, j = i + 1, j - 1  # 左指针右移一位，右指针左移一位
        return cnt <= 2  # 最多允许 2 对不匹配，满足则能通过替换变成回文串
