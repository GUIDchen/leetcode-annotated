// 题目：2330. 验证回文串 IV（Valid Palindrome IV）
// 思路：双指针从两端向中间比较，统计对称位置不相等的字符对数；每对不相等最多用一次替换修好，
//       因此只要不匹配对数不超过 2 就能变成回文串；时间复杂度 O(n)，空间复杂度 O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool makePalindrome(string s) {  // s 是待判断的字符串
        int cnt = 0;  // 计数器：记录对称位置字符不相等的对数
        int i = 0, j = s.size() - 1;  // 左右两个指针，分别指向首尾
        for (; i < j; ++i, --j) {  // 双指针向中间靠拢，i 与 j 相遇即停止
            cnt += s[i] != s[j];  // 布尔值参与加法：不相等时 cnt 加 1，否则加 0
        }  // 循环体结束
        return cnt <= 2;  // 没有越界时 i > j 退出循环；最多允许 2 对不匹配
    }  // 方法结束
};  // 类定义结束