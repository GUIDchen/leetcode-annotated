# 题目：2378. 选择边来最大化树的得分（Choose Edges to Maximize Score in a Tree）
# 思路：树上最大权匹配的树形 DP。dfs(i) 返回 (父边被选中时子树最优值, 父边未被选中时子树最优值)；父边被选则子边全禁，父边未选则用「w + 选子边的值 - 不选子边的值」挑一条净增益最大的子边。
# 时间复杂度：O(n)，每个节点只被 DFS 访问一次；空间复杂度：O(n)，邻接表与递归栈各占 O(n)。
class Solution:  # LeetCode 约定的题解类
    def maxScore(self, edges: List[List[int]]) -> int:  # edges[i] = [父节点, 边权]，返回互不相邻的边的最大权值和
        def dfs(i):  # 递归函数：i 为当前子树根，返回该子树在两种父边状态下的最优得分
            a = b = t = 0  # a：父边被选中时的得分；b：父边未被选中时的得分；t：额外选一条子边的最大净增益
            for j, w in g[i]:  # 遍历 i 的每条子边 (i, j)，w 为该边权重
                x, y = dfs(j)  # 递归求出子节点 j 的两种状态值：x = 选中该子边的值，y = 不选该子边的值
                a += y  # 父边被选时 i 已被占用，子边一条都不能选，只累加子树的「父边未选」值 y
                b += y  # 父边未被选时先按「子边全不选」累加 y，稍后再决定是否加一条子边的增益
                t = max(t, x - y + w)  # 选中 (i, j) 的净增益为 w + x - y，在所有子边中取最大
            b += t  # 至多再选一条子边：加入最优净增益 t（t 为 0 表示一条都不选）
            return a, b  # 按 (父边被选, 父边未被选) 的顺序返回两个值

        # ——— 以下是建图与入口：先建邻接表，再从根节点 0 开始求解 ———
        g = defaultdict(list)  # 邻接表：键为父节点，值为 (子节点, 边权) 列表
        for i, (p, w) in enumerate(edges[1:], 1):  # edges[1:] 跳过根的占位项，enumerate 的起始下标设为 1 以对应节点编号
            g[p].append((i, w))  # 把子节点 i 连同边权挂到父节点 p 的邻接表上
        return dfs(0)[1]  # 根节点没有父边，等价于「父边未被选中」，取下标 1 的值
