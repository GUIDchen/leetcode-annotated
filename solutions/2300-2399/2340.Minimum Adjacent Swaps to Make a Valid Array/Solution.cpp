// 题目：2340. 生成有效数组的最少交换次数（Minimum Adjacent Swaps to Make a Valid Array）
// 思路：有效数组要求队首是最小值、队尾是最大值，因此只需把最小值移到最前、最大值移到最后；贪心取最小值的最左下标 i 与最大值的最右下标 j，答案是 i + (n-1-j)，当 i > j 时两条路径交叉，中间那一次交换被共用，需要减 1。
// 时间复杂度：O(n)，一次线性扫描；空间复杂度：O(1)，只用了常数个下标变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumSwaps(vector<int>& nums) {  // nums：输入数组；返回最少的相邻交换次数
        int n = nums.size();  // 记录数组长度，后面算尾部偏移要用
        int i = 0, j = 0;  // i 记录最小值的最左下标，j 记录最大值的最右下标
        for (int k = 0; k < n; ++k) {  // 一次线性扫描，同时维护这两个下标
            if (nums[k] < nums[i] || (nums[k] == nums[i] && k < i)) {  // 更小，或值相同但更靠左，都想把 i 往左挪
                i = k;  // 贪心取最小值的最左出现位置，这样移到队首的步数最少
            }  // 结束最小值判断
            if (nums[k] > nums[j] || (nums[k] == nums[j] && k > j)) {  // 更大，或值相同但更靠右，都想把 j 往右挪
                j = k;  // 贪心取最大值的最右出现位置，这样移到队尾的步数最少
            }  // 结束最大值判断
        }  // 扫描结束，i、j 就是最终要移动的两个端点元素
        if (i == j) {  // 两个下标重合，说明最值本就是同一个元素
            return 0;  // 已经满足有效条件，无需交换
        }  // 结束特判
        return i + n - 1 - j - (i > j);  // i 步把最小值换到队首，(n-1-j) 步把最大值换到队尾；i > j 时二者会交叉，那一次交换被两段共用故减 1
    }  // 方法结束
};  // 类结束