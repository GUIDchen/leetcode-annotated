// 题目：2370. 最长理想子序列（Longest Ideal Subsequence）
// 核心思路：动态规划 + 26 个字母「最近出现下标」表；dp[i] 表示以 s[i] 结尾的最长理想子序列长度，枚举与 s[i] 相差不超过 k 的前驱字符来承接。
// 时间复杂度：O(26n)，即 O(n)，每个位置只枚举 26 个字母；空间复杂度：O(n)，dp 数组与哈希表的开销。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int longestIdealString(string s, int k) {  // s：只含小写字母的字符串；k：相邻字符差的绝对值上限
        int n = s.size();  // 先取字符串长度，后面建 dp 和循环都要用到
        int ans = 1;  // 答案至少是单个字符，所以初值设为 1
        vector<int> dp(n, 1);  // dp[i]：以 s[i] 结尾的最长理想子序列长度，至少能只取自己，故初始化为 1
        unordered_map<char, int> d;  // 哈希表：字符 → 它最后一次出现的下标，用于 O(1) 承接前驱
        d[s[0]] = 0;  // 第一个字符之前没有前驱，先把它的下标记入表中
        for (int i = 1; i < n; ++i) {  // 从第二个字符开始逐个向右计算 dp
            char a = s[i];  // 当前字符 a，作为子序列的结尾
            for (char b = 'a'; b <= 'z'; ++b) {  // 枚举 26 种可能的前驱字符 b（只有 26 个，代价很小）
                if (abs(a - b) > k) continue;  // 相邻字符差值超过 k 就不理想，直接跳过这个前驱
                if (d.count(b)) dp[i] = max(dp[i], dp[d[b]] + 1);  // b 曾经出现过：拿 b 的最近下标承接，长度加一后与现有值取较大者
            }  // 26 个前驱都试完了
            d[a] = i;  // 更新 a 的最新下标；越靠后的下标对后续字符越有利
            ans = max(ans, dp[i]);  // 顺手维护全局最大值，避免最后再扫一遍 dp
        }  // 所有位置处理完毕
        return ans;  // 返回最长理想子序列的长度
    }  // 方法结束
};  // 类定义结束