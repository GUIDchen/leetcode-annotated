# 题目：2370. 最长理想子序列（Longest Ideal Subsequence）
# 核心思路：动态规划 + 26 个字母「最近出现下标」字典；dp[i] 表示以 s[i] 结尾的最长理想子序列长度，枚举与 s[i] 相差不超过 k 的前驱字符来承接。
# 时间复杂度：O(26n)，即 O(n)，每个位置只枚举 26 个字母；空间复杂度：O(n)，dp 数组与字典的开销。
class Solution:  # LeetCode 约定的题解类
    def longestIdealString(self, s: str, k: int) -> int:  # s：只含小写字母的字符串；k：相邻字符差的绝对值上限
        n = len(s)  # 先取字符串长度，后面建 dp 和循环都要用到
        ans = 1  # 预留的答案变量（本实现最后直接返回 max(dp)，这个值不再参与计算）
        dp = [1] * n  # dp[i]：以 s[i] 结尾的最长理想子序列长度，至少能只取自己，故全部初始化为 1
        d = {s[0]: 0}  # 字典：字符 → 它最后一次出现的下标，同时把首字符放进表中
        for i in range(1, n):  # 从第二个字符开始逐个向右计算 dp
            a = ord(s[i])  # 把当前字符转成整数，方便用做差来比较相邻字符的差距
            for b in ascii_lowercase:  # 枚举 26 个小写字母作为可能的「前驱字符」
                if abs(a - ord(b)) > k:  # 前驱与当前字符的差距超过 k，就不满足理想子序列要求
                    continue  # 跳过这个不合法前驱，继续试下一个字母
                if b in d:  # 该前驱字符确实在本字符之前出现过
                    dp[i] = max(dp[i], dp[d[b]] + 1)  # 用前驱的最近下标承接，长度加一后与当前最优值取较大者
            d[s[i]] = i  # 更新当前字符的最新下标，越靠后对后续字符越有利
        return max(dp)  # 所有位置算完，整个 dp 的最大值就是以某处结尾的最长理想子序列长度
