// 题目：2381. 字母移位 II（Shifting Letters II）
// 思路：用差分数组把每个区间的带符号位移量 O(1) 地叠加上去，再做一次前缀和还原每个下标的总位移，最后逐字符对 26 取模环绕。
// 时间复杂度：O(n + m)，n 为字符串长度、m 为操作次数；空间复杂度：O(n)，差分数组占 n + 1 个位置。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string shiftingLetters(string s, vector<vector<int>>& shifts) {  // s：待移位的字符串；shifts：每个元素是 [左端点, 右端点, 方向]
        int n = s.size();  // 字符串长度，后续所有下标都以它为界
        vector<int> d(n + 1);  // 差分数组，多开一位用于在右端点 +1 处撤销位移
        for (auto& e : shifts) {  // 逐个处理操作，取引用是为了就地改写方向值
            if (e[2] == 0) {  // 方向 0 表示向前（左）移位，即 -1
                e[2]--;  // 把 0 就地改成 -1，之后统一按带符号的位移量处理
            }
            d[e[0]] += e[2];  // 区间起点处累加位移量
            d[e[1] + 1] -= e[2];  // 区间终点的后一位减去位移量，前缀和时才能只影响 [l, r]
        }
        for (int i = 1; i <= n; ++i) {  // 从左到右做前缀和
            d[i] += d[i - 1];  // 求和后 d[i] 就是第 i 个字符上的累计位移量
        }
        string ans;  // 结果字符串，逐字符追加
        for (int i = 0; i < n; ++i) {  // 遍历每个字符，按累计位移量环绕移位
            int j = (s[i] - 'a' + d[i] % 26 + 26) % 26;  // 字母序号 0~25 加位移后取模；先 % 26 限幅再 +26 避免负数取模得到负值
            ans += ('a' + j);  // 把序号转回小写字母并拼到答案末尾
        }
        return ans;  // 返回整体移位后的字符串
    }
};