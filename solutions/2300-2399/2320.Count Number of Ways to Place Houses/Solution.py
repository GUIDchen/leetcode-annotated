# 题目：2320. 统计放置房子的方式数（Count Number of Ways to Place Houses）
# 核心思路：两侧街道独立，先对单侧 DP：f[i] 表示第 i 位放房子的方案数，g[i] 表示第 i 位不放的方案数；单侧总数 v=f[-1]+g[-1]，两侧答案即 v²。
# 时间复杂度：O(n)，一次线性递推；空间复杂度：O(n)，两个长度为 n 的数组。
class Solution:  # LeetCode 约定的题解类
    def countHousePlacements(self, n: int) -> int:  # n：街道每侧的位置数；返回两侧放置方案数之积（对 1e9+7 取模）
        mod = 10**9 + 7  # 取模常量，防止答案过大
        f = [1] * n  # f[i]：第 i 个位置放房子的方案数，统一初始化为 1
        g = [1] * n  # g[i]：第 i 个位置不放房子的方案数，统一初始化为 1
        for i in range(1, n):  # 从第二个位置开始递推到最后一个位置
            f[i] = g[i - 1]  # 第 i 位放房子要求前一位空着，方案数等于 g[i-1]
            g[i] = (f[i - 1] + g[i - 1]) % mod  # 第 i 位不放时前一位任意，方案数为 f[i-1]+g[i-1]，并取模
        v = f[-1] + g[-1]  # 末位放与不放两类之和，即单侧街道的方案总数
        return v * v % mod  # 两侧互不影响，方案数相乘后对 1e9+7 取模返回
