// 题目：2320. 统计放置房子的方式数（Count Number of Ways to Place Houses）
// 核心思路：街道两侧互不影响，先对单侧做动态规划：f[i] 表示第 i 个位置放房子的方案数，g[i] 表示第 i 个位置不放房子的方案数；单侧总数 v=f[n-1]+g[n-1]，两侧答案即 v²。
// 时间复杂度：O(n)，一次线性递推；空间复杂度：O(n)，两个长度为 n 的数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countHousePlacements(int n) {  // n：街道每侧的位置数；返回两侧放置方案数之积（对 1e9+7 取模）
        const int mod = 1e9 + 7;  // 取模常量，防止答案溢出
        int f[n], g[n];  // f[i]：第 i 个位置放房子的方案数；g[i]：第 i 个位置不放房子的方案数
        f[0] = g[0] = 1;  // 边界：只有 1 个位置时，放与不放各 1 种方案
        for (int i = 1; i < n; ++i) {  // 从第二个位置开始线性递推到第 n 个位置
            f[i] = g[i - 1];  // 第 i 位放房子要求第 i-1 位空着，方案数等于 g[i-1]
            g[i] = (f[i - 1] + g[i - 1]) % mod;  // 第 i 位不放房子时前一位放不放都行，方案数为 f[i-1]+g[i-1]，并取模
        }  // 递推循环结束
        long v = f[n - 1] + g[n - 1];  // 单侧街道的总方案数：末位放 + 末位不放；用 long 存，平方时不会先溢出 32 位
        return v * v % mod;  // 两侧街道相互独立，方案数相乘后对 1e9+7 取模返回
    }  // countHousePlacements 结束
};  // 类定义结束