// 题目：2357. 使数组中所有元素都等于零（Make Array Zero by Subtracting Equal Amounts）
// 思路：每次操作只能减去当前的最小非零值，因此不同的非零值个数就是所需操作次数；用值域 0..100 的标记数组去重计数。
// 时间复杂度：O(n)，扫描一遍数组；空间复杂度：O(1)，长度 101 的定长标记数组。
int minimumOperations(int* nums, int numsSize) {  // nums 是输入数组，numsSize 是长度；返回最少操作次数
    int vis[101] = {0};  // 值域 0..100，标记 v 是否已经出现过，开 101 足够
    vis[0] = 1;  // 0 不需要任何操作，提前标记为已处理
    int ans = 0;  // 统计不同的非零值个数
    for (int i = 0; i < numsSize; i++) {  // 扫描整个数组
        if (vis[nums[i]]) {  // 该值之前已经出现过（含 0）
            continue;  // 它会在更早的某次操作中被减成 0，跳过，不增加次数
        }  // if 块结束，重复值已跳过
        vis[nums[i]] = 1;  // 首次出现的非零值，标记它
        ans++;  // 不同的非零值每多一个，就需要多一次操作
    }  // 全部元素扫描完毕
    return ans;  // 返回不同的非零值个数，即最少操作次数
}  // 函数结束