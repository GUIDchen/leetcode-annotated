// 题目：2357. 使数组中所有元素都等于零（Make Array Zero by Subtracting Equal Amounts）
// 思路：每次操作只能减去当前的最小非零值，所以答案就是不同非零值的个数；遍历时用值域定长布尔数组标记出现过的值。
// 时间复杂度：O(n)，只看一遍数组；空间复杂度：O(1)，长度 101 的定长标记数组。
class Solution {  // LeetCode 约定的题解类
public:
    int minimumOperations(vector<int>& nums) {  // nums 是输入数组，返回把数组全部清零所需的最少操作次数
        bool s[101]{};  // 值域 0..100，s[v] 表示数值 v 是否已被某次操作处理过
        s[0] = true;  // 0 本身不需要操作，提前标记为已处理
        int ans = 0;  // 统计不同的非零值个数
        for (int& x : nums) {  // 遍历数组中的每个元素
            if (!s[x]) {  // 这个值此前没出现过
                ++ans;  // 需要多一次操作
                s[x] = true;  // 标记为已处理，后续重复值不再计数
            }  // 本次元素处理结束
        }  // 遍历结束，所有元素都处理过
        return ans;  // 返回不同的非零值个数，即最少操作次数
    }  // 方法结束
};  // 类定义结束