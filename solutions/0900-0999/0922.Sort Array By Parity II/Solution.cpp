// 题目：922. 按奇偶排序数组 II（Sort Array By Parity II）
// 思路：偶数下标只放偶数、奇数下标只放奇数；用指针 j 记录下一个错位的奇数下标，遇到偶数位上的奇数就与 j 位交换。
// 时间复杂度：O(n)，i 与 j 都只前进不回退；空间复杂度：O(1)，只在原数组上原地交换。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> sortArrayByParityII(vector<int>& nums) {  // nums：输入数组，原地调整后原样返回
        for (int i = 0, j = 1; i < nums.size(); i += 2) {  // i 只遍历偶数下标；j 从 1 开始，始终指向奇数下标
            if (nums[i] % 2) {  // 偶数下标上却是奇数，说明这个位置放错了
                while (nums[j] % 2) {  // 向后找第一个「奇数下标上放偶数」的位置，交换才有意义
                    j += 2;  // j 每次跨 2，保证它一直是奇数下标
                }  // 交换后偶数下标拿到偶数、奇数下标拿到奇数，两边同时归位
                swap(nums[i], nums[j]);  // 该位置已修正，继续看下一个偶数下标
            }  // 内层循环结束，本轮的错位已处理完毕
        }  // 偶数下标已全部遍历完
        return nums;  // 返回调整好的数组
    }  // 方法结束
};  // 类定义结束