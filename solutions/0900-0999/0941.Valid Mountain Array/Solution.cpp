// 题目：941. 有效的山脉数组（Valid Mountain Array）
// 思路：双指针相向爬坡 —— 左指针只走严格上坡、右指针只走严格下坡，两者在同一个峰顶相遇即为合法山脉数组。
// 时间复杂度：O(n)，每个元素最多被访问一次；空间复杂度：O(1)，只用两个指针。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool validMountainArray(vector<int>& arr) {  // arr 是待判定数组，返回它是否为合法的山脉数组
        int n = arr.size();  // 数组长度
        if (n < 3) {  // 山脉至少要满足「上坡 + 峰顶 + 下坡」，长度不足 3 必不合法
            return false;  // 长度不够直接否决
        }
        int i = 0, j = n - 1;  // i 从左往右爬坡，j 从右往左爬坡
        while (i + 1 < n - 1 && arr[i] < arr[i + 1]) {  // 左指针严格上升；i + 1 < n - 1 保证不会越过峰顶（峰顶不能是首尾元素）
            ++i;  // 右移一步，继续上坡
        }
        while (j - 1 > 0 && arr[j - 1] > arr[j]) {  // 右指针严格下降；j - 1 > 0 保证不会越过峰顶
            --j;  // 左移一步，继续下坡
        }
        return i == j;  // 只有两个指针停在同一个峰顶才说明恰好是一次先升后降
    }
};  // 类定义结束