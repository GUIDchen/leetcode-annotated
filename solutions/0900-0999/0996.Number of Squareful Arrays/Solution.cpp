// 题目：996. 平方数组的数目（Number of Squareful Arrays）
// 思路：状压 DP，f[i][j] 表示已选下标集合 i、以 j 结尾且相邻两数之和都是完全平方数的排列数；最后除以各值出现次数的阶乘做多重集去重。
// 时间复杂度：O(2^n · n^2)，空间复杂度：O(2^n · n)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numSquarefulPerms(vector<int>& nums) {  // nums：输入数组；返回相邻元素之和全为完全平方数的不同排列数目
        int n = nums.size();  // 数组长度，n ≤ 12，所以 2^n 状压可行
        int f[1 << n][n];  // f[i][j]：已选下标集合为 i、最后一个元素是 nums[j] 的合法排列数
        memset(f, 0, sizeof(f));  // 整体清零，作为 DP 的初始状态
        for (int j = 0; j < n; ++j) {  // 初始化只选一个元素的集合
            f[1 << j][j] = 1;  // 集合里只有 j 且以 j 结尾，方案数为 1
        }
        for (int i = 0; i < 1 << n; ++i) {  // 从小到大枚举所有选中的下标集合 i
            for (int j = 0; j < n; ++j) {  // 枚举集合 i 中作为排列末尾的元素 j
                if ((i >> j & 1) == 1) {  // 第 j 位为 1 才说明 j 真的在集合 i 里
                    for (int k = 0; k < n; ++k) {  // 枚举排在 j 前面的元素 k
                        if ((i >> k & 1) == 1 && k != j) {  // k 也要在集合 i 中，且不能和 j 是同一个下标
                            int s = nums[j] + nums[k];  // 相邻两元素之和 s
                            int t = sqrt(s);  // 向下取整开平方，用于判断完全平方数
                            if (t * t == s) {  // 平方后能还原，说明 s 是完全平方数，j 与 k 可以相邻
                                f[i][j] += f[i ^ (1 << j)][k];  // 去掉 j 后的集合以 k 结尾的状态转移而来（同值不同下标会重复计数，稍后统一去重）
                            }
                        }
                    }
                }
            }
        }
        long long ans = 0;  // 用 long long 累加，避免中间结果溢出
        for (int j = 0; j < n; ++j) {  // 枚举全集排列的最后一个元素
            ans += f[(1 << n) - 1][j];  // (1<<n)-1 表示所有元素都被选中；累加以各元素结尾的方案数
        }
        unordered_map<int, int> cnt;  // 统计每个值出现的次数，用于消除重复元素造成的重复计数
        for (int x : nums) {  // 遍历数组中的每个元素
            ++cnt[x];  // 该值的出现次数加一
        }
        int g[13] = {1};  // g[i] 表示 i!，n ≤ 12，所以数组开到 13 就够用
        for (int i = 1; i < 13; ++i) {  // 递推计算 1! 到 12!
            g[i] = g[i - 1] * i;  // i! = (i-1)! · i
        }
        for (auto& [_, v] : cnt) {  // 结构化绑定：_ 是元素值（这里用不到），v 是出现次数
            ans /= g[v];  // 多重集排列去重：相同值互换不产生新排列，所以除以各自出现次数的阶乘
        }
        return ans;  // 返回去重后的合法排列总数（隐式转回 int）
    }
};