// 题目：978. 最长湍流子数组（Longest Turbulent Subarray）
// 思路：线性 DP，f 表示以当前元素结尾且最后一步上升的最长湍流长度，g 表示最后一步下降的长度。
// 时间复杂度：O(n)，一次遍历；空间复杂度：O(1)，只用了常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxTurbulenceSize(vector<int>& arr) {  // arr：输入数组，返回最长湍流子数组的长度
        int ans = 1, f = 1, g = 1;  // ans 记录答案；f 表示最后一步为上升的最长湍流长度，g 表示最后一步为下降的长度
        for (int i = 1; i < arr.size(); ++i) {  // 从第二个元素开始，逐个与前一元素比较，i 为当前元素下标
            int ff = arr[i - 1] < arr[i] ? g + 1 : 1;  // 当前是上升（前一元素 < 当前元素）时可接在「下降结尾」的 g 后面，否则湍流断裂重新从 1 开始
            int gg = arr[i - 1] > arr[i] ? f + 1 : 1;  // 当前是下降（前一元素 > 当前元素）时可接在「上升结尾」的 f 后面，否则重新从 1 开始
            f = ff;  // 用新值更新上升结尾的最长长度
            g = gg;  // 用新值更新下降结尾的最长长度
            ans = max({ans, f, g});  // 答案取三者最大值（含单元素构成的湍流）
        }  // for 循环结束
        return ans;  // 返回最长湍流子数组长度
    }  // 题解方法结束
};  // Solution 类结束