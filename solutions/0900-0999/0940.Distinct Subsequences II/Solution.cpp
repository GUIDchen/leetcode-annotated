// 题目：940. 不同的子序列 II（Distinct Subsequences II）
// 思路：以「结尾字母」为状态去重计数，f[c] 存以 c 结尾的不同子序列数；每读一个字符，新值 = 所有 f 之和 + 1，并覆盖旧值。
// 时间复杂度：O(26n)，每字符遍历 26 个表位；空间复杂度：O(26)，常数级计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int distinctSubseqII(string s) {  // s 是输入字符串，返回不同非空子序列个数（对 1e9+7 取模）
        const int mod = 1e9 + 7;  // 取模常量，避免累加溢出
        int f[26]{};  // f[c] 表示以字母 c 结尾的不同子序列数，值初始化花括号保证全部为 0
        for (char& c : s) {  // 逐字符扫描字符串
            int x = 1;  // 从 1 开始：1 代表只由当前字符构成的单字符子序列
            for (int v : f) {  // 遍历 26 个结尾字母的计数
                x = (x + v) % mod;  // 已有子序列都接上当前字符，累加并取模
            }
            f[c - 'a'] = x;  // 覆盖旧值：以 c 结尾的旧子序列已被新集合覆盖，直接覆盖实现去重
        }
        int ans = 0;  // 所有结尾的不同子序列总数
        for (int v : f) {  // 遍历 26 个字母的计数
            ans = (ans + v) % mod;  // 累加并取模
        }
        return ans;  // 返回不同非空子序列的个数
    }
};  // 类定义结束
