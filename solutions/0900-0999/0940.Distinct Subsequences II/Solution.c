// 题目：940. 不同的子序列 II（Distinct Subsequences II）
// 思路：按结尾字母去重计数。f[c] 表示以字母 c 结尾的不同子序列个数，遇到 s[i] 时新个数 = 之前所有结尾之和 + 1（单字符），并直接覆盖旧值以消除重复。
// 时间复杂度：O(26n)，每个字符扫一遍 26 个字母表位；空间复杂度：O(26)，只需 26 个计数。
int distinctSubseqII(char* s) {  // s 是输入字符串，返回不同非空子序列的个数（对 1e9+7 取模）
    const int mod = 1e9 + 7;  // 取模常量，防止计数在累加时溢出
    int f[26] = {0};  // f[c] 表示以字母 c 结尾的不同子序列个数，下标 0..25 对应 a..z，全部初始化为 0
    for (int i = 0; s[i]; ++i) {  // 逐字符扫描，C 字符串以 '\0' 结束所以可以直接用 s[i] 判断
        int x = 1;  // 从 1 开始：1 代表只由当前字符构成的单字符子序列
        for (int j = 0; j < 26; ++j) {  // 枚举 26 个可能的前驱结尾字母
            x = (x + f[j]) % mod;  // 把已有子序列接上当前字符，累加计数并取模
        }
        f[s[i] - 'a'] = x;  // 直接覆盖旧值：以该字母结尾的旧子序列都已包含在新集合中，覆盖即可去重
    }
    int ans = 0;  // 累加器：所有结尾的不同子序列总数
    for (int i = 0; i < 26; ++i) {  // 遍历 26 个字母的计数
        ans = (ans + f[i]) % mod;  // 累加并对 mod 取模
    }
    return ans;  // 返回不同非空子序列的个数
}  // 函数定义结束
