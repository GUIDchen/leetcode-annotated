# 题目：949. 给定数字能组成的最大时间（Largest Time for Given Digits）
# 思路：从最大的合法时间 23:59 开始按字典序倒着枚举所有时刻，用数字出现次数的计数数组判断该时刻能否由给定 4 个数字拼出。
# 时间复杂度：O(24×60×10) 即常数级；空间复杂度：O(10)，两张固定长度的计数数组。
class Solution:  # LeetCode 约定的题解类
    def largestTimeFromDigits(self, arr: List[int]) -> str:  # arr 是给定的 4 个数字（0-9）
        cnt = [0] * 10  # cnt 统计每个数字出现的次数，下标 0-9
        for v in arr:  # 遍历这 4 个数字
            cnt[v] += 1  # 对应数字的计数加一
        for h in range(23, -1, -1):  # 小时从 23 递减到 0，保证先试大的时间
            for m in range(59, -1, -1):  # 分钟从 59 递减到 0，同样从大到小
                t = [0] * 10  # t 记录当前时刻 h:m 各数字需要出现的次数
                t[h // 10] += 1  # 小时十位需要的数字个数加一
                t[h % 10] += 1  # 小时个位需要的数字个数加一
                t[m // 10] += 1  # 分钟十位需要的数字个数加一
                t[m % 10] += 1  # 分钟个位需要的数字个数加一
                if cnt == t:  # 计数数组完全一致，说明这 4 个数字刚好能拼出该时刻
                    return f'{h:02}:{m:02}'  # 按 24 小时制两位格式返回，h 和 m 补前导零
        return ''  # 所有时刻都不行，按题意返回空串
