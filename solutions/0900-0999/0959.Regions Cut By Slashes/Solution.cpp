// 题目：959. 由斜杠划分区域（Regions Cut By Slashes）
// 思路：把每个 n×n 格子拆成上(0)、右(1)、下(2)、左(3)四个小三角形，用并查集把跨格子的相邻边和斜杠不隔离的同侧三角形合并，最后数连通分量。
// 时间复杂度：O(n²·α(n²))，并查集近似线性，总节点数 4n²；空间复杂度：O(n²)，父数组长度 4n²。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法与辅助方法对外可见
    vector<int> p;  // 并查集父数组，每个小三角形是一个节点
    int size;  // 当前连通分量个数，初始是全部节点数，每成功合并一次减一

    int regionsBySlashes(vector<string>& grid) {  // grid：n×n 的斜杠网格，返回被划分出的区域个数
        int n = grid.size();  // n：网格的边长
        size = n * n * 4;  // 每个格子拆成 4 个三角形，所以总节点数是 n*n*4
        p.resize(size);  // 把父数组扩到节点总数
        for (int i = 0; i < size; ++i) p[i] = i;  // 并查集初始化：每个节点的父亲指向自己，各自是一个独立区域
        for (int i = 0; i < n; ++i) {  // 枚举行 i
            for (int j = 0; j < n; ++j) {  // 枚举列 j
                int k = i * n + j;  // 把二维坐标压成一维的格子编号 k
                if (i < n - 1) merge(4 * k + 2, (k + n) * 4);  // 与下方格子连通：本格「下」三角形(4k+2) 接下一行同列格的「上」三角形(4*(k+n))
                if (j < n - 1) merge(4 * k + 1, (k + 1) * 4 + 3);  // 与右方格子连通：本格「右」三角形(4k+1) 接右邻格的「左」三角形(4*(k+1)+3)
                char v = grid[i][j];  // 取出当前格子的字符：正斜杠、反斜杠或空格
                if (v == '/') {  // 正斜杠从右上斜到左下，把「上」和「左」、「右」和「下」分到两侧
                    merge(4 * k, 4 * k + 3);  // 正斜杠不隔开「上」和「左」，把它们合并
                    merge(4 * k + 1, 4 * k + 2);  // 正斜杠不隔开「右」和「下」，把它们合并
                } else if (v == '\\') {  // 反斜杠从左上斜到右下，把「上」和「右」、「下」和「左」分到两侧
                    merge(4 * k, 4 * k + 1);  // 反斜杠不隔开「上」和「右」
                    merge(4 * k + 2, 4 * k + 3);  // 反斜杠不隔开「下」和「左」
                } else {  // 空格不切割格子，四个三角形属于同一区域
                    merge(4 * k, 4 * k + 1);  // 合并「上」与「右」
                    merge(4 * k + 1, 4 * k + 2);  // 合并「右」与「下」
                    merge(4 * k + 2, 4 * k + 3);  // 合并「下」与「左」
                }
            }
        }
        return size;  // 剩下的连通分量个数就是区域数量
    }

    void merge(int a, int b) {  // 合并 a、b 所在的两个集合
        int pa = find(a);  // 先求 a 的根
        int pb = find(b);  // 再求 b 的根
        if (pa == pb) return;  // 本来就在同一个集合，无需合并
        p[pa] = pb;  // 把一个根挂到另一个根下
        --size;  // 成功合并一次，连通分量数减一
    }

    int find(int x) {  // 查并查集里 x 的根，带路径压缩
        if (p[x] != x) p[x] = find(p[x]);  // 父亲不是自己就继续向上找，并把沿途节点直接挂到根上
        return p[x];  // 返回根节点
    }
};