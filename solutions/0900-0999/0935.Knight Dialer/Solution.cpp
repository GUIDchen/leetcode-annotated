// 题目：935. 骑士拨号器（Knight Dialer）
// 思路：按位动态规划。f[d] 是当前最后一位为数字 d 的号码个数，下一轮按骑士走法把能跳到 d 的前驱方案数累加到 g[d]。
// 时间复杂度：O(n)，共 n 轮、每轮常数次加法；空间复杂度：O(1)，只保留长度为 10 的两个数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int knightDialer(int n) {  // n 是号码长度，返回长度为 n 的合法号码个数（对 1e9+7 取模）
        const int mod = 1e9 + 7;  // 取模常量，防止方案数爆炸
        vector<long long> f(10, 1);  // f[d]：长度为 1、最后一位停在 d 上的号码个数，都是 1
        while (--n) {  // 还需要再按 n-1 次（先自减，n 为 1 时循环不执行）
            vector<long long> g(10);  // g 保存多按一位之后的状态；数字 5 没有任何走法，所以 g[5] 始终保持 0，代码里省略赋值
            g[0] = (f[4] + f[6]) % mod;  // 骑士从 4、6 能跳到 0
            g[1] = (f[6] + f[8]) % mod;  // 骑士从 6、8 能跳到 1
            g[2] = (f[7] + f[9]) % mod;  // 骑士从 7、9 能跳到 2
            g[3] = (f[4] + f[8]) % mod;  // 骑士从 4、8 能跳到 3
            g[4] = (f[0] + f[3] + f[9]) % mod;  // 骑士从 0、3、9 能跳到 4
            g[6] = (f[0] + f[1] + f[7]) % mod;  // 骑士从 0、1、7 能跳到 6
            g[7] = (f[2] + f[6]) % mod;  // 骑士从 2、6 能跳到 7
            g[8] = (f[1] + f[3]) % mod;  // 骑士从 1、3 能跳到 8
            g[9] = (f[2] + f[4]) % mod;  // 骑士从 2、4 能跳到 9
            f = g;  // 滚动更新，g 成为下一轮的 f
        }
        return accumulate(f.begin(), f.end(), 0LL) % mod;  // 累加所有终点的方案数，再取一次模
    }
};
