// 题目：995. K 连续位的最小翻转次数（Minimum Number of K Consecutive Bit Flips）
// 思路：贪心 + 差分数组。从左到右，若当前位的有效值仍为 0 就必须从这里翻 k 位；越界即无解。
// 时间复杂度：O(n)，每个位置只处理一次；空间复杂度：O(n)，差分数组长度为 n+1。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minKBitFlips(vector<int>& nums, int k) {  // nums：01 数组；k：每次必须翻转的连续长度；返回最少翻转次数，无法达成返回 -1
        int n = nums.size();  // n 为数组长度
        int d[n + 1];  // 差分数组 d，d[i] 表示从位置 i 开始生效的翻转次数增量
        memset(d, 0, sizeof(d));  // 差分数组清零
        int ans = 0, s = 0;  // ans 记录翻转次数；s 记录当前位置累计被翻转的次数
        for (int i = 0; i < n; ++i) {  // 从左到右依次确定每个位置是否需要翻转
            s += d[i];  // 累加差分，得到当前位置实际被翻转的次数
            if (s % 2 == nums[i]) {  // 翻转次数的奇偶性恰好等于当前值，说明这一位最终会是 0，必须再翻一次
                if (i + k > n) {  // 从这里开始翻 k 个会越界，无法完成
                    return -1;  // 返回 -1 表示无解
                }  // 越界判断结束
                ++d[i];  // 差分标记：区间 [i, i+k) 整体翻转次数加一
                --d[i + k];  // 区间右端以外的位置减一，抵消这次翻转的影响
                ++s;  // 当前位置的累计翻转次数同步加一
                ++ans;  // 答案加一
            }  // 需要翻转的分支结束
        }  // 该位置处理结束
        return ans;  // 所有位置都处理完，返回最少翻转次数
    }  // minKBitFlips 函数结束
};  // 类定义结束
