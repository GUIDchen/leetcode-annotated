// 4000. 给定数位和的最大整数 / Largest Integer With Given Digit Sum（简单）
// 核心思路：要让整数尽量大，就从最高位开始贪心——每一位都取 min(剩余数位和, 9)，把能用的数位和优先塞给高位；若 n 位全取 9 仍凑不满 s 则无解。
// 复杂度：时间 O(n)，空间 O(1)。
class Solution {  // 题解类
public:  // 公有接口
    int largestInteger(int n, int s) {  // 返回至多 n 位、数位和为 s 的最大整数，不存在则返回 -1
        if (n * 9 < s) {  // n 位全取 9 也凑不出 s，无解
            return -1;  // 返回 -1 表示不存在这样的整数
        }  // if 结束
        int ans = 0;  // 逐位拼出答案
        for (int i = 0; i < n; ++i) {  // 从最高位到最低位依次填写 n 个数位
            int x = min(s, 9);  // 当前位取 9 与剩余数位和的较小者，保证高位尽量大
            ans = ans * 10 + x;  // 把这一位接到答案末尾
            s -= x;  // 扣掉这一位已经用掉的数位和
        }  // 循环结束
        return ans;  // 返回最大整数（s 为 0 时得到 0）
    }  // 方法结束
};  // 类定义结束