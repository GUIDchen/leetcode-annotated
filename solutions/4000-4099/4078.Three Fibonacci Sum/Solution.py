# 4078. 连续三项斐波那契数之和（Three Fibonacci Sum）
# 核心思路：连续三项斐波那契数之和等于 2 * F(k+2)，故 n 可表示当且仅当 n 为偶数且 n / 2 是斐波那契数；先离线生成 1e9 以内的斐波那契集合，再 O(1) 查表。
# 复杂度：预处理 O(log n) 项斐波那契数，单次查询 O(1)，空间 O(log n)。
a, b = 0, 1  # 相邻两项，F(0) = 0、F(1) = 1
mx = 10**9 + 1  # 需要覆盖的上界：n 最大 1e9，n / 2 不超过 1e9 + 1
f = set()  # 存放所有不超过上界的斐波那契数
while b < mx:  # 递推生成斐波那契数
    a, b = b, a + b  # 滚动前移，b 成为下一个斐波那契数
    f.add(b)  # 把新生成的斐波那契数加入集合


class Solution:  # 题解类
    def threeFibonacciSum(self, n: int) -> bool:  # 判断 n 能否表示为三个连续斐波那契数之和，即 n 为偶数且 n / 2 是斐波那契数
        return n % 2 == 0 and n // 2 in f  # 偶数是必要条件，再检查 n // 2 是否落在斐波那契集合中
