// 题目：4022. 无限字符串里第 K 个数字（K-th Digit in Infinite String）
// 思路：无限串由 1..9 在前，之后每个块 b 依次写出 10b..10b+9（b 为偶数时递增、b 为奇数时递减）。先跳过 9 个一位数，再按位数 d 分段：d 位数共 9·10^(d-2) 个块、每块 10·d 个字符，用除法定位 k 落在哪个块、块内第几个数以及该数的第几位，最后按块编号奇偶还原出具体数字并取位。
// 时间复杂度：O(log k)，位数区间的段数与 k 的位数同阶；空间复杂度：O(1)，只用常数个整数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int kthDigit(long long k) {  // k：1-based 下标；返回按「块」规则拼出的无限字符串的第 k 位数字
        if (k <= 9) {  // 前 9 位就是 1..9 这 9 个一位数
            return (int) k;  // 第 k 位恰好就是数字 k
        }  // 一位数分支结束

        k -= 9;  // 跳过开头 9 个一位数，k 变成从 2 位数部分起算的偏移（1-based）
        long long d = 2;  // 从 2 位数的块开始扩展，d 表示当前块的数字位数
        long long start = 1;  // d 位数对应的第一个块编号（2 位数从块 1 开始，3 位数从块 10 开始……）
        long long size = 0;  // 每个块的总字符数（10 个 d 位数、每个 d 位）

        while (true) {  // 不断进入更长位数的区间，直到 k 落在当前区间内
            long long cnt = 9 * (long long) pow(10, d - 2);  // d 位数一共占 cnt 个块（数字 10^(d-2)..10^(d-1)-1，每 10 个一组）
            size = 10 * d;  // 一个块含 10 个数字、每个 d 位，共 10*d 个字符

            if (k <= cnt * size) {  // k 落在当前 d 位数的所有块之内
                break;  // 确定好位数区间，跳出循环
            }  // 判断结束

            k -= cnt * size;  // 整个 d 位数区间都跳过，k 减去这些字符数
            d++;  // 进入更长一位的区间
            start *= 10;  // 该区间第一个块的编号也进一位
        }  // 继续判断更长的位数区间

        long long b = start + (k - 1) / size;  // 定位到具体的块编号 b（从 start 起偏移）
        long long pos = (k - 1) % size;  // 块内的字符偏移（0-based）

        long long i = pos / d;  // 块内第几个数字（0..9），每个数字占 d 位

        long long num;  // 该位置所属的具体数字
        if (b % 2 == 0) {  // 块编号为偶数时，块内按递增顺序排列
            num = 10 * b + i;  // 递增排列时第 i 个数是 10*b + i
        } else {  // 块编号为奇数时，块内按递减顺序排列
            num = 10 * b + 9 - i;  // 递减排列时第 i 个数是 10*b + 9 - i
        }  // 奇偶分支结束

        return to_string(num)[pos % d] - '0';  // 在 num 的十进制表示中取第 pos % d 位，再转成数字返回
    }  // 方法结束
};  // 类定义结束