# 题目：4022. 无限字符串里第 K 个数字（K-th Digit in Infinite String）
# 思路：无限串开头是 1..9，之后每个块 b 写出 10b..10b+9（b 为偶数递增、为奇数递减）。跳过 9 个一位数后按位数 d 分段：d 位数共 9·10^(d-2) 个块、每块 10·d 个字符，用整除与取模定位块号、块内数字序号与该数字的第几位，再按块号奇偶还原具体数字并取位。
# 时间复杂度：O(log k)，位数区间段数与 k 的位数同阶；空间复杂度：O(1)，只用常数个整数变量。
class Solution:  # LeetCode 约定的题解类
    def kthDigit(self, k: int) -> int:  # k：1-based 下标；返回按「块」规则拼出的无限字符串的第 k 位数字
        if k <= 9:  # 前 9 位就是 1..9 这 9 个一位数
            return k  # 第 k 位恰好就是数字 k

        k -= 9  # 跳过开头 9 个一位数，k 变成从 2 位数部分起算的偏移（1-based）
        d = 2  # 从 2 位数的块开始扩展，d 表示当前块的数字位数
        start = 1  # d 位数对应的第一个块编号（2 位数从块 1 开始，3 位数从块 10 开始……）

        while True:  # 不断扩大位数区间，直到 k 落在当前区间内
            cnt = 9 * 10 ** (d - 2)  # d 位数一共占 cnt 个块（数字 10^(d-2)..10^(d-1)-1，每 10 个一组）
            size = 10 * d  # 一个块含 10 个数字、每个 d 位，共 10*d 个字符

            if k <= cnt * size:  # k 落在当前 d 位数的所有块之内
                break  # 确定好位数区间，结束循环

            k -= cnt * size  # 整个 d 位数区间都跳过，k 减去这些字符数
            d += 1  # 进入更长一位的区间
            start *= 10  # 该区间第一个块的编号也进一位

        b = start + (k - 1) // size  # 定位到具体的块编号 b（从 start 起偏移）
        pos = (k - 1) % size  # 块内的字符偏移（0-based）

        i = pos // d  # 块内第几个数字（0..9），每个数字占 d 位
        num = 10 * b + i if b % 2 == 0 else 10 * b + 9 - i  # 块号为偶数时递增排列取 10*b + i，为奇数时递减排列取 10*b + 9 - i

        return int(str(num)[pos % d])  # 取 num 十进制表示的第 pos % d 位并转成数字返回
