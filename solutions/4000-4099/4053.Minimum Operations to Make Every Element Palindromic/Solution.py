# 题目：4053. 使每个元素变为回文数的最少操作次数（Minimum Operations to Make Every Element Palindromic）
# 思路：每次操作只能把元素 +2 或 -2，奇偶性始终不变，所以每个元素只能落到与它同奇偶的回文数上；先枚举 1..10^5 作为回文的“半边”，拼出所有 2k 位与 2k-1 位回文数并按奇偶分桶排序，再对每个元素二分找同奇偶的最近回文数，数值距离除以 2 就是操作次数。
# 时间复杂度：O(M log M + n log M)，M 为预计算出的回文数个数（约 2×10^5），排序只做一次、每次查询二分；空间复杂度：O(M)，用于保存全部回文数与两个奇偶桶。
ps = [[], []]  # ps[0] 存偶数回文数、ps[1] 存奇数回文数，下标即奇偶位
for i in range(1, 10**5 + 1):  # 枚举“半边” i，用它同时拼出偶数位与奇数位回文数
    s = str(i)  # i 的十进制串作为回文的前半段（奇数位回文时含中间位）
    t1 = s[::-1]  # t1 是 s 的反转，s + t1 即为回文
    t2 = s[:-1][::-1]  # t2 是去掉末位后再反转，s + t2 长度只比 s + t1 少 1
    x = int(s + t1)  # 拼出 2k 位的偶数位回文数
    ps[x & 1].append(x)  # 按奇偶放进对应的桶（下标就是 x & 1）
    y = int(s + t2)  # 拼出 2k-1 位的奇数位回文数
    ps[y & 1].append(y)  # 同样按奇偶入桶
for p in ps:  # 两个桶各自排序，便于二分查找
    p.sort()  # 升序排序后即可用 bisect 找最近的回文数


class Solution:  # LeetCode 约定的题解类
    def minOperations(self, nums: list[int]) -> int:  # nums：待变成回文数的数组；返回让每个元素都变成回文数的最少操作次数
        ans = 0  # ans 累计所有元素的最小操作次数
        for x in nums:  # 逐个元素处理
            p = ps[x & 1]  # 每次操作改变 2，奇偶性不变，只能变成同奇偶的回文数
            i = bisect_left(p, x)  # 二分找到第一个大于等于 x 的同奇偶回文数
            t = inf  # t 记录到最近回文数的数值距离，先置为无穷大
            if i < len(p):  # 右侧存在不小于 x 的回文数
                t = p[i] - x  # 右侧候选的距离
            if i:  # 左侧还存在小于 x 的同奇偶回文数
                t = min(t, x - p[i - 1])  # 与左侧候选比较取更小的距离
            ans += t // 2  # 每次操作改变 2，操作次数就是数值距离整除 2
        return ans  # 返回最少操作总数
