// 题目：4006. 统计有效前缀数目（Count Valid Prefixes）
// 思路：把前缀中 '1' 与 '0' 的个数差记为 t，遍历时遇到 '1' 加 1、遇到 '0' 减 1；只要 |t| <= 1（即 0 与 1 的数量相差不超过 1），该前缀就有效。
// 时间复杂度：O(n)，只需遍历一遍字符串；空间复杂度：O(1)，只用了两个整型变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countValidPrefixes(string s) {  // s：只含 '0' 和 '1' 的字符串；返回满足条件的前缀数目
        int ans = 0, t = 0;  // ans 记录有效前缀个数，t 记录前缀中 '1' 与 '0' 的个数差
        for (char c : s) {  // 从左到右逐字符扫描，逐步扩张前缀
            t += c == '1' ? 1 : -1;  // 遇到 '1' 差值加 1，遇到 '0' 差值减 1
            if (abs(t) <= 1) {  // 差值绝对值不超过 1，说明 0 与 1 的数量基本持平，该前缀有效
                ans++;  // 有效前缀计数加 1
            }  // 结束有效性判断
        }  // 结束字符遍历
        return ans;  // 返回有效前缀的总数
    }  // 结束 countValidPrefixes
};  // 结束 Solution 类