# 题目：4006. 统计有效前缀数目（Count Valid Prefixes）
# 思路：把前缀中 '1' 与 '0' 的个数差记为 t，遍历时遇到 '1' 加 1、遇到 '0' 减 1；只要 |t| <= 1（即 0 与 1 的数量相差不超过 1），该前缀就有效。
# 时间复杂度：O(n)，只需遍历一遍字符串；空间复杂度：O(1)，只用了两个整型变量。
class Solution:  # LeetCode 约定的题解类
    def countValidPrefixes(self, s: str) -> int:  # s：只含 '0' 和 '1' 的字符串；返回满足条件的前缀数目
        ans = t = 0  # ans 记录有效前缀个数，t 记录前缀中 '1' 与 '0' 的个数差
        for c in s:  # 从左到右扫描，逐个字符扩张前缀
            t += 1 if c == '1' else -1  # 遇到 '1' 差值加 1，遇到 '0' 差值减 1
            ans += 1 if abs(t) <= 1 else 0  # 差值绝对值不超过 1 就加 1，否则加 0（即不计数）
        return ans  # 返回有效前缀的总数
