# 题目：4050. 得到恰好 N 分的最少天数（Minimum Days to Score Exactly N Points）
# 思路：完全背包式的预处理 DP。一段连续 j 天恰好得 1+2+...+j = j(j+1)/2 分，故 f[i] = min(f[i-s] + j + 1)，s 取遍不超过 i 的三角数；把 f[0] 设为 -1 作哨兵，使得「只取一个三角数」的总天数正好是 j。模块级只算一次，之后 O(1) 查表。
# 复杂度：时间复杂度 O(M * sqrt(M))，M = 10^5+1 为预处理上界，单次查询 O(1)；空间复杂度 O(M)。
mx = 10**5 + 1  # 预处理的最大分数
f = [inf] * mx  # f[i]：恰好得到 i 分的最少天数，先全部置为无穷
f[0] = -1  # 哨兵：让转移式里的 +1 在「只取一段」时被抵消，使 j(j+1)/2 分恰好花 j 天
for i in range(1, mx):  # 从小到大递推每个分数
    j = 1  # 本段连续天数，从 1 开始枚举
    while (s := (1 + j) * j // 2) <= i:  # 海象运算符：连续 j 天的分数 s = j(j+1)/2，不超过 i 才有效
        f[i] = min(f[i], f[i - s] + j + 1)  # 用这一段的 s 分，天数 = 剩余部分的天数 + j + 1
        j += 1  # 天数加一，继续尝试更长的段


class Solution:  # LeetCode 约定的题解类
    def minDays(self, n: int) -> int:  # n：目标分数；返回恰好得到 n 分的最少天数
        return f[n]  # 预处理表里直接查答案
