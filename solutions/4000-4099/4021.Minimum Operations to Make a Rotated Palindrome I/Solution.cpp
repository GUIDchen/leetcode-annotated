// 题目：4021. 得到旋转回文字符串的最少操作次数 I（Minimum Operations to Make a Rotated Palindrome I）
// 思路：枚举左旋次数 k（旋 n 次回到原串，故只需 0..n-1），旋转代价 k 先计入；旋转后用双指针从两端向中间检查每一对对称字符，把它们改成相同字母的代价是 min(|x-y|, 26-|x-y|)（可以正向递增，也可以绕过 z→a 反向靠近），累加后取所有 k 的最小值。
// 时间复杂度：O(n²)，n 种旋转 × 每次 O(n) 的对称检查；空间复杂度：O(1)，只用常数个指针与累加变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minOperations(string s) {  // s：小写字母串；返回用「字符递增」与「左旋」两种操作把它变成回文串的最少次数
        int n = s.size();  // 字符串长度 n，最多需要考虑 n 种旋转
        int ans = INT_MAX;  // 最少操作次数，先置为无穷大

        for (int k = 0; k < n; ++k) {  // 枚举左旋次数 k（旋 n 次回到原串，所以只需 0..n-1）
            int t = k;  // 旋转本身要花 k 次操作，先计入总代价
            int i = 0, j = n - 1;  // 旋转后字符串的双指针：i 从头、j 从尾向中间靠拢

            while (i < j) {  // 逐对检查回文对称位置的字符
                int x = s[(i + k) % n] - 'a';  // 左旋 k 次后，原下标 (i + k) % n 的字符移到了位置 i
                int y = s[(j + k) % n] - 'a';  // 对称位置 j 上的字符来自原下标 (j + k) % n

                int d = abs(x - y);  // 两个字符在字母表中的序号差
                t += min(d, 26 - d);  // 可以直接递增到对方，也可以绕过 'z'→'a' 反向靠近，取两者的较小代价

                ++i;  // 左指针右移
                --j;  // 右指针左移
            }  // 本对对称字符处理完毕

            ans = min(ans, t);  // 用这次旋转方案的代价更新最优解
        }  // 所有旋转次数枚举完毕

        return ans;  // 返回所有旋转方案中最少的操作次数
    }  // 方法结束
};  // 类定义结束