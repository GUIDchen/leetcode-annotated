# 题目：4019. 合并靠近字符 II（Merge Close Characters II，会员题）
# 思路：按「总是合并最靠左的靠近对」的规则做一次从左到右的贪心扫描——字典记录每种字符在结果串中最后一次保留的位置，若当前字符与它的距离不超过 k 就删除（合并）当前字符，否则保留并刷新位置；删除只会让后续字符距离更小，所以一次扫描即得终态。
# 时间复杂度：O(n)，每个字符只处理一次；空间复杂度：O(1)，字典最多存 26 个小写字母的位置。
class Solution:  # LeetCode 约定的题解类
    def mergeCharacters(self, s: str, k: int) -> str:  # s：小写字母串；k：距离阈值；返回不断合并靠近的相同字符后剩下的字符串
        last = {}  # last[c]：字符 c 在结果串中最后一次出现的下标
        ans = []  # ans 用列表收集保留的字符，其长度就是下一个字符的落点
        for c in s:  # 按原顺序扫描每个字符，决定保留还是删除
            cur = len(ans)  # 若保留，当前字符将放到结果串的下标 cur 处
            if c in last and cur - last[c] <= k:  # 该字符此前出现过，且与上次保留位置的距离不超过 k，说明「靠近」需要合并
                continue  # 丢弃右侧这个字符（合并进左边那个），继续看下一个
            ans.append(c)  # 不靠近则保留该字符
            last[c] = cur  # 更新字符 c 在结果串中的最新位置
        return ''.join(ans)  # 把保留的字符拼成结果字符串返回
