// 题目：4019. 合并靠近字符 II（Merge Close Characters II，会员题）
// 思路：按题目「总是合并最靠左的靠近对」的规则做一次从左到右的贪心扫描——哈希表记录每种字符在结果串中最后一次保留的位置，若当前字符与它的距离不超过 k 就删除（合并）当前字符，否则保留并刷新位置；删除只会让后面字符的距离变小，所以一次扫描即得终态。
// 时间复杂度：O(n)，每个字符只处理一次；空间复杂度：O(1)，哈希表最多存 26 个小写字母的位置。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string mergeCharacters(string s, int k) {  // s：由小写字母组成的原字符串；k：距离阈值；返回不断合并靠近的相同字符后剩下的字符串
        unordered_map<char, int> last;  // last[c]：字符 c 在结果串中最后一次出现的下标
        string ans;  // ans 按顺序保存保留下来的字符，它的长度就是下一个字符将要落到的位置
        for (char c : s) {  // 按原顺序扫描每个字符，决定保留还是删除
            int cur = ans.size();  // 若保留，当前字符将放到结果串的下标 cur 处
            if (last.count(c) && cur - last[c] <= k) {  // 该字符此前出现过，且与上次保留位置的距离不超过 k，说明构成「靠近」需要合并
                continue;  // 删除右侧这个字符（合并进左边那个），继续看下一个
            }  // 靠近判断结束
            ans += c;  // 不靠近则保留该字符，追加到结果末尾
            last[c] = cur;  // 记录它在结果串中的最新下标
        }  // 原字符串扫描完毕
        return ans;  // 返回合并完成后的字符串
    }  // 方法结束
};  // 类定义结束
