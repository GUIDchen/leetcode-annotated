// 题目：4044. 统计好循环移位的数量（Count Good Cyclic Rotations）
// 思路：环形滑窗求和。先把数组分成长度 m = n/2 的前半与后半并分别求和，之后每右移一位只有两个元素换边（nums[i] 从前半到后半、nums[i+m] 从后半到前半），用 O(1) 增量更新两侧之和，统计「前半之和 > 后半之和」的移位个数。
// 复杂度：时间复杂度 O(n)，n 为数组长度；空间复杂度 O(1)，只用到两侧和与答案等常数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countGoodRotations(vector<int>& nums) {  // nums：环形数组；返回「前半之和 > 后半之和」的循环移位个数
        int n = nums.size();  // 数组长度，也是循环移位的个数
        int m = n / 2;  // 前半部分的长度

        long long l = 0, r = 0;  // l：前半之和；r：后半之和（用 long long 防止溢出）
        for (int i = 0; i < m; i++) {  // 统计不移位时前半部分的和
            l += nums[i];  // 累加前半元素
        }  // 前半求和循环结束
        for (int i = m; i < n; i++) {  // 统计不移位时后半部分的和
            r += nums[i];  // 累加后半元素
        }  // 后半求和循环结束

        int ans = l > r;  // 不移位这一种是否满足 l > r

        for (int i = 0; i < n - 1; i++) {  // 依次右移，枚举余下的 n-1 种移位
            l -= nums[i];  // 前半最左的元素被移出前半
            r += nums[i];  // 它进入后半的最右端
            l += nums[(i + m) % n];  // 后半最左的元素换进前半的最右端
            r -= nums[(i + m) % n];  // 同时把它从后半中移除
            ans += l > r;  // 当前移位满足 l > r 则累加答案
        }  // 移位枚举结束

        return ans;  // 返回满足条件的循环移位个数
    }  // 方法结束
};  // 题解类结束