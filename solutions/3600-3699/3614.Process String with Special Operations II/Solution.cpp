// 3614. Process String with Special Operations II / 用特殊操作处理字符串 II
// 核心思路：正向只累计长度 m 而不真正构造字符串，再逆序回放每个操作，把最终下标 k 一步步映射回原字符。
// 复杂度：时间复杂度 O(n)，空间复杂度 O(1)，n 为操作串长度。
class Solution {  // 定义题解类
public:  // 公有成员：对外提供 processStr
    char processStr(string s, long long k) {  // 求操作全部执行完后第 k 个字符，越界返回点号
        long long m = 0;  // m 记录字符串的最终长度
        for (char c : s) {  // 第一遍：只统计长度，不真正构造字符串
            if (c == '*') {  // 星号会删掉一个字符
                m = max(0LL, m - 1);  // 长度减一，但下界为 0
            } else if (c == '#') {  // 井号会让长度翻倍
                m <<= 1;  // 左移一位等价于乘以 2
            } else if (c != '%') {  // 剩下的字母会追加一个字符（百分号不改变长度）
                m += 1;  // 长度加一
            }  // 结束第一遍分支判断
        }  // 结束长度统计
        if (k >= m) {  // 若下标越界
            return '.';  // 返回题目要求的占位符
        }  // 结束越界判断
        for (int i = s.length() - 1;; i--) {  // 第二遍：从后往前回放操作，把最终下标映射回原字符
            char c = s[i];  // 取当前操作字符
            if (c == '*') {  // 逆序看星号：长度恢复为加一
                m += 1;  // 长度加一
            } else if (c == '#') {  // 逆序看井号：长度恢复为一半
                m /= 2;  // 长度折半，得到复制前的长度
                if (k >= m) {  // 若下标落在后半段
                    k -= m;  // 平移到前半段的对应位置
                }  // 结束下标平移
            } else if (c == '%') {  // 逆序看百分号：反转会把下标镜像
                k = m - 1 - k;  // 下标关于中心对称
            } else {  // 剩下的情况是字母
                m -= 1;  // 该字母贡献一个长度
                if (k == m) {  // 若正好落在该字母上
                    return c;  // 找到答案字符并返回
                }  // 结束命中判断
            }  // 结束第二遍分支判断
        }  // 循环结束（逻辑上一定会中途返回）
    }  // 方法结束
};  // 类定义结束