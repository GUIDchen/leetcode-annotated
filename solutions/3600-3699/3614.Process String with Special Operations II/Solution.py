# 3614. Process String with Special Operations II / 用特殊操作处理字符串 II
# 核心思路：正向只累计长度 m 而不真正构造字符串，再逆序回放每个操作，把最终下标 k 一步步映射回原字符。
# 复杂度：时间复杂度 O(n)，空间复杂度 O(1)，n 为操作串长度。
class Solution:  # 定义题解类
    def processStr(self, s: str, k: int) -> str:  # 求操作全部执行完后第 k 个字符，越界返回点号
        m = 0  # m 记录字符串的最终长度
        for c in s:  # 第一遍：只统计长度，不真正构造字符串
            if c == "*":  # 星号会删掉一个字符
                m = max(0, m - 1)  # 长度减一，但下界为 0
            elif c == "#":  # 井号会让长度翻倍
                m <<= 1  # 左移一位等价于乘以 2
            elif c != "%":  # 剩下的字母会追加一个字符（百分号不改变长度）
                m += 1  # 长度加一
        if k >= m:  # 若下标越界
            return "."  # 返回题目要求的占位符
        for c in reversed(s):  # 第二遍：从后往前回放操作，把最终下标映射回原字符
            if c == "*":  # 逆序看星号：长度恢复为加一
                m += 1  # 长度加一
            elif c == "#":  # 逆序看井号：长度恢复为一半
                m //= 2  # 长度整除 2，得到复制前的长度
                if k >= m:  # 若下标落在后半段
                    k -= m  # 平移到前半段的对应位置
            elif c == "%":  # 逆序看百分号：反转会把下标镜像
                k = m - 1 - k  # 下标关于中心对称
            else:  # 剩下的情况是字母
                m -= 1  # 该字母贡献一个长度
                if k == m:  # 若正好落在该字母上
                    return c  # 找到答案字符并返回
