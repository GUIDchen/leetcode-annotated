# 题目：3640. 三段式数组 II（Trionic Array II）
# 核心思路：按段扫描。先走完严格上升的第一段，再走严格下降的第二段，最后走严格上升的第三段；谷底之后的上升段取最大前缀和、第一段取以峰顶左邻结尾的最大后缀和，两者叠加到「峰顶+整个下降段」的固定和上，用该段候选和更新答案，再从谷底重新开始下一段。
# 复杂度：时间 O(n)，每个下标最多被扫描常数次；空间 O(1)，只用了常数个变量。
class Solution:  # LeetCode 题解类
    def maxSumTrionic(self, nums: List[int]) -> int:  # nums：输入数组；返回三段式子数组的最大和
        n = len(nums)  # 数组长度
        i = 0  # 当前扫描位置
        ans = -inf  # 答案，初始为负无穷，保证任何合法和都能更新它
        while i < n:  # 从每个尚未处理的位置开始尝试新的一段
            l = i  # 记录本段的起点
            i += 1  # 起点本身先计入第一段上升段
            while i < n and nums[i - 1] < nums[i]:  # 第一段：严格上升（相邻元素严格递增）
                i += 1  # 继续向右扩张上升段
            if i == l + 1:  # 上升段长度只有 1，不满足「严格上升」
                continue  # 放弃本段，换下一个起点

            p = i - 1  # p 是第一段的峰顶下标
            s = nums[p - 1] + nums[p]  # 峰顶及其左邻先计入当前和（此时至少两个元素）
            while i < n and nums[i - 1] > nums[i]:  # 第二段：严格下降
                s += nums[i]  # 下降段的元素整体都要，直接累加进当前和
                i += 1  # 继续向右扩张下降段
            if i == p + 1 or i == n or nums[i - 1] == nums[i]:  # 下降段为空、已走到数组末尾、或末尾出现相等元素，都不是合法三段式
                continue  # 放弃本段

            q = i - 1  # q 是第二段下降的谷底下标
            s += nums[i]  # 谷底右侧第一个元素，必属于第三段上升段
            i += 1  # 该元素已处理，指针右移
            mx = t = 0  # mx：第三段的最大前缀和；t：当前前缀和
            while i < n and nums[i - 1] < nums[i]:  # 第三段：严格上升
                t += nums[i]  # 累加当前前缀和
                i += 1  # 指针右移
                mx = max(mx, t)  # 记录第三段的最优前缀和（可以为空，即只取上升的那一个元素）
            s += mx  # 把第三段的最优收益并入当前和

            mx = t = 0  # 重置，改为向左扩展第一段
            for j in range(p - 2, l - 1, -1):  # 从峰顶左侧往回走，取以 p-2 结尾的最大后缀和
                t += nums[j]  # 向左累加
                mx = max(mx, t)  # 记录第一段的最优后缀和（可以为空）
            s += mx  # 把第一段的最优收益并入当前和

            ans = max(ans, s)  # 更新全局答案
            i = q  # 从谷底重新开始，避免漏掉以它开头的新三段式
        return ans  # 返回三段式子数组的最大和
