// 3663. Find The Least Frequent Digit（3663. 出现频率最低的数字）
// 核心思路：逐位拆解整数，用长度为 10 的数组统计每个数字的出现次数，再从小到大枚举取出现次数最少的数字（并列取较小者）。
// 复杂度：时间 O(log n)（数的位数），空间 O(1)。
class Solution {  // 定义题解类
public:  // 公有成员，供判题器调用
    int getLeastFrequentDigit(int n) {  // 返回 n 中出现频率最低的数字，并列时取较小者
        int cnt[10]{};  // 统计 0~9 每个数字出现的次数
        for (; n > 0; n /= 10) {  // 逐位拆解 n，直到 n 为 0
            ++cnt[n % 10];  // 取出最低位数字并计数
        }  // 结束拆解循环
        int ans = 0, f = 1 << 30;  // ans 记录答案，f 记录当前最小出现次数
        for (int x = 0; x < 10; ++x) {  // 从小到大枚举数字 0~9
            if (cnt[x] > 0 && cnt[x] < f) {  // 该数字出现过且次数比当前最小次数更少
                f = cnt[x];  // 更新最小出现次数
                ans = x;  // 更新答案（严格小于保证并列时取较小数字）
            }  // 结束比较判断
        }  // 结束枚举循环
        return ans;  // 返回出现次数最少的数字
    }  // 结束方法
};  // 结束题解类
