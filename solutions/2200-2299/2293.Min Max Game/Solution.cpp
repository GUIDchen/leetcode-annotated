// 题目：2293. 极大极小游戏（Min Max Game）
// 核心思路：原地模拟。每轮长度减半，偶数下标取相邻两数的较小值、奇数下标取较大值，结果写回数组前部，缩到 1 个元素即答案。
// 时间复杂度：O(n)，总操作数 n + n/2 + ... < 2n；空间复杂度：O(1)，只用了常数个临时变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minMaxGame(vector<int>& nums) {  // nums：输入数组；返回游戏结束后剩下的那个数
        for (int n = nums.size(); n > 1;) {  // n 表示当前有效长度，每轮在循环体内减半，所以 for 不写自增表达式
            n >>= 1;  // 新一轮的有效长度是旧长度的一半
            for (int i = 0; i < n; ++i) {  // 只遍历前 n 个位置，结果就地覆盖旧数据
                int a = nums[i << 1], b = nums[i << 1 | 1];  // 一次取出相邻两个元素：下标 2i 与 2i+1
                nums[i] = i % 2 == 0 ? min(a, b) : max(a, b);  // 偶数下标取较小值、奇数下标取较大值，写回数组前部
            }  // 结束本轮合并
        }  // 结束外层循环，此时长度已缩到 1
        return nums[0];  // 只剩一个元素时 nums[0] 就是最终答案
    }
};  // 结束 Solution 类定义