// 题目：2211. 统计道路上的碰撞次数（Count Collisions on a Road）
// 思路：先剥掉左侧连续向左、右侧连续向右这些永远不会相遇的车，中间区间里除静止车之外每辆车都会碰撞一次。
// 时间复杂度：O(n)，两端扫描加一次计数共线性时间；空间复杂度：O(1)，只用了常数个边界变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countCollisions(string s) {  // s：每辆车用 'L' 或 'R' 表示朝向，返回碰撞总次数
        int n = s.size();  // n：道路上的车辆总数
        int l = 0, r = n - 1;  // l 指向第一辆不朝左的车，r 指向最后一辆不朝右的车
        while (l < n && s[l] == 'L') {  // 跳过开头一路向左的车，它们前面没有车，永远不会碰撞
            ++l;  // 左边界右移
        }
        while (r >= 0 && s[r] == 'R') {  // 跳过结尾一路向右的车，它们后面没有车，永远不会碰撞
            --r;  // 右边界左移
        }
        return r - l + 1 - count(s.begin() + l, s.begin() + r + 1, 'S');  // 区间 [l, r] 内每辆车都会碰撞，减去本来就静止的 'S' 个数即答案
    }
};
