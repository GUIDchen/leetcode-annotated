// 题目：2248. 多个数组求交集（Intersection of Multiple Arrays）
// 思路：用值域计数数组统计每个数在所有数组中出现的总次数，出现次数等于数组个数即为公共元素，按下标升序输出正好有序。
// 时间复杂度：O(元素总数 + 1000)；空间复杂度：O(1000)，值域计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> intersection(vector<vector<int>>& nums) {  // nums：若干数组（每个数组内元素互不相同）；返回它们的交集（升序）
        int cnt[1001]{};  // 值域为 1..1000 的计数器，{} 保证全部初始化为 0
        for (auto& arr : nums) {  // 逐个数组统计出现次数
            for (int& x : arr) {  // 遍历当前数组里的每个数
                ++cnt[x];  // 某个数每出现一次就累加，最终得到的是跨所有数组的总出现次数
            }  // 当前数组统计完毕
        }  // 所有数组都统计完毕
        vector<int> ans;  // 存放交集结果
        for (int x = 0; x < 1001; ++x) {  // 按数值从小到大扫描，结果天然升序；0 不会出现在输入里，一并跳过
            if (cnt[x] == nums.size()) {  // 出现次数恰好等于数组个数，说明每个数组都包含它
                ans.push_back(x);  // 公共元素加入答案
            }  // 判断结束
        }  // 扫描结束
        return ans;  // 返回升序的交集
    }  // 方法结束
};  // 类定义结束