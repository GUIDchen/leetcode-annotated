// 题目：2268. 最少按键次数（Minimum Number of Keypresses）
// 思路：统计每个字母的频次并从大到小排序，出现最多的 9 个字母安排 1 次按键，接下来 9 个安排 2 次，其余安排 3 次，按频次加权求和。
// 时间复杂度：O(n)，统计频次 O(n) 后只对 26 个字母排序（常数级）；空间复杂度：O(1)，仅用长度 26 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的解题方法
    int minimumKeypresses(string s) {  // s：输入字符串；返回把 26 个字母映射到键盘所需的最少按键次数
        int cnt[26]{};  // 频次数组：下标 0~25 对应字母 a~z，全部初始化为 0
        for (char& c : s) {  // 遍历字符串中的每个字符（引用避免拷贝）
            ++cnt[c - 'a'];  // 把字符映射成 0~25 的下标，对应频次加一
        }  // 内层统计结束
        sort(begin(cnt), end(cnt), greater<int>());  // 按频次从大到小排序，让高频字母排在最前面
        int ans = 0, k = 1;  // ans：累计按键总数；k：当前档位每按一次代表几次击键
        for (int i = 1; i <= 26; ++i) {  // 按频次从高到低遍历 26 个字母位置
            ans += k * cnt[i - 1];  // 高频字母优先占用 k 较小的键位，按键总数为 k 乘以频次
            if (i % 9 == 0) {  // 每 9 个字母正好用满一轮 9 个键位
                ++k;  // 下一档字母需要多按一次键
            }  // 档位提升判断结束
        }  // 遍历结束
        return ans;  // 返回最少按键总数
    }  // 解题方法结束
};  // 题解类结束