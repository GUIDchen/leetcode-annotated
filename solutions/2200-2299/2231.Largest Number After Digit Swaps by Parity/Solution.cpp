// 题目：2231. 按奇偶性交换后的最大数字（Largest Number After Digit Swaps by Parity）
// 核心思路：交换只能发生在奇偶性相同的两个数字之间，所以每一位能填的数字集合由该位原数字的奇偶性决定；
//           先统计 0-9 各数字的出现次数，再从高位到低位尽量填入同奇偶性中最大的可用数字。
// 时间复杂度：O(n + 10)，n 是数字的位数；空间复杂度：O(1)，只用到长度为 10 的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int largestInteger(int num) {  // num：输入的非负整数
        string s = to_string(num);  // 转成字符串，方便按下标逐位处理
        int cnt[10] = {0};  // cnt[d]：数字 d 还剩下几个可用（交换只能搬动同奇偶的数字）
        for (char c : s) {  // 第一次遍历：统计每个数字在 num 中出现的次数
            cnt[c - '0']++;  // 字符转成数字后，对应的计数加一
        }
        int idx[2] = {8, 9};  // idx[0]：当前可用的最大偶数字；idx[1]：当前可用的最大奇数字
        int ans = 0;  // 逐位拼出的答案
        for (char c : s) {  // 第二次遍历：从左到右确定每个位置能放的最大数字
            int x = c - '0';  // 该位置原来的数字，它的奇偶性决定了这一位能用哪些数字
            while (cnt[idx[x & 1]] == 0) {  // 当前同奇偶性中最大的数字已经用完了
                idx[x & 1] -= 2;  // 退到下一个同奇偶性的数字（减 2 不改变奇偶性）
            }
            ans = ans * 10 + idx[x & 1];  // 把选中的数字接到答案末尾；高位优先所以整体必然最大
            cnt[idx[x & 1]]--;  // 这个数字用掉一个，剩余计数减一
        }
        return ans;  // 返回能得到的最大数字
    }
};
