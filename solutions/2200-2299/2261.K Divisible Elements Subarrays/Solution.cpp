// 题目：2261. 含最多 K 个可整除元素的子数组（K Divisible Elements Subarrays）
// 思路：枚举左端点，向右扩展右端点；用计数器限制被 p 整除的元素不超过 k 个，同时滚动维护双哈希，把每个合法子数组的哈希签名塞进集合去重，集合大小即答案。
// 时间复杂度：O(n^2)，每个左端点向右最多扩展 n 步；空间复杂度：O(n^2)，集合最多保存 O(n^2) 个子数组的签名。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countDistinct(vector<int>& nums, int k, int p) {  // nums：原数组；k：子数组内可被 p 整除元素的上限；返回本质不同且合法的子数组个数
        unordered_set<long long> s;  // 集合存放子数组的双哈希签名，借用集合特性自动去重
        int n = nums.size();  // 数组长度，作为两层循环的上界
        int base1 = 131, base2 = 13331;  // 两组不同的哈希基数，降低两个哈希同时碰撞的概率
        int mod1 = 1e9 + 7, mod2 = 1e9 + 9;  // 两个大质数模数，把哈希值压在 32 位以内，便于拼接
        for (int i = 0; i < n; ++i) {  // 枚举子数组的左端点 i
            long long h1 = 0, h2 = 0;  // 空子数组的哈希值记为 0，从这里开始向右滚动
            int cnt = 0;  // 当前子数组内能被 p 整除的元素个数
            for (int j = i; j < n; ++j) {  // 枚举右端点 j，逐个把 nums[j] 接进当前子数组
                cnt += nums[j] % p == 0;  // 布尔表达式转成 0/1 累加，统计可整除元素
                if (cnt > k) {  // 可整除元素已经超过 k 个，再往右延长只会更多
                    break;  // 提前结束本轮右端点扩张
                }
                h1 = (h1 * base1 + nums[j]) % mod1;  // 滚动哈希：h1 = h1 * base1 + 新元素，相当于在末尾追加一位
                h2 = (h2 * base2 + nums[j]) % mod2;  // 第二组哈希用另一个基数和模数同步滚动
                s.insert(h1 << 32 | h2);  // 把两个哈希拼成一个 64 位整数作为签名插入集合，相同内容只保留一份
            }
        }
        return s.size();  // 集合大小就是满足条件的本质不同子数组数量
    }
};
