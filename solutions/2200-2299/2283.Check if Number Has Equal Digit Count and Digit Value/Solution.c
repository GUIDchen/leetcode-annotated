// 题目：2283. 判断一个数的数字计数是否等于数位的值（Check if Number Has Equal Digit Count and Digit Value）
// 核心思路：先统计字符串中 0~9 各出现多少次，再逐位校验「第 i 位的字符」是否正好等于「数字 i 的出现次数」。
// 时间复杂度：O(n)，两趟线性扫描；空间复杂度：O(1)，只需要长度固定为 10 的计数数组。
bool digitCount(char* num) {  // num：只含数字字符的字符串，第 i 位声明数字 i 应出现的次数
    int cnt[10] = {0};  // 10 个数字的出现次数，全部初始化为 0
    for (int i = 0; num[i] != '\0'; ++i) {  // 第一趟：遍历字符串，直到结尾的 '\0'
        ++cnt[num[i] - '0'];  // 字符减去 '0' 得到数值，对应计数加一
    }  // 第一趟结束
    for (int i = 0; num[i] != '\0'; ++i) {  // 第二趟：逐位校验声明是否与实际计数一致
        if (cnt[i] != num[i] - '0') {  // 数字 i 的真实出现次数与第 i 位声明的次数不一致
            return false;  // 有一个位置不满足就立即判假
        }  // 判断分支结束
    }  // 校验循环结束
    return true;  // 所有位置都一致，返回真
}  // 函数结束