# 题目：2222. 选择建筑的方案数（Number of Ways to Select Buildings）
# 思路：合法方案形如 010 或 101，枚举中间位置，用左右两侧异类计数相乘并累加；边遍历边维护两侧计数。
# 时间复杂度：O(n)，只扫描字符串一次；空间复杂度：O(1)，只用四个计数器。
class Solution:  # LeetCode 约定的题解类
    def numberOfWays(self, s: str) -> int:  # s：由 '0'/'1' 组成的街道字符串，返回合法三元组个数
        l = [0, 0]  # l[0]/l[1]：当前位置左侧（已遍历部分）0 和 1 的个数，初始为空
        r = [s.count("0"), s.count("1")]  # r[0]/r[1]：右侧（未遍历部分）0 和 1 的个数，初始是整个字符串
        ans = 0  # 累加所有合法方案的个数
        for x in map(int, s):  # 把每个字符转成 0/1，并把它当作三元组的中间建筑
            r[x] -= 1  # 当前位置本身要从中移出，右侧对应计数减一
            ans += l[x ^ 1] * r[x ^ 1]  # 左右两侧都取 x 的相反值才能形成 010/101，用乘法原理累加
            l[x] += 1  # 当前位置归入左侧，为后面的中间位置更新计数
        return ans  # 返回选择建筑的方案总数
