// 题目：2222. 选择建筑的方案数（Number of Ways to Select Buildings）
// 思路：合法方案形如 010 或 101，枚举中间位置，用左右两侧异类计数相乘并累加；边遍历边维护计数。
// 时间复杂度：O(n)，只扫描字符串一次；空间复杂度：O(1)，只用四个计数器。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long numberOfWays(string s) {  // s：由 '0'/'1' 组成的街道字符串，返回合法三元组个数
        int n = s.size();  // 街道长度，决定遍历范围
        int l[2]{};  // l[0]/l[1]：当前位置左侧（已遍历部分）0 和 1 的个数，初始都为 0
        int r[2]{};  // r[0]/r[1]：当前位置右侧（未遍历部分）0 和 1 的个数
        r[0] = ranges::count(s, '0');  // 初始时整个字符串都算右侧，先统计其中 0 的个数
        r[1] = n - r[0];  // 剩下的自然都是 1，这样无需再遍历一次
        long long ans = 0;  // 累加所有合法方案的个数
        for (int i = 0; i < n; ++i) {  // 把每个位置当作三元组的中间建筑
            int x = s[i] - '0';  // 把字符转成 0/1，方便当作数组下标使用
            r[x]--;  // 当前位置本身要从中移出，右侧计数减一
            ans += 1LL * l[x ^ 1] * r[x ^ 1];  // 左右两侧取 x 的相反值才能形成 010/101，乘法原理累加
            l[x]++;  // 当前位置归入左侧，为后面的中间位置更新计数
        }
        return ans;  // 返回选择建筑的方案总数
    }
};
