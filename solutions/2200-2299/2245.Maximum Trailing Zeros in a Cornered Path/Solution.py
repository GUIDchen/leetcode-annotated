# 题目：2245. 转角路径的乘积中最多能有几个尾随零（Maximum Trailing Zeros in a Cornered Path）
# 思路：尾随零来自乘积中的 10 = 2*5，故只需统计路径上因子 2 与因子 5 的个数并取较小者；
# 时间复杂度：O(m*n)，枚举拐角点后 O(1) 拼算；空间复杂度：O(m*n)，四张 (m+1)*(n+1) 前缀和表。
class Solution:  # LeetCode 约定的题解类
    def maxTrailingZeros(self, grid: List[List[int]]) -> int:  # grid 为 m 行 n 列矩阵；返回转角路径乘积中尾随零的最大个数
        m, n = len(grid), len(grid[0])  # 元素个数分别记为 m、n，后面建表要各多出一行/一列
        r2 = [[0] * (n + 1) for _ in range(m + 1)]  # r2[i][j]：第 i 行第 1 列到第 j 列（含）的因子 2 个数之和
        c2 = [[0] * (n + 1) for _ in range(m + 1)]  # c2[i][j]：第 j 列第 1 行到第 i 行（含）的因子 2 个数之和
        r5 = [[0] * (n + 1) for _ in range(m + 1)]  # r5[i][j]：第 i 行第 1 列到第 j 列的因子 5 个数之和
        c5 = [[0] * (n + 1) for _ in range(m + 1)]  # c5[i][j]：第 j 列第 1 行到第 i 行的因子 5 个数之和
        for i, row in enumerate(grid, 1):  # enumerate 从 1 开始，让网格下标与 1-based 前缀和下标一致，省去边界判断
            for j, x in enumerate(row, 1):  # 同时取到列下标 j 与格子里的数 x
                s2 = s5 = 0  # s2、s5 分别累计本格因子 2 与因子 5 的个数（链式赋值同时置 0）
                while x % 2 == 0:  # 反复除以 2，直到 x 不再含因子 2
                    x //= 2  # 整除 2，剥掉一个因子 2
                    s2 += 1  # 因子 2 计数加一
                while x % 5 == 0:  # 在剩下的 x 上继续剥离因子 5
                    x //= 5  # 整除 5，剥掉一个因子 5
                    s5 += 1  # 因子 5 计数加一
                r2[i][j] = r2[i][j - 1] + s2  # 行方向前缀和：左边的累计值加上本格的因子 2 个数
                c2[i][j] = c2[i - 1][j] + s2  # 列方向前缀和：上边的累计值加上本格的因子 2 个数
                r5[i][j] = r5[i][j - 1] + s5  # 行方向因子 5 的前缀和，与 r2 完全对称
                c5[i][j] = c5[i - 1][j] + s5  # 列方向因子 5 的前缀和，与 c2 完全对称
        ans = 0  # 答案至少为 0：单个格子也可能没有零因子
        for i in range(1, m + 1):  # 枚举拐角点所在行
            for j in range(1, n + 1):  # 枚举拐角点所在列
                a = min(r2[i][j] + c2[i - 1][j], r5[i][j] + c5[i - 1][j])  # a = 向左横臂（含拐角格）+ 向上竖臂（不含拐角格）
                b = min(r2[i][j] + c2[m][j] - c2[i][j], r5[i][j] + c5[m][j] - c5[i][j])  # b = 向左横臂 + 向下竖臂：整列减去前 i 行即得到 i 行以下的格子
                c = min(r2[i][n] - r2[i][j] + c2[i][j], r5[i][n] - r5[i][j] + c5[i][j])  # c = 向右横臂 + 向上竖臂：整行减去前 j 列即得到 j 列以右的格子
                d = min(  # d = 向右横臂 + 向下竖臂：两臂都含拐角格，故用 j-1、i 作为切分边界
                    r2[i][n] - r2[i][j - 1] + c2[m][j] - c2[i][j],  # 下臂的因子 2 个数（多行表达式，便于逐项核对）
                    r5[i][n] - r5[i][j - 1] + c5[m][j] - c5[i][j],  # 下臂的因子 5 个数，与上一行对称
                )  # 多行表达式结束
                ans = max(ans, a, b, c, d)  # 取四种拼法的 min(因子2, 因子5)，再与已有答案比较
        return ans  # 返回最大尾随零个数
