// 题目：2245. 转角路径的乘积中最多能有几个尾随零（Maximum Trailing Zeros in a Cornered Path）
// 思路：尾随零的个数 = 路径乘积中因子 2 与因子 5 个数的较小值；先预处理每个格子的行/列方向因子 2、因子 5 前缀和，
// 时间复杂度：O(m*n)，枚举拐角点并做 O(1) 的四种拼算；空间复杂度：O(m*n)，四张 (m+1)*(n+1) 前缀和表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxTrailingZeros(vector<vector<int>>& grid) {  // grid：m 行 n 列的非负整数矩阵；返回转角路径乘积中尾随零的最大个数
        int m = grid.size(), n = grid[0].size();  // 记下行数 m 与列数 n，后面建前缀和表时每个方向都要多开一行/一列
        vector<vector<int>> r2(m + 1, vector<int>(n + 1));  // r2[i][j]：第 i 行从第 1 列到第 j 列（含）的因子 2 个数之和
        vector<vector<int>> c2(m + 1, vector<int>(n + 1));  // c2[i][j]：第 j 列从第 1 行到第 i 行（含）的因子 2 个数之和
        vector<vector<int>> r5(m + 1, vector<int>(n + 1));  // r5[i][j]：第 i 行从第 1 列到第 j 列的因子 5 个数之和
        vector<vector<int>> c5(m + 1, vector<int>(n + 1));  // c5[i][j]：第 j 列从第 1 行到第 i 行的因子 5 个数之和
        for (int i = 1; i <= m; ++i) {  // 行下标从 1 开始，正好与上面 1-based 的前缀和下标对齐，省去边界判断
            for (int j = 1; j <= n; ++j) {  // 列下标同样从 1 开始
                int x = grid[i - 1][j - 1];  // 取出原矩阵中对应的格子（前缀和下标比原矩阵整体大 1）
                int s2 = 0, s5 = 0;  // s2、s5 分别累计这一格的因子 2 与因子 5 的个数
                for (; x % 2 == 0; x /= 2) {  // 反复除以 2，直到 x 不再含有因子 2
                    ++s2;  // 每除掉一个 2，因子 2 的计数加一
                }  // 因子 2 统计结束
                for (; x % 5 == 0; x /= 5) {  // 在剩下的 x 上反复除以 5，5 与 2 互不影响，可接着除
                    ++s5;  // 每除掉一个 5，因子 5 的计数加一
                }  // 因子 5 统计结束
                r2[i][j] = r2[i][j - 1] + s2;  // 行方向前缀和：左边的累计值加上本格的因子 2 个数
                c2[i][j] = c2[i - 1][j] + s2;  // 列方向前缀和：上边的累计值加上本格的因子 2 个数
                r5[i][j] = r5[i][j - 1] + s5;  // 行方向因子 5 的前缀和，写法与 r2 完全对称
                c5[i][j] = c5[i - 1][j] + s5;  // 列方向因子 5 的前缀和，写法与 c2 完全对称
            }  // 本行预处理完成
        }  // 所有格子的四个前缀和都建好了
        int ans = 0;  // 答案至少为 0：单个格子也可能没有零因子
        for (int i = 1; i <= m; ++i) {  // 枚举拐角点所在的行
            for (int j = 1; j <= n; ++j) {  // 枚举拐角点所在的列
                int a = min(r2[i][j] + c2[i - 1][j], r5[i][j] + c5[i - 1][j]);  // a = 向左的横臂 + 向上的竖臂：横臂含拐角格，竖臂从 i-1 行往上取
                int b = min(r2[i][j] + c2[m][j] - c2[i][j], r5[i][j] + c5[m][j] - c5[i][j]);  // b = 向左的横臂 + 向下的竖臂：竖臂用整列减去前 i 行得到 i 行以下的格子
                int c = min(r2[i][n] - r2[i][j] + c2[i][j], r5[i][n] - r5[i][j] + c5[i][j]);  // c = 向右的横臂 + 向上的竖臂：横臂用整行减去前 j 列，竖臂含拐角格
                int d = min(r2[i][n] - r2[i][j - 1] + c2[m][j] - c2[i][j], r5[i][n] - r5[i][j - 1] + c5[m][j] - c5[i][j]);  // d = 向右的横臂 + 向下的竖臂：两条臂都含拐角格，故 j 侧用 j-1、i 侧用 i 来切分
                ans = max({ans, a, b, c, d});  // 对每种拼法取 min(因子2总数, 因子5总数)，再与已有答案比较
            }  // 本行的拐角点枚举完毕
        }  // 所有拐角点都已尝试
        return ans;  // 返回出现过的最大尾随零个数
    }  // 方法结束
};  // 类定义结束