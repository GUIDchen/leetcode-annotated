# 题目：2272. 最大波动的子字符串（Substring With Largest Variance）
# 思路：枚举字符有序对 (a, b)，把 a 记 +1、b 记 -1，用两个滚动状态求「至少含一个 b」的最大子段和。
# 时间复杂度：O(26 × 25 × n) = O(n)；空间复杂度：O(1)，只用了常数个状态。
class Solution:  # LeetCode 约定的题解类
    def largestVariance(self, s: str) -> int:  # s：输入字符串；返回最大波动值
        ans = 0  # 全局答案；单字符子串的波动为 0，所以从 0 开始
        for a, b in permutations(ascii_lowercase, 2):  # 枚举所有有序字符对：a 为多数方、b 为少数方（排列不会重复取同一字符）
            if a == b:  # 防御性判断：两字符相同时波动恒为 0
                continue  # 直接跳过这一对
            f = [0, -inf]  # f 的下标 0 表示「末尾连续 a 段长度」（遇 b 清零），下标 1 表示「末尾至少含一个 b 的最大 a 数 - b 数」，-inf 表示该状态还不存在
            for c in s:  # 从左到右扫描整个字符串
                if c == a:  # 遇到 a，相当于差值加 1
                    f[0], f[1] = f[0] + 1, f[1] + 1  # 两个状态同步加 1：纯 a 段延长，已有合法段的差值也变大
                elif c == b:  # 遇到 b，相当于差值减 1
                    f[1] = max(f[1] - 1, f[0] - 1)  # 要么接在已有合法段之后，要么用「前面的纯 a 段 + 当前 b」新开一段
                    f[0] = 0  # 出现 b 后纯 a 段被切断，长度清零重新累计
                if ans < f[1]:  # 当前结尾的最优差值比答案更好时
                    ans = f[1]  # 更新全局答案
        return ans  # 返回所有字符对、所有子串中的最大波动值
