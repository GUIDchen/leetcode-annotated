// 题目：2272. 最大波动的子字符串（Substring With Largest Variance）
// 思路：枚举有序字符对 (a, b)，把 a 记 +1、b 记 -1，用两个滚动状态求「至少含一个 b」的最大子段和，再对所有字符对取最大。
// 时间复杂度：O(26 × 26 × n) = O(n)，常数 676；空间复杂度：O(1)，只用常数个状态变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int largestVariance(string s) {  // s：输入字符串；返回任意子串中「出现次数差」的最大值
        int n = s.size();  // 记下字符串长度，后面用 -n 作为「还没出现过 b」的哨兵初值
        int ans = 0;  // 全局答案；单字符或空子串的波动为 0，所以从 0 开始
        for (char a = 'a'; a <= 'z'; ++a) {  // 枚举子串里出现次数较多的那个字符 a
            for (char b = 'a'; b <= 'z'; ++b) {  // 枚举子串里出现次数较少的那个字符 b
                if (a == b) {  // 两个字符相同就谈不上「次数差」
                    continue;  // 跳过这一对，避免自己减自己
                }
                int f[2] = {0, -n};  // f[0]：以当前位置结尾的连续 a 段长度（遇到 b 会清零）；f[1]：以当前位置结尾且至少含一个 b 的最大 (a 个数 - b 个数)，-n 表示这种段还不存在
                for (char c : s) {  // 从左到右扫描整个字符串
                    if (c == a) {  // 遇到字符 a，相当于给差值加 1
                        f[0]++;  // 纯 a 段继续延长
                        f[1]++;  // 已存在的合法段差值同样加 1
                    } else if (c == b) {  // 遇到字符 b，相当于给差值减 1
                        f[1] = max(f[1] - 1, f[0] - 1);  // 要么把 b 接在已有合法段之后，要么用「前面的纯 a 段 + 当前这个 b」重新开一段
                        f[0] = 0;  // 出现过 b 之后，纯 a 段被切断，必须从下一位置重新累计
                    }  // 其他字符既不是 a 也不是 b，不影响差值，直接忽略
                    ans = max(ans, f[1]);  // 用「以当前字符结尾」的最优差值更新答案
                }
            }
        }
        return ans;  // 返回所有字符对、所有子串中的最大波动值
    }
};
