# 题目：3983. Subsequence After One Replacement（3983. 一次替换后的子序列）
# 核心思路：双指针贪心。i0 表示还没用掉替换时 s 已匹配的长度，i1 表示已经用掉替换时 s 已匹配的长度，i1 始终至少领先 i0 一位（相差的那一位就是被替换的字符），按 t 逐字符推进。
# 复杂度：时间 O(m + n)（m、n 分别为 s、t 的长度），空间 O(1)。
class Solution:  # 定义题解类
    def canMakeSubsequence(self, s: str, t: str) -> bool:  # 判断 s 中用至多一次替换后能否成为 t 的子序列
        m, n = len(s), len(t)  # m、n 分别为两串长度
        i0 = i1 = j = 0  # i0 未用替换的匹配长度，i1 已用替换的匹配长度，j 为 t 的下标

        while i1 < m and j < n:  # s 还没匹配完且 t 还没扫完时继续
            if s[i1] == t[j]:  # 已使用替换的路径可以自由匹配当前字符
                i1 += 1  # 匹配成功，i1 前进一位
            i1 = max(i1, i0 + 1)  # 强制 i1 至少比 i0 多走一位，多出的这一位就是被替换掉的字符

            if s[i0] == t[j]:  # 未使用替换的路径也能匹配当前字符
                i0 += 1  # 未使用替换的匹配长度前进一位

            j += 1  # t 的下标后移；没被匹配上的字符就是被替换的那个

        return i1 == m  # i1 达到 m 说明整个 s 都已匹配（含一处替换）
