// 3964. 照亮道路的最少灯泡数 / Minimum Lights to Illuminate a Road
// 核心思路：先用差分数组标记已有灯泡的照明覆盖区间，再扫描整条路找出所有未被照亮的连续空段，
//          新增路灯照不到 3 个连续位置，因此长度为 cnt 的空段需要 ceil(cnt/3) = (cnt+2)/3 盏。
// 复杂度：时间 O(n)（两次线性扫描），空间 O(n)（差分数组）。

class Solution {
public:
    int minLights(vector<int>& lights) {  // 返回让所有位置都可见所需的最少新增路灯数
        int n = lights.size();  // 道路长度
        vector<int> d(n);  // 差分数组，用于还原每个位置被多少盏已有灯照亮

        for (int i = 0; i < n; ++i) {  // 遍历每个位置上的已有灯泡
            int v = lights[i];  // 该位置灯泡的照明半径，0 表示没有可用灯泡
            if (v > 0) {  // 只有存在可用灯泡时才标记覆盖区间
                int l = max(0, i - v);  // 覆盖区间左端点（不越界）
                int r = min(n - 1, i + v);  // 覆盖区间右端点（不越界）
                ++d[l];  // 差分：区间起点覆盖数加一
                if (r + 1 < n) {  // 区间右端点之后仍在数组范围内
                    --d[r + 1];  // 差分：区间结束后覆盖数减一
                }
            }
        }

        int s = 0, cnt = 0, ans = 0;  // s 为当前位置覆盖数，cnt 为当前未照亮空段长度，ans 为新增灯泡总数
        for (int x : d) {  // 从左到右扫描整条路
            s += x;  // 用差分前缀和得到当前位置的覆盖灯泡数
            if (s == 0) {  // 该位置没有被任何已有灯泡照亮
                ++cnt;  // 未照亮空段长度加一
            } else {  // 空段被已有照明打断
                ans += (cnt + 2) / 3;  // 一盏新灯最多覆盖 3 个连续位置，向上取整即 (cnt+2)/3
                cnt = 0;  // 重置空段计数，开始统计下一段
            }
        }

        ans += (cnt + 2) / 3;  // 处理扫描结束时仍在累积的最后一段空段
        return ans;  // 返回所需的最少新增灯泡数
    }
};