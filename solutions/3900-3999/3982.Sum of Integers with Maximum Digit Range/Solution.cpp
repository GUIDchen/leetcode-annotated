// 题目：3982. Sum of Integers with Maximum Digit Range（3982. 最大数字范围的整数之和）
// 核心思路：逐个整数拆位求出「最大数位 - 最小数位」，维护全局最大数位差；数位差更大则重置答案，并列最大则累加该数。
// 复杂度：时间 O(n·log10 V)（V 为数值大小，每个数要拆位），空间 O(1)。
class Solution {  // 定义题解类
public:  // 公开接口
    int maxDigitRange(vector<int>& nums) {  // 主函数：返回数位差最大的所有整数之和
        int ans = 0, mx = 0;  // ans 存和，mx 存当前见过的最大数位差
        for (int x : nums) {  // 依次枚举数组中的每个整数
            int a = 10, b = 0;  // a 记录最小数位（初值 10 便于取小），b 记录最大数位
            for (int y = x; y > 0; y /= 10) {  // 不断除以 10，从低位到高位拆出每一位
                int v = y % 10;  // v 为当前最低位上的数字
                a = min(a, v);  // 用当前位更新最小数位
                b = max(b, v);  // 用当前位更新最大数位
            }  // 拆位循环结束
            int r = b - a;  // r 为该整数的数位差 = 最大数位 - 最小数位
            if (mx < r) {  // 出现了更大的数位差
                mx = r;  // 更新全局最大数位差
                ans = x;  // 之前累加的结果作废，答案重置为当前整数
            } else if (mx == r) {  // 数位差与当前最大值相等
                ans += x;  // 把当前整数累加进答案
            }  // 条件分支结束
        }  // 数组遍历结束
        return ans;  // 返回所有最大数位差的整数之和
    }  // 方法结束
};  // 类定义结束