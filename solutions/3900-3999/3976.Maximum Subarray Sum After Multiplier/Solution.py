# 3976. Maximum Subarray Sum After Multiplier | 乘以系数后最大子数组和（中等）
# 核心思路：把“是否已经用过乘 / 除操作”编成 4 个状态做线性 DP：f[i][0] 表示还没用操作、f[i][1] 表示正处在“整体乘 k”的段内、f[i][2] 表示正处在“整体除 k”的段内、f[i][3] 表示乘或除已经结束；每个状态都可以从“在此处重新开始子数组”（取 0）或延续上一位置转移而来，最后取所有状态的最大值。
# 复杂度：时间 O(n)，每个位置只做常数次转移与一次 4 元素取最大；空间 O(n)，需要 n + 1 个长度为 4 的状态数组。
class Solution:  # 定义题解类
    def maxSubarraySum(self, nums: List[int], k: int) -> int:  # 返回最多使用一次乘 k / 除 k 之后的最大子数组和
        n = len(nums)  # 数组长度
        f = [[-inf] * 4 for _ in range(n + 1)]  # f[i][s]：以第 i 个元素结尾、处于状态 s 的最大子数组和，先全部置为负无穷
        f[0][0] = 0  # 空前缀、还没用任何操作，和是 0，作为一切转移的起点
        ans = -inf  # 记录所有状态、所有位置上的最大值
        for i, x in enumerate(nums, 1):  # 从 1 开始编号，逐个元素推进 DP
            f[i][0] = max(f[i - 1][0], 0) + x  # 还没用操作：要么延续上一段的未操作部分，要么从这里重新开始（取 0）
            f[i][1] = max(f[i - 1][0], f[i - 1][1], 0) + x * k  # 乘 k 段内：可从“未操作”刚切进来、继续留在乘 k 段，或在此重新开始，当前元素乘 k
            f[i][2] = max(f[i - 1][0], f[i - 1][2], 0) + int(x / k)  # 除 k 段内：同理，当前元素整除 k；int(x / k) 表示向零取整，与 C++ 的整数除法一致
            f[i][3] = max(f[i - 1][1], f[i - 1][2], f[i - 1][3]) + x  # 乘或除已结束：从“乘 k 段内”“除 k 段内”或“已结束”延续，当前元素按原值计入
            ans = max(ans, max(f[i]))  # 用当前位置四个状态的最大值更新全局答案
        return ans  # 返回最大子数组和
