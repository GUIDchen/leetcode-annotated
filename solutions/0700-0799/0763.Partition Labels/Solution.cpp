// 题目：763. 划分字母区间（Partition Labels）
// 思路：先记录每个字母最后出现的位置，再贪心扫描：当前片段的右端点不断扩展到已扫描字母的最远出现位置，右端点与下标重合时切分。
// 时间复杂度：O(n)，两趟线性扫描；空间复杂度：O(1)，仅用 26 个字母的最后位置数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> partitionLabels(string s) {  // s：待划分的小写字母字符串
        int last[26] = {0};  // last[c] 记录字母 c 最后一次出现的下标
        int n = s.size();  // 字符串长度
        for (int i = 0; i < n; ++i) {  // 第一趟：预处理每个字母的最远出现位置
            last[s[i] - 'a'] = i;  // 用字符减 'a' 映射到 0..25 的下标
        }
        vector<int> ans;  // 保存每个片段的长度
        int mx = 0, j = 0;  // mx 是当前片段能延伸到的最远下标，j 是片段起点
        for (int i = 0; i < n; ++i) {  // 第二趟：贪心地扩展片段右端点
            mx = max(mx, last[s[i] - 'a']);  // 用当前字符的最后出现位置刷新右端点
            if (mx == i) {  // 右端点与当前下标重合，说明片段内字母都不会再出现在后面
                ans.push_back(i - j + 1);  // 记录该片段长度
                j = i + 1;  // 下一个片段的起点
            }
        }
        return ans;  // 返回各片段长度
    }
};  // 类定义结束（源文件末尾无换行）