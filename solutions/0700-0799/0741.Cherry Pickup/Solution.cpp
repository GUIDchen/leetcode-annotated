// 题目：741. 摘樱桃（Cherry Pickup）
// 思路：一来一回等价于「两个人同时从 (0,0) 走到 (n-1,n-1)」；用 k = i + j 表示步数做阶段，f[k][i1][i2] 表示两人分别在第 i1、i2 行时的最大樱桃数。
// 时间复杂度：O(n^3)，状态数与转移都是 O(n^3)；空间复杂度：O(n^3)，三维 DP 数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int cherryPickup(vector<vector<int>>& grid) {  // grid：n×n 地图，1 表示有樱桃、0 表示空、-1 表示障碍，返回往返最多能摘到的樱桃数
        int n = grid.size();  // 地图边长
        vector<vector<vector<int>>> f(n << 1, vector<vector<int>>(n, vector<int>(n, -1e9)));  // f[k][i1][i2]：第 k 步时两人所在行；-1e9 表示该状态不可达
        f[0][0][0] = grid[0][0];  // 起点只有一种状态：两人都在 (0,0)，樱桃只算一次
        for (int k = 1; k < n * 2 - 1; ++k) {  // 枚举步数 k = 行 + 列，取值范围 1 .. 2n-2
            for (int i1 = 0; i1 < n; ++i1) {  // 枚举第一个人的行号
                for (int i2 = 0; i2 < n; ++i2) {  // 枚举第二个人的行号
                    int j1 = k - i1, j2 = k - i2;  // 由步数与行反推出两人的列号
                    if (j1 < 0 || j1 >= n || j2 < 0 || j2 >= n || grid[i1][j1] == -1 || grid[i2][j2] == -1) {  // 越界或踩到障碍 ⇒ 该状态非法，跳过
                        continue;  // 跳过这一对 (i1, i2)
                    }  // 结束 if
                    int t = grid[i1][j1];  // 当前位置的樱桃
                    if (i1 != i2) {  // 两人不在同一格时才加上第二个人的樱桃（重合只算一次）
                        t += grid[i2][j2];  // 加上第二个人所在格的樱桃
                    }  // 结束 if
                    for (int x1 = i1 - 1; x1 <= i1; ++x1) {  // 枚举第一个人在上一行/同一行时的行号（只能从上方或左侧走来）
                        for (int x2 = i2 - 1; x2 <= i2; ++x2) {  // 枚举第二个人对应的上一行行号
                            if (x1 >= 0 && x2 >= 0) {  // 上一行行号合法才可转移
                                f[k][i1][i2] = max(f[k][i1][i2], f[k - 1][x1][x2] + t);  // 用上一阶段的最优值加上本格樱桃来更新当前状态
                            }  // 结束 x2 的循环
                        }  // 结束 x1 的循环
                    }  // 结束 i2 的循环
                }  // 结束 i1 的循环
            }  // 结束 k 的循环
        }
        return max(0, f[n * 2 - 2][n - 1][n - 1]);  // 终点必然共处一格；与 0 取大，表示无解时返回 0
    }  // 结束 cherryPickup
};  // 结束 Solution 类