// 题目：709. 转换成小写字母（To Lower Case）
// 思路：逐字符扫描，只把大写字母 A 到 Z 通过按位或 32 变成小写，其余字符原样保留。
// 时间复杂度：O(n)，n 为字符串长度；空间复杂度：O(1)，直接在原字符串上就地修改。
char* toLowerCase(char* s) {  // 就地把字符串中的大写字母转成小写，返回同一个指针
    int n = strlen(s);  // 求字符串长度，作为循环上界（换大写字母不改变长度）
    for (int i = 0; i < n; i++) {  // 逐字符扫描整个字符串
        if (s[i] >= 'A' && s[i] <= 'Z') {  // 只处理大写字母 A 到 Z
            s[i] |= 32;  // 大写与小写的 ASCII 码相差 32，按位或 32 即可把小写化
        }
    }  // 返回修改后的字符串
    return s;  // 函数结束
}