// 题目：738. 单调递增的数字（Monotone Increasing Digits）
// 思路：从高位找第一处下降，把下降位置的前一位减一（并向前连锁处理相等的情况），其后的所有位统一改成 9，得到不超过 n 的最大单调递增数。
// 时间复杂度：O(log n)，只扫描数字的位数；空间复杂度：O(log n)，保存数字的字符串。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int monotoneIncreasingDigits(int n) {  // n：待转换的整数，返回不超过 n 的最大单调递增数
        string s = to_string(n);  // 转成字符串，方便按下标修改某一位数字
        int i = 1;  // 从第二位开始找第一处「前一位大于当前位」的下降位置
        for (; i < s.size() && s[i - 1] <= s[i]; ++i)  // 只要仍然非递减就继续右移
            ;  // 循环体为空：i 最终停在第一个下降下标（或等于长度表示整个数已单调）
        if (i < s.size()) {  // 存在下降位置，需要调整；否则原数本身就是答案
            for (; i > 0 && s[i - 1] > s[i]; --i) {  // 从下降位置向前回溯：前一位大于当前位时借位减一
                --s[i - 1];  // 把前一位数字减一，使高位变小
            }  // 结束向前回溯的 for
            ++i;  // 此时 i 指向被减一的位置的下一位
            for (; i < s.size(); ++i) {  // 把这之后的所有位都填成 9 才能取到最大
                s[i] = '9';  // 该位改成 9
            }  // 结束填空 9 的 for
        }  // 结束 if
        return stoi(s);  // 字符串转回整数作为答案
    }  // 结束 monotoneIncreasingDigits
};  // 结束 Solution 类