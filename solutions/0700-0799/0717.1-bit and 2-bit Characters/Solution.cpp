// 题目：717. 1 比特与 2 比特字符（1-bit and 2-bit Characters）
// 核心思路：顺序贪心解码。遇 0 说明这是 1 比特字符，前进 1 格；遇 1 说明这是 2 比特字符的首位，前进 2 格。最终若正好停在最后一位，该位就是独立的 1 比特字符。
// 时间复杂度：O(n)，指针单调前进；空间复杂度：O(1)，只用了两个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 对外可见的接口区
    bool isOneBitCharacter(vector<int>& bits) {  // bits 是末尾为 0 的编码数组，判断最后一位是否只能是单比特字符
        int i = 0, n = bits.size();  // i 是当前解码位置，n 是编码总长度
        while (i < n - 1) {  // 只要还没走到最后一位，就继续按规则前进
            i += bits[i] + 1;  // 遇 1 说明是 2 比特字符（跳 2 格），遇 0 说明是 1 比特字符（跳 1 格）
        }  // 结束解码循环
        return i == n - 1;  // 正好停在最后一位说明它是单比特字符；若越过则说明它是某个 2 比特字符的第二位
    }  // 结束 isOneBitCharacter 方法
};  // 结束 Solution 类定义
