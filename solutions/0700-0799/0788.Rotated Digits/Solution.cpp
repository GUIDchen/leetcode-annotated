// 题目：788. 旋转数字（Rotated Digits）
// 思路：先用映射表 d 把每个数字旋转 180°；逐位旋转拼出新数 y，遇到 3/4/7 直接失败，最后要求 y != x。
// 时间复杂度：O(n log n)，每个数要处理它的每位数字；空间复杂度：O(1)，只用固定大小的表与常数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int rotatedDigits(int n) {  // 统计 [1, n] 中「每位旋转 180° 后仍合法、且新数与原数不同」的个数
        int d[10] = {0, 1, 5, -1, -1, 2, 9, -1, 8, 6};  // d[i] 是数字 i 旋转后的值，-1 表示旋转后不合法（3、4、7）
        auto check = [&](int x) -> bool {  // 判断 x 是否为好数的 lambda
            int y = 0, t = x;  // y 保存旋转结果，t 是待逐位剥离的剩余部分
            int k = 1;  // k 是当前位的位权，从个位的 1 开始
            while (t) {  // 从低位到高位逐位处理
                int v = t % 10;  // 取出最低位的数字
                if (d[v] == -1) {  // 该位旋转后不合法，整个数作废
                    return false;  // 直接判定不是好数
                }  // 分支结束
                y = d[v] * k + y;  // 把旋转后的数字按原位权累加进 y
                k *= 10;  // 位权升一档（1 → 10 → 100 …）
                t /= 10;  // 去掉已处理的最低位
            }  // 逐位循环结束
            return x != y;  // 旋转后必须与原数不同才算好数（否则只是自身对称，如 0、1、8）
        };  // lambda 定义结束
        int ans = 0;  // 好数计数
        for (int i = 1; i <= n; ++i) {  // 逐个检查 [1, n]
            ans += check(i);  // check 返回 bool，true 转成 1 累加，false 转成 0
        }  // 枚举循环结束
        return ans;  // 返回好数总数
    }  // 方法结束
};  // 题解类结束
