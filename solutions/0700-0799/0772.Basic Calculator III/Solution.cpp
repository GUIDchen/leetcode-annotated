// 题目：772. 基本计算器 III（Basic Calculator III）
// 核心思路：把字符串装进队列做全局游标，递归下降处理括号；每层用栈暂存加减结果，遇到乘除立刻与栈顶结合。
// 时间复杂度 O(n)（每个字符进出队列各一次）；空间复杂度 O(n)（字符队列 + 递归栈 + 运算栈）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对判题器可见
    int calculate(string s) {  // s：含 + - * / 与括号的表达式字符串，返回其整数值
        queue<char> q;  // 队列：把字符串变成能被任意深度的递归共享的字符流
        for (char c : s) {  // 逐个字符入队
            q.push(c);  // 入队当前字符
        }  // for 循环结束
        return dfs(q);  // 交给递归函数处理整个表达式
    }  // 方法结束

private:  // 私有辅助函数：递归时子表达式复用同一套逻辑
    int dfs(queue<char>& q) {  // q 是共享的字符队列，返回时游标已推进到匹配的右括号之后
        long long num = 0;  // num 用来累积当前正在读取的操作数
        char sign = '+';  // sign 记录上一个读到的运算符，初始为加号以处理表达式开头
        vector<long long> stk;  // 栈：加减法转成带符号的数入栈，乘除直接作用在栈顶
        while (!q.empty()) {  // 队列不空就继续处理当前层
            char c = q.front();  // 取出队首字符
            q.pop();  // 从队列移除，保证每个字符只被处理一次
            if (isdigit(c)) {  // 是数字字符，继续拼接多位数字
                num = num * 10 + (c - '0');  // 十进制累积：旧值乘 10 再加上新数位
            }  // if 结束
            if (c == '(') {  // 遇到左括号，开始一个子表达式
                num = dfs(q);  // 递归求出括号内的值，作为本轮的操作数
            }  // if 结束
            if (c == '+' || c == '-' || c == '*' || c == '/' || c == ')' || q.empty()) {  // 遇到运算符、右括号，或队列已空（表达式结尾也必须结算）
                if (sign == '+') {  // 上一个运算符是加号：当前数原样入栈
                    stk.push_back(num);  // 压入正数
                } else if (sign == '-') {  // 上一个运算符是减号：当前数取反入栈
                    stk.push_back(-num);  // 压入相反数，把减法统一成加法
                } else if (sign == '*') {  // 上一个运算符是乘号：立刻与栈顶相乘，体现乘除优先级
                    stk.back() *= num;  // 乘到栈顶
                } else {  // 剩下只可能是除号
                    stk.back() /= num;  // 除到栈顶（C++ 的整数除法向零截断，符合题目要求）
                }  // 分支结束
                num = 0;  // 当前操作数已结算，清零准备读取下一个数
                sign = c;  // 记住这个运算符，供下一个操作数使用
            }  // if 结束
            if (c == ')') {  // 遇到右括号，说明本层子表达式结束
                break;  // 跳出循环，把控制权交回上一层
            }  // if 结束
        }  // while 结束
        return accumulate(stk.begin(), stk.end(), 0LL);  // 栈中全是同号的加数，求和即为本层结果
    }  // dfs 结束
};  // 类定义结束
