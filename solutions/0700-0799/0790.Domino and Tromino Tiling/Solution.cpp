// 题目：790. 多米诺和托米诺平铺（Domino and Tromino Tiling）
// 思路：按右端面形状做状态压缩 DP，f[0..3] 分别是「齐平 / 上排多一格 / 下排多一格 / 需托米诺补齐的缺口」，每列按固定转移矩阵推进。
// 时间复杂度：O(n)，每列只做常数次转移；空间复杂度：O(1)，只用两个长度 4 的数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numTilings(int n) {  // 求 2×n 棋盘用多米诺与托米诺铺满的方案数（对 1e9+7 取模）
        const int mod = 1e9 + 7;  // 取模常量，防止方案数溢出
        long long f[4] = {1, 0, 0, 0};  // f 是当前列四种端面形状的方案数；初始只有「齐平」为 1（铺了 0 列）
        for (int i = 1; i <= n; ++i) {  // 逐列推进，i 从 1 到 n
            long long g[4];  // g 暂存推进一列后的新方案数
            g[0] = (f[0] + f[1] + f[2] + f[3]) % mod;  // 新的齐平状态：可由任一种端面形状补齐/收口得到
            g[1] = (f[2] + f[3]) % mod;  // 转为「上排多出一格」：只能由状态 2 或状态 3 沿阶梯接续得到
            g[2] = (f[1] + f[3]) % mod;  // 转为「下排多出一格」：与上式镜像对称
            g[3] = f[0];  // 只有完全齐平时，才可能横放一块托米诺造成一格悬挑
            memcpy(f, g, sizeof(g));  // 把 g 写回 f，作为下一列推导的输入
        }  // 列循环结束
        return f[0];  // 铺满 n 列且齐平的方案数就是答案
    }  // 方法结束
};  // 题解类结束