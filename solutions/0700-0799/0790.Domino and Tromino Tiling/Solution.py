# 题目：790. 多米诺和托米诺平铺（Domino and Tromino Tiling）
# 思路：按右端面形状做状态压缩 DP；f 的 4 个分量依次表示齐平、上排多一格、下排多一格、留缺口四种端面状态，逐列乘固定转移矩阵。
# 时间复杂度：O(n)，每列常数次转移；空间复杂度：O(1)，只保留两个长度 4 的数组。
class Solution:  # LeetCode 约定的题解类
    def numTilings(self, n: int) -> int:  # 求 2×n 棋盘用多米诺与托米诺铺满的方案数（对 1e9+7 取模）
        f = [1, 0, 0, 0]  # 四种端面状态的方案数；初始只有「齐平」为 1（还没铺任何列）
        mod = 10**9 + 7  # 取模常量
        for i in range(1, n + 1):  # 逐列推进
            g = [0] * 4  # g 暂存推进一列后的方案数
            g[0] = (f[0] + f[1] + f[2] + f[3]) % mod  # 新的齐平状态：可由任一种端面形状补齐收口
            g[1] = (f[2] + f[3]) % mod  # 转为「上排多出一格」：由状态 2 或状态 3 接续得到
            g[2] = (f[1] + f[3]) % mod  # 转为「下排多出一格」：与上式镜像对称
            g[3] = f[0]  # 只有完全齐平时才能横放托米诺造成一格悬挑
            f = g  # 用新状态替换旧状态，进入下一列
        return f[0]  # 铺满 n 列且齐平的方案数就是答案
