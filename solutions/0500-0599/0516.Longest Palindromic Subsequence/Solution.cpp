// 题目：516. 最长回文子序列（Longest Palindromic Subsequence）
// 思路：区间 DP。f[i][j] 表示子串 s[i..j] 的最长回文子序列长度；两端相等时由 f[i+1][j-1]+2 转移，否则取去掉某一端的较大值。
// 时间复杂度：O(n²)，每个区间算一次；空间复杂度：O(n²)，即 DP 表大小。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int longestPalindromeSubseq(string s) {  // 返回字符串 s 的最长回文子序列长度
        int n = s.size();  // 字符串长度
        int f[n][n];  // f[i][j]：子串 s[i..j] 的最长回文子序列长度
        memset(f, 0, sizeof(f));  // 先全部置 0，长度 1 的区间稍后单独赋值
        for (int i = 0; i < n; ++i) {  // 处理长度为 1 的所有区间
            f[i][i] = 1;  // 单个字符本身就是长度 1 的回文
        }  // 初始化完成
        for (int i = n - 1; ~i; --i) {  // 左端点从右往左，保证 f[i+1][...] 已经算好
            for (int j = i + 1; j < n; ++j) {  // 右端点从 i+1 往右，保证 f[...][j-1] 已经算好
                if (s[i] == s[j]) {  // 两端字符相同，可以同时并入回文
                    f[i][j] = f[i + 1][j - 1] + 2;  // 去掉两端后的最优长度再加 2
                } else {  // 两端字符不同，只能舍去其中一端
                    f[i][j] = max(f[i + 1][j], f[i][j - 1]);  // 两种舍弃方式取较大者
                }  // 分支结束
            }  // 枚举完右端点
        }  // 枚举完左端点
        return f[0][n - 1];  // 整个字符串区间的答案
    }  // 方法结束
};  // 类定义结束