// 题目：598. 区间加法 II（Range Addition II）
// 思路：所有操作都从 (0,0) 开始，因此被覆盖次数最多的格子就是所有操作的公共左上角矩形，边长只由最小的行范围与列范围决定。
// 时间复杂度：O(k)，k 为 ops 长度；空间复杂度：O(1)，只维护两个最小值。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxCount(int m, int n, vector<vector<int>>& ops) {  // m、n 是矩阵的行数与列数，ops 中每个二元组是一次「前若干行若干列加一」操作
        for (const auto& op : ops) {  // 遍历所有操作，逐步收缩公共矩形的范围
            m = min(m, op[0]);  // 每次操作只影响前 op[0] 行，取最小值才是被所有操作都覆盖的行数
            n = min(n, op[1]);  // 列方向同理，取所有操作列范围的最小值
        }  // 循环结束，m、n 已收缩为所有操作的公共范围
        return m * n;  // 公共矩形的格子数即被加次数最多的格子个数，直接相乘返回
    }  // 方法结束
};  // 类定义结束
