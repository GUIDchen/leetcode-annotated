# 题目：544. 输出比赛匹配对（Output Contest Matches）
# 思路：每一轮把首尾配对（第 i 个与第 n-1-i 个，最强的对最弱的），用括号包起来塞回前半段，再令 n 减半，重复到只剩一个字符串。
# 时间复杂度：O(n^2)，每轮拼出的字符串越来越长；空间复杂度：O(n^2)，用于存放所有中间字符串。
class Solution:  # LeetCode 约定的题解类
    def findContestMatch(self, n: int) -> str:  # n 是参赛队伍数（2 的幂），返回完整的比赛对阵字符串
        s = [str(i + 1) for i in range(n)]  # 第 i 个元素初始为队伍编号 i+1，作为「参赛者」
        while n > 1:  # 每轮把选手数减半；n<=1 时只剩一个完整的对阵字符串，退出循环
            for i in range(n >> 1):  # 处理本轮的前半段：第 i 个与倒数第 i 个配对
                s[i] = f"({s[i]},{s[n - i - 1]})"  # 首尾配对并用括号包起来，写回前半段的第 i 个位置（最强的对最弱的）
            n >>= 1  # 晋级下一轮，选手数减半
        return s[0]  # 全部合并后 s[0] 就是所求的完整对阵字符串
