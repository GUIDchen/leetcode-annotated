// 题目：556. 下一个更大元素 III（Next Greater Element III）
// 核心思路：把数字当成字符串，从右往左找第一个升位，与右侧稍大的数交换，再把后缀反转成最小升序。
// 时间复杂度：O(d)，d 为位数；空间复杂度：O(d)，用于存放位数序列。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int nextGreaterElement(int n) {  // n：正整数，返回由同样数字组成且比 n 大的最小整数，没有则返回 -1
        string s = to_string(n);  // 转成字符串，便于按位比较和交换
        n = s.size();  // 复用 n 记录位数，省去额外变量
        int i = n - 2, j = n - 1;  // i 从倒数第二位开始，j 从最后一位开始，用于找升位与交换对象
        for (; i >= 0 && s[i] >= s[i + 1]; --i)  // 从右往左找第一个满足 s[i] < s[i+1] 的位置，即需要被换大的那一位
            ;  // 循环体为空：全部逻辑都在循环头部的判断与自减里完成
        if (i < 0) return -1;  // i < 0 说明整个序列非递增，不存在更大的排列，按题意返回 -1
        for (; s[i] >= s[j]; --j)  // 从右往左找第一个大于 s[i] 的数字作为交换对象（它离末位最近，换完增量最小）
            ;  // 循环体为空：条件判断与自减都写在循环头部
        swap(s[i], s[j]);  // 交换 s[i] 与 s[j]，让这一位增大到刚好超过原来的值
        reverse(s.begin() + i + 1, s.end());  // 把 i 之后的后缀反转成升序，使整体成为「最小的大于原值」的排列
        long ans = stol(s);  // 转回整数；用 long 暂存，避免中间结果溢出 int
        return ans > INT_MAX ? -1 : ans;  // 超过 int 上限说明不存在合法的 32 位答案，返回 -1
    }  // 方法结束
};  // 类定义结束