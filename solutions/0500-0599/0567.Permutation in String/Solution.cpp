// 题目：567. 字符串的排列（Permutation in String）
// 思路：滑动窗口加计数欠账：cnt 记录窗口内各字符相对 s1 的差值，need 记录还有多少种字符没对齐；窗口长度保持 |s1|，need 归零即找到一个排列。
// 时间复杂度：O(|s2|)，窗口线性滑动；空间复杂度：O(1)，只用到 26 个计数。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool checkInclusion(string s1, string s2) {  // s1 是模式串，判断 s2 中是否存在它的某个排列作为连续子串
        int need = 0;  // need：还有多少种字符的计数尚未与 s1 对齐
        int cnt[26]{};  // 26 个字母的计数器，{} 保证全部初始化为 0
        for (char c : s1) {  // 先统计 s1 中各字符需要的次数
            if (++cnt[c - 'a'] == 1) {  // 某字符计数从 0 变 1，说明这是一种新需要的字符
                ++need;  // 需要的字符种类数加一
            }  // 统计结束
        }  // m 是窗口长度（等于 |s1|），n 是 s2 的长度
        int m = s1.size(), n = s2.size();  // 右端点 i 从 0 滑到 n-1
        for (int i = 0; i < n; ++i) {  // 当前右端字符对应的字母编号
            int c = s2[i] - 'a';  // 窗口新增一个该字符：计数减 1，向目标靠拢
            if (--cnt[c] == 0) {  // 减到 0 说明这种字符刚好对齐
                --need;  // 需要对齐的种类数减一
            }  // 窗口长度超过 m 时，必须把最左侧字符移出窗口
            if (i >= m) {  // 被移出字符的字母编号
                c = s2[i - m] - 'a';  // 移出后计数加 1，重新偏离目标
                if (++cnt[c] == 1) {  // 从 0 变 1 说明这种字符重新变成欠账
                    ++need;  // 欠账种类数加一
                }  // 窗口维持好后，检查是否所有字符都已对齐
            }  // need 为 0 说明窗口内计数与 s1 完全一致，即找到一个排列
            if (need == 0) {  // 判断结束
                return true;  // 循环结束
            }  // 遍历完 s2 仍未找到
        }  // 方法结束
        return false;
    }
};
