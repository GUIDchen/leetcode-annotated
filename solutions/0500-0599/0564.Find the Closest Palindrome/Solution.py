# 题目：564. 寻找最近的回文数（Find the Closest Palindrome）
# 思路：候选回文来自「前半部分 -1/不变/+1 后镜像」以及 999…9、100…001 两类边界值；放入集合、剔除原数后按（距离, 数值）取最优。
# 时间复杂度：O(L)，L 为位数（候选只有常数个）；空间复杂度：O(L)，用于字符串与候选集合。
class Solution:  # LeetCode 约定的题解类
    def nearestPalindromic(self, n: str) -> str:  # n 是十进制字符串，返回与它差值最小的不同回文数
        x = int(n)  # 原数转整数，便于计算距离
        l = len(n)  # l 是原数的位数
        res = {10 ** (l - 1) - 1, 10**l + 1}  # 候选集合：先放入两类边界值——少一位的全 9 数与多一位的 100…001，set 自动去重
        left = int(n[: (l + 1) >> 1])  # 取前半部分（(l+1)>>1 位，奇数长度时包含中间位）
        for i in range(left - 1, left + 2):  # 枚举前半部分 -1、不变、+1 三种取值
            j = i if l % 2 == 0 else i // 10  # 偶数长度整段镜像；奇数长度先去掉中间位再镜像
            while j:  # 只要前半部分还有没镜像的位就继续
                i = i * 10 + j % 10  # 把前半部分的最低位接到当前回文末尾
                j //= 10  # 去掉已经使用的最低位
            res.add(i)  # 镜像完成，加入候选集合
        res.discard(x)  # 剔除原数本身，题目要求返回不同的回文数

        ans = -1  # -1 表示还没有选出答案
        for t in res:  # 遍历所有候选回文
            if (  # 判断是否更优：首轮直接接受 / 距离更小 / 距离相同但数值更小
                ans == -1  # 还没有答案时无条件接受
                or abs(t - x) < abs(ans - x)  # 距离更近则替换
                or (abs(t - x) == abs(ans - x) and t < ans)  # 距离相等时取数值更小的那个
            ):  # 条件判断结束
                ans = t  # 记录当前最优候选
        return str(ans)  # 转成字符串返回
