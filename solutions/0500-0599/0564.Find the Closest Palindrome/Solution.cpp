// 题目：564. 寻找最近的回文数（Find the Closest Palindrome）
// 思路：候选回文只可能来自「前半部分 -1/不变/+1 后镜像」以及 999…9、100…001 两类边界值；把这些候选放入集合，剔除原数后取距离最近、数值更小者。
// 时间复杂度：O(L)，L 为位数（候选只有常数个）；空间复杂度：O(L)，用于字符串与候选集合。
using i128 = __int128_t;  // 128 位整数别名：位数最多 18 位，中间值 ±1 可能超出 64 位范围

class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string nearestPalindromic(string n) {  // n 是十进制字符串表示的正整数，返回与它差值最小的不同回文数
        i128 x = parse(n);  // 把原数字符串解析成 128 位整数，方便做差与比较
        int l = n.size();  // l 是原数的位数
        set<i128> res;  // res 存候选回文，set 自动去重并按数值升序排列
        res.insert(pow10(l - 1) - 1);  // 边界候选一：比原数少一位的全 9 数（如 999…9）
        res.insert(pow10(l) + 1);  // 边界候选二：比原数多一位、首尾为 1 的回文（100…001）
        i128 left = parse(n.substr(0, (l + 1) / 2));  // 取前半部分（(l+1)/2 位，奇数时包含中间位）
        for (int d = -1; d <= 1; ++d) {  // 枚举前半部分 -1、不变、+1 三种情况
            i128 i = left + d;  // i 是本次尝试使用的前半部分数值
            i128 j = l % 2 == 0 ? i : i / 10;  // 偶数长度整段镜像；奇数长度要跳过中间位，避免重复
            while (j) {  // 把前半部分从低位到高位依次追加，构造回文
                i = i * 10 + j % 10;  // 取出 i 的最低位接到当前回文末尾
                j /= 10;  // 去掉已经使用的这一位
            }  // 循环结束时 i 就是镜像完成后的回文数
            res.insert(i);  // 加入候选集合
        }  // 三种镜像候选枚举结束
        res.erase(x);  // 剔除原数本身，题目要求返回最近的不同回文数
        i128 ans = -1;  // ans = -1 表示还没有选出答案
        for (i128 t : res) {  // 按升序检查每个候选
            i128 dt = iabs(t - x);  // 候选与原数的距离
            i128 da = iabs(ans - x);  // 当前最优解与原数的距离（ans 为 -1 时该值不会被采用）
            if (ans == -1 || dt < da || (dt == da && t < ans)) {  // 更近，或距离相同但数值更小，则更新答案
                ans = t;  // 记录更优的候选
            }  // 比较判断结束
        }  // 候选遍历结束
        return toStr(ans);  // 把选出的回文数转回字符串
    }  // 方法结束

private:  // 以下为私有辅助函数
    i128 parse(const string& s) {  // 把十进制字符串转成 128 位整数
        i128 x = 0;  // 累加器从 0 开始
        for (char c : s) {  // 逐位处理字符串
            x = x * 10 + (c - '0');  // 每读一位，把已有结果左移一位十进制并加上新数字
        }  // 字符循环结束
        return x;  // 返回解析结果
    }

    i128 pow10(int k) {  // 返回 10 的 k 次方，用 128 位整数避免溢出
        i128 x = 1;  // 从 1 开始累乘
        while (k--) {  // 循环 k 次
            x *= 10;  // 每次乘 10
        }  // 循环结束
        return x;  // 返回 10^k
    }

    i128 iabs(i128 x) {  // 128 位整数的绝对值
        return x < 0 ? -x : x;  // 负数取反，非负原样返回
    }

    string toStr(i128 x) {  // 把 128 位整数转成十进制字符串
        if (x == 0) {  // 0 需要单独处理，否则下面的 while 一次都不会执行
            return "0";  // 直接返回字符串 0
        }  // 非 0 数值继续转换
        string s;  // 结果先按低位到高位逆序拼接
        while (x) {  // 逐位取出，直到数值为 0
            s.push_back(char('0' + x % 10));  // 把最低位转成字符追加（此时是逆序）
            x /= 10;  // 去掉最低位
        }  // 取位循环结束
        reverse(s.begin(), s.end());  // 反转成正常的十进制顺序
        return s;  // 返回转换后的字符串
    }
};
