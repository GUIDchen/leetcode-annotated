// 题目：503. 下一个更大元素 II（Next Greater Element II）
// 思路：把数组复制一份接到末尾形成长度 2n 的环，从右往左扫描；单调递减栈的栈顶即右侧第一个更大的元素。
// 时间复杂度：O(n)，每个元素最多入栈出栈各一次；空间复杂度：O(n)，答案数组与栈。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> nextGreaterElements(vector<int>& nums) {  // nums：环形数组；返回每个位置的下一个更大元素（不存在则为 -1）
        int n = nums.size();  // 数组长度 n，后面用它把扩展下标折回原数组
        vector<int> ans(n, -1);  // 答案数组先全部填 -1，表示暂时没找到更大的元素
        stack<int> stk;  // 单调栈：从栈底到栈顶单调递减，保存还没匹配到答案的元素值
        for (int i = n * 2 - 1; ~i; --i) {  // 从 2n-1 倒着遍历到 0，相当于把数组复制一份后再从右往左扫
            int j = i % n;  // 扩展下标 i 折回原数组，得到真实位置 j
            while (stk.size() && stk.top() <= nums[j]) {  // 栈顶不大于当前元素，它不可能成为当前元素右边第一个更大元素
                stk.pop();  // 弹出这些更小或相等的元素，维持栈的单调性
            }  // 循环结束时，栈顶（若存在）就是 nums[j] 右侧第一个更大元素
            if (stk.size()) {  // 栈非空说明右侧确实存在更大的元素
                ans[j] = stk.top();  // 记录答案：栈顶即下一个更大元素
            }  // 栈为空说明右侧没有更大值，ans[j] 保持 -1
            stk.push(nums[j]);  // 当前元素入栈，继续为更左边的元素提供候选
        }  // 整轮扫描结束，所有位置都已得到答案
        return ans;  // 返回结果数组
    }  // 方法结束
};  // 类定义结束