// 题目：552. 学生出勤记录 II（Student Attendance Record II）
// 思路：状态压缩 DP，f[j][k] 表示「已经放了 j 个 A、末尾已有 k 个连续 L」时后续还能补出多少种合法记录；每轮往末尾补一位（P/A/L）并把三种转移相加，滚动 n 轮后 f[0][0] 即答案。
// 时间复杂度：O(n)，每轮只有 2×3 个状态、常数条转移；空间复杂度：O(1)，只用了两张 2×3 的表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int checkRecord(int n) {  // n 是记录长度，返回长度为 n 的可奖励记录数（对 1e9+7 取模）
        const int mod = 1e9 + 7;  // 题目要求的取模常量
        int f[2][3] = {{1, 1, 1}, {1, 1, 1}};  // f[j][k]：已出现 j 个 A、末尾已有 k 个连续 L 时，后面还能补出多少种合法记录（空后缀算 1 种，所以初值全为 1）
        for (int i = 0; i < n; ++i) {  // 每轮相当于在末尾再补一位字符，一共补 n 位
            int g[2][3]{};  // 下一轮的状态表，{} 保证全部初始化为 0
            for (int j = 0; j < 2; ++j) {  // 枚举当前已出现的 A 的个数（出现 2 个就不合法，所以只有 0 和 1）
                for (int k = 0; k < 3; ++k) {  // 枚举末尾连续 L 的个数（连续 3 个就不合法，所以只有 0、1、2）
                    int ans = f[j][0];  // 下一位填 P：末尾连续 L 归零，接上 f[j][0]
                    if (j == 0) {  // 还没出现过 A 时，下一位才可以填 A
                        ans = (ans + f[1][0]) % mod;  // 填 A 后状态变成 (1, 0)，累计上 f[1][0]
                    }  // 结束「填 A」的判断
                    if (k < 2) {  // 末尾连续 L 少于 2 个时，下一位才可以填 L
                        ans = (ans + f[j][k + 1]) % mod;  // 填 L 后连续长度变成 k+1，累计上 f[j][k+1]
                    }  // 结束「填 L」的判断
                    g[j][k] = ans % mod;  // 三种字符的贡献相加并取模，写入新状态表
                }  // 结束 k 的循环
            }  // 结束 j 的循环
            for (int j = 0; j < 2; ++j) {  // 把下一轮状态回写成当前状态
                for (int k = 0; k < 3; ++k) {  // 逐个状态拷贝
                    f[j][k] = g[j][k];  // 滚动数组更新
                }  // 结束 k 的循环
            }  // 结束 j 的循环
        }  // 结束长度为 n 的迭代
        return f[0][0];  // 从「0 个 A、末尾 0 个 L」出发，长度 n 的合法记录数就是答案
    }  // 结束 checkRecord
};  // 类定义结束
