// 题目：1963. 使字符串平衡的最小交换次数（Minimum Number of Swaps to Make the String Balanced）
// 思路：扫描时用 x 记录未匹配的 '[' 个数，配不上的 ']' 记为前缀亏欠；最终剩余 x 个多余左括号，每次交换修复两处，故答案为 ceil(x/2)。
// 时间复杂度：O(n)，只需一次扫描；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minSwaps(string s) {  // s 是只含 '[' 和 ']' 且两者数量相等的括号串
        int x = 0;  // x 记录当前未被匹配的 '[' 个数，也就是前缀亏欠的对数
        for (char& c : s) {  // 逐个字符扫描，char& 避免拷贝
            if (c == '[') {  // 遇到左括号
                ++x;  // 未匹配的左括号加一
            } else if (x) {  // 遇到右括号，且当前确实有可配对的左括号
                --x;  // 与一个左括号配对，抵消一个；x 为 0 时的 ']' 属于前缀亏欠，交换时会被修掉，故忽略
            }  // 结束分支
        }  // 结束 for
        return (x + 1) / 2;  // 剩 x 个多余左括号，一次交换修复两处，(x+1)/2 即向上取整
    }  // 结束方法
};  // 结束类