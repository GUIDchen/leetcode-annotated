# 题目：1963. 使字符串平衡的最小交换次数（Minimum Number of Swaps to Make the String Balanced）
# 思路：扫描时用 x 记录未匹配的 '[' 个数，配不上的 ']' 直接忽略；最终剩余 x 个多余左括号，每次交换修复两处，答案为 ceil(x/2)。
# 时间复杂度：O(n)，一次扫描；空间复杂度：O(1)，只用常数个变量。
class Solution:  # LeetCode 约定的题解类
    def minSwaps(self, s: str) -> int:  # s 是只含 '[' 和 ']' 且两者数量相等的括号串
        x = 0  # x 记录当前未被匹配的 '[' 个数，也就是前缀亏欠对数
        for c in s:  # 逐个字符扫描
            if c == "[":  # 遇到左括号
                x += 1  # 未匹配的左括号加一
            elif x:  # 遇到右括号且当前有可配对的左括号
                x -= 1  # 抵消一个左括号；x 为 0 时的 ']' 是前缀亏欠，交换时会被修掉，故忽略
        return (x + 1) >> 1  # 右移一位等价于 (x+1)/2，即 ceil(x/2)：每次交换修复两处亏欠
