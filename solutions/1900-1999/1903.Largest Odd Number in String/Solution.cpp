// 题目：1903. 字符串中的最大奇数（Largest Odd Number in String）
// 思路：数字是否为奇数只取决于末位，因此从右往左找第一个奇数数字，以它为结尾的前缀就是最大的奇数。
// 时间复杂度：O(n)，最坏扫描整个字符串；空间复杂度：O(1)，除返回值外只用常数空间。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string largestOddNumber(string num) {  // num：只含数字字符的字符串
        for (int i = num.size() - 1; i >= 0; --i) {  // 从右往左找第一个奇数数字，越靠右保留的位数越多、数值越大
            int c = num[i] - '0';  // 把数字字符转换成对应的整数值
            if ((c & 1) == 1) {  // 末位是奇数，则以它结尾的整个前缀就是奇数
                return num.substr(0, i + 1);  // 从开头到 i 的前缀比更短的都大，直接返回
            }  // 结束 if 分支
        }  // 结束 for 循环
        return "";  // 没有奇数数字，按题目要求返回空串
    }  // 结束题解方法
};  // 结束题解类