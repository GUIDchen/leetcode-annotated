// 题目：1927. 求和游戏（Sum Game）
// 思路：分别统计左右半边的数字和与问号数；问号总数是奇数则先手必胜，偶数时需满足 s1-s2 == 9*(cnt2-cnt1)/2 才轮到后手取胜。
// 时间复杂度：O(n)，只扫描一遍字符串；空间复杂度：O(1)，仅使用四个计数器。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool sumGame(string num) {  // num：由数字和 '?' 组成的字符串，长度保证为偶数
        int n = num.size();  // 字符串总长度
        int cnt1 = 0, cnt2 = 0;  // cnt1：左半边问号数；cnt2：右半边问号数
        int s1 = 0, s2 = 0;  // s1：左半边数字之和；s2：右半边数字之和
        for (int i = 0; i < n / 2; ++i) {  // 遍历左半部分
            if (num[i] == '?') {  // 遇到问号
                cnt1++;  // 左半边问号计数加一
            } else {  // 否则是数字字符
                s1 += num[i] - '0';  // 字符转数字后累加到左边数字和
            }
        }
        for (int i = n / 2; i < n; ++i) {  // 遍历右半部分
            if (num[i] == '?') {  // 遇到问号
                cnt2++;  // 右半边问号计数加一
            } else {  // 否则是数字字符
                s2 += num[i] - '0';  // 字符转数字后累加到右边数字和
            }
        }
        return (cnt1 + cnt2) % 2 == 1 || (s1 - s2) != 9 * (cnt2 - cnt1) / 2;  // 问号总数奇数先手必赢；偶数时只有差值为 9*(cnt2-cnt1)/2 才判先手输
    }
};