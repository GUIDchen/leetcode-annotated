// 题目：1987. 不同的好子序列数目（Number of Unique Good Subsequences）
// 思路：按结尾字符去重计数：f 统计以 '1' 结尾的不同好子序列，g 统计以 '0' 结尾的，单独的 "0" 再另记一次。
// 时间复杂度：O(n)，一趟扫描；空间复杂度：O(1)，只用了常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberOfUniqueGoodSubsequences(string binary) {  // binary：只含 '0' 和 '1' 的字符串
        const int mod = 1e9 + 7;  // 答案要对 1e9+7 取模
        int f = 0, g = 0;  // f：以 '1' 结尾的不同好子序列数；g：以 '0' 结尾的（暂不含单独的 "0"）
        int ans = 0;  // ans 先当标记用：只要出现过 '0'，单独的 "0" 就也是一个好子序列
        for (char& c : binary) {  // 从左到右逐个字符处理
            if (c == '0') {  // 当前字符是 '0'
                g = (g + f) % mod;  // 把 '0' 接到每个以 '1' 结尾的子序列后面，得到新的以 '0' 结尾的子序列
                ans = 1;  // 单独一个 "0" 也是好子序列，单独记一次
            } else {  // 当前字符是 '1'
                f = (f + g + 1) % mod;  // 把 '1' 接到所有已有子序列后面，再加上单独起始的 "1"
            }  // 分支结束
        }  // 扫描结束
        ans = (ans + f + g) % mod;  // 汇总：单独的 "0" + 以 '1' 结尾 + 以 '0' 结尾的数目
        return ans;  // 返回不同好子序列总数
    }  // 方法结束
};  // 类定义结束