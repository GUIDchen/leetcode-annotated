// 题目：1992. 找到所有的农场组（Find All Groups of Farmland）
// 思路：每个农场组都是互不重叠的矩形，只有「左上角」格子值得当起点（它左侧与上方都不是农田）；从左上角沿列向下、再沿行向右各推到底，就得到右下角。
// 时间复杂度：O(m*n)，每个格子最多被检查常数次；空间复杂度：O(1)（不计返回结果）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<vector<int>> findFarmland(vector<vector<int>>& land) {  // land：0/1 矩阵，1 表示农田；返回每组农场地的 [左上x, 左上y, 右下x, 右下y]
        vector<vector<int>> ans;  // 收集所有农场组的答案
        int m = land.size();  // 行数
        int n = land[0].size();  // 列数（题目保证至少有一列）
        for (int i = 0; i < m; ++i) {  // 枚举每一行，寻找可能的左上角行
            for (int j = 0; j < n; ++j) {  // 枚举每一列，寻找可能的左上角列
                if (land[i][j] == 0 || (j > 0 && land[i][j - 1] == 1) || (i > 0 && land[i - 1][j] == 1)) continue;  // 跳过非农田，以及左侧或上方已是农田的格子（它们只能是组的内部或右下角）
                int x = i;  // 记录当前组的左上角行
                int y = j;  // 记录当前组的左上角列
                for (; x + 1 < m && land[x + 1][j] == 1; ++x)  // 农场组是矩形，沿同一列一直向下延伸到不是 1 为止，得到最下面的行
                    ;  // 空循环体：推进由循环头里的 ++x 完成
                for (; y + 1 < n && land[x][y + 1] == 1; ++y)  // 沿最下面一行向右延伸到不是 1 为止，得到最右边的列
                    ;  // 空循环体：推进由循环头里的 ++y 完成
                ans.push_back({i, j, x, y});  // 左上角与右下角都已确定，按题目要求的顺序写入答案
            }  // 本行枚举结束
        }  // 全部行枚举结束
        return ans;  // 返回所有农场组
    }  // 方法结束
};  // 题解类结束