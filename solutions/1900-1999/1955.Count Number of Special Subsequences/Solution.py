# 题目：1955. 统计特殊子序列的数目（Count Number of Special Subsequences）
# 思路：用 f[i][j] 记录前 i+1 个元素中处于第 j 种形态（0 只含 0、1 形如 0…1…、2 形如 0…1…2…）的子序列个数，逐元素按当前值转移。
# 时间复杂度：O(n)，每个元素只做 O(1) 次转移；空间复杂度：O(n)，需要保存 n×3 的状态表。
class Solution:  # LeetCode 约定的题解类
    def countSpecialSubsequences(self, nums: List[int]) -> int:  # nums 只含 0/1/2，返回特殊子序列数目对 1e9+7 取模的结果
        mod = 10**9 + 7  # 取模常量，防止计数溢出（Python 大整数虽不溢出，但题目要求取模）
        n = len(nums)  # 数组长度，用作循环上界
        f = [[0] * 3 for _ in range(n)]  # 建 n×3 的状态表：f[i][j] 表示前 i+1 个元素中第 j 种形态的子序列数
        f[0][0] = nums[0] == 0  # 只有一个元素时，仅当它等于 0 才能构成「0…」子序列
        for i in range(1, n):  # 从第二个元素开始逐个递推
            if nums[i] == 0:  # 当前元素为 0：可另起新的 0…，也可接在已有 0… 之后
                f[i][0] = (2 * f[i - 1][0] + 1) % mod  # 2*f 表示「接 / 不接」，+1 表示只选当前这个 0 作为新起点
                f[i][1] = f[i - 1][1]  # 0 不能延长 0…1…，状态沿用
                f[i][2] = f[i - 1][2]  # 0 也不影响 0…1…2… 的计数
            elif nums[i] == 1:  # 当前元素为 1：可从 0… 接过来，也可接在已有 0…1… 之后
                f[i][0] = f[i - 1][0]  # 1 不能开启 0…，沿用上一行
                f[i][1] = (f[i - 1][0] + 2 * f[i - 1][1]) % mod  # 新开一段 0…1 或延长已有 0…1…，两种来源相加
                f[i][2] = f[i - 1][2]  # 1 不影响 0…1…2… 的计数
            else:  # 当前元素为 2：可从 0…1… 接过来，也可接在已有 0…1…2… 之后
                f[i][0] = f[i - 1][0]  # 2 不能开启 0…，沿用
                f[i][1] = f[i - 1][1]  # 2 不能产生 0…1…，沿用
                f[i][2] = (f[i - 1][1] + 2 * f[i - 1][2]) % mod  # 从 0…1… 接上当前 2，或延长已有 0…1…2…，两者相加
        return f[n - 1][2]  # 答案为前 n 个元素中形如 0…1…2… 的子序列数
