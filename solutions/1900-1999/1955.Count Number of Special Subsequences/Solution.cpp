// 题目：1955. 统计特殊子序列的数目（Count Number of Special Subsequences）
// 思路：特殊子序列形如 0…1…2…，用 f[i][j] 记录前 i+1 个元素中处于第 j 种形态（j=0 只含 0，j=1 形如 0…1…，j=2 形如 0…1…2…）的子序列个数，逐元素转移。
// 时间复杂度：O(n)，每个元素只做常数次转移；空间复杂度：O(n)，需要保存 n×3 的状态表（源文件用变长数组）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countSpecialSubsequences(vector<int>& nums) {  // nums 是只含 0/1/2 的数组；返回特殊子序列个数对 1e9+7 取模的结果
        const int mod = 1e9 + 7;  // 取模常量，避免计数过程中溢出
        int n = nums.size();  // 数组长度，后面循环上界反复使用
        // 变长数组（判题环境为 gnu++20，支持 VLA）：f[i][j] 表示前 i+1 个元素里第 j 种形态的子序列数
        // j=0：只由 0 组成；j=1：形如 0…1…；j=2：形如 0…1…2…
        int f[n][3];
        memset(f, 0, sizeof(f));  // 把所有状态先清零，未填的位置保持 0 表示不可达
        f[0][0] = nums[0] == 0;  // 只有一个元素时，只有它等于 0 才能构成「0…」形态的子序列
        for (int i = 1; i < n; ++i) {  // 从第二个元素开始逐个递推
            if (nums[i] == 0) {  // 当前元素为 0：可以另起一个新的 0…，也可以接在已有 0… 后面
                f[i][0] = (2 * f[i - 1][0] % mod + 1) % mod;  // 2*f 表示「接上 / 不接」两种选择，+1 表示单独选当前这个 0 作为新起点
                f[i][1] = f[i - 1][1];  // 0 无法延长 0…1…，直接沿用上一行状态
                f[i][2] = f[i - 1][2];  // 0 也不会影响 0…1…2… 的计数
            } else if (nums[i] == 1) {  // 当前元素为 1：可以从 0… 接过来，也可以接在已有 0…1… 后面
                f[i][0] = f[i - 1][0];  // 1 不能开启 0…，所以这一维沿用上一行
                f[i][1] = (f[i - 1][0] + 2 * f[i - 1][1] % mod) % mod;  // 新开一段 0…1 或延长已有 0…1…，两种来源相加
                f[i][2] = f[i - 1][2];  // 1 不影响 0…1…2… 的计数
            } else {  // 当前元素为 2：可以从 0…1… 接过来，也可以接在已有 0…1…2… 后面
                f[i][0] = f[i - 1][0];  // 2 不能开启 0…，状态沿用
                f[i][1] = f[i - 1][1];  // 2 不能产生 0…1…，状态沿用
                f[i][2] = (f[i - 1][1] + 2 * f[i - 1][2] % mod) % mod;  // 从 0…1… 接上当前 2，或延长已有 0…1…2…，两者相加
            }
        }
        return f[n - 1][2];  // 答案就是前 n 个元素中形如 0…1…2… 的子序列个数
    }
};