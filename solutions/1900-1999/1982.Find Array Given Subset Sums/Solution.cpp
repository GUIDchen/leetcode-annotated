// 题目：1982. 从子集的和还原数组（Find Array Given Subset Sums）
// 思路：把所有子集和整体平移，使空集对应 0；每轮取剩余最小值当新元素，并删掉「含刚确定元素」的那一半子集和；最后把子集和等于平移量的那些元素取相反数。
// 时间复杂度：O(n·2^n)（枚举子集求和，另含 multiset 的对数代价）；空间复杂度：O(2^n)，用 multiset 保存全部子集和。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> recoverArray(int n, vector<int>& sums) {  // n：原数组长度；sums：全部 2^n 个子集的和（含空集的 0）
        int m = *min_element(sums.begin(), sums.end());  // 取所有子集和中的最小值，它对应「把负数全部选上」的那个子集
        m = -m;  // 取反得到平移量：把最小子集和搬到 0，也就是让空集的和变成 0
        multiset<int> st;  // 有序可重集合：既能反复取最小值，也能按值删除一份
        for (int x : sums) {  // 逐个遍历原始子集和
            st.insert(x + m);  // 加上平移量后，空集对应的和正好变成最小值 0
        }  // 循环结束，st 中是平移后的全部子集和
        st.erase(st.begin());  // 删掉 0（空集），剩下的最小非零和就是原数组中绝对值最小的元素
        vector<int> ans;  // 存放还原出来的数组元素
        ans.push_back(*st.begin());  // 最小非零子集和 = 最小的那个元素，先确定它
        for (int i = 1; i < n; ++i) {  // 依次确定第 2 个到第 n 个元素
            for (int j = 0; j < 1 << i; ++j) {  // 枚举前 i 个已确定元素的 2^i 个子集掩码
                if (j >> (i - 1) & 1) {  // 只处理最高位（第 i-1 位）为 1 的掩码，即子集包含刚确定的元素 ans[i-1]
                    int s = 0;  // 该掩码对应的子集和
                    for (int k = 0; k < i; ++k) {  // 逐位检查掩码的第 k 位
                        if (j >> k & 1) {  // 第 k 位为 1，说明该子集包含 ans[k]
                            s += ans[k];  // 把该元素累加进子集和
                        }  // 分支结束
                    }  // 扫描结束，s 就是掩码 j 对应的和
                    st.erase(st.find(s));  // 从 st 里删掉这一份：后面未确定的元素会让同一个和成对出现，这里只保留另一半
                }  // 掩码处理结束
            }  // 本轮子集枚举结束
            ans.push_back(*st.begin());  // 删掉一半后，st 的最小值就是下一个待确定的元素
        }  // 全部元素确定完毕
        for (int i = 0; i < 1 << n; ++i) {  // 枚举原数组的所有子集，找出和正好等于平移量 m 的那个
            int s = 0;  // 当前子集的元素和
            for (int j = 0; j < n; ++j) {  // 逐位扫描
                if (i >> j & 1) {  // 第 j 位为 1，说明该子集包含 ans[j]
                    s += ans[j];  // 累加进子集和
                }  // 分支结束
            }  // 本子集求和结束
            if (s == m) {  // 平移前该子集的和为 0，说明它在真正的原数组中应当取负
                for (int j = 0; j < n; ++j) {  // 逐位处理该子集
                    if (i >> j & 1) {  // 位为 1 才需要取负
                        ans[j] = -ans[j];  // 翻转符号，恢复成原始数组
                    }  // 分支结束
                }  // 取负结束
                break;  // 已找到正确的符号分配，题目保证解唯一，直接跳出
            }  // 分支结束
        }  // 枚举结束
        return ans;  // 返回还原出的原数组
    }  // 方法结束
};  // 类定义结束