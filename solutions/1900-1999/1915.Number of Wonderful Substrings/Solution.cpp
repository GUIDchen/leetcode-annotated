// 题目：1915. 最美子字符串的数目（Number of Wonderful Substrings）
// 思路：前缀奇偶性状态压缩。用 10 位掩码记录每个字母出现次数的奇偶性，哈希表 cnt 统计各掩码作为前缀出现的次数；相同掩码配对得偶数次子串，只差一比特配对得恰一个字母奇数次。
// 时间复杂度：O(10n)，每个字符枚举 10 种掩码；空间复杂度：O(2^10) = O(1)，固定 1024 个计数。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long wonderfulSubstrings(string word) {  // word 只含 'a'~'j' 十个字母，返回其中“最美子字符串”的个数
        int cnt[1024] = {1};  // cnt[mask] 记录前缀掩码 mask 的出现次数；{1} 让 cnt[0] 初值为 1，代表空前缀，其余自动为 0
        long long ans = 0;  // 答案累加器，子串总数可达 O(n^2)，必须用 64 位整数
        int st = 0;  // st 是当前前缀的奇偶性掩码：第 i 位为 1 表示字母 i 出现了奇数次
        for (char c : word) {  // 从左到右逐个字符扩展前缀
            st ^= 1 << (c - 'a');  // 翻转当前字符对应的位：出现次数 +1 会让该字母的奇偶性取反
            ans += cnt[st];  // 之前出现过相同掩码的前缀 ⇒ 两前缀之间的子串里所有字母都是偶数次，直接计入答案
            for (int i = 0; i < 10; ++i) {  // 枚举“允许恰有一个字母出现奇数次”的十种情况
                ans += cnt[st ^ (1 << i)];  // 若旧前缀掩码与 st 只差第 i 位，则中间子串只有字母 i 为奇数次，也属于最美子串
            }  // 结束十种情况的枚举
            ++cnt[st];  // 把当前前缀掩码计入哈希表，供后面的前缀与它配对
        }  // 结束字符遍历
        return ans;  // 返回最美子字符串总数
    }  // 方法结束
};  // 类定义结束