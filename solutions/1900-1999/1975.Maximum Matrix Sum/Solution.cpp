// 题目：1975. 最大方阵和（Maximum Matrix Sum）
// 思路：翻转相邻两数的符号可成对消掉负号，故先取所有元素绝对值求和；负数个数为偶数即可全部翻正，为奇数则牺牲最小绝对值，减去其两倍。
// 时间复杂度：O(n^2)，需遍历方阵每个格子；空间复杂度：O(1)，只用常数个额外变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long maxMatrixSum(vector<vector<int>>& matrix) {  // matrix：输入的 n×n 整数方阵，返回可达到的最大方阵和
        long long s = 0;  // s：所有元素绝对值之和，即负号全被消掉时的理想最大和
        int mi = 1 << 30, cnt = 0;  // mi：记录绝对值最小的元素；cnt：统计负数个数
        for (const auto& row : matrix) {  // 逐行遍历方阵，外层先取到一整行 row
            for (int x : row) {  // 再逐个遍历当前行里的元素 x
                cnt += x < 0 ? 1 : 0;  // x < 0 为真时加 1，从而统计负数个数（布尔值可隐式转成 0/1）
                int y = abs(x);  // y：当前元素的绝对值，取绝对值相当于先把它翻成非负数
                mi = min(mi, y);  // 用更小的绝对值更新 mi，为可能「牺牲」一个元素做准备
                s += y;  // 把绝对值累加进总和
            }  // 当前行遍历结束
        }  // 所有行遍历结束
        return cnt % 2 == 0 ? s : s - mi * 2;  // 偶数个负数能两两抵消全部翻正；奇数个必须留下一个负号，代价是减掉两倍的最小绝对值
    }  // 方法结束
};  // 类定义结束
