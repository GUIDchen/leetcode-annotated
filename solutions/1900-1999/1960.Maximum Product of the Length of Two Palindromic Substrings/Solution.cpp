// 题目：1960. 两个回文子字符串长度的最大乘积（Maximum Product of the Length of Two Palindromic Substrings）
// 思路：Manacher 求出以每个位置为中心的最长奇回文半径 m[i]，再用两个队列分别在右→左、左→右扫描中维护「覆盖当前位置的最长回文」，得到前缀/后缀内最长回文长度，最后枚举分割点取乘积最大值。
// 时间复杂度：O(n)，Manacher 与两趟队列扫描都是线性的；空间复杂度：O(n)，保存半径 m 与后缀最优 r。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    long long maxProduct(string s) {  // s 为输入字符串，返回两个不重叠回文子串长度的最大乘积
        long long res = 0, l = 0, n = s.size();  // res 记录答案，l 记录前缀内最长回文长度，n 为串长
        vector<int> m(n), r(n);  // m[i]：以 i 为中心的最长奇回文半径（回文长 2*m[i]-1）；r[i]：完全落在后缀 [i,n-1] 内的最长回文长度

        for (int i = 0, l = 0, r = -1; i < n; ++i) {  // Manacher 第一趟：求每个中心的最长半径；此处 l、r 是当前最右回文的左/右边界，与外层同名变量互不影响
            int k = (i > r) ? 1 : min(m[l + r - i], r - i + 1);  // i 落在最右回文内部时可用对称点的半径加速，否则从 1 开始中心扩展
            while (0 <= i - k && i + k < n && s[i - k] == s[i + k])  // 中心扩展：左右两侧字符相等就继续扩大
                k++;  // 仍在界内且对称字符相同，半径加一
            m[i] = k--;  // 先记下最终半径 k，再自减得到回文右端相对中心的偏移
            if (i + k > r) {  // 新回文右端超出已知最右回文，说明可以更新边界
                l = i - k;  // 更新最右回文的左边界
                r = i + k;  // 更新最右回文的右边界
            }
        }

        queue<array<int, 2>> q, q1;  // q 按中心从大到小保存 (中心, 半径)，用于从右往左求后缀内的最长回文；q1 用于从左往右求前缀内的最长回文

        for (int i = n - 1; i >= 0; --i) {  // 从右往左扫描，r[i] 表示完全落在后缀 [i,n-1] 内的最长回文长度
            while (!q.empty() && q.front()[0] - q.front()[1] > i - 1)  // 队首回文的左端点已越过 i，它覆盖不到 i，对本轮及之后更小的 i 都无用
                q.pop();  // 弹出这个候选
            r[i] = 1 + (q.empty() ? 0 : (q.front()[0] - i) * 2);  // 覆盖 i 的最长回文：中心到 i 的距离往返，再加上中心字符本身
            q.push({i, m[i]});  // 把当前中心加入候选，供更靠左的 i 使用
        }

        for (int i = 0; i < n - 1; i++) {  // 从左往右扫描，l 随之更新为完全落在前缀 [0,i] 内的最长回文长度
            while (!q1.empty() && q1.front()[0] + q1.front()[1] < i + 1)  // 队首回文的右端点已在 i 之前，它覆盖不到 i，可以丢弃
                q1.pop();  // 弹出该候选
            l = max(l, 1ll + (q1.empty() ? 0 : (i - q1.front()[0]) * 2));  // 覆盖 i 的最长回文长度；取 max 后 l 单调递增，即前缀内最长回文
            res = max(res, l * r[i + 1]);  // 用前缀 [0,i] 与后缀 [i+1,n-1] 各自的最长回文相乘来更新答案
            q1.push({i, m[i]});  // 当前中心入队，供后续更大的 i 使用
        }

        return res;  // 返回最大乘积
    }
};
