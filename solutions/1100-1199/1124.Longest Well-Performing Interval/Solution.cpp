// 题目：1124. 表现良好的最长时间段（Longest Well-Performing Interval）
// 思路：把「工时大于 8 小时」记为 +1、其余记为 -1，问题转化为求「区间和为正」的最长连续子数组；用哈希表记录每个前缀和首次出现的最小下标，当前前缀和 s>0 时整段合法，否则用 s-1 的首次出现位置把区间拉到最长。
// 时间复杂度：O(n)，只需一次线性扫描；空间复杂度 O(n)，哈希表最多保存 n 个不同前缀和。
class Solution {  // LeetCode 约定的题解类
public:  // 接口对外可见
    int longestWPI(vector<int>& hours) {  // hours：每天工作时长；返回表现良好时间段的最长长度
        int ans = 0, s = 0;  // ans：当前最优答案；s：前缀和（>8 小时记 +1，否则记 -1）
        unordered_map<int, int> pos;  // pos：键为前缀和，值为它第一次出现的下标，越靠前越能拉长区间
        for (int i = 0; i < hours.size(); ++i) {  // 从左到右逐天扫描
            s += hours[i] > 8 ? 1 : -1;  // 更新前缀和：表现良好加 1，否则减 1
            if (s > 0) {  // 前缀和为正，说明从第 0 天到第 i 天整段都表现良好
                ans = i + 1;  // 整段长度就是当前答案
            } else if (pos.count(s - 1)) {  // 否则找更早出现的前缀和 s-1，区间 (pos[s-1], i] 之和恰为 1
                ans = max(ans, i - pos[s - 1]);  // 用这个更早的位置拉长区间，取长度更大者
            }  // if-else 分支结束
            if (!pos.count(s)) {  // 前缀和只在第一次出现时记录，保证位置最靠前
                pos[s] = i;  // 记录首次出现的下标
            }  // if 分支结束
        }  // for 循环结束
        return ans;  // 返回最长表现良好时间段的长度
    }  // 方法结束
};  // 类定义结束