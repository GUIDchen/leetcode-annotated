// 题目：1154. 一年中的第几天（Day of the Year）
// 思路：解析出年、月、日，按闰年规则确定二月天数，累加前面各月的天数再加上当月第几天 d。
// 时间复杂度：O(1)，月份最多循环 11 次；空间复杂度：O(1)，只用固定长度的天数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int dayOfYear(string date) {  // date 形如 YYYY-MM-DD
        int y, m, d;  // 年、月、日三个整数
        sscanf(date.c_str(), "%d-%d-%d", &y, &m, &d);  // 用 sscanf 按格式解析出年月日
        int v = y % 400 == 0 || (y % 4 == 0 && y % 100) ? 29 : 28;  // 闰年判定：能被 400 整除，或能被 4 整除但不能被 100 整除
        int days[] = {31, v, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};  // 平年各月天数，二月用 v 替换
        int ans = d;  // 先算上当月已经过的天数 d
        for (int i = 0; i < m - 1; ++i) {  // 累加前面 m-1 个整月的天数
            ans += days[i];  // 加上该月天数
        }  // 循环结束
        return ans;  // 返回这一天是一年中的第几天
    }  // 方法结束
};  // 类定义结束