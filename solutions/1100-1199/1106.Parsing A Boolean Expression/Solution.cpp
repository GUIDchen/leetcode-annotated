// 题目：1106. 解析布尔表达式（Parsing A Boolean Expression）
// 思路：用栈同时保存操作符与操作数；遇到右括号就连续弹出 't'/'f' 统计真假个数，再弹出操作符求值并压回栈中。
// 时间复杂度：O(n)，每个字符至多入栈、出栈各一次；空间复杂度：O(n)，栈最深可达表达式长度。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的解题接口
    bool parseBoolExpr(string expression) {  // expression 是题目保证合法的布尔表达式字符串
        stack<char> stk;  // 单栈混存操作符 '!' '&' '|' 与操作数 't' 'f'
        for (char c : expression) {  // 从左到右逐个字符扫描
            if (c != '(' && c != ')' && c != ',')  // 操作符和操作数都要入栈，括号与逗号只起分隔作用
                stk.push(c);  // 把有效字符压栈
            else if (c == ')') {  // 遇到右括号，说明一个子表达式已经扫描完，可以就地求值
                int t = 0, f = 0;  // 统计该子表达式内真值与假值的个数
                while (stk.top() == 't' || stk.top() == 'f') {  // 连续弹出所有布尔操作数，直到露出操作符
                    t += stk.top() == 't';  // 栈顶是真值则 t 加一（bool 参与算术运算会转成 0/1）
                    f += stk.top() == 'f';  // 栈顶是假值则 f 加一
                    stk.pop();  // 弹出已统计过的操作数
                }
                char op = stk.top();  // 操作数弹空后，栈顶即该子表达式的操作符
                stk.pop();  // 弹出操作符，腾出位置放结果
                if (op == '!') c = f ? 't' : 'f';  // 取反：只要出现假值结果就是真
                if (op == '&') c = f ? 'f' : 't';  // 与：只要出现假值结果就是假
                if (op == '|') c = t ? 't' : 'f';  // 或：只要出现真值结果就是真
                stk.push(c);  // 把子表达式的求值结果压回栈顶，供外层继续使用
            }
        }
        return stk.top() == 't';  // 整个表达式求值完毕，栈顶字符就是最终结果
    }
};