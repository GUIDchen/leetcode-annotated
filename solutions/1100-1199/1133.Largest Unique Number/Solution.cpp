// 题目：1133. 最大唯一数（Largest Unique Number）
// 思路：先用计数数组统计每个数出现的次数，再从最大值 1000 向下扫描，第一个出现次数恰好为 1 的数就是答案；若没有唯一数则返回 -1。
// 时间复杂度：O(n + V)，V 为数值上界 1000，可视为常数；空间复杂度 O(V)，计数数组大小固定。
class Solution {  // LeetCode 约定的题解类
public:  // 接口对外可见
    int largestUniqueNumber(vector<int>& nums) {  // nums：整数数组；返回只出现一次的最大值，没有则返回 -1
        int cnt[1001]{};  // cnt：值 → 出现次数，题目数值范围 0~1000，开 1001 足够
        for (int& x : nums) {  // 统计每个数的出现次数
            ++cnt[x];  // 出现一次使计数加一
        }  // 统计循环结束
        for (int x = 1000; ~x; --x) {  // 从最大值 1000 向下扫描，~x 等价于 x >= 0
            if (cnt[x] == 1) {  // 出现次数为 1 即为唯一数
                return x;  // 第一个满足条件的就是最大唯一数
            }  // if 分支结束
        }  // 扫描结束
        return -1;  // 没有唯一数，按题意返回 -1
    }  // 方法结束
};  // 类定义结束