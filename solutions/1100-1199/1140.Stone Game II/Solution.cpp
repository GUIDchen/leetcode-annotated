// 题目：1140. 石子游戏 II（Stone Game II）
// 思路：记忆化博弈搜索：dfs(i,m) 求从第 i 堆起、当前 M=m 时当前玩家能拿到的最大石子数，答案为剩余总和减去对手的最优结果。
// 时间复杂度：O(n^3)，状态 O(n^2) 个、每个状态枚举 O(n) 种 x；空间复杂度：O(n^2)，记忆化表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int stoneGameII(vector<int>& piles) {  // piles 是石子堆（只能从前向后取），返回先手能拿到的最多石子数
        int n = piles.size();  // 石子堆的数量
        int s[n + 1];  // 前缀和数组，s[i] 表示前 i 堆石子之和（变长数组，clang 扩展支持）
        s[0] = 0;  // 前缀和起点：前 0 堆为 0
        for (int i = 0; i < n; ++i) {  // 递推构造前缀和
            s[i + 1] = s[i] + piles[i];  // 前 i+1 堆之和 = 前 i 堆之和 + 第 i 堆
        }  // 前缀和构造结束
        int f[n][n + 1];  // 记忆化表 f[i][m]：从第 i 堆开始、当前 M=m 时当前玩家能拿到的最多石子数
        memset(f, 0, sizeof f);  // 初始化为 0，用 0 表示尚未计算（答案至少为 1，不会与 0 冲突）
        function<int(int, int)> dfs = [&](int i, int m) -> int {  // 记忆化深搜：i 为剩余区间的起点，m 为当前 M
            if (m * 2 >= n - i) {  // 如果一次能把剩下的全部拿走（2m 已覆盖剩余堆数），就直接全拿
                return s[n] - s[i];  // 剩余区间 [i, n) 的总和就是本轮的全部收获
            }  // 直接全拿的分支结束
            if (f[i][m]) {  // 之前算过这个状态就直接用缓存，保证每个状态只计算一次
                return f[i][m];  // 返回缓存中的最优值
            }  // 缓存分支结束
            int res = 0;  // 本轮至少要能拿 0 个
            for (int x = 1; x <= m << 1; ++x) {  // 本轮可取 1..2m 堆（m<<1 即 2m，移位优先级高于比较运算符）
                res = max(res, s[n] - s[i] - dfs(i + x, max(x, m)));  // 自己拿到的 = 剩余总和 - 对手从 i+x 起按新 M 的最优结果，对所有 x 取最大
            }  // x 枚举结束
            return f[i][m] = res;  // 写入记忆化表并返回结果
        };  // 深搜 lambda 定义结束
        return dfs(0, 1);  // 从第 0 堆开始、初始 M=1 出发求解
    }  // 方法结束
};  // 类定义结束