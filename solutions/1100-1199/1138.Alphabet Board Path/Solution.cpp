// 题目：1138. 字母板上的路径（Alphabet Board Path）
// 思路：字母序号整除/取余得到坐标，按固定顺序 L→U→R→D 逐字符移动到目标再点击 '!'；先左后上是为了避开右下角缺失的格子。
// 时间复杂度：O(总移动步数 + |target|)；空间复杂度：O(总移动步数)，即返回串本身。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string alphabetBoardPath(string target) {  // target 是目标单词，返回在 5 列字母板上移动并点击的指令串
        string ans;  // 保存结果的指令串
        int i = 0, j = 0;  // 当前所在位置（行 i、列 j），起点是左上角的 'a'
        for (char& c : target) {  // 依次处理目标单词的每个字符
            int v = c - 'a';  // 字母转成 0..25 的序号
            int x = v / 5, y = v % 5;  // 序号除以 5 得行、对 5 取余得列（第 v 行放 v*5 到 v*5+4 这 5 个字母）
            while (j > y) {  // 先向左走：必须优先离开第 5 行（'z' 所在行只有一列，右边没有格子），否则会越界
                --j;  // 列号减 1
                ans += 'L';  // 追加向左的指令
            }  // 向左走完
            while (i > x) {  // 再向上走
                --i;  // 行号减 1
                ans += 'U';  // 追加向上的指令
            }  // 向上走完
            while (j < y) {  // 再向右走
                ++j;  // 列号加 1
                ans += 'R';  // 追加向右的指令
            }  // 向右走完
            while (i < x) {  // 最后向下走
                ++i;  // 行号加 1
                ans += 'D';  // 追加向下的指令
            }  // 向下走完
            ans += '!';  // 到达目标格后点击选中
        }  // 单词处理完毕
        return ans;  // 返回完整指令串
    }  // 方法结束
};  // 类定义结束