// 题目：1427. 字符串的左右移（Perform String Shifts）
// 思路：把所有指令折算成「右移为正、左移为负」的步数并累加，对长度取模后一次拼接完成。
// 时间复杂度：O(n + m)，n 为串长、m 为指令数；空间复杂度：O(n)，拼接产生新字符串。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string stringShift(string s, vector<vector<int>>& shift) {  // s：待平移的字符串；shift[i] = [方向, 步数]，方向 0 为左移、1 为右移
        int x = 0;  // 累计净右移步数：右移记正、左移记负
        for (auto& e : shift) {  // 逐条合并指令；用引用是为了下面可以就地改符号
            if (e[0] == 0) {  // 方向 0 表示左移，先统一成右移的符号约定
                e[1] = -e[1];  // 左移 b 步等价于右移 -b 步
            }  // if 结束
            x += e[1];  // 把这条指令的等效右移步数累加进净偏移
        }  // 指令遍历结束
        int n = s.size();  // 字符串长度，用来把总步数折算到一个周期内
        x = (x % n + n) % n;  // C++ 的 % 可能得到负数，先加 n 再取模，把 x 落在 [0, n) 内
        return s.substr(n - x, x) + s.substr(0, n - x);  // 右移 x 步：末尾 x 个字符搬到前面，其余 n-x 个字符接在后面
    }  // 方法结束
};  // 类定义结束