// 题目：1496. 判断路径是否相交（Path Crossing）
// 思路：模拟行走，把经过的每个坐标编码成整数存入哈希集合，一旦发现重复坐标就说明路径相交。
// 时间复杂度：O(n)，n 为路径长度；空间复杂度：O(n)，哈希集合存储坐标。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isPathCrossing(string path) {  // 返回路径是否经过同一个坐标两次
        int i = 0, j = 0;  // 当前坐标，i 表示行、j 表示列，起点为 (0,0)
        unordered_set<int> s{{0}};  // 记录走过的坐标编码；起点先放进去
        for (char& c : path) {  // 逐字符模拟移动
            if (c == 'N') {  // 向北：行坐标减一
                --i;  // 更新行坐标
            } else if (c == 'S') {  // 向南：行坐标加一
                ++i;  // 更新行坐标
            } else if (c == 'E') {  // 向东：列坐标加一
                ++j;  // 更新列坐标
            } else {  // 剩下的只可能是向西
                --j;  // 向西：列坐标减一
            }  // 方向判断结束
            int t = i * 20000 + j;  // 把二维坐标压成一个整数；偏移 20000 足够大，不会与其他坐标撞车
            if (s.count(t)) {  // 该坐标以前走过
                return true;  // 路径相交，立即返回 true
            }  // if 结束
            s.insert(t);  // 记录当前坐标
        }  // for 结束，说明没有重复坐标
        return false;  // 路径不自交
    }  // 方法结束
};  // 类定义结束