// 题目：1446. 连续字符（Consecutive Characters）
// 核心思路：一次线性扫描，用 t 记录以当前位置结尾的连续相同字符段长度，用 ans 维护历史最大值。
// 时间复杂度：O(n)，只遍历字符串一遍；空间复杂度：O(1)，只用两个整型变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxPower(string s) {  // 返回字符串中最长的一段连续相同字符的长度
        int ans = 1, t = 1;  // ans 保存历史最长段长；t 保存当前连续段长，字符串非空时至少为 1
        for (int i = 1; i < s.size(); ++i) {  // 从第二个字符开始，逐个与它的前一个字符比较
            if (s[i] == s[i - 1]) {  // 当前字符与前一个相同，说明连续段还在延续
                ans = max(ans, ++t);  // 先让当前段长加一，再用它刷新答案
            } else {  // 字符发生变化，连续段在此断开
                t = 1;  // 以新字符开启一个新的连续段，长度重新从 1 开始
            }  // if-else 分支结束
        }  // for 循环结束
        return ans;  // 返回最长连续段的长度
    }  // maxPower 方法结束
};  // 类定义结束（源文件此处无结尾换行，保持原样）