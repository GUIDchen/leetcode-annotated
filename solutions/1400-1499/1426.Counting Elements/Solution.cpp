// 题目：1426. 数元素（Counting Elements）
// 核心思路：元素取值在 0..1000 内，用计数数组统计每个值出现的次数；若 x+1 出现过，则值为 x 的元素全部计入答案。
// 时间复杂度：O(n + V)，V = 1000 为值域；空间复杂度：O(V)，计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int countElements(vector<int>& arr) {  // arr：整数数组
        int cnt[1001]{};  // 计数数组，下标即元素值（题面保证 0 <= arr[i] <= 1000）
        for (int x : arr) {  // 统计每个值出现的次数
            ++cnt[x];  // 值 x 的计数加一
        }  // 计数结束
        int ans = 0;  // 记录满足 x+1 也在数组中的元素个数
        for (int x = 0; x < 1000; ++x) {  // 只需枚举到 999，因为要检查的 x+1 仍在计数范围内
            if (cnt[x + 1]) {  // 若 x+1 也出现过，则所有取值为 x 的元素都满足条件
                ans += cnt[x];  // 把值为 x 的元素全部计入答案
            }  // 条件判断结束
        }  // 枚举结束
        return ans;  // 返回满足条件的元素个数
    }  // 方法结束
};  // 题解类定义结束