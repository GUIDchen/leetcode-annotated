// 题目：1419. 数青蛙（Minimum Number of Frogs Croaking）
// 核心思路：把每个字母映射成 "croak" 中的阶段下标，用计数数组检查前驱阶段是否有青蛙可接，并同时统计最大并发数。
// 时间复杂度：O(n)，n 为字符串长度；空间复杂度：O(1)，只用了长度 5 与 26 的两个常数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minNumberOfFrogs(string croakOfFrogs) {  // croakOfFrogs：只由 c、r、o、a、k 组成的字符串
        int n = croakOfFrogs.size();  // 记录字符串长度，供后面判断是否为 5 的倍数
        if (n % 5 != 0) {  // 一只青蛙完整叫出 5 个字母，长度不是 5 的倍数必然非法
            return -1;  // 无法组成合法鸣叫，直接返回 -1
        }  // 长度检查结束
        int idx[26]{};  // 字母 → 它在 croak 中位置 的映射，26 个字母先全部置 0
        string s = "croak";  // 标准叫声，用来建立字母与阶段的对应关系
        for (int i = 0; i < 5; ++i) {  // 遍历叫声的 5 个阶段
            idx[s[i] - 'a'] = i;  // 把每个字母映射到它的阶段下标 0..4
        }  // 映射建立完毕
        int cnt[5]{};  // cnt[i]：当前停在阶段 i 的青蛙数量
        int ans = 0, x = 0;  // ans 记录历史最大并发；x 记录当前正在叫的青蛙数
        for (char& c : croakOfFrogs) {  // 按顺序读入每个字母
            int i = idx[c - 'a'];  // 该字母属于第几个阶段
            ++cnt[i];  // 到达阶段 i 的青蛙数加一
            if (i == 0) {  // i == 0 表示字母是 c：一只青蛙开始新一轮叫声
                ans = max(ans, ++x);  // 正在叫的青蛙数加一，并更新历史最大值
            } else {  // 否则必须由上一阶段的青蛙接上
                if (--cnt[i - 1] < 0) {  // 上一阶段没有青蛙可接，说明叫声顺序非法
                    return -1;  // 判定此串无效
                }  // 上一阶段接续失败的处理结束
                if (i == 4) {  // i == 4 表示字母是 k：这一轮叫完了
                    --x;  // 该青蛙空闲下来，正在叫的数量减一
                }  // 结束字母处理
            }  // 非首字母分支结束
        }  // 所有字母处理完毕
        return x > 0 ? -1 : ans;  // 仍有青蛙没叫完说明有残缺叫声，否则返回最大并发数
    }  // 方法结束
};  // 题解类定义结束