// 题目：1492. n 的第 k 个因子（The kth Factor of n）
// 思路：从 1 到 n 升序枚举，每遇到一个能整除 n 的数就把 k 减一，k 减到 0 时的因子即答案。
// 时间复杂度：O(n)，最坏枚举到 n；空间复杂度：O(1)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int kthFactor(int n, int k) {  // 返回 n 的第 k 个因子；因子不足 k 个时返回 -1
        for (int i = 1; i <= n; ++i) {  // 从小到大枚举，因子因此天然按升序出现
            if (n % i == 0 && (--k == 0)) {  // i 能整除 n 说明 i 是因子；同时把剩余需要的个数 k 减一，减到 0 说明正好数到第 k 个
                return i;  // 第 k 个因子就是 i
            }  // if 结束
        }  // for 结束，说明因子总数不足 k 个
        return -1;  // 不存在第 k 个因子，按题目要求返回 -1
    }  // 方法结束
};  // 类定义结束