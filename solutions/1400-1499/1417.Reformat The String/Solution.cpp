// 题目：1417. 重新格式化字符串（Reformat The String）
// 思路：把数字和字母分别挑出，数量差超过 1 就无解；否则让多的一组打头交替拼接，多出的一个补在末尾。
// 时间复杂度：O(n)，只做一次遍历与一次拼接；空间复杂度：O(n)，保存两组字符与结果串。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string reformat(string s) {  // s 是数字与小写字母混合的字符串，返回数字字母交替的重排结果
        string a = "", b = "";  // a 收集所有数字，b 收集所有字母
        for (char c : s) {  // 遍历原串，按字符种类分组
            if (isdigit(c))  // 当前字符是数字
                a += c;  // 归入数字组
            else  // 否则说明是小写字母
                b += c;  // 归入字母组
        }  // 结束分组遍历
        int m = a.size(), n = b.size();  // m、n 分别是数字和字母的个数
        if (abs(m - n) > 1) return "";  // 两类数量相差超过 1 就不可能交替排列，按题目要求返回空串
        string ans = "";  // 结果串，逐对拼接
        for (int i = 0; i < min(m, n); ++i) {  // 先交替拼完两组共有的部分
            if (m > n) {  // 数字比字母多，必须以数字开头
                ans += a[i];  // 先放一个数字
                ans += b[i];  // 再放一个字母，保证相邻异类
            } else {  // 否则字母不少于数字，从字母开头
                ans += b[i];  // 先放一个字母
                ans += a[i];  // 再放一个数字
            }  // 结束方向分支
        }  // 结束交替拼接循环
        if (m > n) ans += a[m - 1];  // 数字多出一个，补在末尾
        if (m < n) ans += b[n - 1];  // 字母多出一个，补在末尾
        return ans;  // 返回重排后的字符串
    }  // 结束题解方法
};  // 结束题解类