// 题目：1463. 摘樱桃 II（Cherry Pickup II）
// 思路：把两个机器人按行同步推进，f[i][j1][j2] 表示走到第 i 行且两机器人分别位于 j1、j2 列时的最大收益；每个机器人上一行只能来自 j-1、j、j+1 三列，两机器人同格时该格樱桃只算一次。
// 时间复杂度：O(m×n^2×9)，即每行枚举 n^2 个位置、每个位置 9 种来源组合；空间复杂度：O(m×n^2)，三维 dp 表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int cherryPickup(vector<vector<int>>& grid) {  // grid：每格樱桃数；返回两机器人合计能摘到的最大樱桃数
        int m = grid.size(), n = grid[0].size();  // m 为行数，n 为列数
        int f[m][n][n];  // f[i][j1][j2]：走到第 i 行、两机器人分别在第 j1、j2 列时的最大收益
        memset(f, -1, sizeof(f));  // memset 按字节填 -1，表示该状态暂时不可达
        f[0][0][n - 1] = grid[0][0] + grid[0][n - 1];  // 初始状态：第一个机器人在左上角，第二个在右上角，收益为两格樱桃之和
        for (int i = 1; i < m; ++i) {  // 从第 1 行开始逐行向下推进
            for (int j1 = 0; j1 < n; ++j1) {  // 枚举第一个机器人本行所在的列 j1
                for (int j2 = 0; j2 < n; ++j2) {  // 枚举第二个机器人本行所在的列 j2
                    int x = grid[i][j1] + (j1 == j2 ? 0 : grid[i][j2]);  // 本行两格的收益；两机器人同格时该格只能摘一次，所以加 0
                    for (int y1 = j1 - 1; y1 <= j1 + 1; ++y1) {  // 枚举第一个机器人上一行的来源列 y1（左、中、右三选一）
                        for (int y2 = j2 - 1; y2 <= j2 + 1; ++y2) {  // 枚举第二个机器人上一行的来源列 y2（同样三选一）
                            if (y1 >= 0 && y1 < n && y2 >= 0 && y2 < n && f[i - 1][y1][y2] != -1) {  // 来源列必须不越界，且上一行该状态必须可达（不为 -1）
                                f[i][j1][j2] = max(f[i][j1][j2], f[i - 1][y1][y2] + x);  // 用上一行可达状态加本行收益，更新当前状态的最大值
                            }  // if 语句块结束
                        }  // 内层 for 循环体结束
                    }  // 中层 for 循环体结束
                }  // 中层 for 循环体结束
            }  // 外层 for 循环体结束
        }  // 外层 for 循环体结束
        int ans = 0;  // 记录最后一行的最大收益
        for (int j1 = 0; j1 < n; ++j1) {  // 枚举第一个机器人在最后一行的落点列
            for (int j2 = 0; j2 < n; ++j2) {  // 枚举第二个机器人在最后一行的落点列
                ans = max(ans, f[m - 1][j1][j2]);  // 在所有终态中取最大值
            }  // 内层 for 循环体结束
        }  // 外层 for 循环体结束
        return ans;  // 返回答案
    }  // 方法体结束
};  // 类定义结束