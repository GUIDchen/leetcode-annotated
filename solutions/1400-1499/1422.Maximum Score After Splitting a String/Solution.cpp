// 题目：1422. 分割字符串的最大得分（Maximum Score After Splitting a String）
// 核心思路：先统计全串 1 的个数作为右段得分，再从左往右移动切点，增量维护左段 0 的个数与右段 1 的个数。
// 时间复杂度：O(n)，n 为字符串长度；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxScore(string s) {  // s：只含 '0' 和 '1' 的二进制字符串
        int l = 0, r = count(s.begin(), s.end(), '1');  // l：左段 0 的个数（动态增长）；r：右段 1 的个数（初始为全串 1 的个数）
        int ans = 0;  // 记录遍历过程中的最大得分
        for (int i = 0; i < s.size() - 1; ++i) {  // 切点 i 表示左段为 s[0..i]，必须给右段至少留一个字符
            l += (s[i] - '0') ^ 1;  // 字符为 '0' 时异或 1 得 1，左段 0 的个数加一；为 '1' 则加 0
            r -= s[i] - '0';  // 该字符从右段划入左段：若是 '1' 就让右段 1 的个数减一
            ans = max(ans, l + r);  // 当前切法得分 = 左段 0 的个数 + 右段 1 的个数，取最大值
        }  // 所有切点枚举结束
        return ans;  // 返回最大得分
    }  // 方法结束
};  // 题解类定义结束
