// 题目：1410. HTML 实体解析器（HTML Entity Parser）
// 思路：建立实体到单字符的哈希表，从左到右扫描文本，按长度 1..7 尝试匹配实体，命中就整体跳过。
// 时间复杂度：O(n * L)，L 为实体最大长度 7，视为 O(n)；空间复杂度：O(n)，答案字符串与常数大小的哈希表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string entityParser(string text) {  // text 是含 HTML 实体的字符串，返回把实体替换成字符后的结果
        unordered_map<string, string> d = {  // 实体到单字符的映射表，键是实体原文
            {"&quot;", "\""},  // &quot; 解析成双引号
            {"&apos;", "'"},  // &apos; 解析成单引号
            {"&amp;", "&"},  // &amp; 解析成 & 符号（放在最后匹配可避免二次转义）
            {"&gt;", ">"},  // &gt; 解析成大于号
            {"&lt;", "<"},  // &lt; 解析成小于号
            {"&frasl;", "/"},  // &frasl; 解析成斜杠
        };  // 结束映射表初始化
        string ans = "";  // 结果串，边扫描边向后拼接
        int i = 0, n = text.size();  // i 是当前扫描位置，n 是文本长度
        while (i < n) {  // 从左到右扫描整段文本
            bool found = false;  // 标记当前位置是否匹配到了某个实体
            for (int l = 1; l < 8; ++l) {  // 实体最长 7 个字符，按长度枚举所有可能
                int j = i + l;  // 以 i 开头、长度为 l 的子串的右端点（开区间）
                if (j <= n) {  // 子串不能越过文本末尾
                    string t = text.substr(i, l);  // 取出候选子串
                    if (d.count(t)) {  // 候选子串正好是一个实体
                        ans += d[t];  // 追加该实体对应的单个字符
                        i = j;  // 跳过整个实体，i 直接移到右端点
                        found = true;  // 标记已经匹配成功
                        break;  // 匹配到就不必再尝试更长的子串
                    }  // 结束命中判断
                }  // 结束长度合法性判断
            }  // 结束长度枚举循环
            if (!found) ans += text[i++];  // 没有命中任何实体，就把当前字符原样保留并后移一位
        }  // 结束主扫描循环
        return ans;  // 返回解析后的字符串
    }  // 结束题解方法
};  // 结束题解类