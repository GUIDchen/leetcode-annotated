// 题目：1434. 每个人戴不同帽子的方案数（Number of Ways to Wear Different Hats to Each Other）
// 思路：按帽子编号从小到大做状态压缩 DP，f[i][j] 表示只考虑前 i 顶帽子、已戴帽子的人集合为 j 的方案数。
// 时间复杂度：O(m * 2^n * 边数)，实际为 O(m 2^n + 总喜好数)；空间复杂度：O(m 2^n)。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberWays(vector<vector<int>>& hats) {  // hats[i] 是第 i 个人喜欢的帽子编号列表，返回让每人戴不同帽子的方案数
        int n = hats.size();  // n：人数，也是状态压缩的位数
        int m = 0;  // m：需要枚举到的最大帽子编号
        for (auto& h : hats) {  // 遍历每个人，求出最大的帽子编号，缩小枚举范围
            m = max(m, *max_element(h.begin(), h.end()));  // 取当前人喜好列表中的最大编号，与全局最大值比较
        }  // 求最大值结束
        vector<vector<int>> g(m + 1);  // g[v] 存放喜欢帽子 v 的所有人的下标，把「人 → 帽子」翻转成「帽子 → 人」
        for (int i = 0; i < n; ++i) {  // 逐个处理每个人
            for (int& v : hats[i]) {  // 处理他喜欢的每一顶帽子
                g[v].push_back(i);  // 把该人的下标加入这顶帽子的候选列表；v 是引用，避免拷贝
            }  // 内层循环结束
        }  // 外层循环结束
        const int mod = 1e9 + 7;  // 方案数取模，防止溢出
        int f[m + 1][1 << n];  // 状态表：f[i][j] 为前 i 顶帽子、已戴帽子的集合为 j 的方案数（VLA，大小由 n 决定）
        memset(f, 0, sizeof(f));  // 全部初始化为 0，表示还没有任何方案
        f[0][0] = 1;  // 边界：0 顶帽子、没人戴帽子，只有 1 种方案（什么都不做）
        for (int i = 1; i <= m; ++i) {  // 按帽子编号从小到大递推
            for (int j = 0; j < 1 << n; ++j) {  // 枚举已戴帽子的所有可能集合 j
                f[i][j] = f[i - 1][j];  // 本顶帽子不选：方案数完全继承上一顶帽子的结果
                for (int k : g[i]) {  // 尝试把帽子 i 分给喜欢它的某个人 k
                    if (j >> k & 1) {  // 只有当 j 中已经包含 k（第 k 位为 1）时才可能由更小的集合转移过来
                        f[i][j] = (f[i][j] + f[i - 1][j ^ (1 << k)]) % mod;  // 从 j 中去掉 k 这一位，表示 k 是在本步才戴上帽子的，累加并取模
                    }  // if 结束
                }  // 候选人的循环结束
            }  // 集合枚举结束
        }  // 帽子枚举结束
        return f[m][(1 << n) - 1];  // 所有人都戴上帽子（集合为全 1）的方案数即为答案
    }  // 方法结束
};  // 类定义结束