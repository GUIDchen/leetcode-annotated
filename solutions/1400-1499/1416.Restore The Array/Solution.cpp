// 题目：1416. 恢复数组（Restore The Array）
// 思路：从右往左动态规划，f[i] 表示后缀 s[i..] 的方案数，枚举第一段的结束位置并累加 f[j+1]。
// 时间复杂度：O(n * log k)，每段长度受 k 限制；空间复杂度：O(n)，一维 DP 数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberOfArrays(string s, int k) {  // s 是数字字符串，k 是每段允许的最大值，返回合法的分割方案数
        const int mod = 1e9 + 7;  // 方案数可能很大，按题目要求取模
        int n = s.size();  // 字符串长度
        vector<int> f(n + 1);  // f[i] 表示后缀 s[i..n-1] 的合法分割方案数
        f[n] = 1;  // 空后缀视为一种方案，是递推的边界
        for (int i = n - 1; i >= 0; --i) {  // 从右往左逐个求后缀的方案数
            if (s[i] == '0') {  // 以 0 开头的段不合法（数字不能有前导零）
                continue;  // 该位置没有任何方案，直接跳过
            }  // 结束前导零判断
            long long x = 0;  // x 逐步累加当前段的数值，用 long long 防止溢出
            for (int j = i; j < n; ++j) {  // 枚举当前段的右端点 j
                x = x * 10 + s[j] - '0';  // 把 s[j] 接到当前段末尾，x 变成新段的数值
                if (x > k) {  // 段值已经超过 k，再延长只会更大
                    break;  // 提前结束这一层枚举
                }  // 结束超限判断
                f[i] = (f[i] + f[j + 1]) % mod;  // 把 s[i..j] 当作第一段，累加剩余后缀的方案数
            }  // 结束右端点枚举
        }  // 结束后缀循环
        return f[0];  // f[0] 就是整个字符串的方案数
    }  // 结束题解方法
};  // 结束题解类
