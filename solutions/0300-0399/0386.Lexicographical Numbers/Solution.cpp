// 题目：386. 字典序排数（Lexicographical Numbers）
// 思路：把 1..n 看成十叉字典树，能乘 10 就往下走，走不动就回退到能加一的层，恰好按字典序输出 n 个数。
// 时间复杂度：O(n)，每个数均摊只被访问常数次；空间复杂度：O(1)，除答案数组外只用常数变量。
class Solution {  // 题解类
public:  // 对外接口
    vector<int> lexicalOrder(int n) {  // n 是上界，返回 1..n 按字典序排好的数组
        vector<int> ans;  // 结果数组，按字典序依次追加
        int v = 1;  // 当前要输出的数，字典序的第一个数是 1
        for (int i = 0; i < n; ++i) {  // 一共要输出 n 个数，循环次数固定
            ans.push_back(v);  // 当前数就是字典序下的下一个，先放进答案
            if (v * 10 <= n) {  // 还能往下一层走（末尾补 0）就优先往下
                v *= 10;  // 乘 10 得到字典序上的第一个子节点
            } else {  // 走不动了，需要回退或右移
                while (v % 10 == 9 || v + 1 > n) {  // 末位已是 9 或加一就超界，必须先退回父节点
                    v /= 10;  // 去掉末位，回到上一层
                }
                ++v;  // 回退到能加一的层后向右移到兄弟节点
            }
        }
        return ans;  // 返回按字典序排好的 1..n
    }
};