// 题目：387. 字符串中的第一个唯一字符（First Unique Character in a String）
// 思路：先用 26 个桶统计每个字母出现次数，再从左到右找第一个计数为 1 的位置。
// 时间复杂度：O(n)，两趟线性扫描；空间复杂度：O(1)，只用固定 26 个计数桶。
class Solution {  // 题解类
public:  // 对外接口
    int firstUniqChar(string s) {  // s 是只含小写字母的字符串，返回第一个不重复字符的下标
        int cnt[26]{};  // 计数桶：下标 0~25 对应 'a'~'z'，{} 保证初始化为 0
        for (char& c : s) {  // 第一趟统计每个字母的出现次数
            ++cnt[c - 'a'];  // 字符减 'a' 映射到 0~25，计数加一
        }
        int n = s.size();  // 缓存长度，避免循环里反复调用 size()
        for (int i = 0; i < n; ++i) {  // 第二趟按原顺序找第一个计数为 1 的字母
            if (cnt[s[i] - 'a'] == 1) {  // 只出现一次，就是题目要找的第一个唯一字符
                return i;  // 直接返回它的下标
            }
        }
        return -1;  // 扫完都没有唯一字符，按题目约定返回 -1
    }
};