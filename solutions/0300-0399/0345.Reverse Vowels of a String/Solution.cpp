// 题目：345. 反转字符串中的元音字母（Reverse Vowels of a String）
// 思路：用 128 个下标的布尔表标记哪些字符是元音，双指针跳过非元音字符，两端都停在元音上时交换。
// 时间复杂度：O(n)，两个指针各自单向走完全程；空间复杂度：O(1)，元音表与指针都是常数级。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string reverseVowels(string s) {  // s：输入字符串，返回把元音字母反转后的新字符串
        bool vowels[128];  // ASCII 码 0..127 的查表数组，用下标直接判断字符是否为元音，O(1) 查询
        memset(vowels, false, sizeof(vowels));  // 整体清零，等价于把所有字符先标记为「非元音」
        for (char c : "aeiouAEIOU") {  // 遍历全部大小写元音字母，把它们在下标数组中标为 true
            vowels[c] = true;  // 该字符是元音，置标记为 true
        }  // 元音表构建结束
        int i = 0, j = s.size() - 1;  // 双指针：i 从左、j 从右扫描字符串
        while (i < j) {  // 两个指针没相遇就继续寻找可交换的元音对
            while (i < j && !vowels[s[i]]) {  // i 向右寻找元音；i < j 保证不会越过 j
                ++i;  // 当前字符不是元音，左指针右移一格继续找
            }  // 左侧跳过非元音字符
            while (i < j && !vowels[s[j]]) {  // j 向左寻找元音；同样不能越过 i
                --j;  // 当前字符不是元音，右指针左移一格继续找
            }  // 右侧跳过非元音字符
            if (i < j) {  // 两侧都停在元音上时交换；若指针已相遇说明没有成对的元音，无需交换
                swap(s[i++], s[j--]);  // 交换两个元音，并让 i 右移、j 左移，避免死循环
            }  // if 结束
        }  // 外层 while 结束
        return s;  // 返回反转元音后的字符串
    }  // 方法体结束
};  // 类定义结束