# 题目：397. 整数替换（Integer Replacement）
# 思路：偶数直接除 2；奇数若末两位是 11 就加一（n 等于 3 时除外），否则减一，贪心地让后续能连续除以 2。
# 时间复杂度：O(log n)，每步至少消掉一位二进制；空间复杂度：O(1)，只用常数个变量。
class Solution:  # LeetCode 约定的题解类
    def integerReplacement(self, n: int) -> int:  # n 是输入整数，返回把它变成 1 的最少操作次数
        ans = 0  # 记录已执行的操作次数
        while n != 1:  # 不断操作直到 n 变成 1
            if (n & 1) == 0:  # n 是偶数
                n >>= 1  # 右移一位等价于除以 2
            elif n != 3 and (n & 3) == 3:  # 奇数且末两位是 11，加一比减一更优
                n += 1  # 加一后末位变 0，可以连续除以 2
            else:  # 其余情况（含 n 等于 3 的特例）
                n -= 1  # 减一变成偶数
            ans += 1  # 无论哪种操作，次数都加一
        return ans  # 返回总操作次数
