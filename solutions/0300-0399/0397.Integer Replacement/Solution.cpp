// 题目：397. 整数替换（Integer Replacement）
// 思路：偶数直接除 2；奇数若末两位是 11 就加一（n 等于 3 时除外），否则减一，贪心地让后续能连续除以 2。
// 时间复杂度：O(log n)，每步至少消掉一位二进制；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int integerReplacement(int N) {  // N 是输入整数，返回把它变成 1 的最少操作次数
        int ans = 0;  // 记录已执行的操作次数
        long n = N;  // 用 long 承接，避免 INT_MAX 加一时溢出
        while (n != 1) {  // 一直操作到 n 变成 1
            if ((n & 1) == 0)  // n 是偶数：直接除以 2
                n >>= 1;  // 右移一位等价于除以 2，比除法更快
            else if (n != 3 && (n & 3) == 3)  // 奇数且末两位是 11：加一能让接下来的除法更多
                ++n;  // 加一后末位变 0，可以连续除以 2
            else  // 其余奇数（末两位是 01，或者 n 本身就是 3）
                --n;  // 减一变成偶数
            ++ans;  // 无论哪种操作，次数都加一
        }
        return ans;  // 返回总操作次数
    }
};