# 题目：301. 删除无效的括号（Remove Invalid Parentheses）
# 思路：先扫描一次算出必须删掉的左、右括号个数；再 DFS 枚举「删当前括号 / 保留当前括号」两种分支，配合剩余字符数与右括号前缀两个剪枝。
# 时间复杂度：O(n · 2^n)，最坏情况枚举每个括号删或不删；空间复杂度：O(n + k)，递归栈深度 n、结果集合存 k 个解。
class Solution:  # LeetCode 约定的题解类
    def removeInvalidParentheses(self, s: str) -> List[str]:  # s：含括号的字符串；返回所有删除次数最少的合法结果
        def dfs(i, l, r, lcnt, rcnt, t):  # i：当前下标；l/r：剩余需删数；lcnt/rcnt：已保留的左右括号数；t：当前构造的串
            if i == n:  # 已经走到字符串末尾
                if l == 0 and r == 0:  # 该删的括号都删完了，说明这是一个合法解
                    ans.add(t)  # 加入结果集合（set 自动去重）
                return  # 递归边界返回
            if n - i < l + r or lcnt < rcnt:  # 剪枝：剩余字符不够删，或已保留的右括号多于左括号
                return  # 此分支不可能产生合法解，直接剪掉
            if s[i] == '(' and l:  # 当前字符是左括号且还需要删左括号，尝试删除它
                dfs(i + 1, l - 1, r, lcnt, rcnt, t)  # 删除数减一后继续往下搜索
            elif s[i] == ')' and r:  # 当前字符是右括号且还需要删右括号，尝试删除它
                dfs(i + 1, l, r - 1, lcnt, rcnt, t)  # 删除数减一后继续往下搜索
            dfs(i + 1, l, r, lcnt + (s[i] == '('), rcnt + (s[i] == ')'), t + s[i])  # 另一个分支：保留当前字符；布尔值可直接当 0/1 参与计数

        l = r = 0  # l、r：还需删除的左、右括号个数
        for c in s:  # 一次扫描统计至少要删掉多少个左、右括号
            if c == '(':  # 遇到左括号
                l += 1  # 需要的左括号数加一
            elif c == ')':  # 遇到右括号
                if l:  # 前面有可匹配的左括号
                    l -= 1  # 配对成功，消耗掉一个左括号
                else:  # 前面没有可匹配的左括号
                    r += 1  # 这个右括号是多出来的，必须删除
        ans = set()  # 结果集合，自动去重，避免不同删除路径产生相同字符串
        n = len(s)  # 串长；dfs 在第 27 行才调用，闭包此时能取到这个值
        dfs(0, l, r, 0, 0, '')  # 从下标 0、空串开始搜索所有删除方案
        return list(ans)  # 转成列表返回
