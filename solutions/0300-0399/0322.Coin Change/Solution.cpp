// 题目：322. 零钱兑换（Coin Change）
// 思路：完全背包动态规划，f[i][j] 表示用前 i 种硬币凑出金额 j 的最少硬币数，转移时枚举「不用」与「再用一枚」。
// 时间复杂度：O(m * n)，m 为硬币种数、n 为金额；空间复杂度：O(m * n)，使用二维 DP 表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int coinChange(vector<int>& coins, int amount) {  // coins：硬币面值；amount：目标金额；返回最少硬币数，凑不出返回 -1
        int m = coins.size(), n = amount;  // m 为硬币种数，n 为目标金额
        int f[m + 1][n + 1];  // 完全背包 DP 表：f[i][j] 表示用前 i 种硬币凑出金额 j 的最少硬币数
        memset(f, 0x3f, sizeof(f));  // memset 按字节填充 0x3f，得到一个足够大的「无穷大」，表示暂时凑不出
        f[0][0] = 0;  // 边界：用 0 种硬币凑出金额 0 需要 0 枚
        for (int i = 1; i <= m; ++i) {  // 逐个考虑每种硬币（i 从 1 开始，对应 coins[i-1]）
            for (int j = 0; j <= n; ++j) {  // 枚举目标金额 j，顺序遍历以支持同种硬币重复使用
                f[i][j] = f[i - 1][j];  // 不用第 i 种硬币：直接继承前 i-1 种的结果
                if (j >= coins[i - 1]) {  // 金额够用当前面值时，才可能再放一枚
                    f[i][j] = min(f[i][j], f[i][j - coins[i - 1]] + 1);  // 用上当前硬币后仍是 f[i][j-x]（可继续用同种），取较小值
                }  // 分支结束
            }  // 金额枚举结束
        }  // 硬币种类枚举结束
        return f[m][n] > n ? -1 : f[m][n];  // 仍是无穷大说明凑不出（其值远大于 n），返回 -1，否则返回最少硬币数
    }  // 方法结束
};  // 类定义结束