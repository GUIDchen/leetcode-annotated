# 题目：344. 反转字符串（Reverse String）
# 思路：双指针从两端向中间靠拢，逐对交换字符，直接在传入的列表上原地修改。
# 时间复杂度：O(n)，每个字符只被访问并交换一次；空间复杂度：O(1)，只用两个下标变量。
class Solution:  # LeetCode 约定的题解类
    def reverseString(self, s: List[str]) -> None:  # s：待反转的字符列表；题目要求原地修改，因此返回 None
        i, j = 0, len(s) - 1  # 初始化双指针：i 指向首字符，j 指向尾字符
        while i < j:  # 当左指针仍在右指针左边时继续交换，相遇或交错即结束
            s[i], s[j] = s[j], s[i]  # Python 元组赋值一次性交换两个字符，中间不产生临时列表
            i, j = i + 1, j - 1  # 左指针右移、右指针左移，向中间收缩
