// 题目：344. 反转字符串（Reverse String）
// 思路：双指针分别指向首尾，向中间靠拢并逐对交换字符；题目要求原地修改，所以不能借助额外数组。
// 时间复杂度：O(n)，每个字符只被访问并交换一次；空间复杂度：O(1)，只用两个指针。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    void reverseString(vector<char>& s) {  // s：待反转的字符数组，要求原地修改，返回值为 void
        for (int i = 0, j = s.size() - 1; i < j;) {  // 双指针：i 从头部、j 从尾部出发；循环条件没有自增表达式，留给循环体在交换时同步移动
            swap(s[i++], s[j--]);  // 交换 s[i] 与 s[j]；i++ 与 j-- 让两个指针在交换后同时向中间收缩
        }  // 循环体结束
    }  // 方法体结束
};  // 类定义结束