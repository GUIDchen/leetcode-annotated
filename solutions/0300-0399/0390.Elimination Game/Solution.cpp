// 题目：390. 消除游戏（Elimination Game）
// 思路：只维护剩余等差数列的首项、末项与公差，每轮根据删除方向和剩余个数的奇偶推进端点。
// 时间复杂度：O(log n)，每轮剩余个数减半；空间复杂度：O(1)，只用了常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int lastRemaining(int n) {  // n 表示初始序列 1..n，返回最后剩下的那个数
        int a1 = 1, an = n, step = 1;  // 用首项 a1、末项 an、公差 step 三个量描述当前剩下的等差数列
        for (int i = 0, cnt = n; cnt > 1; cnt >>= 1, step <<= 1, ++i) {  // i 记录轮次（偶数为从左边删）；cnt 是剩余个数；每轮个数减半、公差翻倍
            if (i % 2) {  // 奇数轮：从右往左删
                an -= step;  // 从右删时末项必定被删，新末项左移一个公差
                if (cnt % 2) a1 += step;  // 剩余个数为奇数时首项也会被删，故首项右移一个公差
            } else {  // 偶数轮：从左往右删
                a1 += step;  // 从左删时首项必定被删，新首项右移一个公差
                if (cnt % 2) an -= step;  // 剩余个数为奇数时末项也会被删，故末项左移一个公差
            }
        }
        return a1;  // 只剩一个数，首项就是答案
    }
};