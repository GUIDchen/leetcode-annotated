# 题目：390. 消除游戏（Elimination Game）
# 思路：只维护剩余等差数列的首项、末项与公差，每轮根据删除方向和剩余个数的奇偶推进端点。
# 时间复杂度：O(log n)，每轮剩余个数减半；空间复杂度：O(1)，只用了常数个变量。
class Solution:  # LeetCode 约定的题解类
    def lastRemaining(self, n: int) -> int:  # n 表示初始序列 1..n，返回最后剩下的那个数
        a1, an = 1, n  # 首项 a1 与末项 an，初始分别是 1 和 n
        i, step, cnt = 0, 1, n  # i 是轮次（偶数为从左边删），step 是公差，cnt 是剩余个数
        while cnt > 1:  # 剩余多于一个数就继续消除
            if i % 2:  # 奇数轮：从右往左删
                an -= step  # 从右删时末项必定被删，新末项左移一个公差
                if cnt % 2:  # 剩余个数为奇数
                    a1 += step  # 此时首项也会被删，故首项右移一个公差
            else:  # 偶数轮：从左往右删
                a1 += step  # 从左删时首项必定被删，新首项右移一个公差
                if cnt % 2:  # 剩余个数为奇数
                    an -= step  # 此时末项也会被删，故末项左移一个公差
            cnt >>= 1  # 每轮消除一半，剩余个数减半
            step <<= 1  # 元素间隔翻倍，公差随之翻倍
            i += 1  # 轮次加一，下一轮换方向
        return a1  # 只剩一个数，首项就是答案
