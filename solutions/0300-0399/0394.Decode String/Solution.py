# 题目：394. 字符串解码（Decode String）
# 思路：两个栈分别保存重复次数与外层已解码前缀，遇到左括号压栈并把当前数字与结果清零，遇到右括号弹栈结算，普通字母直接追加。
# 时间复杂度：O(L)，L 为解码后字符串长度；空间复杂度：O(L)，栈与中间结果的总量级与答案同阶。
class Solution:  # LeetCode 约定的题解类
    def decodeString(self, s: str) -> str:  # s 是形如 3[a2[c]] 的编码串，返回解码后的字符串
        s1, s2 = [], []  # 两个栈：s1 存重复次数，s2 存进入括号前的已解码前缀
        num, res = 0, ''  # num 累积当前数字，res 累积当前这一层的解码结果
        for c in s:  # 逐个字符处理编码串
            if c.isdigit():  # 数字字符可能连续出现，需要拼成多位数
                num = num * 10 + int(c)  # 十进制拼接：旧数字左移一位再加上新数位
            elif c == '[':  # 遇到左括号，进入新的一层
                s1.append(num)  # 把这一层的重复次数压栈
                s2.append(res)  # 把外层已解码的前缀压栈，供弹出时拼回
                num, res = 0, ''  # 重置计数器和结果，开始解码括号内的内容
            elif c == ']':  # 遇到右括号，结算当前层
                res = s2.pop() + res * s1.pop()  # 弹出次数与前缀：前缀 + 当前内容重复相应次数
            else:  # 既不是数字也不是括号，就是普通字母
                res += c  # 直接追加到当前层结果
        return res  # 遍历结束，res 就是完整解码结果
