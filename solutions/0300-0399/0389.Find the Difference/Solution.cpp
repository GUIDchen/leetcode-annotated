// 题目：389. 找不同（Find the Difference）
// 思路：先用 26 个桶统计 s 的字母，再遍历 t 逐个扣减，第一个被扣成负数的字符就是多出来的那个。
// 时间复杂度：O(n)，两趟线性扫描；空间复杂度：O(1)，只用固定 26 个计数桶。
class Solution {  // 题解类
public:  // 对外接口
    char findTheDifference(string s, string t) {  // s 是原串，t 是 s 打乱后多加一个字符的串，返回多出来的字符
        int cnt[26]{};  // 计数桶：下标 0~25 对应 'a'~'z'，{} 保证初始化为 0
        for (char& c : s) {  // 第一趟统计 s 里每个字母出现的次数
            ++cnt[c - 'a'];  // 字符减 'a' 映射到 0~25，计数加一
        }
        for (char& c : t) {  // 第二趟用 t 的字符去消耗库存
            if (--cnt[c - 'a'] < 0) {  // 先扣减再判断：第一处被扣成负数的地方就是多出来的字符
                return c;  // 直接返回这个字符
            }
        }
        return ' ';  // 逻辑上一定会在循环里返回，这里只是让函数有兜底返回值
    }
};