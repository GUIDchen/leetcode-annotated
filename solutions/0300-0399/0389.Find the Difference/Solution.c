// 题目：389. 找不同（Find the Difference）
// 思路：用 26 个桶做差分计数，s 与 t 的前 n 个字符一一抵消，最后单独扣掉 t 末尾多出来的那个字符。
// 时间复杂度：O(n)，两趟线性扫描；空间复杂度：O(1)，只用固定 26 个计数桶。
char findTheDifference(char* s, char* t) {  // s 是原串，t 是 s 打乱后多加一个字符的串，返回那个多出来的字符
    int n = strlen(s);  // n 是 s 的长度，t 的长度为 n + 1
    int cnt[26] = {0};  // 26 个计数桶，下标 0~25 对应 'a'~'z'，初始化为 0
    for (int i = 0; i < n; i++) {  // 同时遍历 s 与 t 的前 n 个字符，做加减抵消
        cnt[s[i] - 'a']++;  // s 中的字符让对应桶计数加一
        cnt[t[i] - 'a']--;  // t 中的字符让对应桶计数减一，相同字符正好抵消成 0
    }
    cnt[t[n] - 'a']--;  // t 比 s 多出的最后一个字符，单独再扣减一次
    for (int i = 0;; i++) {  // 扫描计数桶找唯一的非零项，循环上界由题目保证可省略
        if (cnt[i]) {  // 非零说明这个字母在 t 里多出来了一次
            return 'a' + i;  // 把桶下标还原成对应的小写字母返回
        }
    }
}