// 题目：388. 文件的最长绝对路径（Longest Absolute File Path）
// 思路：用一个栈按下标保存每层目录的累计绝对路径长度，按行扫描：先数制表符得到深度，再按需弹栈、取父路径长度、目录入栈。
// 时间复杂度：O(n)，每个字符只被扫描常数次；空间复杂度：O(n)，栈最多保存最大嵌套深度的目录长度。
class Solution {  // 题解类
public:  // 对外接口
    int lengthLongestPath(string input) {  // input 是用 '\n' 分行、'\t' 表示目录层级的文件系统字符串
        int i = 0, n = input.size();  // i 是扫描下标，n 是字符串总长度
        int ans = 0;  // ans 保存已见过的最长文件绝对路径长度
        stack<int> stk;  // 单调栈：下标 k 处的值表示深度为 k 的目录的累计路径长度
        while (i < n) {  // 按行（以 '\n' 分隔）逐行扫描输入
            int ident = 0;  // ident 记录本行开头的制表符个数，也就是该条目的目录深度
            for (; input[i] == '\t'; ++i) {  // 连续吃掉行首的所有制表符
                ++ident;  // 每多一个制表符，就多嵌套一层
            }

            int cur = 0;  // cur 统计本行条目（目录名或文件名）本身的字符长度
            bool isFile = false;  // 标记本行是文件还是目录，名字里带 '.' 即视为文件
            for (; i < n && input[i] != '\n'; ++i) {  // 一直扫到本行结尾的换行符为止
                ++cur;  // 名字长度加一
                if (input[i] == '.') {  // 名字里出现点号，说明这一行是文件而不是目录
                    isFile = true;  // 置上文件标记
                }
            }
            ++i;  // 跳过本行结尾的换行符，指向下一行的首字符

            // 弹栈：栈深超过本行深度，说明那些目录已经离开当前路径
            // popd
            while (!stk.empty() && stk.size() > ident) {  // 只保留深度小于本行深度的祖先目录
                stk.pop();  // 弹出多余的层级
            }

            if (stk.size() > 0) {  // 栈不空说明本行不在根目录，前面还有父路径要拼接
                cur += stk.top() + 1;  // 加上父目录的累计长度和连接用的那一个 '/'
            }

            // 入栈：目录要留给它的子项复用累计长度，文件只更新答案
            // pushd
            if (!isFile) {  // 目录才需要入栈给下一层用
                stk.push(cur);  // 记录该目录的累计绝对路径长度
                continue;  // 目录不参与答案更新，直接处理下一行
            }

            ans = max(ans, cur);  // 本行是文件，用它完整的绝对路径长度更新最大值
        }
        return ans;  // 返回最长文件路径长度；输入里没有文件时就是 0
    }
};