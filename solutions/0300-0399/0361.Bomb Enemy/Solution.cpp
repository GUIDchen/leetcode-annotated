// 题目：361. 轰炸敌人（Bomb Enemy）
// 思路：对每行、每列分别做左→右、右→左、上→下、下→上的扫描，用计数 t 统计两个墙之间的敌人数并累加到 g 上。
// 时间复杂度：O(mn)，四次遍历网格；空间复杂度：O(mn)，辅助计数矩阵。
class Solution {  // LeetCode 题解类
public:  // 对外接口
    int maxKilledEnemies(vector<vector<char>>& grid) {  // grid 由 'W'（墙）、'E'（敌人）、'0'（空地）组成
        int m = grid.size(), n = grid[0].size();  // 行列数
        vector<vector<int>> g(m, vector<int>(n));  // 辅助矩阵：累计每个格子四个方向能炸到的敌人数
        for (int i = 0; i < m; ++i) {  // 逐行处理水平方向
            int t = 0;  // 当前行从左往右的连续敌人数
            for (int j = 0; j < n; ++j) {  // 从左往右扫描
                if (grid[i][j] == 'W')  // 遇到墙
                    t = 0;  // 墙阻断视线，计数清零
                else if (grid[i][j] == 'E')  // 遇到敌人
                    ++t;  // 计数加一
                g[i][j] += t;  // 把左侧能看到的敌人数累加进辅助矩阵
            }  // 左向扫描结束
            t = 0;  // 重置计数，准备从右往左
            for (int j = n - 1; j >= 0; --j) {  // 从右往左扫描
                if (grid[i][j] == 'W')  // 遇到墙
                    t = 0;  // 墙阻断视线，计数清零
                else if (grid[i][j] == 'E')  // 遇到敌人
                    ++t;  // 计数加一
                g[i][j] += t;  // 把右侧能看到的敌人数累加进辅助矩阵
            }  // 右向扫描结束
        }  // 行处理结束
        for (int j = 0; j < n; ++j) {  // 逐列处理竖直方向
            int t = 0;  // 当前列从上往下的连续敌人数
            for (int i = 0; i < m; ++i) {  // 从上往下扫描
                if (grid[i][j] == 'W')  // 遇到墙
                    t = 0;  // 墙阻断视线，计数清零
                else if (grid[i][j] == 'E')  // 遇到敌人
                    ++t;  // 计数加一
                g[i][j] += t;  // 把上方能看到的敌人数累加进辅助矩阵
            }  // 上向扫描结束
            t = 0;  // 重置计数，准备从下往上
            for (int i = m - 1; i >= 0; --i) {  // 从下往上扫描
                if (grid[i][j] == 'W')  // 遇到墙
                    t = 0;  // 墙阻断视线，计数清零
                else if (grid[i][j] == 'E')  // 遇到敌人
                    ++t;  // 计数加一
                g[i][j] += t;  // 把下方能看到的敌人数累加进辅助矩阵
            }  // 下向扫描结束
        }  // 列处理结束
        int ans = 0;  // 记录最大答案
        for (int i = 0; i < m; ++i) {  // 枚举行
            for (int j = 0; j < n; ++j) {  // 枚举列
                if (grid[i][j] == '0') ans = max(ans, g[i][j]);  // 只有空地能放炸弹，用四方向累加值更新答案
            }  // 列枚举结束
        }  // 行枚举结束
        return ans;  // 返回最多能炸死的敌人数
    }  // 方法结束
};  // 题解类结束