// 题目：335. 路径交叉（Self Crossing）
// 核心思路：路径按「上、左、下、右」循环前进，只有当新边与前面的边相交才算自交，共归纳出三种相交形态并逐条判断。
// 时间复杂度：O(n)，只扫描一遍距离数组；空间复杂度：O(n)，复制了一份距离数组（若原地读取则为 O(1)）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isSelfCrossing(vector<int>& distance) {  // distance：每一步的长度，方向按上、左、下、右循环；返回路径是否自交
        vector<int> d = distance;  // 复制一份距离数组，方便按下标就近访问 i-1、i-2 等
        for (int i = 3; i < d.size(); ++i) {  // 从第 4 条边（下标 3）开始检查，因为至少 4 条边才可能相交
            if (d[i] >= d[i - 2] && d[i - 1] <= d[i - 3]) return true;  // 情况一：第 i 条边长度覆盖了第 i-2 条边，且第 i-1 条边没有越出第 i-3 条边，必然相交
            if (i >= 4 && d[i - 1] == d[i - 3] && d[i] + d[i - 4] >= d[i - 2]) return true;  // 情况二：第 i 条边与第 i-3 条边共线相撞（第 i-1 条边正好与第 i-3 条边齐平）
            if (i >= 5 && d[i - 2] >= d[i - 4] && d[i - 1] <= d[i - 3] && d[i] >= d[i - 2] - d[i - 4] && d[i - 1] + d[i - 5] >= d[i - 3]) return true;  // 情况三：绕圈后第 i 条边从内侧穿过第 i-3 条边（需要至少 6 条边）
        }  // for 循环结束
        return false;  // 所有边都检查完毕，没有发现相交
    }  // 方法结束
};  // 类定义结束