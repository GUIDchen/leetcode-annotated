// 题目：343. 整数拆分（Integer Break）
// 思路：动态规划，f[i] 表示把 i 拆分后各因子乘积的最大值；枚举第一部分 j，用 max(f[i-j]*j, (i-j)*j) 更新 f[i]。
// 时间复杂度：O(n^2)，两层循环枚举拆分点；空间复杂度：O(n)，需要长度为 n+1 的 dp 数组。
#define max(a, b) (((a) > (b)) ? (a) : (b))  // 宏定义：用三元运算符取 a、b 中的较大者，参数都加括号避免展开后优先级出错

int integerBreak(int n) {  // n：要拆分的正整数（n >= 2）；返回拆分后各因子乘积的最大值
    int* f = (int*) malloc((n + 1) * sizeof(int));  // 申请 n+1 个 int 作为 dp 数组，让下标 1..n 都能直接使用
    f[1] = 1;  // 边界：1 无法再拆，按定义令 f[1] = 1，供递推使用
    for (int i = 2; i <= n; ++i) {  // 自小到大依次求出 f[2] 到 f[n]
        f[i] = 0;  // 先把 f[i] 置 0，下面用各种拆分方案不断刷新最大值
        for (int j = 1; j < i; ++j) {  // 枚举第一部分 j，即把 i 拆成 j 和 i-j 两段
            f[i] = max(f[i], max(f[i - j] * j, (i - j) * j));  // 两种方案取大：i-j 继续拆是 f[i-j]*j，(i-j) 不再拆是 (i-j)*j；再与已有的 f[i] 比较保留最优
        }  // 内层枚举结束
    }  // 外层枚举结束
    return f[n];  // 返回整数 n 拆分后的最大乘积
}  // 函数结束