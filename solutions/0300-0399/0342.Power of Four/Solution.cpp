// 题目：342. 4的幂（Power of Four）
// 思路：4 的幂必须同时满足三个条件——大于 0、二进制只有一个 1（即 2 的幂）、且这个 1 落在偶数位上。
// 时间复杂度：O(1)，只做几次位运算；空间复杂度：O(1)，不使用额外存储。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool isPowerOfFour(int n) {  // n：待判断的整数；返回 n 是否为 4 的幂
        return n > 0 && (n & (n - 1)) == 0 && (n & 0xaaaaaaaa) == 0;  // 三个条件同时成立才算：n>0 保证正数；(n&(n-1))==0 说明二进制只有一个 1（2 的幂）；0xaaaaaaaa 是奇数位全 1 的掩码，与它按位与为 0 说明那个 1 在偶数位上
    }  // 方法体结束
};  // 类定义结束