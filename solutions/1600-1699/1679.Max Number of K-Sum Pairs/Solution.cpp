// 题目：1679. K 和数对的最大数目（Max Number of K-Sum Pairs）
// 思路：先排序，再用左右双指针从两端逼近；两数之和等于 k 就配对并同时内移，和偏大就让右指针左移，和偏小就让左指针右移。
// 时间复杂度：O(n log n)，排序主导，双指针扫描为 O(n)；空间复杂度：O(1)，只用常数个变量（排序自身的栈空间另计）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxOperations(vector<int>& nums, int k) {  // nums：整数数组；k：目标和；返回最多能凑出的数对数目
        sort(nums.begin(), nums.end());  // 先排序，数组递增后才可以用双指针从两端向中间收缩
        int cnt = 0;  // cnt 记录已经成功配对的数对数目
        int i = 0, j = nums.size() - 1;  // 左指针指向最小值，右指针指向最大值
        while (i < j) {  // 两指针还没相遇，就继续尝试配对
            if (nums[i] + nums[j] == k) {  // 两数之和恰好等于 k，说明这两个数可以配成一对
                i++;  // 左指针右移，换用更大的数
                j--;  // 右指针左移，换用更小的数
                cnt++;  // 数对数目加一
            } else if (nums[i] + nums[j] > k) {  // 和太大，需要减小，于是右指针左移
                j--;  // 右指针左移，让下一轮的和变小
            } else {  // 和太小，需要增大，于是左指针右移
                i++;  // 左指针右移，让下一轮的和变大
            }
        }
        return cnt;  // 返回最多能凑出的数对数目
    }
};  // 题解类结束