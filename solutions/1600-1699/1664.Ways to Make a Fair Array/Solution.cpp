// 题目：1664. 生成平衡数组的方案数（Ways to Make a Fair Array）
// 思路：先算出原数组偶数下标和 s1、奇数下标和 s2，再从左到右枚举删除位置，用前缀和推算删后两侧的新奇偶和。
// 时间复杂度：O(n)，两次线性扫描；空间复杂度：O(1)，只用常数个累加变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int waysToMakeFair(vector<int>& nums) {  // nums：输入数组；返回删除恰好一个元素后「平衡」的方案数
        int s1 = 0, s2 = 0;  // s1 存偶数下标元素之和，s2 存奇数下标元素之和
        int n = nums.size();  // 数组长度，避免重复调用 size()
        for (int i = 0; i < n; ++i) {  // 先整体统计一遍奇偶下标和
            s1 += i % 2 == 0 ? nums[i] : 0;  // 下标为偶数时累加到 s1，否则加 0
            s2 += i % 2 == 1 ? nums[i] : 0;  // 下标为奇数时累加到 s2，否则加 0
        }  // 预处理循环结束
        int t1 = 0, t2 = 0;  // t1/t2 是删除位置之前（左侧）的偶/奇下标和前缀
        int ans = 0;  // ans 记录满足条件的删除方案数
        for (int i = 0; i < n; ++i) {  // 枚举要删除的下标 i
            int v = nums[i];  // v 是当前被删除的元素
            ans += i % 2 == 0 && t2 + s1 - t1 - v == t1 + s2 - t2;  // i 为偶数时：删后左侧偶数下标 t1、左侧奇数 t2 不变；右侧整体左移一位，奇偶互换
            ans += i % 2 == 1 && t2 + s1 - t1 == t1 + s2 - t2 - v;  // i 为奇数时同理，只是被删的 v 从奇数侧扣除
            t1 += i % 2 == 0 ? v : 0;  // 把 v 累加进左侧偶数下标和（若 i 为偶数）
            t2 += i % 2 == 1 ? v : 0;  // 把 v 累加进左侧奇数下标和（若 i 为奇数）
        }  // 枚举结束
        return ans;  // 返回方案总数
    }  // 方法结束
};  // 类定义结束