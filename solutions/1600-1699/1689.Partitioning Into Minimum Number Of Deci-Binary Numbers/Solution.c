// 题目：1689. 十-二进制数的最少数目（Partitioning Into Minimum Number Of Deci-Binary Numbers）
// 思路：每个十-二进制数的每一位非 0 即 1，所以数字串中最大的那一位决定了最少需要的数的个数。
// 时间复杂度：O(n)，扫描一遍字符串；空间复杂度：O(1)，只用两个整型变量。
int minPartitions(char* n) {  // n：十进制数字串（判题器直接调用，无需 main）
    int ans = 0;  // ans 记录出现过的最大数字，初值为 0
    for (int i = 0; n[i]; i++) {  // 逐位扫描，直到字符串结尾的 '\0'
        int v = n[i] - '0';  // 字符数字减去 '0' 转成对应的整数值
        if (v > ans) {  // 出现更大的数字就更新答案
            ans = v;  // 更新当前最大值
        }  // 比较分支结束
    }  // 扫描循环结束
    return ans;  // 最大数字就是最少需要的十-二进制数个数
}  // 函数结束