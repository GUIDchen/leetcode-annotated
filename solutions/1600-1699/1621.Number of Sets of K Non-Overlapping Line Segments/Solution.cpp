// 题目：1621. 大小为 K 的不重叠线段的数目（Number of Sets of K Non-Overlapping Line Segments）
// 思路：线性 DP，f[i][j] 表示点 i 是最后一条线段右端点、共选 j 条线段的方案数，g[i][j] 表示点 i 不是右端点的方案数，逐点向右扩展转移。
// 时间复杂度：O(n·k)，两层循环各遍历一遍；空间复杂度：O(n·k)，需要两张二维 DP 表。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberOfSets(int n, int k) {  // n：可用点的个数（坐标为 0..n-1），k：要选出的不重叠线段数
        const int mod = 1e9 + 7;  // 取模常量，避免方案数溢出 int 范围
        vector<vector<int>> f(n + 1, vector<int>(k + 1));  // f[i][j]：以点 i 作为最后一条线段右端点、共选 j 条线段的方案数
        vector<vector<int>> g(n + 1, vector<int>(k + 1));  // g[i][j]：点 i 不作为任何线段右端点、共选 j 条线段的方案数
        f[1][0] = 1;  // 边界：只有 0 号点时，把 0 号点看作「虚拟右端点」，0 条线段算 1 种方案
        for (int i = 2; i <= n; ++i) {  // 从 1 号点开始向右扩展，i 是当前考虑的最右端点位置
            for (int j = 0; j <= k; ++j) {  // 枚举已经选出的线段条数 j
                f[i][j] = (f[i - 1][j] + g[i - 1][j]) % mod;  // 点 i 作右端点：要么把原来的线段延长到 i，要么从 i-1 处新开一条线段
                g[i][j] = g[i - 1][j];  // 点 i 不作右端点：先继承 i-1 的方案，即点 i 被跳过不使用
                if (j) {  // 只有至少选过一条线段（j > 0）时，才可能在 i-1 处「开始新线段」
                    g[i][j] = (g[i][j] + f[i - 1][j - 1]) % mod;  // 上一点是右端点时，新开的第 j 条线段从 i-1 起，且还要向右延伸，故 i 不是右端点
                    g[i][j] = (g[i][j] + g[i - 1][j - 1]) % mod;  // 上一点不是右端点时，同样可以从 i-1 起再开一条线段
                }  // if (j) 分支结束
            }  // 内层 j 循环结束
        }  // 外层 i 循环结束
        return (f[n][k] + g[n][k]) % mod;  // 最后一条线段可能以 n-1 为右端点，也可能不是，两种状态相加即答案
    }  // 方法结束
};  // 类定义结束
