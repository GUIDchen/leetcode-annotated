// 题目：1695. 删除子数组的最大得分（Maximum Erasure Value）
// 思路：滑动窗口 + 前缀和。窗口内元素必须互不相同，用数组 d 记录每个值上次出现的下标 1 位置，左端点 j 只会单调右移。
// 时间复杂度：O(n)，每个元素至多进出窗口各一次；空间复杂度：O(V)，d 的大小取决于 nums[i] 的取值上界 V。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maximumUniqueSubarray(vector<int>& nums) {  // nums：可以删除的子数组所在的输入数组
        int d[10001]{};  // d[v]：值 v 上一次出现的「右端点下标 + 1」，0 表示从未出现
        int n = nums.size();  // 数组长度
        int s[n + 1];  // 前缀和：s[i] = nums[0] + ... + nums[i-1]
        s[0] = 0;  // 空前缀的和为 0，作为边界
        for (int i = 0; i < n; ++i) {  // 一次遍历构造前缀和数组
            s[i + 1] = s[i] + nums[i];  // 在前一个前缀和上累加当前元素
        }
        int ans = 0, j = 0;  // ans：最大得分；j：当前合法窗口的左端点（下标从 0 开始）
        for (int i = 1; i <= n; ++i) {  // i 是窗口右端点的 1 基下标，逐步向右扩展
            int v = nums[i - 1];  // 刚刚并入窗口的元素值
            j = max(j, d[v]);  // 若 v 之前出现过，窗口左端点必须跳过它的上一次出现位置
            ans = max(ans, s[i] - s[j]);  // 用前缀和 O(1) 算出当前窗口和，并更新答案
            d[v] = i;  // 记录 v 本次出现的位置，供后面重复时收缩窗口使用
        }
        return ans;  // 返回所有无重复元素连续子数组中的最大和
    }
};