// 题目：1641. 统计字典序元音字符串的数目（Count Sorted Vowel Strings）
// 思路：记忆化搜索，dfs(i, j) 表示「已选 i 个字符、下一个元音最小下标为 j」的方案数，枚举下一个元音累加后缓存。
// 时间复杂度：O(n·5·5)，共 n×5 个状态、每个状态最多 5 次转移；空间复杂度：O(n·5)，记忆化表大小。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外开放
    int countVowelStrings(int n) {  // n：目标字符串长度，返回长度为 n 的字典序元音字符串个数
        int f[n][5];  // 记忆化表：f[i][j] 表示已选 i 个字符、下一个字符最小元音下标为 j 时的方案数
        memset(f, 0, sizeof f);  // 全部清零，0 表示「尚未计算」（真实方案数至少为 1，不会与 0 冲突）
        function<int(int, int)> dfs = [&](int i, int j) {  // 递归函数：i 是已选字符数，j 是下一个元音的最小下标（保证字母序不降）
            if (i >= n) {  // 已经选满 n 个字符，得到一个合法字符串
                return 1;  // 空后缀视作 1 种方案
            }  // 递归边界处理结束
            if (f[i][j]) {  // 该状态已经算过，直接复用缓存
                return f[i][j];  // 返回缓存值，避免重复计算
            }  // 缓存命中分支结束
            int ans = 0;  // ans 累计当前状态的所有方案数
            for (int k = j; k < 5; ++k) {  // 枚举下一个元音 k，从 j 开始保证字母序不降
                ans += dfs(i + 1, k);  // 选定 k 之后继续往后选
            }  // 枚举结束
            return f[i][j] = ans;  // 把答案写入记忆化表并返回
        };  // lambda 定义结束
        return dfs(0, 0);  // 从「一个字符都没选、下一个元音从 a 开始」出发
    }  // 方法结束
};  // 类定义结束