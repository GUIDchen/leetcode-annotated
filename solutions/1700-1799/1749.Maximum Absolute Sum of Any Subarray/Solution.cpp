// 题目：1749. 任意子数组和的绝对值的最大值（Maximum Absolute Sum of Any Subarray）
// 核心思路：子数组和的绝对值最大，只可能来自「最大的子数组和」或「最小的子数组和」，于是用两个 Kadane 状态分别维护以当前元素结尾的最大和 f 与最小和 g，答案取 max(f, |g|)。
// 时间复杂度：O(n)，一次遍历；空间复杂度：O(1)，只使用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxAbsoluteSum(vector<int>& nums) {  // nums：输入数组；返回：任意子数组和的绝对值的最大值
        int f = 0, g = 0;  // f：以当前位置结尾的最大子数组和；g：以当前位置结尾的最小子数组和
        int ans = 0;  // 空子数组的和为 0，所以答案从 0 开始就足够
        for (int& x : nums) {  // 从左到右枚举区间的右端点
            f = max(f, 0) + x;  // 最大和：前缀为负就丢弃，从 x 重新开始，因此取 max(f, 0) 再加 x
            g = min(g, 0) + x;  // 最小和：前缀为正就丢弃，从 x 重新开始，因此取 min(g, 0) 再加 x
            ans = max({ans, f, abs(g)});  // 当前结尾的最大和与最小和的绝对值都可能是答案，一起刷新
        }  // 右端点枚举结束
        return ans;  // 返回最大的绝对值
    }  // 方法结束
};  // 题解类结束