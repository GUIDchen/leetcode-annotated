// 题目：1736. 替换隐藏数字得到的最晚时间（Latest Time by Replacing Hidden Digits）
// 思路：按 HH:MM 从高位到低位贪心：小时十位看个位是否不小于 4 来决定取 1 还是 2，小时个位看十位是否为 2 来决定取 3 还是 9，分钟位固定取 5 与 9。
// 时间复杂度：O(1)，只做常数次字符判断；空间复杂度：O(1)，原地修改原字符串后返回。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    string maximumTime(string time) {  // time 形如 "??:??"，'?' 表示被隐藏的数字
        if (time[0] == '?') {  // 小时的十位待填
            time[0] = (time[1] >= '4' && time[1] <= '9') ? '1' : '2';  // 个位是 4~9 时小时最大只能是 19，否则可以取 2x
        }
        if (time[1] == '?') {  // 小时的个位待填
            time[1] = (time[0] == '2') ? '3' : '9';  // 十位已是 2 则小时最多 23，否则可以取 x9
        }
        if (time[3] == '?') {  // 分钟的十位待填
            time[3] = '5';  // 分钟十位最大是 5
        }
        if (time[4] == '?') {  // 分钟的个位待填
            time[4] = '9';  // 分钟个位最大是 9
        }
        return time;  // 返回填好的最晚时间
    }
};