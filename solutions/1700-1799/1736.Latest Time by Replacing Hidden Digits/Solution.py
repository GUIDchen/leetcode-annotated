# 题目：1736. 替换隐藏数字得到的最晚时间（Latest Time by Replacing Hidden Digits）
# 思路：把字符串转成列表逐位贪心填最大的数字：小时十位看个位是否不小于 4 决定取 1 还是 2，小时个位看十位是否为 2 决定取 3 还是 9，分钟位固定取 5 与 9。
# 时间复杂度：O(1)，只做常数次判断；空间复杂度：O(1)，额外一个长度固定的列表。
class Solution:  # LeetCode 约定的题解类
    def maximumTime(self, time: str) -> str:  # time 形如 "??:??"，'?' 是隐藏位
        t = list(time)  # 转成列表，方便按下标原地修改字符
        if t[0] == '?':  # 小时的十位待填
            t[0] = '1' if '4' <= t[1] <= '9' else '2'  # 个位不小于 4 时小时最多 19，否则可填 2x
        if t[1] == '?':  # 小时的个位待填
            t[1] = '3' if t[0] == '2' else '9'  # 十位为 2 则最多 23，否则可填 x9
        if t[3] == '?':  # 分钟的十位待填
            t[3] = '5'  # 分钟十位最大为 5
        if t[4] == '?':  # 分钟的个位待填
            t[4] = '9'  # 分钟个位最大为 9
        return ''.join(t)  # 拼回字符串返回
