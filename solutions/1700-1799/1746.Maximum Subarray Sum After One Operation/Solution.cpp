// 题目：1746. 经过一次操作后的最大子数组和（Maximum Subarray Sum After One Operation）
// 核心思路：线性 DP，用 f 记录「以当前元素结尾且尚未使用平方操作」的最大和，用 g 记录「已经使用过平方操作」的最大和，每轮在「现在把 x 平方」与「沿用它处已经用过的操作」之间取较大者。
// 时间复杂度：O(n)，只遍历数组一次；空间复杂度：O(1)，只使用常数个额外变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maxSumAfterOperation(vector<int>& nums) {  // nums：输入数组；返回：最多把一个元素改成它的平方后能取到的最大子数组和
        int f = 0, g = 0;  // f：以当前位置结尾、还没用过平方操作的最大和；g：已经用过平方操作的最大和
        int ans = INT_MIN;  // 答案先取最小整数，保证数组全为负数时也能被正常更新
        for (int x : nums) {  // 从左到右枚举区间的右端点
            int ff = max(f, 0) + x;  // 不用平方操作：前缀和为负时不如从 x 重新开始，所以取 max(f, 0) 再加 x
            int gg = max(max(f, 0) + x * x, g + x);  // 用平方操作：要么之前没用、现在把 x 平方（max(f,0)+x*x），要么之前已用过、直接接上 x（g+x）
            f = ff;  // 先算出 ff 再赋值，避免本轮新值污染另一状态的推导
            g = gg;  // g 的新值同样已在上面算好，这里只做滚动覆盖
            ans = max({ans, f, g});  // 用两种结尾状态中最优的一个刷新全局答案
        }  // 右端点枚举结束
        return ans;  // 返回全局最大值
    }  // 方法结束
};  // 题解类结束