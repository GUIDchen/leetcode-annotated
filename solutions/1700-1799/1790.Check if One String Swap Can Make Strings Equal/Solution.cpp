// 题目：1790. 仅执行一次字符串交换能否使两个字符串相等（Check if One String Swap Can Make Strings Equal）
// 思路：边遍历边统计不同位置并缓存最近一处的两个字符，若超过两处或第二处不满足交叉相等就失败；最后只剩「仅一处不同」这种无解情况。
// 时间复杂度：O(n)，一次线性扫描；空间复杂度：O(1)，只用常数个计数器与字符变量。
class Solution {
public:
    bool areAlmostEqual(string s1, string s2) {  // 主函数：判断能否只交换 s1 中的一对字符就使两串相等
        int cnt = 0;  // 统计字符不同的位置个数
        char c1 = 0, c2 = 0;  // 记录最近一处不同位置上 s1、s2 各自的字符，用于交叉校验
        for (int i = 0; i < s1.size(); ++i) {  // 逐位比较两个字符串
            char a = s1[i], b = s2[i];  // 取出同一下标处的两个字符
            if (a != b) {  // 该位置字符不同
                if (++cnt > 2 || (cnt == 2 && (a != c2 || b != c1))) {  // 不同位置超过 2 处，或第 2 处与第 1 处不能交叉配对（a 必须等于上一个 b、b 必须等于上一个 a），都无解
                    return false;  // 不满足一次交换可修复的条件，直接返回假
                }
                c1 = a, c2 = b;  // 记住这一处的两个字符，供下一处交叉校验
            }
        }
        return cnt != 1;  // 不同位置数为 0 或 2 时可行；只剩 1 处不同无法靠一次交换修复
    }  // 函数结束
};  // 题解类定义结束