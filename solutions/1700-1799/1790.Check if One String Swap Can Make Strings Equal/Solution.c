// 题目：1790. 仅执行一次字符串交换能否使两个字符串相等（Check if One String Swap Can Make Strings Equal）
// 思路：逐位比较，记录不同的位置：没有不同则已相等；恰好两个不同且交叉相等才可一次交换修复；超过两个或只有一个不同都无解。
// 时间复杂度：O(n)，只扫描一遍字符串；空间复杂度：O(1)，仅用几个下标变量。
bool areAlmostEqual(char* s1, char* s2) {  // 判题片段，无需 main；strlen 由判题器提供的头文件声明
    int n = strlen(s1);  // 两个字符串等长，取第一个串的长度即可
    int i1 = -1;  // 第一处不同字符的下标，-1 表示还没遇到
    int i2 = -1;  // 第二处不同字符的下标，-1 表示还没遇到
    for (int i = 0; i < n; i++) {  // 逐位比较两个字符串
        if (s1[i] != s2[i]) {  // 当前位置字符不同
            if (i1 == -1) {  // 这是第一处不同
                i1 = i;  // 记下第一个不同位置
            } else if (i2 == -1) {  // 这是第二处不同
                i2 = i;  // 记下第二个不同位置
            } else {  // 出现了第三处不同
                return 0;  // 一次交换最多修复两处，直接返回不可能
            }
        }
    }
    if (i1 == -1 && i2 == -1) {  // 完全没有不同位置
        return 1;  // 两串已经相等，交换任意两个相同字符即可（等价于不交换）
    }
    if (i1 == -1 || i2 == -1) {  // 只有一处不同
        return 0;  // 一处不同无法通过交换修复，返回不可能
    }
    return s1[i1] == s2[i2] && s1[i2] == s2[i1];  // 恰好两处不同：交换后要相等，必须交叉相等 s1[i1]==s2[i2] 且 s1[i2]==s2[i1]
}  // 函数结束