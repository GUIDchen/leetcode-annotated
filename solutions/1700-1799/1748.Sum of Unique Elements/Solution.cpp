// 题目：1748. 唯一元素的和（Sum of Unique Elements）
// 核心思路：题目限定元素取值在 1 到 100 之间，用一个长度 101 的计数数组统计出现次数，再遍历所有取值把恰好出现一次的取值累加。
// 时间复杂度：O(n + 100)，n 为数组长度；空间复杂度：O(1)，计数数组大小固定为 101。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int sumOfUnique(vector<int>& nums) {  // nums：输入数组；返回：所有只出现一次的元素之和
        int cnt[101]{};  // 计数数组，下标就是元素值；{} 保证全部初始化为 0（取值不超过 100）
        for (int& x : nums) {  // 第一遍遍历：统计每个取值的出现次数
            ++cnt[x];  // 当前元素计数加一
        }  // 计数结束
        int ans = 0;  // 累加结果（唯一元素之和）
        for (int x = 0; x < 101; ++x) {  // 第二遍遍历所有可能的取值，0 不会被累加因此可以从 0 开始
            if (cnt[x] == 1) {  // 恰好出现一次才是「唯一元素」
                ans += x;  // 累加该取值
            }  // 判断结束
        }  // 取值遍历结束
        return ans;  // 返回唯一元素之和
    }  // 方法结束
};  // 题解类结束