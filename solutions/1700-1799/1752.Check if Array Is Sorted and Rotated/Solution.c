// 题目：1752. 检查数组是否经排序和轮转得到（Check if Array Is Sorted and Rotated）
// 核心思路：把数组看成一个环，统计「后一个元素比当前元素小」的下降位置个数；排序后再轮转得到的数组最多只允许出现一次下降。
// 时间复杂度：O(n)，一次遍历；空间复杂度：O(1)，只使用一个计数器。
bool check(int* nums, int numsSize) {  // nums：输入数组；numsSize：数组长度；返回是否为排序后轮转的结果
    int cnt = 0;  // 下降点计数：环上相邻逆序的次数
    for (int i = 0; i < numsSize; i++) {  // 遍历每个位置，与它的下一个位置比较
        if (nums[i] > nums[(i + 1) % numsSize]) {  // 取模让最后一个元素与第一个元素比较，从而把数组首尾连成环
            cnt++;  // 出现一次下降
        }  // if 判断结束
    }  // 循环结束
    return cnt <= 1;  // 下降点不超过 1 个才可能是排序数组的轮转
}  // 函数结束