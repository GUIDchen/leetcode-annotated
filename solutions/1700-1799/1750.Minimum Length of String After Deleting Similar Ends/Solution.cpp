// 题目：1750. 删除字符串两端相同字符后的最短长度（Minimum Length of String After Deleting Similar Ends）
// 核心思路：双指针 i、j 从两端向中间夹，只要 s[i] == s[j] 就把两端各自的整段同字符一起删掉（跳过整段再各自内移一格），直到两端字符不同或指针相遇。
// 时间复杂度：O(n)，i 与 j 合计最多走完整个字符串；空间复杂度：O(1)，只使用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumLength(string s) {  // s：输入字符串；返回删除两端相同字符后能得到的最短长度
        int i = 0, j = s.size() - 1;  // i 指向未删除部分的首字符，j 指向末字符
        while (i < j && s[i] == s[j]) {  // 两端字符相同才允许继续删除
            while (i + 1 < j && s[i] == s[i + 1]) {  // 跳过左端与 s[i] 相同的整段字符，只保留最后一个位置
                ++i;  // 左指针右移
            }  // 左端整段定位完成
            while (i < j - 1 && s[j] == s[j - 1]) {  // 跳过右端与 s[j] 相同的整段字符，只保留最前一个位置
                --j;  // 右指针左移
            }  // 右端整段定位完成
            ++i;  // 删除左端这一整段
            --j;  // 删除右端这一整段
        }  // 检查新的两端是否仍然相同
        return max(0, j - i + 1);  // 指针交叉时长度会算成负数，用 0 兜底
    }  // 方法结束
};  // 题解类结束