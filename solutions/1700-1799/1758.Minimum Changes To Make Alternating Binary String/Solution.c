// 题目：1758. 生成交替二进制字符串的最少操作数（Minimum Changes To Make Alternating Binary String）
// 思路：交替串只有两种可能（"0101..." 或 "1010..."），先统计与 "0101..." 不同的位数 cnt，答案就是 min(cnt, n-cnt)。
// 时间复杂度：O(n)，只需一次线性扫描；空间复杂度：O(1)，只用几个计数变量。
int minOperations(char* s) {  // s 是给定的二进制字符串
    int cnt = 0;  // 统计按 "0101..." 模式需要翻转的字符个数
    int n = strlen(s);  // 字符串长度，另一种模式 "1010..." 的代价就是 n - cnt
    for (int i = 0; i < n; ++i) {  // 逐位扫描字符串
        if (s[i] != "01"[i & 1]) {  // 用 i 的奇偶性从字面量 "01" 中取期望字符：偶数位 '0'、奇数位 '1'
            ++cnt;  // 与 "0101..." 不一致，说明这一位需要改，计数加一
        }
    }
    return cnt < (n - cnt) ? cnt : (n - cnt);  // 两种交替模式取代价更小的那个
}
