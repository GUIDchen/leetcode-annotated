// 题目：1706. 球会落何处（Where Will the Ball Fall）
// 思路：对每个球做一次向下搜索；每层先判断撞墙与两块挡板相对形成的 V/∧ 夹口，没卡住就沿挡板方向进入下一层，走到第 m 层即为出口列。
// 时间复杂度：O(m × n)，每个球最多走 m 层；空间复杂度：O(m)，递归调用栈深度。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    vector<int> findBall(vector<vector<int>>& grid) {  // grid：n 列挡板网格，1 表示向右下引导、-1 表示向左下引导
        int m = grid.size(), n = grid[0].size();  // m 是层数（行数），n 是每层的列数
        vector<int> ans(n);  // 答案数组：ans[j] 记录第 j 个球最终掉出的列号
        function<int(int, int)> dfs = [&](int i, int j) {  // dfs(i, j)：球位于第 i 层第 j 列，返回最终掉出的列号，卡住则返回 -1
            if (i == m) {  // 球已经越过最后一层，说明顺利掉出
                return j;  // 当前列就是掉出的列号
            }  // 本层判断结束
            if (j == 0 && grid[i][j] == -1) {  // 在第 0 列且挡板朝左，球被左边墙挡住
                return -1;  // 卡住，按题意返回 -1
            }  // 本层判断结束
            if (j == n - 1 && grid[i][j] == 1) {  // 在最右列且挡板朝右，球被右边墙挡住
                return -1;  // 卡住，按题意返回 -1
            }  // 本层判断结束
            if (grid[i][j] == 1 && grid[i][j + 1] == -1) {  // 当前挡板朝右而右邻挡板朝左，两块板形成 V 形夹口，球落不下去
                return -1;  // 球被夹住，返回 -1
            }  // 本层判断结束
            if (grid[i][j] == -1 && grid[i][j - 1] == 1) {  // 当前挡板朝左而左邻挡板朝右，两块板形成 ∧ 形夹口，球落不下去
                return -1;  // 球被夹住，返回 -1
            }  // 本层判断结束
            return grid[i][j] == 1 ? dfs(i + 1, j + 1) : dfs(i + 1, j - 1);  // 挡板朝右则下一层列号 +1，朝左则 -1，继续递归
        };  // lambda 定义结束
        for (int j = 0; j < n; ++j) {  // 枚举每个球从顶部各列落下的情况
            ans[j] = dfs(0, j);  // 记录第 j 个球的最终列号（-1 表示卡住）
        }  // 本列处理结束
        return ans;  // 返回所有球的落点数组
    }  // 方法结束
};  // 类定义结束