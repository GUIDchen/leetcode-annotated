// 题目：1759. 统计同质子字符串的数目（Count Number of Homogenous Substrings）
// 思路：滑动窗口。每一段连续相同字符的长度为 L 时，该段贡献 L*(L+1)/2 个同质子串，逐段累加并取模。
// 时间复杂度：O(n)，一趟扫描；空间复杂度：O(1)，只用了常数个变量。
int countHomogenous(char* s) {  // 返回同质子字符串的数目（对 1e9+7 取模）
    int MOD = 1e9 + 7;  // 题目要求的取模常数
    int ans = 0;  // 累计答案
    for (int i = 0, j = 0; s[j]; j++) {  // i 是当前连续段的起点，j 是扫描指针，遇到 '\0' 结束
        if (s[i] != s[j]) {  // 字符发生变化，说明上一段连续区结束了
            i = j;  // 把段起点移动到新字符处，开始新的一段
        }
        ans = (ans + j - i + 1) % MOD;  // 以 j 结尾的同质子串长度为 1..j-i+1，共 j-i+1 个，累加后取模
    }
    return ans;  // 返回总数目
}