// 题目：1753. 移除石子的最大得分（Maximum Score From Removing Stones）
// 思路：每轮从当前最多的两堆中各取一颗石子，循环到第二多的那一堆为空；用长度为 3 的数组排序模拟。
// 时间复杂度：O(n)，n = a + b + c，每轮石子总数至少减少 2；空间复杂度：O(1)，只用一个长度为 3 的数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int maximumScore(int a, int b, int c) {  // a、b、c 为三堆石子的初始个数
        vector<int> s = {a, b, c};  // 把三堆放进数组，便于排序后直接取最大的两堆
        sort(s.begin(), s.end());  // 升序排序：s[0] 最小、s[2] 最大
        int ans = 0;  // 累计得分，也就是成功执行了多少次操作
        while (s[1]) {  // 第二大的堆还有石子，说明至少有两堆非空，可以继续取
            ++ans;  // 本次操作得 1 分
            s[1]--;  // 从第二大的堆里取走一颗石子
            s[2]--;  // 从最大的堆里取走一颗石子（两堆必须是不同的堆）
            sort(s.begin(), s.end());  // 取完重新排序，保证下一轮 s[1]、s[2] 仍是最大的两堆
        }
        return ans;  // 不能再操作时，累计分数就是最大得分
    }
};