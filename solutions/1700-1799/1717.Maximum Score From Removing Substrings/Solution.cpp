// 题目：1717. 删除子字符串的最大得分（Maximum Score From Removing Substrings）
// 思路：贪心。先删除得分更高的组合：扫描时用计数器攒住该组合的首字符，遇到次字符立即配对；遇到其他字符则把段内两侧剩余字符按低分组合配对。交换 x、y 以保证 x 始终是高分组合。
// 时间复杂度：O(n)；空间复杂度：O(1)。
class Solution {
public:
    int maximumGain(string s, int x, int y) {  // s：原始字符串；x：删除 "ab" 的得分；y：删除 "ba" 的得分
        char a = 'a', b = 'b';  // a、b 记录「先删除哪种组合」，其中 a 是高价值组合的首字符
        if (x < y) {  // 若 ab 的得分不是更高
            swap(x, y);  // 交换得分，让 x 始终对应高分组合
            swap(a, b);  // 同时交换组合中的字符顺序，保证逻辑不用改动
        }

        int ans = 0, cnt1 = 0, cnt2 = 0;  // ans：总得分；cnt1：待配对的首字符个数；cnt2：另一字符（只能用于低分组合）的个数
        for (char c : s) {  // 逐字符扫描字符串
            if (c == a) {  // 遇到高价值组合的首字符
                cnt1++;  // 先攒着，等后面出现次字符时配对
            } else if (c == b) {  // 遇到高价值组合的次字符
                if (cnt1) {  // 前面有可配对的首字符，立即配对（得分最高，贪心正确）
                    ans += x;  // 加上高价值组合的得分
                    cnt1--;  // 消耗一个首字符
                } else {  // 前面没有可配对的首字符
                    cnt2++;  // 只能攒着，留给低价值组合
                }
            } else {  // 其他字符把字符串切成若干段，跨段无法配对
                ans += min(cnt1, cnt2) * y;  // 段内剩余首字符与次字符按低价值组合两两配对
                cnt1 = 0;  // 清空首字符计数，开始统计下一段
                cnt2 = 0;  // 清空次字符计数，开始统计下一段
            }
        }
        ans += min(cnt1, cnt2) * y;  // 最后一段也可能残留可配对的字符
        return ans;  // 返回总得分
    }
};