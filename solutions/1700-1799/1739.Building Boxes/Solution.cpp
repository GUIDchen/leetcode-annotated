// 题目：1739. 放置盒子（Building Boxes）
// 思路：先贪心堆满一层层完整的“金字塔”（第 k 层需要 k*(k+1)/2 个盒子），剩下的盒子再沿底层边缘逐个补放，每个只让底面积增加 1。
// 时间复杂度：O(n^(1/3))，堆整层的循环约 n 的立方根次、补盒子的循环不超过底边长度；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumBoxes(int n) {  // n：需要放下的盒子总数，返回最少需要的底面积（底层格子数）
        int s = 0, k = 1;  // s：已经堆好的盒子数；k：正在尝试的层号（从顶部往下数第 k 层）
        while (s + k * (k + 1) / 2 <= n) {  // 第 k 层是边长为 k 的三角形，需 k*(k+1)/2 个盒子，装得下就整层放下
            s += k * (k + 1) / 2;  // 把这一整层的盒子累加进已放置数量
            ++k;  // 层号加一，继续尝试下一层
        }
        --k;  // 循环结束时 k 是第一个放不下的层，减一后正好等于已放满的完整层数
        int ans = k * (k + 1) / 2;  // 完整金字塔的底面积：底层是边长 k 的三角形，共 k*(k+1)/2 个格子
        k = 1;  // 复用 k，改成第二阶段“这是第几个补在底层边缘的盒子”的计数
        while (s < n) {  // 还有盒子没放下，就继续在底层边缘补放
            ++ans;  // 每补一个盒子，底面积只增加 1 个格子
            s += k;  // 但顺着它能往上多叠 k 个盒子，所以已放置总数增加 k
            ++k;  // 下一个补位盒子能叠得更高，增量随之加一
        }
        return ans;  // 返回最少需要的底面积
    }
};