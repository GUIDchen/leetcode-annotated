// 题目：801. 使序列递增的最小交换次数（Minimum Swaps To Make Sequences Increasing）
// 思路：动态规划，a 表示处理到当前位且「本位不交换」的最少次数，b 表示「本位交换」的最少次数，按相邻两列是否已严格递增分情况转移。
// 时间复杂度：O(n)，只扫一遍数组；空间复杂度：O(1)，只用了常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minSwap(vector<int>& nums1, vector<int>& nums2) {  // nums1、nums2：两个等长数组；返回最少交换次数
        int a = 0, b = 1, n = nums1.size();  // a：第 0 位不交换的次数；b：第 0 位交换的次数（代价 1）；n：数组长度
        for (int i = 1; i < n; ++i) {  // 从第 2 个位置（下标 1）开始向右推进
            int x = a, y = b;  // 暂存上一列的两个状态，因为转移要同时用到它们的旧值
            if (nums1[i - 1] >= nums1[i] || nums2[i - 1] >= nums2[i]) {  // 不交换时相邻两列已不严格递增，说明必须靠交换解决
                a = y, b = x + 1;  // 当前不换 ⇐ 上一列换；当前换 ⇐ 上一列不换再换一次
            } else {  // 不交换本身是合法的，还有第二种选择
                b = y + 1;  // 当前换：在上一列已换的基础上再换一次，代价加 1
                if (nums1[i - 1] < nums2[i] && nums2[i - 1] < nums1[i]) {  // 交叉比较也成立，说明换与不换可以自由切换
                    a = min(a, y);  // 当前不换可继承上一列换的状态，两者取较小值
                    b = min(b, x + 1);  // 当前换也可继承上一列不换再换一次，两者取较小值
                }  // 交叉条件分支结束
            }  // 是否必须交换的分支结束
        }  // 遍历结束
        return min(a, b);  // 最后一位换或不交换，取更优的那个
    }  // 方法结束
};  // 类定义结束