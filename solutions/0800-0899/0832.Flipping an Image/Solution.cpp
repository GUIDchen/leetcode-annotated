// 题目：832. 翻转图像（Flipping an Image）
// 思路：先水平翻转再取反，等价于对每一行用双指针：两个位置值相同就都取反，不同就都不动；正中间那个元素单独取反。
// 时间复杂度：O(n^2)，每个元素处理一次；空间复杂度：O(1)，直接原地修改。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    vector<vector<int>> flipAndInvertImage(vector<vector<int>>& image) {  // image 是 0/1 矩阵，返回水平翻转并取反后的矩阵（原地修改）
        for (auto& row : image) {  // 逐行处理，用引用避免拷贝整行
            int i = 0, j = row.size() - 1;  // 双指针：i 从行首、j 从行尾向中间靠拢
            for (; i < j; ++i, --j) {  // 循环头沿用外层已声明的 i、j：每轮把 i 后移、j 前移
                if (row[i] == row[j]) {  // 两个位置的值相同（00 或 11）：翻转后仍是这两个值，取反后两个位置仍然相同且都要变
                    row[i] ^= 1;  // 左侧取反
                    row[j] ^= 1;  // 右侧取反
                }  // 结束 if
            }  // 结束双指针循环
            if (i == j) {  // 长度为奇数时 i == j，正中间的元素翻转后位置不变，但取反必须做一次
                row[i] ^= 1;  // 中间元素取反
            }  // 结束中间元素处理
        }  // 结束行循环
        return image;  // 返回处理完的矩阵
    }  // 结束方法
};  // 结束类