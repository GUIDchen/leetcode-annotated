// 题目：844. 比较含退格的字符串（Backspace String Compare）
// 思路：从两个字符串末尾往前扫描，用计数器跳过被 '#' 删除的字符，再逐个比较真正有效的字符。
// 时间复杂度：O(n + m)，每个字符最多被访问一次；空间复杂度：O(1)，只用常数个指针与计数器。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool backspaceCompare(string s, string t) {  // s、t 是含退格符 '#' 的两个字符串；返回它们退格后是否相等
        int i = s.size() - 1, j = t.size() - 1;  // 双指针 i、j 都从末尾开始：从后往前扫才能判断字符是否被后面的退格删除
        int skip1 = 0, skip2 = 0;  // skip1、skip2 记录两侧当前还欠着多少个要删除的字符
        for (; i >= 0 || j >= 0; --i, --j) {  // 只要有一侧还没扫完就继续；每轮各自左移一位
            while (i >= 0) {  // 先把 s 中无效字符跳过，让 i 停在下一个真正有效的字符上
                if (s[i] == '#') {  // 遇到退格符，说明前面有一个字符要被删除
                    ++skip1;  // 欠账加一
                    --i;  // 指针左移，继续往前找要被删除的字符
                } else if (skip1) {  // 不是退格符，但还存在未偿还的退格
                    --skip1;  // 偿还一个退格，相当于删掉当前字符
                    --i;  // 指针继续左移
                } else  // 既没有退格也没有欠账，当前字符有效
                    break;  // 停下，i 指向 s 中待比较的有效字符
            }  // s 侧跳过无效字符结束
            while (j >= 0) {  // 对 t 做同样处理，把 j 挪到下一个有效字符
                if (t[j] == '#') {  // 遇到退格符
                    ++skip2;  // t 侧欠账加一
                    --j;  // 指针左移
                } else if (skip2) {  // 不是退格符，但还有未偿还的退格
                    --skip2;  // 偿还一个退格
                    --j;  // 指针继续左移
                } else  // 当前字符有效
                    break;  // 停下，j 指向 t 中待比较的有效字符
            }  // t 侧跳过无效字符结束
            if (i >= 0 && j >= 0) {  // 两个字符串都还有有效字符
                if (s[i] != t[j]) return false;  // 有效字符不同就直接判定不相等
            } else if (i >= 0 || j >= 0)  // 有一侧已经扫完、另一侧还有有效字符
                return false;  // 长度不同，必然不相等
        }  // 本轮比较结束，循环继续向前
        return true;  // 所有有效字符都相同，退格后两串相等
    }  // 方法结束
};  // 类定义结束