# 题目：864. 获取所有钥匙的最短路径（Shortest Path to Get All Keys）
# 思路：状态压缩 BFS。状态是 (行, 列, 已收集钥匙的二进制掩码)，锁要求掩码对应位为 1 才能通过，首次集齐全部钥匙的层数即最短步数。
# 时间复杂度：O(m·n·2^k)，k 为钥匙数量，每个状态只入队一次；空间复杂度：O(m·n·2^k)，访问集合与队列。
class Solution:  # LeetCode 约定的题解类
    def shortestPathAllKeys(self, grid: List[str]) -> int:  # grid：迷宫地图；返回收集全部钥匙的最短步数，无法完成返回 -1
        m, n = len(grid), len(grid[0])  # m、n 分别为地图的行数与列数
        # 找起点 (si, sj)（用生成器表达式定位 @ 所在的行列坐标）
        si, sj = next((i, j) for i in range(m) for j in range(n) if grid[i][j] == '@')  # next 取第一个满足条件的格子，即起点的行列坐标
        # 统计钥匙数量（小写字母是钥匙，按行、按格统计总数）
        k = sum(v.islower() for row in grid for v in row)  # 统计钥匙总数 k，用于确定钥匙掩码的上界
        dirs = (-1, 0, 1, 0, -1)  # 四个方向的增量，相邻两项拼成一个 (dx, dy) 方向向量
        q = deque([(si, sj, 0)])  # BFS 队列，元素为 (行, 列, 已收集钥匙的位掩码)
        vis = {(si, sj, 0)}  # 已访问集合：(行, 列, 钥匙状态) 三元组，避免重复搜索
        ans = 0  # 当前 BFS 层数，即已走的步数
        while q:  # 队列非空就继续扩展
            for _ in range(len(q)):  # 一次处理完当前层，保证层数与步数一一对应
                i, j, state = q.popleft()  # 取出队首状态并拆成行、列、钥匙掩码
                # 找到所有钥匙，返回当前步数（位掩码全为 1 说明 k 把钥匙都已拿到）
                if state == (1 << k) - 1:  # 集齐钥匙，当前层步数就是最短步数
                    return ans  # 立即返回答案

                # 往四个方向搜索（依次尝试四个方向，pairwise 把增量两两配对）
                for a, b in pairwise(dirs):  # 枚举每个方向向量 (a, b)
                    x, y = i + a, j + b  # 由当前坐标加上方向增量，得到相邻格子的坐标
                    nxt = state  # 下一步的钥匙状态先继承当前状态
                    # 在边界范围内（只处理不越界的格子）
                    if 0 <= x < m and 0 <= y < n:  # 坐标越界检查
                        c = grid[x][y]  # 取出相邻格子的字符
                        # 是墙，或者是锁，但此时没有对应的钥匙，无法通过（'#' 是墙；大写字母是锁，缺少对应钥匙时无法通过）
                        if (  # 多行条件判断：下面依次检查墙、锁及其钥匙
                            c == '#'  # 是墙，永远无法通过
                            or c.isupper()  # 是大写字母，即锁
                            and (state & (1 << (ord(c) - ord('A')))) == 0  # 且钥匙掩码中缺少这把锁对应的钥匙
                        ):  # 条件表达式结束
                            continue  # 墙或缺钥匙的锁，跳过这个方向
                        # 是钥匙（小写字母是钥匙，捡到后要更新状态）
                        if c.islower():  # 当前格子是钥匙
                            # 更新状态（把钥匙对应的二进制位置 1）
                            nxt |= 1 << (ord(c) - ord('a'))  # 用位或把 (c - 'a') 位置 1，表示已拥有该钥匙
                        # 此状态未访问过，入队（只有 (位置, 钥匙状态) 首次出现才需要入队）
                        if (x, y, nxt) not in vis:  # 该状态没被访问过
                            vis.add((x, y, nxt))  # 标记为已访问，防止重复入队
                            q.append((x, y, nxt))  # 加入队列，等待下一层扩展
            # 步数加一（一层扩展完毕，步数加一）
            ans += 1  # 步数加一，进入下一层
        return -1  # 队列空了仍未集齐钥匙，说明无解
