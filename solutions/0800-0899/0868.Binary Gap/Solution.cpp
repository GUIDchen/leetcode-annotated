// 题目：868. 二进制间距（Binary Gap）
// 思路：从低位到高位扫描 n 的二进制位，记录上一个 1 的位置 pre 与当前位下标 cur，遇到 1 就用 cur-pre 更新答案。
// 时间复杂度：O(log n)，即 n 的二进制位数；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int binaryGap(int n) {  // 返回 n 的二进制表示中相邻两个 1 之间的最大距离
        int ans = 0;  // ans 记录最大间距，初值 0 表示目前还没有间距
        for (int pre = 100, cur = 0; n != 0; n >>= 1) {  // pre 是上一个 1 的位置，初始 100 作哨兵；cur 是当前位下标；每轮把 n 右移一位
            if (n & 1) {  // 判断最低位是否为 1
                ans = max(ans, cur - pre);  // 用当前位置 cur 减去上一个 1 的位置得间距并取最大值；第一个 1 会算出负值，自动被 0 压住
                pre = cur;  // 更新「上一个 1」的位置为当前位置
            }
            ++cur;  // 当前位下标后移，对应的正是刚刚检查过的那一位
        }
        return ans;  // 返回最大间距；不足两个 1 时 ans 保持 0
    }
};  // 题解类定义结束
