// 题目：829. 连续整数求和（Consecutive Numbers Sum）
// 思路：设写成 k 个连续正整数，则 N = k*(2a+k-1)/2，等价于 2N 能被 k 整除、且 2N/k + 1 - k 是偶数（首项 a 为正整数）。枚举所有合法的 k 计数即可。
// 时间复杂度：O(sqrt(N))，k 只需枚举到 k(k+1) <= 2N；空间复杂度：O(1)，只用了几个整型变量。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    int consecutiveNumbersSum(int n) {  // n 是待拆分的正整数，返回能表示成连续正整数之和的方案数
        n <<= 1;  // 先把 n 换成 2N，后面用整除与奇偶性判断更省事（同时也避免 2a+k-1 的半数问题）
        int ans = 0;  // 方案数
        for (int k = 1; k * (k + 1) <= n; ++k) {  // 枚举项数 k；k*(k+1) <= 2N 保证首项 a >= 1，越界后更长的一定不合法，可以停止
            if (n % k == 0 && (n / k + 1 - k) % 2 == 0) {  // 条件一：2N 能被 k 整除；条件二：a = (2N/k + 1 - k)/2 必须是整数，即 2N/k + 1 - k 为偶数
                ++ans;  // 两个条件都满足，说明这组 k 能对应一组连续正整数
            }  // 结束 if
        }  // 结束 k 循环
        return ans;  // 返回方案数
    }  // 结束方法
};  // 结束类