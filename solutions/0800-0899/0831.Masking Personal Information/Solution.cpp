// 题目：831. 隐藏个人信息（Masking Personal Information）
// 思路：按是否含 '@' 分两种情况。邮箱保留首字母与域名，中间固定 5 个星号；电话先抽出所有数字，保留后 4 位，按数字个数决定是否加国家码前缀。
// 时间复杂度：O(n)，只需几次线性扫描；空间复杂度：O(n)，构造返回字符串。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    string maskPII(string s) {  // s 是邮箱地址或电话号码，返回隐藏后的字符串
        int i = s.find('@');  // 查找 '@'：返回其下标，找不到时为 npos（-1）
        if (i != -1) {  // 有 '@' 说明是邮箱地址
            string ans;  // 构造邮箱的隐藏结果
            ans += tolower(s[0]);  // 名字首字母统一转小写后保留
            ans += "*****";  // 名字剩余部分一律用 5 个星号代替
            for (int j = i - 1; j < s.size(); ++j) {  // 从 '@' 前一个字符（名字最后一个字母）开始拼域名部分
                ans += tolower(s[j]);  // 域名同样统一转小写后拼接，这样保留了 '@' 及其后的全部内容
            }  // 结束域名拼接
            return ans;  // 返回邮箱隐藏结果
        }  // 结束邮箱分支
        string t;  // 电话分支：先把所有数字字符收集起来，丢弃 '+'、'-'、'('、')'、空格等分隔符
        for (char c : s) {  // 逐字符扫描原串
            if (isdigit(c)) {  // 是数字就保留
                t += c;  // 收集数字
            }  // 结束 if
        }  // 结束扫描
        int cnt = t.size() - 10;  // 去掉本地与地区号码共 10 位后剩下的位数，就是国家码长度（0 表示没有国家码）
        string suf = "***-***-" + t.substr(t.size() - 4);  // 固定后缀：***-***- 加上最后 4 位数字
        return cnt == 0 ? suf : "+" + string(cnt, '*') + "-" + suf;  // 无国家码直接返回后缀；有国家码则拼上 +、若干星号与连字符
    }  // 结束方法
};  // 结束类