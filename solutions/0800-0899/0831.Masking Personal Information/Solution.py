# 题目：831. 隐藏个人信息（Masking Personal Information）
# 思路：首字符是字母就按邮箱处理（首字母小写 + 五个星号 + 从 '@' 前一位起的域名）；否则抽出全部数字，保留后 4 位，按多出的位数决定国家码前缀。
# 时间复杂度：O(n)，一次线性扫描；空间复杂度：O(n)，保存中间字符串。
class Solution:  # LeetCode 约定的题解类
    def maskPII(self, s: str) -> str:  # s 是邮箱地址或电话号码，返回隐藏后的字符串
        if s[0].isalpha():  # 首字符是字母即邮箱（电话号码首字符是数字、'+' 或括号）
            s = s.lower()  # 邮箱不区分大小写，先整体转小写
            return s[0] + '*****' + s[s.find('@') - 1 :]  # 首字母 + 5 个星号 + 从 '@' 前一位开始的域名部分
        s = ''.join(c for c in s if c.isdigit())  # 电话分支：只保留数字字符，丢掉所有分隔符
        cnt = len(s) - 10  # 去掉本地区号码 10 位后的剩余位数，就是国家码位数
        suf = '***-***-' + s[-4:]  # 固定后缀：***-***- 加最后 4 位数字
        return suf if cnt == 0 else f'+{"*" * cnt}-{suf}'  # 没有国家码就返回后缀，否则加上 +、对应个数的星号和连字符
