// 题目：856. 括号的分数（Score of Parentheses）
// 思路：记录当前嵌套深度 d；遇到相邻的 "()" 这一最小单元时，它对答案的贡献是 2^d（d 为匹配后所在深度）。
// 时间复杂度：O(n)，一次遍历；空间复杂度：O(1)，只用两个变量。
class Solution {  // 题解类
public:
    int scoreOfParentheses(string s) {  // s 是合法的括号字符串
        int ans = 0, d = 0;  // ans 累计分数，d 为当前括号深度
        for (int i = 0; i < s.size(); ++i) {  // 从左到右扫描每个字符
            if (s[i] == '(') {  // 遇到左括号，深度加一
                ++d;  // 进入更深一层
            } else {  // 遇到右括号
                --d;  // 先退出一层，得到这一对括号的深度
                if (s[i - 1] == '(') {  // 形如 "()" 的原子括号可独立贡献 2^d 分
                    ans += 1 << d;  // 1 << d 即 2 的 d 次方，累加到总分
                }  // 原子括号判断结束
            }  // 右括号分支结束
        }  // 扫描结束
        return ans;  // 返回总得分
    }  // 方法结束
};  // 题解类结束