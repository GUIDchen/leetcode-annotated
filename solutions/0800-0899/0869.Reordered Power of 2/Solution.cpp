// 题目：869. 重新排序得到 2 的幂（Reordered Power of 2）
// 思路：用「每个数字出现次数」的指纹表示数字多重集，枚举 10^9 以内的所有 2 的幂，指纹与 n 相同即可重排得到。
// 时间复杂度：O(log n + 31 × log 10^9)，只枚举约 31 个 2 的幂；空间复杂度：O(1)，指纹只占常数空间。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    bool reorderedPowerOf2(int n) {  // 判断 n 的数字重新排列后能否得到 2 的幂
        string target = f(n);  // 把 n 的十进制数字计数拼成字符串，作为「数字多重集」的指纹
        for (int i = 1; i <= 1000000000; i <<= 1) {  // 从小到大枚举 2 的幂，上界取题目数据范围 10^9
            if (target == f(i)) {  // 指纹相同说明两个数由同样的数字组成，可以重排得到
                return true;  // 存在即返回 true
            }
        }
        return false;  // 枚举完所有 2 的幂都不匹配
    }

private:  // 私有辅助函数，外部不可见
    string f(int x) {  // f(x)：统计 x 中每个数字出现的次数，返回长度 10 的指纹
        char cnt[10] = {};  // cnt[0..9] 分别记录数字 0..9 出现的次数，char 足以存下计数
        while (x > 0) {  // 逐位拆解 x，直到 x 变成 0
            cnt[x % 10]++;  // 取出末位数字，让对应计数加一
            x /= 10;  // 整除 10 去掉末位
        }
        return string(cnt, cnt + 10);  // 把 10 个计数当作 10 个字节拼成 string，直接按字节串比较即可
    }
};  // 题解类定义结束
