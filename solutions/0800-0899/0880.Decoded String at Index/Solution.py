# 题目：880. 索引处的解码字符串（Decoded String at Index）
# 思路：第一趟正序累加解码后的总长度 m；第二趟倒序回退，把 k 对 m 取模，落在字母上即答案，遇到数字则把长度除回去。
# 时间复杂度：O(n)，两趟线性扫描；空间复杂度：O(1)，只用到 m、k 等常数级变量。
class Solution:  # LeetCode 约定的题解类
    def decodeAtIndex(self, s: str, k: int) -> str:  # s：编码字符串；k：目标位置
        m = 0  # m 记录解码后的总长度（Python 整数自动扩展，不会溢出）
        for c in s:  # 第一趟正序扫描，累计解码后的长度
            if c.isdigit():  # 当前字符是数字，代表重复次数
                m *= int(c)  # 整段内容被重复，长度乘以这个数字
            else:  # 否则当前字符是字母
                m += 1  # 字母自身让长度加一
        for c in s[::-1]:  # 第二趟倒序扫描（切片生成反转副本），从末尾往前缩小范围
            k %= m  # 把 k 折算到当前段内；结果为 0 表示落在该段最后一个字符上
            if k == 0 and c.isalpha():  # 落在末尾且该字符是字母
                return c  # 该字母即答案，直接返回
            if c.isdigit():  # 当前字符是数字，说明要退回上一层重复
                m //= int(c)  # 长度还原成重复之前的值（整除，保持整数）
            else:  # 否则当前字符是字母
                m -= 1  # 长度减去这个字母
