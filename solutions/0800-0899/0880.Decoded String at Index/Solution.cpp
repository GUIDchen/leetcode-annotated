// 题目：880. 索引处的解码字符串（Decoded String at Index）
// 思路：第一趟正序累加解码后的总长度 m；第二趟倒序回退，把 k 对 m 取模，落在字母上即答案，遇到数字则把长度除回去。
// 时间复杂度：O(n)，两趟线性扫描；空间复杂度：O(1)，只用到 m、k、i 等常数级变量。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    string decodeAtIndex(string s, int k) {  // s：编码字符串；k：1-based 的目标位置
        long long m = 0;  // m 记录解码后的总长度，可能很大，用 long long
        for (char& c : s) {  // 第一趟正序扫描，累计解码后的长度
            if (isdigit(c)) {  // 当前字符是数字，代表重复次数
                m *= (c - '0');  // 整段内容被重复，长度乘以这个数字
            } else {  // 否则当前字符是字母
                ++m;  // 字母自身让长度加一
            }
        }
        for (int i = s.size() - 1;; --i) {  // 第二趟倒序扫描，从末尾往前缩小 k 所在的范围
            k %= m;  // 把 k 折算到当前段内；结果为 0 表示落在该段最后一个字符上
            if (k == 0 && isalpha(s[i])) {  // 落在末尾且该位置是字母
                return string(1, s[i]);  // 该字母就是答案，构造长度为 1 的字符串返回
            }
            if (isdigit(s[i])) {  // 当前位置是数字，说明要退回上一层重复
                m /= (s[i] - '0');  // 长度还原成重复之前的值
            } else {  // 否则当前位置是字母
                --m;  // 长度减去这个字母
            }
        }
    }  // 方法结束
};  // 类定义结束