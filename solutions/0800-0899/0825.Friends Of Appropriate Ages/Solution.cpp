// 题目：825. 适龄的朋友（Friends Of Appropriate Ages）
// 思路：年龄只有 1..120 共 120 种可能，先用计数数组统计每种年龄有多少人，再枚举 (ax, ay) 这一对年龄，跳过题目给出的三种不发送条件，剩下的组合数就是答案。
// 时间复杂度：O(m^2 + n)，m = 121 是年龄上限，n 是人数；空间复杂度：O(m)，计数数组大小固定。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    int numFriendRequests(vector<int>& ages) {  // ages：每个人的年龄；返回满足条件的「发送者→接收者」对数
        const int m = 121;  // 年龄取值 1..120，m = 121 让下标 120 也合法
        vector<int> cnt(m);  // 计数数组 cnt[x] 表示年龄恰好为 x 的人数
        for (int x : ages) {  // 遍历每个人的年龄，做一次桶计数
            ++cnt[x];  // 该年龄的人数加一
        }  // 结束统计
        int ans = 0;  // 答案：合法好友请求的总数
        for (int ax = 1; ax < m; ++ax) {  // 外层枚举发送者的年龄 ax（年龄 0 不存在，从 1 开始）
            for (int ay = 1; ay < m; ++ay) {  // 内层枚举接收者的年龄 ay
                if (!(ay <= 0.5 * ax + 7 || ay > ax || (ay > 100 && ax < 100))) {  // 题目给了三条「不发送」条件：ay 太年轻（≤ 0.5*ax + 7）、ay 比 ax 大、ay 超过 100 而 ax 不到 100；取反即为可发送
                    ans += cnt[ax] * (cnt[ay] - (ax == ay ? 1 : 0));  // 可发送时，每个年龄 ax 的人都能向每个年龄 ay 的人发请求；ax == ay 时要去掉自己加自己，所以减 1
                }  // 结束内层判断
            }  // 结束接收者循环
        }  // 结束发送者循环
        return ans;  // 返回累计的对数
    }  // 结束方法
};  // 结束类
