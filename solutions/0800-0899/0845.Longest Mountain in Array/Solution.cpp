// 题目：845. 数组中的最长山脉（Longest Mountain in Array）
// 思路：预处理每个位置向左的上升长度 f 与向右的下降长度 g，枚举山顶把两者拼起来取最大值。
// 时间复杂度：O(n)，三次线性扫描；空间复杂度：O(n)，两个长度数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int longestMountain(vector<int>& arr) {  // arr 是输入数组；返回最长山脉的长度，没有山脉时返回 0
        int n = arr.size();  // 数组长度
        int f[n];  // f[i] 表示以 i 结尾的最长连续上升段长度，长度依赖 n，是变长数组
        int g[n];  // g[i] 表示以 i 开头的最长连续下降段长度
        fill(f, f + n, 1);  // 上升段长度至少为 1，先全部初始化为 1
        fill(g, g + n, 1);  // 下降段长度同样至少为 1
        for (int i = 1; i < n; ++i) {  // 从左到右扫描，计算每个位置向左的上升长度
            if (arr[i] > arr[i - 1]) {  // 当前元素比前一个大，说明上升段可以延长
                f[i] = f[i - 1] + 1;  // 接上前一个位置的上升长度
            }  // 上升段判断结束
        }  // 从左到右扫描结束
        int ans = 0;  // 答案初值为 0，表示暂时没有山脉
        for (int i = n - 2; ~i; --i) {  // 从右往左扫描；~i 等价于 i >= 0 的简写
            if (arr[i] > arr[i + 1]) {  // 当前元素比后一个大，说明从 i 开始可以下降
                g[i] = g[i + 1] + 1;  // 接上后一个位置的下降长度
                if (f[i] > 1) {  // f[i] > 1 说明 i 左侧确实有上升段，i 才能当山顶
                    ans = max(ans, f[i] + g[i] - 1);  // 上升段 + 下降段 - 1（山顶被两边各算了一次）即为山脉长度
                }  // 山顶判断结束
            }  // 下降段判断结束
        }  // 从右往左扫描结束
        return ans;  // 返回最长山脉长度
    }  // 方法结束
};  // 类定义结束