# 题目：804. 唯一摩尔斯密码词（Unique Morse Code Words）
# 思路：把每个单词逐字符翻译成摩尔斯串，放进集合推导式去重，集合大小即不同密码词的数量。
# 时间复杂度：O(L)，L 为所有单词字符总数；空间复杂度：O(L)，集合中存放全部转换结果。
class Solution:  # LeetCode 约定的题解类
    def uniqueMorseRepresentations(self, words: List[str]) -> int:  # words：单词数组；返回不同摩尔斯密码词的数量
        codes = [  # 下标 0~25 依次对应字母 a~z 的摩尔斯码
            ".-",
            "-...",
            "-.-.",
            "-..",
            ".",
            "..-.",
            "--.",
            "....",
            "..",
            ".---",
            "-.-",
            ".-..",
            "--",
            "-.",
            "---",
            ".--.",
            "--.-",
            ".-.",
            "...",
            "-",
            "..-",
            "...-",
            ".--",
            "-..-",
            "-.--",
            "--..",
        ]  # 26 项列表结束，正好覆盖 26 个小写字母
        s = {''.join([codes[ord(c) - ord('a')] for c in word]) for word in words}  # 集合推导式：逐字符换算摩尔斯码并拼接，重复结果自动去重
        return len(s)  # 集合元素个数就是不同密码词的数量
