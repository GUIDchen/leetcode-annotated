// 题目：804. 唯一摩尔斯密码词（Unique Morse Code Words）
// 思路：把每个单词按字母表映射成摩尔斯串，放进哈希集合去重，集合大小就是不同密码词的数量。
// 时间复杂度：O(L)，L 为所有单词字符总数；空间复杂度：O(L)，集合中存放全部转换结果。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int uniqueMorseRepresentations(vector<string>& words) {  // words：单词数组；返回不同摩尔斯密码词的数量
        vector<string> codes = {".-", "-...", "-.-.", "-..", ".", "..-.", "--.", "....", "..", ".---", "-.-", ".-..", "--", "-.",  // 字母表顺序（a~z）对应的摩尔斯码表，前半部分
            "---", ".--.", "--.-", ".-.", "...", "-", "..-", "...-", ".--", "-..-", "-.--", "--.."};  // 码表后半部分（p~z）
        unordered_set<string> s;  // 哈希集合，负责去重
        for (auto& word : words) {  // 逐个单词做转换
            string t;  // 当前单词的摩尔斯串
            for (char& c : word) t += codes[c - 'a'];  // 用字母偏移量 c - 'a' 取出对应的码并追加
            s.insert(t);  // 插入集合，重复的会自动忽略
        }  // 单词循环结束
        return s.size();  // 集合大小就是不同表示的数量
    }  // 方法结束
};  // 类定义结束