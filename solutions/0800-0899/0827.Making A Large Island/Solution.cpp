// 题目：827. 最大人工岛（Making A Large Island）
// 思路：先 DFS 给每个 1 连通块编号并统计面积，再枚举每个 0，用集合收集它四邻不同的连通块编号，把这些面积相加再加 1 就是填海后的面积，全程取最大值。
// 时间复杂度：O(n^2)，每个格子最多被 DFS 访问一次、被枚举一次；空间复杂度：O(n^2)，p 标记数组与递归栈。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    int largestIsland(vector<vector<int>>& grid) {  // grid：0/1 方阵，返回最多把一个 0 改成 1 后能得到的最大的岛面积
        int n = grid.size();  // 方阵边长
        int p[n][n];  // p[i][j] 存 (i, j) 属于哪块岛（0 表示还不是已编号的陆地）；n 运行时才确定，这里是变长数组（GNU 扩展）
        memset(p, 0, sizeof(p));  // 全部清 0，表示还没有任何格子被编号
        int cnt[n * n + 1];  // cnt[id] 记录编号 id 的岛的面积；编号最多 n*n 个，所以开 n*n+1
        memset(cnt, 0, sizeof(cnt));  // 面积表清零
        const int dirs[5] = {-1, 0, 1, 0, -1};  // 四个方向的偏移量，相邻两项 (dirs[k], dirs[k+1]) 恰好组成一个方向向量
        int root = 0;  // 当前正在编号的岛号，从 0 开始，每发现一块新岛就加一
        int ans = 0;  // 答案：最大岛面积（全是水时保持 0）
        function<int(int, int)> dfs = [&](int i, int j) {  // 递归 lambda：从 (i, j) 出发淹没整块岛并返回其面积；[&] 按引用捕获外部变量
            p[i][j] = root;  // 打上当前岛号，同时充当“已访问”标记，避免重复递归
            ++cnt[root];  // 当前岛面积加一
            for (int k = 0; k < 4; ++k) {  // 枚举上下左右四个方向
                int x = i + dirs[k];  // 邻居的行坐标
                int y = j + dirs[k + 1];  // 邻居的列坐标
                if (x >= 0 && x < n && y >= 0 && y < n && grid[x][y] && !p[x][y]) {  // 不越界、邻居是陆地、并且还没被任何岛编号过
                    dfs(x, y);  // 递归淹没这个邻居
                }  // 结束 if
            }  // 结束方向循环
            return cnt[root];  // 返回这块岛的最终面积
        };  // lambda 定义结束
        for (int i = 0; i < n; ++i) {  // 第一遍遍历：给所有陆地连通块编号，顺便记下“不填海”时的最大面积；逐行扫描
            for (int j = 0; j < n; ++j) {  // 逐列扫描
                if (grid[i][j] && !p[i][j]) {  // 是陆地且尚未编号，说明发现了一块新岛
                    ++root;  // 分配新岛号
                    ans = max(ans, dfs(i, j));  // 淹没整块岛并更新答案（不填海时原岛也可能已经是最大）
                }  // 结束新岛判断
            }  // 结束列扫描
        }  // 结束行扫描
        for (int i = 0; i < n; ++i) {  // 第二遍遍历：尝试把每个 0 填成 1，看能连通哪些岛；逐行扫描
            for (int j = 0; j < n; ++j) {  // 逐列扫描
                if (!grid[i][j]) {  // 只考虑水格子（填成陆地才有意义）
                    unordered_set<int> s;  // 用集合收集四邻的岛号，天然去重，避免同一块岛被重复加面积
                    for (int k = 0; k < 4; ++k) {  // 枚举上下左右四个方向
                        int x = i + dirs[k];  // 邻居行坐标
                        int y = j + dirs[k + 1];  // 邻居列坐标
                        if (x >= 0 && x < n && y >= 0 && y < n) {  // 只检查不越界（水格子也要记录，编号 0 面积为 0）
                            s.insert(p[x][y]);  // 记下邻格所属岛号；水格编号是 0，而 cnt[0] 恒为 0，不会多算面积，所以无需额外过滤
                        }  // 结束 if
                    }  // 结束方向循环
                    int t = 1;  // 填海后的面积先算上新填的这一格
                    for (int x : s) {  // 遍历所有相邻且不同的岛号
                        t += cnt[x];  // 累加每个相邻岛的面积
                    }  // 结束面积累加
                    ans = max(ans, t);  // 更新全局最大面积
                }  // 结束水格子处理
            }  // 结束列扫描
        }  // 结束行扫描
        return ans;  // 返回最大人工岛面积
    }  // 结束方法
};  // 结束类