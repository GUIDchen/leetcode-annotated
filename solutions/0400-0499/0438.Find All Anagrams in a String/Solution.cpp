// 题目：438. 找到字符串中所有字母异位词（Find All Anagrams in a String）
// 思路：固定长度滑动窗口 + 两个长度 26 的字母计数表——窗口右移时右端进一个字符、左端出一个字符，两表相等即说明该窗口是 p 的异位词。
// 时间复杂度：O(m + n)，m、n 为两串长度，两表比较是常数 26 次；空间复杂度：O(1)，只有两个 26 元数组。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    vector<int> findAnagrams(string s, string p) {  // 返回 s 中所有 p 的字母异位词子串的起始下标
        int m = s.size(), n = p.size();  // m 为主串长度，n 为模式串长度（也就是滑动窗口的大小）
        vector<int> ans;  // 答案数组，按从左到右的顺序记录起始下标
        if (m < n) {  // 主串比模式串还短，不可能存在异位词
            return ans;  // 提前返回空答案
        }
        vector<int> cnt1(26);  // cnt1：p 的字母计数表，下标 0..25 对应 'a'..'z'
        for (char& c : p) {  // 遍历 p 的每个字符（引用遍历，避免拷贝）
            ++cnt1[c - 'a'];  // 用 c - 'a' 把字母映射到 0..25，再累加计数
        }
        vector<int> cnt2(26);  // cnt2：当前窗口的字母计数表
        for (int i = 0; i < n - 1; ++i) {  // 先放入窗口的前 n-1 个字符，后面每轮循环再补上第 n 个，形成长度 n 的窗口
            ++cnt2[s[i] - 'a'];  // 把 s[i] 计入窗口计数
        }
        for (int i = n - 1; i < m; ++i) {  // 窗口右端点从左到右滑动，i 即窗口的右端下标
            ++cnt2[s[i] - 'a'];  // 右端纳入新字符，窗口长度变为 n
            if (cnt1 == cnt2) {  // 两表完全相等，说明窗口内字符组成与 p 相同
                ans.push_back(i - n + 1);  // 窗口左端点 i - n + 1 就是一个答案，记录下标
            }
            --cnt2[s[i - n + 1] - 'a'];  // 左端最左侧字符移出窗口，为下一轮滑动做准备
        }
        return ans;  // 返回收集到的全部起始下标
    }
};