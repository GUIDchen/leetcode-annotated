// 题目：455. 分发饼干（Assign Cookies）
// 思路：两个数组都升序排序，双指针让最小的饼干去满足最容易满足的孩子；饼干太小就丢弃，够大就同时后移。
// 时间复杂度：O(m log m + n log n)（两次排序）；空间复杂度：O(log m + log n)（排序递归栈，不计输入）。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int findContentChildren(vector<int>& g, vector<int>& s) {  // g：每个孩子的胃口值；s：每块饼干的尺寸；返回最多能满足的孩子数
        sort(g.begin(), g.end());  // 把胃口从小到大排序，优先满足最容易满足的孩子，把大饼干留给大胃口
        sort(s.begin(), s.end());  // 饼干尺寸也从小到大排序，使双指针同向单调前进
        int m = g.size(), n = s.size();  // m 为孩子数，n 为饼干数
        for (int i = 0, j = 0; i < m; ++i) {  // i 指向当前孩子，j 指向当前待分配的饼干
            while (j < n && s[j] < g[i]) {  // 跳过所有尺寸不够喂饱当前孩子的饼干
                ++j;  // 这块饼干太小，指针后移换下一块更大的
            }  // 循环结束：要么找到足够大的饼干，要么饼干已经用完
            if (j++ >= n) {  // 先取走当前饼干（j 后移）；若取之前已没有饼干则无法继续
                return i;  // 前 i 个孩子已全部满足，故最多只能满足 i 个
            }  // 结束无法继续的分支
        }  // 结束孩子遍历（所有孩子已满足或饼干已用尽）
        return m;  // 所有孩子都被满足，答案是孩子总数
    }
};