# 题目：439. 三元表达式解析器（Ternary Expression Parser）
# 思路：反转表达式后从右往左扫描，用列表当栈暂存操作数；遇到 '?' 后按条件的 T/F 只保留真值或假值分支，遇到 ':' 直接跳过。
# 复杂度：时间复杂度 O(n)，每个字符只处理一次；空间复杂度 O(n)，栈最多保存 n 个字符。
class Solution:  # 题解类：负责解析三元表达式
    def parseTernary(self, expression: str) -> str:  # expression 是形如 'T?2:3' 的表达式，返回最终结果的单个字符
        stk = []  # 用列表当栈，暂存从右往左扫描到的操作数与中间结果
        cond = False  # 标记刚读到的 '?' 是否还未被它的冒号分支消费
        for c in expression[::-1]:  # [::-1] 反转字符串，等价于从右往左扫描，让最内层三元式先化简
            if c == ':':  # ':' 只是分支分隔符
                continue  # 直接跳过，继续看下一个字符
            if c == '?':  # 遇到 '?'：它的条件字符已经在栈顶等着求值
                cond = True  # 置位标记，下一个读到的字符就是条件 T/F
            else:  # 否则当前字符是普通字符
                if cond:  # cond 为真：当前字符是 '?' 后面的条件
                    if c == 'T':  # 条件为真，保留真值分支，丢弃假值分支
                        x = stk.pop()  # 取出栈顶，即真值分支的结果
                        stk.pop()  # 再弹出一个，即被丢弃的假值分支
                        stk.append(x)  # 真值分支结果压回栈，作为整个三元式的结果
                    else:  # 否则条件为假，只保留假值分支
                        stk.pop()  # 弹出真值分支，假值分支留在栈顶
                    cond = False  # 这个 '?' 处理完毕，清除标记
                else:  # 否则当前字符是普通操作数
                    stk.append(c)  # 操作数入栈，等待外层三元运算使用
        return stk[0]  # 扫描结束，栈里只剩答案，取出返回
