// 题目：409. 最长回文串（Longest Palindrome）
// 思路：统计每种字符的频次，成对的部分都能左右对称使用；只要还剩任意一个字符，就能放到正中间再加 1。
// 时间复杂度：O(n + 128)，一遍统计加一遍固定 128 项求和；空间复杂度：O(128)，即常数额外计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int longestPalindrome(string s) {  // s 由大小写字母组成，返回能拼出的最长回文串长度
        int cnt[128]{};  // ASCII 128 个字符的出现次数，花括号把数组值初始化为 0
        for (char c : s) {  // 遍历字符串中的每个字符
            ++cnt[c];  // 该字符的计数加一
        }  // 字符统计结束
        int ans = 0;  // 累计可以放进回文串的字符数
        for (int v : cnt) {  // 遍历每种字符的频次
            ans += v / 2 * 2;  // 成对的部分都能左右对称放置，奇数频次先丢掉多出的那一个
        }  // 频次循环结束
        ans += ans < s.size();  // 若还有字符剩余就可以放到正中间，长度再加 1（bool 隐式转 int）
        return ans;  // 返回最长回文串长度
    }  // 方法结束
};  // 类定义结束（源文件末尾无换行，此处保持一致）