# 题目：400. 第 N 位数字（Nth Digit）
# 思路：按位数分段。k 位数有 9*10^(k-1) 个、占 k*9*10^(k-1) 位，整段跳过还不够 n 的部分，再用整除与取余定位到具体的数和数内的位。
# 时间复杂度：O(log n)，最多遍历 log10(n) 个位数段；空间复杂度：O(1)，只用常数个变量。
class Solution:  # LeetCode 约定的题解类
    def findNthDigit(self, n: int) -> int:  # 返回无限序列 123456789101112... 的第 n 位数字（n 从 1 开始）
        k, cnt = 1, 9  # k 是当前位数；cnt 是 k 位数共有多少个（1 位数 9 个，2 位数 90 个…）
        while k * cnt < n:  # 当前整段的长度不足 n 时整段跳过（Python 整数无溢出问题）
            n -= k * cnt  # 减去这一段的长度，把问题缩小
            k += 1  # 位数加一
            cnt *= 10  # 下一批数字个数是上一批的 10 倍
        num = 10 ** (k - 1) + (n - 1) // k  # 10^(k-1) 是 k 位数的起点，加上前面跳过的完整数字个数就得到目标数字
        idx = (n - 1) % k  # 目标数字在该数内部的偏移（从 0 开始）
        return int(str(num)[idx])  # 取该数字对应位置的字符，再转成整数返回
