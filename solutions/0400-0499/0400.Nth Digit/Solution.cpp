// 题目：400. 第 N 位数字（Nth Digit）
// 思路：按位数分段。k 位数共有 9*10^(k-1) 个、共占 k*9*10^(k-1) 位，先整段跳过不足 n 的部分，再用 (n-1)/k 定位到具体的数、(n-1)%k 定位到该数内部的位。
// 时间复杂度：O(log n)，位数最多 log10(n) 段；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    int findNthDigit(int n) {  // 返回把 1,2,3,... 依次拼接后得到的无限长序列的第 n 位数字（n 从 1 开始）
        int k = 1, cnt = 9;  // k 是当前考察的位数；cnt 是 k 位数共有多少个（1 位数 9 个，2 位数 90 个…）
        while (1ll * k * cnt < n) {  // 如果当前这一整段还不够 n 位就先跳过；1ll 把乘法提升到 long long，避免 k*cnt 溢出 int
            n -= k * cnt;  // 从 n 中减去这一整段的长度，把问题缩小到后面的数字
            ++k;  // 位数加一，进入下一批更长的数字
            cnt *= 10;  // 下一批数字的个数是上一批的 10 倍
        }
        int num = pow(10, k - 1) + (n - 1) / k;  // 定位到具体的数：k 位数的起点是 10^(k-1)，再加上跳过 (n-1)/k 个完整数字
        int idx = (n - 1) % k;  // 目标数字在这个数内部的偏移（从 0 开始）
        return to_string(num)[idx] - '0';  // 转成字符串取对应字符，减去 '0' 的 ASCII 值就得到数字本身
    }
};  // 题解类结束