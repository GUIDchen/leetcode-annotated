// 题目：493. 翻转对（Reverse Pairs）
// 思路：归并排序统计；每次合并前先用双指针数出「左半段元素 > 右半段元素 × 2」的对数（左右两段各自有序，所以指针可以单调前移），再正常合并两段。
// 时间复杂度：O(n log n)，归并 O(log n) 层、每层线性统计与合并；空间复杂度：O(n)，辅助数组 t 与递归栈。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int reversePairs(vector<int>& nums) {  // nums：输入数组；返回满足 i < j 且 nums[i] > 2 * nums[j] 的数对个数
        int n = nums.size();  // 数组长度
        int t[n];  // 归并用的辅助数组（变长数组，gnu++ 扩展，大小随 n 决定）
        function<int(int, int)> mergeSort = [&](int l, int r) -> int {  // 递归式归并排序：处理区间 [l, r]，返回该区间内的翻转对数量
            if (l >= r) {  // 区间长度 ≤ 1，没有数对
                return 0;  // 递归出口直接返回 0
            }  // 出口分支结束
            int mid = (l + r) >> 1;  // 取中点，注意 (l + r) >> 1 等价于向下取整的 (l + r) / 2
            int ans = mergeSort(l, mid) + mergeSort(mid + 1, r);  // 先分别排好左右两段，并累加两段内部的翻转对
            int i = l, j = mid + 1, k = 0;  // i 指向左段、j 指向右段、k 是辅助数组的写指针
            while (i <= mid && j <= r) {  // 双指针统计跨段的翻转对：两段分别有序，故 j 单调右移
                if (nums[i] <= nums[j] * 2LL) {  // 左段元素还不够大（这里用 2LL 防止 nums[j] * 2 溢出 int）
                    ++i;  // 左指针右移，继续找更大的左段元素
                } else {  // 否则 nums[i] > 2 * nums[j]，即右段这个元素对左段 i..mid 都成立
                    ans += mid - i + 1;  // 左段从 i 到 mid 共 mid - i + 1 个元素都能与 nums[j] 构成翻转对
                    ++j;  // 右指针右移，处理下一个更小的候选
                }  // 统计分支结束
            }  // 跨段统计结束
            i = l;  // 重置左指针，准备归并
            j = mid + 1;  // 重置右指针，准备归并
            while (i <= mid && j <= r) {  // 标准归并：两段都还有剩余时按大小取较小的放入辅助数组
                if (nums[i] <= nums[j]) {  // 左段当前元素不大于右段，取左段的
                    t[k++] = nums[i++];  // 写入辅助数组后两个指针一起后移
                } else {  // 否则取右段的元素
                    t[k++] = nums[j++];  // 写入辅助数组，右段指针后移
                }  // 归并分支结束
            }  // 主归并循环结束
            while (i <= mid) {  // 左段还有剩余，直接搬到辅助数组尾部
                t[k++] = nums[i++];  // 逐个拷贝左段剩余元素
            }  // 左段剩余处理结束
            while (j <= r) {  // 右段还有剩余，直接搬到辅助数组尾部
                t[k++] = nums[j++];  // 逐个拷贝右段剩余元素
            }  // 右段剩余处理结束
            for (i = l; i <= r; ++i) {  // 把辅助数组 [0, r - l] 的内容写回原数组 [l, r]
                nums[i] = t[i - l];  // t[i - l] 是相对偏移，映射回原数组的位置
            }  // 写回结束，此时 [l, r] 已有序
            return ans;  // 返回本段的翻转对总数
        };  // lambda 定义结束
        return mergeSort(0, n - 1);  // 对整个数组做归并排序并统计答案
    }  // 方法结束
};  // 类定义结束