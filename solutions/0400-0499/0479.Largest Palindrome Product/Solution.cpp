// 题目：479. 最大回文数乘积（Largest Palindrome Product）
// 思路：从大到小枚举回文数的前半部分 a，把它逐位反转拼成完整回文数 x，再用不超过 10^n-1 的因子 t 从大到小试除；第一次整除得到的 x 就是最大的回文数乘积。
// 时间复杂度：对每个候选回文数 x 只需枚举因子到 √x，总体约为 O(10^n · √x) 的上界（命中即返回，实际远小于此）；空间复杂度：O(1)，只用了常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的题解方法
    int largestPalindrome(int n) {  // n 是位数，返回最大回文数乘积对 1337 取模后的结果
        int mx = pow(10, n) - 1;  // n 位数的最大值，例如 n = 2 时 mx = 99
        for (int a = mx; a > mx / 10; --a) {  // 从大到小枚举前半部分 a；a > mx / 10 保证 a 仍然是 n 位数
            int b = a;  // 复制一份 a 用来逐位取数字，避免破坏枚举变量
            long x = a;  // x 初始为前半部分，随后在末尾拼接它的逆序
            while (b) {  // 只要 b 还有位就继续拼接
                x = x * 10 + b % 10;  // 取出 b 的最后一位接到 x 末尾，逐步造出回文数
                b /= 10;  // 去掉 b 已经用过的最后一位
            }  // 循环结束时 x 就是由 a 生成的完整回文数
            for (long t = mx; t * t >= x; --t)  // 从 mx 向下枚举较大因子 t；t * t < x 说明 t 已越过平方根，之后不会再有更大的合法因子
                if (x % t == 0)  // 能整除说明 x = t * (x / t)，且两个因子都落在 n 位范围内
                    return x % 1337;  // 第一个满足条件的 x 即最大回文数乘积，按题目要求取模返回
        }  // 结束 a 的枚举
        return 9;  // 兜底：n = 1 时答案是 9（3 * 3）
    }  // 结束题解方法
};  // 结束题解类