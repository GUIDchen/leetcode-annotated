# 题目：479. 最大回文数乘积（Largest Palindrome Product）
# 思路：从大到小枚举回文数的前半部分 a，把它逐位反转拼成完整回文数 x，再从 10**n - 1 向下试除，第一个能整除的 x 就是最大的回文数乘积。
# 时间复杂度：每个候选回文数只枚举因子到 √x，总体约为 O(10^n · √x) 的上界（命中即返回）；空间复杂度：O(1)，只用了常数个变量。
class Solution:  # LeetCode 约定的题解类
    def largestPalindrome(self, n: int) -> int:  # n 是位数，返回最大回文数乘积对 1337 取模后的结果
        mx = 10**n - 1  # n 位数的最大值，例如 n = 2 时 mx = 99
        for a in range(mx, mx // 10, -1):  # range 的步长为 -1，从大到小枚举前半部分 a；到 mx // 10 为止保证 a 仍是 n 位数
            b = x = a  # 同时把 a 赋给 b 和 x：b 用来逐位取数字，x 用来拼接反转部分
            while b:  # 只要 b 还有位就继续拼接
                x = x * 10 + b % 10  # 取出 b 的最后一位接到 x 末尾，逐步造出回文数
                b //= 10  # 去掉 b 已经用过的最后一位（整除，保持整数）
            t = mx  # 较大因子 t 从 n 位数最大值 mx 开始向下试
            while t * t >= x:  # t * t >= x 才可能成为较大的那个因子，越过平方根就没有更大的因子了
                if x % t == 0:  # 能整除说明 x = t * (x // t)，两个因子都在 n 位范围内
                    return x % 1337  # 第一个满足条件的 x 即最大回文数乘积，按要求取模返回
                t -= 1  # 换下一个更小的因子
        return 9  # 兜底：n = 1 时答案是 9（3 * 3）
