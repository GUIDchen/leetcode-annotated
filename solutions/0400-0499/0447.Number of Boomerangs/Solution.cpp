// 题目：447. 回旋镖的数量（Number of Boomerangs）
// 思路：以每个点作回旋镖顶点，统计其余点到它的距离；同距离有 k 个点时可组成 k*(k-1) 个有序点对，边遍历边累加 cnt[d] 即得无序对数，最后乘 2。
// 时间复杂度：O(n^2)，每个顶点都要扫一遍所有点求距离（哈希表均摊 O(1)）；空间复杂度：O(n)，单个顶点的距离计数表最多 n-1 个键。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberOfBoomerangs(vector<vector<int>>& points) {  // points：平面上的所有点，每个点形如 [x, y]；返回有序回旋镖三元组的个数
        int ans = 0;  // ans：有序回旋镖的数量，边统计边累加
        for (auto& p1 : points) {  // 枚举回旋镖的顶点 p1（回旋镖的第一、三个点是同距的另外两点）
            unordered_map<int, int> cnt;  // 哈希表：到 p1 的距离平方 → 该距离上已经出现了多少个点
            for (auto& p2 : points) {  // 枚举终点 p2（会包含 p1 自己，距离为 0，不影响最终结果）
                int d = (p1[0] - p2[0]) * (p1[0] - p2[0]) + (p1[1] - p2[1]) * (p1[1] - p2[1]);  // 用坐标差的平方和当天平方法度，避免开根号带来的浮点误差
                ans += cnt[d];  // 之前已有 cnt[d] 个点到 p1 的距离同为 d，各与 p2 配成一个无序点对
                cnt[d]++;  // 把 p2 也计入该距离的计数，供后续点继续配对
            }  // 结束内层遍历：以 p1 为顶点的点对已全部统计完
        }  // 结束外层遍历：所有顶点都处理完毕
        return ans << 1;  // 无序点对乘以 2（左移一位）得到 (i, j) 与 (j, i) 两种先后顺序
    }  // 结束 numberOfBoomerangs
};  // 结束 Solution 类