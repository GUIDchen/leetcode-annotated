// 题目：484. 寻找排列（Find Permutation）
// 思路：先取字典序最小的升序排列 1..n+1；'D' 意味着相邻递减，所以把每一段连续的 'D' 连同它左边那个数一起反转，就能让这段满足降序且整体最小。
// 时间复杂度：O(n)，每个位置最多被反转一次；空间复杂度：O(n)，存放长度为 n+1 的答案数组。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的题解方法
    vector<int> findPermutation(string s) {  // s 是由 'I'（递增）和 'D'（递减）组成的比较关系串
        int n = s.size();  // 关系串长度 n，排列长度应为 n + 1
        vector<int> ans(n + 1);  // 结果排列，长度 n + 1
        iota(ans.begin(), ans.end(), 1);  // 先填成字典序最小的升序排列 1, 2, ..., n+1
        int i = 0;  // i 表示当前待处理的关系下标（也从这里开始处理一段 'D'）
        while (i < n) {  // 从头到尾处理每段关系
            int j = i;  // j 从 i 出发，去找连续 'D' 的结束位置
            while (j < n && s[j] == 'D') {  // 只要还是 'D' 就继续往后走
                ++j;  // 扩大到下一个下标
            }  // 此时 [i, j] 这段 'D' 已确定（j 可能等于 n）
            reverse(ans.begin() + i, ans.begin() + j + 1);  // 反转 ans[i..j]：连续的 'D' 需要降序，反转后这段恰好从大到小
            i = max(i + 1, j);  // 跳过已处理的 'D' 段；至少前进一位，避免 i 停滞
        }  // 结束关系串的遍历
        return ans;  // 返回构造出的最小排列
    }  // 结束题解方法
};  // 结束题解类