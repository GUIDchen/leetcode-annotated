# 题目：484. 寻找排列（Find Permutation）
# 思路：先取字典序最小的升序排列 1..n+1；'D' 要求相邻递减，因此把每段连续的 'D' 连同它左边那个数一起反转，既满足降序又保持整体最小。
# 时间复杂度：O(n)，每个位置最多被反转一次；空间复杂度：O(n)，存放长度为 n+1 的答案列表。
class Solution:  # LeetCode 约定的题解类
    def findPermutation(self, s: str) -> List[int]:  # s 是由 'I'（递增）和 'D'（递减）组成的比较关系串
        n = len(s)  # 关系串长度 n，排列长度应为 n + 1
        ans = list(range(1, n + 2))  # 先构造成字典序最小的升序排列 1, 2, ..., n+1
        i = 0  # i 指向当前待处理的关系下标
        while i < n:  # 从头到尾处理每一段关系
            j = i  # j 从 i 出发，用于寻找连续 'D' 的结束位置
            while j < n and s[j] == 'D':  # 只要还是 'D' 就继续往后走
                j += 1  # 扩大到下一个下标
            ans[i : j + 1] = ans[i : j + 1][::-1]  # 切片赋值反转 ans[i..j]：连续的 'D' 需要降序，反转后正好从大到小
            i = max(i + 1, j)  # 跳过已处理的 'D' 段；max 保证至少前进一位，防止死循环
        return ans  # 返回构造出的最小排列
