// 题目：413. 等差数列划分（Arithmetic Slices）
// 思路：一次遍历相邻差值，公差连续相同就让等差段延长、候选项数加一，并累加所有新增的等差子数组个数。
// 时间复杂度：O(n)，只扫一遍数组；空间复杂度：O(1)，只用常数个变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int numberOfArithmeticSlices(vector<int>& nums) {  // nums 是整数数组，返回其中等差连续子数组（长度 ≥ 3）的个数
        int ans = 0, cnt = 0;  // ans 累计答案；cnt 记录以当前相邻对结尾的等差段长度
        int d = 3000;  // 当前公差，取题面范围外的 3000 当哨兵
        for (int i = 0; i < nums.size() - 1; ++i) {  // 遍历每一对相邻元素，i 只到倒数第二个下标
            if (nums[i + 1] - nums[i] == d) {  // 差值与当前公差相同，等差段继续延长
                ++cnt;  // 段长计数加一
            } else {  // 否则公差变化，等差段在此断开并重新开始
                d = nums[i + 1] - nums[i];  // 更新当前公差
                cnt = 0;  // 重新从 0 开始计数
            }  // 分支结束
            ans += cnt;  // 以该位置结尾的新增等差子数组正好 cnt 个
        }  // 循环结束
        return ans;  // 返回等差子数组总数
    }  // 方法结束
};  // 类定义结束（源文件末尾无换行，此处保持一致）