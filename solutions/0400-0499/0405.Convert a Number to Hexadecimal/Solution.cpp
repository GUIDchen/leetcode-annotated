// 题目：405. 数字转换为十六进制数（Convert a Number to Hexadecimal）
// 思路：按补码逐组取位。32 位整数正好是 8 个十六进制位，从高到低每次取 4 位并映射成字符，跳过前导 0。
// 时间复杂度：O(1)，固定循环 8 次；空间复杂度：O(1)，结果最长 8 个字符。
class Solution {  // LeetCode 约定的题解类
public:  // 方法对外可见
    string toHex(int num) {  // 把 32 位整数转成十六进制字符串；负数按补码解释，不带负号
        if (num == 0) return "0";  // 0 的十六进制表示就是 "0"，单独返回
        string s = "";  // 存放结果的字符串
        for (int i = 7; i >= 0; --i) {  // 从最高的第 7 组取到最低的第 0 组，共 8 组 4 位
            int x = (num >> (4 * i)) & 0xf;  // 算术右移取当前这一组，再用 0xf 掩码只保留低 4 位
            if (s.size() > 0 || x != 0) {  // 前面已经有非零位，或这一组本身非零时才输出，从而跳过前导 0
                char c = x < 10 ? (char) (x + '0') : (char) (x - 10 + 'a');  // 0-9 映射成 '0'-'9'，10-15 映射成 'a'-'f'
                s += c;  // 把字符追加到结果末尾
            }
        }
        return s;  // 返回十六进制字符串
    }
};  // 题解类结束