// 题目：487. 最大连续1的个数 II（Max Consecutive Ones II）
// 思路：滑动窗口 [l, 右端] 内最多允许 1 个 0；每加入一个元素就统计 0 的个数，超过 1 个就右移左端点把窗口挤回合法，最终窗口长度最大。
// 时间复杂度：O(n)，每个元素最多进窗口一次、出窗口一次；空间复杂度：O(1)，只用了几个计数变量。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int findMaxConsecutiveOnes(vector<int>& nums) {  // nums：只含 0/1 的数组；允许把至多一个 0 翻转成 1，返回最长全 1 连续段长度
        int l = 0, cnt = 0;  // l：滑动窗口左端点；cnt：窗口内 0 的个数（最多允许 1 个）
        for (int x : nums) {  // 右端点逐位右移，逐个把元素纳入窗口
            cnt += x ^ 1;  // x 为 0 时 x^1 得 1，正好给「0 的计数」加一；x 为 1 时加 0，不影响计数
            if (cnt > 1) {  // 窗口内 0 超过 1 个就不再合法，必须从左侧收缩窗口
                cnt -= nums[l++] ^ 1;  // 左端点右移一格：若被移出的是 0 就让 cnt 减 1，保证窗口内至多一个 0
            }  // 收缩分支结束
        }  // 遍历结束，此时窗口的右端刚好固定在数组末尾
        return nums.size() - l;  // 窗口长度 n - l 就是「可全 1」的最长连续段长度
    }  // 方法结束
};  // 类定义结束