# 题目：481. 神奇字符串（Magical String）
# 思路：神奇字符串自描述：第 i 个数字表示“接下来要连续写几个字符”。用下标 i 边读长度边交替生成 1/2，直到长度达到 n。
# 时间复杂度：O(n)，每个字符只生成一次；空间复杂度：O(n)，需要保存生成的序列。
class Solution:  # LeetCode 约定的题解类
    def magicalString(self, n: int) -> int:  # n 是需要的字符个数，返回前 n 位中 '1' 的个数
        s = [1, 2, 2]  # 1 和 2 分别代表字符 '1' 与 '2'；开头固定为 1 2 2
        i = 2  # i 指向“当前该按第 i 个数字决定生成长度”的位置
        while len(s) < n:  # 长度还没到 n 就继续生成
            pre = s[-1]  # pre 是已生成部分的最后一个字符
            cur = 3 - pre  # 相邻两段字符必然交替，所以新字符 = 3 - pre（1 变 2，2 变 1）
            s += [cur] * s[i]  # 第 i 个数字 s[i] 表示紧接着连续写几个 cur，用列表乘法一次性追加
            i += 1  # 移到下一个“长度指示器”
        return s[:n].count(1)  # 只统计前 n 位中 1 的个数
