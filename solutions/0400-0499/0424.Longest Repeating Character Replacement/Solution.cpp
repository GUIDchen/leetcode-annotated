// 题目：424. 替换后的最长重复字符（Longest Repeating Character Replacement）
// 思路：滑动窗口内维护出现次数最多的字符计数 mx，当窗口长度减 mx 大于 k 时左指针右移一格，窗口只增不减，最终长度即答案。
// 时间复杂度：O(n)，每个字符最多进出窗口一次；空间复杂度：O(1)，字符计数数组固定 26 个槽位。
class Solution {  // LeetCode 题解类
public:  // 方法对外可见
    int characterReplacement(string s, int k) {  // s：大写字母组成的字符串；k：最多可替换的字符数
        int cnt[26]{};  // 记录当前窗口内每个字符出现的次数，{} 保证初始化为 0
        int l = 0, mx = 0;  // l：窗口左边界；mx：窗口内同一字符的最大出现次数
        int n = s.length();  // n：字符串长度，后面用来计算答案
        for (int r = 0; r < n; ++r) {  // r 是窗口右边界，从左到右扩张窗口
            mx = max(mx, ++cnt[s[r] - 'A']);  // 新字符入窗并计数，同时更新窗口内最高频字符的计数
            if (r - l + 1 - mx > k) {  // 窗口长度减去 mx 就是需要替换的字符数，超过 k 说明窗口不合法
                --cnt[s[l++] - 'A'];  // 把左边界字符移出窗口，并让左边界右移一格
            }  // if 语句块结束
        }  // for 循环结束
        return n - l;  // 循环结束时窗口长度 n - l 就是历史最长合法窗口
    }  // 方法结束
};  // 类定义结束