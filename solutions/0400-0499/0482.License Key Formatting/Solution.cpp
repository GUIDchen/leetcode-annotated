// 题目：482. 密钥格式化（License Key Formatting）
// 思路：非 '-' 字符个数除以 k 取余就是第一组的长度（余数为 0 则第一组满 k 个），随后从左往右扫，遇到非 '-' 就转大写并追加，够 k 个就补一个 '-'（最后一组除外）。
// 时间复杂度：O(n)，只扫描一遍字符串；空间复杂度：O(n)，结果串需要存放全部字符与分隔符。
class Solution {  // LeetCode 约定的题解类
public:  // 对外暴露的题解方法
    string licenseKeyFormatting(string s, int k) {  // s 是原密钥字符串，k 是除第一组外每组的字符数
        int n = s.length();  // 记住原串长度，后面判断“是否最后一个下标”时要用
        int cnt = (n - count(s.begin(), s.end(), '-')) % k;  // 先算出第一组的长度：有效字符数对 k 取余，余数即第一组剩余个数
        if (cnt == 0) {  // 余数为 0 说明能整除
            cnt = k;  // 此时第一组实际是满的 k 个
        }  // 结束 if
        string ans;  // 存放格式化后的密钥
        for (int i = 0; i < n; ++i) {  // 从左到右扫描原串
            char c = s[i];  // 取出当前字符
            if (c == '-') {  // 遇到分隔符 '-'
                continue;  // 直接跳过，它不参与分组
            }  // 结束 if
            ans += toupper(c);  // 字母统一转成大写后加入结果（非字母字符保持不变）
            if (--cnt == 0) {  // 本组计数减一，减到 0 说明这一组已经凑满
                cnt = k;  // 重置计数器，准备下一组
                if (i != n - 1) {  // 只有不是原串最后一个字符时才补分隔符，避免末尾多出 '-'
                    ans += '-';  // 追加分组用的分隔符
                }  // 结束内层 if
            }  // 结束内层 if
        }  // 结束 for 循环
        if (!ans.empty() && ans.back() == '-') {  // 兜底：最后一个有效字符可能早于原串末尾，导致结果尾部残留 '-'
            ans.pop_back();  // 去掉结果末尾多余的 '-'
        }  // 结束 if
        return ans;  // 返回格式化后的密钥
    }  // 结束题解方法
};  // 结束题解类