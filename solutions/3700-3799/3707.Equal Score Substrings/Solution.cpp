// 3707. Equal Score Substrings（3707. 相等子字符串分数）
// 核心思路：先把整串字母的 1~26 分数全部累加为右段，再从左往右把字符逐个搬进左段，途中任一步左右相等就说明存在合法切分。
// 复杂度：时间 O(n)，空间 O(1)。
class Solution {  // 定义题解类
public:  // 公有成员，供判题器调用
    bool scoreBalance(string s) {  // 判断能否把 s 切成两段非空子串且分数相等
        int l = 0, r = 0;  // l 为左段分数，r 为右段分数
        for (char c : s) {  // 遍历整个串
            int x = c - 'a' + 1;  // 把字母映射为 1~26 的分数
            r += x;  // 先把全部分数累加进右段
        }  // 右段初值统计完毕
        for (int i = 0; i < s.size() - 1; ++i) {  // 枚举切分点 i：左段 s[0..i]、右段 s[i+1..]，两段都非空
            int x = s[i] - 'a' + 1;  // 当前字母的分数
            l += x;  // 把该字母记入左段
            r -= x;  // 同时从右段扣掉
            if (l == r) {  // 两段分数相等，切分合法
                return true;  // 返回存在
            }  // 结束判断
        }  // 结束枚举
        return false;  // 所有切分点都不满足
    }  // 方法结束
};  // 类定义结束
