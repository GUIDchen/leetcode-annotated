// 题目：3713. 最长的平衡子串 I（Longest Balanced Substring I）
// 思路：枚举左端点并向右扩展，用数组统计每个字母的出现次数；当「最大出现次数 × 不同字母个数 == 子串长度」时，所有字母次数都等于最大值，子串平衡，据此更新最长长度。
// 时间复杂度：O(n² + 26n)，空间复杂度：O(1)，只需 26 个字母的计数数组。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int longestBalanced(string s) {  // s：只含小写字母的字符串；返回最长平衡子串的长度
        int n = s.size();  // 字符串长度
        vector<int> cnt(26, 0);  // 每个小写字母在当前子串中的出现次数
        int ans = 0;  // 记录最长平衡子串长度
        for (int i = 0; i < n; ++i) {  // 枚举子串左端点
            fill(cnt.begin(), cnt.end(), 0);  // 换左端点时把计数数组清零
            int mx = 0, v = 0;  // mx：当前子串的最大出现次数；v：不同字母个数
            for (int j = i; j < n; ++j) {  // 枚举子串右端点
                int c = s[j] - 'a';  // 当前字符映射到 0..25
                if (++cnt[c] == 1) {  // 该字母在子串中首次出现
                    ++v;  // 不同字母个数加一
                }  // 首次出现判断结束
                mx = max(mx, cnt[c]);  // 更新最大出现次数
                if (mx * v == j - i + 1) {  // 最大次数 × 字母种类数 == 子串长度，说明每种字母次数都等于 mx
                    ans = max(ans, j - i + 1);  // 更新答案
                }  // 平衡判断结束
            }  // 右端点枚举结束
        }  // 左端点枚举结束
        return ans;  // 返回最长平衡子串长度
    }  // 方法结束
};  // 类定义结束
