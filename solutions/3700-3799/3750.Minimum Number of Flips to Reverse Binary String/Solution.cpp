// 题目：3750. 最少翻转次数得到反转二进制字符串（Minimum Number of Flips to Reverse Binary String）
// 核心思路：要让二进制串等于其反转，前后对称的每一位都必须相同；只需逐对比较对称位置，字符不同的那对必须两端各翻转一次，故答案为不同对称对的个数乘 2。
// 复杂度：时间 O(log n)，二进制只有 O(log n) 位；空间 O(log n)，用数组暂存各二进制位。
class Solution {  // LeetCode 约定的题解类
public:  // 题解方法对外可见
    int minimumFlips(int n) {  // 返回使 n 的二进制串等于其反转所需的最少翻转次数
        vector<int> s;  // s 存放 n 的二进制位，低位在前
        while (n > 0) {  // 反复取最低位，把 n 拆成二进制数字
            s.push_back(n & 1);  // 取 n 的最低位放入 s
            n >>= 1;  // n 右移一位，继续处理下一位
        }  // 循环结束

        int m = s.size();  // m 是二进制串的长度
        int cnt = 0;  // cnt 统计「关于中心对称但字符不同」的位置对数
        for (int i = 0; i < m / 2; i++) {  // 只遍历前半部分，与后半部分的对称位置比较
            if (s[i] != s[m - i - 1]) {  // 对称位置字符不同时，这一对必须都翻转
                cnt++;  // 计数加一
            }  // if 分支结束
        }  // 遍历结束
        return cnt * 2;  // 每一对不同的对称位置需要两端各翻转一次，故乘 2
    }  // 方法结束
};  // 类定义结束
