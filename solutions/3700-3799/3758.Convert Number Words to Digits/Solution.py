# 3758. 将数字词转换为数字（Convert Number Words to Digits）
# 核心思路：按数字 0~9 顺序准备英文单词表，从左到右在每个位置尝试与单词做前缀匹配，命中就把该数字写入答案并跳过整个单词长度。
# 复杂度：时间 O(n × 10 × 5) 即 O(n)，空间 O(1)（不含答案）。
class Solution:  # 定义解法类
    def convertNumber(self, s: str) -> str:  # 接口：把由英文数字单词拼成的字符串转换回数字串
        d = [  # d 按 0~9 的顺序保存对应的英文单词
            "zero",  # 数字 0 的英文单词
            "one",  # 数字 1 的英文单词
            "two",  # 数字 2 的英文单词
            "three",  # 数字 3 的英文单词
            "four",  # 数字 4 的英文单词
            "five",  # 数字 5 的英文单词
            "six",  # 数字 6 的英文单词
            "seven",  # 数字 7 的英文单词
            "eight",  # 数字 8 的英文单词
            "nine",  # 数字 9 的英文单词
        ]  # 单词表结束
        i, n = 0, len(s)  # i 为扫描位置，n 为输入串长度
        ans = []  # ans 收集转换出的数字字符
        while i < n:  # 从左到右扫描输入串的每个位置
            for j, t in enumerate(d):  # 依次尝试 0~9 这十个单词（j 为数字、t 为单词）
                m = len(t)  # m 为该单词长度，即要跳过的字符数
                if i + m <= n and s[i : i + m] == t:  # 先保证不越界，再判断从 i 起是否正好是这个词
                    ans.append(str(j))  # 命中则把对应数字字符追加到答案
                    i += m - 1  # 跳过整个单词的剩余字符
                    break  # 同一个位置无需再试别的单词
            i += 1  # 位置前进一位，准备处理下一段
        return "".join(ans)  # 把收集到的数字字符拼成结果返回
