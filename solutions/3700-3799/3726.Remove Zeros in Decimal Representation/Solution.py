# 3726. Remove Zeros in Decimal Representation（移除十进制表示中的所有零）
# 核心思路：从低位到高位逐位取出数字，遇到 0 直接丢弃，非 0 数字按当前位权拼进结果，从而删掉所有零。
# 复杂度：时间 O(log n)（n 的十进制位数），空间 O(1)。

class Solution:
    def removeZeros(self, n: int) -> int:  # 返回十进制表示中删除所有 0 之后得到的数
        k = 1  # k 表示当前应放置的位权（个位为 1，依次乘 10）
        ans = 0  # ans 保存最终结果
        while n:  # 从低位到高位逐位处理，n 为 0 时结束
            x = n % 10  # 取出当前最低位数字
            if x:  # 只有非 0 的数字才需要保留
                ans = k * x + ans  # 把该数字放到当前位权上（低位先拼，故与新结果相加）
                k *= 10  # 位权升一位，准备处理下一个非 0 数字
            n //= 10  # 丢掉最低位，处理下一位
        return ans  # 返回删除所有 0 之后的数
